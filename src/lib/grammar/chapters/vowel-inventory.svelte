<S t="Phonetic quality" id="phonetics">
	<p>
		Shiraishi surveys acoustic studies beginning with Obata and Teshima's recordings of three male
		speakers, two from Asahikawa and one from Sakhalin. Later studies examined Saru and other
		Hokkaido speakers <Ref k="shiraishi2022" p="§2" />. The small, differently composed samples are
		useful evidence about particular speakers; they should be kept distinct in comparisons of vowel
		quality.
	</p>
	<S t="The proximity of neighboring vowels" id="mid-vowels">
		<p>
			Several studies reviewed by Shiraishi found small acoustic distances between /i/ and /e/, and
			between /u/ and /o/. Ōhashi's comparison of two Saru speakers with her own Japanese vowels
			found the pairs closer in the Ainu data <Ref k="shiraishi2022" p="§2" />. Acoustic proximity
			can help explain listeners' difficulty distinguishing the vowels. It does not establish a
			merger of the phonemes.
		</p>
	</S>
	<S t="The vowel u" id="u-quality">
		<p>
			Ainu /u/ is described as rounded and farther back than Japanese /u/. Nakagawa connects this
			difference with older Japanese spellings such as <span lang="ja">アイノ</span>
			for <i lang="ain-Latn">aynu</i>, in which listeners represented the final vowel as
			<em>o</em>
			<Ref k="nakagawa2024" p="26" />. Bugaeva makes a similar observation about transcriptions by
			European-language speakers <Ref k="bugaeva2012" p="466" />.
		</p>
		<p>
			The acoustic evidence reviewed by Shiraishi includes a lower second formant for Ainu /u/ than
			for the Japanese comparison vowel, consistent with a more back articulation
			<Ref k="shiraishi2022" p="§2" />. This gives a more specific basis for the comparison than the
			spelling resemblance alone.
		</p>
	</S>
</S>

<S t="Devoicing" id="devoicing">
	<p>
		The vowels /i/, /u/, and sometimes /e/ can be devoiced between voiceless consonants. Shiraishi
		cites realizations of <i lang="ain-Latn">cise</i> “house,”
		<i lang="ain-Latn">sutu</i> “root,” and <i lang="ain-Latn">seta</i> “dog” with a devoiced first
		vowel <Ref k="shiraishi2022" p="§2.1" />. Devoicing changes the production of a vowel; it need
		not remove the syllable from the word's phonological structure.
	</p>
	<p>
		The frequency and distribution vary markedly. In Tamura's comparison of two female Saru
		speakers, one produced approximately twenty-five times as much devoicing as the other.
		Shiraishi's acoustic study of Saru recordings found it most readily in
		<span lang="ain-Latn">si</span> and <span lang="ain-Latn">ci</span>, with no instances in
		<span lang="ain-Latn">tu, pi, pu</span>
		in that study
		<Ref k="shiraishi2022" p="§2.1" />. These findings describe the recordings examined; they do not
		justify an exceptionless rule for every Hokkaido speaker.
	</p>
	<p>
		Japanese and Ainu devoicing overlap in some environments but differ in others. Shiraishi reports
		Tamura's observation that Japanese-speaking learners can extend devoicing to Ainu forms where it
		is inappropriate <Ref k="shiraishi2022" p="§2.1" />. Pronunciation should therefore be learned
		from the relevant Ainu recording as well as from its transcription.
	</p>
</S>

<S t="Length and lengthening" id="length">
	<p>
		A vowel may be long in an utterance even though vowel length does not distinguish Hokkaido
		words. A monosyllabic open word can be prolonged in isolation; accented vowels in longer words
		also tend to be lengthened. Shiraishi illustrates these contexts with
		<i lang="ain-Latn">to</i> “lake” and <i lang="ain-Latn">poro</i> “big,” among other forms <Ref
			k="shiraishi2022"
			p="§2.2"
		/>.
	</p>
	<p>
		Emphatic forms can have a different structure. The forms transcribed [weʔen] “very bad” and
		[toʔo] “far away” contain a glottal interruption and are analyzed as two syllables
		<Ref k="shiraishi2022" p="§§2.2, 4.1" />. They should be distinguished from a single vowel
		prolonged in performance; see <Xr ch="glottal-stop" s="emphatic" />.
	</p>
	<p>
		Sakhalin Ainu provides a comparative contrast because it has phonemic vowel length.
		Correspondences between Sakhalin length and Hokkaido accent are discussed by Nakagawa and
		Itabashi <Ref k="nakagawa2024" p="26–27" />; <Ref k="itabashi2001" />. The comparison requires
		attention to the particular words and dialects; length and high pitch do not correspond
		uniformly in every case.
	</p>
</S>

<S t="Vowel sequences and final glides" id="sequences">
	<p>
		A sequence written with two vowel letters in an older transcription may be represented with a
		final glide in modern spelling. Shibatani writes the sequences pronounced [aj], [uj], and [aw]
		as <span lang="ain-Latn">ay, uy, aw</span>
		<Ref k="shibatani1990" p="§2.1" />. Under the consonant analysis, the glide occupies the
		syllable coda. Morphological evidence for this treatment is considered in
		<Xr ch="glides-w-y" />.
	</p>
</S>

<S t="Interpreting vowel counts" id="frequency">
	<p>
		A count of written vowels depends on the transcription and the unit being counted. Counting each
		dictionary headword once gives a different measure from counting every word occurrence in
		connected speech. Person forms and common particles can strongly affect the latter measure. Any
		comparison of vowel frequencies needs to identify the sample and counting convention; see <Xr
			ch="dialect-sample-and-corpus-method"
		/>.
	</p>
</S>

<S t="Vowels in derivational patterns" id="harmony">
	<p>
		Certain transitive-verb and possessive-noun formations show restrictions on the combination of
		the stem vowel and a following suffix vowel. Examples include
		<i lang="ain-Latn">kay-e</i> “break” and <i lang="ain-Latn">mos-o</i> “wake someone,” discussed
		in Shiraishi's review of Chiri's analysis
		<Ref k="shiraishi2022" p="§4.5" />. The restrictions concern particular morphological patterns,
		rather than the choice of vowels throughout the language.
	</p>
	<p>
		The interpretation as vowel harmony is disputed. Shiraishi reviews objections by Shibatani,
		Vovin, and Satō: the patterns have limited morphological scope and do not fit a single familiar
		harmony feature such as backness <Ref k="shiraishi2022" p="§4.5" /> ‹contested›. The data and competing
		analyses are developed in
		<Xr ch="affiliative-suffix-morphophonology" />.
	</p>
</S>

<S t="Dialect comparison" id="dialect">
	<p>
		A shared inventory of five vowels allows differences in the realization or distribution of those
		vowels. Nakagawa and Fukazawa describe lexical correspondences involving /u/ and /o/ in Sōya and
		/o/ and /e/ in Yakumo <Ref k="nakagawafukazawa2022" p="§3" />. Such correspondences should be
		distinguished from small phonetic differences within one vowel category. Claims about either
		require locality and speaker information.
	</p>
</S>
