<S t="The reflexive-possessive function" id="reflexive-possessive">
	<p>
		When a transitive verb incorporates a body-part or closely possessed nominal,
		<A w="si-" /> can mark that nominal as belonging to the subject — the reflexive-possessive
		function. The example cited by the Handbook is
		<A w="si-etu-uyna" gl="hold one's own nose" /> 'hold one's nose', where <A w="si-" />
		supplies the possessor 'one's own' for the incorporated noun <A w="etu" gl="nose" /> and
		<A w="uyna" gl="hold something" /> is thereby intransitivized
		<Ref k="bugaevakobayashi2022" p="§4.2.2" />. The parallel
		<A w="yay-" />-possessive <A w="yay-par-oyki" gl="feed oneself; do to one's own mouth" />
		— 'feed oneself', literally 'do to one's own mouth' — shows that both prefixes can supply
		the possessor of an incorporated nominal, with the yay-/si- distinction projecting onto
		the possessive domain in the same way it does onto the reflexive <Ref k="bugaevakobayashi2022" p="§4.2.2" />.
	</p>
	<p>
		The reflexive-possessive reading also surfaces obligatorily in locative contexts: when a
		locative nominal's possessor is coreferential with the clause subject,
		<A w="si-" /> (or the applicative construction built around it) is required, and
		substituting a non-coreferential possessor yields a distinct, non-reflexive reading
		<Ref k="sato2008" p="251–253" />.
	</p>
	<p>
		In arity terms the function remains −1: the incorporated nominal fills one argument slot,
		<A w="si-" /> fills that nominal's possessor internally, and one external argument is
		removed. The parallel in noun incorporation is the possessor-requiring subject type, where
		the stranded possessor receives a reflexive interpretation by recovery from the clause
		subject — the 'reflexive interpretation rescue' in Satō's markedness calculus, treated in
		<Xr ch="noun-incorporation-subject-possessor-stranding" /> <Ref k="satoni2022" p="§3.3, §5" />.
	</p>
	<p>
		The reciprocal construction uses the same word-internal possession pattern with
		<i lang="ain-Latn">u-</i>. Forms such as <i lang="ain-Latn">u-tek-kisma</i>
		‘shake hands’, <i lang="ain-Latn">u-oruspe-nu</i> ‘discuss things’, and
		<i lang="ain-Latn">u-itak-nu</i> ‘agree; obey’ are treated together with the
		reflexive patterns in <Xr ch="reciprocal-u" s="quasi-possessive" />. The shared structure
		is a possessor prefix followed by a bare incorporated noun and its verbal host.
	</p>
</S>

<S t="The 'pretend to' construction" id="pretend">
	<p>
		<A w="si-" /> combined with a causative suffix yields a 'pretend to V' reading.
		Nakagawa (2024: 188) gives three examples with the productive suffix
		<i lang="ain-Latn">-re</i>: <A w="si-mokor-e" gl="feign sleep" /> 'feign sleep',
		<A w="si-kamuyne-re" gl="pretend to be a kamuy" /> 'pretend to be a kamuy', and
		<A w="si-ponpene-re" gl="act childishly" /> 'act childishly'. With the direct-causative
		<i lang="ain-Latn">-ka</i>, Satō (2007: ≈36) gives
		<A w="si-ranpewtek-ka" gl="pretend not to know" /> 'pretend not to know'. In each
		instance the state or appearance is externally attributed: sleep must be witnessed to be
		believed, kamuy status requires another to be deceived, ignorance requires an observer to
		accept it. The 'pretend to' reading is therefore a direct realisation of the
		indirect-reflexive semantics of <A w="si-" /> in a context of social inference.
	</p>

	<Ex
		m="ku=ko-si-ranpewtek-ka wa k=an"
		g="1SG.A=APPL-REFL-know.nothing-CAUS CONJ 1SG.S=exist"
		tr="I was pretending not to know about it."
		cite="sato2007:36"
		dial="CHI"
		place="Shirasawa Nabe; Satō ex. 6"
		note="Satō writes ku-ko-si-ranpewtek-ka wa k-an and glosses the final k- as first-person singular subject, an as 'exist'. The existential follows the person-marked reflexive-causative predicate in a wa construction. Both predicates refer to the same first-person singular subject."
	/>

	<p>
		The cited examples establish 'pretend to' readings for particular combinations of
		<i lang="ain-Latn">si-</i> and causative morphology. Nakagawa also records
		<i lang="ain-Latn">si-ray-re</i> 'pretend to be dead'
		<Ref k="nakagawa2024" p="188" />. Satō discusses
		<i lang="ain-Latn">si-ranpewtek-ka</i> as an intentional act and interprets the
		observer's recognition of the pretended state as indirect participation
		<Ref k="sato2007" p="37–38" />.
	</p>
</S>

<S t="Position in the verb template" id="template">
	<p>
		The relative order of reflexive and applicative prefixes depends on the derivation.
		Nakagawa places nominal and applicative prefixes in the same region of the template
		and states that their order depends on meaning <Ref k="nakagawa2024" p="210" />.
		Satō records both <i lang="ain-Latn">ko-si-ranpewtek-ka</i>, with the applicative
		outside <i lang="ain-Latn">si-</i>, and <i lang="ain-Latn">si-ko-etaye</i>,
		with <i lang="ain-Latn">si-</i> outside the applicative
		<Ref k="sato2007" p="36–37, ex. 6, 8" />. For the two reflexive prefixes together,
		Nakagawa cites <A w="yay-si-turi-re" gl="lie down stretching oneself" /> and reports
		no examples of the reverse order. He tentatively compares the inner
		<i lang="ain-Latn">si-</i> to a stem-forming affix
		<Ref k="nakagawa2024" p="188" />.
	</p>

	<Ex
		m="yay-si-turi-re=an"
		g="REFL-REFL-stretch-CAUS=4.S"
		tr="I lie down, stretching myself out."
		cite="nakagawa2024:188"
		constructed
		note="Nakagawa cites the stem yay-si-turi-re. The fourth-person inflection is constructed. His analysis starts with transitive turi, derives intransitive si-turi, adds causative -re to form a transitive, and applies yay- to yield the final intransitive. The suffix =an attaches to that whole derived stem."
	/>

	<p>
		Satō's derivation list gives transitive <i lang="ain-Latn">ko-i-ruska</i> →
		intransitive <i lang="ain-Latn">si-ko-i-ruska</i>, with <i lang="ain-Latn">si-</i>
		outside the applicative. The corresponding causative
		<i lang="ain-Latn">si-ko-i-ruska-re</i> is transitive
		<Ref k="sato2023b" p="40" />. In
		the polysynthetic example discussed in <Xr ch="valency-voice-overview" /> —
		<i lang="ain-Latn">a=e-yay-ko-tuyma-si-ram-suy-pa</i> — a second <A w="si-" /> sits
		immediately before the incorporated noun <A w="ram" gl="heart" /> in the
		reflexive-possessive reading ('one's own heart'), while <A w="yay-" /> occupies the outer
		layer at the applicative boundary. The yay-outer / si-inner hierarchy is visible in a
		single stacked verb form <Ref k="shibatani1990" p="73" />;
		<Ref k="bugaevakobayashi2022" p="§4.1.1" />.
	</p>
</S>
