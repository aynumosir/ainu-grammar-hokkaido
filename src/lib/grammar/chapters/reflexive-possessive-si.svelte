<S t="Verbal uses of si-" id="overview">
	<p>
		Reflexive <i lang="ain-Latn">si-</i> occurs in verbs of bodily motion, spontaneous change,
		action involving oneself, and pretending. Nakagawa gives
		<i lang="ain-Latn">si-turi</i> “stretch,” <i lang="ain-Latn">si-rutu</i> “shift,”
		<i lang="ain-Latn">si-suye</i> “sway,” and <i lang="ain-Latn">si-yupu</i> “tighten,” derived
		from transitive bases <Ref k="nakagawa2024" p="188" />. Their subjects undergo the movement or
		change. The available forms and meanings are partly lexical.
	</p>
	<p>
		Other uses involve deliberate action. Satō's <i lang="ain-Latn">si-kasuy-re</i>
		means to have someone help oneself. In his indirect-reflexive analysis, the helper acts on the subject,
		whose participation consists in arranging the help
		<Ref k="sato2007" p="§3.3" />; <Ref k="sato2008" p="250" />. This account and the traditional
		intentional/unintentional distinction are competing explanations of the
		<i lang="ain-Latn">yay-/si-</i> contrast ‹contested›; see <Xr ch="reflexive-yay" />.
	</p>
</S>

<S t="Causatives and pretending" id="causatives">
	<Ex
		m="ku=ko-si-ranpewtek-ka wa k=an"
		g="1SG.A=APPL-REFL-know.nothing-CAUS CONJ 1SG.S=exist.SG"
		tr="I was pretending not to know about it."
		cite="sato2007:example 6"
		dial="CHI"
		note="Person boundaries are written with = here. Satō analyzes the involvement of other people's perception as part of the indirect-reflexive meaning."
	/>
	<p>
		The simulative reading recurs in <i lang="ain-Latn">si-mokor-e</i> “pretend to sleep” and
		<i lang="ain-Latn">si-ray-re</i>
		“pretend to be dead”
		<Ref k="nakagawa2024" p="188" />. The shape
		<i lang="ain-Latn">si-…-CAUS</i> also permits other readings, as “have someone help oneself”
		shows. Kobayashi cites deliberate coughing with
		<i lang="ain-Latn">si-musis-ka</i>, a causative based on a one-place verb
		<Ref k="kobayashi2010" p="155–157, §5" />.
	</p>
	<p>
		Kobayashi distinguishes causatives of one-place and two-place bases and the order in which
		reflexivization and causativization apply. With a two-place base, a reflexive can identify the
		original patient with either the original actor or the added causer, depending on the
		derivation. For one-place bases he explicitly discusses identity of causer and causee, then
		relates it to a more articulated underlying structure. He leaves parts of that analysis
		unresolved ‹contested› <Ref k="kobayashi2010" p="153–157, §§4.3–5.3" />. The participant
		identified by <i lang="ain-Latn">si-</i> therefore requires analysis of the particular construction.
	</p>
</S>

<S t="A subject's own spatial reference point" id="locative">
	<p>
		The prefix also occurs on locative nouns. In Satō's Chitose description, when the locative
		reference point and the clause subject are coreferential,
		<i lang="ain-Latn">si-</i> marks that relation. A third-person locative form instead refers to
		someone else's position <Ref k="sato2008" p="252" />.
	</p>
	<Ex
		m="si-y-etok un inkar=an akusu"
		g="REFL-EP-front ALLAT look=4.S CONJ"
		tr="When I looked ahead of myself, …"
		cite="sato2008:252"
		place="Opening of an oral-literature example"
		note="The source writes inkar-an. The consonant y links si- to the vowel-initial noun. Satō rejects i-y-etok and yay-etok for this coreferential reading."
	/>
	<Ex
		m="katkemat si-sam ta tennep hotkere wa"
		g="woman REFL-side LOC baby lay.down CONJ"
		tr="The woman laid the baby beside herself, and …"
		cite="sato2008:252"
		place="Opening of an oral-literature example"
		note="The source continues with her digging lily bulbs. The locative reference point is the woman who is the subject of hotkere."
	/>
	<p>
		Satō distinguishes these spatial uses from idiomatic <i lang="ain-Latn">yaykata</i>
		“by oneself.” He regards their connection with his indirect-reflexive analysis as still uncertain
		<Ref k="sato2008" p="252–253" />. Locative reference and ordinary nominal possession are
		compared in <Xr ch="relational-and-spatial-nouns" />.
	</p>
</S>

<S t="Possessors and the history of the verbal functions" id="history">
	<p>
		Incorporated body-part nouns can take a reflexive possessor. The Handbook's
		<i lang="ain-Latn">si-etu-uyna</i>, literally “take one's own nose,” uses the plural stem
		<i lang="ain-Latn">uyna</i>. It describes astonishment and is attributed to Satō 2018
		<Ref k="bugaevakobayashi2022" p="§4.2.2, example 17" />. This is a derivational possessor
		construction, compared with quasi-incorporation in
		<Xr ch="noun-incorporation-oblique-polysynthesis-debate" />.
	</p>
	<p>
		Bugaeva's later historical proposal derives the verbal functions through reflexive →
		autocausative → anticausative. In this terminology, an autocausative presents self-induced
		motion, while an anticausative presents a change without an expressed causer. She proposes that <i
			lang="ain-Latn">yay-</i
		>
		retained reflexivity as its main function while <i lang="ain-Latn">si-</i> extended through
		these other functions ‹speculative› <Ref k="bugaeva2025" p="179–181, §3.1.2" />. This proposal
		accommodates several present-day uses; it does not establish one uniform meaning for every
		<i lang="ain-Latn">si-</i> word.
	</p>
</S>
