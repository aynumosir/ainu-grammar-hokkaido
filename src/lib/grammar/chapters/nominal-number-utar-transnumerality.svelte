<S t="Plural nouns and verbal number" id="verbal-number">
	<p>
		Some verbs have singular and plural forms, but many do not. Verbal number may concern the
		subject, an object, or repeated events, depending on the verb and construction
		<Ref k="nakagawa2024" p="141–143" />. Refsing also discusses duration and respect among the uses
		of forms grouped as plural
		<Ref k="refsing1986" p="150–151" />.
	</p>
	<p>
		A numeral does not invariably require a plural verb. Kindaichi and Chiri give
		<i lang="ain-Latn">tu ainu an</i> “there are two people” and
		<i lang="ain-Latn">re ainu ek</i> “three people came,” using the forms otherwise classified as
		singular <Ref k="kindaichi1936" p="65, §100" />. The lexical and constructional conditions are
		described in
		<Xr ch="suppletive-verbal-number" />.
	</p>
</S>

<S t="Sakhalin comparison" id="sakhalin-contrast">
	<p>
		Sakhalin descriptions distinguish plural forms of the
		<i lang="ain-Latn">-(a)hcin</i> type from
		<i lang="ain-Latn">-utara</i>. Nakagawa reports Murasaki's Raichishka examples of the former
		after affiliative nouns, including a form meaning “my grandchildren.” He also reports
		Sakaguchi's analysis of its occurrence after nominalized clauses
		<Ref k="nakagawa2024" p="260–261" />.
	</p>
	<p>
		In the analysis reported there, the <i lang="ain-Latn">-(a)hcin</i> type principally expresses
		ordinary plurality, while <i lang="ain-Latn">-utara</i>
		also allows associative readings. Nakagawa questions whether these patterns amount to an obligatory
		grammatical number category on Sakhalin nouns
		<Ref k="nakagawa2024" p="260–261" />. This is his interpretation of a system with a wider
		morphological distinction than the Hokkaido constructions described above.
	</p>
</S>
