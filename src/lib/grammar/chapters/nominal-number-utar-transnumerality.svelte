<S t="Nouns without obligatory number marking" id="transnumerality">
	<p>
		Ordinary Hokkaido Ainu nouns do not obligatorily distinguish singular and plural forms. The same <i
			lang="ain-Latn">aynu</i
		>
		occurs in
		<i lang="ain-Latn">sine aynu</i> “one person” and
		<i lang="ain-Latn">tu aynu</i> “two people”
		<Ref k="shibatani1990" p="32" />. Nakagawa describes the absence of a required nominal number
		distinction, alongside optional expressions of plurality
		<Ref k="nakagawa2024" p="259" />. This number-neutral use of a noun is often called
		<em>transnumeral</em>.
	</p>
	<Ex
		m="tu aynu"
		g="two person"
		tr="two people"
		cite="shibatani1990:32"
		place="Hokkaido, dialect not specified"
	/>
	<p>
		The interpretation of an unquantified noun depends on context. Explicit numerals, quantifiers,
		plural <i lang="ain-Latn">utar</i>, and the number behavior of particular verbs contribute
		different kinds of information.
	</p>
</S>

<S t="Utar as a plural expression" id="utar-formal-noun">
	<p>
		<i lang="ain-Latn">Utar</i> follows nouns, prenominals, and modifying clauses. Nakagawa
		classifies it as a formal noun and gives
		<i lang="ain-Latn">cikappo utar</i> “small birds” alongside a clause referring to people whom
		the speaker had helped <Ref k="nakagawa2024" p="258" />. Satō describes its noun-following use
		as appositional; Refsing and Shibatani use a suffix analysis <Ref k="sato2008" p="181" />;
		<Ref k="refsing1986" p="159" />;
		<Ref k="shibatani1990" p="32" /> ‹contested›.
	</p>
	<p>
		Two interpretations recur. An ordinary plural denotes several members of the named class. An
		associative plural denotes a person together with associated people. Kindaichi and Chiri explain <i
			lang="ain-Latn">acha utar arki</i
		>
		as an uncle and his company coming, alongside ordinary plurals of gods, people, dogs, and birds
		<Ref k="kindaichi1936" p="30, §37" />. Shibatani likewise recognizes both readings <Ref
			k="shibatani1990"
			p="32"
		/>.
	</p>
</S>

<S t="Animacy and differences among descriptions" id="animacy-debate">
	<p>
		The descriptions differ over inanimate referents. Kindaichi and Chiri exclude such combinations
		as stones or trees with <i lang="ain-Latn">utar</i> unless they are personified <Ref
			k="kindaichi1936"
			p="30–31"
		/>. Refsing reports no inanimate examples in her Shizunai material <Ref
			k="refsing1986"
			p="159"
		/>. Nakagawa includes <i lang="ain-Latn">suma utar</i> “stones” and
		<i lang="ain-Latn">ni utar</i> “trees,” with Saru sentences about furs and lacquerware <Ref
			k="nakagawa2024"
			p="259"
		/> ‹contested›.
	</p>
	<Ex
		m="a=kor rus utar"
		g="4.A=have fur PL"
		tr="my furs"
		cite="nakagawa2024:259, example 334"
		dial="SAR"
		note="Noun-phrase excerpt from the example about carrying furs to a boat."
	/>
	<p>
		Tamura's Saru dictionary marks inanimate use as rare but records
		<i lang="ain-Latn">citarpe utar</i> “mats”
		<Ref k="tamura1996" p="s.v. utar" />. Satō gives
		<i lang="ain-Latn">utukani utar</i> “dogwood trees”
		<Ref k="sato2008" p="298" />. The reported restrictions thus vary by description and its
		material; the inanimate examples have specific lexical and contextual settings.
	</p>
	<p>
		Nakagawa suggests that Ainu conceptions of spirits may help explain the inanimate uses <Ref
			k="nakagawa2024"
			p="259"
		/> ‹speculative›.
	</p>
</S>

<S t="Lexical plurals and repeated forms" id="hekattar">
	<p>
		<i lang="ain-Latn">Hekattar</i> “children” is historically analyzed as
		<i lang="ain-Latn">hekaci</i> plus <i lang="ain-Latn">utar</i>
		<Ref k="kindaichi1936" p="31" />; <Ref k="refsing1986" p="159" />. Tamura's Saru entry defines
		the result as children of both sexes, although
		<i lang="ain-Latn">hekaci</i> denotes a boy
		<Ref k="tamura1996" p="s.v. hekattar" />. Kindaichi and Chiri also record
		<i lang="ain-Latn">hekattar utar</i>, with a further
		<i lang="ain-Latn">utar</i>
		<Ref k="kindaichi1936" p="31" />.
	</p>
	<p>
		The same grammar lists repeated nominal forms with plural-like reference, including
		<i lang="ain-Latn">ramram</i> “scales” and
		<i lang="ain-Latn">taktak</i> “lumps”
		<Ref k="kindaichi1936" p="31, §38" />. Reduplication also occurs extensively in verbal word
		formation; see <Xr ch="reduplication-phonology-rule-interaction" />.
	</p>
</S>

