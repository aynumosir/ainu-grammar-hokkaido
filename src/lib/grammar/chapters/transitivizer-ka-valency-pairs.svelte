<S t="The distribution of -ka" id="ka">
	<p>
		Nakagawa lists <i lang="ain-Latn">-ka</i> formations including
		<i lang="ain-Latn">retar-ka</i> “whiten,” <i lang="ain-Latn">iunin-ka</i> “cause pain,”
		<i lang="ain-Latn">us-ka</i> “extinguish,” <i lang="ain-Latn">teyne-ka</i> “wet,” and
		<i lang="ain-Latn">een-ka</i> “sharpen,” with different dialect distributions
		<Ref k="nakagawa2024" p="202, table 43" />. Satō's Chitose account groups
		<i lang="ain-Latn">-ka</i> among causative endings while explicitly listing exceptions to suffix
		selection by the stem's final sound <Ref k="sato2008" p="235–237" />.
	</p>
	<p>
		The geographical generalization is disputed. Bugaeva describes stronger use of
		<i lang="ain-Latn">-ka</i> in northeastern Hokkaido and Sakhalin and proposes replacement by the
		productive causative in southwestern varieties. Nakagawa finds no clear region in which
		<i lang="ain-Latn">-ka</i>
		predominates
		<Ref k="bugaeva2014" p="135–136, 144" />;
		<Ref k="nakagawa2024" p="202" /> ‹contested›. Kobayashi reports both inter-dialect differences and
		alternatives within Saru, including <i lang="ain-Latn">nam-te / nam-ka</i>
		<Ref k="kobayashi2015" p="34" />.
	</p>
</S>

<S t="Why the classifications differ" id="analysis">
	<p>
		Bugaeva groups vowel endings, <i lang="ain-Latn">-ke</i>, and
		<i lang="ain-Latn">-ka</i> among nonproductive direct causatives. Her broader category relates
		their meanings and syntactic behavior to productive causation
		<Ref k="bugaeva2014" p="130–134, 143–144" />. Kobayashi distinguishes vowel and
		<i lang="ain-Latn">-ke</i> formation from causative <i lang="ain-Latn">-ka</i>, citing regional
		substitution, local alternatives, and attachment to already derived bases
		<Ref k="kobayashi2015" p="33–35" /> ‹contested›.
	</p>
	<Ex
		m="a=kor son a=ipe-rusuy-ka a=erampokiwen wakusu"
		g="4.A=have son 4.A=eat.meal-DES-CAUS 4.A=feel.sorry.for because"
		tr="Because I felt sorry about making my son go hungry, …"
		cite="kobayashi2015:34 n. 19"
		dial="SAR"
		place="Kimura Kimi corpus K7803231UP, cited through Nakagawa and Bugaeva 2012 by Kobayashi"
		note="Kobayashi gives the analysis ipe-rusuy-ka in the surrounding discussion. Person glosses here follow the transitive argument roles."
	/>
	<p>
		Kobayashi also analyzes <i lang="ain-Latn">ar-us-tek-ka</i> and leaves the precise status of
		<i lang="ain-Latn">tek</i>
		open <Ref k="kobayashi2015" p="34" />. These formations support his distinction without
		establishing that every derived base accepts
		<i lang="ain-Latn">-ka</i>.
	</p>
</S>

