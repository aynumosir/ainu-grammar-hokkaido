<S t="Person marking on predicates" id="person-indexing">
	<p>
		Ainu predicates distinguish participants through person marking. Independent pronouns are
		usually optional and can add emphasis or contrast; they do not replace the verb's person pattern
		<Ref k="nakagawa2024" p="163–165" />;
		<Ref k="bugaeva2012" p="472–473" />. The following description concerns ordinary indexed
		predicates; imperatives, copular complements, and support constructions have additional
		restrictions.
	</p>
	<p>
		Three role labels make the paradigms easier to compare. <strong>S</strong>
		is the sole argument of an intransitive; <strong>A</strong> is the agent-like argument of a
		transitive; <strong>O</strong> is its object. These are grammatical roles. An experiencer or an
		affected participant can be S, and an O need not be a physically affected patient
		<Ref k="bugaeva2012" p="472–473" />;
		<Ref k="nakagawa2024" p="129–134" />.
	</p>
	<Ex
		m="ku=mina"
		g="1SG.S=laugh"
		tr="I laughed."
		cite="bugaeva2012:473, example 14c"
		dial="CHI"
		note="Oda Ito example; the source also shows an optional independent pronoun kani."
	/>
</S>

