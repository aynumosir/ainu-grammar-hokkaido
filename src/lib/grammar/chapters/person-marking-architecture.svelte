<S t="Alignment depends on person" id="alignment">
	<p>
		Bugaeva describes this system as mixed alignment. In first singular, S and A share <i
			lang="ain-Latn">ku=</i
		>
		and contrast with O
		<i lang="ain-Latn">en=</i>: S = A ≠ O, a nominative–accusative pattern. First plural and fourth
		person distinguish all three roles: S ≠ A ≠ O, a tripartite pattern. Second and third person
		show a neutral pattern in the basic paradigm, S = A = O
		<Ref k="bugaeva2012" p="472" />.
	</p>
	<p>
		Formal identity does not erase the grammatical role. In the following Ishikari example, the
		first <i lang="ain-Latn">e=</i> indexes the object of “bring,” while the second indexes the subject
		of “come.”
	</p>
	<Ex
		m="nen e=ekte wa e=ek ka ki"
		g="who 2SG.O=bring CONJ 2SG.S=come FOC do"
		tr="Who made you come here?"
		cite="nakagawa2024:170, example 124"
		dial="ISH"
		note="Nakagawa cites Ōtsuka 1990: 27. The question literally relates someone bringing the addressee to the addressee's coming."
	/>
	<p>
		These differences concern person and argument role. They provide no lexical split in which one
		class of intransitives takes
		<i lang="ain-Latn">ku=</i> and another takes
		<i lang="ain-Latn">en=</i>. The verb's frame must be established before its person forms are
		interpreted.
	</p>
</S>

<S t="Combinations are not simple concatenations" id="interactions">
	<p>
		Saru and Chitose use <i lang="ain-Latn">eci=</i> for conversational first-person A acting on
		second-person O across four number combinations: singular or plural A with singular or plural O.
		This portmanteau coincides in form with the ordinary second-plural marker
		<Ref k="nakagawa2024" p="171, tables 28–29" />;
		<Ref k="sato2008" p="146–147" />.
	</p>
	<p>
		The reverse combinations also require a paradigm. Saru distinguishes second-plural A in <i
			lang="ain-Latn">eci=en=</i
		>
		and
		<i lang="ain-Latn">eci=un=</i>. Satō's principal Chitose account uses <i lang="ain-Latn">en=</i>
		and <i lang="ain-Latn">un=</i>
		for both second-singular and second-plural A, while also reporting the longer Chitose variants from
		Nakagawa's dictionary
		<Ref k="sato2008" p="147" />;
		<Ref k="nakagawa2024" p="171–173" />. See <Xr ch="eci-portmanteau-and-second-plural" /> for the dialect
		comparisons.
	</p>
</S>

<S t="Zero expression and the analysis of third person" id="third-person">
	<p>
		Third person has no audible exponent in these paradigms. Satō analyzes it as a zero person
		affix. Nakagawa instead treats third person as the absence of an affix in his arity analysis
		<Ref k="sato2008" p="121" />;
		<Ref k="nakagawa2024" p="137, 166–170" /> ‹contested›. Both descriptions account for clauses without
		a spoken person marker; the difference concerns the underlying grammatical representation.
	</p>
	<p>
		Satō's later criticism of Nakagawa's earlier account distinguishes semantic participants,
		available argument positions, and morphological indexing <Ref
			k="sato2023b"
			p="39, note 3, discussing Nakagawa 2001"
		/>. Those distinctions also matter for three-place verbs: one object index does not mean that
		the verb has only one semantic object. See
		<Xr ch="object-indexing-monotransitive" />.
	</p>
</S>

