<S t="Regional divisions and documentary samples" id="classification">
	<p>
		The broad division into Hokkaido, Sakhalin, and Kuril varieties is useful geographically, but
		grammatical and lexical boundaries require comparison of particular records. Within Hokkaido,
		southwestern and northeastern groupings recur in the literature, alongside distinctive features
		of Sōya and variation within each group
		<Ref k="nakagawafukazawa2022" p="§§1–2" />.
	</p>
	<p>
		Three influential datasets must be distinguished. Hattori and Chiri's 1960 comparison sampled
		nineteen localities: thirteen in Hokkaido and six in Sakhalin, with separate Kuril material from
		Torii. Hattori's 1964 dictionary directly investigated nine varieties, adding Torii's Kuril
		records as a tenth. Its Hokkaido varieties were Yakumo, Horobetsu, Saru at Hiratori, Asahikawa,
		Obihiro, Bihoro, Nayoro, and Sōya; the Sakhalin variety was Raichishka
		<Ref k="nakagawafukazawa2022" p="§2.1" />;
		<Ref k="hattori1964" p="37–38" />. Asai's later comparison selected 110 items, while Hattori and
		Chiri's 1960 calculations used 91 selected items. Their coverage and selection are consequently
		different <Ref k="nakagawafukazawa2022" p="§2.2; §3, opening" />.
	</p>
</S>

<S t="What a lexical similarity percentage measures" id="lexical-similarity">
	<p>
		Lexical comparison can count forms as corresponding despite regular sound differences. Nakagawa
		and Fukazawa illustrate this with the ‘tooth’ forms <i lang="ain-Latn"
			>mimak, nimak, imak, imah</i
		>. In their explanation of Hattori and Chiri's method, a correspondence counts as one match.
		Where multiple variants yield both a match and a non-match, the comparison contributes half a
		match. Uncertain or missing entries are excluded from the denominator
		<Ref k="nakagawafukazawa2022" p="§2.1" />.
	</p>
	<p>
		Their hypothetical calculation has 60 matches, 30 partial matches, and 10 non-matches: (60 + 15)
		/ 100 = 75%. This illustrates the method; it is not a new measurement of two dialects. Decisions
		about variant selection, correspondence, and missing data affect the result. A percentage
		measures similarity under those decisions and does not supply a date of separation <Ref
			k="nakagawafukazawa2022"
			p="§2.1"
		/>.
	</p>
	<p>
		The 1960 sample also omits Shizunai, Mitsuishi, and Urakawa. Descriptions of a boundary near
		Shizunai and Niikappu therefore draw on a broader body of evidence than that nineteen-locality
		table
		<Ref k="nakagawafukazawa2022" p="§2.3" />.
	</p>
</S>

<S t="Reanalysis and dialectometry" id="dialectometry">
	<p>
		Ono reexamines the position of Northern Kuril vocabulary. His analysis finds its strongest
		Hokkaido relationship with northeastern varieties, including Asahikawa and Nayoro, followed by
		southwestern varieties. He also compares artificial modifications of similarity matrices to
		examine the behavior of different classification methods. Those modified matrices are
		methodological demonstrations
		<Ref k="ono2020" p="234–235; 242–246, §2.3" />.
	</p>
	<p>
		Fukazawa and Ono use correspondence analysis to reconsider dialect boundaries. They normalize
		some accentual, glottal, and phonetic variation while retaining contrasts such as
		<i lang="ain-Latn">car/cara</i>. Their treatment of multiple variants lets a locality share
		lexical features with more than one group. The resulting overlap represents relationships in the
		analyzed data; it is not a genealogical tree with a date on each branch
		<Ref k="fukazawaono2024" p="161–171, §§4–5" />.
	</p>
	<p>
		Kasuga's conference abstract extends classification to 75 localities using existing lexical
		records, regularity features, geographic information, and established labels. It reports
		leave-one-out prediction of broad labels for 73 of 75 localities, with a lower subgroup score of
		0.653. These results evaluate recovery of the classification labels used in the study. They are
		neither a new 75-locality field survey nor independent proof of common ancestry for each
		predicted group <Ref k="kasuga2026" p="92–93, poster P-11" />.
	</p>
</S>

