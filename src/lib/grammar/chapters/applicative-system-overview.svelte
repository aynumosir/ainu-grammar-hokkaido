<S t="Adding an object to the verb's frame" id="overview">
	<p>
		The applicative prefixes <i lang="ain-Latn">e-, ko-, o-</i> allow a verb to take an additional
		object. A one-place base can become two-place, and a two-place base can become three-place <Ref
			k="nakagawa2024"
			p="192–194"
		/>;
		<Ref k="sato2008" p="243" />;
		<Ref k="bugaeva2006" p="187–188" />. The added object may express a participant otherwise
		introduced by a postposition, or a relation for which the lexical construction has no
		corresponding postpositional expression.
	</p>
	<Ex
		m="casi upsor ta ahun=an ruwe ne"
		g="house inside LOC enter=4.S EVID COP"
		tr="I entered the house."
		cite="bugaeva2006:187"
		dial="CHI"
		place="Example 1a; Oda Ito"
		note="The source's bracketed optional pronoun asinuma is omitted. Person labels follow this grammar's fourth-person convention."
	/>
	<Ex
		m="casi upsor a=o-ahun ruwe ne"
		g="house inside 4.A=APPL-enter EVID COP"
		tr="I entered the house."
		cite="bugaeva2006:187"
		dial="CHI"
		place="Example 1b; Oda Ito"
		note="The source's optional pronoun and written zero object marker are omitted; the overt person form is unchanged."
	/>
	<p>
		In the first construction, <i lang="ain-Latn">ta</i> marks the destination and the verb has S
		<i lang="ain-Latn">=an</i>. In the second, the destination is an object of
		<i lang="ain-Latn">o-ahun</i>, and the subject has A <i lang="ain-Latn">a=</i>. Bugaeva presents
		this as a prototypical applicative alternation
		<Ref k="bugaeva2006" p="187" />.
	</p>
</S>

<S t="A transitive base with two objects" id="valency">
	<Ex
		m="sirkorkamuy emus e-tuye"
		g="standing.tree sword APPL-cut"
		tr="He cut the standing tree with a sword."
		cite="nakagawa2024:193"
		dial="SAR"
		place="Example 173, from Monbetsu 1969:237, as reproduced by Nakagawa"
		note="The source prints etuye; the prefix boundary is shown here. The Ainu clause has no expressed subject noun phrase."
	/>
	<p>
		The base “cut” already takes the tree as its object. Applicative
		<i lang="ain-Latn">e-</i> adds the sword as another object
		<Ref k="nakagawa2024" p="193" />. Both objects occur without case postpositions. This is a
		three-place predicate even though third-person indexing is not overt.
	</p>
	<p>
		Bugaeva describes only one object index alongside the subject index, with first- and
		second-person objects receiving priority in the material she discusses. She leaves open whether
		the two objects behave symmetrically under every diagnostic
		<Ref k="bugaeva2006" p="188 n. 5" />. See <Xr ch="object-indexing-monotransitive" />.
	</p>
</S>

<S t="Meanings and lexical restrictions" id="functions">
	<p>
		The three prefixes overlap in semantic range. Instrumental uses often involve
		<i lang="ain-Latn">e-</i>, directed relations often involve <i lang="ain-Latn">ko-</i>, and
		<i lang="ain-Latn">o-</i>
		is strongly associated with location and direction. Those associations leave many lexical
		differences and less frequent uses
		<Ref k="bugaeva2006" p="190–192" />;
		<Ref k="sato2008" p="243–245" />.
	</p>
	<p>
		Nakagawa divides <i lang="ain-Latn">e-</i> into four constructional types: instrument, purpose,
		relations without a corresponding paraphrase, and place. His place type has paraphrases with
		<i lang="ain-Latn">ta, un</i>
		or <i lang="ain-Latn">peka</i>; only the third type lacks the listed alternative <Ref
			k="nakagawa2024"
			p="194, table 37"
		/>. Bugaeva uses finer semantic labels, including Content and Theme. These classifications
		divide the material by different criteria <Ref k="bugaeva2006" p="190–191" />.
	</p>
	<p>
		Satō notes that an applicative can preserve much of the base's meaning or create a more
		lexicalized relation. He also leaves the precise differences between applicative and
		postpositional alternatives incompletely understood <Ref k="sato2008" p="243" />. English
		“with,” “to,” or “at” consequently does not determine a prefix on its own.
	</p>
</S>

<S t="Recognizing the relevant morpheme" id="homophony">
	<p>
		Person <i lang="ain-Latn">e=</i> and applicative <i lang="ain-Latn">e-</i> have different
		functions. Nominal prefixes can also have the shapes <i lang="ain-Latn">e-</i> and
		<i lang="ain-Latn">o-</i>. Nakagawa's <i lang="ain-Latn">e-puni</i>, “raise someone's head,”
		contains the nominal element referring to the object's head and retains the base's two-place
		valency <Ref k="nakagawa2024" p="191–192, example 172" />. It is distinct from an applicative
		that adds an object.
	</p>
	<p>
		The argument frame, lexical meaning and person combination together support the analysis. A
		prefix such as <i lang="ain-Latn">ku=</i>, shared by S and A, cannot independently prove
		transitivity <Ref k="nakagawa2024" p="166–170" />.
	</p>
</S>

<S t="Related derivations and historical terminology" id="combinations">
	<p>
		Applicatives combine with causatives, reflexives, reciprocals, antipassives and incorporated
		material. Some words also contain both <i lang="ain-Latn">e-</i> and
		<i lang="ain-Latn">ko-</i>
		<Ref k="bugaeva2006" p="188" />;
		<Ref k="bugaevakobayashi2022" p="§4.1.1" />. The actual order and remaining arguments depend on
		the derivation; see <Xr ch="applicative-stacking-relativization-feeding" />.
	</p>
	<p>
		Nakagawa traces the earlier terms to Kindaichi and Chiri's 1936 “applicative” category and
		Chiri's 1942 description of prefixes expressing case relations
		<Ref k="nakagawa2024" p="192" />. The modern descriptions develop this shared domain while
		differing over lexical classes, semantic divisions and formal analysis. The individual prefixes
		are treated in <Xr ch="applicative-e" />, <Xr ch="applicative-ko" />, and
		<Xr ch="applicative-o" />.
	</p>
</S>
