<S t="Paired expressions" id="pairing">
	<p>
		Parallel expressions repeat a grammatical pattern while changing part of its wording. Nakagawa
		distinguishes pairs with related meanings, contrasting meanings, and numerical expressions. He
		notes that many pairs can occur in either order
		<Ref k="nakagawa2024" p="595–598, §25.4.1" />.
	</p>
	<p>
		His examples include the intensifying pair
		<i lang="ain-Latn">wen cironnup / toy cironnup</i> ‘bad fox / terrible fox’ and the contrasting
		<i lang="ain-Latn">kunne hene / tokap hene</i>
		‘night and day’. In another pair, carving an ordinary sword sheath and carving a treasured sword sheath
		evoke a peaceful domestic scene
		<Ref k="nakagawa2024" p="595–596, examples 1277, 1280, 1284" />.
	</p>
	<p>
		Endō describes such pairings alongside metaphor and formulaic expressions. Her account does not
		require matched lines to rhyme or assign every pairing a fixed composition rule
		<Ref k="endo2022" p="§4" />.
	</p>
</S>

<S t="Two, three, and abundance" id="numerical-pairs">
	<p>
		Pairs with <i lang="ain-Latn">tu</i> ‘two’ and
		<i lang="ain-Latn">re</i> ‘three’ commonly convey multiplicity. Nakagawa distinguishes
		repetition of a noun–verb sequence from two paired nominal expressions followed by a shared
		predicate
		<Ref k="nakagawa2024" p="597–598" />.
	</p>
	<Ex
		m="tu pu epuni re pu epuni"
		g="two storehouse erect three storehouse erect"
		tr="Building two storehouses, building three storehouses…"
		cite="nakagawa2024:597"
		dial="CHI"
		place="Example 1291"
		note="The passage describes a diligent woman's abundant harvest, requiring several storehouses. The paired numbers express abundance in that context."
	/>
	<p>
		The following embroidery formula instead shares a final predicate. Endō describes it as an
		exaggerated image of fine stitching
		<Ref k="endo2022" p="§4, example 16" />.
	</p>
	<Ex
		m="tu imeru kur re imeru kur kotuytuyke"
		g="two lightning reflection three lightning reflection cross"
		tr="Two flashes of light, three flashes of light pass across."
		cite="endo2022:§4, example 16; nakagawa1995:45, s.v. imeru"
		dial="CHI"
		place="Shirasawa Nabe, recording N8709011.KY"
		note="Endō excerpts a longer formula in the Chitose dictionary, omitting its initial tu uturu. Kur denotes reflected light or shade here."
	/>
	<p>
		Nakagawa also gives the more elevated
		<i lang="ain-Latn">otu / ore</i> pair and combinations with
		<i lang="ain-Latn">wan</i> ‘ten’. Their interpretation depends on the expression. A two–three
		pair does not require the hearer to add the numbers into a literal total
		<Ref k="nakagawa2024" p="598, examples 1294–1299" />.
	</p>
</S>

<S t="Parallelism in prose" id="prose">
	<p>
		Paired expressions also occur in prose tales. Nakagawa's Chitose example repeats a whole clause
		with ‘old’ and ‘new’, describing signs that people live nearby.
	</p>
	<Ex
		m="husko ni tuypa ru ka oka asir ni tuypa ru ka oka"
		g="old tree cut.PL trace ADD exist.PL new tree cut.PL trace ADD exist.PL"
		tr="There are traces of cutting old trees. There are traces of cutting new trees."
		cite="nakagawa2024:597"
		dial="CHI"
		place="Example 1289, citing Midoribon 1988:34"
		note="Nakagawa explicitly identifies this as prose, then supplies a verse counterpart as example 1290. That counterpart has additional words and different line divisions."
	/>
	<p>
		Another expansion repeats a noun before its positional expression:
		<i lang="ain-Latn">a=kor nupuri / nupuri tapka</i> ‘my mountain / the mountain's summit’.
		Nakagawa describes this device in both verse and ornate prose. The repetition can distribute an
		expression across lines without adding another participant
		<Ref k="nakagawa2024" p="599, §25.4.2" />.
	</p>
