<S t="Activity and resulting state" id="contrast">
	<p>
		A predicate followed by <i lang="ain-Latn">kor an</i> commonly describes an activity or change
		in progress. With <i lang="ain-Latn">wa an</i>, many predicates describe the state resulting
		from a change. The existential has plural forms
		<i lang="ain-Latn">oka</i> and <i lang="ain-Latn">okay</i>. These patterns are prominent in Saru
		and Chitose descriptions <Ref k="nakagawa2024" p="439–441" /><Ref k="sato2008" p="195–198" />.
	</p>
	<Ex
		m="tane ku=monrayke kor k=an ma"
		g="now 1SG.S=work CONJ 1SG.S=exist.SG FIN"
		tr="I am working now."
		cite="sato2008:195"
		dial="CHI"
		place="Lesson 25, example 1"
	/>
	<Ex
		m="isepo karip eus wa an ray wa an"
		g="rabbit trap be.caught CONJ exist.SG die CONJ exist.SG"
		tr="A rabbit is caught in the trap. It is dead."
		cite="sato2008:195"
		dial="CHI"
		place="Lesson 25, example 2"
		note="The two wa an combinations describe the resulting states of becoming trapped and dying."
	/>
	<p>
		The verb's meaning matters. Nakagawa distinguishes activity, change, and state predicates, while
		observing that a state word can also express a change into that state
		<Ref k="nakagawa2024" p="437–438" />. With motion <i lang="ain-Latn">ek</i>, his
		<i lang="ain-Latn">ek kor an</i> describes coming, and
		<i lang="ain-Latn">ek wa an</i> describes having arrived
		<Ref k="nakagawa2024" p="441, examples 986–987" />.
	</p>
</S>

<S t="Habitual activity and continuing circumstances" id="habitual">
	<p>
		<i lang="ain-Latn">Kor an</i> can describe regularly repeated activity. Nakagawa's Saru
		net-making example explicitly says ‘every day’; his charcoal-burning example describes someone's
		livelihood <Ref k="nakagawa2024" p="441–442" />.
	</p>
	<Ex
		m="kesto kesto ku=kor poysaranip ku=tese kor k=an kor easir k=eramasu"
		g="every.day every.day 1SG.A=have small.net.bag 1SG.A=weave CONJ 1SG.S=exist.SG CONJ really 1SG.A=enjoy"
		tr="I really enjoy weaving my little net bags day after day."
		cite="nakagawa2024:441–442"
		dial="SAR"
		place="Example 988, citing Honda 2001:24"
		note="The repeated temporal expression makes the habitual setting explicit. The sentence need not refer to weaving at the instant of speech."
	/>
	<p>
		Yoshikawa keeps the boundary between aspectual interpretation and accompanying circumstances
		open. In this account, the existential supplies continuation, while the whole construction and
		lexical predicate determine what continues
		<Ref k="yoshikawa2022" p="§§2–3, 5" />.
	</p>
</S>

<S t="Whose state does the existential describe?" id="person">
	<p>
		Each predicate has its own argument structure. When both concern the same person, the
		appropriate person series still depends on whether the first verb is transitive or intransitive.
		Nakagawa's <i lang="ain-Latn">a=supa wa a=e kor an=an</i> uses fourth-person actor prefixes on
		‘cook’ and ‘eat’, followed by the fourth-person subject suffix on the existential <Ref
			k="nakagawa2024"
			p="443, example 991"
		/>.
	</p>
	<Ex
		m="inaw k=asi wa an ruwe ne"
		g="prayer.stick 1SG.A=erect CONJ exist.SG EVID COP"
		tr="I have erected the inaw prayer stick."
		cite="sato2008:195"
		dial="CHI"
		place="Lesson 25, example 6"
		note="The speaker performs the erecting; the prayer stick is what remains standing. An therefore has a third-person subject."
	/>
	<p>
		Satō explicitly relates the existential's person and number to the affected object in this type
		of result-state construction <Ref k="sato2008" p="198, 201" />. Nakagawa also contrasts a
		singular hidden pot with plural clothes being worn:
		<i lang="ain-Latn">an</i> and <i lang="ain-Latn">okay</i> refer to those objects
		<Ref k="nakagawa2024" p="439–440" />.
	</p>
</S>

<S t="Lexical interpretation and disagreements" id="lexical">
	<p>
		Similar translations can conceal different constructions. Nakagawa describes
		<i lang="ain-Latn">mokor wa an</i> ‘be asleep’ through the result of falling asleep. He
		contrasts <i lang="ain-Latn">tere wa an</i> ‘wait’ with
		<i lang="ain-Latn">ekanunara kor an</i> ‘wait expectantly’, and discusses differences between
		intransitive <i lang="ain-Latn">inkar</i> and transitive
		<i lang="ain-Latn">nukar</i> ‘see’ <Ref k="nakagawa2024" p="444–445" />.
	</p>
	<p>
		His earlier account invoked active engagement in the event. He reports Satō's criticism that the
		fundamental contrast is continuation of an action versus continuation of its result, with active
		engagement arising contextually
		<Ref k="nakagawa2024" p="446, reporting Satō 2006:65" />. Satō's grammar also analyzes
		understanding as either a developing process or an acquired state, while treating the extension
		to perception predicates cautiously
		<Ref k="sato2008" p="199" />.
	</p>
</S>

<S t="States and regional limits" id="variation">
	<p>
		A temporary-state reading occurs in some existential combinations, but is not inherent in every <i
			lang="ain-Latn">wa an</i
		>. Yoshikawa's Shizunai examples include being a particular deity or a human being, where the
		author finds neither a clear temporary reading nor a clear difference from the simple copula
		<Ref k="yoshikawa2021shizunai" p="11–12, §3.2" />. The published forms also include
		<i lang="ain-Latn">e=ne wa an</i>
		and
		<i lang="ain-Latn">oka wa an</i>, which qualify a mechanical requirement that both predicates
		always show matching person and number forms.
	</p>
	<p>
		Tokachi provides a different restriction: Takahashi's account excludes first-person subjects
		from progressive <i lang="ain-Latn">kor an</i> and uses
		<i lang="ain-Latn">kan an</i> for such events <Ref k="takahashi2022" p="§4" />. These regional
		facts belong alongside the Saru/Chitose patterns.
	</p>
</S>

<S t="Negation and further combinations" id="negation">
	<p>
		For remaining without doing something, Satō gives the Chitose pattern
		<i lang="ain-Latn">(ka) somo ki no an</i>
		<Ref k="sato2008" p="201" />. This is a specific negative construction; its linker and scope
		must be considered alongside the positive patterns.
	</p>
	<p>
		Both existential combinations can also precede <i lang="ain-Latn">a</i>. Ma's Saru/Chitose study
		includes continuing activity, recent activity, habits, and persistent result states in these
		combinations <Ref k="ma2023" p="32, table 1" />. The meaning of the longer sequence requires its
		own analysis; see
		<Xr ch="perfective-anterior-a" />.
	</p>
</S>
