<S t="A series of forms with several uses" id="formal-set">
	<p>
		The label <em>fourth person</em> identifies a series of person forms whose interpretation
		depends on context. In the Saru/Chitose reference paradigm, it comprises intransitive S
		<i lang="ain-Latn">=an</i>, transitive A <i lang="ain-Latn">a=</i>, and object
		<i lang="ain-Latn">i=</i>. Other dialects also use A <i lang="ain-Latn">an=</i>
		<Ref k="nakagawa2024" p="168–170, 174–175" />.
	</p>
	<table>
		<thead><tr><th>Use</th><th>Typical reference</th></tr></thead>
		<tbody>
			<tr><td>Inclusive</td><td>The speaker and addressee, possibly with others</td></tr>
			<tr><td>Honorific</td><td>A respectfully addressed participant</td></tr>
			<tr><td>Indefinite</td><td>A participant whose identity is left unspecified</td></tr>
			<tr><td>Narrative</td><td>The narrator within a story</td></tr>
			<tr><td>Quoted speaker</td><td>The person whose words or thoughts are represented</td></tr>
		</tbody>
	</table>
	<p>
		These are Nakagawa's five broad uses, with dialect-specific distributions
		<Ref k="nakagawa2024" p="175–180" />. Bugaeva uses <em>indefinite</em> as a cover term and
		<em>logophoric</em> for reference to the represented speaker
		<Ref k="bugaeva2012" p="474–476" />. Tamura's more detailed semantic classification
		distinguishes eleven person categories; it does not posit eleven unrelated affix sets
		<Ref k="tamura1972" p="18–23, 35, 39" /> ‹contested›.
	</p>
</S>

<S t="The regional distribution of a= and an=" id="side-encoding">
	<p>
		Nakagawa describes <i lang="ain-Latn">a=</i> as the usual A form in western Hidaka and Chitose.
		In Tokachi, <i lang="ain-Latn">an=</i> occurs before a vowel-initial stem without initial
		accent, with <i lang="ain-Latn">a=</i> elsewhere. Shizunai uses both forms without that same
		conditioning distinction. Other eastern and northern descriptions show further variation, while
		verse formulae preserve <i lang="ain-Latn">an=</i> in Saru, Chitose and Horobetsu too <Ref
			k="nakagawa2024"
			p="168–169, examples 117–121"
		/>.
	</p>
	<p>
		The prefix and suffix are selected by argument role: A uses a prefix, S a suffix. They can
		therefore alternate across verbs describing the same participant. Combined A–O forms require the
		interaction paradigm; see <Xr ch="person-marking-architecture" /> and
		<Xr ch="eci-portmanteau-and-second-plural" />.
	</p>
</S>

<S t="Inclusive and indefinite reference" id="inclusive-impersonal">
	<p>
		Inclusive reference includes the addressee, as in an invitation to go together. An independent
		pronoun can make that reference explicit. In the indefinite-agent use, the corresponding pronoun
		is excluded in the descriptions under discussion: the construction leaves the agent unidentified <Ref
			k="nakagawa2024"
			p="175, 177"
		/>;
		<Ref k="sato2008" p="203–204" />;
		<Ref k="takahashi2015" p="208" />.
	</p>
	<Ex
		m="makanak a=ye kor pirka p an"
		g="how 4.A=say COND good NMLZ exist"
		tr="How should one say it?"
		cite="nakagawa2024:168"
		dial="CHI"
		place="Example 117"
	/>
	<p>
		An indefinite subject also occurs in clauses translated with an English passive. Satō and
		Nakagawa analyze the affected participant as retaining object status
		<Ref k="sato2008" p="203–206" />;
		<Ref k="nakagawa2024" p="177" />. An explicit agent may nevertheless be expressed through
		<i lang="ain-Latn">or(o) wa</i>, and that agent need not be human.
	</p>
	<Ex
		m="okkaypo sinen tanto kamuy oro wa a=rayke yakaye"
		g="young.man one.person today bear place ABL 4.A=kill REP"
		tr="A young man was reportedly killed by a bear today."
		cite="sato2008:203"
		dial="CHI"
		place="Example 6"
		note="Satō analyzes yakaye as a reportative expression structurally divisible into yak and a-ye."
	/>
	<p>
		The passive analysis and its syntactic diagnostics are examined in
		<Xr ch="middle-anticausative-passive" />. Inclusive and indefinite readings can also
		approach one another in context; Satō notes cases where their interpretation is intermediate <Ref
			k="sato2008"
			p="204"
		/>.
	</p>
</S>

<S t="Honorific address" id="honorific">
	<p>
		Honorific fourth person occurs especially in women's address to adult men and in prayers.
		Nakagawa describes these as usage tendencies. His examples include ordinary second-person
		address to deities alongside fourth-person address <Ref k="nakagawa2024" p="176" />. Refsing's
		Shizunai account also records respectful address through status nouns
		<Ref k="refsing1986" p="218" />.
	</p>
	<Ex
		m="hunak wa arki=an ruwe an"
		g="where ABL come.PL=4.S NMLZ exist"
		tr="Where have you come from?"
		cite="nakagawa2024:176"
		dial="CHI"
		place="Example 140"
		note="A woman addresses an adult man respectfully. The plural verb can refer to one addressee."
	/>
	<p>
		Respectful reference can select a plural verb for one person. Verbal number therefore needs to
		be interpreted alongside person use; see <Xr ch="suppletive-verbal-number" />.
	</p>
</S>

<S t="The narrator and verbal number" id="honorific-narrative">
	<p>
		A story told from a character's perspective can use fourth-person forms for that narrator.
		Western Hidaka, Chitose and Horobetsu can pair them with a singular verb when one narrator is
		involved. Shizunai, Kushiro and Tokachi examples use plural verbs even for a single narrator
		<Ref k="nakagawa2024" p="178–179" />;
		<Ref k="takahashi2015" p="209 n. 6" />.
	</p>
	<Ex
		m="sinen ne oka=an wa mismu=an na"
		g="one.person COP exist.PL=4.S CONJ be.bored=4.S FIN"
		tr="I was alone and was bored."
		cite="nakagawa2024:178"
		dial="SHI"
		place="Example 151"
		note="Sinen explicitly identifies one person; oka is nevertheless the plural existential stem."
	/>
	<p>
		Pronoun shape adds another distinction. Horobetsu has a plural-shaped fourth-person pronoun with
		singular narrative verbs. Shizunai has singular and plural pronoun forms while using plural
		narrative verbs <Ref k="nakagawa2024" p="179" />. Pronoun form, person series, verbal number and
		the number of people referred to must therefore be considered separately.
	</p>
</S>

<S t="Reference inside quotation" id="quotation">
	<p>
		In Saru reported speech, the quoted speaker can be represented by fourth-person forms where the
		original utterance would use first person. Nakagawa illustrates this with Haca's words as quoted
		by another speaker <Ref k="nakagawa2024" p="179, example 153" />.
	</p>
	<Ex
		m="a=ye wa anun katkemat a=nure"
		g="4.A=say CONJ other lady 4.A=make.hear"
		tr="I will tell it and let the lady from elsewhere hear it."
		cite="nakagawa2024:179"
		dial="SAR"
		place="Quoted portion of example 153, from Tamura 1984: 22, as reproduced by Nakagawa"
		note="The surrounding clause identifies Haca as the speaker being quoted."
	/>
	<p>
		Nakagawa considers this use well established in Saru and cautiously identifies related Chitose
		examples <Ref k="nakagawa2024" p="179–180" />. Takahashi's Tokachi account instead retains
		ordinary first-person forms in such everyday quotations. Switching person series inside literary
		quotations is a separate pattern in his description
		<Ref k="takahashi2015" p="207, 210–211" />.
	</p>
</S>

<S t="Semantic divisions and historical explanations" id="terminology">
	<p>
		Shared forms leave room for different semantic classifications. Nakagawa suggests that the
		inclusive, honorific and indefinite uses might be separated from narrator and quoted-speaker
		reference as different persons in Saru and Chitose, citing their differences in reference and
		number behavior <Ref k="nakagawa2024" p="180" /> ‹speculative›. His formal grouping therefore coexists
		with a possible finer analysis.
	</p>
	<p>
		Historical explanations also differ. Refsing proposes a connection between indefinite person and
		existential <i lang="ain-Latn">an</i>
		<Ref k="refsing1986" p="218–219" />. Takahashi explains the Tokachi functions through extensions
		of inclusive reference while leaving a possible indefinite origin for further investigation <Ref
			k="takahashi2015"
			p="211–212"
		/> ‹speculative›. Neither proposal makes every occurrence synonymous with “we.”
	</p>
</S>
