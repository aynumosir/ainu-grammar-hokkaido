<S t="Particles following place expressions" id="place-particles">
	<p>
		Ainu expresses many spatial relations with a place expression followed by a particle. In
		Nakagawa's Saru account, four particles form a spatial group:
		<i lang="ain-Latn">ta</i>, <i lang="ain-Latn">wa</i>,
		<i lang="ain-Latn">un</i>, and <i lang="ain-Latn">peka</i>
		<Ref k="nakagawa2024" p="296–299" />.
	</p>
	<table>
		<thead><tr><th>Particle</th><th>Main spatial function</th></tr></thead>
		<tbody>
			<tr><td lang="ain-Latn">ta</td><td>Location of a state or activity; arrival point</td></tr>
			<tr><td lang="ain-Latn">wa</td><td>Origin or starting point</td></tr>
			<tr><td lang="ain-Latn">un</td><td>Direction or goal</td></tr>
			<tr><td lang="ain-Latn">peka</td><td>An extended area in which something takes place</td></tr>
		</tbody>
	</table>
	<p>
		These particles require what Nakagawa calls a grammatical place. An ordinary noun may enter that
		construction through a locative noun such as
		<i lang="ain-Latn">or</i>. Words such as <i lang="ain-Latn">kim</i>
		already have place status and take the particle directly
		<Ref k="nakagawa2024" p="246–247, 296" />;
		<Ref k="sato2008" p="35–38" />. See <Xr ch="relational-and-spatial-nouns" />.
	</p>
</S>

<S t="Location, direction, and arrival" id="location-direction">
	<p>
		<i lang="ain-Latn">Ta</i> marks where someone is, where an activity occurs, or where movement
		arrives. Nakagawa also gives its use for a temporal position, such as after a person's death <Ref
			k="nakagawa2024"
			p="296–297"
		/>. Directional <i lang="ain-Latn">un</i> specifies the direction toward which an action is oriented.
	</p>
	<Ex
		m="ni ka ta hemesu=an"
		g="tree above LOC climb=4.S"
		tr="I climbed up the tree."
		cite="nakagawa2024:298–299, example 420"
		dial="SAR"
		note="First sentence of the example; Nakagawa interprets ta as the reached destination."
	/>
	<p>
		Nakagawa contrasts this with an instruction to climb toward a treetop using
		<i lang="ain-Latn">un</i>. In his explanation, <i lang="ain-Latn">un</i> points toward the
		destination and <i lang="ain-Latn">ta</i> presents arrival there
		<Ref k="nakagawa2024" p="298–299, examples 419–420" />. Satō's Chitose description also allows
		endpoints with
		<i lang="ain-Latn">un</i>, but leaves its difference from
		<i lang="ain-Latn">ta</i> unclear in his material
		<Ref k="sato2008" p="37–38" /> ‹contested›.
	</p>
	<p>
		Direction extends beyond motion. Nakagawa's Saru example about hearing a child's voice uses <i
			lang="ain-Latn">ne nay or un</i
		>, literally oriented toward the valley, where English would commonly say the voice came “from”
		it <Ref k="nakagawa2024" p="299, example 421" />.
	</p>
</S>

<S t="An origin and a route through something" id="origin-route">
	<p>
		<i lang="ain-Latn">Wa</i> marks an origin. Its longer form
		<i lang="ain-Latn">wano</i> is also used spatially and is especially common for temporal
		starting points in Nakagawa's description
		<Ref k="nakagawa2024" p="297" />.
	</p>
	<Ex
		m="nea pira or wa rap=an hine"
		g="that cliff place ABL descend.PL=4.S CONJ"
		tr="I came down from that cliff, and…"
		cite="nakagawa2024:297, example 413"
		dial="SAR"
	/>
	<p>
		A traversed opening is expressed differently. Nakagawa uses
		<i lang="ain-Latn">puyar kari apa kari</i> for moving objects through a window and doorway. In
		another scene, a hand extends inward from a doorway, and <i lang="ain-Latn">apa or wa</i>
		identifies that doorway as the action's starting point <Ref
			k="nakagawa2024"
			p="297–298, examples 416–417"
		/>. The scene determines whether an opening is construed as a route or an origin.
	</p>
</S>

<S t="An extended area" id="extended-area">
	<p>
		<i lang="ain-Latn">Peka</i> presents an extended domain of activity. Nakagawa's
		<i lang="ain-Latn">kim peka</i>
		occurs in a statement about accompanying someone through the mountains. His following example
		describes the ground splitting throughout the area where someone sits
		<Ref k="nakagawa2024" p="299, examples 423–424" />. Motion is therefore only one kind of event
		that can occur in a
		<i lang="ain-Latn">peka</i> phrase.
	</p>
	<p>
		The difference from route <i lang="ain-Latn">kari</i> also involves noun phrase structure.
		Nakagawa contrasts a phrase with ordinary noun plus
		<i lang="ain-Latn">or peka</i> against expressions such as
		<i lang="ain-Latn">ruyka kari</i> “across the mist bridge” and
		<i lang="ain-Latn">saramanto kari</i> “through the skylight”
		<Ref k="nakagawa2024" p="282, examples 369–372" />.
	</p>
</S>

<S t="Postposed adverbs and classification differences" id="postposed-adverbs">
	<p>
		Nakagawa distinguishes the case particles from postposed adverbs such as instrumental <i
			lang="ain-Latn">ani/ari</i
		>, comitative
		<i lang="ain-Latn">tura</i>, comparative
		<i lang="ain-Latn">akkari</i>, and route
		<i lang="ain-Latn">kari</i>. Postposed adverbs can occur independently with a contextually
		supplied reference point, whereas his case particles require an immediately preceding expression
		<Ref k="nakagawa2024" p="280–282, 296" />.
	</p>
	<Ex
		m="ru kari arpa"
		g="road via go.SG"
		tr="Someone goes along the road."
		cite="sato2008:39"
		dial="CHI"
		note="The source leaves the subject unexpressed."
	/>
	<p>
		O-series person marking is common with postposed adverbs, but Nakagawa explicitly gives <i
			lang="ain-Latn">a=opitta</i
		>
		as an exception for
		<i lang="ain-Latn">opitta</i> “all”
		<Ref k="nakagawa2024" p="281" />. The class's shared properties have lexical qualifications.
	</p>
	<p>
		The category inventory also varies by author. Satō places limit
		<i lang="ain-Latn">pak(no)</i> among case particles and comparison
		<i lang="ain-Latn">pak(no)</i> among postposed adverbs; Nakagawa places
		<i lang="ain-Latn">pak(no)</i> in the latter class
		<Ref k="sato2008" p="35–41" />;
		<Ref k="nakagawa2024" p="280–281" /> ‹contested›.
	</p>
</S>

<S t="Translative ne and the copula" id="translative-ne">
	<p>
		Nakagawa separates translative particle <i lang="ain-Latn">ne</i>, which describes a role,
		result, or composition, from the person-marked verb
		<i lang="ain-Latn">ne</i>. His numerical examples make the difference explicit <Ref
			k="nakagawa2024"
			p="300–301"
		/>:
	</p>
	<Ex
		m="ren a=ne wa oka=an"
		g="three.people 4.A=COP CONJ exist.PL=4.S"
		tr="The three of us lived there."
		cite="nakagawa2024:300, example 431"
		dial="SAR"
		note="Continuous excerpt; a=ne is the person-marked copular verb."
	/>
	<Ex
		m="tosir corpok ta a=aca-utar-i ren ne oka wa"
		g="bank below LOC 4.A=uncle-PL-POSS three.people TRANSL exist.PL CONJ"
		tr="My three uncles were below the bank, and…"
		cite="nakagawa2024:301, example 432"
		dial="SAR"
		note="Here ne is the translative particle in Nakagawa's analysis; surface acautari is segmented."
	/>
	<p>
		Satō questions the category assignment of <i lang="ain-Latn">ne</i> in his case-particle
		discussion <Ref k="sato2008" p="35–41" />
		‹contested›. Its classification should remain distinct from the observable contrast in person marking
		between these constructions.
	</p>
</S>

<S t="Regional direction forms and adnominal uses" id="regional-direction">
	<p>
		Nakagawa's regional summary gives directional
		<i lang="ain-Latn">un</i> in western Hidaka and farther west,
		<i lang="ain-Latn">en</i> in eastern Hidaka and Tokachi, and
		<i lang="ain-Latn">(e)ne</i> in eastern Hokkaido and Ishikari. He proposes a historical
		connection among these forms and verbal
		<i lang="ain-Latn">ne</i>
		<Ref k="nakagawa2024" p="302–303" /> ‹speculative›.
	</p>
	<p>
		He separately analyzes adnominal <i lang="ain-Latn">un</i>, as in
		<i lang="ain-Latn">kim un kamuy</i> “a god of the mountains,” through its noun-modifying syntax
		and relation to the verb
		<i lang="ain-Latn">un</i>. This adnominal use has a broader geographic distribution than western
		directional <i lang="ain-Latn">un</i>
		<Ref k="nakagawa2024" p="301–302" />. The shared spelling therefore needs interpretation within
		the construction.
	</p>
</S>
