<S t="Older Latin transcription" id="hepburn-tradition">
	<p>
		Batchelor, Kindaichi, and Chiri Yukie used Latin conventions related to Hepburn romanization.
		Their texts commonly have <em>ch</em> and <em>sh</em> where modern phonemic spelling uses
		<em>c</em> and <em>s</em>. They also use final <em>i</em> and <em>u</em> for sounds written
		<em>y</em> and <em>w</em> in modern transcription <Ref k="nakagawa2024" p="54–55" />. These
		conventions remain important when reading early editions and their reprints.
	</p>
	<p>
		There was substantial variation within this tradition. Chiri Yukie's treatment of final /r/
		differs from Batchelor's, and Chiri Mashiho later experimented with several other letter
		systems. “Older spelling” therefore identifies a period and a set of practices; it does not
		supply a single conversion rule for every text.
	</p>
</S>

