<S t="Voiced letters and consonant analysis" id="segments">
	<p>
		Batchelor, Kindaichi, and Chiri Yukie used <em>b, d, g</em> alongside <em>p, t, k</em>
		<Ref k="nakagawa2024" p="55" />. Modern phonemic transcription does not posit a corresponding
		voiced–voiceless opposition in the ordinary Ainu stop system
		<Ref k="nakagawa2024" p="25–28" />. A historical voiced letter may therefore record a
		pronunciation variant within a phoneme.
	</p>
	<p>
		Transcription history also includes changes in analysis. Chiri Mashiho's 1942 inventory counted
		syllable-initial <em>h</em> and syllable-final <em>x</em> separately, while his other letter
		choices sought closer correspondence between phonemes and characters
		<Ref k="nakagawa2024" p="56" />. A consonant count quoted from that work cannot be transferred
		without qualification to the Hokkaido inventory used here.
	</p>
</S>

<S t="Final r and vowel-like release" id="echo-vowels">
	<p>
		Final /r/ is especially important. Its release can sound vowel-like, and Batchelor commonly
		wrote an additional vowel. Nakagawa contrasts Batchelor's
		<i lang="ain-Latn">nukara</i> and <i lang="ain-Latn">pirika</i> with Chiri Yukie's
		<i lang="ain-Latn">nukar</i> “see” and <i lang="ain-Latn">pirka</i> “good”
		<Ref k="nakagawa2024" p="55" />. Chiri's spelling distinguishes final /r/ from a full /rV/
		syllable.
	</p>
	<p>
		The distinction is audible, though it can be difficult to identify in a single occurrence.
		Nakagawa illustrates /r/ versus /rV/ with <i lang="ain-Latn">etor</i> “nasal mucus” and
		<i lang="ain-Latn">etoro</i> “snore” <Ref k="nakagawa2024" p="30" />. Removing every vowel after
		<em>r</em>
		would erase genuine vowels as well as historical spelling expansions. See <Xr ch="rhotic-r" /> for
		the phonetic evidence.
	</p>
</S>

<S t="Word division and person forms" id="person-word-division">
	<p>
		A historical word division need not match a modern morphological analysis. Nakagawa's comparison
		of person notation includes continuous spelling, spacing, hyphens, and equals signs <Ref
			k="nakagawa2024"
			p="59–61"
		/>. Each makes different aspects of a form visible. The spelling of a person form can also
		change when it combines with a vowel-initial stem.
	</p>
	<p>
		For a grammatical example, an analyzed line can show the proposed boundaries while the source
		form remains available for comparison. The notation itself supplies no proof that the editor's
		divisions are the correct analysis. The conventions used in glossed examples are explained in <Xr
			ch="glossing-abbreviations-and-citation"
		/>.
	</p>
</S>

<S t="Source and dialect" id="dialect-mixture">
	<p>
		Batchelor's dictionary chiefly reflects Saru material, but its transcription and translations
		require critical reading <Ref k="nakagawa2024" p="91" />;
		<Ref k="refsing1986" p="§2.1" />. Refsing discusses serious inaccuracies while also recognizing
		that usable material can be recovered. The reliability of an entry depends on the particular
		form and evidence supporting it.
	</p>
	<p>
		Differences between an old entry and a modern dictionary may involve dialect, transcription,
		meaning, or error. Comparison with a documented speaker or a better-localized source helps
		separate these possibilities. Modernizing the letters alone does not establish the dialect or
		validate the translation.
	</p>
</S>

<S t="The development of phonemic spelling" id="comparative-ladder">
	<p>
		Chiri Yukie's distinction between /r/ and /rV/ influenced Kindaichi's transcription. Nakagawa
		notes that the revised practice appears in the <em>Taiden</em> section of Kindaichi's 1923
		<em>Ainu Seiten</em>, while other sections retain older conventions
		<Ref k="nakagawa2024" p="55, n. 3" />. Even a single volume can therefore require more than one
		set of reading conventions.
	</p>
	<p>
		Chiri Mashiho experimented with letters such as <em>č, j, ŭ</em>; his later practice moved
		closer to the forms familiar today. Nakagawa credits Hattori and Tamura with developing the
		phonemic transcription used from the 1950s, while documenting continuing disagreements about
		particular segments <Ref k="nakagawa2024" p="56–58" />. The development was gradual, with
		analytical and practical choices changing at different times.
	</p>
</S>

<S t="Using a historical passage" id="reading-today">
	<p>
		Begin with the edition's own spelling conventions and the provenance of the passage. Where a
		grammatical argument depends on a reading, cite the original spelling alongside the normalized
		form and explain any uncertain boundary or segment. A later edition can be a useful guide, but
		its changes also need attribution.
	</p>
