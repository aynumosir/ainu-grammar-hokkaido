<S t="Address and the worship predicate" id="predicate">
	<p>
		<i lang="ain-Latn">Mosir kor</i> modifies
		<i lang="ain-Latn">huci</i>: the deity is addressed through a relationship to the land. The
		worship predicate begins with first-person singular <i lang="ain-Latn">ku=</i>. Endō analyzes
		<i lang="ain-Latn">e-</i>
		as instrumental and
		<i lang="ain-Latn">ko-</i> as directed toward the addressee;
		<i lang="ain-Latn">pase</i> contributes the respectful sense of weight or importance <Ref
			k="endo2022"
			p="§2.3, example 13"
		/>.
	</p>
