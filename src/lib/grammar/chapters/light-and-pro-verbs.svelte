<S t="Several constructions with ki" id="ki-constructions">
	<p>
		The verb <i lang="ain-Latn">ki</i> “do” occurs as a lexical predicate, as support for a larger
		verbal expression, and as a pro-verb referring to previously mentioned material. These uses
		differ in person marking and phrase structure. Nakagawa distinguishes five functions, including
		two associated with verse
		<Ref k="nakagawa2024" p="372–378" />.
	</p>
	<p>
		Lexical <i lang="ain-Latn">ki</i> is transitive. The related-looking
		<i lang="ain-Latn">iki</i> “do” is intransitive and has its own behavior with additional number
		morphology
		<Ref k="nakagawa2024" p="159–160, 372" />. Their frames should be distinguished even when
		English uses “do” for both.
	</p>
</S>

<S t="Ki as the indexed main verb" id="main-verb-ki">
	<p>
		In one construction, person marking appears on
		<i lang="ain-Latn">ki</i> while the preceding expression names the activity. Nakagawa treats
		that expression as nominal and as the object of main-verb <i lang="ain-Latn">ki</i>
		<Ref k="nakagawa2024" p="372–373" />.
	</p>
	<Ex
		m="tapkar ku=ki nankor"
		g="dance 1SG.A=do probably"
		tr="I will probably dance."
		cite="nakagawa2024:372, example 723"
		dial="SAR"
		note="Nakagawa cites Tamura 1988b: 32. The original text is accessed through Nakagawa here."
	/>
	<p>
		The predicate carrying person marking is transitive even though the activity word <i
			lang="ain-Latn">tapkar</i
		>
		is ordinarily intransitive. Nakagawa also gives constructions in which a transitive verb and its object
		together supply the activity expression before
		<i lang="ain-Latn">ki</i>
		<Ref k="nakagawa2024" p="373, example 725" />.
	</p>
</S>

<S t="Support after an indexed verb" id="formal-verb-ki">
	<p>
		In Nakagawa's “formal verb” use, the lexical predicate retains person marking and <i
			lang="ain-Latn">ki</i
		>
		has none of its own. It allows a verbal expression to continue after material such as
		<i lang="ain-Latn">ka</i> or a following adverb. The two person patterns occur together in the
		following Saru example
		<Ref k="nakagawa2024" p="373–374" />.
	</p>
	<Ex
		m="ipe ka a=ki, rok=an ka ki wa oka=an kusu ne ruwe ne"
		g="eat ADD 4.A=do sit.PL=4.S ADD do CONJ exist.PL=4.S PURP COP fact COP"
		tr="We intend to live eating and sitting."
		cite="nakagawa2024:374, example 728"
		dial="SAR"
		note="Nakagawa interprets the subject as plural. The first ki carries a=; the second follows person-marked rok=an."
	/>
	<p>
		The preceding <i lang="ain-Latn">ka</i> therefore does not determine one person-placement rule
		across all these constructions. Nakagawa also notes that third-person examples without audible
		indices may not distinguish his two analyses
		<Ref k="nakagawa2024" p="374, example 729" />.
	</p>
</S>

<S t="Shizunai assertion and person placement" id="shizunai-assertion">
	<p>
		Refsing describes an assertive auxiliary
		<i lang="ain-Latn">ki</i> in Shizunai. Her examples include person marking on the lexical verb,
		on <i lang="ain-Latn">ki</i>, and on both <Ref k="refsing1986" p="208–210" />.
	</p>
	<Ex
		m="pirka ku=mokor ku=ki ayne"
		g="well 1SG.S=sleep 1SG.A=do CONJ"
		tr="I did sleep well, and then…"
		cite="refsing1986:210, example 330"
		dial="SHI"
		note="Refsing's spaces at person boundaries are normalized to equals signs; the source's continuation is retained."
	/>
	<p>
		Refsing states that when <i lang="ain-Latn">ka</i> intervenes, the person marker stays on the
		lexical verb in her Shizunai construction. Nakagawa's Saru <i lang="ain-Latn">ipe ka a=ki</i>
		belongs to a different described pattern
		<Ref k="refsing1986" p="210, examples 331–332" />;
		<Ref k="nakagawa2024" p="373–374" /> ‹contested›.
	</p>
</S>

<S t="Negation and verse" id="negation-and-verse">
	<p>
		The negative sequence is <i lang="ain-Latn">V (ka) somo ki</i>: optional
		<i lang="ain-Latn">ka</i>
		precedes the negative word. Nakagawa includes it in the formal-verb use, while Refsing describes the
		emphatic Shizunai pattern within her account of assertion
		<Ref k="nakagawa2024" p="374" />;
		<Ref k="refsing1986" p="209–210" />. Ordinary negation does not require every occurrence to be
		emphatic; see <Xr ch="negation-somo-standard-clausal" />.
	</p>
	<p>
		Verse supplies further uses. Nakagawa distinguishes a metrically useful
		<i lang="ain-Latn">ki</i> from poetic expressions in which person-marked
		<i lang="ain-Latn">ki</i>
		precedes an activity verb. He considers alternative constituent analyses for the latter, including
		a nominal interpretation of the following activity expression
		<Ref k="nakagawa2024" p="375–377" /> ‹contested›. These patterns extend beyond the ordinary postverbal
		support construction.
	</p>
</S>

<S t="Ki referring back to an earlier predicate" id="pro-verb">
	<p>
		Pro-verbal <i lang="ain-Latn">ki</i> can recover material from an earlier clause. Nakagawa
		discusses a passage where a heap of mouse tails and heads is first said to exist, with
		<i lang="ain-Latn">an</i>. A later phrase locates it by the grandparents' sleeping place and
		ends with
		<i lang="ain-Latn">ki pa ruwe an yakne</i>. He interprets
		<i lang="ain-Latn">ki</i> as referring back to the earlier existential predicate <Ref
			k="nakagawa2024"
			p="377, example 735"
		/>.
	</p>
	<p>
		He also allows a formal-verb analysis in which the location has been placed after an initially
		completed clause. Satō discusses a comparable problem in a Chitose text and presents his
		auxiliary explanation as provisional <Ref k="nakagawa2024" p="377–378" />;
		<Ref k="sato2008" p="297, commentary on lines 44–45" /> ‹contested›. The published evidence thus includes
		reference across intervening material, although its precise syntactic analysis remains open.
	</p>
</S>

<S t="Other predicates and auxiliary constructions" id="other-predicates">
	<p>
		The copula <i lang="ain-Latn">ne</i> and existential
		<i lang="ain-Latn">an</i> have their own argument frames and constructional uses. Their
		occurrence after nominal expressions should be analyzed separately from the functions of
		<i lang="ain-Latn">ki</i>
		<Ref k="nakagawa2024" p="129–132" />. See <Xr ch="copula-ne-predicate-nominals" /> and
		<Xr ch="nonverbal-predicate-tam-negation" />.
	</p>
	<p>
		“Auxiliary” can also refer to different structures in different descriptions. Nakagawa separates
		elements directly following a verb from auxiliary constructions linked by <i lang="ain-Latn"
			>wa</i
		>; verbs in the latter can carry their own person marking
		<Ref k="nakagawa2024" p="305–318, 450" />. Consequently, the person-placement diagnostics of one
		construction cannot be applied to every sequence of verbs.
	</p>
</S>
