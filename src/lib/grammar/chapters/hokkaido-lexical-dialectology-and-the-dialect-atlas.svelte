<S t="Reading a distribution map" id="maps">
	<p>
		A dialect map shows where a form was recorded. Different words produce different distributions:
		an east–west division, a central form surrounded by another form, or a pattern linking only
		particular regions. Nakagawa and Fukazawa compare maps of ‘mouth’, ‘tongue’, interrogatives, and
		kinship terms to show why one branching diagram cannot express every relationship
		<Ref k="nakagawafukazawa2022" p="§5" />.
	</p>
	<p>
		The history inferred from a map also depends on dates, consultant usage, and lexical analysis. A
		form recorded late may have been known long before it entered a survey. Multiple forms at one
		locality may be synonyms, differ in meaning, or differ between active use and recognition <Ref
			k="fukazawa2025"
			p="136–140"
		/>.
	</p>
</S>

<S t="Mouth, lip, and tongue" id="mouth">
	<p>
		The well-known comparison of <i lang="ain-Latn">par</i> and
		<i lang="ain-Latn">car</i> ‘mouth’ has several historical interpretations. Nakagawa and Fukazawa
		report an early
		<i>pa &gt; ca</i> proposal, Naert's common-source reconstruction, Kirikae's proposal of two
		older morphemes, and Fukazawa's account involving lexical replacement. They call the
		distribution a pseudo-correspondence because it is restricted to <i>a</i> and concentrated in
		words connected with the mouth
		<Ref k="nakagawafukazawa2022" p="§5.1" />.
	</p>
	<p>
		‘Lip’ illustrates the lexical detail. The forms
		<i lang="ain-Latn">capus, papus, catoy, patoy</i> combine the mouth element with different
		second members. Asahikawa and Nayoro have several variants whose usage differences remain
		unclear. For Chitose, Nakagawa distinguishes <i lang="ain-Latn">papus</i>, a projecting part,
		from <i lang="ain-Latn">patoy</i>, the lips as a whole <Ref
			k="nakagawafukazawa2022"
			p="§5.1, Maps 2–3, citing Nakagawa 1995:323"
		/>.
	</p>
	<p>
		<i lang="ain-Latn">Parunpe</i> ‘tongue’, analyzed as
		<i lang="ain-Latn">par</i> ‘mouth’ +
		<i lang="ain-Latn">un</i> ‘be in’ +
		<i lang="ain-Latn">pe</i> ‘thing’, occurs even in regions with
		<i lang="ain-Latn">car</i>. The account reports no corresponding
		<i lang="ain-Latn">carunpe</i>. Peripheral
		<i lang="ain-Latn">aw</i> around central
		<i lang="ain-Latn">parunpe</i> motivates the hypothesis that
		<i lang="ain-Latn">aw</i> is older; the map itself does not date that replacement. The wider
		<i lang="ain-Latn">pan/can</i>
		‘thin’ and
		<i lang="ain-Latn">pas/cas</i> ‘run’ comparisons remain problems for a purely mouth-based
		explanation <Ref k="nakagawafukazawa2022" p="§5.1, Map 4" />.
	</p>
	<p>
		Place names provide another kind of record. The same discussion reports Ishikari counts of
		eleven <i>par</i> and no <i>car</i>
		names, against nine <i>car</i> and no <i>par</i> names in Kushiro, and four <i>car</i> names in
		Nemuro. These are counts in the cited place-name material, not modern lexical-frequency
		measurements
		<Ref
			k="nakagawafukazawa2022"
			p="§5.1, Table 22, through Kirikae 1994:109–110 and Nagata 1909"
		/>.
	</p>
</S>

<S t="Interrogatives and kinship cross different boundaries" id="lexical-patterns">
	<p>
		The Saru–Chitose–Mukawa interrogative group includes forms such as
		<i lang="ain-Latn">hemanta</i> ‘what’ and
		<i lang="ain-Latn">hunna</i> ‘who’. Their relation to
		<i lang="ain-Latn">nep</i> and <i lang="ain-Latn">nen</i>
		differs from that in other varieties, where those forms can serve both interrogative and indefinite
		functions
		<Ref k="nakagawafukazawa2022" p="§5.2, Tables 23–24" />. The constructional qualifications
		appear in
		<Xr ch="interrogative-pro-forms" />.
	</p>
	<p>
		Kinship vocabulary draws another map. Coastal
		<i lang="ain-Latn">mici</i> ‘father’ crosses the usual northeastern–southwestern division, while
		<i lang="ain-Latn">iyapo</i> is associated with the Saru river mouth. Historical explanations of
		this distribution, including Yamada's proposed Pacific-coast grouping, remain interpretations of
		the lexical geography <Ref k="nakagawafukazawa2022" p="§5.3" />.
	</p>
</S>

<S t="Survey history and apparent lexical change" id="survey-history">
	<p>
		Fukazawa examines Chiri's preliminary survey records, probably from April 1955, against later
		surveys. The preliminary material covers fourteen dialects, with separate Tarantomari
		consultants. She tentatively distinguishes earlier recorded usage vocabulary from some later
		additions reflecting comprehension vocabulary
		<Ref k="fukazawa2025" p="136–139" />.
	</p>
	<p>
		For ‘three’, preliminary Yakumo and Oshamambe records have
		<i lang="ain-Latn">reppis</i>; the 1960 comparison has
		<i lang="ain-Latn">rep</i> for both; the 1964 dictionary has both forms for Yakumo. These
		records show why survey differences cannot automatically be read as successive innovations in
		speech. Fukazawa uses the wider distribution to propose a history for the
		<i lang="ain-Latn">reppis</i> family
		<Ref k="fukazawa2025" p="139" />. For quantitative comparisons and their sampling limits, see
		<Xr ch="hokkaido-dialect-classification-and-dialectometry" />.
	</p>
