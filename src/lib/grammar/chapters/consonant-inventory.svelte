<S t="Syllable-initial consonants" id="onset">
	<p>
		The stops /p, t, k/ have bilabial, dental, and velar articulations. A voiced pronunciation does
		not create a contrast with a separate series /b, d, g/. Nakagawa reports that /p/ is
		particularly liable to sound voiced, with /t/ and /k/ showing the tendency less strongly
		<Ref k="nakagawa2024" p="28" />.
	</p>
	<p>
		The affricate /c/ is commonly described as [tʃ] or [tɕ]. Bugaeva records speaker variation
		between [tʃ] and [ts] in <i lang="ain-Latn">cup</i> “sun; moon”
		<Ref k="bugaeva2012" p="466" />. Shiraishi, reporting Tamura, specifically notes a [ts]
		realization before /u/ <Ref k="shiraishi2022" p="§3" />. These descriptions concern variation
		within the affricate phoneme.
	</p>
	<p>
		The two fricatives have different distributions of phonetic variation. The palatalization of /s/
		is described in <Xr ch="s-palatalization" />. For /h/, Nakagawa describes [h], [ç], and [ɸ]
		realizations according to the following vowel. Shiraishi reports Tamura's observation that this
		conditioning can be weak, especially in recordings of older speakers
		<Ref k="nakagawa2024" p="28" />; <Ref k="shiraishi2022" p="§3" />. A single phonetic table would
		conceal some of this speaker variation.
	</p>
</S>

<S t="Syllable-final consonants" id="coda">
	<p>
		Nine consonants occur as Hokkaido syllable codas: /p, t, k, s, m, n, r, y, w/. The affricate /c/
		and fricative /h/ are excluded from this position. Analyses with /ʔ/ also exclude it from the
		coda <Ref k="nakagawa2024" p="27" />;
		<Ref k="bugaeva2012" p="467" />. The permitted combinations are described in
		<Xr ch="syllable-template" />.
	</p>
	<p>
		Final stops are unreleased: the closure is made without a following audible burst. Bugaeva gives <i
			lang="ain-Latn">kap</i
		>
		[kap̚] “skin; bark,”
		<i lang="ain-Latn">kut</i> [kut̚] “girdle,” and <i lang="ain-Latn">sik</i> [sik̚] “eye” <Ref
			k="bugaeva2012"
			p="465"
		/>. A final stop is therefore a consonant of the syllable even when its release is difficult to
		hear.
	</p>
	<p>
		Sakhalin comparisons require a separate inventory of permitted codas. Tangiku describes the
		widespread replacement of historical final stops by /h/, while also identifying Sakhalin
		localities that preserve final stops <Ref k="tangiku2022" p="§§2.2–2.3" />. These dialect
		differences should be retained in comparisons; see
		<Xr ch="sakhalin-and-kuril-ainu-contrast" />.
	</p>
</S>

<S t="Nasals and place assimilation" id="nasals">
	<p>
		The nasal phonemes are /m/ and /n/. Final /n/ is ordinarily articulated with the tongue tip at
		the teeth, but it takes the place of a following consonant: [m] before /p, m/ and [ŋ] before
		/k/. Nakagawa illustrates the latter with
		<i lang="ain-Latn">honkor</i> [hoŋkor] “be pregnant”
		<Ref k="nakagawa2024" p="30" />.
	</p>
	<p>
		Nasals before labials are written differently across dictionaries. A spelling with
		<em>n</em> can preserve a morphological relationship or follow a convention for nasal
		neutralization; it need not indicate an alveolar pronunciation in that position
		<Ref k="nakagawa2024" p="58–59" />. The alternatives are explained in
		<Xr ch="orthographic-standardization-and-word-division" s="nasal-labial" />.
	</p>
</S>

<S t="Voicing variation" id="voicing">
	<p>
		Stops and the affricate can be voiced between vowels, after a nasal, and after /r/. Shiraishi
		gives <i lang="ain-Latn">hapo</i> ~ <i lang="ain-Latn">habo</i> “mother,”
		<i lang="ain-Latn">tampe</i> ~ <i lang="ain-Latn">tambe</i> “this one,” and
		<i lang="ain-Latn">unarpe</i> ~ <i lang="ain-Latn">unarbe</i> “aunt,” reporting the descriptive
		literature <Ref k="shiraishi2022" p="§3.1" />. Voicing is variable in these environments.
	</p>
	<p>
		Shiraishi also reports Yamashita's study of recorded Saru speech, in which the post-nasal
		environment had the highest voicing rate, approximately 40%. That figure describes the study's
		sample. It is evidence of a tendency, with ample unvoiced realizations remaining
		<Ref k="shiraishi2022" p="§3.1" />.
	</p>
</S>

<S t="The rhotic" id="rhotic">
	<p>
		The common realization of /r/ is a tap [ɾ], with trilled, lateral, and stop-like variants
		reported in the literature. In final position it often has a vowel-like release
		<Ref k="nakagawa2024" p="28, 30" />; <Ref k="shiraishi2022" p="§3.2" />. The contrast between
		final /r/ and /r/ followed by a vowel is established by pronunciation and by morphological
		behavior. It is examined in <Xr ch="rhotic-r" />.
	</p>
</S>

<S t="Glides" id="glides">
	<p>
		The glides /y/ and /w/ occur at the beginning and end of syllables. In final position they have
		vowel-like realizations, but their morphological behavior supports grouping them with
		consonants. Shiraishi points to the selection of the consonant-following nominalizer in <i
			lang="ain-Latn">okay-pe</i
		>
		“those who are” and
		<i lang="ain-Latn">siw-pe</i> “bitter thing” <Ref k="shiraishi2022" p="§3" />. The evidence and
		the older diphthong terminology are discussed in <Xr ch="glides-w-y" />.
	</p>
</S>
