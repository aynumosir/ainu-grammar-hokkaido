<S t="The verb and the material following it" id="overview">
	<p>
		The ordinary Ainu clause places noun phrases and adverbial expressions before its verb phrase.
		Auxiliaries, sentence endings and clause-linking material may follow the lexical verb <Ref
			k="nakagawa2024"
			p="361–365"
		/>. “Verb-final” describes the predicate's relation to its preceding participants and modifiers;
		it does not mean that the lexical verb must be the final spoken word.
	</p>
	<Ex
		m="sine uepeker ku=nu rusuy"
		g="one story 1SG.A=hear DES"
		tr="I want to hear a story."
		cite="nakagawa2024:365"
		dial="SAR"
		place="Example 706"
		note="The desiderative auxiliary follows ku=nu. Sine is the adnominal numeral modifying uepeker."
	/>
	<p>
		Nakagawa's structural description permits lexical noun phrases to be absent when their
		interpretation can be supplied from context. His technical term for a sentence containing all of
		the predicate's lexical arguments does not make shorter utterances ungrammatical
		<Ref k="nakagawa2024" p="362" />; see <Xr ch="argument-realization-indexing" />.
	</p>
</S>

<S t="Preverbal order and participant interpretation" id="arguments">
	<p>
		The descriptions differ in the role they assign to noun-phrase order. Shibatani treats SOV as
		basic and uses a bear–person comparison to show order determining the ordinary interpretation.
		He also recognizes OSV where context or lexical meaning makes the roles clear <Ref
			k="shibatani1990"
			p="23"
		/>. Nakagawa places greater emphasis on the absence of a grammatically fixed subject–object
		order and on contextual interpretation ‹contested› <Ref k="nakagawa2024" p="363–365" />.
	</p>
	<Ex
		m="menoko ne hike a=macihi menoko monrayke epakasnu"
		g="woman COP NMLZ 4.POSS=wife woman work teach"
		tr="My wife taught our daughter women's work."
		cite="nakagawa2024:364"
		dial="CHI"
		place="Example 700"
		note="Menoko ne hike identifies the female child in the narrative. The order is addressee–actor–theme before the verb."
	/>
	<Ex
		m="menoko ne hike menoko monrayke a=macihi epakasnu"
		g="woman COP NMLZ woman work 4.POSS=wife teach"
		tr="My wife taught our daughter women's work."
		cite="nakagawa2024:364"
		dial="CHI"
		place="Example 701"
		note="This example has addressee–theme–actor order. Nakagawa's examples 700–702 come from the same speaker in different stories; they are not an elicited permutation paradigm."
	/>
	<p>
		The interpretation remains wife as teacher, daughter as learner, and work as the subject matter.
		Nakagawa notes that the reverse assignment of wife and daughter is structurally possible but
		less plausible in the described situation. He tentatively connects initial position with
		topic-marked expressions in some examples
		<Ref k="nakagawa2024" p="364–365" />. The Saru example he adds has yet another order and
		separate provenance.
	</p>
</S>

<S t="Adverbials and head-final phrases" id="modifiers">
	<p>
		Adverbial phrases can occur among the noun phrases before the verb. Nakagawa illustrates a
		temporal expression, a subject, an instrumental phrase, a manner adverb and an object in that
		order <Ref k="nakagawa2024" p="361" />.
	</p>
	<Ex
		m="numan k=unuhu ipepasuy ani yupkeno ku=teke kik"
		g="yesterday 1SG.POSS=mother chopsticks INS severely 1SG.POSS=hand hit"
		tr="Yesterday my mother hit my hand hard with chopsticks."
		cite="nakagawa2024:361"
		place="Author's illustration 696"
		note="The two first-person prefixes belong to possessed nouns. The actor of kik is the mother, and its object is the hand."
	/>
	<p>
		Postpositions follow their noun phrases; demonstrative modifiers and modifying clauses precede
		their head nouns. These patterns motivate the description of Ainu as generally head-final <Ref
			k="shibatani1990"
			p="23"
		/>;
		<Ref k="nakagawa2024" p="365" />. Nominal numerals and particles have their own positions, so
		this generalization does not replace the constructional description in
		<Xr ch="noun-phrase-structure" />.
	</p>
</S>

<S t="Clause endings and later specifications" id="endings">
	<p>
		Sentence-final forms and connectives follow the predicate, while negators such as
		<i lang="ain-Latn">somo</i> and prohibitive forms precede the verb phrase
		<Ref k="nakagawa2024" p="361–365" />. A clause may also be followed by another expression
		specifying a participant. Bugaeva describes examples in which a nounless predicate is followed
		by a noun phrase with support verb <i lang="ain-Latn">ki</i>, making the participant clearer <Ref
			k="bugaeva2022"
			p="§4.3"
		/>. These extended constructions require their own analysis; they do not erase the ordinary
		verb-final pattern. See <Xr ch="light-and-pro-verbs" />.
	</p>
</S>
