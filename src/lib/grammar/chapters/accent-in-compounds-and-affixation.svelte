<S t="Accent in complex forms" id="prosodic-word">
	<p>
		A complex Ainu form may preserve the accent of one component or receive an accent based on the
		syllable structure of the whole. Both patterns occur in the accentual varieties described here.
		Their distribution depends on the construction and sometimes on the particular word <Ref
			k="nakagawa2024"
			p="52–54"
		/>;
		<Ref k="shiraishi2022" p="§§5.1–5.2" />.
	</p>
	<p>
		The usual first-or-second-syllable rule provides the background. A closed initial syllable
		ordinarily bears the accent, while an open initial syllable is ordinarily followed by an
		accented second syllable. This chapter concerns the ways morphology interacts with that pattern.
		The regional limits of the rule are described in
		<Xr ch="pitch-accent-placement-rule" />.
	</p>
</S>

<S t="First-element priority in compounds" id="compounds">
	<p>
		Compounds often retain the accent of their first member. Nakagawa gives
		<i lang="ain-Latn">kamúy</i> “god” plus <i lang="ain-Latn">nomí</i> “pray to” as
		<i lang="ain-Latn">kamúynomi</i> “pray to the gods.” A monosyllabic first member can also bear
		the resulting accent: <i lang="ain-Latn">ni</i> “tree” plus
		<i lang="ain-Latn">tek</i> “hand” gives <i lang="ain-Latn">nítek</i> “branch”
		<Ref k="nakagawa2024" p="54" />.
	</p>
	<Ex
		m="kamúy-nomi"
		g="god-pray.to"
		tr="pray to the gods"
		cite="nakagawa2024:54"
		dial="HK"
		note="The source writes kamúynomi and gives the two components separately. The boundary and English glosses are supplied here."
	/>
	<p>
		Shiraishi describes a broader first-element tendency in compounds and close syntactic
		combinations. In the account he reports from Tamura, the second member's accent becomes
		secondary and can disappear <Ref k="shiraishi2022" p="§5.2" />. Accent on the first member does
		not mean that only one syllable has high pitch: Nakagawa explicitly allows the later syllables
		of <i lang="ain-Latn">kamúynomi</i> to remain high
		<Ref k="nakagawa2024" p="49" />.
	</p>
</S>

<S t="Exceptions to first-element priority" id="somo">
	<p>
		A frequent alternative appears when a consonant-final first component combines with a
		vowel-initial second component. Shiraishi gives <i lang="ain-Latn">cep-étu</i>
		“fish nose” and <i lang="ain-Latn">nay-étok</i> “source of a stream,” with accent on the second
		syllable of the whole form <Ref k="shiraishi2022" p="§5.2, example 25" />. The consonant before
		the boundary becomes the onset of that syllable.
	</p>
	<p>
		Shiraishi reports an earlier explanation in terms of lexicalization: some combinations come to
		behave like simple words. Satō gives a structural account using resyllabification and rhythmic
		feet, illustrated by <i lang="ain-Latn">aw-ósma</i> “go inside”
		<Ref k="shiraishi2022" p="§5.2" />; <Ref k="satoni2022" p="§2" />. These are attributed analyses
		of the accent pattern. Nakagawa explicitly treats compound accent as a tendency with
		word-specific exceptions <Ref k="nakagawa2024" p="54" />.
	</p>
</S>

<S t="Derivational prefixes" id="derivational">
	<p>
		Nakagawa describes the prefixed derivative as a domain for the usual accent rule. Adding a
		prefix can therefore alter the position of accent within the original stem
		<Ref k="nakagawa2024" p="53" />.
	</p>
	<S t="A derivative with yay-" id="yay">
		<p>
			His example <i lang="ain-Latn">iták</i> “speak” becomes
			<i lang="ain-Latn">yáykoytak</i> “talk to oneself,” analyzed as
			<i lang="ain-Latn">yay-ko-itak</i>. The whole derivative begins with the closed syllable
			/yay/, which bears the accent <Ref k="nakagawa2024" p="53" />. The glide in the following
			portion is part of the vowel-contact phenomena treated in
			<Xr ch="glide-epenthesis-hiatus-resolution" />.
		</p>
	</S>
	<S t="Nominal e- and applicative e-" id="applicatives">
		<p>
			Nakagawa also gives <i lang="ain-Latn">puní</i> “lift something” beside
			<i lang="ain-Latn">epúni</i> “lift someone's head”
			<Ref k="nakagawa2024" p="53" />. Here the initial element is his nominal
			<i lang="ain-Latn">e-</i> referring to the head, distinguished in his morphological account
			from argument-adding applicative <i lang="ain-Latn">e-</i>
			<Ref k="nakagawa2024" p="191–193" />. The accent example consequently has a specific
			derivational analysis despite the shared spelling of the prefixes.
		</p>
	</S>
	<S t="Causative suffixes and koré" id="causative-kore">
		<p>
			Suffixes usually leave the stem accent in place in Nakagawa's account. His causative examples
			include <i lang="ain-Latn">é-re</i> “make someone eat,”
			<i lang="ain-Latn">kú-re</i> “make someone drink,” and
			<i lang="ain-Latn">kár-e</i> “make someone do or make something”
			<Ref k="nakagawa2024" p="53" />. The first two have an accented open initial syllable, an
			exception to the usual placement pattern.
		</p>
		<p>
			<i lang="ain-Latn">Koré</i> “give,” related to <i lang="ain-Latn">kor</i>
			“have,” has second-syllable accent. Nakagawa explains this through weakened awareness of the derivation
			and application of the ordinary word rule
			<Ref k="nakagawa2024" p="53" /> ‹speculative›. Satō's Chitose treatment states a broader distinction
			between accent retention with <i lang="ain-Latn">-re</i> and accent movement with
			<i lang="ain-Latn">-e</i>, illustrated by
			<i lang="ain-Latn">koré</i>
			<Ref k="sato2008" p="234" />. Nakagawa's
			<i lang="ain-Latn">káre</i> makes the source difference relevant to any general rule for rhotic-final
			stems ‹contested›.
		</p>
	</S>
</S>

<S t="Accent with person markers" id="person-affix">
	<p>
		Person prefixes fall into different accentual classes in the southern descriptions. The
		distinction concerns how they affect the following stem, separately from which participant they
		identify <Ref k="nakagawa2024" p="52–53" />;
		<Ref k="bugaeva2012" p="472–473" />.
	</p>
	<S t="Prefixes included in accent placement" id="shifting">
		<p>
			Nakagawa illustrates <i lang="ain-Latn">ku=</i>, <i lang="ain-Latn">e=</i>, and
			<i lang="ain-Latn">ci=</i> as part of the domain of accent placement.
			<i lang="ain-Latn">Hopúni</i> “rise” becomes
			<i lang="ain-Latn">ku=hópuni</i> “I rise”: the accented stem syllable moves one position to
			the left <Ref k="nakagawa2024" p="52" />. Bugaeva includes
			<i lang="ain-Latn">en=</i>, <i lang="ain-Latn">un=</i>, and
			<i lang="ain-Latn">i=</i> in the class affected by the general rule
			<Ref k="bugaeva2012" p="473" />.
		</p>
		<Ex
			m="ku=hópuni"
			g="1SG.S=rise"
			tr="I rise."
			cite="nakagawa2024:52"
			dial="HK"
			note="The source contrasts this with unprefixed hopúni. English gloss supplied here."
		/>
		<p>
			Contraction can obscure this relationship. Nakagawa derives
			<i lang="ain-Latn">k=ómare</i> from <i lang="ain-Latn">ku=ómare</i>, with accent shift
			preceding loss of the prefix vowel. He identifies Saru, Chitose, and Mukawa as contracting
			varieties, contrasting them with the uncontracted forms of most other dialects <Ref
				k="nakagawa2024"
				p="52"
			/>. The surface initial syllable is open in
			<span lang="ain-Latn">kó.ma.re</span> despite its initial accent.
		</p>
	</S>
	<S t="Prefixes that preserve stem accent" id="non-shifting">
		<p>
			<i lang="ain-Latn">A=</i> and <i lang="ain-Latn">eci=</i> preserve the stem's accent. Nakagawa
			gives <i lang="ain-Latn">a=omáre</i> and
			<i lang="ain-Latn">eci=etú</i> “your nose” (addressing several people), with the accent at the
			same location within the stem as in the unprefixed forms <Ref k="nakagawa2024" p="53" />.
			Shiraishi gives the corresponding pattern with
			<i lang="ain-Latn">a-onáha</i> and <i lang="ain-Latn">eci-onáha</i>
			<Ref k="shiraishi2022" p="§5.1, example 19" />.
		</p>
	</S>
	<S t="Secondary accent on person suffixes" id="secondary">
		<p>
			Shiraishi reports secondary accent on person suffixes alongside the stem accent:
			<span lang="ain-Latn">iˈruska-ˌas</span> “we, excluding you, are angry” and
			<span lang="ain-Latn">ipˈe-ˌan</span> “we, including you, eat.” The marks ˈ and ˌ indicate
			primary and secondary accent in his transcription
			<Ref k="shiraishi2022" p="§5.1, example 20" />.
		</p>
		<p>
			The same account lacks the secondary accent after a closed monosyllabic stem:
			<span lang="ain-Latn">ˈcis-an</span> “we cry” and
			<span lang="ain-Latn">ˈsap-an</span> “we go downstream”
			<Ref k="shiraishi2022" p="§5.1, example 21" />. The stem's shape thus matters within the
			suffixal pattern as well.
		</p>
	</S>
</S>

<S t="Suffixes and the limits of accent retention" id="neutral-suffixes">
	<p>
		Shibatani gives <i lang="ain-Latn">nú-pa</i> “hear, with a plural object” beside
		<i lang="ain-Latn">nú-re</i> “make someone hear,” both retaining stem accent
		<Ref k="shibatani1990" p="§2.3, example 1" />. These forms support the tendency for suffixes to
		leave accent unchanged, also stated by Nakagawa
		<Ref k="nakagawa2024" p="53" />.
	</p>
	<p>
		Possessive forms involve their own stem shapes and suffixes. Their complete formation must be
		distinguished from the addition of a final optional extension. The patterns are described in <Xr
			ch="affiliative-suffix-morphophonology"
		/>; the general suffix tendency here leaves room for the lexical and morphological exceptions
		discussed above.
	</p>
</S>

<S t="Accent as evidence for word structure" id="diagnostics">
	<p>
		Bugaeva uses the difference between shifting and nonshifting person prefixes as part of her
		argument for distinct affix and clitic statuses
		<Ref k="bugaeva2012" p="472–473" />. Satō's account of incorporation uses rhythmic feet and
		resyllabification to explain accentual unity in complex words
		<Ref k="satoni2022" p="§2" />. These are analyses built on the accent patterns; the broader
		category questions are treated in <Xr ch="person-marking-architecture" />
		and <Xr ch="noun-incorporation-object" />.
	</p>
	<p>
		Accent and consonant sandhi can extend over different domains. Shiraishi documents sandhi across
		words and, for /r/, across sentence boundaries in his Saru sample
		<Ref k="shiraishi2022" p="§6.2" />. A boundary relevant to compound accent is therefore not
		automatically a boundary for every phonological process.
	</p>
</S>
