<S t="Compounds and locative connections" id="compounds-locatives">
	<p>
		Some nouns change suffix class as the second element of a compound. Nakagawa compares <i
			lang="ain-Latn">at</i
		>
		→ <i lang="ain-Latn">atu(hu)</i>
		with <i lang="ain-Latn">tar-at</i> →
		<i lang="ain-Latn">tar-aci(hi)</i>, the cord section of a carrying strap. He suggests that a
		weakened semantic connection with the independent noun allows the common
		<i lang="ain-Latn">-i</i>
		pattern
		<Ref k="nakagawa2024" p="228" /> ‹speculative›. His observation concerns some compounds, rather than
		an obligatory suffix replacement in every compound.
	</p>
	<p>
		Nakagawa also connects many vowel-repeating forms historically with locative nouns. He compares
		locative <i lang="ain-Latn">sut</i> “lower edge/hem,” long <i lang="ain-Latn">sutu</i>, with
		ordinary noun
		<i lang="ain-Latn">tap-sut</i> “shoulder” and its affiliative
		<i lang="ain-Latn">tap-sut-u(hu)</i>. He explicitly leaves some members of the class outside
		this explanation
		<Ref k="nakagawa2024" p="228" /> ‹speculative›.
	</p>
</S>

