<S t="Phonological and historical analyses" id="analyses">
	<p>
		The vowel patterns have been discussed in terms of harmony, assimilation, and morphological
		classes. Shiraishi reviews these accounts, including Chiri's historical proposal and later
		formal analyses, while emphasizing lexical restrictions and troublesome vowel combinations
		<Ref k="shiraishi2022" p="§4.5" /> ‹contested›. The descriptive classes above do not by themselves
		decide between those accounts.
	</p>
	<p>
		For the long forms, Kindaichi and Chiri propose a development from repeated vowels to an
		intervening <i lang="ain-Latn">h</i>
		<Ref k="kindaichi1936" p="17" /> ‹speculative›. Refsing reviews competing views about whether short
		or long forms are basic
		<Ref k="refsing1986" p="85" /> ‹contested›. The present alternation is better established than its
		historical derivation.
	</p>
</S>

<S t="Sakhalin comparison" id="sakhalin-contrast">
