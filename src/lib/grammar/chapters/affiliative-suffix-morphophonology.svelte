		<i lang="ain-Latn">ram-uhu</i>. He also describes the restoration of stem-final consonants in
		<i lang="ain-Latn">teh</i>
		→
		<i lang="ain-Latn">tek-ihi</i> and <i lang="ain-Latn">otoh</i> →
		<i lang="ain-Latn">otop-ihi</i>
		<Ref k="tangiku2022" p="§§4.1–4.2, reporting Murasaki 1979: 83–84" />. These Sakhalin patterns
		require their own account; the Hokkaido short/long pairing cannot simply be transferred to them.
	</p>
</S>
