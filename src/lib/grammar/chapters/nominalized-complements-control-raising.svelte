<S t="A clause used as an argument" id="complements">
	<p>
		A complement clause can serve as a subject or object of another predicate. Bugaeva also records
		the less common possibility of an actor complement with a transitive predicate <Ref
			k="bugaeva2012"
			p="498"
		/>. Common overt markers include
		<i lang="ain-Latn">hi/i</i>, <i lang="ain-Latn">p/pe</i>, and forms with more specific modal or
		sensory meanings. The choice depends on the construction and the selecting predicate.
	</p>
	<Ex
		m="hekattar tura sinot=an hi ka a=ona-ha kopan"
		g="children with play=4.S NMLZ ADD 4.POSS=father-POSS refuse"
		tr="My father refused to let me play with the children."
		cite="nakagawa2024:507"
		dial="SAR"
		place="Example 1161"
		note="Hi presents the activity as the object of kopan. The father is the matrix subject; the narrator is the subject of sinot. The prefix on onaha is possessive."
	/>
	<p>
		Nakagawa treats the material before <i lang="ain-Latn">hi</i> as an internally complete clause:
		the narrator plays, with the children as companions. The formal noun does not fill an open
		participant role within that clause <Ref k="nakagawa2024" p="508" />. This distinguishes the
		complement from a relative that identifies a participant; see <Xr
			ch="prenominal-gap-relative-clauses"
		/>.
	</p>
	<p>
		A complement can instead be the subject of a property predicate. Bugaeva's example
		<i lang="ain-Latn">ku=kemeyki kor ku=itak hi iyotta pirka</i> evaluates talking while sewing as
		best <Ref k="bugaeva2016" p="101, quoting Tamura 2000:126" />. The complete glossed example
		appears in <Xr ch="lexical-head-formal-noun-nominalization" />.
	</p>
</S>

<S t="Perception and content" id="perception">
	<p>
		Sensory or situation heads can specify what is perceived. Their complement uses extend beyond
		sentence-final evidential expressions. Satō's Chitose example places
		<i lang="ain-Latn">ruwe</i> before ‘see’
		<Ref k="sato2008" p="174, example 2" />.
	</p>
	<Ex
		m="okkaypo tumasnu ruwe ku=nukar wa k=eramusinne"
		g="young.man be.healthy NMLZ 1SG.A=see CONJ 1SG.A=be.relieved"
		tr="I saw that the young man was well and felt relieved."
		cite="sato2008:174"
		dial="CHI"
		place="Lesson 22, example 2"
		note="The broad NMLZ gloss identifies ruwe's complement function here. The example does not contain a final ruwe ne construction."
	/>
	<p>
		Nakagawa likewise gives <i lang="ain-Latn">siri</i> with a clause describing a woman walking
		through a field as the object of ‘see’, and <i lang="ain-Latn">hawe</i> with crying as the
		object of ‘hear’ <Ref k="nakagawa2024" p="507, 509" />. The head's meaning and the selecting
		predicate jointly determine the relation.
	</p>
</S>

<S t="Complements without an overt nominalizer" id="zero">
	<p>
		An overt formal noun is not required in every construction. Bugaeva explicitly analyzes zero
		nominalization alongside nominalizing-word constructions, illustrating it with material before <i
			lang="ain-Latn">ki</i
		>
		‘do’
		<Ref k="bugaeva2016" p="99–100" />.
	</p>
	<Ex
		m="apun-no a=reska pirka a=reska ki wa"
		g="peaceful-ADV 4.A=bring.up be.good 4.A=bring.up do CONJ"
		tr="We were bringing them up peacefully, bringing them up gently."
		cite="bugaeva2016:99"
		dial="CHI"
		place="Example 4b, citing Bugaeva 2004:285"
		note="Bugaeva brackets the two reska phrases together as the material nominally used before ki. The person marking on reska remains visible."
	/>
	<p>
		In this account, embedding does not introduce a special nonfinite verb paradigm. Person and
		aspect morphology can remain in the embedded material
		<Ref k="bugaeva2016" p="99–100" />. Zero nominalization describes its nominal function without
		an overt nominalizing word.
	</p>
</S>

<S t="Bare verbs and auxiliary constructions" id="auxiliary-boundary">
	<p>
		Satō distinguishes another pair of patterns by the location of person marking. His <i
			lang="ain-Latn">mokor k=esinki</i
		>
		‘I am tired of sleeping’ has personal marking on <i lang="ain-Latn">esinki</i>; he treats bare
		<i lang="ain-Latn">mokor</i>
		as nominally used as its object. In <i lang="ain-Latn">ku=mokor esinki</i>, personal marking
		belongs to the first verb and <i lang="ain-Latn">esinki</i> has an auxiliary use
		<Ref k="sato2008" p="89–90" />.
	</p>
	<p>
		The distinction is construction-specific. Satō also finds register differences in verbal and
		auxiliary uses and leaves some functional differences unresolved. A bare form can therefore
		require more analysis than simply assigning it an unexpressed third-person subject.
	</p>
</S>

<S t="Participant reference and structural analysis" id="reference">
	<p>
		A complement's subject may differ from the matrix subject, as in the father's refusal, or the
		same person may participate in both predicates, as in being tired of sleeping. The observed
		reference pattern is one part of the analysis. Terms such as <em>control</em>
		and <em>raising</em> make additional claims about the grammatical relation between predicates and
		participants; shared reference alone does not establish them.
	</p>
	<p>
		The descriptions above instead distinguish overt nominalization, zero nominalization, nominal
		use of a bare verb, and auxiliary use through their stated structural diagnostics
		<Ref k="bugaeva2016" p="99–101" /><Ref k="sato2008" p="89–90" />. Indirect content selected by
		<i lang="ain-Latn">ye</i>
		and
		<i lang="ain-Latn">ramu</i> introduces further constructional choices, treated in
		<Xr ch="kuni-complementizer-purpose-complements" />.
	</p>
</S>
