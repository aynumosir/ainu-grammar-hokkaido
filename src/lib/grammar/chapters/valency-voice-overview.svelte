<S t="Causation changes the participant structure" id="causative">
	<Ex
		m="ku=sinot"
		g="1SG.S=play"
		tr="I played."
		cite="nakagawa2024:431"
		place="Example 955; published grammatical illustration, variety unspecified"
	/>
	<Ex
		m="hapo en=sinot-te"
		g="mother 1SG.O=play-CAUS"
		tr="Mother made me play."
		cite="nakagawa2024:431"
		place="Example 955′; published grammatical illustration, variety unspecified"
	/>
	<p>
		The participant playing changes from S to O; the mother is the added causer and transitive
		subject. Nakagawa uses this pair to show a distinction that would remain unexpressed if both
		participants were third person <Ref k="nakagawa2024" p="431" />. See <Xr
			ch="causative-morphological-re-e-te"
		/> and
		<Xr ch="causee-marking-ditransitive-double-causative" />.
	</p>
	<p>
		Indefinite <i lang="ain-Latn">-yar/-ar</i> has a different effect. The causer replaces the
		base's subject, and the causee is unavailable as a core object, so the number of core arguments
		remains unchanged <Ref k="nakagawa2024" p="200–201, 432–433" />;
		<Ref k="bugaevakobayashi2022" p="§4.3.1" />. An oblique phrase can still identify a causee in
		documented constructions; see <Xr ch="permissive-sociative-causative-yar" />.
	</p>
</S>

<S t="Lexical pairs and morphological analysis" id="lexical-pairs">
	<p>
		Lexical pairs such as <i lang="ain-Latn">mak-ke</i> “open” intransitively and
		<i lang="ain-Latn">mak-a</i> “open something” differ in their argument structure. Nakagawa
		treats their endings as forming suffixes on a root and assigns no independent arity to those
		suffixes <Ref k="nakagawa2024" p="199" />. Bugaeva places such formations within a broader
		comparison of direct causation, while Kobayashi distinguishes forming suffixes from causative
		suffixes <Ref k="bugaeva2014" p="130–132" />;
		<Ref k="kobayashi2015" p="33–35" /> ‹contested›.
	</p>
	<p>
		The analyses differ over how the related words are derived. A table of argument counts should
		therefore distinguish an operation on an existing verb from alternative formations of verbs from
		a shared root. The lexical patterns are treated in
		<Xr ch="transitivizer-ka-valency-pairs" />.
	</p>
</S>

<S t="Voice, interpretation, and complex verbs" id="voice">
	<p>
		Changes in viewpoint do not always change the number of indexed arguments. Indefinite-agent
		constructions can receive passive translations, with competing accounts of the affected
		participant's syntactic status <Ref k="sato2008" p="203–206" />;
		<Ref k="shibatani1990" p="58–60" /> ‹contested›. See <Xr ch="middle-anticausative-passive" /> for
		the evidence behind those analyses.
	</p>
	<p>
		Complex verbs can combine several operations, but each attested combination needs its own
		argument account. An inventory of double applicatives, causatives and incorporation patterns
		does not establish that every operation can be repeated together without restriction
		<Ref k="nakagawa2024" p="207–210" />;
		<Ref k="bugaevakobayashi2022" p="§6" />. The distinction between person markers and derivational
		elements is described in <Xr ch="verb-word-template" />.
	</p>
</S>
