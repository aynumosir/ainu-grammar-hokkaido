<S t="Arguments, indexes, and expressed phrases" id="overview">
	<p>
		Valency concerns the arguments a predicate takes. A clause need not express each argument with a
		separate noun phrase, and a verb's person indexes do not directly count its arguments. A
		three-place verb may have a subject and two objects while displaying only an A–O person
		combination <Ref k="sato2008" p="147–148" />;
		<Ref k="nakagawa2024" p="127, 135–137" />. These distinctions underlie the valency and voice
		constructions described in this part of the grammar.
	</p>
	<p>
		Person marking can diagnose a change where the paradigm distinguishes S and A. Fourth-person
		<i lang="ain-Latn">=an</i> versus <i lang="ain-Latn">a=</i>, and first-plural
		<i lang="ain-Latn">=as</i> versus <i lang="ain-Latn">ci=</i>, supply such contrasts.
		First-singular <i lang="ain-Latn">ku=</i> is shared by S and A
		<Ref k="nakagawa2024" p="166–170" />. The latter form alone cannot identify a predicate's
		transitivity.
	</p>
</S>

