<S t="Question types and intonation" id="question-types">
	<p>
		Polar questions ask whether a proposition holds; content questions ask for a person, place,
		reason, or other missing information. Ainu uses intonation, interrogative particles, and nominal
		clause endings in both types. The forms of the question words differ by region; their paradigms
		appear in <Xr ch="interrogative-pro-forms" />
		<Ref k="nakagawa2024" p="409–418" />.
	</p>
	<p>
		Nakagawa describes polar questions with the same words as a statement and a higher final
		contour. Satō likewise describes a tendency toward a higher, stronger ending in Chitose. These
		observations do not make rising pitch obligatory: Fukuda explicitly notes for Saru that a
		question need not rise, and a rising utterance need not be a question. Intonation, grammatical
		form, and context contribute together
		<Ref k="nakagawa2024" p="409" /><Ref k="sato2008" p="134" />
		<Ref k="fukuda1961" p="34, note 22" />.
	</p>
</S>

<S t="Nominal endings in questions" id="nominal-endings">
	<p>
		A polar question can end in a <Xr ch="evidential-schema-overview">formal noun</Xr>, including
		<i lang="ain-Latn">ruwe</i>
		or
		<i lang="ain-Latn">hawe</i>, without a following copula.
	</p>
	<Ex
		m="cip c=o yakka pirka ruwe"
		g="boat 1PL.EXCL.A=board even.if be.good EVID"
		tr="May we board the boat?"
		cite="nakagawa2024:409"
		dial="CHI"
		place="Example 843"
		note="The permission question ends in bare ruwe. The source marks this example as Chitose."
	/>
	<p>
		Satō gives a three-way pattern for Chitose
		<i lang="ain-Latn">ruwe, hawe, siri, humi</i>:
		<i lang="ain-Latn">ne</i> follows in statements,
		<i lang="ain-Latn">an</i> in content questions, and neither follows in polar questions. His
		explanation in terms of a situation's nature and existence is a proposed interpretation of this
		pattern
		<Ref k="sato2008" p="136–137" />.
	</p>
	<p>
		Other documented questions require a broader account. Nakagawa's Saru content questions include
		endings in
		<i lang="ain-Latn">ruwe ne ya</i> and
		<i lang="ain-Latn">p ne ya</i>. Fukuda compares a Saru ‘Where are you going?’ question ending in
		<i lang="ain-Latn">siri an</i>
		with one ending in bare <i lang="ain-Latn">siri</i>; she describes
		<i lang="ain-Latn">an</i> as dispensable in this construction
		<Ref k="nakagawa2024" p="410, examples 853–854" />
		<Ref k="fukuda1961" p="35, §32" />.
	</p>
	<p>
		Interrogative expressions also have conventional restrictions. For Saru, Nakagawa gives <i
			lang="ain-Latn">hemanta an?</i
		>
		for ‘What is it?’ and says that <i lang="ain-Latn">hemanta ne?</i> is normally not used with
		that meaning. The latter can mean ‘why’; shortened
		<i lang="ain-Latn">hnta ne</i> is attested with the meaning ‘What is it?’
		<Ref k="nakagawa2024" p="411–412" />.
	</p>
</S>

<S t="Ya and the effect of the question" id="ya">
	<p>
		Final <i lang="ain-Latn">ya</i> occurs in both polar and content questions. Descriptions of its
		conversational effect depend on the comparison. Fukuda finds that adding it softens the
		corresponding Saru question. Bugaeva also describes a softening effect. Satō observes that
		direct questions on a bare Chitose verb, with intonation or
		<i lang="ain-Latn">ya</i>, suit urgent situations or close relations; he describes formal-noun
		questions as more polite
		<Ref k="fukuda1961" p="33–34, §29" />
		<Ref k="bugaeva2012" p="497" />
		<Ref k="sato2008" p="75, 134–135" />.
	</p>
	<p>
		The relation between interrogative <i lang="ain-Latn">a</i> and
		<i lang="ain-Latn">ya</i> also varies across descriptions. Refsing analyzes postconsonantal
		<i lang="ain-Latn">a</i>
		as a pronunciation of <i lang="ain-Latn">ya</i> in Shizunai. Nakagawa treats them as separate
		particles where Chitose and Ishikari place
		<i lang="ain-Latn">a</i> after vowels
		<Ref k="refsing1986" p="229" />
		<Ref k="nakagawa2024" p="332–333" />.
	</p>
</S>

<S t="He after phrases and predicates" id="he">
	<p>
		<i lang="ain-Latn">He</i> can follow the expression whose interpretation is being checked. Nakagawa's
		next example responds to ‘when there was nothing to eat’ by asking whether the speaker means a famine.
	</p>
	<Ex
		m="keman hi ta he"
		g="famine NMLZ LOC Q"
		tr="During the famine?"
		cite="nakagawa2024:409"
		dial="SAR"
		place="Example 846, citing Tamura 1984:26"
		note="The question consists of a time expression followed by he."
	/>
	<p>
		The same particle can follow a conditional clause or a final predicate. In the following content
		question it follows the verb, while the questioned reason is expressed earlier. Here
		<i lang="ain-Latn">hnta</i> is a form of
		<i lang="ain-Latn">hemanta</i> ‘what’
		<Ref k="nakagawa2024" p="409, example 847; 411, example 855 and Table 77" />.
	</p>
	<Ex
		m="hnta kusu somo e=ipe he"
		g="what because NEG 2SG.S=eat Q"
		tr="Why aren't you eating?"
		cite="nakagawa2024:411"
		dial="SAR"
		place="Example 855"
	/>
	<p>
		Satō also illustrates alternative questions by repeating
		<i lang="ain-Latn">he</i> after two source phrases: the speaker asks whether the information
		came from the addressee's mother or father
		<Ref k="sato2008" p="63" />. Combinations such as <i lang="ain-Latn">ruwe he an</i> are attested
		in polar questions <Ref k="nakagawa2024" p="410, example 848" />.
	</p>
</S>

<S t="Embedded questions and replies" id="embedded-questions">
	<p>
		A clause ending in <i lang="ain-Latn">ya</i> can serve as a complement. The embedded question
		may concern an unknown quantity or location, as well as whether an event occurred
		<Ref k="fukuda1961" p="33–34, §29" />
		<Ref k="sato2008" p="179" />.
	</p>
	<Ex
		m="hempak pa ka apkas=an humi ne ya ka a=eramuskari"
		g="how.many year ADD walk=4.S EVID COP Q ADD 4.A=not.know"
		tr="I do not even know how many years I walked."
		cite="nakagawa2024:333"
		dial="CHI"
		place="Example 574"
		note="Nakagawa describes ya both as the embedded clause's final particle and as a complement marker. Fourth-person forms refer to the narrator here."
	/>
	<p>
		Replies can be shorter than a clause. Fukuda and Satō describe nominal and locative answers
		followed by <i lang="ain-Latn">un</i>. Nakagawa's negative replies include Saru
		<i lang="ain-Latn">somo</i>
		and Horobetsu <i lang="ain-Latn">senne</i>
		<Ref k="fukuda1961" p="34–35, §30" />
		<Ref k="sato2008" p="74" />
		<Ref k="nakagawa2024" p="408, examples 840–841" />. Further conversational endings appear in
		<Xr ch="sentence-final-particles-illocutionary-force" />.
	</p>
</S>
