<S t="A noun inside the verb" id="overview">
	<p>
		Object incorporation combines a noun with a verb into a complex verbal stem. Nakagawa contrasts <i
			lang="ain-Latn">cep ku=koyki</i
		>
		“I catch fish” with
		<i lang="ain-Latn">ku=cep-koyki</i> “I fish.” In the incorporated form, person marking precedes
		the noun–verb combination <Ref k="nakagawa2024" p="481–482" />. The noun supplies a participant
		within the stem, reducing the remaining argument frame.
	</p>
	<p>
		The first-person singular form alone does not distinguish transitive A from intransitive S,
		since both use <i lang="ain-Latn">ku=</i>. Fourth-person forms show the change more clearly: A
		<i lang="ain-Latn">a=</i>
		corresponds to S <i lang="ain-Latn">=an</i>
		<Ref k="nakagawa2024" p="482" />; <Ref k="satoni2022" p="§2" />.
	</p>
	<Ex
		m="pukusa a=ta"
		g="wild.garlic 4.A=dig"
		tr="We dig wild garlic."
		cite="satoni2022:§2"
		place="Example 2a"
		note="Satō's source comparison. Accent marks are omitted and person boundaries use =. The source translates fourth person inclusively."
	/>
	<Ex
		m="pukusa-ta=an"
		g="wild.garlic-dig=4.S"
		tr="We dig wild garlic."
		cite="satoni2022:§2"
		place="Example 2b"
		note="The incorporated verb is one-place. It takes the fourth-person S form; this is the second member of Satō's comparison."
	/>
	<p>
		Third-person forms may supply less morphological evidence because their person indexes are zero.
		Nakagawa cautions that a written space or a presumed intonational contrast cannot by itself
		settle whether a third-person sequence is a compound
		<Ref k="nakagawa2024" p="482" />. See <Xr ch="verb-word-template" /> for the broader question of word
		boundaries.
	</p>
</S>

<S t="A remaining object with three-place bases" id="valency">
	<p>
		Incorporating one object normally removes one argument. A two-place verb becomes one-place,
		while a three-place verb becomes two-place. Satō illustrates the latter with
		<i lang="ain-Latn">hoku-kore</i> “provide someone with a husband”
		<Ref k="sato2008" p="224–225" />. Nakagawa gives a corresponding comparison with
		<i lang="ain-Latn">mat</i> “wife” <Ref k="nakagawa2024" p="486" />.
	</p>
	<Ex
		m="ku=po mat ku=kore"
		g="1SG.POSS=son wife 1SG.A=give"
		tr="I give my son a wife."
		cite="nakagawa2024:486"
		place="Author's lexical comparison"
	/>
	<Ex
		m="ku=po ku=mat-kore"
		g="1SG.POSS=son 1SG.A=wife-give"
		tr="I arrange a marriage for my son."
		cite="nakagawa2024:486"
		place="Author's lexical comparison"
		note="The son remains the object of the two-place incorporated verb. A boundary has been added inside the source's matkore."
	/>
	<p>
		Applicatives extend the available object relations to instruments, companions and places. For
		example, Nakagawa's <i lang="ain-Latn">cip-e-kusa</i> means to take someone across a river by
		boat and retains that person as an object
		<Ref k="nakagawa2024" p="486–487" />. The derivation and ordering of such forms are treated in <Xr
			ch="applicative-stacking-relativization-feeding"
		/>.
	</p>
</S>

<S t="Generic reference and conventional events" id="genericity">
	<p>
		Satō describes incorporated nouns as typically generic and the resulting verbs as often naming
		conventional activities. His contrast between <i lang="ain-Latn">pet</i> “river” and the
		specific river name <i lang="ain-Latn">Sikotpet</i> illustrates a restriction:
		<i lang="ain-Latn">ku=pet-tomotuye</i> “I cross a river” is accepted, while his
		<i lang="ain-Latn">*ku=Sikotpet-tomotuye</i> is rejected
		<Ref k="sato2008" p="226" />; <Ref k="satoni2022" p="§2" />. This restriction concerns the
		incorporated noun's reference, even though a particular river may be understood from the event's
		context.
	</p>
	<p>
		Satō also distinguishes an incorporated stem from a phrase modified by
		<i lang="ain-Latn">pirka</i> “good.” His <i lang="ain-Latn">pirka pukusa</i> “good wild garlic”
		does not form the incorporated constituent in the comparison above
		<Ref k="satoni2022" p="§2" />. Incorporation nevertheless remains a productive means of word
		formation in his account, with lexical and semantic restrictions
		<Ref k="satoni2022" p="§1" />. Productivity and conventional lexical meanings coexist.
	</p>
</S>

<S t="Compound nouns and two incorporated objects" id="complex-nouns">
	<p>
		A compound noun can itself be incorporated. Nakagawa gives
		<i lang="ain-Latn">kikinni-kutek-kar</i> “make a rowan fence” and
		<i lang="ain-Latn">pan-usey-kar</i> “make thin porridge,” both attested with S
		<i lang="ain-Latn">=an</i>. He treats each noun compound as one constituent, so it reduces arity
		by one. These lexical compounds differ from Satō's modified phrase
		<Ref k="nakagawa2024" p="487–488" />.
	</p>
	<p>
		Nakagawa also documents incorporation of two separate objects:
		<i lang="ain-Latn">cep-ya-o-kuta</i> “dump fish onto the shore” incorporates both the fish and
		the location, while <i lang="ain-Latn">itak-mak-kus-te</i> expresses using hidden words. He
		calls such formations rare and suggests that the object–location relation may constrain them
		‹speculative› <Ref k="nakagawa2024" p="488–489" />. Compound-noun incorporation supplies one
		internally complex noun; these two-object formations supply two arguments.
	</p>
</S>

<S t="Possession and the other incorporation types" id="possession">
	<p>
		The restriction on an inflectionally marked possessor inside object incorporation differs from
		derivational possession with reflexive or reciprocal prefixes. Subject incorporation also
		permits a possessed-noun stem whose possessor becomes the subject of the whole verb
		<Ref k="satoni2022" p="§§3.3, 4" />. These distinctions are developed in
		<Xr ch="noun-incorporation-subject-possessor-stranding" /> and
		<Xr ch="noun-incorporation-oblique-polysynthesis-debate" />. The latter chapter also compares
		Satō's quasi-incorporation analysis with Tamura's and Nakagawa's descriptions.
	</p>
	<p>
		Object incorporation is the largest category in Satō's published Chitose sample, accounting for
		85.9% of the incorporation constructions in his classification
		<Ref k="sato2016" p="88, table 2" />. The four-way distribution and its distinction from his
		proposed hierarchy scores appear in the incorporation comparison chapter.
	</p>
</S>
