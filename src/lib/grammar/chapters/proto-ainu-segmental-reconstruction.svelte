<S t="What a reconstructed form represents" id="reconstruction">
	<p>
		Proto-Ainu is the proposed common ancestor of the documented Ainu varieties. An asterisk marks a
		reconstructed form: its sounds are inferred from correspondences and alternations, rather than
		transcribed from a speaker. The evidence includes Hokkaido, Sakhalin, and Kuril records, whose
		dates, transcription systems, and coverage differ. Alonso de la Fuente reviews Vovin's
		reconstruction, proposes alternatives, and distinguishes lexical evidence from extensions
		suggested by typology
		<Ref k="alonso2022" p="§§1–2" />.
	</p>
	<p>
		Alonso calls his approach internal reconstruction, including the explanation of differences
		among Ainu dialects. Whatever the methodological label, a proposed ancestral contrast must
		explain the recorded forms. Similarity to a neighboring language may instead reflect borrowing;
		a plausible sound inventory by itself supplies no missing correspondence <Ref
			k="alonso2022"
			p="§1"
		/>.
	</p>
</S>

<S t="Vowels and the interpretation of old spellings" id="vowels">
	<p>
		The modern five vowel qualities provide the starting point. Vovin's larger reconstructed system
		differentiates stem vowels according to following vowels and proposed developments. Alonso
		questions how much phonetic detail these correspondences recover and presents an alternative
		with five qualities. His review's numerical description of Vovin's inventory is internally
		inconsistent, so the listed distinctions matter more than its stated total <Ref
			k="alonso2022"
			p="§2.1, Tables 1–4"
		/>.
	</p>
	<p>
		Early spellings that alternate between <i>i</i> and <i>e</i>, or
		<i>o</i> and <i>u</i>, require attention to the recorder's language and orthography. Likewise,
		an apparent final vowel can have more than one history. Alonso discusses Janhunen's contrast
		between proposed
		<i>*CVC.V# &gt; CVC</i> and <i>*CVC.Vx &gt; CVC-Vx</i> developments; the final consonant in the
		second reconstruction is part of that explanation <Ref k="alonso2022" p="§2.1" />.
	</p>
</S>

