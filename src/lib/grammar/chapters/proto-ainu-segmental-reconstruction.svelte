<S t="Palatalization and consonant sequences" id="palatalization">
	<p>
		Forms such as southwestern <i lang="ain-Latn">par</i> and eastern
		<i lang="ain-Latn">car</i> ‘mouth’ have motivated palatalized ancestors. Alonso's <i>*pʲ</i> and
		<i>*hʲ</i>
		proposals use particular lexical correspondences; extensions to a fuller series, including
		<i>*kʲ</i>, <i>*mʲ</i>, and <i>*nʲ</i>, rely more heavily on typological possibilities <Ref
			k="alonso2022"
			p="§2.2.6"
		/>.
	</p>
	<p>
		For <i>pa/ca</i>, Nakagawa and Fukazawa describe a geographically and lexically restricted
		distribution. Their review includes analyses in terms of distinct morphemes and lexical
		replacement, alongside a palatalization account. The concentration of examples around ‘mouth’
		and the restriction to the vowel <i>a</i> limit its use as an unqualified sound law <Ref
			k="nakagawafukazawa2022"
			p="§5.1, Maps 2–4"
		/>. See <Xr ch="hokkaido-lexical-dialectology-and-the-dialect-atlas" />.
	</p>
	<p>
		Reconstruction also concerns sequences preserved with relatively little change. Alonso discusses
		geminates in <i>*wakka</i> ‘water’ and
		<i>*kokka</i> ‘knee’, whose presence need not result from assimilation, and medial clusters
		<i>*nr, *rn, *rt, *tk, *pn, *ns</i>. The disputed history of the cluster in ‘steal’ shows why
		one exceptional word is a weak basis for choosing between sound change and borrowing
		<Ref k="alonso2022" p="§2.2.7" />.
	</p>
</S>

<S t="Length and accent" id="prosody">
	<p>
		Sakhalin vowel length and Hokkaido pitch accent motivate competing historical accounts.
		Itabashi's own conclusion reconstructs both length and pitch; the length-only account he
		discusses belongs to Hattori <Ref k="itabashi2001" p="92; 98–101, §5" />. Satō argues that
		Sakhalin length can develop secondarily, using
		<i lang="ain-Latn">tuuki</i> ‘sake cup’, borrowed from Japanese, and the alternation of
		independent <i lang="ain-Latn">nii</i>
		‘tree’ with short-vowel forms in compounds. Long-vowel notation in early Japanese records consequently
		needs an explanation of how the recorder represented Ainu pronunciation
		<Ref k="bugaeva2022" p="Satō, chapter 3, §5.1" />.
	</p>
	<p>
		Alonso's discussion contains conflicting length-only and pitch-only conclusions. These cannot
		jointly define a settled Proto-Ainu prosodic system <Ref k="alonso2022" p="§§2.3–2.4" />. The
		documented Sakhalin alternations and regional Hokkaido accents can be described more firmly than
		their common ancestor; see
		<Xr ch="final-h-history-and-sakhalin-length-reflex" /> and
		<Xr ch="hokkaido-phonological-microvariation" />.
	</p>
</S>
