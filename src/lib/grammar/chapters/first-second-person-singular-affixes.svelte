<S t="First-person subjects and contraction" id="ku">
	<Ex
		m="orwano ku=cise or ta ku=an kor"
		g="then 1SG.POSS=house place LOC 1SG.S=exist CONJ"
		tr="Then, while I was at my house, …"
		cite="nakagawa2024:166"
		dial="ISH"
		place="Example 104, from Sunazawa 1983: 75, as reproduced by Nakagawa"
		note="The two ku= forms mark a nominal possessor and an intransitive subject respectively."
	/>
	<p>
		The existential predicate in this Ishikari example retains <i lang="ain-Latn">ku=</i> before
		<i lang="ain-Latn">an</i>. In western Hidaka and Chitose, Nakagawa describes contraction of
		<i lang="ain-Latn">ku=</i> to <i lang="ain-Latn">k=</i> before stems beginning in
		<i lang="ain-Latn">a, u, e, o</i>. His notation <i lang="ain-Latn">k(u)=</i> records this
		alternation <Ref k="nakagawa2024" p="166–167" />. The regional and phonological limits are
		discussed in <Xr ch="personal-affix-sandhi-connected-speech-reduction" />.
	</p>
</S>

<S t="The first-person object" id="en">
	<p>
		The object form <i lang="ain-Latn">en=</i> can identify a participant translated as “me” or “to
		me,” according to the verb's argument structure <Ref k="sato2008" p="120–121" />. An overt
		first-person pronoun is unnecessary in the following Shizunai clause.
	</p>
	<Ex
		m="toon seta en=sikerayka"
		g="that dog 1SG.O=stare.at"
		tr="That dog is staring at me."
		cite="refsing1986:214"
		dial="SHI"
		place="First clause of example 342"
		note="Refsing writes the person form separately. Equals signs follow this grammar's notation."
	/>
	<p>
		Refsing associates this form with personal reference in conversation
		<Ref k="refsing1986" p="214–215" />. Narration and reported speech can use another person series
		for a participant translated as “I” or “me”; the dialect and register restrictions are treated
		in <Xr ch="indefinite-fourth-person-paradigm" />.
	</p>
</S>

<S t="Second-person roles and imperative address" id="e">
	<p>
		The role of <i lang="ain-Latn">e=</i> follows from the construction. Refsing's example below
		indexes the recipient of giving. The subject has no overt third-person marker, and the fish is
		the transferred object <Ref k="refsing1986" p="217, example 350" />.
	</p>
	<Ex
		m="cep e=kore"
		g="fish 2SG.O=give"
		tr="Did he give you the fish?"
		cite="refsing1986:217"
		dial="SHI"
		place="Example 350; boundary notation normalized"
	/>
	<p>
		Addressing someone does not by itself require an overt second-person index. In Refsing's
		<i lang="ain-Latn">e=e rusuy cik, e</i>, “if you want to eat, eat,” the conditional clause has
		<i lang="ain-Latn">e=</i>, while the final imperative is the bare verb
		<Ref k="refsing1986" p="216, example 348" />. See <Xr ch="imperative-and-prohibitive" />
		for the imperative constructions.
	</p>
	<p>
		When first and second person are both arguments of a transitive verb, the interaction paradigm
		supplies forms that cannot be predicted by simply joining the two rows above. Conversational
		first-to-second-person reference in Saru and Chitose uses
		<i lang="ain-Latn">eci=</i>
		<Ref k="sato2008" p="146–147" />;
		<Ref k="bugaeva2012" p="474" />. Those combinations and their regional differences are set out
		in <Xr ch="eci-portmanteau-and-second-plural" />.
	</p>
