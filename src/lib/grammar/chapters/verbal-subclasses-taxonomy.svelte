<S t="Argument structure and person marking" id="taxonomy">
	<p>
		Ainu verbs are classified both by the arguments they license and by their person marking. The
		usual person-based division distinguishes zero-argument verbs, intransitives, transitives, and
		the copula
		<Ref k="sato2008" p="20–21" />;
		<Ref k="bugaeva2012" p="470–471" />. Refsing's Shizunai account uses the corresponding groups of
		closed, intransitive, transitive, and copular verbs
		<Ref k="refsing1986" p="140–143" />.
	</p>
	<p>
		Nakagawa additionally organizes verbs by the number of arguments, ranging from zero to four when
		derived forms are included <Ref k="nakagawa2024" p="128–136" />. An argument may be expressed by
		a noun phrase, indexed on the verb, or understood from context. The number of visible words or
		person markers therefore need not equal the verb's argument count <Ref
			k="nakagawa2024"
			p="125–127"
		/>.
	</p>
	<table>
		<caption>Argument patterns in Nakagawa's classification</caption>
		<thead><tr><th>Argument count</th><th>Pattern</th><th>Published example</th></tr></thead>
		<tbody>
			<tr><td>0</td><td>No external subject or object</td><td lang="ain-Latn">sirpirka</td></tr>
			<tr><td>1</td><td>Subject</td><td lang="ain-Latn">apkas</td></tr>
			<tr
				><td>2</td><td>Subject and object; the copula has a subject and nominal complement</td><td
					lang="ain-Latn">nukar; ne</td
				></tr
			>
			<tr><td>3</td><td>Subject and two objects</td><td lang="ain-Latn">kore</td></tr>
			<tr
				><td>4</td><td>Subject and three objects in a derived predicate</td><td lang="ain-Latn"
					>omarere</td
				></tr
			>
		</tbody>
	</table>
	<p>
		The forms mean “be good weather,” “walk,” “see,” “be,” “give,” and “cause someone to put
		something into something,” respectively
		<Ref k="nakagawa2024" p="129–135" />. Four-place examples are rare in Nakagawa's account; they
		arise through further derivation of a three-place verb.
	</p>
</S>

<S t="What person marking distinguishes" id="person-marking-diagnostic">
	<p>
		Intransitives use the S series, while transitives use A and O series. Some forms coincide:
		first-person singular <i lang="ain-Latn">ku=</i> belongs to both S and A. First-person plural
		and fourth-person forms provide clearer contrasts in the Southern Hokkaido paradigms <Ref
			k="bugaeva2012"
			p="471, Table 15.2"
		/>. Refsing likewise uses the prefix-versus-suffix position of particular subject markers in
		classifying Shizunai verbs <Ref k="refsing1986" p="140–142" />.
	</p>
	<p>
		Third person has zero marking. Other person combinations can involve fused or otherwise special
		forms, so A and O roles do not always produce two separately visible prefixes. The combinations
		are described in
		<Xr ch="person-marking-architecture" /> and
		<Xr ch="personal-affix-template-and-ordering" />.
	</p>
</S>

<S t="Intransitives and the role of the subject" id="intransitive">
	<p>
		An intransitive licenses one argument, its subject. That argument can be an actor, an
		experiencer, the bearer of a property, or an entity undergoing change. Nakagawa gives action
		verbs such as <i lang="ain-Latn">apkas</i> “walk” and
		<i lang="ain-Latn">ipe</i> “eat a meal,” alongside
		<i lang="ain-Latn">pirka</i> “good” and <i lang="ain-Latn">pewre</i> “young”
		<Ref k="nakagawa2024" p="129" />.
	</p>
	<p>
		In his Chitose example, <i lang="ain-Latn">rittursere=an</i> means “I was rolled by the waves.”
		The person undergoing the event receives S marking because the resulting verb is intransitive <Ref
			k="nakagawa2024"
			p="129–130, example 14"
		/>. A subject's semantic role thus need not be that of a deliberate actor. Property predicates
		are discussed in <Xr ch="no-adjective-class-property-verbs" />.
	</p>
</S>

<S t="Transitives and object selection" id="transitive">
	<p>
		A transitive licenses a subject and at least one object. Similar English translations can
		conceal a difference in Ainu argument structure. Nakagawa contrasts intransitive
		<i lang="ain-Latn">inkar</i> “look” with transitive
		<i lang="ain-Latn">nukar</i> “see something,” and
		<i lang="ain-Latn">ikka</i> “steal” with <i lang="ain-Latn">eikka</i>
		“steal something” <Ref k="nakagawa2024" p="131–132" />. The choice determines whether a
		particular entity is an object of the predicate.
	</p>
	<p>
		Refsing calls some transitives <em>pseudo-intransitives</em> because an object can remain
		unexpressed, as in her examples with “forget” and “understand”
		<Ref k="refsing1986" p="142–143" />. These remain in her transitive class. Contextual omission
		is distinct from the derivational processes described in
		<Xr ch="valency-voice-overview" />.
	</p>
</S>

<S t="Three-place verbs and further derivation" id="three-place">
	<p>
		<i lang="ain-Latn">Kore</i> “give” licenses a giver, a recipient, and a theme. Both objects can appear
		as bare noun phrases:
	</p>
	<Ex
		m="topenpe hekattar ku=kore"
		g="sweets children 1SG.A=give"
		tr="I gave the children sweets."
		cite="nakagawa2024:127, example 11a"
		place="Hokkaido, dialect not specified"
	/>
	<p>
		Nakagawa also gives versions with either object omitted when its reference is understood: <i
			lang="ain-Latn">topenpe ku=kore</i
		>
		and
		<i lang="ain-Latn">hekattar ku=kore</i>
		<Ref k="nakagawa2024" p="127, examples 11b–c" />. The lexical three-place relation persists
		across these different overt expressions.
	</p>
	<p>
		Applicative and causative morphology creates many three-place verbs. Nakagawa includes
		<i lang="ain-Latn">ko-e</i> “eat something together with something” and
		<i lang="ain-Latn">e-re</i> “make someone eat something”
		<Ref k="nakagawa2024" p="133–134" />. A further causative can produce a four-place predicate,
		illustrated by <i lang="ain-Latn">a=omarere</i> in a Saru narrative <Ref
			k="nakagawa2024"
			p="135, example 34"
		/>.
	</p>
	<p>
		Descriptions differ over the basic three-place inventory. Bugaeva treats all three-place verbs
		as derived, whereas Nakagawa identifies
		<i lang="ain-Latn">o</i> “put something into a location” as a basic three-place stem <Ref
			k="bugaeva2012"
			p="471"
		/>;
		<Ref k="nakagawa2024" p="134, 136" /> ‹contested›.
	</p>
</S>

<S t="The copula and existential verbs" id="copula-existential">
	<p>
		The copula <i lang="ain-Latn">ne</i> combines with a nominal complement and takes A-series
		subject marking. The complement takes no corresponding O-series index <Ref
			k="bugaeva2012"
			p="471"
		/>;
		<Ref k="nakagawa2024" p="132" />.
	</p>
	<Ex
		m="okkayo ku=ne"
		g="man 1SG.A=COP"
		tr="I am a man."
		cite="nakagawa2024:132, example 23"
		place="Hokkaido, dialect not specified"
	/>
	<p>
		The first-person singular form in this example coincides with S marking; its classification
		follows the wider copular paradigm. Existential
		<i lang="ain-Latn">an</i> and <i lang="ain-Latn">oka</i> belong to the intransitive class in
		Refsing's account <Ref k="refsing1986" p="140–141" />. Their constructional differences are
		described in
		<Xr ch="copula-ne-predicate-nominals" /> and
		<Xr ch="existential-locational-an-oka" />.
	</p>
</S>

<S t="Zero-argument predicates and word boundaries" id="avalent">
	<p>
		Zero-argument, or <em>avalent</em>, predicates take no external subject or object. Examples
		include <i lang="ain-Latn">sirpirka</i> “be good weather” and
		<i lang="ain-Latn">mean</i> “be cold,” describing the weather
		<Ref k="nakagawa2024" p="129–130" />. Personal coldness instead uses the one-place
		<i lang="ain-Latn">merayke</i>, which takes a person marker for the experiencer <Ref
			k="nakagawa2024"
			p="130, Table 12"
		/>.
	</p>
	<p>
		Some proposed members involve a disputed word boundary. Refsing lists
		<i lang="ain-Latn">aptoas</i> “rain” among closed verbs
		<Ref k="refsing1986" p="140–141" />. Nakagawa notes the alternative analysis of
		<i lang="ain-Latn">apto as</i>
		as a noun subject followed by a verb, and discusses similar difficulties for expressions of
		sound or report
		<Ref k="nakagawa2024" p="129, 493–494" /> ‹contested›. The analyses depend on whether the noun-like
		element remains an independent constituent.
	</p>
</S>

<S t="Locative objects and separable formations" id="locative-object-ambitransitive">
	<p>
		Some transitives select a grammatical location as an object. Nakagawa contrasts
		<i lang="ain-Latn">cise or ta ahun</i> “enter the house,” with a locative particle, and
		<i lang="ain-Latn">cise or osma</i>
		“jump into the house,” where the location directly fills an object position
		<Ref k="nakagawa2024" p="128, examples 12–13" />. The wider pattern is described in <Xr
			ch="postpositions-local-case-and-motion-events"
		/>.
	</p>
	<p>
		Nakagawa's phrasal verbs involve a noun and a verb that can function as one word or as two; Satō
		discusses related formations under the traditional label <em>third-group verbs</em>
		<Ref k="nakagawa2024" p="495–496" />;
		<Ref k="satoni2022" p="§4" />. Their classification involves the interaction between person
		marking, incorporation, and the position of the nominal element; see
		<Xr ch="noun-incorporation-object" /> and
		<Xr ch="noun-incorporation-subject-possessor-stranding" />.
	</p>
</S>
