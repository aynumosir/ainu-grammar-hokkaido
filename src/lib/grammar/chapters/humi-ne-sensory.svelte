<S t="Sensation and felt experience" id="experience">
	<p>
		<i lang="ain-Latn">Humi</i> can concern sound, smell, taste, touch, bodily sensation, or an
		internal impression. Nakagawa relates these uses to information outside vision and verbal
		expression, while showing that a felt reaction can arise in a visibly present situation <Ref
			k="nakagawa2024"
			p="400–401"
		/>.
	</p>
	<Ex
		m="ku=cikiri arka humi"
		g="1SG.POSS=foot hurt EVID"
		tr="Oh, my foot hurts!"
		cite="nakagawa2024:400–401"
		dial="SAR"
		place="Example 816"
	/>
	<p>
		A different exclamation concerns a daughter returned home in a monstrous form. Her appearance is
		visible, but Nakagawa understands <i lang="ain-Latn">humi</i>
		as expressing the mother's horrified feeling about what she sees
		<Ref k="nakagawa2024" p="401, example 817" />. The grammatical choice reflects the experience
		being expressed, beyond simply cataloguing which physical senses are available.
	</p>
</S>

<S t="Humi ne and its continuations" id="continuations">
	<p>
		Nakagawa observes that standalone final <i lang="ain-Latn">humi ne</i> is uncommon in his
		material. Expressions meaning ‘think’, ‘seem’, or ‘whether’ often follow it. One narrator feels
		as if a bear has caused a dream, then gets up; another does not know where they seem to be going
		<Ref k="nakagawa2024" p="400, examples 813–815" />.
	</p>
	<p>
		The dream example has <i lang="ain-Latn">humi ne pekor yaynu=an</i>. Nakagawa uses it to explain
		that a dream's presentation can be treated as felt experience even where another language would
		naturally speak of ‘seeing’ a dream
		<Ref k="nakagawa2024" p="400, example 814" />.
	</p>
</S>

<S t="Sound-based questions and replies" id="questions">
	<p>
		Tamura's Saru dictionary illustrates <i lang="ain-Latn">humi an</i> with a question about an
		audible activity. The answer identifies what is being dragged and ends in
		<i lang="ain-Latn">humi un</i>
		<Ref k="tamura1996" p="s.v. humi, formal-noun entry" />.
	</p>
	<Ex
		m="hńta ninpa wa arpa humi an"
		g="what drag CONJ go.SG EVID exist.SG"
		tr="What is someone dragging away?"
		cite="tamura1996"
		dial="SAR"
		place="s.v. humi, formal-noun entry"
		note="The question concerns the sound of dragging. The dictionary's hńta spelling is retained."
	/>
	<p>
		The same entry distinguishes formal <i lang="ain-Latn">humi</i> from the ordinary possessed noun
		<i lang="ain-Latn">humi(hi)</i>: the formal use does not take the extra
		<i lang="ain-Latn">hi</i>
		syllable. For meaningful cries interpreted as messages, compare
		<Xr ch="hawe-ne-reportative" />.
	</p>
</S>

<S t="Regional descriptions" id="regional">
	<p>
		Takahashi's Tokachi examples use shorter <i lang="ain-Latn">hum</i> with
		<i lang="ain-Latn">an</i>. They include both a temporary bodily state after putting down a load
		and a garment's relatively stable properties
		<Ref k="takahashi2013" p="133, examples 28–29" />.
	</p>
	<Ex
		m="taan imi ponno ironne wa pase hum an"
		g="this garment somewhat be.thick CONJ be.heavy NMLZ exist.SG"
		tr="This garment is somewhat thick and heavy."
		cite="takahashi2013:133"
		dial="TOK"
		place="Example 29; material from Sawai Tomeno of Honbetsu"
	/>
	<p>
		Refsing reports a different evidentiary limit for Shizunai: she has ordinary
		<i lang="ain-Latn">humi</i>, sometimes modified by a clause, but no generalized nominalizer or
		corresponding clause-ending use in her material
		<Ref k="refsing1986" p="37" />. This records the limits of that sample.
	</p>
</S>

<S t="Inference and the absence of a feeling" id="scope">
	<p>
		Dal Corso analyzes <i lang="ain-Latn">humi as</i> as an inferential expression in the surveyed
		Hokkaido constructions, alongside its independent lexical uses for sound or sensation. He finds
		no reportative use in those data
		<Ref k="dalcorso2018" p="308, 318, 329" />. For combinations with other endings, see
		<Xr ch="mirativity-scope-grammaticalization" />.
	</p>
	<p>
		<i lang="ain-Latn">Humi ka isam</i> can deny the presence of a sensation or impression. Tamura's
		examples include failing to feel sweetness despite added sugar <Ref
			k="tamura1996"
			p="s.v. humi, formal-noun entry"
		/>. That construction differs in scope from a negated predicate followed by an evidential
		ending, where the negative proposition is what the speaker presents as known or perceived; see <Xr
			ch="negation-somo-standard-clausal"
		/>.
	</p>
</S>
