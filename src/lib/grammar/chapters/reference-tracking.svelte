<S t="Recovering a participant from context" id="omission">
	<p>
		A participant need not be named in every clause. Nakagawa allows a noun
		phrase to be absent when its meaning can be supplied from context
		<Ref k="nakagawa2024" p="362" />.
		The verb's argument structure constrains the participant's role, while
		the surrounding discourse helps identify the person or thing involved.
	</p>
	<Ex m="tanpe topenpe ne na ekasi ku=kore na"
		g="this sweet COP FIN old.man 1SG.A=give FIN"
		tr="This is a sweet. I will give it to the old man."
		cite="sato2025a:370" dial="CHI" place="Example 21"
		note="The source's explicit third-person zero sign on ne is omitted here. The two sentences are separated after the first na in the source." />
	<p>
		The sweet is the understood theme of giving. Satō uses the example to
		argue that a three-place predicate can retain an anaphorically interpreted
		theme without giving it a separate person index
		<Ref k="sato2025a" p="369–371, §4.2" />.
		The preceding sentence supplies the particular referent in this example.
		The competing analyses of indexes and overt noun phrases are discussed in
		<Xr ch="nonconfigurationality-pronominal-argument" />.
	</p>
</S>

<S t="What a person form does and does not identify" id="person">
	<p>
		Person forms constrain interpretation, but a third-person form does not
		uniquely identify one previously mentioned individual. Bugaeva illustrates
		this in an indirect report whose two third-person subjects may refer to
		the same person or to different people
		<Ref k="bugaeva2008" p="65–66, §8.1, example 63a" />.
	</p>
	<Ex m="arpa kusu ne yak ye"
		g="go.SG intention COP COMP say"
		tr="He said that he would go."
		cite="bugaeva2008:66" dial="SAR" place="Example 63a, after Tamura 1972/2001:377 (T1); colloquial"
		note="Bugaeva allows the person who goes to be either the speaker of the reported words or someone else. Her explicit third-person zero signs are omitted here." />
	<p>
		Her plural example likewise permits either ‘They said that they themselves
		did not know it’ or a report about other people who did not know it.
		She identifies context as the means of resolving the ambiguity
		<Ref k="bugaeva2008" p="66, example 66" />.
	</p>
</S>

<S t="Narrative and logophoric reference" id="fourth-person">
	<p>
		Fourth-person morphology has several uses, including reference to a
		narrator and logophoric reference to the person whose speech or perspective
		is reported. Its morphological label is distinct from the person used in
		an English translation. Nakagawa's example uses fourth-person object
		<i lang="ain-Latn">i=</i> for the narrator
		<Ref k="nakagawa2024" p="170, example 127" />.
	</p>
	<Ex m="i=erampokiwen i=rewsire wa i=kore"
		g="4.O=pity 4.O=make.stay.overnight CONJ 4.O=give"
		tr="Take pity on me and give me lodging."
		cite="nakagawa2024:170" dial="SAR" place="Example 127; narrator reference" />
	<p>
		Bugaeva analyzes a particular reported-discourse use of this series as
		logophoric. Her account distinguishes it from both direct speech and
		indirect reports such as the preceding ambiguous example
		<Ref k="bugaeva2008" p="41–43, 65–66" />.
		Quotation therefore does not automatically replace every first-person form
		with a fourth-person form. See <Xr ch="indefinite-fourth-person-paradigm" />
		and <Xr ch="quotative-complementation-sekor" />.
	</p>
</S>

