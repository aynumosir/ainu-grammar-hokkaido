		Shizunai <i lang="ain-Latn">wa</i> examples have the same subject in
		about 90 percent of her sample <Ref k="refsing1986" p="241" />.
		The documented different-subject constructions are discussed in
		<Xr ch="clause-linkage-overview" s="subjects" /> and
		<Xr ch="simultaneous-kor-clauses" />.
	</p>
	<p>
		Yoshikawa's narrative observations concern changes of scene, topic, or
		actor around <i lang="ain-Latn">a</i> with
		<i lang="ain-Latn">p</i>, <i lang="ain-Latn">korka</i>, or
		<i lang="ain-Latn">wa</i>; they do not require an actor change at every
		occurrence <Ref k="yoshikawa2022" p="§4.1.1, examples 34–36" />.
