<S t="One sibilant phoneme, several realizations" id="overview">
	<p>
		Hokkaido Ainu has a sibilant phoneme /s/ whose realizations include [s] and palatalized [ʃ] or
		[ɕ]. These symbols describe variation within /s/; the consonant inventory also contains the
		separate fricative /h/ <Ref k="shibatani1990" p="§2.2" />;
		<Ref k="bugaeva2012" p="465" />. The degree and distribution of palatalization vary among
		descriptions and speakers.
	</p>
	<p>
		The conditioning by /i/ is well documented. Broader claims need their dialect scope kept
		visible: Bugaeva's Chitose description limits the usual palatalization to positions next to /i/,
		whereas other accounts describe palatalized final /s/ more generally
		<Ref k="bugaeva2012" p="465" />; <Ref k="nakagawa2024" p="29" />.
	</p>
</S>

<S t="At the beginning of a syllable" id="onset-realization">
	<p>
		Before /i/, /s/ has the palatal realization heard in the syllable
		<span lang="ain-Latn">si</span>. Satō explicitly distinguishes this from [si] with a plain [s] <Ref
			k="sato2008"
			p="11"
		/>. Shiraishi illustrates palatalization with
		<i lang="ain-Latn">sini</i> [ʃini] “rest,” citing earlier descriptions
		<Ref k="shiraishi2022" p="§3" />.
	</p>
	<p>
		Before other vowels, the evidence is less uniform. Nakagawa notes older kana spellings
		corresponding to <span lang="ja">シャ、シュ、シェ、ショ</span>, but leaves open whether they
		record an earlier pronunciation or a different transcription practice
		<Ref k="nakagawa2024" p="28" />. Bugaeva describes most Chitose instances away from /i/ as
		comparatively unpalatalized <Ref k="bugaeva2012" p="465" />. The older spellings alone cannot
		establish a historical sound change.
	</p>
</S>

<S t="At the end of a syllable" id="coda-allophony">
	<p>
		Nakagawa distinguishes final /s/ after /i/, realized as [ɕ], from final /s/ after the other
		vowels, described more approximately as [sʲ]. His examples contrast
		<i lang="ain-Latn">cis</i> “cry” with <i lang="ain-Latn">as</i> “stand”
		<Ref k="nakagawa2024" p="29" />. Bugaeva's Chitose description reports less palatalization away
		from /i/, including in final position <Ref k="bugaeva2012" p="465" />.
	</p>
	<p>
		Final /s/ must still be distinguished from an open syllable ending in /si/. Nakagawa uses the
		following pair to illustrate the difference
		<Ref k="nakagawa2024" p="29–30" />:
	</p>
	<Ex
		m="tures"
		g="younger.sister"
		tr="younger sister"
		cite="nakagawa2024:30"
		dial="HK"
		note="The word ends in /s/. The source does not identify a dialect for this pair; English glosses are supplied here."
	/>
	<Ex
		m="tures-i"
		g="younger.sister-POSS"
		tr="his or her younger sister"
		cite="nakagawa2024:30"
		dial="HK"
		note="The possessive form includes a final vowel. Segmentation and English glosses are supplied here."
	/>
	<p>
		The second form contains an additional vowel and syllable. Palatalized pronunciation of the
		consonant does not eliminate that difference. The possessive formation is treated in
		<Xr ch="affiliative-suffix-morphophonology" />.
	</p>
</S>

<S t="Connected-speech environments" id="sw-constraint">
	<p>
		A final consonant should also be examined in its phrase, where the following segment may affect
		its realization. Refsing describes final /s/ as frequently palatalized but gives an exception
		before a following word beginning with /s/
		<Ref k="refsing1986" p="§10.3" />. A statement about a word pronounced in isolation therefore
		need not exhaust its behavior in connected speech.
	</p>
</S>

<S t="Comparison with Japanese" id="vs-japanese">
	<p>
		Japanese kana and Japanese sound labels are useful approximations in the descriptive literature,
		but authors differ in how closely they identify the Ainu sounds with them. Bugaeva explicitly
		describes Chitose /s/ as less palatalized in many environments than the corresponding Japanese
		comparison suggests <Ref k="bugaeva2012" p="465" />. A kana spelling is consequently best read
		together with the author's phonetic explanation.
	</p>
</S>

<S t="Speaker and dialect variation" id="speaker-variation">
	<p>
		Bugaeva reports Tamura's observation of individual variation in Saru palatalization, while
		presenting her own Chitose observations separately <Ref k="bugaeva2012" p="465" />. These
		reports favor an account that identifies the speaker and environment. Combining all published
		variants into one obligatory rule would overstate their agreement.
	</p>
</S>

