<S t="Presenting something as fact" id="fact">
	<p>
		<i lang="ain-Latn">Ruwe ne</i> can present something the speaker recognizes as fact. It occurs
		in explanations of personal circumstances, accounts of direct experience, and narratives.
		Nakagawa distinguishes this use from the ordinary noun <i lang="ain-Latn">ru</i> ‘path, trace’
		<Ref k="nakagawa2024" p="391, 397" />.
	</p>
	<Ex
		m="poronno rawraw ku=kor ruwe ne"
		g="much rawraw 1SG.A=have EVID COP"
		tr="I have a lot of rawraw."
		cite="nakagawa2024:397"
		dial="CHI"
		place="Example 797"
		note="Rawraw is the plant named in the source. The sentence reports the speaker's own possession; no separate act of inference is specified."
	/>
	<p>
		The ending also serves in explanations of linguistic and cultural practice. Nakagawa's preceding
		example identifies a conventional speech of reunion
		<Ref k="nakagawa2024" p="397, example 796" />. ‘Inferential’ is consequently too narrow as a
		definition of every occurrence.
	</p>
</S>

<S t="The noun and its morphology" id="morphology">
	<p>
		Tamura distinguishes the ordinary possessed noun <i lang="ain-Latn">ruwe(he)</i> ‘trace, path
		left by someone’ from formal <i lang="ain-Latn">ruwe</i>, which her dictionary says does not
		take the extra <i lang="ain-Latn">he</i> syllable <Ref
			k="tamura1996"
			p="s.vv. ruwe and ruwe(he)"
		/>. Dal Corso reports a few full-form examples in his own reference material <Ref
			k="dalcorso2018"
			p="142, note 39"
		/>.
	</p>
	<p>
		The segmentation is also analyzed differently. Tamura's entry gives <i lang="ain-Latn">ru-e</i>;
		Dal Corso proposes an underlying <i lang="ain-Latn">ruw-</i> stem and <i lang="ain-Latn">-e</i>
		possessive ending, while acknowledging countervailing compound forms and the need for further
		morphophonological study <Ref k="tamura1996" p="s.v. ruwe, formal-noun entry" /><Ref
			k="dalcorso2018"
			p="142–143, §5.3.1.2"
		/>.
	</p>
</S>

<S t="Questions and replies" id="questions">
	<p>
		The noun appears in several frames. Bare <i lang="ain-Latn">ruwe</i> can end a polar question,
		while <i lang="ain-Latn">ruwe an</i> commonly ends a content question in Nakagawa's southern
		examples
		<Ref k="nakagawa2024" p="394–396" />.
	</p>
	<Ex
		m="hemanta e=nukar kusu soy ta e=an ruwe an"
		g="what 2SG.A=see CONJ outside LOC 2SG.S=exist.SG EVID exist.SG"
		tr="What were you outside to look at?"
		cite="nakagawa2024:394"
		dial="SAR"
		place="Example 783"
	/>
	<p>
		An affirmative reply may use <i lang="ain-Latn">ruwe un</i>. The following response answers a
		question about whether the addressee heard something. Here <i lang="ain-Latn">un</i> closes a
		confirming reply; the particle has other functions outside this frame
		<Ref k="nakagawa2024" p="396" />.
	</p>
	<Ex
		m="ku=nu ruwe un"
		g="1SG.A=hear EVID FIN"
		tr="Yes, I heard it."
		cite="nakagawa2024:396"
		dial="SAR"
		place="Example 794, reply, citing Tamura 1985:32"
	/>
	<p>
		Satō discusses <i lang="ain-Latn">ruwe</i> in Chitose questions about an abstract relation, such
		as whether a house belongs to the addressee. He tentatively connects the choice of these formal
		nouns with knowledge or experience already available from context. His further link to their
		possessed morphology is a suggestion, not an established entailment of the form
		<Ref k="sato2008" p="135–136" />.
	</p>
</S>

<S t="Knowledge and information processing" id="knowledge">
	<p>
		Dal Corso proposes that <i lang="ain-Latn">ruwe ne</i> involves information processed and
		assimilated by the speaker. In his account, this helps explain its use for traditional narrative
		knowledge even when the present performer did not personally witness the event. He contrasts
		this with his treatment of
		<i lang="ain-Latn">siri ne</i> as presenting a visual stimulus that remains external to the
		speaker's assimilated knowledge
		<Ref k="dalcorso2018" p="320–321, §8.3.1" />.
	</p>
	<p>
		Hirosawa likewise proposes a knowledge-based interpretation, but develops it through discourse
		functions: presenting new information, drawing together an explanation, and treating information
		as within the speaker's informational domain
		<Ref k="hirosawa2026" p="75–82, 89–90, §§6.2–6.6" />. The proposals address related observations
		with different analytical commitments. Neither makes the English word ‘trace’ a literal
		paraphrase of every ending.
	</p>
</S>

<S t="Negation and neighboring constructions" id="scope">
	<p>
		Nakagawa distinguishes a negated predicate followed by
		<i lang="ain-Latn">ruwe ne</i> from rhetorical
		<i lang="ain-Latn">ruwe somo ne</i>. His first example says that the narrator has lost nothing;
		the second confirms that the narrator had failed to notice a wife's nightly departures <Ref
			k="nakagawa2024"
			p="393, examples 779–780"
		/>. Tamura also records ordinary denial with <i lang="ain-Latn">ruwe somo ne</i>, so the
		rhetorical interpretation requires its source context
		<Ref k="tamura1997" p="71" />.
	</p>
	<p>
		A non-question <i lang="ain-Latn">ruwe an</i> string need not be the same clause-ending
		construction. Nakagawa treats a Saru expression about the favorable state of available trees as
		a more lexical use of ‘state’
		<Ref k="nakagawa2024" p="395, example 788" />. Tokachi has additional declarative and
		relative-clause patterns, introduced in
		<Xr ch="evidential-schema-overview" />. Compare
		<Xr ch="siri-ne-situational" /> for appearance and
		<Xr ch="mirativity-scope-grammaticalization" /> for combinations.
	</p>
</S>
