				<tr>
					<td>vowel-initial syllable; following vowel accented and/or in a closed syllable</td>
					<td>[ʔ] clearly audible</td>
					<td>Tamura 1970: 586, cited via <Ref k="shiraishi2022" p="§4.3" /></td>
				</tr>
				<tr>
