					<td>Tamura 1970: 586–587, cited via <Ref k="shiraishi2022" p="§4.3" /></td>
				</tr>
				<tr>
					<td>after a coda consonant that resyllabifies onto the following vowel</td>
					<td>[∅]; coda consonant fills the onset slot</td>
