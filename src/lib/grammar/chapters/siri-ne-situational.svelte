		The ending can also concern a consequence visible in the present situation. In another Saru
		passage, a person mistreated by relatives finds a sword blade under the bedding and speaks of
		the extraordinary death they will suffer. The proposition is prospective even though the present
		circumstances motivate it
		<Ref k="nakagawa2024" p="393, example 777" />.
	</p>
</S>

<S t="The speaker's own conduct" id="speaker">
	<p>
		A speaker can explain an action that the addressee can see. Nakagawa gives a Saru apology ending
		in <i lang="ain-Latn">yayattasa=an siri ne</i> and a Chitose prayer informing the water deity
		that the speaker and family are travelling by canoe <Ref
			k="nakagawa2024"
			p="397–398, examples 799–800"
		/>. Neither use requires the speaker to stand apart as an observer of someone else's action.
	</p>
	<p>
		Related questions concern the addressee's current conduct or perception. Nakagawa's Chitose
		examples ask what someone is eating and whether a daughter with unusual powers can see something
		invisible to others
		<Ref k="nakagawa2024" p="398, examples 801–802" />. The choice of <i lang="ain-Latn">siri</i> does
		not establish that every participant shares the same visual access.
	</p>
</S>

<S t="Siri an and siri ki" id="related">
	<p>
		<i lang="ain-Latn">Siri an</i> occurs in content questions in the southern clause-ending pattern <Ref
			k="nakagawa2024"
			p="394, example 784"
		/>. Dal Corso also analyzes <i lang="ain-Latn">siri an</i> and
		<i lang="ain-Latn">siri ki</i> as indirect visual evidentials in other constructions. ‘Indirect’
		in that analysis does not mean that the speaker has seen nothing: his examples include seeing a
		brother approach in the distance and interpreting a woman's skillful cooking
		<Ref k="dalcorso2018" p="307, examples 245–246" />.
	</p>
	<p>
		His account distinguishes evidential, aspectual, and independent lexical uses. The aspectual
		uses retain an evidential contribution in his reference material; lexical <i lang="ain-Latn"
			>sir-ki</i
		>
		can describe how a situation is
		<Ref k="dalcorso2018" p="314–318, §8.2.3" />. These distinctions require attention to the whole
		construction, including whether it is a dependent or independent predicate. Compare
		<Xr ch="continuative-siri-siran-kane-an" />.
	</p>
</S>

<S t="Tokachi and the kind of predication" id="tokachi">
	<p>
		Takahashi's Tokachi study finds a further restriction involving what is predicated. In the data
		from Sawai Tomeno of Honbetsu,
		<i lang="ain-Latn">sir</i> occurs with ongoing events and temporary states. An observed
		shivering person provides a straightforward example
		<Ref k="takahashi2013" p="132–133, §§4–5" />.
	</p>
	<Ex
		m="e=uyuyke sir an"
		g="2SG.S=tremble NMLZ exist.SG"
		tr="You are trembling."
		cite="takahashi2013:132"
		dial="TOK"
		place="Example 18, second sentence"
		note="The preceding question asks whether the addressee is cold. The sir construction states the observed situation."
	/>
	<p>
		Descriptions of more stable properties instead use <i lang="ain-Latn">ru</i>
		in his examples, even when those properties are visible: a long neck, a spacious room, and a large
		mountain. Takahashi analyzes the distinction in terms of temporary situations versus individual properties
		<Ref k="takahashi2013" p="132–134, examples 24–27 and §5" />. The documented restriction
		concerns this Tokachi material.
	</p>
</S>
