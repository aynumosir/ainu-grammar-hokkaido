<S t="Person and numerals" id="person-numerals">
	<p>
		The described Sakhalin system lacks dedicated exclusive
		<i lang="ain-Latn">ci-/-as</i> forms. Its
		<i lang="ain-Latn">an-/-an</i> series covers both inclusive and exclusive plural reference and
		can also occur with singular reference in elders' speech <Ref k="tangiku2022" p="§§7.2–7.4" />.
		The interaction paradigm also differs from Saru: for first singular acting on second singular,
		both have <i lang="ain-Latn">eci-</i>; for first singular acting on second plural, Sakhalin has
		<i lang="ain-Latn">eci-…-an</i> where Saru has
		<i lang="ain-Latn">eci-</i>
		<Ref k="tangiku2022" p="§7.7, Table 3" />.
	</p>
	<p>
		The numeral system supplies another structural contrast. Tangiku lists decimal <i
			lang="ain-Latn">tu-kunkutu</i
		>
		‘twenty’,
		<i lang="ain-Latn">re-kunkutu</i> ‘thirty’, and
		<i lang="ain-Latn">sine-tanku</i> ‘one hundred’, alongside
		<i lang="ain-Latn">hohne</i> for twenty. An Itelmen source for
		<i lang="ain-Latn">kunkutu</i> is a historical proposal
		<Ref k="tangiku2022" p="§3.3" />.
	</p>
</S>

