<S t="Sound correspondences" id="sounds">
	<p>
		Sakhalin <i lang="ain-Latn">kaani</i> ‘metal’ and
		<i lang="ain-Latn">seeseh</i> ‘hot’ correspond to Hokkaido
		<i lang="ain-Latn">káni</i> and <i lang="ain-Latn">sések</i>. Length can alternate with a
		suffix, as in
		<i lang="ain-Latn">kii/ki-hci</i> ‘do’. Tangiku discusses whether length belongs to the
		underlying vowel or to its realization; the predictable pitch pattern is a separate descriptive
		fact
		<Ref k="tangiku2022" p="§§2.1, 2.5" />.
	</p>
	<p>
		Common syllable-final correspondences include <i>p, t, k &gt; h</i>, with <i>s</i> after
		<i>i</i>; <i>m &gt; n</i>; and an added vowel after <i>r</i>. Their geographic and morphological
		conditions are described in <Xr ch="final-h-history-and-sakhalin-length-reflex" />. Initial
		<i>r/t</i>
		also varies: ‘white’ appears as Hokkaido
		<i lang="ain-Latn">retar</i>, southern Sakhalin
		<i lang="ain-Latn">retara</i>, and
		<i lang="ain-Latn">tetara</i> in Esutoru and Nairo. For ‘ice’, Tangiku lists Hokkaido
		<i lang="ain-Latn">rup</i>, Esutoru
		<i lang="ain-Latn">ruh</i>, Tarantomari
		<i lang="ain-Latn">rup</i>, and Nairo
		<i lang="ain-Latn">tup</i>
