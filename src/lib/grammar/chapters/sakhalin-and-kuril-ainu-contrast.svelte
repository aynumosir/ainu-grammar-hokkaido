	<p>
		Verbal plural <i lang="ain-Latn">-(a)hci</i> differs from affiliative-noun plural
		<i lang="ain-Latn">-(a)hcin</i>. The latter can reflect plural possessors or plural possessed
		entities. In two passages from a story about three sisters,
		<i lang="ain-Latn">nanna-ha-hcin</i> refers first to one elder sister relative to two younger
		sisters, and later to two elder sisters relative to the youngest. The same form permits both
