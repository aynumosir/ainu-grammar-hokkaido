<S t="Aspectual and connective variation" id="particles">
	<p>
		Several varieties east of Shizunai use
		<i lang="ain-Latn">kane/kan</i> for continuing actions and sustained states, where other
		descriptions distinguish constructions with <i lang="ain-Latn">kor</i> and
		<i lang="ain-Latn">wa</i>. Nakagawa and Fukazawa illustrate a sustained state in Ishikari and
		ongoing actions in Tokachi; they also compare continuing-result
		<i lang="ain-Latn">ayne</i> with Tokachi
		<i lang="ain-Latn">ahinne</i>
		<Ref k="nakagawafukazawa2022" p="§4.3.2, examples 19–20" />.
	</p>
	<p>
		Such distributions explain why a rule drawn from Saru should carry that locality into
		comparisons. The same spelling in another variety may have a broader or narrower set of
		functions.
	</p>
