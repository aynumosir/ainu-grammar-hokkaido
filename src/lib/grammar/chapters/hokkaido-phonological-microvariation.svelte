<S t="Accent systems" id="accent">
	<p>
		Hokkaido varieties differ in whether word accent is distinctive and where it falls. Nakagawa and
		Fukazawa contrast a widespread pattern, represented by Saru, with Yakumo's pattern and varieties
		described as unaccented. In Yakumo, when the first two syllables are open, high pitch falls on
		the third: <i lang="ain-Latn">iperékut</i>
		‘esophagus’, <i lang="ain-Latn">sinuyé</i> ‘tattoo’, and
		<i lang="ain-Latn">hopuní</i> ‘rise’ correspond to Saru
		<i lang="ain-Latn">ipérekut, sinúye, hopúni</i>. A closed second syllable can retain
		second-syllable accent, as in
		<i lang="ain-Latn">parúnpe</i> ‘tongue’
		<Ref k="nakagawafukazawa2022" p="§3.1, Table 3" />.
	</p>
	<p>
		Their unaccented group includes Shizunai, Urakawa, Samani, Bihoro, Kushiro, and Shiranuka. This
		means that lexical accent is not distinctive; pitch still varies in speech. Samani has a
		tendency toward final high pitch, while Shizunai lacks a stable corresponding pattern <Ref
			k="nakagawafukazawa2022"
			p="§3.1"
		/>.
	</p>
</S>

