<S t="The copula within the predicate" id="copula">
	<p>
		A nominal predicate ordinarily contains the copula <i lang="ain-Latn">ne</i>. The noun phrase
		supplies the identity or classification, and <i lang="ain-Latn">ne</i>
		carries the subject's person form <Ref k="nakagawa2024" p="132" />. Time, modality and the
		speaker's presentation of the statement can be expressed through further material. For example,
		Satō gives <i lang="ain-Latn">pe ne a p</i> within a recollection of having seen someone only as
		a small child <Ref k="sato2008" p="175–176" />.
	</p>
	<p>
		Property predicates such as <i lang="ain-Latn">pirka</i> ‘be good’ already behave as verbs; see <Xr
			ch="property-concept-predication"
		/>. The constructions below concern nominal predication with a copula and the clause endings
		that can follow it. The competing analyses of time-marking <i lang="ain-Latn">a</i> apply here too;
		its occurrence does not establish a separate nominal tense paradigm.
	</p>
</S>

<S t="Negating nominal predication" id="negation">
	<p>
		Satō's Chitose description places <i lang="ain-Latn">ka somo</i> before
		<i lang="ain-Latn">ne</i> in a negative copular sentence
		<Ref k="sato2008" p="22" />.
	</p>
	<Ex
		m="tan pe anak seta ka somo ne wa"
		g="this thing TOP dog ADD NEG COP FIN"
		tr="This is not a dog."
		cite="sato2008:22"
		dial="CHI"
		place="Example 6"
		note="Final wa is a sentence particle here. The source contrasts this pattern with the ordinary verbal construction V ka somo ki."
	/>
	<p>
		Satō says that <i lang="ain-Latn">ne ka somo ki</i> hardly occurs, despite the copula's verbal
		status. His statement describes a strong distributional difference rather than an absolute
		impossibility. Nakagawa also gives a Chitose clause with
		<i lang="ain-Latn">menoko ka somo ne</i>, in which a woman denies being from Chitose
		<Ref k="nakagawa2024" p="256, example 323" />.
	</p>
	<p>
		The negative meanings of <i lang="ain-Latn">isam</i> ‘not exist’ and
		<i lang="ain-Latn">sak</i> ‘lack’ belong to those lexical verbs
		<Ref k="bugaeva2012" p="496" />. They concern existence and possession, respectively, and are
		treated in <Xr ch="existential-locational-an-oka" /> and
		<Xr ch="predicative-possession-clauses" />.
	</p>
</S>

<S t="Evidential endings after ne" id="evidentials">
	<p>
		A clause with a nominal predicate can be followed by a formal-noun ending. Bugaeva gives the
		following example from Nakagawa's dictionary, retaining both a reportative and an assumptive
		interpretation <Ref k="bugaeva2016" p="102" />.
	</p>
	<Ex
		m="pirka uepeker ne haw-e ne wa"
		g="be.good folktale COP voice-POSS COP FIN"
		tr="It is said to be / I assume it is a good folktale."
		cite="bugaeva2016:102"
		place="Example 9, quoting Nakagawa 1995:54"
		note="The first ne predicates ‘a good folktale’. The second belongs to the hawe ne ending. The lexical gloss of hawe shows its nominal source without choosing between the published interpretations."
	/>
	<p>
		Bugaeva reports Tamura's analysis of these endings as a nominalized clause followed by a copula,
		and proposes increasing grammaticalization toward a single complex predicate
		<Ref k="bugaeva2016" p="102" />. These analyses assign different internal structures to the same
		sequence.
	</p>
	<Ex
		m="yosiko e=ne ruwe"
		g="Yoshiko 2SG.A=COP EVID"
		tr="Are you Yoshiko?"
		cite="bugaeva2012:497"
		place="Example 77b, source NN22"
		note="The published southern Hokkaido polar question ends in ruwe. The copula inside the nominal predicate remains present; there is no following copula after ruwe."
	/>
	<p>
		Question endings have their own distributions. Bugaeva contrasts this polar pattern with content
		questions ending in a formal noun plus <i lang="ain-Latn">an</i>
		<Ref k="bugaeva2012" p="497" />. Nakagawa documents additional regional forms and expanded
		endings <Ref k="nakagawa2024" p="394–396" />.
	</p>
</S>

<S t="Scope and order" id="scope">
	<p>
		The position of negation affects the interpretation. Nakagawa's ordinary negative statement
		negates the predicate before <i lang="ain-Latn">ruwe ne</i>. His separate
		<i lang="ain-Latn">ruwe somo ne</i>
		example has a rhetorical-confirmation reading, approximately ‘wasn't it the case that…’ <Ref
			k="nakagawa2024"
			p="393, examples 779–780"
		/>. A negative copula at the end therefore need not express simple denial of the preceding
		event.
	</p>
	<p>
		The endings also constrain what can follow. Nakagawa records
		<i lang="ain-Latn">a</i> and <i lang="ain-Latn">nankor</i> after
		<i lang="ain-Latn">ruwe ne</i>, while describing other following auxiliaries as rare
		<Ref k="nakagawa2024" p="378" />. He accepts prospective
		<i lang="ain-Latn">kusu ne ruwe ne</i> but rejects the reverse
		<i lang="ain-Latn">*ruwe ne kusu ne</i>. He likewise rejects
		<i lang="ain-Latn">*pirka ruwe ne kewtum</i> as a modifier of ‘heart, disposition’
		<Ref k="nakagawa2024" p="394" />. The distribution of a complete clause ending differs from that
		of an ordinary verb phrase.
	</p>
</S>
