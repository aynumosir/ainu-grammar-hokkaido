		In a separate study, Takahashi describes all four sensory nominalizers in Horobetsu adverbial
		clauses and argues that their evidential distinctions remain relevant there
		<Ref k="takahashi2018" p="108–112" />. This clause-linking development and the Tokachi
		independent endings represent different extensions. Neither establishes that every formal noun
		can freely terminate an independent clause throughout Hokkaido.
	</p>
</S>
