	<p>
		The pronunciation <i lang="ain-Latn">i</i> varies by description and variety. Satō says that
		<i lang="ain-Latn">hi</i>
		can lose its initial consonant after a consonant
		<Ref k="sato2008" p="175" />. Refsing also records loss after vowels in rapid speech
		<Ref k="refsing1986" p="260" />, while Takahashi treats Tokachi
		<i lang="ain-Latn">hi/i</i> as free variants <Ref k="takahashi2014nom" p="151, note 4" />.
	</p>
	<p>
		Place interpretations often require an overt relation to the action. Citing Okuda, Nakagawa
		contrasts <i lang="ain-Latn">oro ta cise kar hi</i> ‘the place where a house was built’ with
		temporal <i lang="ain-Latn">pon=an hi wano</i> ‘since I was small’. The place construction
		retains <i lang="ain-Latn">oro ta</i> ‘there’; the time construction does not. He also records
		exceptions, including Horobetsu
		<i lang="ain-Latn">seta utar osoma hi</i> ‘the dogs’ latrine’, without that locative phrase
		<Ref k="nakagawa2024" p="511–512, citing Okuda 1989:63 and Chiri Yukie" />.
	</p>
</S>

<S t="Place heads usi and uske" id="place-heads">
	<p>
		<i lang="ain-Latn">Usi</i> and <i lang="ain-Latn">uske</i> occur as relative heads and as
		complement markers in Nakagawa's account <Ref k="nakagawa2024" p="509–510" />. Their
		place-related meaning does not by itself remove the grammatical relation inside a relative
		clause. Bugaeva's Chitose <i lang="ain-Latn">eun a=nu usi ka isam</i>
		‘there was nowhere I could ask about it’ retains <i lang="ain-Latn">eun</i>, expressing the
		place or source toward which the inquiry is directed
		<Ref k="bugaeva2015" p="49, example 16, quoting Bugaeva 2004:390" />.
	</p>
</S>

<S t="Sensory nouns and clause complements" id="sensory">
	<p>
		Nakagawa documents four concept–affiliative pairs:
		<i lang="ain-Latn">ru/ruwe</i> ‘path, trace’, <i lang="ain-Latn">haw/hawe</i> ‘voice’,
		<i lang="ain-Latn">sir/siri</i> ‘appearance’, and <i lang="ain-Latn">hum/humi</i>
		‘sound, sensation’ <Ref k="nakagawa2024" p="259, table 66" />. This morphological relationship
		concerns these particular nouns. Formal nouns as a whole do not share one uniform possessive
		paradigm.
	</p>
	<p>
		These forms can head ordinary complements of perception or evaluation predicates. Nakagawa's <i
			lang="ain-Latn">cis hawe a=nu</i
		>
		means ‘I heard crying’, and his next example uses <i lang="ain-Latn">humi</i> for the sound of a
		mother tending the fire and cooking
		<Ref k="nakagawa2024" p="509, examples 1168–1169" />. The sensory head contributes to what is
		perceived, even when no sentence-final <i lang="ain-Latn">ne</i> follows it.
	</p>
	<p>
		Satō suggests a connection between these affiliative forms and knowledge or experience already
		available in the situation or discourse. He presents this as a tentative explanation
		<Ref k="sato2008" p="135" />. The interpretation of complete evidential endings, and the
		competing accounts of their structure, are discussed in
		<Xr ch="nonverbal-predicate-tam-negation" />.
	</p>
</S>

<S t="Conventional words and productive phrases" id="lexicalization">
	<p>
		Bugaeva gives lexical nominalizations <i lang="ain-Latn">ci=ronnu-p</i> ‘fox’, analyzed as ‘what
		we kill’, and <i lang="ain-Latn">ape-o-i</i> ‘hearth’, analyzed as ‘place where fire enters’ <Ref
			k="bugaeva2016"
			p="100, examples 5a–b"
		/>. Her analysis retains the first-person exclusive plural actor in the former and the plural
		root <i lang="ain-Latn">ronnu</i>. Such conventional words must be distinguished from phrases
		assembled to identify a particular referent.
	</p>
	<p>
		Nakagawa contrasts the compound <i lang="ain-Latn">tureptani</i> ‘lily-digging stick’ with
		<i lang="ain-Latn">nea menoko ani turepta ni</i>
		‘the stick with which that woman dug lilies’. He analyzes the compound as
		<i lang="ain-Latn">turepta</i>
		plus
		<i lang="ain-Latn">ni</i>, with <i lang="ain-Latn">turep</i> ‘lily’ already incorporated in
		<i lang="ain-Latn">turepta</i>. The full relative phrase requires instrumental
		<i lang="ain-Latn">ani</i>
		<Ref k="nakagawa2024" p="506" />. A conventional compound and an identifying relative clause can
		therefore differ in their internal grammatical relations.
	</p>
</S>

<S t="Independent endings and adverbial clauses" id="extensions">
	<p>
		A nominalizing form can develop uses outside an ordinary noun phrase. Takahashi examines Tokachi
		independent clauses ending in <i lang="ain-Latn">ru</i>,
		<i lang="ain-Latn">(h)aw</i>, or <i lang="ain-Latn">(h)i</i>, using the term
		<em>insubordination</em>. He also notes that distinguishing this analysis from omission of a
		main clause requires further work <Ref k="takahashi2014nom" p="151–154" />.
	</p>
