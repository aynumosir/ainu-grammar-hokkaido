<S t="Heads, nominalizers, and their meanings" id="inventory">
	<p>
		A clause before a noun can identify the noun's referent or supply its content. The head may be
		an ordinary lexical noun, a general noun such as <i lang="ain-Latn">kur</i> ‘person’, or a
		dependent form such as <i lang="ain-Latn">hi</i>. Authors divide the latter group differently.
		Satō distinguishes relative heads from whole-clause nominalizers; Nakagawa treats membership in
		the formal-noun class separately from the function of a particular occurrence <Ref
			k="sato2008"
			p="175–180"
		/><Ref k="nakagawa2024" p="508–510" />.
	</p>
