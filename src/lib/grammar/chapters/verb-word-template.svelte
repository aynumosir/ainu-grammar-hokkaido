<S t="Suffix position and valency" id="suffix-valency">
	<p>
		Suffix position alone does not predict a change in argument count. Productive <i lang="ain-Latn"
			>-re/-e/-te</i
		>
		causativization introduces a causer alongside the base's participants. By contrast,
		<i lang="ain-Latn">-yar/-ar</i> replaces the original subject with a causer while leaving the
		causee unavailable as an independently expressed or indexed argument <Ref
			k="nakagawa2024"
			p="200–201"
		/>;
		<Ref k="bugaevakobayashi2022" p="§4.3.1" />.
	</p>
	<p>
		The latter derivation therefore retains valency despite its causative meaning. Lexical
		transitivizing suffixes and the direct/indirect causative analysis also require separate
		treatment. See <Xr ch="transitivity-and-valence-classes" />
		and <Xr ch="denominal-deverbal-verb-derivation" />.
	</p>
</S>

<S t="Number morphology and the outer boundary" id="number-boundaries">
	<p>
		Stem-forming <i lang="ain-Latn">-pa</i> differs from additional plural or iterative
		<i lang="ain-Latn">pa</i>. Nakagawa discusses special behavior with <i lang="ain-Latn">iki</i>,
		<i lang="ain-Latn">kor</i>, <i lang="ain-Latn">kar</i>, and
		<i lang="ain-Latn">kus</i>, including different positions relative to person suffixes <Ref
			k="nakagawa2024"
			p="159–160"
		/>.
	</p>
	<p>
		Satō's Chitose account gives <i lang="ain-Latn">yaynu-an-pa</i> and rejects
		<i lang="ain-Latn">*yaynu-pa-an</i>
		<Ref k="sato2008" p="104" />. The source-specific ordering matters when using person morphology
		as a word-boundary diagnostic. Authors differ over the suffix, auxiliary, or clitic analysis of
		additional number forms
		<Ref k="nakagawa2022" p="§5.1" /> ‹contested›. The examples and dialect contrasts are developed in
		<Xr ch="suppletive-verbal-number" />.
	</p>
</S>

<S t="Person zones require their own paradigms" id="person-zones">
	<p>
		Person marking expresses combinations of grammatical person and argument role. Some combinations
		use prefixes, some use a suffix or circumfix, and some have a form representing more than one
		participant. A single sequence of subject and object slots cannot replace those paradigms
		<Ref k="nakagawa2024" p="163–172" />;
		<Ref k="sato2023b" p="39, 46–50" />.
	</p>
	<p>
		The equals sign used for person boundaries in this grammar keeps them distinct from derivational
		hyphens. It does not settle the affix–clitic analysis. That question, the treatment of zero
		third person, and the mixed alignment patterns are addressed in <Xr
			ch="person-marking-architecture"
		/>.
	</p>
</S>

<S t="Verbal phrases and lexical words" id="quasi-incorporation">
	<p>
		A morphological template describes one verb word. The noun–verb pattern among Tamura's
		<span lang="ja">連他動詞</span> consists of two words that function together as a conventional
		verbal expression. In her
		<i lang="ain-Latn">e-tom k-osma</i>, “I bumped into you,” the noun carries O-series marking and
		the verb carries A-series marking. The two positions remain visible inside the phrase
		<Ref k="tamura1997" p="15, §C.4" />.
	</p>
	<p>
		Satō analyzes this kind of expression as quasi-incorporation: two morphological words can
		constitute one lexical word. His
		<i lang="ain-Latn">en-par a-oyki</i> “people support me” contrasts with one-word derivational
		<i lang="ain-Latn">yay-par-oyki</i>
		“support oneself” <Ref k="sato2021" p="90–94" />. See <Xr
			ch="noun-incorporation-oblique-polysynthesis-debate"
		/> for the verbal construction and <Xr
			ch="relational-and-spatial-nouns"
			s="quasi-incorporation"
		/>
		for Satō's proposed extension to locative noun–particle combinations.
	</p>
</S>
