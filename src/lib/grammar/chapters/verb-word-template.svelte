	<p>
		Bugaeva's revisions distinguish direct causation and anticausative formation in the inner suffix
		zone from indirect causation farther out. She also allows incorporated nouns before the base and
		before applicative positions. She reports no verb containing all six kinds of affix together
		with incorporation
		<Ref k="bugaeva2012" p="481" />.
	</p>
	<p>
		Nakagawa's account similarly treats formative suffixes and stem-forming
		<i lang="ain-Latn">-pa</i> as alternatives. It allows the order of nominal and applicative
		prefixes to vary with the derived meaning and allows a category to occur more than once <Ref
			k="nakagawa2024"
			p="210"
		/>. These descriptions give constrained patterns of combination, with lexical restrictions on
		which bases accept particular formatives.
	</p>
</S>

