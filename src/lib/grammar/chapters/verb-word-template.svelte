<S t="Roots, derived stems, and person marking" id="stem-and-person">
	<p>
		An Ainu verb can consist of a root with person marking, or of a derived stem containing further
		prefixes, suffixes, or an incorporated noun. Descriptions distinguish the formation of that stem
		from the person forms used in a clause
		<Ref k="bugaeva2012" p="481" />;
		<Ref k="nakagawa2024" p="210" />. A template shows recurring positions; the possible
		combinations also depend on the individual verb and the meaning of the derivation.
	</p>
	<p>
		Nakagawa places person markers outside the expanded derivational stem. His schematic order puts
		nominal and applicative prefixes before the root, formative morphology next to it, and causative
		morphology farther out
		<Ref k="nakagawa2024" p="210, table 45" />. The placement of some number forms complicates a
		wholly mechanical division between a verb and following elements, as discussed below.
	</p>
</S>

