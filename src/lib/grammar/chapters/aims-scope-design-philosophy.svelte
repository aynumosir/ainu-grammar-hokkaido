<S t="Aims and intended readership" id="aims">
	<p>
		This reference grammar describes the sounds, word formation, sentence structure, and discourse
		patterns of Hokkaido Ainu. It brings together descriptions of individual dialects, studies of
		particular constructions, and examples from recorded speech and oral literature. The chapters
		assume some familiarity with linguistic terminology; Ainu forms are accompanied by translations
		and, in sentence examples, interlinear glosses.
	</p>
	<p>
		<Xr ch="typological-profile" /> introduces the principal structures. Readers looking for a particular
		form can consult <Xr ch="index-of-grammatical-morphemes" />; the
		<Xr ch="glossary-grammatical-terms">glossary</Xr> explains grammatical terms. The chapters on
		<Xr ch="ainu-people-homeland-history">historical setting</Xr> and
		<Xr ch="sociolinguistic-situation-revitalization">language use and revitalization</Xr> give context
		for the linguistic description.
	</p>
</S>

<S t="Organization" id="comprehensiveness">
	<p>
		The description proceeds from phonology and writing to word classes, possession, the verb,
		person marking, and clause structure. Later chapters treat aspect, modality, evidentiality,
		negation, clause linkage, and discourse. Historical comparison and language contact have
		separate chapters, followed by glossed texts and reference indexes. Cross-references connect
		constructions that involve several of these domains: possession, for example, bears on both
		nominal morphology and evidential expressions.
	</p>
</S>

<S t="Scope" id="scope">
	<S t="Dialects and varieties" id="hokkaido-focus">
		<p>
			Hokkaido Ainu includes varieties with unequal documentary coverage. Refsing's grammar concerns
			Shizunai <Ref k="refsing1986" />; Satō identifies Chitose as the default reference of his
			description <Ref k="sato2008" p="preface" />. Nakagawa works chiefly from Saru and frequently
			uses Chitose examples, alongside material from Horobetsu, Shizunai, Ishikari, Tokachi, and
			Shiranuka <Ref k="nakagawa2024" p="16" />. A form documented in one of these varieties cannot
			automatically be assigned to all the others.
		</p>
		<p>
			Dialect labels on examples identify their provenance where it is known. More specific
			localities and speakers are given with the source attribution. Sakhalin and Kuril examples
			carry their own labels; the main comparisons appear in
			<Xr ch="sakhalin-and-kuril-ainu-contrast" />. The sources and limitations of dialect sampling
			are discussed in <Xr ch="dialect-sample-and-corpus-method" />.
		</p>
		<p>
			Oral narratives, conversations, prayers, and contemporary teaching materials differ in genre,
			purpose, and circumstances of production. Forms used in revitalization and teaching are
			discussed in <Xr ch="sociolinguistic-situation-revitalization" />.
		</p>
	</S>
	<S t="Lexical information" id="grammar-only">
		<p>
			Words appear here as evidence for grammatical patterns: a verb's valency, a noun's possessed
			form, or a sound alternation. Glosses give the meaning needed to interpret each example.
			Dictionary links lead to fuller lexical entries; the principal dictionaries are described in
			<Xr ch="written-sources-grammars-dictionaries" />.
		</p>
	</S>
</S>

<S t="Reading the evidence" id="method">
	<S t="Examples and corpus figures" id="corpus-quantification">
		<p>
			Examples give their source and, where available, a page or example number. An example marked
			<em>constructed</em> is an illustration supplied by the grammar. It does not establish that the
			expression occurred in recorded speech. Corpus figures apply to the material counted; their interpretation
			depends on the dialects, speakers, genres, and search conditions represented. A count of written
			forms may combine several grammatical uses of the same form.
		</p>
		<p>
			<Xr ch="oral-literature-and-spoken-corpora" /> describes the text and recording collections.
			<Xr ch="dialect-sample-and-corpus-method" /> explains how to interpret their coverage, while
			<Xr ch="glossing-abbreviations-and-citation" /> sets out the citation conventions.
		</p>
	</S>
	<S t="Typological comparison" id="typological-framing">
		<p>
			Terms such as <em>head-marking</em>, <em>applicative</em>, and <em>noun incorporation</em>
			relate Ainu structures to cross-linguistic descriptions. Each requires an account of the construction:
			which participants are indexed, what a prefix contributes, or how incorporation affects a verb's
			arguments. <Xr ch="typological-profile" /> introduces these comparisons.
		</p>
	</S>
	<S t="Historical interpretation" id="diachrony">
		<p>
			Historical analyses draw on earlier records, correspondences between dialects, and relations
			between grammatical and lexical forms. Reconstruction and grammaticalization are treated in
			<Xr ch="proto-ainu-segmental-reconstruction" /> and
			<Xr ch="internal-reconstruction-and-grammaticalization-pathways" />; the documentary record is
			surveyed in <Xr ch="history-of-description-research" />.
		</p>
	</S>
	<S t="Competing analyses" id="formal-layer">
		<p>
			Several constructions receive substantially different analyses in the literature. These
			include <Xr ch="alignment-hierarchical-and-the-debate">person alignment</Xr>,
			<Xr ch="applicative-system-overview">applicatives</Xr>,
			<Xr ch="noun-incorporation-oblique-polysynthesis-debate">incorporation</Xr>,
			<Xr ch="evidential-schema-overview">evidential expressions</Xr>, and the relation between
			<Xr ch="hine-akusu-switch-reference">clause linkage and reference tracking</Xr>. The relevant
			chapters distinguish the observed pattern from the analysis proposed to explain it.
		</p>
	</S>
</S>

<S t="Evidence labels" id="evidence-grades">
	<p>
		Labels following a claim indicate its treatment in this grammar. <em>Contested</em> identifies a
		disagreement between analyses. <em>Corpus-confirmed</em> and <em>corpus-suggested</em>
		distinguish a result checked against corpus data from a tentative interpretation of those data.
		<em>Speculative</em> marks an unverified hypothesis; <em>original-needs-review</em> marks a
		proposal originating in this grammar. <em>Consensus</em> is the default grade for unmarked descriptive
		prose. A label should be read together with the cited evidence and the stated scope of the claim.
	</p>
</S>

