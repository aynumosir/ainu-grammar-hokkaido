<S t="Predictable accent and lexical exceptions" id="predictable-lexical">
	<p>
		In Saru and other varieties with the usual accent pattern, a closed first syllable normally
		takes the accent; after an open first syllable, the second normally takes it. A substantial set
		of words departs from the second rule by having initial accent
		<Ref k="nakagawa2024" p="50–51" />; <Ref k="sato2008" p="15" />. These exceptions make accent
		part of the information needed to identify a word.
	</p>
	<p>
		Nakagawa's Saru examples include <i lang="ain-Latn">húci</i> “grandmother,”
		<i lang="ain-Latn">húre</i> “be red,” <i lang="ain-Latn">mína</i> “laugh,”
		<i lang="ain-Latn">núman</i> “yesterday,” and <i lang="ain-Latn">tópen</i> “be sweet.” The list
		is illustrative rather than exhaustive <Ref k="nakagawa2024" p="51" />. The default rule alone
		would place the accent incorrectly in each case.
	</p>
	<p>
		Satō also records rarer third-syllable accents in his Chitose description, including
		<i lang="ain-Latn">aokáy</i>, <i lang="ain-Latn">taanúka</i>, and
		<i lang="ain-Latn">toanúka</i>
		<Ref k="sato2008" p="15" />. These are lexical exceptions outside the Yakumo placement pattern
		described in
		<Xr ch="pitch-accent-placement-rule" />.
	</p>
</S>

