<S t="How much work the contrast does" id="functional-load">
	<p>
		Shiraishi describes a small number of accent-only minimal pairs, while also documenting many
		words that follow the ordinary placement rule <Ref k="shiraishi2022" p="§5.1" />. The number of
		minimal pairs and the number of lexically exceptional accents are different quantities. An
		exceptional accent need not have a segmentally identical word with another accent.
	</p>
	<p>
		The published pairs show that accent can distinguish words. They do not provide a measurement of
		how often listeners rely on that distinction in conversation. Such a measurement would also have
		to account for syntax and context: “suddenly” and “shin,” for example, usually occur in
		different grammatical environments.
	</p>
	<p>
		Regional scope is essential. Nakagawa and Fukazawa distinguish accentual varieties from
		varieties in which pitch does not have this lexical function
		<Ref k="nakagawafukazawa2022" p="§3.1" />. In Shizunai, Nakagawa reports variation between
		initial and second-syllable prominence in tokens meaning “suddenly”; this is part of his
		argument for an unaccented analysis, which differs from Refsing's description
		<Ref k="nakagawa2024" p="50" />; <Ref k="refsing1986" p="§10.6" /> ‹contested›.
	</p>
	<p>
		Accent marks are therefore most informative when their source and variety are known. A
		dictionary's notation can represent a particular speaker or regional pattern; it should not
		silently be imposed on every recording of the same word.
	</p>
</S>

<S t="Complex words and related forms" id="loans-reduplications">
	<p>
		The accent of a simple word does not always determine the accent of a larger expression.
		Shiraishi describes both preservation of first-element accent and renewed application of the
		usual placement rule in complex forms <Ref k="shiraishi2022" p="§5.2" />. The contrast between
		lexical accent and predictable placement must therefore be examined at the level of the complete
		form being pronounced.
	</p>
	<p>
		A useful comparison keeps the base, the derived or repeated form, and their accents together. It
		also distinguishes an attested whole-word accent from a prediction based on the spelling. The
		relevant patterns are described in
		<Xr ch="accent-in-compounds-and-affixation" /> and
		<Xr ch="reduplication-phonology-rule-interaction" />.
	</p>
	<p>
		<strong>Sakhalin comparison.</strong> Some lexical exceptions have corresponding long vowels in
		Sakhalin: Hokkaido <i lang="ain-Latn">mína</i> and Sakhalin
		<i lang="ain-Latn">miina</i> “laugh,” for example
		<Ref k="nakagawa2024" p="51" />. This comparative pattern helps identify a historical question;
		it does not turn the modern Hokkaido accent into a vowel-length distinction.
	</p>
</S>
