<S t="Historical range" id="homeland">
	<p>
		The documented regional varieties of Ainu come from Hokkaido, Sakhalin, and the Kuril Islands.
		Historical accounts also place Ainu communities in northern Honshu and southern Kamchatka.
		Janhunen distinguishes these areas from the smaller Ainu presence on the Asian mainland, which
		he associates with trade through the lower Amur region
		<Ref k="janhunen2022" p="§2(1–3)" />. These distributions changed through migration, language
		shift, colonial settlement, and forced relocation.
	</p>
	<p>
		Evidence for an earlier distribution on Honshu includes place names and proposed lexical
		borrowings. Janhunen's account centres on northern Honshu; Vovin argues for a much wider earlier
		presence on the basis of names and proposed Ainu loans in Old Japanese
		<Ref k="janhunen2022" p="§3(1)" />; <Ref k="vovin2022" p="§§1–2" /> ‹contested›. The geographical
		conclusions depend on those etymologies and their chronology. The proposals are examined in <Xr
			ch="ainu-loanwords-and-toponymy-in-japanese"
		/>.
	</p>
	<p>
		Within Hokkaido, the documentary record distinguishes varieties associated with Saru, Chitose,
		Shizunai, Horobetsu, Ishikari, Tokachi, and other areas. Their grammatical and phonological
		differences are surveyed in <Xr ch="hokkaido-dialect-classification-and-dialectometry" />. The
		availability of records for each variety is treated separately in
		<Xr ch="dialect-sample-and-corpus-method" />.
	</p>
</S>

<S t="Social setting of the recorded language" id="society">
	<p>
		Historical Ainu communities combined fishing, hunting, gathering, gardening, and trade in
		proportions that varied with locality and season. Janhunen describes both maritime and inland
		activities, together with exchanges linking Hokkaido and Sakhalin to the Amur region
		<Ref k="janhunen2022" p="§2(2), §2(5)" />. This regional and economic variation forms part of
		the setting of the recorded narratives and conversations.
	</p>
	<p>
		Oral literature preserves several kinds of speech and performance. Heroic epics, divine songs,
		prose narratives, and prayers differ in their conventions and grammatical patterning
		<Ref k="endo2022" />; <Ref k="okuda2022" />. A narrated event also has its own participants,
		time, and place, which may differ from those of the recording session. These distinctions matter
		for the interpretation of person indexes, quotation, and evidential expressions; see
		<Xr ch="oral-literature-genre-taxonomy" /> and
		<Xr ch="logophoric-narration-and-reported-discourse" />.
	</p>
</S>

<S t="Prehistory and archaeological interpretation" id="archaeology">
	<p>
		Janhunen connects the spread of ancestral Ainu from Honshu to Hokkaido with the Satsumon
		culture, conventionally dated to approximately 700–1200 CE in his account. He links later
		expansion northward to contact with populations associated with the Okhotsk culture
		<Ref k="janhunen2022" p="§3(1–3)" />. This is a reconstruction combining linguistic, historical,
		and archaeological evidence. The identification of an archaeological population with a
		particular language remains an inference.
	</p>
	<p>
		In the same account, the language, material culture, and ancestry of historical Ainu communities
		have partly different histories. Language could spread through a population adopting it, as well
		as through migration. Janhunen therefore separates continuity of the Ainu linguistic lineage
		from the emergence of the cultural complex documented in later centuries
		<Ref k="janhunen2022" p="§4" />. His placement of that lineage among the languages of Jōmon
		Japan leaves the identities and relationships of the other prehistoric languages unresolved.
	</p>
	<p>
		The linguistic evidence recoverable through comparison of Ainu varieties and internal
		reconstruction is discussed in <Xr ch="proto-ainu-segmental-reconstruction" />. Proposed
		connections with other language families are assessed in
		<Xr ch="genetic-position-macro-comparison" />.
	</p>
</S>

<S t="Trade and colonial boundaries" id="early-contact">
	<p>
		Contact with Japanese traders and officials produced early word lists and practical records of
		Ainu. Refsing describes this documentary tradition in her history of research
		<Ref k="refsing1986" p="17–18" />. Its purposes and transcription conventions affect the
		linguistic evidence it preserves; see <Xr ch="history-of-description-research" /> and
		<Xr ch="historical-orthographies-and-the-batchelor-tradition" />.
	</p>
	<p>
		On Sakhalin, Ainu communities had sustained contact with Nivkh and Uilta communities. The Santan
		trade connected this region with the lower Amur and the Japanese islands
		<Ref k="janhunen2022" p="§2(2)" />. Japanese and Russian expansion subsequently changed the
		political boundaries across Ainu territories. The 1875 Treaty of St. Petersburg assigned
		Sakhalin to Russia and the Kuril Islands to Japan; after 1905, southern Sakhalin was under
		Japanese administration until 1945 <Ref k="janhunen2022" p="§2(1)" />. The linguistic
		consequences of northern contact are examined in
		<Xr ch="northern-contact-nivkh-tungusic-manchu" />.
	</p>
</S>

<S t="Colonization and language shift" id="meiji-colonial">
	<p>
		The expansion of Japanese settlement after 1869–1870 transformed the demographic and political
		position of Ainu communities in Hokkaido <Ref k="janhunen2022" p="§2(1)" />. Ōno describes the
		pressures that led families to shift to Japanese, including discrimination and restrictions on
		Ainu use in schools. He distinguishes those restrictions from a general legal prohibition of the
		language, for which he reports no record <Ref k="ono2022" p="§2" />.
	</p>
	<p>
		Forced relocation also affected the survival of regional varieties. The Northern Kuril Ainu were
		moved to Shikotan in 1884; Sakhalin Ainu communities were displaced to Hokkaido after 1945.
		Janhunen relates the subsequent loss of these varieties to the disruption of their speech
		communities <Ref k="janhunen2022" p="§2(3)" />. Hokkaido records likewise reflect language
		shift, but its timing and the opportunities for recording differed between places and families.
		Speaker biographies are therefore part of the evidence for each collection.
	</p>
</S>

<S t="Recognition and language revitalization" id="recognition">
	<p>
		The 1997 Ainu Culture Promotion Act established a framework for support of cultural activity,
		including language programmes. Ōno describes the 2008 parliamentary resolution on indigenous
		recognition and the 2019 legislation that replaced the 1997 act, alongside the establishment of
		Upopoy in Shiraoi <Ref k="ono2022" p="§6, §7.3" />. The museum is one part of Upopoy, which also
		includes a park and memorial facilities.
	</p>
	<p>
		Language revitalization also has a longer local history, including recording work by Ainu
		speakers and community teaching initiatives. Ōno traces Kayano Shigeru's language school in
		Nibutani to 1983 and the Ainu Association's organized language classes to 1987
		<Ref k="ono2022" p="§4" />. These activities and their implications for language use are
		discussed in <Xr ch="sociolinguistic-situation-revitalization" />.
	</p>
</S>
