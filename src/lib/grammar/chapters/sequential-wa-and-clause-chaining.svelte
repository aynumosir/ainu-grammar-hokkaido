<S t="Connected events with wa" id="wa">
	<p>
		<i lang="ain-Latn">Wa</i> connects events that can be understood as a sequence, a cause and
		result, or an action with its attendant circumstances. Satō notes that the boundaries between
		these uses are often unclear
		<Ref k="sato2008" p="45–46" />.
	</p>
	<Ex
		m="suma eokok wa esitciw"
		g="stone stumble.over CONJ fall"
		tr="[Someone] stumbled over a stone and fell."
		cite="sato2008:45"
		dial="CHI"
		place="§6.2, sequential use of wa"
	/>
	<p>
		A shared subject is possible, as here, but is not required. The child-and-barrel example in <Xr
			ch="clause-linkage-overview"
			s="subjects"
		/>
		has distinct subjects. Refsing reports shared subjects in about 90 percent of the
		<i lang="ain-Latn">wa</i>
		examples in her own Shizunai material; this is a description of that sample <Ref
			k="refsing1986"
			p="240–241"
		/>.
	</p>
	<p>
		Nakagawa emphasizes the connection between the events. His Saru
		<i lang="ain-Latn">kor wa ek</i> ‘bring’ involves coming while carrying something, while
		<i lang="ain-Latn">arpa wa inkar</i>
		can mean trying to go. In the latter construction, the second verb contributes an attemptive
		meaning
		<Ref k="nakagawa2024" p="339, examples 606–609" />.
	</p>
</S>

<S t="Result states and manner" id="phase">
	<p>
		For Saru, Nakagawa proposes a comparison in which
		<i lang="ain-Latn">wa</i> presents the result of an action,
		<i lang="ain-Latn">kor</i> its ongoing phase, and
		<i lang="ain-Latn">no</i> a state without temporal change. Thus
		<i lang="ain-Latn">ipe wa soyne</i>
		describes going outside after eating, while <i lang="ain-Latn">ipe kor soyne</i> describes going
		out while eating <Ref k="nakagawa2024" p="341" />.
	</p>
	<p>
		He also identifies a limit to that account:
		<i lang="ain-Latn">apkas wa arpa</i> ‘go on foot’ combines walking with going. It requires an
		account of manner or of the events as an integrated whole, beyond simple completion of the first
		action
		<Ref k="nakagawa2024" p="342" />.
	</p>
	<p>
		With <i lang="ain-Latn">an</i>, the construction can describe a resulting state, as in
		<i lang="ain-Latn">racitke wa an tuki</i>
		‘a hanging cup’
		<Ref k="nakagawa2024" p="339, example 607" />. The aspectual constructions are treated in <Xr
			ch="existential-aspect-an-oka"
		/>.
	</p>
</S>

<S t="Duration and a subsequent development: ayne" id="ayne">
	<p>
		<i lang="ain-Latn">Ayne</i> relates a situation that lasts for some time to what follows. Satō's
		example repeats the pulling action before describing the eventual result <Ref
			k="sato2008"
			p="44"
		/>.
	</p>
	<Ex
		m="k=etaye a k=etaye a k=etaye a ayne easir sinrit turano k=etaye"
		g="1SG.A=pull ITR 1SG.A=pull ITR 1SG.A=pull ITR CONJ finally root together.with 1SG.A=pull"
		tr="I kept pulling and finally pulled it out with its roots."
		cite="sato2008:44"
		dial="CHI"
		place="§6.2, ayne example"
		note="ITR identifies the repeated-action use of a in this construction. Refsing describes comparable V a V a sequences as iterative or durative (pp. 247–248)."
	/>
	<p>
		The outcome need not be an achievement. Refsing illustrates walking followed by tiredness and
		associates Shizunai <i lang="ain-Latn">ayne</i> with impatience <Ref
			k="refsing1986"
			p="247, example 431"
		/>. Nakagawa's Saru example describes staying in another household for a while before returning
		home <Ref k="nakagawa2024" p="346–347, example 638" />.
	</p>
	<p>
		Nakagawa also gives a Chitose negative construction interpreted as jumping ashore before a boat
		has reached land. For Tokachi he lists
		<i lang="ain-Latn">ahinne</i> and <i lang="ain-Latn">ainne</i>
		<Ref k="nakagawa2024" p="347, examples 639–640" />. Neither affirmative polarity nor a
		successful effort is inherent in every use of this connective.
	</p>
</S>

<S t="Negation and pronunciation" id="distribution">
	<p>
		Satō describes <i lang="ain-Latn">no</i> as the regular Chitose connector for negative
		expressions of sequence or attendant circumstance
		<Ref k="sato2008" p="44–47" />. Refsing's Shizunai example nevertheless links
		<i lang="ain-Latn">ku oyra ka somo ki</i> ‘I do not forget’ with
		<i lang="ain-Latn">wa</i> to a following statement about recounting the grandmother's words <Ref
			k="refsing1986"
			p="240, example 415"
		/>. These descriptions do not support a prohibition of negative
		<i lang="ain-Latn">wa</i> across Hokkaido.
	</p>
	<p>
		Refsing records a Shizunai pronunciation <i lang="ain-Latn">ma</i> after predicates ending in
		<i>n</i>
		or <i>m</i>
		<Ref k="refsing1986" p="241" />. This is a phonological variant of the connective in the
		environment she describes; other particles written <i lang="ain-Latn">ma</i> require their own grammatical
		identification.
	</p>
</S>
