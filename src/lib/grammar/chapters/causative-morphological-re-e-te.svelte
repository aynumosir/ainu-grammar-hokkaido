		<thead><tr><th>Final sound</th><th>Suffix</th><th>Published formation</th></tr></thead>
		<tbody>
			<tr
				><td>A vowel, y, or w</td><td><i lang="ain-Latn">-re</i></td><td
					><i lang="ain-Latn">nu → nu-re</i>, hear → let someone hear</td
				></tr
			>
			<tr
