		The patterns are lexical: the Handbook account, for example, excludes the
		<i lang="ain-Latn">-ke</i>
		series for
		<i lang="ain-Latn">etok</i>
		<Ref k="nakagawa2022pos" p="§§5.1, 5.3.1" />. The suffix also occurs beyond locative nouns, as
		in
