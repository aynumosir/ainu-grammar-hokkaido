<S t="The descriptive starting points" id="overview">
	<p>
		Ainu permits contextually understood noun phrases to be absent, indexes participants on the
		verb, and allows considerable variation in preverbal noun-phrase order. These properties
		motivate questions about how noun phrases relate to verbal arguments
		<Ref k="bugaeva2022" p="§§4.1, 4.3" />;
		<Ref k="nakagawa2024" p="362–365" />. They do not by themselves determine a single analysis of
		phrase structure.
	</p>
	<p>
		The term <em>nonconfigurationality</em> groups questions about flexible order, omitted
		expressions and the structural positions assigned to them. The narrower pronominal-argument
		question concerns whether person forms themselves satisfy a predicate's arguments, and what
		grammatical status remains for a coreferential lexical noun phrase. Bugaeva reviews appositive
		and shared-argumenthood accounts, while Satō develops an analysis in Role and Reference Grammar <Ref
			k="bugaeva2022"
			p="§4.3"
		/>;
		<Ref k="sato2025a" p="362–370" />.
	</p>
</S>

<S t="Head marking and the indexed noun phrase" id="head-marking">
	<p>
		In the head-marking framework of <Ref k="nichols1986" />, grammatical relations are marked on
		the head of a construction. Satō applies this perspective to Ainu personal forms and combines it
		with a layered clause analysis: a predicate nucleus, a core containing its arguments, and larger
		clause and sentence structures
		<Ref k="sato2025a" p="360–364" />.
	</p>
	<Ex
		m="cep a=Ø=koyki"
		g="fish 4.A=3.O=catch"
		tr="We catch fish."
		cite="sato2025a:365"
		dial="CHI"
		place="Example 17"
		note="The source explicitly prints a third-person zero and translates the actor inclusively. Its hyphens are rendered as person boundaries = here."
	/>
	<p>
		For this construction, Satō treats the personal elements as satisfying the arguments inside the
		core and places lexical <i lang="ain-Latn">cep</i> outside it. With
		<i lang="ain-Latn">cep-koyki=an</i>, incorporation instead places the noun inside the complex
		predicate <Ref k="sato2025a" p="364–367, examples 17–18" />. This is his analysis of the
		relationship between lexical expression and morphological realization ‹contested›.
	</p>
</S>

<S t="The unindexed argument and shared argumenthood" id="alternatives">
	<p>
		Satō's account does not place every lexical noun phrase outside the core. A three-place
		predicate can have a theme with no corresponding person index. In his constructed
		<i lang="ain-Latn">wakka eci=ta-re</i> “I make you draw water,” the water belongs inside the
		core but outside the predicate nucleus. He also shows that an unindexed theme can be recovered
		from discourse <Ref k="sato2025a" p="368–370" />. The examples are given in <Xr
			ch="argument-realization-indexing"
		/>.
	</p>
	<p>
		Bugaeva favors shared argumenthood between person forms and coreferential noun phrases for Ainu.
		In her view, location-class information on a noun phrase supports retaining a grammatical
		contribution for that phrase ‹contested›
		<Ref k="bugaeva2022" p="§§4.3–4.4" />. Nakagawa demonstrates how locative nouns help distinguish
		two object roles in otherwise unmarked noun phrases
		<Ref k="nakagawa2022pos" p="§6.1" />.
	</p>
