<S t="Complex noun phrases and claims about displacement" id="noun-phrases">
	<p>
		A sequence containing separated nominal elements can still be one noun phrase. Nakagawa
		discusses a quantified expression with the numeral noun
		<i lang="ain-Latn">sinep</i> “one” <Ref k="nakagawa2024" p="384" />.
	</p>
	<Ex
		m="toma ka sinep ka isam"
		g="mat ADD one ADD not.exist"
		tr="There is not a single mat either."
		cite="nakagawa2024:384"
		dial="SAR"
		place="Second sentence of example 750"
	/>
	<p>
		His analysis groups <i lang="ain-Latn">toma ka sinep ka</i> into one noun phrase, which is the
		sole argument of <i lang="ain-Latn">isam</i>. Treating “mat” and “one” as separate arguments
		would give that one-place predicate an extra argument
		<Ref k="nakagawa2024" p="384, examples 750′–750‴" />. The particle-separated form is therefore
		evidence for his complex nominal structure. It supplies no independent demonstration of
		quantifier movement or noun-phrase discontinuity.
	</p>
</S>
