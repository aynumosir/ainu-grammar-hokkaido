<S t="Location and the argument–adjunct distinction" id="obliques">
	<p>
		An expression of place, instrument or accompaniment can stand outside a predicate's core
		argument frame. Its grammatical status depends on the construction. Nakagawa contrasts two
		motion verbs with similar English translations but different requirements
		<Ref k="nakagawa2024" p="127–128" />.
	</p>
	<Ex
		m="cise or ta ahun"
		g="house place LOC enter.SG"
		tr="Someone entered the house."
		cite="nakagawa2024:128"
		place="Author's illustration 12"
		note="Ahun is intransitive; cise or ta is a postpositional phrase. The source leaves the actor unexpressed."
	/>
	<Ex
		m="cise or osma"
		g="house place enter"
		tr="Someone jumped into the house."
		cite="nakagawa2024:128"
		place="Author's illustration 13"
		note="Osma takes a locative object, here cise or, without ta. The English ‘into’ does not correspond to an extra postposition in this example."
	/>
	<p>
		A locative noun can thus belong to a core object phrase. Conversely, a postpositional phrase can
		add an instrument, companion or place to a clause without changing the verb's argument count <Ref
			k="nakagawa2024"
			p="127–128"
		/>. Applicatives provide another construction, registering an object relation on the verb; see
		<Xr ch="applicative-system-overview" />.
	</p>
</S>

<S t="Complete utterances without a verbal predicate" id="verbless">
	<p>
		Tamura's sentence classification includes noun or adverbial phrases accompanied by a final
		particle, as well as verbal-predicate sentences, interjections and vocatives. Satō reproduces
		this classification and its examples
		<Ref k="sato2025a" p="354–355, §2.1" />. The following noun-phrase utterances are complete
		sentences under that description.
	</p>
	<Ex
		m="poro cise un"
		g="big house FIN"
		tr="Here is a big house."
		cite="sato2025a:354"
		place="Example 3, quoting Tamura 1988"
	/>
	<Ex
		m="tan pe he"
		g="this thing Q"
		tr="Is it this?"
		cite="sato2025a:355"
		place="Example 4, quoting Tamura 1988"
	/>
	<p>
		Nakagawa describes the ordinary sentence pattern around a verb phrase
		<Ref k="nakagawa2024" p="362" /> and states that noun-ended sentences are generally avoided
		<Ref k="nakagawa2022pos" p="§2.1" />. These classifications differ in the kinds of utterance
		included and in the units used to describe them. Tamura's examples do not require an unspoken
		copula to be added to their published analysis.
	</p>
</S>

<S t="Short questions and formal-noun endings" id="questions">
	<p>
		A short question can pick up material from a preceding utterance. Nakagawa's example asks
		whether a reference to having nothing to eat means a time of famine
		<Ref k="nakagawa2024" p="409" />.
	</p>
	<Ex
		m="keman hi ta he"
		g="famine time LOC Q"
		tr="At the time of famine?"
		cite="nakagawa2024:409"
		dial="SAR"
		place="Example 846, citing Tamura 1984:26"
		note="This is an echo question about the preceding speaker's reference to a time without food. He follows the locative phrase."
	/>
	<p>
		Formal-noun clause endings form a separate descriptive group. Nakagawa gives questions ending in <i
			lang="ain-Latn">ruwe</i
		>
		or <i lang="ain-Latn">hawe</i> without
		<i lang="ain-Latn">ne</i>, as well as rhetorical questions and exclamations with these endings <Ref
			k="nakagawa2024"
			p="395–396"
		/>.
	</p>
	<Ex
		m="e=apkas wa te pakno e=ek ruwe"
		g="2SG.S=walk CONJ here until 2SG.S=come.SG EVID"
		tr="Did you walk all the way here?"
		cite="nakagawa2024:395"
		dial="SAR"
		place="Example 789, citing Honda 2001:19"
		note="Ruwe is given a broad evidential gloss here. The source presents the form as a question without ne."
	/>
	<p>
		Here the preceding clause contains verbal predicates. The bare ending is therefore a different
		issue from a noun-phrase-only utterance. Nakagawa also records affirmative replies with <i
			lang="ain-Latn">ruwe un</i
		>, while noting that
		<i lang="ain-Latn">un</i> itself has other uses and that this reply pattern may be limited to
		southern varieties <Ref k="nakagawa2024" p="396" />. The range cannot be reduced to a single
		rule of optional copula deletion.
	</p>
</S>

<S t="Ambient predicates and word boundaries" id="ambient">
	<p>
		Expressions of weather and surrounding conditions contain verbal material even when they have no
		ordinary personal subject. Nakagawa initially presents zero-argument predicates with <i
			lang="ain-Latn">sir-</i
		>, <i lang="ain-Latn">me-</i> and related material, then explicitly revisits whether all such
		expressions are single words
		<Ref k="nakagawa2024" p="128–131, 493" />.
	</p>
	<p>
		He compares Refsing's <i lang="ain-Latn">aptoas</i> with Tamura's
		<i lang="ain-Latn">apto as</i> “it rains.” Because a zero-argument expression has no person
		index by definition, the usual person-position test cannot settle its word boundary <Ref
			k="nakagawa2024"
			p="493"
		/>. This uncertainty concerns compounding and segmentation; it does not establish an absence of
		a verb. See
		<Xr ch="noun-incorporation-subject-possessor-stranding" />.
	</p>
</S>
