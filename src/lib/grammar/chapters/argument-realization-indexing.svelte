<S t="Arguments, indexes, and noun phrases" id="overview">
	<p>
		A predicate's argument structure, its person marking, and the noun phrases pronounced in a
		clause need to be distinguished. A three-place verb can occur with fewer than three lexical noun
		phrases, and its person-marking system does not provide an independent index for every
		participant <Ref k="nakagawa2024" p="127–128" />;
		<Ref k="sato2025a" p="368–370" />. These are related properties of argument realization, with
		different consequences for analysis.
	</p>
	<p>
		Verbal person forms identify S, A and O according to the paradigm and construction. Third-person
		forms are commonly analyzed as zero, while portmanteau forms can express an interaction between
		two persons <Ref k="bugaeva2022" p="§4.1" />. The paradigms and disagreements about their
		morphological status appear in
		<Xr ch="person-marking-architecture" />.
	</p>
</S>

<S t="Contextually omitted noun phrases" id="omission">
	<p>
		Nakagawa compares three forms of a clause with <i lang="ain-Latn">kore</i> “give.” The full form
		expresses both the theme and the recipient; either can be omitted when context supplies its
		interpretation <Ref k="nakagawa2024" p="127" />.
	</p>
	<Ex
		m="topenpe hekattar ku=kore"
		g="sweet children 1SG.A=give"
		tr="I gave sweets to the children."
		cite="nakagawa2024:127"
		place="Author's illustration 11a"
	/>
	<Ex
		m="topenpe ku=kore"
		g="sweet 1SG.A=give"
		tr="I gave sweets to them."
		cite="nakagawa2024:127"
		place="Author's illustration 11b"
		note="The children are understood from context in the source comparison."
	/>
	<Ex
		m="hekattar ku=kore"
		g="children 1SG.A=give"
		tr="I gave them to the children."
		cite="nakagawa2024:127"
		place="Author's illustration 11c"
		note="The sweets are understood from context. Omitting this noun does not turn kore into a two-place lexical verb."
	/>
	<p>
		Both expressed objects are bare noun phrases. Their roles follow the verb and the context; there
		is no added nominal case ending distinguishing “to the children” from “sweets” in these examples <Ref
			k="nakagawa2024"
			p="127"
		/>. Omission differs from incorporation, which combines nominal material with the stem and can
		change its argument frame.
	</p>
</S>

<S t="An argument without a separate person index" id="unindexed">
	<p>
		Satō makes the distinction between argument count and indexing explicit with a causative of
		“draw water.” The portmanteau <i lang="ain-Latn">eci=</i> expresses first-person actor acting on
		a second-person causee; the water is an additional, unindexed theme
		<Ref k="sato2025a" p="368–369" />.
	</p>
	<Ex
		m="wakka eci=ta-re"
		g="water 1SG.A.2SG.O=draw-CAUS"
		tr="I make you draw water."
		cite="sato2025a:369"
		constructed
		place="Author's constructed example 19"
		note="Satō explicitly constructs this example. Eci= is the singular first-to-second-person interaction form here."
	/>
	<p>
		In his Role and Reference Grammar analysis, the theme belongs to the clause's core even though
		it has no person index. It may also be omitted anaphorically. His next example introduces a
		sweet, then gives a clause in which that sweet remains understood as the thing to be given <Ref
			k="sato2025a"
			p="369–370"
		/>.
	</p>
	<Ex
		m="ekasi ku=kore na"
		g="old.man 1SG.A=give FIN"
		tr="I will give it to the old man."
		cite="sato2025a:370"
		dial="CHI"
		place="Second sentence of example 21"
		note="The preceding sentence identifies an object as a sweet. The omitted sweet is the theme of kore. The article gives Shirasawa Nabe's Chitose as its default example provenance."
	/>
	<p>
		This is an argument licensed by the predicate and recovered through reference, without its own
		person form. Theoretical treatments of indexed and unindexed noun phrases are compared in <Xr
			ch="nonconfigurationality-pronominal-argument"
		/>.
	</p>
</S>

<S t="Location and other role information" id="roles">
	<p>
		Locative noun classes can help identify which participant has a spatial role. Nakagawa compares <i
			lang="ain-Latn">cise or ta ahun</i
		>
		“enter the house” with
		<i lang="ain-Latn">cise or osma</i> “jump into the house.” The first has a postpositional
		phrase; the second has a locative object selected by the transitive verb
		<Ref k="nakagawa2024" p="128" />. Location in the event does not by itself determine whether the
		expression is a core object or an adjunct.
	</p>
	<p>
		His Handbook example with <i lang="ain-Latn">oma-re</i> “put into” contains two objects, cooked
		food and a basket's location, while leaving the actor unexpressed. The locative noun
		<i lang="ain-Latn">or</i>
		marks the basket phrase as the location
		<Ref k="nakagawa2022pos" p="§6.1, example 74" />. Person marking, nominal class, lexical
		selection and discourse all contribute to identifying the participants. See
		<Xr ch="relational-and-spatial-nouns" /> for the locative forms.
	</p>
</S>
