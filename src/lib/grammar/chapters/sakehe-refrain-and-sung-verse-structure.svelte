<S t="Meaning, alternation, and narrator changes" id="meaning">
	<p>
		Chiri's classification, quoted by Nakagawa, includes refrains associated with voices,
		characteristic actions or properties, situations in a story, and cries or calls. Some suggest
		who is speaking; many have become opaque <Ref
			k="nakagawa2024"
			p="582–584, citing Chiri 1954a:166–168"
		/>.
	</p>
	<p>
		A refrain need not remain constant throughout a story. Nakagawa reports a tale in which it
		changes as the narrator changes from one bird to another. He also gives Chitose lines
		alternating
		<i lang="ain-Latn">HUNNAO</i> and <i lang="ain-Latn">NOWAO</i>. Across traditions, the same
		story can have different refrains, and the same refrain can accompany different stories
		<Ref k="nakagawa2024" p="581, example 1249; 583–584, citing Kindaichi 1931a:149–155" />.
	</p>
	<p>
		Nakagawa also identifies “secondary refrains”: recurring phrases embedded in the story's text
		that may depart from its usual grammar. His analysis of the fox song in Chiri Yukie's collection
		preserves those departures as part of the particular expression
		<Ref k="nakagawa2024" p="584, §24.5.5" />.
	</p>
</S>

<S t="Syllable counting and accent" id="metre">
	<p>
		Ainu metrical descriptions count syllables. Okuda distinguishes organization centered on
		syllable count from organization centered on the placement of accent within the opening part of
		a line. In his latter analysis, initial accent in a four-syllable line corresponds to accent on
		either of the first two syllables in a five-syllable line. His review describes five-syllable
		tendencies and several techniques for adjusting the wording, including added particles, expanded
		forms, and <i lang="ain-Latn">ki</i> constructions
		<Ref k="okuda2022" p="§§2.1, 3.2–3.4" />.
	</p>
	<p>
		The published samples contain variation. In Hatozawa Wateke's
		<i lang="ain-Latn">Amamecikappo</i>, Okuda counts 90 lines apart from refrains: 14 with four
		syllables, 49 with five, 23 with six, and four with seven. Twelve of the fourteen four-syllable
		lines have initial accent. Other samples include lines of eight or nine syllables
		<Ref k="okuda2022" p="§3.3" />.
	</p>
	<p>
		Wateke's heroic epic <i lang="ain-Latn">Tumi suykere wenpe suykere</i>
		uses both organizations within one performance, differentiated by musical rhythm. Okuda leaves their
		wider geographical distribution open <Ref k="okuda2022" p="§5.2" />. For grammatical expansions
		in verse, see
		<Xr ch="poetic-archaic-elevated-register" />; for recurrent paired phrases, see <Xr
			ch="parallelism-couplets-and-word-pairs"
		/>.
	</p>
	<p>
		Okuda distinguishes recurrent sounds from a metrical requirement. He reports no obligatory rhyme
		or alliteration scheme, while quoting Philippi's observation that some alliteration may be
		consciously cultivated <Ref k="okuda2022" p="§2.2, citing Philippi 1979" />.
	</p>
</S>
