<S t="Refrain and manner of singing" id="refrain">
	<p>
		<i lang="ain-Latn">Sakehe</i> names the recurring refrain of a divine epic, but can also include
		its melody, rhythm, and overall manner of singing. Tamura's Saru dictionary records both senses.
		It describes refrains inserted at roughly established points, while spoken passages within or at
		the end of the performance lack them
		<Ref k="tamura1996" p="s.vv. sáke, sákehe" />.
	</p>
	<p>
		Placement varies. Nakagawa distinguishes refrains at the beginning of a line, at its end, on an
		independent line, and in combinations of these positions. Repetition may follow every line or
		occur less regularly; some performances alternate two refrains
		<Ref k="nakagawa2024" p="579–581, §§24.5.1–24.5.2" />.
	</p>
</S>

