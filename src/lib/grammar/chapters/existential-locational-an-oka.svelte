<S t="Existence and location" id="existence">
	<p>
		The verb <i lang="ain-Latn">an</i> expresses existence or presence. Its subject is the person or
		thing present; a place can be specified separately. Satō treats it as a one-place verb and
		illustrates a location expressed with a locative phrase and topic particle
		<Ref k="sato2008" p="3–4" />.
	</p>
	<Ex
		m="Tokiyo ot ta anakne poro cise poronno an"
		g="Tokyo place LOC TOP big house many exist.SG"
		tr="There are many big houses in Tokyo."
		cite="sato2008:4"
		dial="CHI"
		place="Author's illustration"
		note="Satō gives this as the more usual expression, while allowing the alternative with Tokiyo as a bare topic. The noun cise itself has no plural ending."
	/>
	<p>
		A location phrase does not become an additional argument of <i lang="ain-Latn">an</i>. This
		distinguishes the construction from verbs which take a place as their object; see <Xr
			ch="oblique-adjunct-verbless-clauses"
		/>. With a personal subject,
		<i lang="ain-Latn">an</i> carries the corresponding intransitive person marker.
	</p>
	<Ex
		m="orwano ku=cise or ta ku=an kor"
		g="then 1SG.POSS=house place LOC 1SG.S=exist.SG CONJ"
		tr="Then, while I was at my house…"
		cite="nakagawa2024:166"
		dial="ISH"
		place="Example 104, citing Sunazawa 1983:75"
		note="The Ishikari form ku=an is retained. Chitose and western Hidaka commonly contract this prefix before a vowel."
	/>
</S>

<S t="Number, dialect, and narrative person" id="number">
	<p>
		The plural counterpart is <i lang="ain-Latn">oka</i> or <i lang="ain-Latn">okay</i>. Nakagawa
		records <i lang="ain-Latn">oka</i> in Saru, Chitose, Mukawa and Shizunai, and
		<i lang="ain-Latn">okay</i>
		more widely, including Chitose. Even varieties normally using <i lang="ain-Latn">oka</i> have
		<i lang="ain-Latn">okay</i>
		before
		<i lang="ain-Latn">pe</i> or <i lang="ain-Latn">pa p</i> in his description
		<Ref k="nakagawa2024" p="146–147, table 16 note 1" />.
	</p>
	<p>
		Verbal number also interacts with the fourth-person series and narrative convention. A single
		narrator can use the plural existential in Shizunai or Kushiro. Nakagawa contrasts this with the
		usual singular-root narration of one participant in western Hidaka, Chitose and Horobetsu <Ref
			k="nakagawa2024"
			p="178–179"
		/>.
	</p>
	<Ex
		m="sinen ne oka=an wa mismu=an na"
		g="one.person COP exist.PL=4.S CONJ be.bored=4.S FIN"
		tr="I was alone and bored."
		cite="nakagawa2024:178"
		dial="SHI"
		place="Example 151"
		note="Sinen ne explicitly identifies one person. Oka=an is the published narrative form."
	/>
	<p>
		The existential root <i lang="ain-Latn">an</i> and the fourth-person suffix
		<i lang="ain-Latn">=an</i> are separate grammatical elements. The latter can attach to other
		verbs, as both verbs in this example show. See <Xr ch="person-number-interactions" />.
	</p>
</S>

<S t="Seasons, states, and continuation" id="extensions">
	<p>
		Existence includes the onset of a situation. Nakagawa's seasonal example uses
		<i lang="ain-Latn">paykar an</i> for the arrival of spring
		<Ref k="nakagawa2022pos" p="§2.3, example 11" />.
	</p>
	<Ex
		m="paykar an yakun kina-kar=an kusu paye=an ro"
		g="spring exist.SG if plant-gather=4.S PURP go.PL=4.S HORT"
		tr="When spring comes, let’s go gather edible wild plants."
		cite="nakagawa2022pos:§2.3"
		dial="CHI"
		place="Example 11"
		note="The two suffixes =an refer to the inclusive participants. The first an is the existential verb."
	/>
	<p>
		Existential verbs also occur after linked predicates in expressions of continuing states or
		activities; Nakagawa's <i lang="ain-Latn">ku=hotke wa k=an</i> describes lying down and
		remaining there <Ref k="nakagawa2024" p="166, example 103" />. The interpretation belongs to the
		whole combination. The distinctions between progressive and resulting states are developed in
		the aspect chapters.
	</p>
</S>

<S t="Absence and other existential frames" id="absence">
	<p>
		<i lang="ain-Latn">Isam</i> means ‘not exist’ or ‘be absent’. Bugaeva groups it with verbs whose
		meanings already contain negation, including possessive
		<i lang="ain-Latn">sak</i> ‘lack’ <Ref k="bugaeva2012" p="496" />. Nakagawa's Saru question
		repeats <i lang="ain-Latn">isam</i> while asking why a bowl is missing
		<Ref k="nakagawa2024" p="410, example 849" />. Lexical absence, possession, and ordinary
		negation have related meanings but different predicate structures.
	</p>
	<p>
		An affiliative noun followed by an existential can express possession; see
		<Xr ch="predicative-possession-clauses" />. Existentials also follow formal nouns in clause
		endings, including the Saru question <i lang="ain-Latn">ruwe he an</i>
		<Ref k="nakagawa2024" p="410, example 848" />. Their distribution there depends on the
		particular ending and sentence type.
	</p>
</S>
