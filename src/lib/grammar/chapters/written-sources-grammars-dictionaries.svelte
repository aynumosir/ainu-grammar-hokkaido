<S t="The early grammatical descriptions" id="classical-grammars">
	<p>
		A source's dialect, speaker, and purpose determine what evidence it supplies. A reference
		grammar may synthesize a system from many examples; a dictionary records properties of
		individual words; a text edition preserves expressions in discourse. Their contributions
		overlap, but each has its own limits. The history of these publications is traced in
		<Xr ch="history-of-description-research" />; recordings and text collections are described in
		<Xr ch="oral-literature-and-spoken-corpora" />.
	</p>
	<p>
		The 1936 outline by Kindaichi and Chiri builds on Kindaichi's grammatical work on heroic epic.
		Nakagawa describes its comparison of the Saru material with Horobetsu
		<Ref k="nakagawa2024" p="93" />; <Ref k="kindaichi1936" />. Chiri's 1942 study centres on
		Sakhalin <Ref k="chiri1942" />. The two works consequently supply different geographical
		perspectives, as well as evidence for the development of grammatical analysis.
	</p>
	<p>
		Refsing's comparison of the earlier tradition shows that familiar labels can conceal differences
		in classification. She contrasts semantic groupings with categories established through the
		distribution of forms <Ref k="refsing1986" p="§2.4.1" />. A citation to an older analysis
		therefore needs to preserve both the author's terminology and the construction to which it
		refers.
	</p>
</S>

