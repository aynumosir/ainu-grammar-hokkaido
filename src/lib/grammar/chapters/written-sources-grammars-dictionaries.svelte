<S t="Dictionaries" id="dictionaries">
	<p>
		Tamura's and Kayano's dictionaries document Saru; Nakagawa's dictionary documents Chitose
		<Ref k="tamura1996" />; <Ref k="kayano1996" />; <Ref k="nakagawa1995" />. Their entries provide
		lexical evidence relevant to grammar, including the forms and constructions in which a word
		occurs. An entry's illustrative sentence also has a different evidentiary role from a general
		rule proposed in a grammar.
	</p>
	<p>
		Hattori's 1964 dictionary brings together ten regional sets of lexical material. Nakagawa lists
		nine varieties surveyed with a common questionnaire: Yakumo, Horobetsu, Saru, Obihiro, Bihoro,
		Asahikawa, Nayoro, Sōya, and Sakhalin Rayciska. Torii's Kuril recordings supply the tenth
		<Ref k="nakagawa2024" p="99" />; <Ref k="hattori1964" />. The nineteen-locality, 200-item survey
		belongs to the separate study by Hattori and Chiri published in 1960
		<Ref k="nakagawa2024" p="100" />; <Ref k="hattorichiri1960" />.
	</p>
	<p>
		Chiri's classified dictionaries organize lexical material by semantic domain, including plants,
		animals, and human beings <Ref k="chiri1953" />;
		<Ref k="refsing1986" p="§2.3" />. Their locality information matters when using an entry in
		dialect comparison. Comparative dictionaries and their sampling are discussed further in
		<Xr ch="hokkaido-lexical-dialectology-and-the-dialect-atlas" />.
	</p>
</S>

<S t="Historical dictionaries and manuscripts" id="philological-record">
	<p>
		Batchelor's dictionary was first published in 1889; the 1905 and 1938 editions represent later
		stages of its publication history <Ref k="refsing1986" p="§2.1" />. Nakagawa describes its
		dialect base as chiefly Saru <Ref k="nakagawa2024" p="91" />. Refsing discusses errors
		identified by Chiri and the need to check individual forms and translations
		<Ref k="refsing1986" p="§2.1" />. The edition cited is therefore relevant to the assessment of a
		particular entry.
	</p>
	<p>
		Earlier manuscripts preserve words and expressions from periods and places for which later
		documentation may be sparse. Refsing surveys practical vocabularies such as the
		<i>Ezo hōgen moshiogusa</i> and their use by later scholars
		<Ref k="refsing1986" p="§1" />. The analysis of such records must account for spelling,
		translation, and transmission between copies. The grammatical interpretation of an old spelling
		is discussed in <Xr ch="historical-orthographies-and-the-batchelor-tradition" />.
	</p>
</S>

<S t="Direct and reported citations" id="source-gaps">
	<p>
		A reported citation indicates that a work is being used through another account. The
		intermediary supplies the passage available for examination, including any selection,
		normalization, translation, or interpretation it contains. Naming both works makes that chain of
		evidence visible. Reported material can support a discussion, but it does not establish that the
		original wording or wider context has been checked.
	</p>
	<p>
		For a grammatical example, the source note identifies the edition and its page, section, or
		example number where available. A transcription adapted to the conventions of this grammar can
		differ from the printed spelling; a source's grammatical analysis can also differ from the gloss
		used here. These distinctions are explained in
		<Xr ch="glossing-abbreviations-and-citation" />.
	</p>
</S>
