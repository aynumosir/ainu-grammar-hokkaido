<S t="Lexical differences among combinations" id="lexical-distribution">
	<p>
		The combinations are not interchangeable paradigm cells. Nakagawa describes
		<i lang="ain-Latn">nep</i> primarily as indefinite, while
		<i lang="ain-Latn">neap</i>
		can refer to an earlier-mentioned entity. He reports <i lang="ain-Latn">newaanpe</i> as the more
		frequent choice for this discourse reference
		<Ref k="nakagawa2024" p="287–288" />. The relation to questions is discussed in <Xr
			ch="interrogative-pro-forms"
		/>.
	</p>
	<p>
		There are examples of <i lang="ain-Latn">nea hi</i>. Nakagawa analyzes
		<i lang="ain-Latn">tani</i> as a contraction of
		<i lang="ain-Latn">tan</i> plus <i lang="ain-Latn">hi</i>, but finds it restricted to formulas
		such as
		<i lang="ain-Latn">toni un tani un</i> “there and here”
		<Ref k="nakagawa2024" p="288" />. A historical relationship does not make every possible
		uncontracted combination an ordinary expression.
	</p>
</S>

<S t="Regional and register differences" id="regional-forms">
	<p>
		The distal forms vary geographically. Nakagawa reports both
		<i lang="ain-Latn">toan</i> and <i lang="ain-Latn">toon</i> in Saru and Chitose, with the latter
		less frequent in the Saru dictionary. He reports no <i lang="ain-Latn">toon</i> examples for the
		Ishikari basin in the dialect dictionary, while Obihiro appears not to use
		<i lang="ain-Latn">toan</i>
		<Ref k="nakagawa2024" p="284–285" />. These are source-specific distribution reports.
	</p>
	<p>
		Discourse-oriented <i lang="ain-Latn">ikia</i> and plural
		<i lang="ain-Latn">ikirok</i> occur from Shizunai eastward, with some Saru examples too.
		<i lang="ain-Latn">Nea</i>
		is widespread, while
		<i lang="ain-Latn">nean</i> is prominent in Tokachi and Kushiro and also occurs alongside
		<i lang="ain-Latn">nea</i>
		elsewhere. Nakagawa leaves their distinction unresolved <Ref k="nakagawa2024" p="285" />.
		Refsing's derogatory reading of <i lang="ain-Latn">ikiap</i> belongs to her Shizunai folktale
		material <Ref k="refsing1986" p="94, §12.3.1" />.
	</p>
	<p>
		Nakagawa also records verse-oriented <i lang="ain-Latn">tanan</i> and the emphatic
		<i lang="ain-Latn">tapan</i>
		/ <i lang="ain-Latn">tapoka(y)</i>, reporting the latter characterization from Tamura's Saru
		dictionary
		<Ref k="nakagawa2024" p="284" />. Register and lexical restrictions remain part of the
		description of these less common forms.
	</p>
</S>

<S t="Place expressions and formation accounts" id="place-expressions">
	<p>
		Expressions such as <i lang="ain-Latn">taan ta</i> “here” and
		<i lang="ain-Latn">toon un</i> “toward there” have a case particle directly after the
		demonstrative. Nakagawa proposes a historical reduction through <i lang="ain-Latn">hi</i>,
		schematically
		<i lang="ain-Latn">taan hi ta</i> → <i lang="ain-Latn">taani ta</i>
		→ <i lang="ain-Latn">taan ta</i>
		<Ref k="nakagawa2024" p="288" /> ‹speculative›.
	</p>
	<p>
		Locative <i lang="ain-Latn">te</i> also combines with place particles, but lacks the
		noun-modifying use: Nakagawa rejects
		<i lang="ain-Latn">*te menoko</i> for “this woman.” He consequently classifies it as a locative
		noun
		<Ref k="nakagawa2024" p="289" />. See
		<Xr ch="relational-and-spatial-nouns" />.
	</p>
	<p>
		Kindaichi and Chiri's earlier account derives demonstrative forms through existential <i
			lang="ain-Latn">an</i
		>
		and
		<i lang="ain-Latn">okay</i>, within its own system of roots and accent distinctions <Ref
			k="kindaichi1936"
			p="57–58, §§85–86"
		/>
		‹speculative›. Refsing organizes her Shizunai forms into a grid of demonstratives, place expressions,
		and interrogatives
		<Ref k="refsing1986" p="108–110, §12.3.6" />. These analyses describe related patterns at
		different levels of detail and with different dialect bases.
	</p>
</S>
