<S t="Situational and discourse reference" id="reference-types">
	<p>
		Nakagawa separates situational <i lang="ain-Latn">tan</i>,
		<i lang="ain-Latn">taan</i>, <i lang="ain-Latn">toan</i>, and
		<i lang="ain-Latn">toon</i> from discourse-oriented
		<i lang="ain-Latn">ne</i>, <i lang="ain-Latn">nea</i>, and
		<i lang="ain-Latn">newaan</i>. He illustrates
		<i lang="ain-Latn">tan</i> with a recording machine before the speakers and
		<i lang="ain-Latn">nea</i>
		with a spear already mentioned in a story
		<Ref k="nakagawa2024" p="284" />.
	</p>
	<p>
		Refsing's Shizunai description allows the spatial demonstratives based on
		<i lang="ain-Latn">ta</i> and <i lang="ain-Latn">to</i> to have anaphoric uses as well <Ref
			k="refsing1986"
			p="§12.3.3"
		/>
		‹contested›. Her account therefore qualifies any attempt to apply the Saru situational/discourse division
		uniformly across Hokkaido.
	</p>
	<p>
		Refsing calls demonstratives definite. Their use helps the hearer identify a referent through
		the situation or prior discourse
		<Ref k="refsing1986" p="§12.3.3" />. Nakagawa's examples likewise show the role of earlier
		mention <Ref k="nakagawa2024" p="284, 287–288" />. These descriptions concern demonstrative
		reference and its constructions.
	</p>
</S>

<S t="Combinations with nominal heads" id="nominal-combinations">
	<p>
		Demonstratives combine with ordinary nouns and with formal nouns such as
		<i lang="ain-Latn">p/pe</i>, <i lang="ain-Latn">hi</i>,
		<i lang="ain-Latn">hike</i>, <i lang="ain-Latn">kur</i>, and
		<i lang="ain-Latn">uske</i>. Combinations with weakly independent
		<i lang="ain-Latn">p</i> and <i lang="ain-Latn">hi</i> are often treated as single demonstrative
		pronouns
		<Ref k="nakagawa2024" p="287" />. See <Xr ch="formal-defective-nouns" />
		for the status of these heads.
	</p>
	<Ex
		m="tan-pe anak su sekor a=ye p ne"
		g="this-thing TOP pot QUOT 4.A=say NMLZ COP"
		tr="This is what is called a pot."
		cite="nakagawa2024:287, example 389"
		dial="SAR"
		note="The source writes tanpe; the internal boundary is displayed here."
	/>
	<p>
		A form containing <i lang="ain-Latn">pe</i> can also refer to a person. Nakagawa quotes Tamura's example
		addressing dancers about a young man who has joined them:
	</p>
	<Ex
		m="toan-pe toykokisma yan"
		g="that-thing hold.firmly IMP.POL"
