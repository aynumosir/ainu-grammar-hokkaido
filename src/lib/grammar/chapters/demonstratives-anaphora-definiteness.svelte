<S t="Demonstrative modifiers" id="demonstrative-modifiers">
	<p>
		Demonstrative adnominals identify a referent by its location in the speech situation or its
		place in the discourse. Their main role is to modify a following noun. Nakagawa distinguishes
		these modifiers from predicates, while also recognizing constructions where some directly
		precede a case particle
		<Ref k="nakagawa2024" p="283, 287–289" />.
	</p>
	<p>
