<S t="Hine and the presentation of successive information" id="hine">
	<p>
		<i lang="ain-Latn">Hine</i> often links successive events. Tamura also describes a broader
		function: presenting one situation and then another, with each carrying its own informational
		weight. She contrasts this with the more integrated events commonly linked by
		<i lang="ain-Latn">wa</i>
		<Ref k="tamura1997" p="47–48" />.
	</p>
	<p>
		Neither event succession nor a shared participant is obligatory in every use. In Satō's Chitose
		example, the speaker releases a cup and the cup breaks
		<Ref k="sato2008" p="44" />.
	</p>
	<Ex
		m="koppu k=opici hine kōne wa isam"
		g="cup 1SG.A=release CONJ break CONJ not.exist"
		tr="I let go of the cup and it broke."
		cite="sato2008:44"
		dial="CHI"
		place="§6.2, second hine example"
		note="The source's long-vowel notation in kōne is retained. Wa isam presents the completed result."
	/>
	<p>
		Tamura also records <i lang="ain-Latn">hine</i> at the beginning of an utterance after a
		conversation had ended tens of minutes earlier. Its discourse-linking uses therefore extend
		beyond a tightly connected sequence within one utterance <Ref k="tamura1997" p="48" />. The
		different structural accounts are compared in <Xr ch="clause-linkage-overview" s="analyses" />.
	</p>
</S>

<S t="Akusu and a following development" id="akusu">
	<p>
		Descriptions of <i lang="ain-Latn">akusu</i> and
		<i lang="ain-Latn">akus</i> emphasize different aspects of the relation. Nakagawa describes a
		subsequent development related to the first event, whether or not the relation is causal
		<Ref k="nakagawa2024" p="345, example 630" />. Satō describes a factual sequence in which the
		second event happens contingently after the first <Ref k="sato2008" p="47" />.
	</p>
	<Ex
		m="kanpi ku=sanke ruwe ne akusu itasa kanpi ek ruwe ne"
		g="letter 1SG.A=send EVID COP CONJ reply letter come.SG EVID COP"
		tr="I sent a letter, and a reply came."
		cite="sato2008:47"
		dial="CHI"
		place="§6.4, akusu example"
	/>
	<p>
		Refsing gives Shizunai <i lang="ain-Latn">akus</i> a more specific description involving
		something new or unexpected. Her examples include a bear suddenly appearing while two women are
		walking and talking
		<Ref k="refsing1986" p="248, examples 433–434" />. Her Shizunai account is more specific than
		Nakagawa’s description of a related subsequent development.
	</p>
</S>

<S t="Regional and genre preferences" id="variation">
	<p>
		Nakagawa notes that initial <i>h</i> in <i lang="ain-Latn">hine</i> is often absent in
		ordinary-speed speech, and that Ishikari texts may write
		<i lang="ain-Latn">ine</i>. For Tokachi he records
		<i lang="ain-Latn">hinne</i>, as well as <i lang="ain-Latn">hine</i>
		outside Honbetsu. His report that Honbetsu does not use
		<i lang="ain-Latn">hine/ine</i> follows Masashi Tamura's description
		<Ref k="nakagawa2024" p="338, after M. Tamura 2011:220–221" />.
	</p>
	<p>
		<i lang="ain-Latn">Awa</i> has uses close to those of
		<i lang="ain-Latn">akusu</i>. Nakagawa reports a preference for
		<i lang="ain-Latn">awa</i> in Saru verse, in Horobetsu, and in Ishikari;
		<i lang="ain-Latn">akusu</i> is more frequent in his account of Shizunai and Tokachi. His Saru
		examples contrast a verse occurrence of
		<i lang="ain-Latn">awa</i> with a comparable prose use of
		<i lang="ain-Latn">akusu</i>
		<Ref k="nakagawa2024" p="345, examples 631–633" />. These are tendencies in the descriptions,
		rather than mutually exclusive regional inventories.
	</p>
</S>

<S t="Participant changes and narrative boundaries" id="narrative">
