		The meanings above do not amount to a grammatical opposition in which
		<i lang="ain-Latn">hine</i> marks the same subject and
		<i lang="ain-Latn">akusu</i> a different subject. The cup example already shows a subject change
		with <i lang="ain-Latn">hine</i>. Event relations and participant identity need to be
		interpreted separately.
	</p>
