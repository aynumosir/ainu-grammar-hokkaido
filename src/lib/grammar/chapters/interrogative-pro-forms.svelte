<S t="Question words belong to several classes" id="word-classes">
	<p>
		Ainu question words include nouns, adverbs, and adnominal modifiers. Nakagawa's Saru
		classification distinguishes their syntax as follows
		<Ref k="nakagawa2024" p="411, table 77" />:
	</p>
	<table>
		<thead><tr><th>Function</th><th>Saru form</th><th>Class in this account</th></tr></thead>
		<tbody>
			<tr><td>What</td><td lang="ain-Latn">hemanta, hnta, hinta</td><td>Noun</td></tr>
			<tr><td>Who</td><td lang="ain-Latn">hunna</td><td>Noun</td></tr>
			<tr
				><td>Where</td><td lang="ain-Latn">hunak, hinak</td><td
					>Noun, usable as a place expression</td
				></tr
			>
			<tr><td>How</td><td lang="ain-Latn">makanak, mak</td><td>Adverb</td></tr>
			<tr><td>When</td><td lang="ain-Latn">hempara</td><td>Adverb</td></tr>
			<tr><td>How many</td><td lang="ain-Latn">hempak</td><td>Adnominal</td></tr>
			<tr><td>Which</td><td lang="ain-Latn">inan, hinaan</td><td>Adnominal</td></tr>
		</tbody>
	</table>
	<p>
		The label “question word” thus groups expressions by function. It does not assign them all the
		same part of speech or the same range of positions in a sentence. Refsing's Shizunai account
		likewise relates interrogative forms to nominal, place, and manner expressions
		<Ref k="refsing1986" p="108–110, §12.3.6" />.
	</p>
</S>

<S t="What and who questions" id="what-who">
	<p>
		For Saru “What is it?”, Nakagawa gives
		<i lang="ain-Latn">hemanta an?</i>, with existential
		<i lang="ain-Latn">an</i>, as the ordinary construction. Full
		<i lang="ain-Latn">hemanta ne</i> instead ordinarily belongs to “why” expressions in this
		account. The contracted
		<i lang="ain-Latn">hnta</i> permits both
		<i lang="ain-Latn">hnta an?</i> and <i lang="ain-Latn">hnta ne?</i>
		for “What is it?” <Ref k="nakagawa2024" p="412" />.
	</p>
	<p>
		The unusual spelling <i lang="ain-Latn">hnta</i> represents a syllabic
		<i lang="ain-Latn">n</i> in Nakagawa's phonetic description. It is a documented contraction,
		distinct from the uncontracted noun use of
		<i lang="ain-Latn">hemanta</i> for a strange being or monster. His narrative example uses that
		noun for an already-known creature
		<Ref k="nakagawa2024" p="412, examples 859–860" />.
	</p>
	<p>
		Saru “Who?” similarly commonly uses <i lang="ain-Latn">hunna an?</i>. Other copular frames are
		documented, including this Chitose question:
	</p>
	<Ex
		m="hunna e=ne ruwe an"
		g="who 2SG.A=COP EVID exist.SG"
		tr="Who are you?"
		cite="nakagawa2024:417, example 885"
		dial="CHI"
	/>
	<p>
		The normal Saru question frame therefore does not establish a general ban on copular predicates
		containing a question word
		<Ref k="nakagawa2024" p="413, 417" />.
	</p>
</S>

<S t="Why and how" id="why-how">
	<p>
		Saru has <i lang="ain-Latn">hemanta kusu</i>,
		<i lang="ain-Latn">hemanta ne</i>, and
		<i lang="ain-Latn">hemanta ne kusu</i> for “why,” with contracted
		<i lang="ain-Latn">hnta</i> variants. Nakagawa explicitly leaves the semantic difference among
		the three constructions unclear
		<Ref k="nakagawa2024" p="412–413" />.
	</p>
	<Ex
		m="hemanta kusu e=tura wa e=ek ruwe ene an"
		g="what for 2SG.A=accompany CONJ 2SG.S=come.SG EVID thus exist.SG"
		tr="Why did you bring that along?"
		cite="nakagawa2024:413, example 861"
		dial="SAR"
		note="The object translated ‘that’ is supplied by the context and is not separately expressed."
	/>
	<p>
		<i lang="ain-Latn">Makanak</i> and Saru <i lang="ain-Latn">mak</i>
		ask about manner. Nakagawa also uses <i lang="ain-Latn">mak e=iki</i>
		when asking what someone is visibly doing: the Ainu construction asks how the person acts, where an
		English translation may use “what”
		<Ref k="nakagawa2024" p="414, examples 870–872" />.
	</p>
</S>

<S t="Place, quantity, and choice" id="place-quantity-choice">
	<p>
		<i lang="ain-Latn">Hunak</i> combines directly with place particles:
		<i lang="ain-Latn">hunak ta</i> “where,”
		<i lang="ain-Latn">hunak un</i> “where to,” and
		<i lang="ain-Latn">hunak wa</i> “where from.” For “of which place,” Saru and Chitose use
		<i lang="ain-Latn">ney un</i>. Nakagawa distinguishes the latter's verb
		<i lang="ain-Latn">un</i>
		“belong to” from the directional particle
		<Ref k="nakagawa2024" p="413–414, 417–418" />.
	</p>
	<p>
		Adnominal <i lang="ain-Latn">hempak</i> normally precedes a noun, as in questions about a number
		of days. Related nominal forms include
		<i lang="ain-Latn">hempakpe</i> “how many things” and
		<i lang="ain-Latn">hempakiw</i> “how many people.”
		<i lang="ain-Latn">Inan</i> and <i lang="ain-Latn">hinaan</i>
		select among alternatives <Ref k="nakagawa2024" p="414–415" />. Counting expressions are
		described in
		<Xr ch="numeral-classifiers-ordinals-and-quantifier-syntax" />.
	</p>
</S>

<S t="Dialect differences" id="regional-paradigms">
	<p>
		For “what” and “who,” Saru, Chitose, and Mukawa use the
		<i lang="ain-Latn">h</i>-initial forms in Nakagawa's comparison. Many other Hokkaido varieties
		use <i lang="ain-Latn">nep</i> and
		<i lang="ain-Latn">nen</i>. Other interrogatives cut across this division
		<Ref k="nakagawa2024" p="415–419, table 78" />:
	</p>
	<table>
		<thead><tr><th>Function</th><th>Selected regional forms</th></tr></thead>
		<tbody>
			<tr
				><td>How</td><td
					>Horobetsu <span lang="ain-Latn">nekona / nekon</span>; Shizunai, Tokachi, Bihoro, and
					Ishikari <span lang="ain-Latn">nekon</span>.</td
				></tr
			>
			<tr
				><td>Where to / from</td><td
					>Shizunai and Tokachi <span lang="ain-Latn">enon / onon</span>; Bihoro
					<span lang="ain-Latn">nene / ney wa</span>; Asahikawa
					<span lang="ain-Latn">ney ne / ney wa</span>.</td
				></tr
			>
			<tr
				><td>When</td><td
					>Tokachi and Bihoro <span lang="ain-Latn">nempara</span>; the other varieties in the table
					have <span lang="ain-Latn">hempara</span>.</td
				></tr
			>
			<tr
				><td>How many</td><td
					>Tokachi and Bihoro <span lang="ain-Latn">nempak</span>, also reported for Kushiro; other
					listed varieties <span lang="ain-Latn">hempak</span>.</td
				></tr
			>
			<tr
				><td>Which</td><td
					>Upper Saru commonly <span lang="ain-Latn">hinaan</span>; Nibutani and downstream Saru
					<span lang="ain-Latn">inan</span>; Shizunai and several eastern varieties
					<span lang="ain-Latn">inkian</span>.</td
				></tr
			>
		</tbody>
	</table>
	<p>
		Nakagawa reports Asahikawa <i lang="ain-Latn">nean</i> “which” from the dialect dictionary but
		says that he has not seen an actual example
		<Ref k="nakagawa2024" p="419" />. The broader Ishikari heading in the table includes this more
		specific locality.
	</p>
</S>

<S t="Interrogative and indefinite uses" id="indefinites">
	<p>
		In Saru and Chitose, the usual question forms for “what,” “who,” and “where” contrast with
		indefinite <i lang="ain-Latn">nep</i>,
		<i lang="ain-Latn">nen</i>, and <i lang="ain-Latn">ney</i>. The distinction does not extend
		uniformly to every semantic category, and
		<i lang="ain-Latn">h</i>-initial forms can sometimes be indefinite too
		<Ref k="nakagawa2024" p="419–421, table 79" />.
	</p>
	<Ex
		m="nep ka a=kar ka etoranne"
		g="what FOC 4.A=do FOC be.bothersome"
		tr="Everything I do feels like a bother."
		cite="nakagawa2024:420, example 901"
		dial="SAR"
	/>
	<p>
		Indefinites frequently occur with <i lang="ain-Latn">ka(y)</i>,
		<i lang="ain-Latn">hene</i>, or <i lang="ain-Latn">ne yakka</i>. Their interpretation depends on
		the construction: Nakagawa's Chitose
		<i lang="ain-Latn">hempara ka</i> means “sometime,” while
		<i lang="ain-Latn">ney ta hene</i> in another example means “always”
		<Ref k="nakagawa2024" p="420–421" />. A particle alone does not determine a single translation
		for every indefinite expression.
	</p>
	<p>
		Horobetsu has both <i lang="ain-Latn">nep</i> and
		<i lang="ain-Latn">hemanta</i> among its indefinite forms for “what”
		<Ref k="nakagawa2024" p="420" />.
	</p>
</S>

<S t="Embedded questions and proposed histories" id="embedding-history">
	<p>
		Question words also occur in embedded questions. Nakagawa quotes Kirikae's Tokachi sentence <i
			lang="ain-Latn">a=kor konnarpe ney ta hokke ru ne ya a=korampetek</i
		>, “I did not know where my aunt was lying”
		<Ref k="nakagawa2024" p="417, example 888, reporting Kirikae 1996: 146" />. Its clause ending
		shows that an embedded question need not use
		<i lang="ain-Latn">p/pe</i> nominalization.
	</p>
	<p>
		Several historical connections have been proposed. Nakagawa suggests
		<i lang="ain-Latn">ney</i> derives from <i lang="ain-Latn">ne</i>
		plus <i lang="ain-Latn">hi</i>, and that analogy helped produce
		<i lang="ain-Latn">nempara</i>. His discussion of
		<i lang="ain-Latn">enon/onon</i> leaves part of their structure unexplained <Ref
			k="nakagawa2024"
			p="417–419"
		/> ‹speculative›. Refsing raises possible relations among anaphoric, interrogative, and copular
		<i lang="ain-Latn">ne</i>
		<Ref k="refsing1986" p="110" />
		‹speculative›. These proposals are separate from the documented regional forms.
	</p>
</S>
