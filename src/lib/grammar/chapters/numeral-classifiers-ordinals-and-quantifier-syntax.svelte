<S t="Numerals before and after a noun" id="numeral-position">
	<p>
		The usual adnominal construction places a numeral stem before the noun:
		<i lang="ain-Latn">sine tuki</i> “one cup.” A numeral noun can follow the counted noun:
		<i lang="ain-Latn">tuki sinep</i>. Nakagawa rejects
		<i lang="ain-Latn">*sinep tuki</i> in the corresponding construction
		<Ref k="nakagawa2024" p="462, 465" />. The forms of both series appear in <Xr
			ch="vigesimal-numeral-system"
		/>.
	</p>
	<p>
		The distribution has qualifications. Refsing's Shizunai data allow a human-series numeral before
		a human noun, as in the following example. Her restriction against prenominal numeral nouns
		applies to the general
		<i lang="ain-Latn">-p/-pe</i> series
		<Ref k="refsing1986" p="115–116" />.
	</p>
	<Ex
		m="tun katkemat ukoitak kane apkas"
		g="two.people woman converse CONJ walk"
		tr="Two women walked while chatting…"
		cite="refsing1986:115, example 99"
		dial="SHI"
		note="Continuous opening excerpt; initial capitalization is normalized."
	/>
	<p>
		Satō also records the fixed Chitose expression
		<i lang="ain-Latn">tup sumawe rep sumawe</i>, in which numeral nouns precede the noun for a bear
		carcass in a published exception to the usual adnominal pattern <Ref k="sato2008" p="257" />.
	</p>
	<p>
		A numeral and its noun need not be immediately adjacent in every variety. Refsing gives the
		Shizunai sequence
		<i lang="ain-Latn">mat ne po keray asiknen</i>, with the restrictive particle
		<i lang="ain-Latn">keray</i>
		between the expression for female children and “five people”
		<Ref k="refsing1986" p="116, example 101" />. Satō reports no intervening modifier in the
		Chitose data considered in his account
		<Ref k="sato2008" p="256–257" />. The Shizunai example establishes particle intervention; it
		does not by itself establish movement of a numeral across a verb.
	</p>
</S>

<S t="Numeral nouns as independent expressions" id="independent-numerals">
	<p>
		A numeral noun can stand without an accompanying lexical noun when the counted referents are
		understood. Refsing gives
		<i lang="ain-Latn">sinen askay</i>, “one person is capable,” with “one person” as the argument
		of the predicate
		<Ref k="refsing1986" p="116, example 103" />. Nakagawa's general series likewise supplies an
		independent object in a negative expression meaning that none were cut or killed
		<Ref k="nakagawa2024" p="464, example 1072" />.
	</p>
	<p>
		A numeral noun with translative <i lang="ain-Latn">ne</i> can specify composition or division.
		In the following imperative,
		<i lang="ain-Latn">tup ne</i> gives the resulting number of portions.
	</p>
	<Ex
		m="tup ne ukosaraye yan"
		g="two.things TRANSL divide.and.share IMP.PL"
		tr="Divide it in two and share it."
		cite="refsing1986:117, example 104"
		dial="SHI"
		note="Continuous final excerpt; the preceding words instruct the hearers not to fight."
	/>
	<p>
		Translative <i lang="ain-Latn">ne</i> also occurs with human counts. It differs from the
		person-marked verb <i lang="ain-Latn">ne</i>
		in such forms as <i lang="ain-Latn">ren a=ne wa oka=an</i>, “the three of us lived there” <Ref
			k="nakagawa2024"
			p="300–301"
		/>. See <Xr ch="postpositions-local-case-and-motion-events" /> for the grammatical distinction.
	</p>
</S>

<S t="Compound counts with a lexical noun" id="compound-counts">
	<p>
		A higher numeral may repeat the counted noun in each component. Nakagawa gives <i
			lang="ain-Latn">sine seta ikasma wan seta e tu hotne seta</i
		>
		for thirty-one dogs. He also reports Tamura's alternative with the noun first,
		<i lang="ain-Latn">seta, sinep ikasma wanpe e tu hotnep</i>
		<Ref k="nakagawa2024" p="466" />.
	</p>
	<p>
		A further pattern combines an initial numeral noun with an adnominal final component: <i
			lang="ain-Latn">sinen ikasma wan poyson</i
		>, “eleven children,” reported from Tamura in the same discussion
		<Ref k="nakagawa2024" p="466" />. These constructions show how the internal arithmetic and the
		syntax of the counted noun interact.
	</p>
</S>

<S t="Counters and the classifier analysis" id="classifiers">
	<p>
		The nominal endings <i lang="ain-Latn">-p/-pe</i> and
		<i lang="ain-Latn">-n/-iw</i> distinguish general and human counts. Refsing calls this a
		rudimentary system of classifiers or counters
		<Ref k="refsing1986" p="111" />. Nakagawa emphasizes the direct combination of a numeral stem
		with a noun and rejects a Japanese-style counter analysis <Ref k="nakagawa2024" p="462, 465" />.
		Alonso de la Fuente discusses the suffixes alongside free counting nouns such as
		<i lang="ain-Latn">to</i>
		“day” and
		<i lang="ain-Latn">suy</i> “time, occasion” under the question of classifiers <Ref
			k="alonso2022"
			p="§3.2"
		/> ‹contested›.
	</p>
	<p>
		The human series is available for people, while the general series can count people as well as
		other referents. Nakagawa illustrates both respectful and disparaging contexts without assigning
		that contrast to the choice of suffix
		<Ref k="nakagawa2024" p="464, examples 1070–1071" />.
	</p>
</S>

<S t="Days, repetitions, and conventional quantities" id="days-and-repetitions">
	<p>
		Day counts include <i lang="ain-Latn">tutko</i> “two days” and
		<i lang="ain-Latn">rerko</i> “three days,” followed by such forms as
		<i lang="ain-Latn">ine rerko</i>
		“four days” and
		<i lang="ain-Latn">asikne rerko</i> “five days.” Nakagawa reports no instances of this pattern
		above six in his material; he generally interprets
		<i lang="ain-Latn">iwan rerko</i> as a long time
		<Ref k="nakagawa2024" p="465" />.
	</p>
	<p>
		Repetition expressions include <i lang="ain-Latn">arsuy</i> “once,”
		<i lang="ain-Latn">tusuy</i> “twice,” and
		<i lang="ain-Latn">resuy</i> “three times.” Refsing describes
		<i lang="ain-Latn">o-</i> in <i lang="ain-Latn">otusuy</i>
		and <i lang="ain-Latn">oresuy</i> as reinforcement
		<Ref k="refsing1986" p="113–114" />.
	</p>
	<p>
		Numerals also have conventional approximate readings. In poetic parallelism, “two” and “three”
		can evoke a large quantity, whereas
		<i lang="ain-Latn">tutko rerko</i> suggests a short span of two or three days.
		<i lang="ain-Latn">Iwan</i>
		can mean literal six or, in context, many <Ref k="nakagawa2024" p="468–469" />.
	</p>
	<Ex
		m="iwan suy a=i=hotuyekar hine"
		g="many time 4.A=4.O=call CONJ"
		tr="I was called repeatedly, and…"
		cite="nakagawa2024:469, example 1080"
		dial="SAR"
		note="Opening clause. The agent is impersonal a=; i= refers to the narrator. The following clause describes the narrator being chased and caught."
	/>
</S>

<S t="Ordinal expressions" id="ordinals">
	<p>
		Kindaichi and Chiri explicitly list ordinal expressions. Their historical paradigm gives <i
			lang="ain-Latn">hoshki</i
		>
		“first,”
		<i lang="ain-Latn">tu-otutanu</i> “second,”
		<i lang="ain-Latn">re-otutanu</i> “third,” and
		<i lang="ain-Latn">ine-otutanu</i> “fourth”
		<Ref k="kindaichi1936" p="64, §97" />. The spelling
		<i lang="ain-Latn">hoshki</i> is retained from that source.
	</p>
	<p>
		Tamura's Saru dictionary records <i lang="ain-Latn">hoski</i>
		with the meaning “first/before” and <i lang="ain-Latn">otutanu</i>
		“next,” including <i lang="ain-Latn">otutanu kur</i>, “the next person” <Ref
			k="tamura1996"
			p="entries hoski and otutanu"
		/>. The historical numbered series and these lexical uses establish expressions for order; their
		distribution need not match that of cardinal numerals.
	</p>
</S>

<S t="Numerals and number marking" id="number-marking">
	<p>
		An explicit count does not determine one uniform choice of nominal or verbal number. Refsing
		records <i lang="ain-Latn">tu hekattar</i>, “two children,” with a plural noun. Her examples
		also include singular
		<i lang="ain-Latn">rikin</i> with two horses and plural
		<i lang="ain-Latn">arki</i> with two small boys
		<Ref k="refsing1986" p="117–118, examples 107–110" />.
	</p>
	<p>
		Kindaichi and Chiri had stated a rule favoring singular forms with numerals; Refsing explicitly
		disputes its absolute form
		<Ref k="kindaichi1936" p="65, §100" />;
		<Ref k="refsing1986" p="117–118" /> ‹contested›. Nominal plurals and verbal number have their own
		distributions, discussed in
		<Xr ch="nominal-number-utar-transnumerality" /> and
		<Xr ch="suppletive-verbal-number" />.
	</p>
</S>

<S t="Other quantity expressions" id="quantity-expressions">
	<p>
		Quantity is also expressed by words outside the numeral paradigm. Refsing groups <i
			lang="ain-Latn">poronno</i
		>, <i lang="ain-Latn">ponno</i>,
		<i lang="ain-Latn">opitta</i>, and <i lang="ain-Latn">inne</i>
		as quantity nouns, with adnominal use restricted to the first two in her account
		<Ref k="refsing1986" p="118, §12.4.7" />. Nakagawa classifies
		<i lang="ain-Latn">opitta</i> “all” as a postposed adverb and notes its exceptional A-series
		person marking
		<Ref k="nakagawa2024" p="280–281" />. The classifications reflect different analyses of the
		words' grammatical behavior ‹contested›.
	</p>
</S>
