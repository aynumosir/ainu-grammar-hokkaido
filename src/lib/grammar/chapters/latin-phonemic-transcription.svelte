<S t="What the Latin spelling represents" id="phonemic-principle">
	<p>
		The Latin transcription identifies the sound distinctions used in a word. It leaves much
		phonetic variation unmarked. For example, a speaker's voiced pronunciation of the middle
		consonant in <i lang="ain-Latn">hapo</i> “mother” does not require a different spelling: Ainu
		has no corresponding distinction between words with /p/ and /b/
		<Ref k="nakagawa2024" p="25–26" />.
	</p>
	<p>
		This principle underlies the phonemic transcriptions used in modern descriptive work, though
		authors differ over glottal stops, transitional glides, and morpheme boundaries
		<Ref k="nakagawa2024" p="57–61" />. A form cited from another author must therefore be read with
		that author's conventions in mind. The present chapter explains the ordinary letter values;
		pronunciation is treated in <Xr ch="consonant-inventory" /> and
		<Xr ch="vowel-inventory" />.
	</p>
</S>

