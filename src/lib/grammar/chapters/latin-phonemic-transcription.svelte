<S t="The letters c and s" id="c-and-s">
	<p>
		The letter <em>c</em> represents the affricate heard in
		<i lang="ain-Latn">cikap</i> “bird.” Older <i lang="ain-Latn">chikap</i> uses two letters for
		the same consonant. Similarly, older <i lang="ain-Latn">shik</i> corresponds to
		<i lang="ain-Latn">sik</i> “eye” in phonemic transcription
		<Ref k="nakagawa2024" p="55" />. These spelling correspondences do not establish a pronunciation
		change between the two texts.
	</p>
	<p>
		The pronunciation of /s/ is palatalized before /i/. In syllable-final position, Nakagawa also
		describes a difference according to the preceding vowel, with a strongly palatal realization
		after /i/ <Ref k="nakagawa2024" p="28–29" />. The letter remains <em>s</em>. A phonetic
		transcription can show these details when they matter to the discussion.
	</p>
</S>

<S t="Vowel-initial spelling and the glottal stop" id="glottal-stop-notation">
	<p>
		A form beginning with a vowel letter may be pronounced with a glottal closure. Authors differ in
		whether they count this as a consonant phoneme and whether they write it. Nakagawa omits it from
		the phonemic inventory; Tamura's later practice can omit the sign while retaining the phoneme in
		the analysis. Hattori's dialect dictionary regularly writes an apostrophe <Ref
			k="nakagawa2024"
			p="57"
		/>. The analyses are discussed in
		<Xr ch="glottal-stop" /> ‹contested›.
	</p>
	<p>
		Ordinary forms here omit the apostrophe. When an older transcription includes one, it should be
		interpreted from the source's account of syllable structure. Sakhalin word-final
		<em>h</em> is a separate matter: it belongs to the transcription of Sakhalin consonants and supplies
		no basis for adding a final laryngeal consonant to Hokkaido words.
	</p>
</S>

<S t="Accent marks" id="accent-diacritics">
	<p>
		An acute accent marks the accented vowel where pitch is relevant. Nakagawa illustrates an accent
		distinction with <i lang="ain-Latn">nísap</i> “suddenly” and
		<i lang="ain-Latn">nisáp</i> “shin” <Ref k="nakagawa2024" p="27" />. Forms without an acute
		accent leave the accent unspecified; the absence of a mark does not classify the word or dialect
		as accentless.
	</p>
	<p>
		Accent evidence requires a stated dialect and source. Its distribution, placement, and
		interaction with person marking are treated in <Xr ch="pitch-accent-placement-rule" />.
		Diacritics on a source form are retained when that distinction is the subject of the example.
	</p>
</S>

<S t="Showing the parts of a word" id="boundary-markers">
	<p>
		In an analyzed form, <code>=</code> separates a person marker and <code>-</code> separates other
		morphemes. Thus <i lang="ain-Latn">ku=itak</i> “I speak” displays the person prefix and the stem
		even where their combination is pronounced with a glide. Nakagawa contrasts this spelling with
		<i lang="ain-Latn">kuytak</i>, which makes the surface syllables easier to read <Ref
			k="nakagawa2024"
			p="59–61"
		/>.
	</p>
	<p>
		The segmentation is part of the grammatical analysis. It does not instruct the reader to pause
		at a boundary. The glossing conventions and the special use of the equals sign are explained in <Xr
			ch="glossing-abbreviations-and-citation"
		/>.
	</p>
</S>

<S t="Capitals and punctuation" id="capitalization">
	<p>
		Capitalization in a source may carry information beyond sentence beginnings and names. Nakagawa,
		for example, uses capitals for the refrain in divine songs and for Japanese words within
		Latin-transcribed text <Ref k="nakagawa2024" p="18" />. These functions should be checked before
		capitalization is normalized in a quotation.
	</p>
	<p>
		Punctuation and line breaks help an editor present a spoken text. They can guide a reading, but
		a comma alone does not establish a clause boundary or an audible pause. Examples that discuss
		delivery require the recording or an explicit transcription of that feature.
	</p>
</S>

<S t="Glides between vowels" id="glide-notation">
	<p>
		Some differences between familiar spellings concern transitional glides. Nakagawa writes
		<i lang="ain-Latn">uepeker</i> “prose tale” and <i lang="ain-Latn">siamam</i> “rice”; Hattori's
		dictionary writes the corresponding sequences with <em>w</em> and <em>y</em>:
		<i lang="ain-Latn">uwepeker</i> and <i lang="ain-Latn">siyamam</i>
		<Ref k="nakagawa2024" p="58" />. The spellings reflect different treatments of the transition
		between vowels.
	</p>
	<p>
		These differences must be distinguished from lexical /w/ and /y/. Deleting every glide between
		vowel letters would change forms without establishing that the glide is predictable. The
		relevant phonological analyses are set out in <Xr ch="glides-w-y" />.
	</p>
</S>

<S t="Comparing transcriptions" id="other-romanizations">
	<p>
		Latin letters in an Ainu spelling are read according to its transcription system. They do not
		all have their IPA values: <em>c</em> and <em>y</em> are especially important cases. Older
		<em>ch</em>
		and <em>sh</em>, the treatment of final glides, and letters for voiced stops are explained in <Xr
			ch="historical-orthographies-and-the-batchelor-tradition"
		/>.
	</p>
	<p>
		For a comparison between editions, establish the dialect and transcription conventions before
		interpreting different spellings as different forms. A change of script, a different morpheme
		division, and an actual pronunciation difference can all produce superficially different written
		words. <Xr ch="cyrillic-and-multiscript-rendering" /> explains how source spellings and normalized
		analyses can be read together.
	</p>
</S>
