<S t="The possessor as subject: kor" id="kor">
	<p>
		Possession can be predicated with transitive <i lang="ain-Latn">kor</i> ‘have’. The possessor is
		its subject and the possessed entity its object. Its meanings include family relationships and
		affiliation, so an English translation with ‘own’ is often too narrow. Chudá discusses these
		uses under the label HAVE construction
		<Ref k="huber2025" p="250–253" />.
	</p>
	<Ex
		m="kamuy e=unu-hu tu matnepo kor"
		g="deity 2SG.POSS=mother-POSS two daughter have"
		tr="Your divine mother has two daughters."
		cite="huber2025:253"
		place="Example 21, citing Nakagawa et al., K8303243UP.123"
		note="The person prefix belongs to ‘mother’. The subject of kor is the whole phrase ‘your divine mother’, with zero third-person marking on the verb."
	/>
	<p>
		The same verb occurs inside noun phrases such as <i lang="ain-Latn">cise kor kur</i>
		‘master of the house’ and <i lang="ain-Latn">nupuri kor kamuy</i> ‘deity of the mountain’
		<Ref k="huber2025" p="250, example 12" />. There the following noun is characterized through its
		relationship with the preceding entity. See <Xr ch="adnominal-possession-double-marking" />
		for the structure of possessive noun phrases.
	</p>
</S>

<S t="The possessed entity as subject: an" id="existential">
	<p>
		An existential construction presents the possessed entity as present. Its possessor can be
		expressed inside an affiliative noun, while the existential predicates the existence of that
		noun's referent. Chudá calls this the BE construction
		<Ref k="huber2025" p="252–253" />.
	</p>
	<Ex
		m="iwan a=yup-i an iwan a=sa-ha an"
		g="six 4.POSS=elder.brother-POSS exist.SG six 4.POSS=elder.sister-POSS exist.SG"
		tr="I have six elder brothers and six elder sisters…"
		cite="huber2025:252"
		place="Example 16, citing Nakagawa et al., K7908032UP.001"
		note="The narrator is expressed as possessor on the kinship nouns. The published existential is an in both clauses, despite the numeral ‘six’."
	/>
	<p>
		The possessive prefix does not index the subject of <i lang="ain-Latn">an</i>. The relatives
		themselves are its third-person subjects. This difference explains why a first-person English
		translation need not have a first-person marker on the existential.
	</p>
	<Ex
		m="a=po-ho ka an"
		g="4.POSS=child-POSS ADD exist.SG"
		tr="I even have a son."
		cite="huber2025:253"
		place="Example 19, citing Nakagawa et al., K7803233UP.127"
		note="The English ‘son’ follows the passage's interpretation; the noun po itself is glossed ‘child’."
	/>
	<p>
		Existence and living together can overlap in context. Chudá's
		<i lang="ain-Latn">a=sa-ha an hine oka=an</i> is translated ‘I lived with my elder sister’: the
		sister exists or lives there, and the narrator and sister live together
		<Ref k="huber2025" p="252, example 17 and note 6" />.
	</p>
</S>

<S t="Lexical range and corpus observations" id="distribution">
	<p>
		Chudá reports that HAVE constructions make up more than 80% of the predicative possession in her
		corpus analysis <Ref k="huber2025" p="250" />. She associates existential possession with
		kinship and body-part nouns, and reports no alienable-noun examples in the oral-literature data
		discussed <Ref k="huber2025" p="252–253" />. These are the distributional findings of that
		study.
	</p>
	<p>
		Refsing's description allows existential possession beyond inalienable nouns
		<Ref k="refsing1986" p="161" />. The sources therefore give different accounts of its range. A
		universal restriction to kinship and body parts would obscure this difference. For the separate
		lexical restrictions on affiliative noun forms, see
		<Xr ch="alienable-inalienable-split" />.
	</p>
</S>

<S t="Incorporation, change, and lack" id="related">
	<p>
		A noun can also form an incorporated stem with <i lang="ain-Latn">kor</i>. Chudá contrasts
		intransitive <i lang="ain-Latn">pokor</i> with the two-word
		<i lang="ain-Latn">po kor</i>, and notes the frequent change-of-state meaning ‘have a child,
		give birth’ in the incorporated form. Related lexical formations include
		<i lang="ain-Latn">matkor</i> ‘marry’ and <i lang="ain-Latn">honkor</i> ‘become pregnant’
		<Ref k="huber2025" p="251" />. Their conventional meanings go beyond a general statement of
		possession.
	</p>
	<p>
		Negative possession can be expressed with <i lang="ain-Latn">sak</i> ‘lack’; negative existence
		uses <i lang="ain-Latn">isam</i>
		<Ref k="bugaeva2012" p="496" />. Nakagawa's Saru example describes a wealthy man's wife as
		lacking even a necklace with
		<i lang="ain-Latn">tamasay ka sak</i>
		<Ref k="nakagawa2024" p="323, example 533" />. These lexical predicates have their own argument
		structures. The choice between them follows what is being predicated of which participant.
	</p>
</S>
