<S t="Person and naming in prayer" id="prayer">
	<p>
		Prayer can combine ordinary first-person reference with special address expressions. Endō's
		example from Motozō Nabesawa, also named Motoanrek, contains <i lang="ain-Latn">ku=</i> and
		addresses the fire deity as the grandmother who rules the land
		<Ref k="endo2022" p="§2.3, example 13" />.
	</p>
	<Ex
		m="mosir kor huci"
		g="land have grandmother"
		tr="Grandmother who rules the land!"
		cite="endo2022:§2.3"
		dial="SAR"
		place="Opening of example 13; Monbetsu-chō Kyōdoshi Kenkyūkai 1966:106–107"
		note="An invocation from an ancestral memorial prayer, transmitted through Endō. Monbetsu here is the lower-Saru town now called Hidaka."
	/>
	<p>
		The same prayer calls the deity <i lang="ain-Latn">i-res-u kamuy</i>, ‘the nourishing deity’.
		Endō glosses <i lang="ain-Latn">i-</i> as antipassive in this expression; it leaves those
		nourished unspecified
		<Ref k="endo2022" p="§2.3, example 13" />. Special epithets coexist with ordinary names. The
		prayers edited by Kitahara include <i lang="ain-Latn">ape uci kamuy</i> and
		<i lang="ain-Latn">apehucikamuy</i>
		<Ref k="kitahara2013" p="237–239, prayers 1, 2, 4" />.
	</p>
	<p>
		Kitahara interprets <i lang="ain-Latn">a=</i> in
		<i lang="ain-Latn">a=keytumu kasi</i> as honorific second person in Sunazawa Tuakanno Ichitarō's
		prayers. He identifies comparable uses by that speaker within the edition, while noting that a
		similar form in another speaker's prayer permits several analyses
		<Ref k="kitahara2013" p="238, note 6" />.
	</p>
	<p>
		This edition concerns Kuramitsu's 1953 volume associated with the Monbetsu City bear ceremony
		and speakers of the Asahikawa and middle Ishikari area. Some prayers had been recorded
		separately beforehand. Kitahara reconstructs the romanization from the earlier kana text,
		marking uncertain readings <Ref k="kitahara2013" p="233–237" />.
	</p>
</S>

<S t="Prayer and incantation" id="ritual-genres">
	<p>
		Endō distinguishes prayers composed for the occasion from shorter incantations with established
		wording. Her account associates prayer and ceremonial negotiation with adult men, while
		incantations can be used by people of either sex and any age. The wording, melody, and
		participation conventions belong to the particular ritual genre
		<Ref k="endo2022" p="§2.3" />.
	</p>
	<p>
		Prayer endings also vary. Endō's example contains
		<i lang="ain-Latn">siri ne hi tapan na</i> and
		<i lang="ain-Latn">ne hi tapan na</i>. These combine familiar formal nouns and predicates with
		the longer phrasing of the prayer
		<Ref k="endo2022" p="§2.3, example 13" />. For the grammatical constructions, see
		<Xr ch="evidential-schema-overview" /> and
		<Xr ch="poetic-archaic-elevated-register" />.
	</p>
</S>

