<S t="Lexical formation and productive derivation" id="verb-formation">
	<p>
		Ainu verb stems include formations based on nouns, formations from bound roots, and derivations
		from independently usable verbs. These sources need to be distinguished: recognizing meaningful
		parts in an established word does not make every new combination available
		<Ref k="refsing1986" p="146–150" />;
		<Ref k="nakagawa2024" p="198–210" />.
	</p>
	<p>
		Refsing describes a set of lexicalized Shizunai verbs consisting of a nominal root and a verb
		formative. She explicitly regards these formatives as nonproductive in that account. Some also
		occur as independent verbs, while others have no independent use
		<Ref k="refsing1986" p="146, §13.6" />.
	</p>
</S>

