<S t="Transitivity pairs with different degrees of resemblance" id="transitivity-correspondences">
	<p>
		Satō separates rare identical intransitive and transitive forms from partly related pairs and
		pairs with no transparent formal connection. His Chitose examples include <i lang="ain-Latn"
			>inunpa / nunpa</i
		>
		“strain, filter” alongside <i lang="ain-Latn">ipe / e</i> “eat” and
		<i lang="ain-Latn">itak / ye</i>
		“speak/say”
		<Ref k="sato2008" p="97" />.
	</p>
	<p>
		Nakagawa also lists visibly related pairs such as
		<i lang="ain-Latn">inu / nu</i> and
		<i lang="ain-Latn">ikka / eikka</i>
		<Ref k="nakagawa2024" p="131, table 13" />. Formal resemblance can support a lexical comparison
		without establishing a freely productive prefix rule. The argument-frame differences remain
		essential when using these verbs in a clause.
	</p>
</S>

<S t="Different uses of kar" id="kar-formations">
	<p>
		Alongside the nominal-root formations above, Nakagawa describes
		<i lang="ain-Latn">-kar</i> added to an intransitive verb to introduce an object. His pairs
		include
		<i lang="ain-Latn">peray / peraykar</i> “fish / catch something by fishing” and
		<i lang="ain-Latn">cis / ciskar</i>
		“cry / cry for someone.” In <i lang="ain-Latn">imek / imekkar</i>, the added object is the
		recipient of food being carried
		<Ref k="nakagawa2024" p="208, examples 209–210" />.
	</p>
	<p>
		A same-shaped addition to an already transitive verb can leave argument count unchanged.
		Nakagawa compares <i lang="ain-Latn">kocari</i>
		with <i lang="ain-Latn">kocarikar</i>, and
		<i lang="ain-Latn">cioranke</i> with
		<i lang="ain-Latn">ciorankekar</i>. He connects this use especially with metrical requirements
		in verse
		<Ref k="nakagawa2024" p="208–209, examples 211–214" />. The valency effect therefore belongs to
		the particular construction.
	</p>
</S>

<S t="Intensive no and other derivations" id="intensive-and-voice">
	<p>
		Verbal intensive <i lang="ain-Latn">-no</i> strengthens a predicate's meaning while preserving
		its verbal use. Nakagawa gives
		<i lang="ain-Latn">retar-no</i>, realized as
		<i lang="ain-Latn">retanno</i> “be pure white,” and
		<i lang="ain-Latn">ipe-no</i> “eat well”
		<Ref k="nakagawa2024" p="209" />. These differ from the adverbial formations discussed in <Xr
			ch="adverbializer-no"
		/>.
	</p>
