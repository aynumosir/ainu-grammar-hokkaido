<S t="Inviting agreement" id="ro">
	<p>
		The final particle <i lang="ain-Latn">ro</i> commonly accompanies an invitation to act together.
		The predicate then uses the inclusive fourth-person series:
		<i lang="ain-Latn">=an</i> on an intransitive verb, or
		<i lang="ain-Latn">a=</i> on a transitive verb. These are uses of the ordinary person forms
		described in <Xr ch="person-marking-architecture" />
		<Ref k="nakagawa2024" p="333–334" />.
	</p>
	<Ex
		m="ney ta ka KURUMA ani mosir epitta payoka=an wa inkar=an ro"
		g="where LOC INDEF car INS land throughout go.about=4.S CONJ look=4.S HORT"
		tr="Let's try travelling all around the country by car sometime."
		cite="nakagawa2024:333"
		dial="SAR"
		place="Example 575, citing Honda 2001:19"
		note="The fourth-person forms include speaker and addressee. Wa inkar contributes the meaning ‘try’; KURUMA is the Japanese loan retained in the source."
	/>
	<p>
		Nakagawa describes <i lang="ain-Latn">ro</i> more broadly as seeking the interlocutor's
		agreement. It can accompany a proposed action by the speaker alone. His Saru exchange has
		<i lang="ain-Latn">k=arpa ro</i>
		‘shall I go?’ followed by permission to go <Ref
			k="nakagawa2024"
			p="334, example 578, citing Tamura 1988a:55"
		/>.
	</p>
	<Ex
		m="te ta ek eci=kay ro"
		g="here LOC come.SG 1SG.A>2SG.O=carry.on.back HORT"
		tr="Come here. Let me carry you on my back."
		cite="nakagawa2024:334"
		dial="CHI"
		place="Example 579"
		note="Eci= expresses a first-person singular actor acting on a second-person singular object in this example."
	/>
</S>

<S t="Regional forms" id="regional">
	<p>
		Nakagawa lists <i lang="ain-Latn">ro</i> for Horobetsu, Saru, Chitose, and Shizunai;
		<i lang="ain-Latn">rok</i>
		for Tokachi and Shiranuka; and
		<i lang="ain-Latn">no</i> for Urakawa and Samani. Both
		<i lang="ain-Latn">ro</i> and <i lang="ain-Latn">rok</i> are reported for Ishikari
		<Ref k="nakagawa2024" p="333–334" />.
	</p>
	<p>
		Refsing's Shizunai description gives <i lang="ain-Latn">na</i> in this function:
		<i lang="ain-Latn">uerpak ipe=an na</i>, ‘let us eat together’. She interprets it as an
		invitation that includes the speaker, sometimes with an admonitory implication <Ref
			k="refsing1986"
			p="204, §14.9.4.3, example 309"
		/>. The reports describe overlapping resources rather than a single exclusive map of regional
		endings.
	</p>
</S>

<S t="Deliberation and wishes" id="wishes">
	<p>
		Chitose <i lang="ain-Latn">so</i> occurs in self-directed deliberation. Nakagawa's
		<i lang="ain-Latn">ku=ye so</i>
		follows mention of telling a story: the speaker considers doing so <Ref
			k="nakagawa2024"
			p="334, example 580"
		/>. The interlocutor's agreement need not be the point of such an utterance.
	</p>
	<p>
		For a wish about a hypothetical situation, Nakagawa describes an expression with emphatic <i
			lang="ain-Latn">ta</i
		>
		and final <i lang="ain-Latn">oka</i>. The following example concerns taking a particular woman
		as a wife if she were a goddess <Ref k="nakagawa2024" p="336" />.
	</p>
	<Ex
		m="sekor an menoko ta kamuy menoko ne yak a=kor oka"
		g="QUOT exist.SG woman EMPH deity woman COP COND 4.A=have OPT"
		tr="If a woman like that were a goddess, I would make her my wife!"
		cite="nakagawa2024:336"
		dial="SAR"
		place="Example 593, citing Tamura 1985:28"
	/>
	<p>
		Desire expressed with <i lang="ain-Latn">rusuy</i> has its own person and word-structure
		questions; see <Xr ch="desiderative-rusuy" />. Direct commands and prohibitions are covered in <Xr
			ch="imperative-and-prohibitive"
		/>.
	</p>
</S>
