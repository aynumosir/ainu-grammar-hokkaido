<S t="Prohibitions with iteki" id="imperative">
	<p>
		<i lang="ain-Latn">Iteki</i> forms a prohibition with an imperative verb. The imperative has no
		subject person affix; an object index may still occur. This is the imperative construction
		described by Satō, alongside other directive constructions that retain subject marking
		<Ref k="sato2008" p="128–129, §§16.1–16.2" />.
	</p>
	<Ex
		m="iteki ape sam ta ek"
		g="PROH fire vicinity LOC come.SG"
		tr="Do not come near the fire."
		cite="nakagawa2024:424"
		dial="SAR"
		place="Example 924"
	/>
	<p>
		The locative phrase intervenes between <i lang="ain-Latn">iteki</i> and the verb. Nakagawa
		allows the prohibitive anywhere before the verb; Satō contrasts this freedom with the usual
		immediately preverbal position of
		<i lang="ain-Latn">somo</i>
		<Ref k="nakagawa2024" p="424" /><Ref k="sato2008" p="124" />.
	</p>
</S>

