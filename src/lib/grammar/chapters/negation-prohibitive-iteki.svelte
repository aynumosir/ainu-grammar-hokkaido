<S t="Addressees and advice" id="address">
	<p>
		In Satō's Chitose description, <i lang="ain-Latn">yan</i> accompanies a plural imperative and
		also permits polite address to one person. A verb with a number contrast uses its plural stem in
		this construction. The particle
		<i lang="ain-Latn">hani</i> adds an instructive or admonitory nuance: his illustration has an
		adult advising children who are going outside into the cold
		<Ref k="sato2008" p="128–129" />. These descriptions concern both the addressees and the
		circumstances of the utterance. See <Xr ch="imperative-and-prohibitive" /> for the affirmative imperative
		and object marking.
	</p>
</S>

<S t="Directives with person marking" id="indexed">
	<p>
		<i lang="ain-Latn">Iteki</i> also combines with person-marked predicates and endings such as
		<i lang="ain-Latn">p ne na</i>
		or
		<i lang="ain-Latn">kusu ne na</i>. A prohibition linked to a following directive by
		<i lang="ain-Latn">no</i>
		can likewise retain its person affix
		<Ref k="nakagawa2024" p="425, examples 929–936" />.
	</p>
	<Ex
		m="iteki e=esina no e=ye p ne na"
		g="PROH 2SG.A=hide CONJ 2SG.A=say NMLZ COP FIN"
		tr="Say it without hiding it."
		cite="nakagawa2024:425"
		dial="SAR"
		place="Example 935"
	/>
	<p>
		The construction as a whole directs the hearer to speak openly. Both predicates have an overt
		second-person index. Thus, the absence of subject marking characterizes the bare imperative,
		rather than every sentence used to prohibit an action.
	</p>
	<p>
		One Saru directive contains both <i lang="ain-Latn">iteki</i> and
		<i lang="ain-Latn">somo</i>:
		<i lang="ain-Latn">iteki pasirota somo eci=ki nankor na</i>, ‘You must certainly not punish
		[them].’ Nakagawa gives the sentence after Ōtani, without deriving its interpretation from two
		separate layers of negation <Ref k="nakagawa2024" p="425, example 932, after Ōtani 2002:124" />.
		The person affix here is on <i lang="ain-Latn">ki</i>.
	</p>
</S>

<S t="Other prohibitive expressions" id="warnings">
	<p>
		Nakagawa also lists <i lang="ain-Latn">ika</i>,
		<i lang="ain-Latn">iki(y)a</i>, and related forms with prohibitive meaning. These normally
		precede a verb with subject person marking
		<Ref k="nakagawa2024" p="425–426, examples 937–939" />. Satō gives Chitose
		<i lang="ain-Latn">ikiyan</i>
		in the same broad domain. He associates several person-marked directives with advice, while
		leaving the finer differences between the constructions unresolved
		<Ref k="sato2008" p="129, §16.2" />.
	</p>
</S>
