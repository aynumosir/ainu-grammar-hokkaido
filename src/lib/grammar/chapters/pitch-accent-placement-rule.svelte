<S t="The rising accent kernel" id="rising-nucleus">
	<p>
		In the accentual varieties of Hokkaido Ainu, the position of high pitch can distinguish words.
		Saru <i lang="ain-Latn">nísap</i> “suddenly” and
		<i lang="ain-Latn">nisáp</i> “shin” contain the same consonants and vowels, but have different
		accent positions. The acute mark identifies the accented syllable
		<Ref k="nakagawa2024" p="48–49" />. Many words have a predictable accent; others, including the
		first member of this pair, require their accent to be learned with the word.
	</p>
	<p>
		Nakagawa describes this as a <em>rising-kernel</em> system. The crucial property is where the
		pitch becomes high. Later syllables may remain high or fall without changing the word's
		identity. His example <i lang="ain-Latn">kamúynomi</i> “pray to the gods” requires low pitch on
		the first syllable and high pitch on the second; the pitch after that point is less constrained <Ref
			k="nakagawa2024"
			p="49"
		/>. The accent mark therefore does not prescribe the entire pitch contour of an utterance.
	</p>
</S>

<S t="Dialect differences" id="dialect-classes">
	<p>
		Accent is not contrastive throughout Ainu. Nakagawa and Fukazawa distinguish three broad
		patterns in Hokkaido <Ref k="nakagawafukazawa2022" p="§3.1" />:
	</p>
	<table>
		<thead
			><tr><th>Pattern</th><th>Distribution in their account</th><th>Main property</th></tr></thead
		>
		<tbody>
			<tr
				><td>Ordinary placement</td><td
					>Saru, Chitose, Horobetsu, Asahikawa, Nayoro, Obihiro, Sōya</td
				><td
					>The first syllable's structure usually determines accent on the first or second syllable.</td
				></tr
			>
			<tr
				><td>Later placement</td><td>Yakumo, Oshamambe</td><td
					>Accent may fall on the third syllable when the first two are open.</td
				></tr
			>
			<tr
				><td>No lexical accent contrast</td><td
					>Shizunai, Urakawa, Samani, Bihoro, Kushiro, Shiranuka</td
				><td>Pitch does not distinguish words in the same way.</td></tr
			>
		</tbody>
	</table>
	<p>
		The Shizunai classification differs from Refsing's description, which states the usual
		first-or-second-syllable rule <Ref k="refsing1986" p="§10.6, 73" />. Nakagawa examines seven
		recordings of “suddenly” from the same speaker and reports two initial-accent and five
		second-syllable-accent realizations. He takes the variation as evidence against a stable lexical
		contrast in that variety <Ref k="nakagawa2024" p="50" /> ‹contested›. These are Nakagawa's reported
		observations; they do not establish the distribution for every Shizunai speaker.
	</p>
</S>

<S t="The usual placement rule" id="placement-rule">
	<p>
		For varieties such as Saru, the default depends on whether the first syllable ends in a
		consonant. A closed first syllable usually bears the accent. After an open first syllable, the
		second syllable usually bears it <Ref k="sato2008" p="15" />;
		<Ref k="nakagawa2024" p="50" />; <Ref k="shibatani1990" p="§2.3" />.
	</p>
	<table>
		<thead><tr><th>First syllable</th><th>Usual accent</th><th>Examples</th></tr></thead>
		<tbody>
			<tr
				><td>Closed, (C)VC</td><td>First syllable</td><td
					><span lang="ain-Latn">áy.nu</span> “person”; <span lang="ain-Latn">pón.no</span> “a little”</td
				></tr
			>
			<tr
				><td>Open, (C)V</td><td>Second syllable</td><td
					><span lang="ain-Latn">ka.múy</span> “god”; <span lang="ain-Latn">i.tán.ki</span> “bowl”</td
				></tr
			>
		</tbody>
	</table>
	<p>
		The examples follow Nakagawa, with dots added to show syllable boundaries
		<Ref k="nakagawa2024" p="50" />. Final /y/ and /w/ count as consonants: the initial syllable of
		<i lang="ain-Latn">áynu</i>
		is closed. See <Xr ch="glides-w-y" />.
	</p>
	<p>
		Yakumo modifies the open-syllable rule. If the second syllable is also open, accent may fall on
		the third: <i lang="ain-Latn">sinuyé</i> “tattoo” corresponds to Saru
		<i lang="ain-Latn">sinúye</i>. A closed second syllable retains second-syllable accent. There
		are lexical exceptions to this pattern too <Ref k="nakagawa2024" p="50–51" />;
		<Ref k="nakagawafukazawa2022" p="§3.1" />.
	</p>
</S>

<S t="Accent within the pitch contour" id="contour">
	<p>
		The accent rule identifies a location of prominence within the word. It leaves room for
		variation in the later pitch contour and for effects of phrase structure. Nakagawa's account of
		a rising kernel and Shiraishi's account of high pitch thus address different aspects of the same
		pronunciation <Ref k="nakagawa2024" p="48–49" />;
		<Ref k="shiraishi2022" p="§5" />. A transcription with one acute mark records less detail than
		an acoustic pitch trace.
	</p>
	<p>
		Accent can also accompany slight vowel lengthening, especially in northeastern varieties
		<Ref k="shiraishi2022" p="§5" />. This phonetic effect does not establish a contrast between
		long and short vowel phonemes in Hokkaido Ainu. Utterance contours are treated in
		<Xr ch="phrasal-and-utterance-intonation" />.
	</p>
</S>

