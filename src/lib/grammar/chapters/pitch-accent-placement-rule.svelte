<S t="Comparison with Sakhalin vowel length" id="sa-correspondence">
	<p>
		<strong>Sakhalin comparison.</strong> A number of Hokkaido words with exceptional initial accent
		correspond to Sakhalin words with a long first vowel. Nakagawa gives Hokkaido
		<i lang="ain-Latn">mína</i> and Sakhalin <i lang="ain-Latn">miina</i> “laugh,” and
		<i lang="ain-Latn">húre</i> beside <i lang="ain-Latn">huure</i> “be red”
		<Ref k="nakagawa2024" p="51" />. The correspondence connects two different systems: lexical
		accent in the relevant Hokkaido varieties and vowel length in Sakhalin.
	</p>
	<p>
		Historical accounts of this relationship require evidence beyond the modern pairs. Nakagawa and
		Fukazawa report a proposal deriving the Hokkaido contrast from earlier vowel length, while
		pointing to an alternative historical account in Satō's Handbook chapter
		<Ref k="nakagawafukazawa2022" p="§3.1" /> ‹contested›.
	</p>
</S>
