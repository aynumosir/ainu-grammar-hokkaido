<S t="An absent entity" id="isam">
	<p>
		<i lang="ain-Latn">Isam</i> is an intransitive verb meaning ‘not exist’, ‘be absent’, or
		‘disappear’. It supplies a lexical negative counterpart to
		<i lang="ain-Latn">an</i> and <i lang="ain-Latn">oka</i> ‘exist’
		<Ref k="tamura1996" p="s.v. isam" /><Ref k="bugaeva2012" p="496" />. The absent entity is its
		subject. A locative expression can identify where the absence holds.
	</p>
	<Ex
		m="k=unihi okari anakne nep ka isam"
		g="1SG.POSS=home around TOP what INDEF not.exist"
		tr="There is nothing around my house."
		cite="sato2008:18"
		dial="CHI"
		place="Lesson 3, commentary on example 1"
	/>
	<p>
		<i lang="ain-Latn">Isam</i> can describe a change as well as a state. Tamura's entry includes
		gradually diminishing, running out, and dying
		<Ref k="tamura1996" p="s.v. isam" />. For positive existence and location, see
		<Xr ch="existential-locational-an-oka" />.
	</p>
</S>

<S t="Lacking something with sak" id="sak">
	<p>
		<i lang="ain-Latn">Sak</i> is transitive: the subject lacks something, and the lacked entity is
		its object. Tamura contrasts it directly with
		<i lang="ain-Latn">kor</i> ‘have’ in a narrative about parents
		<Ref k="tamura1996" p="s.v. sak, transitive-verb entry" />.
	</p>
	<Ex
		m="unu patek a=kor ona a=sak no"
		g="mother only 4.A=have father 4.A=lack CONJ"
		tr="I had only a mother and no father, …"
		cite="tamura1996"
		dial="SAR"
		place="s.v. sak; S folktale example"
	/>
	<p>
		The noun's form can reflect the difference in construction. Tamura compares
		<i lang="ain-Latn">hon ka sak</i> ‘have no belly’, with a concept-form object, and
		<i lang="ain-Latn">honihi ka isam</i>, where the possessed noun identifies the absent belly <Ref
			k="tamura1996"
			p="s.v. sak"
		/>. The dictionary attributes the two conversational examples to W and S respectively; they
		illustrate its comparison across two speakers.
	</p>
</S>

