<S t="Wa isam and a completed change" id="aspect">
	<p>
		A predicate followed by <i lang="ain-Latn">wa isam</i> often describes an action completed with
		something gone or used up. Nakagawa gives a mother's death as a relatively literal example, then
		a brother's going to bed while remaining visible in the same house. In the latter passage, he
		interprets the construction as entering fully into the sleeping posture
		<Ref k="nakagawa2024" p="450–451, examples 1026–1027" />. The more extensive comparison with
		<i lang="ain-Latn">wa okere</i>
		is in
		<Xr ch="phasal-iterative-habitual-aspect" />.
	</p>
</S>

<S t="A historical proposal" id="history">
	<p>
		In a comparative study centered on Sakhalin negation, Dal Corso reconstructs a transitive <i
			lang="ain-Latn">*sam</i
		>
		‘not exist at a place’ and proposes that antipassive <i lang="ain-Latn">i-</i> produced the
		intransitive ancestor of <i lang="ain-Latn">isam</i>. He relates this reconstruction to the
		history of other Ainu negatives <Ref k="dalcorso2025neg" p="43–45, §4.2" />. The asterisk marks
		a reconstructed form; the proposal does not establish a productive modern verb
		<i lang="ain-Latn">sam</i>.
	</p>
</S>
