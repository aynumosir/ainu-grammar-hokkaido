<S t="Early written records" id="edo-records">
	<p>
		Early records of Ainu were produced for trade, travel, administration, and missionary work.
		Refsing describes <i>Matsumae no koto — Ezo kotoba no koto</i>, dated to around 1600, as a
		collection of 117 words and short phrases for merchants. She also discusses Jeronymo de
		Angelis's 1621 list, whose 54 items include 36 numerals
		<Ref k="refsing1986" p="§1" />. Their selection of vocabulary reflects their immediate purposes.
	</p>
	<p>
		The <i lang="ja">蝦夷方言藻汐草</i> (<i>Ezo hōgen moshiogusa</i>), compiled by Uehara Kumajirō
		and Abe Chōzaburō, was published in 1792 and again in 1804. Refsing describes nearly 3,000 words
		organized by meaning, together with phrases and short texts. She traces its use by later
		scholars, including Pfizmaier's nineteenth-century grammatical work in Europe
		<Ref k="refsing1986" p="§1" />.
	</p>
	<p>
		The early record also includes material from the Kurils and Sakhalin. Its geographical
		provenance, spelling practices, copying history, and translations must be considered before
		drawing phonological or grammatical conclusions
		<Ref k="refsing1986" p="§1" />. The conventions of historical sources are examined in <Xr
			ch="historical-orthographies-and-the-batchelor-tradition"
		/>.
	</p>
</S>

<S t="Batchelor and Piłsudski" id="batchelor-pilsudski">
	<p>
		John Batchelor's Ainu–English–Japanese dictionary appeared in several editions, from 1889 to the
		revised fourth edition of 1938. His publications also included translations and grammatical
		description, written in a Latin transcription that influenced later readers' access to Ainu
		<Ref k="refsing1986" p="§2.1" />; <Ref k="batchelor1905" />;
		<Ref k="batchelor1938" />.
	</p>
	<p>
		Refsing recounts Chiri Mashiho's criticism of mistranslations, unattested entries, and incorrect
		forms in the dictionary. Her assessment allows for useful material while requiring individual
		entries and analyses to be checked <Ref k="refsing1986" p="§2.1" />. This affects the use of
		Batchelor as evidence: a printed form establishes what his edition records, while its accuracy
		as an Ainu expression requires further support.
	</p>
	<p>
		Bronisław Piłsudski's <i>Materials for the Study of Ainu Language and Folklore</i>, published in
		1912, contains Sakhalin texts with translations <Ref k="pilsudski1912" />;
		<Ref k="refsing1986" p="§1" />. This documentary tradition provides a basis for comparison with
		Hokkaido material, as well as evidence for Sakhalin Ainu in its own right. Regional differences
		are treated in <Xr ch="sakhalin-and-kuril-ainu-contrast" />.
	</p>
</S>

<S t="Ainu writers and the Kindaichi–Chiri descriptions" id="kindaichi-chiri">
	<p>
		Chiri Yukie's <i lang="ja">アイヌ神謡集</i>, published in 1923, presents Ainu divine songs with
		Japanese translations <Ref k="chiri1923" />. Kannari Matsu recorded a large narrative repertoire
		in manuscript. Refsing describes the seventy notebooks associated with Kindaichi's work on their
		translation and annotation <Ref k="refsing1986" p="§2.2" />. Ōno places both women's writing in
		the history of Ainu people recording their own language
		<Ref k="ono2022" p="§3" />.
	</p>
	<p>
		Kindaichi's grammatical studies were closely connected with his interpretation of oral
		literature. The 1936 outline by Kindaichi and Chiri brought together an account of Ainu grammar;
		Chiri's 1942 study focused on Sakhalin
		<Ref k="kindaichi1936" />; <Ref k="chiri1942" />. Chiri subsequently developed lexical,
		etymological, and place-name research, including his classified dictionaries
		<Ref k="refsing1986" p="§2.3" />.
	</p>
	<p>
		The analyses changed the interpretation of familiar forms. Refsing credits Kindaichi with
		recognizing bound person affixes and with distinguishing the ordinary noun form from a form
		related to a possessor. She then compares the different restrictions Kindaichi, Chiri, and
		Tamura placed on that nominal opposition <Ref k="refsing1986" p="§2.4.1" />. The forms are
		described in <Xr ch="concept-form-affiliative-form" />.
	</p>
	<p>
		Refsing also contrasts their methods of organizing the description. A classification beginning
		with semantic relations such as location or possession can group together expressions with
		different grammatical distributions. Her own approach, following Tamura's use of formal
		criteria, asks which forms occur in the same positions and constructions
		<Ref k="refsing1986" p="§2.4.1" />. This methodological difference helps explain why the same
		material may appear under different word-class or construction labels in successive grammars.
	</p>
</S>

<S t="Dialect comparison and post-war grammars" id="modern-era">
	<p>
		Hattori and Chiri's 1960 lexicostatistical study compared nineteen dialects using a 200-item
		basic-vocabulary list <Ref k="hattorichiri1960" />; <Ref k="refsing1986" p="52" />. Hattori's
		later dialect dictionary supplied a larger comparative lexical resource
		<Ref k="hattori1964" />. The classifications drawn from such material and their limitations are
		discussed in <Xr ch="hokkaido-dialect-classification-and-dialectometry" />.
	</p>
	<p>
		Tamura's work on Saru includes studies of morphology and syntax, recorded texts, a dictionary,
		and a grammar. Her analysis of form and distribution is an important point of comparison in
		Refsing's Shizunai description <Ref k="refsing1986" p="§3.4" />. The Saru dictionary
		<Ref k="tamura1996" /> and the English grammar <Ref k="tamura2000" /> provide different routes into
		that body of work. Citations marked as reported identify uses of the grammar through another publication.
	</p>
	<p>
		Refsing's monograph describes Shizunai morphology and syntax and contains an extended comparison
		with earlier analyses <Ref k="refsing1986" />. Other regional descriptions include Asai's
		Ishikari study and Murasaki's Sakhalin grammar
		<Ref k="asai1969" />; <Ref k="murasaki1979" />. Shibatani's survey places Ainu alongside
		Japanese and Ryukyuan in a broader account of the languages of Japan
		<Ref k="shibatani1990" />.
	</p>
	<p>
		Chitose documentation expanded through work by Satō, Nakagawa, and Bugaeva from the 1980s onward <Ref
			k="nakagawa2024"
			p="96"
		/>. Satō's 2008 grammar is based on material supplied by Shirasawa Nabe. Its preface records her
		request that her words remain attributable to her and explains Satō's decision to preserve her
		expressions in the examples
		<Ref k="sato2008" p="preface" />. Such provenance is part of the descriptive record, alongside
		the analysis supplied by the linguist.
	</p>
</S>

<S t="Specialist studies and published corpora" id="current-state">
	<p>
		The <i>Handbook of the Ainu Language</i>, edited by Bugaeva, brings together studies of
		documentation, phonology, grammar, dialectology, historical linguistics, oral literature, and
		revitalization <Ref k="bugaeva2022" />. Its chapters give separate treatments of such domains as
		phonology <Ref k="shiraishi2022" />, valency <Ref k="bugaevakobayashi2022" />, reconstruction <Ref
			k="alonso2022"
		/>, and dialectology <Ref k="nakagawafukazawa2022" />.
	</p>
	<p>
		Nakagawa's 2024 reference grammar is based chiefly on Saru, with frequent Chitose examples and
		comparisons across several other Hokkaido varieties. Its introduction explains both that
		dialectal scope and its intended use as a reference for people speaking or writing Ainu
		<Ref k="nakagawa2024" p="16" />. The descriptions overlap enough to permit comparison, but their
		evidence differs in dialect, speaker, and genre.
	</p>
	<p>
		Studies devoted to individual constructions include work on applicatives
		<Ref k="bugaeva2010" />, incorporation <Ref k="sato2016" />, and evidentiality
		<Ref k="dalcorso2018" />. These studies address questions that a general grammar may handle
		briefly, including the diagnostics for a particular analysis and variation across contexts. The
		relevant grammatical chapters compare their findings.
	</p>
	<p>
		Published recordings and annotated corpora make some of the underlying speech accessible
		alongside its transcription and translation. NINJAL’s Glossed Audio Corpus of Ainu Folklore
		presents such materials
		<Ref k="glossedcorpus2016" />. Their speakers, genres, and annotation practices are described in <Xr
			ch="oral-literature-and-spoken-corpora"
		/>. They complement grammatical publications by allowing particular analyses to be checked
		against the recorded examples.
	</p>
</S>
