	<p>
		The supporting expression need not be <i lang="ain-Latn">ruwe ne</i>. Dal Corso gives
		<i lang="ain-Latn">siri ki siri ne</i>
		and discusses corresponding combinations with <i lang="ain-Latn">humi</i> and
		<i lang="ain-Latn">hawe</i>. Although the direct expression usually follows the indirect one in
		his sample, <i lang="ain-Latn">humi ne humi as</i> also occurs <Ref
			k="dalcorso2018"
			p="332–333, examples 274–276"
		/>.
	</p>
	<p>
		Ordinary auxiliaries have construction-specific possibilities as well. Nakagawa gives <i
			lang="ain-Latn">kusu ne ruwe ne</i
		>
		while rejecting the reverse sequence in that construction, and permits <i lang="ain-Latn">a</i>
		and <i lang="ain-Latn">nankor</i> after formal-noun-plus-copula endings
		<Ref k="nakagawa2024" p="393–394" />. These observations describe particular combinations; they
		do not supply one unrestricted ordering template.
	</p>
</S>

<S t="Nominal structure and possible reanalysis" id="structure">
	<p>
		The internal structure remains a subject of analysis. In Bugaeva's 2008 account, the clause
		headed by <i lang="ain-Latn">hawe</i> is an object complement of a transitive copula
		<i lang="ain-Latn">ne</i>, yielding a construction with more than one clause <Ref
			k="bugaeva2008"
			p="64–65, §7.3.4"
		/>. This is an analytical treatment of copular argument structure; compare
		<Xr ch="copula-ne-predicate-nominals" />.
	</p>
	<p>
		Dal Corso discusses the retained noun properties, including possessed morphology and intervening
		particles, alongside the biclausal account. For particular
		<i lang="ain-Latn">ruwe ne</i> uses he proposes possible reanalysis as an auxiliary in a single
		clause, drawing on restrictions on clefting and its combinations with other evidentials
		<Ref k="dalcorso2018" p="145–147, §5.3.2.2" />. The proposal is specific to those constructions.
	</p>
	<p>
		Takahashi proposes a further development from nominalizer to adverbial-clause marker in
		Horobetsu literary material <Ref k="takahashi2018" p="111–112, §§3–4" />. The documented
		regional differences are synchronic evidence; arranging Tokachi, Saru, and Horobetsu as
		successive historical stages would require additional evidence.
	</p>
</S>

<S t="Formal and regional endings" id="regional">
	<p>
		The ending <i lang="ain-Latn">tapan</i> often occupies the place of
		<i lang="ain-Latn">ne</i> in formal or verse contexts. Nakagawa illustrates
		<i lang="ain-Latn">ruwe tapan</i> in Horobetsu and
		<i lang="ain-Latn">ru tapan</i> in Tokachi, including a prose narrator's closing account to
		descendants <Ref k="nakagawa2024" p="401–402" />.
	</p>
	<p>
		Ishikari <i lang="ain-Latn">sittapan</i> or <i lang="ain-Latn">sitapan</i>
		appears when speakers explain their own actions. Nakagawa proposes a relationship to
		<i lang="ain-Latn">sir + tapan</i>. He distinguishes it from Tokachi
		<i lang="ain-Latn">ru estap an</i>, and suggests that some older transcriptions confused the
		similar-sounding expressions
		<Ref k="nakagawa2024" p="402–403" />. These endings preserve useful regional distinctions beyond
		the ordinary
		<i lang="ain-Latn">ne</i>, <i lang="ain-Latn">an</i>, and
		<i lang="ain-Latn">un</i> frames.
	</p>
</S>
