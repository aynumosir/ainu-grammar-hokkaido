<S t="Exclamation and retrospective discovery" id="mirativity">
	<p>
		Surprise, discovery, and strong feeling can arise in several constructions. Nakagawa's bare
		formal-noun exclamations include appreciation of a conversation, enjoyment of tea, pain, and
		horror at someone's appearance
		<Ref k="nakagawa2024" p="396, 400–401" />. An exclamation is not automatically an instance of
		the same grammatical category as retrospective <i lang="ain-Latn">aan</i> or
		<i lang="ain-Latn">anan</i>.
	</p>
	<p>
		Yoshikawa discusses discovery and indirect experience with
		<i lang="ain-Latn">aan</i>, but also narrative passages where a deity states something already
		known. These examples motivate a possible narrative function beyond indirect evidence or
		surprise <Ref k="yoshikawa2018" p="14–17, §§4.4–6" />. The later aspectual analysis is developed
		in <Xr ch="perfective-anterior-a" />.
	</p>
</S>

