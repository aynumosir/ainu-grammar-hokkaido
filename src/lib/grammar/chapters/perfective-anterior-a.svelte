<S t="An earlier situation in context" id="earlier">
	<p>
		The auxiliary <i lang="ain-Latn">a</i> places a situation in relation to another time or event.
		Its interpretation has been described through past time, completion, anteriority, and narrative
		sequencing. The choice among these analyses matters: an English past-tense translation alone
		does not establish what the auxiliary contributes
		<Ref k="nakagawa2024" p="305–306" /><Ref k="yoshikawa2022" p="§§4–5" />.
	</p>
	<Ex
		m="tane pakno a=e=tumam wa hotke=an a korka"
		g="now until 4.A=2SG.O=embrace CONJ lie.down=4.S PFV CONJ"
		tr="I have lain embracing you until now, but …"
		cite="nakagawa2024:305–306"
		dial="SAR"
		place="Example 448, opening clause"
		note="The following clause says that the addressee will no longer see the narrator. The example explicitly contrasts the earlier relationship with what follows."
	/>
	<p>
		Nakagawa's next discussion shows why <i lang="ain-Latn">a</i> is not simply an obligatory
		past-tense ending. A narrator describes formerly being the wife of the Poroshiri deity with
		<i lang="ain-Latn">a</i>, then recounts leaving and giving birth without marking each later
		event with it <Ref k="nakagawa2024" p="306, example 450" />.
	</p>
</S>

<p>
	The examples use PFV as a conventional gloss for <i lang="ain-Latn">a</i>; the competing analyses
	are discussed below.
</p>

<S t="Number and repetition" id="number">
	<p>
		Nakagawa pairs <i lang="ain-Latn">a</i> with plural <i lang="ain-Latn">rok</i>. The relevant
		plurality can concern the object: in example 449, a single narrator has hung several things at a
		window, and the expression contains
		<i lang="ain-Latn">a=racitkere rok pa p</i>
		<Ref k="nakagawa2024" p="305–306, table 74 and example 449" />. A rule based solely on how many
		people perform the action would miss this use.
	</p>
	<p>
		Repeated <i lang="ain-Latn">V a</i> sequences can describe sustained or repeated activity.
		Refsing's examples distinguish talking on and on from making successive cuts; the event
		determines the natural interpretation
		<Ref k="refsing1986" p="198–199, examples 290–292" />.
	</p>
	<Ex
		m="os onkami=an a onkami=an a kor ahun=an akusu"
		g="afterward worship=4.S PFV worship=4.S PFV CONJ enter.SG=4.S CONJ"
		tr="Afterward, as I entered while repeatedly paying respects, …"
		cite="nakagawa2024:307"
		dial="SAR"
		place="Example 454, citing Kayano 1974a:70"
	/>
	<p>
		The shorter <i lang="ain-Latn">onkami=an a =an a</i> also occurs. Nakagawa treats this as an
		abbreviated repetition; the full form above remains possible
		<Ref k="nakagawa2024" p="307, examples 453–454" />.
	</p>
</S>

<S t="Aan and retrospective discovery" id="aan">
	<p>
		Nakagawa describes <i lang="ain-Latn">aan</i> as recognizing, at a particular moment, what an
		earlier situation had been. In his example 455, a dog who had taken human form speaks after
		death in a girl's dream. Only then does he explain that the young man who killed him had been
		hiding in the house. The expression
		<i lang="ain-Latn">nuynak wa an aan</i> belongs to that retrospective discovery
		<Ref k="nakagawa2024" p="307" />.
	</p>
	<p>
		Related forms include Chitose <i lang="ain-Latn">anan</i>, Horobetsu and Tokachi
		<i lang="ain-Latn">awan</i>, and Tokachi <i lang="ain-Latn">hawan</i>. Nakagawa lists plural
		<i lang="ain-Latn">rokoka</i>
		and regional
		<i lang="ain-Latn">rokokay</i>, as well as Chitose
		<i lang="ain-Latn">rokoka anan</i>
		<Ref k="nakagawa2024" p="307–308" />. These are documented regional forms, not freely
		interchangeable spellings.
	</p>
</S>

<S t="What the analyses explain" id="analyses">
	<p>
		Yoshikawa analyzes <i lang="ain-Latn">a</i> as perfective and
		<i lang="ain-Latn">aan</i> as perfect, connecting them with direct and indirect evidence. The
		account also includes directly observed, unexpected situations with
		<i lang="ain-Latn">aan</i>. Its evidence comes chiefly from Saru and Chitose narratives, mostly
		in the fourth person <Ref k="yoshikawa2022" p="§§4–5" />. Discovery, surprise, and lack of
		direct observation therefore need separate attention.
	</p>
	<p>
		Ma instead emphasizes the ordering of situations in Saru narratives, including relative clauses
		whose time is understood against a main-clause event. This is a <em>taxis</em> analysis: the
		central relation is between events
		<Ref k="ma2021" p="77–83, §§3.3–4" />. Ma's later study of <i lang="ain-Latn">kor an a</i> and
		<i lang="ain-Latn">wa an a</i> includes activity and states continuing to the time of speaking,
		sometimes with possible further continuation. An earlier-state contrast does not invariably mean
		that the state has ended
		<Ref k="ma2023" p="32, table 1" />.
	</p>
	<p>
		Sentence endings also require context. Satō describes an ordinary tendency for a particle to
		follow final <i lang="ain-Latn">a</i>, while expressly allowing questions ending in
		<i lang="ain-Latn">a</i>
		<Ref k="sato2008" p="187–188" />. For existential combinations, see <Xr
			ch="existential-aspect-an-oka"
		/>; for the evidence-related endings, see <Xr ch="tam-overview" />.
	</p>
</S>
