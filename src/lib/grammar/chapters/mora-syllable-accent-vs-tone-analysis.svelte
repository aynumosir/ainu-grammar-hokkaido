<S t="Syllables and moras" id="mora-syllable">
	<p>
		A syllable groups a vowel with an optional onset and coda. A mora is a unit used in phonological
		analyses of weight. In a weight-based account, calling (C)V light and (C)VC heavy distinguishes
		two syllable shapes; it does not mean that a coda consonant can independently carry the pitch
		accent. The published Ainu rules identify an accented syllable <Ref
			k="shiraishi2022"
			p="§5.1"
		/>;
		<Ref k="nakagawa2024" p="50" />.
	</p>
	<p>
		The distinction matters particularly for /y/ and /w/. In
		<i lang="ain-Latn">áynu</i> “person,” /y/ closes the initial syllable. It contributes to the
		structure relevant to accent placement while remaining part of that syllable
		<Ref k="nakagawa2024" p="31, 50" />. Japanese kana counts can obscure this structure, because a
		written coda may occupy its own character. The Ainu syllable analysis is explained in <Xr
			ch="syllable-template"
		/>.
	</p>
</S>

<S t="What the term pitch accent establishes" id="accent-vs-tone">
	<p>
		Shiraishi describes the Ainu system through word accent and explicitly distinguishes it from
		lexical tone <Ref k="shiraishi2022" p="§5" />. The descriptive generalizations are the location
		of prominence, its dependence on syllable structure, the lexical exceptions, and the behavior of
		complex forms. Those properties provide a more precise account than the typological label by
		itself.
	</p>
	<p>
		A one-mark accent transcription also leaves phonetic information unspecified. Later syllables
		can stay high, and some complex expressions can preserve secondary accent
		<Ref k="nakagawa2024" p="49" />; <Ref k="shiraishi2022" p="§§5.1–5.2" />. “One accent mark”
		should therefore not be read as “exactly one high syllable.”
	</p>
</S>

<S t="The limits of a single dialect model" id="dialect-split">
	<p>
		The familiar first-or-second-syllable rule is associated with varieties including Saru and
		Chitose. Yakumo and Oshamambe have a related pattern allowing third-syllable accent, while
		several eastern and southern varieties lack the same lexical accent contrast
		<Ref k="nakagawafukazawa2022" p="§3.1" />. These distributions qualify any general statement
		about “Ainu accent.”
	</p>
	<p>
		For Shizunai, Refsing states an accent rule, whereas Nakagawa argues from variable realizations
		that the variety lacks a stable contrast
		<Ref k="refsing1986" p="§10.6, 73" />; <Ref k="nakagawa2024" p="50" /> ‹contested›. A variety described
		as unaccented still has pitch and intonation; the term concerns the absence of a lexical distinction.
		The regional comparison is set out in
		<Xr ch="pitch-accent-placement-rule" />.
	</p>
</S>

<S t="Accent and vowel length in historical comparison" id="diachrony">
	<p>
		<strong>Sakhalin comparison.</strong> Exceptional Hokkaido initial accent often corresponds to a
		long vowel in Sakhalin. Nakagawa gives <i lang="ain-Latn">túki</i> beside
		<i lang="ain-Latn">tuuki</i> “cup,” among other pairs
		<Ref k="nakagawa2024" p="51" />. Bugaeva likewise notes the correspondence
		<Ref k="bugaeva2012" p="467" />.
	</p>
	<p>
		The modern correspondence is compatible with a historical relationship between accent and
		length, but does not by itself determine the direction of change. Nakagawa and Fukazawa report
		Hattori's earlier-length account and refer to an alternative in Satō's Handbook treatment <Ref
			k="nakagawafukazawa2022"
			p="§3.1"
		/> ‹contested›. A historical reconstruction must be attributed separately from the modern phonological
		description.
	</p>
