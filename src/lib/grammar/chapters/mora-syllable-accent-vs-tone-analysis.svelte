<S t="Pitch accent in the descriptive literature" id="typology">
	<p>
		Descriptions of the accentual Hokkaido varieties identify a position of high pitch within the
		word. Moving that position can change the word's meaning. The customary term is
		<em>pitch accent</em>; it describes the contrast illustrated by Saru
		<i lang="ain-Latn">nísap</i> “suddenly” and <i lang="ain-Latn">nisáp</i> “shin”
		<Ref k="nakagawa2024" p="48–49" />. The same segment sequence occurs with two accents.
	</p>
	<p>
		Several questions follow from this description. The phonetic question concerns how pitch and
		duration realize the accent. The structural question concerns the syllable on which it falls.
		The typological question concerns the label used for the system as a whole. A claim about one of
		these does not automatically answer the others.
	</p>
</S>

<S t="A rising kernel and a variable later contour" id="rising-nucleus">
	<p>
		Nakagawa locates the contrast at the rise into the accented syllable. In
		<i lang="ain-Latn">kamúynomi</i> “pray to the gods,” the first syllable is low and the second
		high. The later syllables may remain high or become lower. Their contour does not create the
		lexical contrast associated with shifting the accent itself
		<Ref k="nakagawa2024" p="49" />.
	</p>
	<p>
		This is the basis of the term <em>rising kernel</em>. Nakagawa contrasts it with the lexically
		relevant pitch fall in Standard Japanese <Ref k="nakagawa2024" p="48–49" />. The comparison
		concerns where the contrast is located; it is not a claim that the two languages share every
		detail of word or phrase intonation.
	</p>
	<p>
		Shiraishi also reports slight lengthening of accented vowels, especially in northeastern
		dialects <Ref k="shiraishi2022" p="§5" />. Such duration differences accompany the accent
		without creating a Hokkaido long–short vowel opposition. See
		<Xr ch="vowel-inventory" /> for the distinction between phonetic duration and vowel length.
	</p>
</S>

<S t="Syllable weight in accent placement" id="placement">
