		falls on the second. A heavy first syllable normally bears the accent itself <Ref
			k="shiraishi2022"
			p="§5.1"
		/>. Nakagawa and Satō give the equivalent open-versus-closed rule <Ref
			k="nakagawa2024"
			p="50"
		/>;
