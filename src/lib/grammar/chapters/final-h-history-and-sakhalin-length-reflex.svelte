<S t="Final stops and their Sakhalin counterparts" id="final-stops">
	<p>
		In many Sakhalin varieties, Hokkaido syllable-final
		<i>p, t, k</i> correspond to <i>h</i> after <i>a, e, o, u</i>
		and to <i>s</i> after <i>i</i>. Tangiku describes this as final-stop change followed by
		<i>h &gt; s</i>
		after <i>i</i>. Thus Hokkaido
		<i lang="ain-Latn">tek</i> ‘hand’ corresponds to west-coast
		<i lang="ain-Latn">teh</i>, and <i lang="ain-Latn">sik</i>
		‘eye’ to <i lang="ain-Latn">sis</i>
		<Ref k="tangiku2022" p="§§2.2–2.3" />.
	</p>
	<p>
		The geographic qualification matters. Stops remain in some northern east-coast varieties and
		around Tarantomari on the central west coast. Tangiku also reports an Esutoru distinction
		between final
		<i>-is</i> and <i>-ih</i>. A single Sakhalin form therefore cannot represent every locality <Ref
			k="tangiku2022"
			p="§2.3"
		/>.
	</p>
</S>

