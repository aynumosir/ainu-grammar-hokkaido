<S t="Final r follows a different pattern" id="final-r">
	<p>
		Final <i>r</i> commonly gains a following vowel: Hokkaido
		<i lang="ain-Latn">nukar</i> ‘see’ corresponds to
		<i lang="ain-Latn">nukara</i>, and
		<i lang="ain-Latn">kisar</i> ‘ear’ to
		<i lang="ain-Latn">kisaru</i>. The added vowel often repeats the preceding one, but lexical
		exceptions occur
		<Ref k="tangiku2022" p="§2.4" />.
	</p>
	<p>
		Suffixes reveal different ordering relations. Tangiku analyzes
		<i lang="ain-Latn">kon-te</i> ‘give’ from
		<i lang="ain-Latn">kor</i> ‘have’ with causative formation before vowel addition and
		<i>r &gt; n</i>
		before <i>t</i>. Plural
		<i lang="ain-Latn">koro-hci</i> instead contains the added vowel before the plural suffix. The
		surface shape of an independent word thus does not predict every derived form
		<Ref k="tangiku2022" p="§2.4" />.
	</p>
</S>

