<S t="Heads and modifying expressions" id="np-template">
	<p>
		An Ainu noun phrase can consist of a noun alone or a nominal head with modifiers.
		Demonstratives, numeral prenominals, property predicates, and relative clauses precede the head
		in the constructions described by Nakagawa, Shibatani, and Bugaeva
		<Ref k="nakagawa2024" p="379–386" />;
		<Ref k="shibatani1990" p="42–44" />;
		<Ref k="bugaeva2012" p="477" />. Numeral nouns also occur after a noun phrase. The structural
		possibilities depend on the kind of modifier and the nominal head.
	</p>
	<p>
		Several modifiers can occur together. Shibatani's Ishikari example has a numeral before a
		property predicate:
	</p>
	<Ex
		m="sine kunne cikap"
		g="one be.black bird"
		tr="one black bird"
		cite="shibatani1990:43, example 66a"
		dial="ISH"
	/>
	<p>
		Kawakami Matsuko's Saru narrative has a relative modifier before
		<i lang="ain-Latn">wen</i> “bad, wretched,” followed by a diminutive noun and plural
		<i lang="ain-Latn">utar</i>:
	</p>
	<Ex
		m="hinak wa arki wen cikap-po utar"
		ain="hinak wa arki wen cikappo utar"
		g="where ABL come.PL bad bird-DIM PL"
		tr="the wretched little birds that came from somewhere"
		cite="kawakami1984:aa-irc/022#23"
		dial="SAR"
		note="Noun-phrase excerpt from a longer quoted utterance. The diminutive boundary is supplied in the morphemic line."
	/>
</S>

<S t="Demonstrative prenominals" id="demonstratives">
	<p>
		Demonstratives identify referents through location or preceding discourse. Nakagawa's Saru
		inventory distinguishes <i lang="ain-Latn">taan</i>, near the speaker or listener, from
		<i lang="ain-Latn">toan</i>, away from both. It also distinguishes
		<i lang="ain-Latn">ne</i>, referring to what has just been mentioned, from
		<i lang="ain-Latn">nea</i>, recalling an earlier referent
		<Ref k="nakagawa2024" p="283" />.
	</p>
	<table>
		<caption>Selected singular–plural pairs in Nakagawa's Saru inventory</caption>
		<thead><tr><th>Singular</th><th>Plural</th></tr></thead>
		<tbody>
			<tr><td lang="ain-Latn">taan</td><td lang="ain-Latn">taoka(y)</td></tr>
			<tr><td lang="ain-Latn">toan</td><td lang="ain-Latn">tooka(y)</td></tr>
			<tr><td lang="ain-Latn">nea</td><td lang="ain-Latn">nerok</td></tr>
		</tbody>
	</table>
	<p>
		These are number distinctions in the demonstratives
		<Ref k="nakagawa2024" p="283, Table 72" />. Bugaeva likewise describes number contrasts among
		anaphoric forms <Ref k="bugaeva2012" p="472" />. Their deictic meanings, regional forms, and
		discourse uses are developed in
		<Xr ch="demonstratives-anaphora-definiteness" />.
	</p>
</S>

<S t="Numerals before and after the noun" id="numerals">
	<p>
		Numeral prenominals directly precede nouns: Nakagawa's Saru examples include
		<i lang="ain-Latn">tu cip</i> “two boats” and
		<i lang="ain-Latn">asikne okkayo</i> “five men”
		<Ref k="nakagawa2024" p="462" />. These constructions contain no intervening classifier. Numeral
		nouns have a different distribution, following the expression they quantify or occurring
		independently
		<Ref k="refsing1986" p="116–117" />;
		<Ref k="shibatani1990" p="42–43" />.
	</p>
	<p>
		Nakagawa's Saru example combines <i lang="ain-Latn">tu okkaypo</i> “two young men” with
		<i lang="ain-Latn">ponmenoko sinep</i>
		“one young woman.” His Chitose examples place <i lang="ain-Latn">sinep</i> after a full nominal
		expression, including <i lang="ain-Latn">siknu wa hosipi p</i> “one who returned alive” and
		<i lang="ain-Latn">a=matnepoho</i>
		“my daughter”
		<Ref k="nakagawa2024" p="383, examples 747–749" />.
	</p>
	<p>
		He analyzes the noun phrase and following numeral noun as one larger noun phrase, including
		examples in which intervening particles separate them
		<Ref k="nakagawa2024" p="384" />. The numeral forms and their constructional differences are
		described in
		<Xr ch="numeral-classifiers-ordinals-and-quantifier-syntax" />.
	</p>
</S>

<S t="Property predicates and other prenominals" id="adnouns-property-verbs">
	<p>
		A property verb can directly modify a noun, as
		<i lang="ain-Latn">kunne</i> “black” does in the Ishikari example above. Such words also take
		person marking and serve as predicates
		<Ref k="nakagawa2022pos" p="§§2.1–2.2" />. Their classification is discussed in <Xr
			ch="no-adjective-class-property-verbs"
		/>.
	</p>
	<p>
		Other prenominals have more restricted noun-modifying uses. Nakagawa lists forms including <i
			lang="ain-Latn">pinne</i
		>
		“male,”
		<i lang="ain-Latn">matne</i> “female,” and
		<i lang="ain-Latn">oya</i> “other”
		<Ref k="nakagawa2024" p="286" />. Some members of his inventory, such as
		<i lang="ain-Latn">sonno</i> and <i lang="ain-Latn">sino</i>, also have adverbial uses. A
		prenominal position alone does not identify a single word class.
	</p>
</S>

<S t="Relative modifiers and nominalized content" id="relative-clauses">
	<p>
		A relative clause precedes its head, which may be an ordinary or a formal noun. The head has a
		grammatical relation to the modifying clause. In content nominalization, a following
		nominalizing form instead presents the preceding proposition as a nominal expression
		<Ref k="nakagawa2024" p="507–510" />. Forms such as
		<i lang="ain-Latn">p/pe</i> occur in both kinds of construction; see
		<Xr ch="lexical-head-formal-noun-nominalization" />.
	</p>
	<p>
		Locative nouns receive different treatments. Nakagawa's 2022 description allows verb-phrase
		modification of them, but his 2024 table explicitly excludes it
		<Ref k="nakagawa2022pos" p="§3.4" />;
		<Ref k="nakagawa2024" p="215" /> ‹contested›. Satō contrasts modifiable formal
		<i lang="ain-Latn">usi</i>
		with locative
		<i lang="ain-Latn">or</i>, which cannot replace it after the modifying clause in his example <Ref
			k="sato2008"
			p="181"
		/>.
	</p>
</S>

<S t="Locations and following case particles" id="postpositions">
	<p>
		Locative nouns can head expressions such as
		<i lang="ain-Latn">nupuri or</i> “the mountain's location,” followed by a case particle in
		<i lang="ain-Latn">nupuri or ta</i>
		“at the mountain”
		<Ref k="nakagawa2024" p="216" />. In this construction the locative noun provides the
		grammatical location required by the particle.
	</p>
	<p>
		Ordinary conceptual nouns generally need this intermediary in location-requiring constructions,
		but lexical and regional exceptions occur. Affiliative forms generally have locative uses
		themselves, as in
		<i lang="ain-Latn">a-uni un</i> “to my home”
		<Ref k="nakagawa2022pos" p="§3.5, example 17; §4.5" />;
		<Ref k="bugaeva2012" p="476–477" />. The nominal expression and the following particle have
		separate roles, detailed in
		<Xr ch="postpositions-local-case-and-motion-events" />.
	</p>
</S>

<S t="Nominal juxtaposition and compounds" id="apposition">
	<p>
		Bugaeva presents combinations such as <i lang="ain-Latn">sisam uwepeker</i>
		“Japanese story” and <i lang="ain-Latn">kamuy rus</i> “bear fur” as attributive noun phrases <Ref
			k="bugaeva2012"
			p="477, example 28"
		/>. Nakagawa instead analyzes conceptual-noun plus conceptual-noun combinations as compounds,
		contrasting them with expressions whose second noun is affiliative
		<Ref k="nakagawa2024" p="380–382" /> ‹contested›. Their analyses differ in the boundary they draw
		between lexical composition and phrase structure.
	</p>
	<p>
		The relevant morphological diagnostics are described in
		<Xr ch="noun-noun-compounding" />. The presence of two adjacent nouns alone does not identify
		them as two expressions referring to the same entity.
	</p>
</S>

<S t="Possession and modifier placement" id="possessor-slot">
	<p>
		Nakagawa distinguishes possession with <i lang="ain-Latn">kor</i> “have,” as in
		<i lang="ain-Latn">ku=kor cip</i>
		“my boat,” from affiliative possession, as in <i lang="ain-Latn">ku=tekehe</i> “my hand”
		<Ref k="nakagawa2024" p="218–219" />. The latter is based on
		<i lang="ain-Latn">tek</i>, with affiliative
		<i lang="ain-Latn">teke(he)</i>. Their distribution is treated in
		<Xr ch="alienable-inalienable-split" /> and
		<Xr ch="adnominal-possession-double-marking" />.
	</p>
	<p>
		Modifiers can occur in more than one position relative to person marking. Shibatani gives Saru <i
			lang="ain-Latn">wen ku-matakihi</i
		>
		and
		<i lang="ain-Latn">ku-wen-matakihi</i>, both translated “my dear younger sister” <Ref
			k="shibatani1990"
			p="43, example 67b"
		/>. Refsing records a comparable Shizunai pattern <Ref k="refsing1986" p="154" />. These
		combinations also enter the discussion of compound and phrase boundaries.
	</p>
</S>

<S t="Coordination and number distinctions" id="np-agreement">
	<p>
		Nominal coordination varies by dialect. Nakagawa gives
		<i lang="ain-Latn">totto newa huci</i> “mother and grandmother” in an Ishikari sentence and
		describes <i lang="ain-Latn">newa</i> in varieties other than Saru and Chitose. His Saru example
		joins the names of two fish deities by juxtaposition <Ref
			k="nakagawa2024"
			p="325–326, examples 540–541"
		/>. This contrasts with verbal and clausal linkage by
		<i lang="ain-Latn">wa</i>
		<Ref k="shibatani1990" p="22" />.
	</p>
	<p>
		Ordinary nouns retain the same form under numeral modification, but demonstratives can
		distinguish number, and modifying clauses retain verbal person and other grammatical material <Ref
			k="shibatani1990"
			p="32, 42–44"
		/>;
		<Ref k="nakagawa2024" p="283" />. Number-neutral nouns, plural expressions, and verbal number
		are described separately in
		<Xr ch="nominal-number-utar-transnumerality" />.
	</p>
</S>
