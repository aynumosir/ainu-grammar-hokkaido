<S t="Four constructional types" id="overview">
	<p>
		Applicative <i lang="ain-Latn">e-</i> adds an object whose role depends on the base verb.
		Nakagawa distinguishes four types by the kind of object and the availability of another
		construction with a similar meaning <Ref k="nakagawa2024" p="194, table 37" />.
	</p>
	<table>
		<thead
			><tr><th>Type</th><th>Typical meaning</th><th>Alternative in Nakagawa's account</th></tr
			></thead
		>
		<tbody>
			<tr><td>Instrument</td><td>With, by means of</td><td><i lang="ain-Latn">ani/ari</i></td></tr>
			<tr><td>Purpose</td><td>For an activity</td><td><i lang="ain-Latn">kusu</i></td></tr>
			<tr
				><td>Other nonplace relation</td><td>Often about or concerning</td><td
					>No corresponding paraphrase supplied</td
				></tr
			>
			<tr
				><td>Place</td><td>At, to, or through a place</td><td
					><i lang="ain-Latn">ta, un, peka</i></td
				></tr
			>
		</tbody>
	</table>
	<p>
		The alternatives belong to the specified constructions. Satō cautions that their functional
		differences are incompletely understood and that both alternatives are seldom equally usual with
		a given verb <Ref k="sato2008" p="243" />.
	</p>
</S>

<S t="Instrumental objects" id="instrument">
	<Ex
		m="a=kemaha a=e-apkas easkay wa kusu"
		g="4.POSS=foot 4.A=APPL-walk can CONJ because"
		tr="Because I can walk on my own feet, …"
		cite="nakagawa2024:194"
		dial="CHI"
		place="Example 176"
	/>
	<p>
		The narrative speaker's feet are the applied object of “walk.” With an already transitive base
		such as “cut,” an instrument can become a second object beside the thing cut
		<Ref k="nakagawa2024" p="193–194" />. The sword example illustrating that three-place frame
		appears in <Xr ch="applicative-system-overview" s="valency" />.
	</p>
	<p>
		A role that English treats as a direct object may enter through this construction. Nakagawa
		compares Horobetsu <i lang="ain-Latn">e-yapkir</i> “throw something” with
		<i lang="ain-Latn">yapkir</i> and a phrase in <i lang="ain-Latn">ari</i>, treating the thrown
		material as instrument-like in the Ainu comparison
		<Ref k="nakagawa2024" p="195, examples 178–179, from Chiri Yukie 1923" />.
	</p>
</S>

<S t="Purpose and content" id="content-purpose">
	<p>
		Nakagawa illustrates the purpose type with <i lang="ain-Latn">turepta e-arpa</i>
		“go to dig lily bulbs,” beside <i lang="ain-Latn">turepta kusu arpa</i>. He treats the one-place
		activity verb as used nominally in the applied construction
		<Ref k="nakagawa2024" p="195" />. This illustrates a particular purpose frame; it is not a rule
		allowing an arbitrary purpose clause to be prefixed to any verb.
	</p>
	<p>
		Other bases acquire a content or related participant without a corresponding postpositional
		paraphrase. Nakagawa gives <i lang="ain-Latn">mina → e-mina</i> “laugh → laugh at” and
		<i lang="ain-Latn">simpay → e-simpay</i> “worry → worry about”
		<Ref k="nakagawa2024" p="195–196" />. Bugaeva's dictionary-based classification likewise finds
		Content the largest category among her <i lang="ain-Latn">e-</i> applicatives: 39%, compared
		with 13% for Means/Instrument <Ref k="bugaeva2006" p="190, table 1" />. These are shares of
		lexical entries in her classification, not frequencies of use in speech.
	</p>
</S>

<S t="Places and paths" id="place">
	<p>
		The place type includes Nakagawa's illustration <i lang="ain-Latn">to teksama e-an</i>, “be at
		the lake's edge,” beside a construction with <i lang="ain-Latn">ta</i>
		<Ref k="nakagawa2024" p="196" />. He describes this type as frequent in verse and less usual in
		prose. A place can also be a path followed in motion.
	</p>
	<Ex
		m="i=corpokke e=e-hoyupu yak pirka na"
		g="4.O=under 2SG.A=APPL-run COND good FIN"
		tr="You had better run under me."
		cite="nakagawa2024:196"
		dial="SAR"
		place="Example 184, from Chiba University ed. 2015:1886, as reproduced by Nakagawa"
		note="A dried spawned-salmon head speaks while guiding the protagonist. The first e= marks the addressee; the second e- introduces the path."
	/>
	<p>
		Here <i lang="ain-Latn">i=corpokke</i> is a person-marked locative expression. Nakagawa compares
		its applied use with a path expression in <i lang="ain-Latn">peka</i>
		<Ref k="nakagawa2024" p="196" />. The location noun contributes the spatial relation; its
		presence does not amount to retention of a case postposition.
	</p>
</S>

<S t="Combination and homophony" id="combination">
	<p>
		Applicative <i lang="ain-Latn">e-</i> can combine with other derivational elements. Bugaeva
		gives <i lang="ain-Latn">e-ko-isoytak</i>, “tell someone stories about something,” with separate
		content and addressee relations <Ref k="bugaeva2006" p="188" />. The limits on stacking and its
		relation to incorporation are described in
		<Xr ch="applicative-stacking-relativization-feeding" />.
	</p>
	<p>
		Nominal <i lang="ain-Latn">e-</i> in <i lang="ain-Latn">e-puni</i>, “raise someone's head,”
		belongs to a different formation. Nakagawa analyzes it as referring to a part of the object and
		retaining two-place valency <Ref k="nakagawa2024" p="191–192" />. The identical spelling has to
		be interpreted through the particular word and argument frame.
	</p>
</S>
