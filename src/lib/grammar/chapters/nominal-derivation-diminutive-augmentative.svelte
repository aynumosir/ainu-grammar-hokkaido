<S t="Lexicalized formations" id="animal-names">
	<p>
		Tamura's Saru dictionary analyzes <i lang="ain-Latn">isepo</i> “rabbit, hare” as
		<i lang="ain-Latn">i-se-po</i>: an imitated cry,
		<i lang="ain-Latn">se</i> “say,” and the diminutive
		<Ref k="tamura1996" p="s.v. isepo" />. This is the dictionary's morphological analysis of the
		lexical animal name. It does not assign an additional small-size meaning to every occurrence of
		the word.
	</p>
</S>

<S t="Okkaypo and okkayopo" id="okkaypo">
	<p>
		Saru and Chitose distinguish <i lang="ain-Latn">okkay-po</i> “young man” from
		<i lang="ain-Latn">okkayo-po</i> “son.” Nakagawa analyzes the former with the diminutive suffix
		and the latter with the noun <i lang="ain-Latn">po</i> “child.” The shortened base
		<i lang="ain-Latn">okkay</i>
		is not an independent noun in those dialects <Ref k="nakagawa2024" p="268" />. Tamura's Saru
		entries give the same distinction <Ref k="tamura1996" p="s.vv. okkaypo, okkayopo" />.
	</p>
	<p>
		Elsewhere, independent <i lang="ain-Latn">okkay</i> occurs, and
		<i lang="ain-Latn">okkaypo</i> can mean either “young man” or “son.” Nakagawa notes that the
		intended interpretation can be ambiguous
		<Ref k="nakagawa2024" p="268" />. The suffix and noun therefore cannot be distinguished from the
		final syllable alone.
	</p>
</S>

<S t="A historical Horobetsu use" id="horobetsu">
	<p>
		Kindaichi and Chiri report a deceased-relative meaning when
		<i lang="ain-Latn">-po</i> follows an intimate kin term in colloquial Horobetsu. Their examples
		include <i lang="ain-Latn">ku-aki-po</i> “my deceased younger brother” and
		<i lang="ain-Latn">ku-kor oper-po</i>
		“my deceased daughter.” They distinguish these from the epic form <i lang="ain-Latn">ak-po</i>
		<Ref k="kindaichi1936" p="25, note 2" />. The meanings are tied to the stated dialect and
		register.
	</p>
	<p>
		The same authors derive the suffix from <i lang="ain-Latn">po</i> “child,” an origin also given
		by Refsing. Nakagawa presents the historical connection as probable <Ref
			k="kindaichi1936"
			p="25, note 2"
		/>;
		<Ref k="refsing1986" p="159" />;
		<Ref k="nakagawa2024" p="268" /> ‹speculative›.
	</p>
</S>

