<S t="Diminutive and affective -po" id="overview">
	<p>
		The suffix <i lang="ain-Latn">-po</i> forms nouns associated with smallness, youth, or
		affection. Nakagawa gives <i lang="ain-Latn">cikap-po</i> “small bird,”
		<i lang="ain-Latn">cep-po</i> “small fish,” and
		<i lang="ain-Latn">supuya-po</i> “faint smoke”
		<Ref k="nakagawa2024" p="268" />. Satō and Refsing also describe diminutive
		<i lang="ain-Latn">-po</i>
		<Ref k="sato2008" p="266" />;
		<Ref k="refsing1986" p="159" />. The suffix's contribution ranges beyond physical size,
		especially in terms for people and in expressions of affection.
	</p>
</S>

<S t="Suffixation and noun compounding" id="morphology">
	<p>
		Nakagawa distinguishes diminutive formations from ordinary noun–noun compounds. In a compound
		such as <i lang="ain-Latn">okkayo-po</i> “son,”
		<i lang="ain-Latn">okkayo</i> “man” qualifies the following noun
		<i lang="ain-Latn">po</i> “child.” In <i lang="ain-Latn">cikap-po</i>, the suffix qualifies the
		preceding noun <Ref k="nakagawa2024" p="267–268" />. This difference in semantic organization
		motivates his classification.
	</p>
	<p>
		Refsing includes <i lang="ain-Latn">-po</i> among suffixes that extend a nominal while
		preserving its category and syntactic function. Her Shizunai description gives
		<i lang="ain-Latn">menoko → menokopo</i> “woman → young woman” and
		<i lang="ain-Latn">cep → ceppo</i> “fish → small fish”
		<Ref k="refsing1986" p="159, §14.2" />.
	</p>
</S>

