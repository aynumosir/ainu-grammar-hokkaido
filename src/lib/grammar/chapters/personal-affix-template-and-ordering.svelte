<S t="Person marking around a derived stem" id="template">
	<p>
		Person marking relates a verb's arguments to the speech situation. In an ordinary two-prefix
		combination, the A index precedes the O index, and both precede the derived verb stem.
		Intransitive first-plural and fourth-person forms instead have a following S marker
		<Ref k="bugaeva2012" p="472–474" />;
		<Ref k="nakagawa2024" p="166–174, 210" />. These patterns can be represented schematically:
	</p>
	<table>
		<thead><tr><th>Pattern</th><th>Order</th></tr></thead>
		<tbody>
			<tr><td>Ordinary transitive prefix combination</td><td>A — O — derived stem</td></tr>
			<tr><td>Intransitive with a prefixed S marker</td><td>S — derived stem</td></tr>
			<tr><td>Intransitive first plural or fourth person</td><td>Derived stem — S</td></tr>
		</tbody>
	</table>
	<p>
		The derived stem may already contain applicative, reflexive, reciprocal, incorporated, or
		causative material. The productive causative suffixes include
		<i lang="ain-Latn">-re, -e, -te</i>
		<Ref k="nakagawa2024" p="137, 210" />. Their internal ordering is treated in <Xr
			ch="verb-word-template"
		/>. A person template must also accommodate portmanteaux, zero forms and dialect-specific
		combinations.
	</p>
</S>

<S t="Two prefixes and a portmanteau" id="prefixes">
	<Ex
		m="eci=en=hotuyekar yak pirka p"
		g="2PL.A=1SG.O=call.out.to COND good CONJ"
		tr="You may have called out to me."
		cite="bugaeva2012:473"
		dial="SAR"
		place="Example 15c, from Tamura 1984: 36, as reproduced by Bugaeva"
		note="You is plural; the translation retains Bugaeva's modal wording. The source glosses final p as but."
	/>
	<p>
		This example displays A before O. Saru/Chitose conversational first-to-second-person forms
		instead use <i lang="ain-Latn">eci=</i> for the combined person values. It covers either number
		of subject and either number of object
		<Ref k="bugaeva2012" p="474" />;
		<Ref k="nakagawa2024" p="171" />. A single visible prefix can therefore express information that
		other cells distribute across two prefixes.
	</p>
	<p>
		Saru and Chitose descriptions should still be kept distinct. Nakagawa gives Saru
		<i lang="ain-Latn">a=eci=</i> beside Chitose <i lang="ain-Latn">aci=</i> for fourth-person A
		with second-plural O. Satō's shorter Chitose second-to-first forms coexist in the literature
		with longer reported variants <Ref k="nakagawa2024" p="171, tables 28–29" />;
		<Ref k="sato2008" p="147" />. See <Xr ch="eci-portmanteau-and-second-plural" />.
	</p>
</S>

<S t="Prefix and suffix combinations" id="circumfix">
	<p>
		Other dialects can distribute transitive person marking across both sides of the stem. In
		Nakagawa's Ishikari example, the bear's first-person subject is expressed after the stem, while
		the people it addresses receive the second-plural object prefix
		<Ref k="nakagawa2024" p="174, example 134" />.
	</p>
	<Ex
		m="es=koinkar=an na"
		g="2PL.O=watch.over=1SG.A FIN"
		tr="I will watch over you."
		cite="nakagawa2024:174"
		dial="ISH"
		place="Example 134, from Sunazawa 1983: 58, as reproduced by Nakagawa"
		note="The bear addresses several people. The gloss identifies the subject's value in this interaction."
	/>
	<p>
		Refsing reports a comparable Shizunai first-singular-to-second-plural construction, with
		<i lang="ain-Latn">eci=…=an</i> alternating with <i lang="ain-Latn">an=eci=</i> in her example
		372 <Ref k="refsing1986" p="225" />. That reported alternative belongs to a particular
		interaction cell; it does not establish free prefix–suffix movement throughout the paradigm.
	</p>
</S>

<S t="Number markers and the stem boundary" id="number">
	<p>
		Additional number marking can follow a person-marked verb. Satō reports Chitose
		<i lang="ain-Latn">yaynu-an-pa</i> and rejects the reversed order with
		<i lang="ain-Latn">pa</i> before the person marker for that example
		<Ref k="sato2008" p="104" />. Nakagawa discusses both additional number particles and special
		constructions involving <i lang="ain-Latn">iki</i>
		<Ref k="nakagawa2024" p="155–160" />. These constructions have to be distinguished from lexical
		stem-forming number suffixes; see <Xr ch="suppletive-verbal-number" />.
	</p>
	<p>
		The placement of a person marker is thus useful evidence about structure, but its position does
		not automatically identify the final boundary of every verbal expression.
	</p>
</S>

<S t="Separability and morphological status" id="status">
	<Ex
		m="tane iperusuy ka =an sinki ka =an kor hoyupu=an ayne"
		g="now be.hungry ADD =4.S be.tired ADD =4.S CONJ run=4.S CONJ"
		tr="I ran, hungry and tired, until …"
		cite="nakagawa2024:183"
		dial="CHI"
		place="Example 161"
		note="The source separates =an from its predicate by ka and leaves the sentence continuing."
	/>
	<p>
		Nakagawa calls this “separated person” marking. He reports frequent examples from one Chitose
		speaker and a Saru parallel, and argues that <i lang="ain-Latn">=an</i> has clitic-like
		independence <Ref k="nakagawa2024" p="183, examples 161–163" />. Bugaeva, following Tamura,
		distinguishes word-like <i lang="ain-Latn">=an/=as</i>, clitic-like
		<i lang="ain-Latn">a=/eci=</i>, and more tightly bound prefixes
		<Ref k="bugaeva2012" p="472–473" /> ‹contested›.
	</p>
	<p>
		These analyses use distributional and phonological evidence. The equals sign used throughout
		this grammar marks person boundaries; by itself it does not decide the affix–clitic question
		<Ref k="nakagawa2024" p="59–60" />.
	</p>
</S>
