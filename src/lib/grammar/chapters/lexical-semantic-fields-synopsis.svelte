<S t="Vocabulary as grammatical evidence" id="scope">
	<p>
		A semantic field groups words by meaning, but grammatical behavior must be established
		separately. Body parts illustrate possession; plant terms occur in noun formation and gathering
		predicates; weather expressions show several kinds of predication. The examples below connect
		these fields to constructions treated elsewhere in the grammar. Their meanings follow the cited
		regional descriptions.
	</p>
</S>

<S t="Plants, fruit, and affiliative forms" id="plants">
	<p>
		Satō explains that Chitose <i lang="ain-Latn">epuyke</i>
		can refer to a flower, bud, or fruit according to context. Its affiliative form
		<i lang="ain-Latn">epuykehe</i>
		occurs in this grammatical illustration <Ref k="sato2008" p="19" />.
	</p>
	<Ex
		m="epuyun yakun epuyke-he ka k=e rusuy"
		g="bear.fruit COND fruit-POSS ADD 1SG.A=eat DES"
		tr="If it bears fruit, I also want to eat its fruit."
		cite="sato2008:19"
		dial="CHI"
		note="The source's grammatical example; the fruit's possessor is understood from context."
	/>
	<p>
		This illustrates both a context-dependent lexical meaning and a possessive form without a
		separately stated possessor. The general patterns appear in <Xr
			ch="alienable-inalienable-split"
		/> and
		<Xr ch="affiliative-suffix-morphophonology" />. Gathering vocabulary also cuts across simple
		English equivalents: Satō's <i lang="ain-Latn">kar</i> includes gathering wild edible plants,
		while Chitose <i lang="ain-Latn">ohawkina</i>
		corresponds to <i lang="ain-Latn">pukusakina</i> elsewhere
		<Ref k="sato2008" p="95, 108" />.
	</p>
</S>

<S t="Body parts, objects, and counting" id="body-parts">
	<p>
		Satō describes <i lang="ain-Latn">kema</i> mainly for human legs and
		<i lang="ain-Latn">cikir</i>
		mainly for legs of animals or objects. He explicitly notes an exception in
		<i lang="ain-Latn">cikir-uhosere</i> ‘sit cross-legged’
		<Ref k="sato2008" p="255" />.
	</p>
	<Ex
		m="otcike cikir-i sine-p meske wa isam"
		g="tray leg-POSS one-thing come.off CONJ disappear"
		tr="One leg of the tray came off."
		cite="sato2008:255"
		dial="CHI"
		place="Lesson 33, example 1"
		note="The source explains wa isam as expressing completion with resulting absence. Sinep counts one of the tray's legs."
	/>
	<p>
		The example combines lexical selection, affiliative morphology, a numeral expression, and an
		aspectual construction. Each has its own distribution; the English translation alone cannot
		predict the Ainu noun or verb form. See
		<Xr ch="numeral-classifiers-ordinals-and-quantifier-syntax" />.
	</p>
</S>

<S t="Weather, surroundings, and perceived signs" id="weather">
	<p>
		Satō cautions that <i lang="ain-Latn">maw</i>, often explained as ‘wind’, also occurs with
		meanings closer to a sign, presence, or impression. His examples include indications of rain, a
		person's presence, and dawn <Ref k="sato2008" p="248" />.
	</p>
	<Ex
		m="apto maw an"
		g="rain sign exist.SG"
		tr="There were signs of rain: mist had appeared."
		cite="sato2008:248"
		dial="CHI"
		note="The translation follows Satō's contextual explanation; maw is not translated mechanically as wind."
	/>
	<p>
		Such lexical descriptions complement the grammatical treatment of surroundings and location in
		<Xr ch="relational-and-spatial-nouns" />. Motion terms likewise require their own spatial
		reference: movement landward from water should not automatically be translated as uphill
		movement.
	</p>
</S>

