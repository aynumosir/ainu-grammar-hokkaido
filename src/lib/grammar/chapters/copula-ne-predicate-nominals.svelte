<S t="Identity and classification with ne" id="overview">
	<p>
		The copula <i lang="ain-Latn">ne</i> relates a subject to a nominal complement, expressing
		identity, membership in a class, or becoming something. Satō separates this construction from
		ordinary intransitive and transitive clauses
		<Ref k="sato2008" p="20–21" />. Refsing likewise distinguishes nominal
		<i lang="ain-Latn">ne</i> predication from existential and locative constructions with
		<i lang="ain-Latn">an/oka</i>
		<Ref k="refsing1986" p="145" />.
	</p>
	<Ex
		m="okkayo ku=ne"
		g="man 1SG.A=COP"
		tr="I am a man."
		cite="nakagawa2024:132"
		place="Author's illustration 23"
	/>
	<Ex
		m="toan kur arikinne wen pe ne"
		g="that person extremely bad person COP"
		tr="That person is a very bad person."
		cite="sato2008:20"
		place="Basic copular construction"
	/>
	<p>
		The nominal complement can itself be complex, as <i lang="ain-Latn">arikinne wen pe</i>
		is here. A property verb can predicate directly without the copula. Nakagawa's
		<i lang="ain-Latn">hure</i> covers both “be red” and “become red”; he rejects
		<i lang="ain-Latn">*hure ne</i> for the simple change-of-color reading
		<Ref k="nakagawa2024" p="119" />. See <Xr ch="no-adjective-class-property-verbs" />.
	</p>
</S>

<S t="Subject forms without object indexing" id="person">
	<p>
		The copula uses the A-series subject forms, including those which differ from the ordinary
		intransitive S series, but takes no object person index
		<Ref k="refsing1986" p="145" />; <Ref k="shibatani1990" p="20" />;
		<Ref k="nakagawa2024" p="132" />. A nominal complement therefore differs from an indexed object
		of an ordinary transitive verb.
	</p>
	<p>
		Nakagawa includes the copula as a special two-place type. Satō's later Role and Reference
		Grammar analysis distinguishes its two syntactic positions from a single semantic macrorole, the
		participant indexed on the verb ‹contested›
		<Ref k="nakagawa2024" p="128, 132" />; <Ref k="sato2025a" p="373" />. These classifications
		preserve the same unusual person-marking behavior while analyzing its valency differently.
	</p>
	<p>
		An independent personal pronoun can occur as the complement in a rare construction discussed by
		Satō. The absence of object indexing does not prohibit that nominal category
		<Ref k="sato2025a" p="373" />.
	</p>
	<Ex
		m="eani ne yakun"
		g="2SG COP COND"
		tr="If the person is you, …"
		cite="sato2025a:373"
		dial="CHI"
		place="Opening of example 25"
		note="The source explicitly writes a third-person zero before ne; it is omitted here. The full sentence continues by refusing to make and give something to the addressee."
	/>
</S>

<S t="States, changes, and existence" id="meaning">
	<p>
		Both a state and entry into that state can be expressed with <i lang="ain-Latn">ne</i>.
		Refsing's <i lang="ain-Latn">kotan konnispa ne</i> can mean being or becoming the village chief <Ref
			k="refsing1986"
			p="145"
		/>. Shibatani likewise gives a change reading for his chief example under a broader heading of
		copular sentences
		<Ref k="shibatani1990" p="20" />. A change reading is not confined to a special added inchoative
		marker.
	</p>
	<p>
		Nakagawa distinguishes verbal <i lang="ain-Latn">ne</i> from a translative particle
		<i lang="ain-Latn">ne</i>. The latter can combine with existential
		<i lang="ain-Latn">an</i>. His examples of <i lang="ain-Latn">ne an</i> include both becoming a
		girl in appearance and being a deity, so this sequence is not exclusively inchoative <Ref
			k="nakagawa2024"
			p="300–301"
		/>. He suggests that the particle developed from the copula ‹speculative› <Ref
			k="nakagawa2024"
			p="300"
		/>.
	</p>
</S>

<S t="Negation and clause endings" id="negation">
	<p>
		The ordinary negative copular pattern places <i lang="ain-Latn">somo</i> before
		<i lang="ain-Latn">ne</i>, sometimes with <i lang="ain-Latn">ka</i>. Satō contrasts this with
		the common lexical-verb pattern ending in <i lang="ain-Latn">ka somo ki</i>
		<Ref k="sato2008" p="22" />.
	</p>
	<Ex
		m="tan pe anak seta ka somo ne wa"
		g="this thing TOP dog ADD NEG COP FIN"
		tr="This is not a dog."
		cite="sato2008:22"
		place="Negative copular illustration"
		note="Ka is glossed consistently with its additive form; the whole ka somo ne sequence receives the negative interpretation in the source."
	/>
	<p>
		Satō describes <i lang="ain-Latn">ne ka somo ki</i> as almost absent in use <Ref
			k="sato2008"
			p="22"
		/>. The choice of negative construction is examined in the negation chapters.
	</p>
	<p>
		Endings such as <i lang="ain-Latn">ruwe ne</i> and <i lang="ain-Latn">hawe ne</i>
		have constructional meanings and distributions of their own. Nakagawa notes restrictions on their
		use as ordinary noun modifiers and distinguishes endings without
		<i lang="ain-Latn">ne</i>
		<Ref k="nakagawa2024" p="392–396" />.
		<Xr ch="oblique-adjunct-verbless-clauses" /> compares these with complete utterances consisting of
		a noun phrase and a final particle.
	</p>
</S>

<S t="Attributive ne" id="attributive">
	<p>
		Between two nominal expressions, <i lang="ain-Latn">ne</i> can contribute an attributive
		relation. Refsing gives <i lang="ain-Latn">okkay ne po</i> “boy,”
		<i lang="ain-Latn">mat ne unma</i> “mare,” and <i lang="ain-Latn">sapa ne kur</i>
		“chief,” describing <i lang="ain-Latn">ne</i> as an attributive postposition in this use <Ref
			k="refsing1986"
			p="161"
		/>. Its classification here follows the larger nominal construction, distinct from the finite
		copular examples above.
	</p>
</S>
