<S t="Kusu: purpose and reason" id="kusu">
	<p>
		<i lang="ain-Latn">Kusu</i> relates one situation to another as a purpose, cause, or reason.
		Nakagawa illustrates going out to collect firewood and preparing a boat because the narrator
		wants to pursue someone
		<Ref k="nakagawa2024" p="352–353, examples 670–672" />. The purpose construction also occurs
		without a motion predicate.
	</p>
	<Ex
		m="hamu ku=petpa wa tane k=e kusu ku=kar kor k=an"
		g="ham 1SG.A=cut.into.strips CONJ now 1SG.A=eat PURP 1SG.A=make CONJ 1SG.S=exist.SG"
		tr="I have cut the ham into strips and am now preparing it to eat."
		cite="sato2008:54"
		dial="CHI"
		place="§6.6, kusu example"
	/>
	<p>
		The intended eating is the purpose of the preparation. Tamura also gives setting a trap to catch
		a bear and saving money to go out
		<Ref k="tamura1997" p="50" />. Purpose is understood relative to the action it motivates; a past
		narrative can therefore describe an action performed for a subsequent purpose.
	</p>
</S>

<S t="Reasons with wa kusu and hi kusu" id="reason">
	<p>
		Nakagawa distinguishes reason-giving <i lang="ain-Latn">wa kusu</i>
		and <i lang="ain-Latn">hi kusu</i> from purposive <i lang="ain-Latn">kusu</i>. His
		<i lang="ain-Latn">wa kusu</i>
		example includes a state: the speaker had withheld information because the addressee was still
		small
		<Ref k="nakagawa2024" p="353, example 674" />.
	</p>
	<Ex
		m="e=pon wa kusu a=ye ka somo ki no an=an a p"
		g="2SG.S=be.small CONJ because 4.A=say ADD NEG do CONJ exist.SG=4.S PFV CONJ"
		tr="Because you were still small, I had not told you, but …"
		cite="nakagawa2024:353"
		dial="SAR"
		place="Example 674"
		note="PFV is the conventional gloss used in chapter 111. Nakagawa analyzes a as presenting earlier background in contrast with what follows (pp. 305–306)."
	/>
	<p>
		Tamura associates <i lang="ain-Latn">wa kusu</i> with actual, concrete situations and permits
		<i lang="ain-Latn">hi kusu</i>
		with general topics as well. The latter contains a nominalized clause with
		<i lang="ain-Latn">hi</i>
		<Ref k="tamura1997" p="50" />. Nakagawa reports few examples of <i lang="ain-Latn">hi kusu</i>
		outside Saru and Chitose <Ref k="nakagawa2024" p="353" />.
	</p>
</S>

<S t="Kunine and a desired outcome" id="kunine">
	<p>
		Tamura distinguishes a direct purpose with <i lang="ain-Latn">kusu</i>
		from an indirectly desired outcome with <i lang="ain-Latn">kunine</i>. She says that the
		participants in the two actions are often the same with purpose <i lang="ain-Latn">kusu</i> and
		often different with
		<i lang="ain-Latn">kunine</i>
		<Ref k="tamura1997" p="51" />.
	</p>
	<Ex
		m="na a=nuno kunine itak"
		g="more 4.A=hear.well PURP speak"
		tr="Speak so that people can hear better."
		cite="sato2008:54"
		dial="CHI"
		place="§6.6, kunine example"
	/>
	<p>
		The directive concerns speaking; the desired result concerns the hearers. Refsing similarly
		illustrates making something so that grandmother may eat it, and reports that <i lang="ain-Latn"
			>kunine</i
		>
		is infrequent in her Shizunai sample <Ref k="refsing1986" p="252–253, example 444" />. These
		source descriptions give participant tendencies, without requiring an identical subject relation
		in every purpose clause.
	</p>
	<p>
		Purpose linkage belongs alongside the distinct complement constructions with <i lang="ain-Latn"
			>kuni</i
		>
		described in
		<Xr ch="kuni-complementizer-purpose-complements" />. The prospective
		<i lang="ain-Latn">kusu ne</i>
		construction is treated in
		<Xr ch="epistemic-irrealis-modality" />.
	</p>
</S>

<S t="Independent uses and regional comparison" id="variation">
	<p>
		Nakagawa also permits <i lang="ain-Latn">kusu</i> at the beginning of a new sentence. His
		Chitose example follows a command to bring travellers inside and continues with an intention to
		ask the purpose of their journey
		<Ref k="nakagawa2024" p="353, example 673" />. Independent connective uses are part of the
		broader variation in attachment discussed in <Xr ch="clause-linkage-overview" s="analyses" />.
	</p>
	<p>
		The final vowel of <i lang="ain-Latn">kusu</i> is often devoiced, giving a pronunciation written
		<i lang="ain-Latn">kus</i>
		<Ref k="nakagawa2024" p="352" />. Regional meaning also requires attention. Refsing reports
		causal and purposive <i lang="ain-Latn">kusu</i> in Sakhalin Raychishka through Murasaki's
		description <Ref k="refsing1986" p="252, citing Murasaki 1979:131ff." />. Nakagawa separately
		describes Sakhalin combinations for continuing actions and resulting states, corresponding to
		southern constructions with
		<i lang="ain-Latn">kor</i> and <i lang="ain-Latn">wa</i>
		<Ref k="nakagawa2024" p="344–345, examples 628–629" />.
	</p>
</S>
