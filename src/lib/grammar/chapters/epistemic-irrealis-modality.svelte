<S t="Conjecture with nankor" id="conjecture">
	<p>
		<i lang="ain-Latn">Nankor</i> presents a conjecture. It can concern the future, the present, or
		the past; the event time comes from the surrounding expression and context <Ref
			k="sato2008"
			p="193"
		/>.
	</p>
	<Ex
		m="nisatta anak sirpirka nankor"
		g="tomorrow TOP be.fine.weather probably"
		tr="The weather will probably be fine tomorrow."
		cite="sato2008:193"
		dial="CHI"
		place="§24.2, nankor examples"
	/>
	<Ex
		m="ukuran iyotta mean humi ne nankor"
		g="last.night most be.cold EVID COP probably"
		tr="It was probably coldest last night."
		cite="sato2008:193"
		dial="CHI"
		place="§24.2, nankor examples"
		note="Nankor follows humi ne. This order matters when comparing modal and evidential constructions."
	/>
	<p>
		Descriptions differ in the strength they emphasize. Tamura's Saru account compares
		<i lang="ain-Latn">nankor</i> with a fairly tentative conjecture, while Refsing's Shizunai
		discussion includes a confident reply about someone's arrival
		<Ref k="tamura1960" p="§13, 74 (continuous pagination 350)" /><Ref
			k="refsing1986"
			p="206–207, example 319"
		/>. The form does not supply a fixed numerical probability.
	</p>
</S>

<S t="Intention and prospective events" id="prospective">
	<p>
		<i lang="ain-Latn">Kusu ne</i>, also <i lang="ain-Latn">kus ne</i>, can express an intention or
		a prospective situation. Satō treats the two-word expression as an auxiliary for descriptive
		convenience. His narrative example includes an attempted action that fails, so its use does not
		guarantee that the action occurs
		<Ref k="sato2008" p="191–193" />.
	</p>
	<p>
		Tamura connects its structure with purpose <i lang="ain-Latn">kusu</i> and copular
		<i lang="ain-Latn">ne</i>. Her examples include material that will dry on a stove: a conscious
		planner is not required as grammatical subject
		<Ref k="tamura1997" p="71" />. Indirect directives with this expression are discussed in
		<Xr ch="deontic-necessity" />.
	</p>
	<p>
		Refsing describes Shizunai <i lang="ain-Latn">kusu ki</i> for intention and incipient action,
		with a conscious-agent restriction in her account
		<Ref k="refsing1986" p="206, examples 316–318" />. Related Saru <i lang="ain-Latn">kusu iki</i>
		is also documented by Tamura, including <i lang="ain-Latn">mina rusuy kusu iki</i> ‘be smiling’
		<Ref k="tamura1997" p="71" />. The regional descriptions should be compared without transferring
		every restriction from one to the other.
	</p>
</S>

<S t="Approaching an event" id="onset">
	<p>
		<i lang="ain-Latn">Etokus</i> concerns an event about to occur.
		<i lang="ain-Latn">Etokoyki</i> can have a more concrete preparatory or incipient meaning. Satō
		includes both preparing to eat and flowers beginning to bloom
		<Ref k="sato2008" p="192" />.
	</p>
	<Ex
		m="ni epuy tane epiraske etokoyki kor oka"
		g="tree flower now bloom begin CONJ exist.PL"
		tr="The flowers on the tree are beginning to bloom."
		cite="sato2008:192"
		dial="CHI"
		place="§24.2, etokoyki example"
	/>
	<p>
		<i lang="ain-Latn">Oasi</i> has competing descriptions. Tamura's earlier Saru account emphasizes
		imminent action and tentatively distinguishes the auxiliary from lexical ‘begin’ <Ref
			k="tamura1960"
			p="§11, 73 (continuous pagination 349)"
		/>. Nakagawa argues that the auxiliary presents an event as certain to occur, with imminence
		supplied by context. His bear-deity narrative predicts a marriage and a daughter's future life
		long before the people concerned have entered the story
		<Ref k="nakagawa2024" p="317, example 500" />.
	</p>
</S>

<S t="Seeming, circumlocution, and conditional context" id="other">
	<p>
		Satō gives <i lang="ain-Latn">noyne</i>, alone or with
		<i lang="ain-Latn">an</i>, <i lang="ain-Latn">siran</i>, or
		<i lang="ain-Latn">humas</i>, for ‘seem’ or ‘appear’. His examples concern someone apparently
		awake, expected weather, and a felt prospect of dying
		<Ref k="sato2008" p="194" />. The sensory constructions themselves are introduced in
		<Xr ch="evidential-schema-overview" />.
	</p>
	<p>
		Saru <i lang="ain-Latn">ne manu p</i> often expresses a circumlocution, ‘what is called …’.
		Nakagawa notes that speakers can use it for things they know well; it need not report someone
		else's information
		<Ref k="nakagawa2024" p="309–310" />.
	</p>
	<p>
		Conditional clauses interact with these modal expressions. Satō compares which clause-final
		meanings follow different connectives, while leaving important questions about counterfactual
		expression unresolved
		<Ref k="sato2009" p="51–55" />. The individual constructions provide firmer guidance than a
		single assumed irrealis paradigm or an exceptionless order of all modals and evidentials.
	</p>
</S>
