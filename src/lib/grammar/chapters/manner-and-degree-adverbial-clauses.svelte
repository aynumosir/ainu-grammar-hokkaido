<S t="States and manner with no" id="no">
	<p>
		<i lang="ain-Latn">No</i> links a state or negative situation to the circumstances of another
		event. Its boundary with the adverb-forming suffix
		<i lang="ain-Latn">-no</i> is disputed. Nakagawa discusses
		<i lang="ain-Latn">k=eyam no</i> ‘treating [it] carefully’, whose person marking supports a
		verb-plus-connector analysis, alongside the dictionary's adverb <i lang="ain-Latn">eyamno</i>
		<Ref k="nakagawa2024" p="340–341" />.
	</p>
	<p>
		Lexical formations can have their own changes in form and meaning:
		<i lang="ain-Latn">poronno</i> ‘a lot’ is related to
		<i lang="ain-Latn">poro</i> ‘be large’
		<Ref k="nakagawa2024" p="341" />. See <Xr ch="adverbializer-no" /> for the word-formation analysis.
	</p>
	<p>
		Negative predicates often take <i lang="ain-Latn">no</i>, but Tamura explicitly allows
		<i lang="ain-Latn">wa</i>
		after some negative expressions, including an inability predicate in her example
		<Ref k="tamura1997" p="53–54" />. Neither negativity alone nor participant identity supplies a
		complete rule for choosing the connector.
	</p>
</S>

<S t="Following a model: koraci" id="koraci">
	<p>
		<i lang="ain-Latn">Koraci</i> can take a noun or the content of a clause as a model for a manner
		of acting. Satō gives comparison with a stone and an oral-literature example of something
		happening as a deity had said
		<Ref k="sato2008" p="55" />.
	</p>
	<Ex
		m="a=ye koraci iki"
		g="4.A=say like do"
		tr="Do as I say."
		cite="refsing1986:263"
		dial="SHI"
		place="§14.13.4, example 466"
		note="Refsing prints A ye koraci iki! Person-boundary notation is normalized; the first-person interpretation follows her translation."
	/>
	<p>
		Refsing analyzes predicate-following <i lang="ain-Latn">koraci</i> as a comparative nominalizer,
		while treating its noun-following use as a postposition. Her classification differs from
		accounts organized around connective or adverbial expressions
		<Ref k="refsing1986" p="263–264, §14.13.4" /><Ref k="sato2008" p="55" />.
	</p>
</S>

<S t="Appearance, inference, and pretence" id="appearance">
	<p>
		Satō distinguishes <i lang="ain-Latn">noyne</i>, for inference from appearance or other
		evidence, from <i lang="ain-Latn">pekor</i>, used in his examples for a comparison contrary to
		fact
		<Ref k="sato2008" p="55–56" />.
	</p>
	<Ex
		m="nep ka e=nukar pekor e=yki"
		g="what ADD 2SG.A=see as.if 2SG.S=do"
		tr="You are behaving as if you can see something."
		cite="sato2008:56"
		dial="CHI"
		place="§6.7, first pekor example"
		note="The source specifies that seeing it should actually be impossible. Its yki spelling is retained."
	/>
	<p>
		The descriptions place different limits on the comparison. Tamura says
		<i lang="ain-Latn">pekor</i> and emphatic <i lang="ain-Latn">apekor</i>
		concern resemblance close enough to permit mistaken identification; she excludes using them simply
		for a person's birdlike gait
		<Ref k="tamura1997" p="54" />. Nakagawa describes <i lang="ain-Latn">apekor</i> as often
		introducing a highly unlikely situation, with examples of a person as large as several people
		combined and a child resembling a parent
		<Ref k="nakagawa2024" p="354, examples 680–681" />.
	</p>
	<p>
		Nakagawa lists <i lang="ain-Latn">pekor</i> for Saru and Chitose,
		<i lang="ain-Latn">pokor</i> for Horobetsu, and
		<i lang="ain-Latn">pokon</i> in several other varieties
		<Ref k="nakagawa2024" p="354" />. Refsing treats Shizunai <i lang="ain-Latn">pokon</i> and
		<i lang="ain-Latn">kotom</i> as appearance nominalizers, associating the former especially with
		pretence
		<Ref k="refsing1986" p="262–263, §14.13.3" />.
	</p>
</S>

<S t="Extent and degree" id="degree">
	<p>
		A clause before <i lang="ain-Latn">pak</i> can specify a degree. Satō's illustration describes
		something wet enough to wring out
		<Ref k="sato2008" p="56" />.
	</p>
	<Ex
		m="arikinne a=nunpa pak teyne p ne"
		g="very 4.A=wring extent be.wet NMLZ COP"
		tr="It is so wet that one could wring it out."
		cite="sato2008:56"
		dial="CHI"
		place="§6.7, first pak example"
	/>
	<p>
		Satō also illustrates hyperbolic degree with
		<i lang="ain-Latn">nisor eus kane an ranko</i>, a katsura tree whose top is described as
		reaching the sky
		<Ref k="sato2008" p="54–55" />. The limit need not be a degree: Tamura's
		<i lang="ain-Latn">hapo ek pakno</i> ‘until mother comes’ sets a temporal endpoint <Ref
			k="tamura1997"
			p="32"
		/>.
	</p>
</S>

<S t="Comparison through a relative construction" id="comparison">
	<p>
		Bugaeva analyzes a conventional expression for an unequalled person as relativization of a
		degree adjunct. Her example is
		<i lang="ain-Latn">a=ona [sorekusu pak-no nispa isam] nispa ne</i>, ‘Father was really a rich
		man, with no peers.’ The main subject
		<i lang="ain-Latn">a=ona</i> is outside the brackets; the bracketed clause modifies the
		following <i lang="ain-Latn">nispa</i>
		<Ref k="bugaeva2015" p="53, example 23a, K8106233UP.002" />.
	</p>
	<p>
		In her account, the degree phrase's nominal complement is omitted and
		<i lang="ain-Latn">pak-no</i> remains in the relative clause. She describes the construction as
		partly idiomatic while providing a syntactic analysis <Ref k="bugaeva2015" p="52–58, §5" />.
		This is a specific relative-clause construction, alongside the ordinary degree and manner
		expressions above; see
		<Xr ch="prenominal-gap-relative-clauses" />.
	</p>
</S>
