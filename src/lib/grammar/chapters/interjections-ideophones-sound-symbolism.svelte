<S t="Independent responses and speech within a clause" id="interjections">
	<p>
		Interjections include greetings, replies, calls for attention, and expressions of emotion. They
		can form an utterance on their own, but also occur before or within a larger sentence. Refsing's
		Shizunai examples include a cry of pain after a clause, quoted expressions of gratitude, and
		calls introducing commands
		<Ref k="refsing1986" p="131–133, §12.6.2" />.
	</p>
	<Ex
		m="hokure pikan wa apkas"
		g="hurry be.quick CONJ walk"
		tr="Hurry up, walk quickly!"
		cite="refsing1986:133"
		dial="SHI"
		place="Example 150"
		note="The initial interjection calls for action; the following verbs form the command."
	/>
	<p>
		Nakagawa's inventory distinguishes reunion greetings such as eastern
		<i lang="ain-Latn">issorore</i> and Tokachi
		<i lang="ain-Latn">isiorore</i>. He gives
		<i lang="ain-Latn">ikatay</i> for Shizunai and regions farther east. Other entries distinguish
		<i lang="ain-Latn">e</i>
		for assent from
		<i lang="ain-Latn">ho</i> in response to being called, alongside the dog call
		<i lang="ain-Latn">coco</i>, and exclamatory
		<i lang="ain-Latn">oyoyo</i> ‘frightening!’
		<Ref k="nakagawa2024" p="290–292" />. Social restrictions on particular greetings and calls are
		described in
		<Xr ch="gendered-register-speech" />.
	</p>
</S>

<S t="Interjection morphology and verbal uses" id="verbal-uses">
	<p>
		Nakagawa analyzes several interjections as
		<i lang="ain-Latn">i-</i> plus an intransitive base and a causative suffix. For gratitude, he
		relates
		<i lang="ain-Latn">iyairaykere</i> to
		<i lang="ain-Latn">yairayke</i> ‘be thankful’. The usual verb in his description is the shorter
		base, while the longer form commonly serves as the interjection <Ref
			k="nakagawa2024"
			p="292"
		/>.
	</p>
	<p>
		The distribution nevertheless permits exceptions. Nakagawa quotes Kannari Matsu's postcard with
		a <i lang="ain-Latn">ki</i> construction and, in a second sentence, person marking directly on
		<i lang="ain-Latn">iyayraykere</i>. He also cites a Shizunai prayer with
		<i lang="ain-Latn">ki</i>
		<Ref k="nakagawa2024" p="292–293, examples 399–401" />.
	</p>
	<Ex
		m="iyayraykere ku=ki na"
		g="thank 1SG.A=do FIN"
		tr="I thank you."
		cite="nakagawa2024:292"
		dial="HOR"
		place="Example 399; Ekasi to Fuchi 1983, front matter"
		note="From Kannari Matsu's postcard to Kindaichi Kyōsuke. Nakagawa preserves the postcard's spelling iyayraykere, retained here."
	/>
	<p>
		The relation is different for expressions of surprise.
		<i lang="ain-Latn">Iokunnure</i> and
		<i lang="ain-Latn">iokunure</i> have ordinary verbal uses as well as interjection uses in
		Nakagawa's description
		<Ref k="nakagawa2024" p="293, examples 402–404" />.
	</p>
	<Ex
		m="ceppo utar itak hawe ka a=nu wa iokunnure=an"
		g="fish PL speak voice.POSS ADD 4.A=hear CONJ be.surprised=4.S"
		tr="I also heard the fish speaking and was surprised."
		cite="nakagawa2024:293"
		dial="SAR"
		place="Example 403, citing Chiba University 2015:429"
	/>
</S>

<S t="Sound imitation and mimetic description" id="mimetics">
	<p>
		Sound-imitative and mimetic bases participate in verb formation. Kindaichi and Chiri distinguish
		the two in their account of
		<i lang="ain-Latn">-se</i>: <i lang="ain-Latn">yause</i>
		imitates a cat's meowing and <i lang="ain-Latn">wose</i> a dog's or wolf's howl;
		<i lang="ain-Latn">karkarse</i>
		depicts rolling and
		<i lang="ain-Latn">ninninse</i> flickering. Their
		<i lang="ain-Latn">-ke</i> formations likewise include both types
		<Ref k="kindaichi1936" p="119–120, §§179–180" />.
	</p>
	<p>
		Their earlier discussion contrasts a single occurrence with repeated occurrences in formations
		such as
		<i lang="ain-Latn">humkosanu</i> and
		<i lang="ain-Latn">humrototo</i>. It also lists
		<i lang="ain-Latn">-atki</i> formations, including
		<i lang="ain-Latn">tususatki</i> ‘tremble’
		<Ref k="kindaichi1936" p="111–112, §§154–156" />.
	</p>
	<p>
		Nakagawa's account of <i lang="ain-Latn">-atki</i> expressly preserves Tamura's restriction to a
		limited set of lexical bases. His Ishikari poetic example has causative
		<i lang="ain-Latn">an=copop-atki-re</i> for repeatedly dropping pounded millet into a pot with a
		plopping sound
		<Ref k="nakagawa2024" p="207, example 207, citing Kubodera 1977a:407" />. These descriptions
		support particular formations and their meanings; they do not establish a general sound-to-size
		or sound-to-intensity paradigm.
	</p>
</S>
