<S t="Borrowing alongside new word formation" id="lexical-change">
	<p>
		Published speech can retain recognizably Japanese material. Shibatani reproduces an
		autobiographical passage from Sunasawa Kura containing forms such as <i lang="ain-Latn">gakko</i
		>
		‘school’ and <i lang="ain-Latn">takenoko</i> ‘bamboo shoots’
		<Ref k="shibatani1990" p="86" />. Such a passage documents that speaker's usage; it does not
		supply a loan-frequency estimate for every register.
	</p>
	<p>
		Borrowing also coexists with compound and derived expressions. Ōno describes Asahikawa <i
			lang="ain-Latn">tunas-kampi</i
		>
		‘telegram’, literally ‘fast paper’, and the telephone expression
		<i lang="ain-Latn">a-e-y-nu-p</i>. His analysis relates the latter to hearing voices or sounds.
		He discusses these alongside more recent terminology in language revitalization
		<Ref k="ono2022" p="§8.9" />. These examples show continued lexical adaptation across different
		periods and regions.
	</p>
</S>
