<S t="Historical dating and uncertain comparisons" id="history">
	<p>
		Janhunen uses forms including <i lang="ain-Latn">sippo</i>
		and <i lang="ain-Latn">pasuy</i> in a proposed chronology of Japanese contact. This is a
		historical argument whose assumptions must be evaluated with the forms themselves
		<Ref k="janhunen2022" p="§3(3c)" />. Satō notes that <i lang="ain-Latn">pasuy</i> lacks the Old
		Japanese vowel-class diagnostic discussed for
		<i lang="ain-Latn">kamuy</i>. He also treats similarities such as <i lang="ain-Latn">sake</i> as
		comparative questions without settling every direction of transmission
		<Ref k="sato2008" p="8, §1.6" />.
	</p>
