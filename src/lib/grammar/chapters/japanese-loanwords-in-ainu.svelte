<S t="Recognizing a borrowing" id="borrowing">
	<p>
		Japanese is a major identified source of borrowed vocabulary in Southern Hokkaido Ainu. Bugaeva
		lists
		<i lang="ain-Latn">sippo</i> ‘salt’,
		<i lang="ain-Latn">umma</i> ‘horse’,
		<i lang="ain-Latn">tuki</i> ‘sake cup’, and
		<i lang="ain-Latn">kampi</i> ‘paper’, comparing Japanese
		<i>shio, uma, saka-zuki, kami</i>
		<Ref k="bugaeva2012" p="498, §15.5" />. The identification depends on historical and lexical
		comparison; length or unfamiliar structure alone is insufficient.
	</p>
	<p>
		Nakagawa observes that many Ainu roots are one or two syllables, while longer independent forms
		often involve derivation, compounding, or borrowing. He includes <i lang="ain-Latn">tampaku</i>
		‘tobacco’ among loans. The alternatives in this account prevent syllable count from becoming an automatic
		test of origin
		<Ref k="nakagawa2024" p="47, §1.3.3" />.
	</p>
</S>

<S t="Adaptation and the donor pronunciation" id="phonology">
	<p>
		A borrowed word reflects the pronunciation available at the time and place of contact. Alonso
		compares Saru
		<i lang="ain-Latn">cikenki</i> ‘matches’ with Japanese
		<i>tsukegi</i>, and <i lang="ain-Latn">antuki</i> ‘adzuki beans’ with <i>azuki</i>. His
		discussion considers regional and older Japanese features, including prenasalized voiced
		consonants
		<Ref k="alonso2022" p="§1" />.
	</p>
	<p>
		Satō's Chitose commentary makes the same historical distinction for
		<i lang="ain-Latn">sirokane</i> ‘silver’ and
		<i lang="ain-Latn">konkane</i> ‘gold’. He connects the first with an older unvoiced Japanese
		<i>shirokane</i>, and discusses nasal insertion in the second alongside voiced <i>kogane</i>
		<Ref k="sato2008" p="296, 301" />.
	</p>
