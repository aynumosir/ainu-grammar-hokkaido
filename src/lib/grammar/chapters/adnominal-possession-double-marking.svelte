	<p>
		The affiliative <i lang="ain-Latn">santekehe</i> relates the descendants to Ikuresuye. No
		pronounced third-person prefix is needed. The noun is independently attested in Tamura's Saru
		dictionary
		<Ref k="tamura1996" p="s.v. santeke(he)" />.
	</p>
</S>

<S t="Marking on the possessed noun" id="head-marking">
	<p>
		In <i lang="ain-Latn">ku=tekehe</i> “my hand,” the person prefix and affiliative morphology
		occur on the possessed noun. This is head marking: two morphemes on that noun do not by
		themselves constitute marking on both the head and dependent. Chudá contrasts this pattern with
		possession expressed through <i lang="ain-Latn">kor</i>, as well as with unmarked noun sequences
		<Ref k="huber2025" p="247–248, example 8" />.
	</p>
	<p>
		Person forms may stand without an overt possessor phrase. Satō also describes possessors
		separated from their affiliative nouns, including a topic-marked possessor, and argues for a
		looser syntactic relation in such examples
		<Ref k="sato2008" p="156–157" /> ‹contested›. An ordinary adjacent possessive expression and a discourse-linked
		possessor need not receive the same constituent analysis. See <Xr ch="noun-phrase-structure" />.
	</p>
</S>

<S t="Kor with an affiliative noun" id="double-marking">
	<p>
		The pattern called <em>double marking</em> by Chudá combines
		<i lang="ain-Latn">kor</i> with an affiliative possessum:
		<i lang="ain-Latn">a=kor kotanu</i>
		<Ref k="huber2025" p="247–248" />. Satō records this combination in oral literature, and
		Nakagawa gives both village and house in a Chitose verse example
		<Ref k="sato2008" p="152" />;
		<Ref k="nakagawa2024" p="221, example 251" />.
	</p>
	<Ex
		m="a=kor kotan-u"
		g="4.A=have village-POSS"
		tr="my village"
		cite="nakagawa2024:221, example 251"
		dial="CHI"
		note="Phrase excerpt from a rupaye heroic narrative; the surrounding plea asks to be carried home."
	/>
	<p>
		Historical descriptions also record combinations of
		<i lang="ain-Latn">kor</i> and possessed kinship nouns. Kindaichi and Chiri give such forms as
		<i lang="ain-Latn">akor amachihi</i>
		in their original spelling <Ref k="kindaichi1936" p="26–27" />. These examples establish the
		combination's occurrence in particular materials. They do not license unrestricted doubling with
		every noun.
	</p>
</S>

<S t="Possessive classifier verbs" id="classifier-verbs">
	<p>
		Bugaeva, Nichols and Bickel analyze <i lang="ain-Latn">kor</i> as a general possessive
		classifier verb within a relative clause. Other verbs can specify the relation more closely:
		their cited examples include
		<i lang="ain-Latn">un</i> with a house, <i lang="ain-Latn">mut</i>
		with a sword that someone wears, and <i lang="ain-Latn">resu</i> or
		<i lang="ain-Latn">reska</i> with an animal someone raises
		<Ref k="bugaeva2021poss" p="55–57, examples 21–24" />. The examples come from several
		dictionaries and narrative collections, identified individually in that article.
	</p>
	<p>
		This is the article's sense of <em>appositive possession</em>: a classifier construction
		expresses the relationship to the following nominal head. It is distinct from ordinary
		apposition between a person's name and title. Kindaichi and Chiri illustrate the latter contrast
		with
		<i lang="ain-Latn">Risa unarpe ek</i> “Aunt Risa comes” and
		<i lang="ain-Latn">Risa unarpehe ek</i> “Risa's aunt comes”
		<Ref k="kindaichi1936" p="25" />.
	</p>
</S>

<S t="Verbal syntax and alternative analyses" id="kor-analysis">
	<p>
		The relative-clause analysis has syntactic support. Bugaeva, Nichols and Bickel show possessive <i
			lang="ain-Latn">kor</i
		>
		with plurality and perfectivity, and show that possessive relative clauses can be combined with
		further relative clauses. Their example from Tamura (1989: 64) uses
		<i lang="ain-Latn">a-kor a kotan</i> for a formerly possessed village
		<Ref k="bugaeva2021poss" p="58, examples 30–33" />.
	</p>
	<p>
		Refsing instead groups attributive <i lang="ain-Latn">kor</i>,
		<i lang="ain-Latn">un</i>, and <i lang="ain-Latn">ne</i> with postpositions in her Shizunai
		description
		<Ref k="refsing1986" p="160–161, §14.3" /> ‹contested›. The difference concerns the grammatical analysis
		of these attributive uses.
	</p>
	<p>
		Bugaeva, Nichols and Bickel propose a historical expansion of general
		<i lang="ain-Latn">kor</i> at the expense of more specific classifiers, and a tendency toward
		cliticization in some third-person constructions
		<Ref k="bugaeva2021poss" p="57–59" /> ‹speculative›. Their account retains the construction's verbal
		properties; it does not identify <i lang="ain-Latn">kor</i> with an affiliative noun suffix.
	</p>
</S>

<S t="Nested relations" id="nested-possession">
	<p>
		Possessive expressions can themselves contain possessed nouns. Nakagawa's Saru
		<i lang="ain-Latn">a=yupihi turesihi</i> refers to the younger sister of the man whom the
		narrator calls his elder brother
		<Ref k="nakagawa2024" p="224, example 259" />. Each kinship noun contributes its own relation.
		The narrative context determines the social reference of “elder brother”; see <Xr
			ch="kinship-honorific-possession"
		/>.
	</p>
	<p>
		A further possibility is for the possessor to be represented in the clause's verbal grammar when
		a possessed noun is incorporated. That construction has different diagnostics, discussed in
		<Xr ch="external-possession-possessor-raising" />.
	</p>
</S>
