<S t="Possessors within nominal expressions" id="adnominal-possession">
	<p>
		Adnominal possession identifies something through its relation to a possessor. Ainu expresses
		this relation through affiliative noun forms and through constructions with <i lang="ain-Latn"
			>kor</i
		>
		“have.” An overt possessor normally precedes the possessed noun or the verb that introduces it
		<Ref k="nakagawa2024" p="218–221" />;
		<Ref k="bugaeva2021poss" p="52–55" />. The lexical and semantic choices are treated in <Xr
			ch="alienable-inalienable-split"
		/>.
	</p>
