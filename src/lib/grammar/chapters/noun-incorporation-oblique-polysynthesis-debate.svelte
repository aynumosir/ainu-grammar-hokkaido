<S t="Incorporation, lexical units, and complex verbs" id="overview">
	<p>
		Ainu has several ways of combining a noun with verbal material. Morphological noun incorporation
		places a nominal stem inside a verb. Quasi-incorporation, in Satō's account, forms a
		conventional lexical unit while retaining the structure of a phrase. Polysynthesis is the
		broader capacity to express substantial clause-level content in a complex word <Ref
			k="satoni2022"
			p="§§1–2, 4, 6"
		/>;
		<Ref k="bugaeva2014polysynthesis" />.
	</p>
	<p>
		The distinctions matter for argument structure. Simple object incorporation often produces an
		intransitive, but incorporation can also leave a transitive frame. Related noun–verb expressions
		may hemselves have one-word and two-word realizations
		<Ref k="shibatani1990" p="63–64, 68–69" />;
		<Ref k="nakagawa2024" p="495–498" />. The basic object and subject patterns are treated in
		<Xr ch="noun-incorporation-object" /> and
		<Xr ch="noun-incorporation-subject-possessor-stranding" />.
	</p>
</S>

<S t="Incorporation after an applicative" id="correspondences">
	<p>
		An applicative can make an otherwise oblique participant an object, which can then incorporate.
		Shibatani illustrates this with the comitative expression “with its bones.” In his analysis, the
		applicative <i lang="ain-Latn">ko-</i> introduces the bones as an object; incorporating that
		noun leaves the fish as an external object <Ref k="shibatani1990" p="67–69" />.
	</p>
	<Ex
		id="pone-ko-kuykuy"
		m="nea cep a=pone-ko-kuykuy"
		g="that fish 4.A=bone-APPL-bite"
		tr="I bit the fish together with its bones."
		cite="shibatani1990:68, example 122c"
		note="Published illustration. Shibatani interprets a- as literary first person; it is represented with the fourth-series label and an equals sign here. This illustration has no specific dialect label in the source."
	/>
	<p>
		His three-stage comparison begins with
		<i lang="ain-Latn">nea cep pone tura a-kuykuy</i>, then gives
		<i lang="ain-Latn">nea cep pone a-ko-kuykuy</i>, followed by the incorporated form above.
		Shibatani explicitly identifies the middle stage as an artificially constructed illustration
		following Chiri <Ref k="shibatani1990" p="68, example 122" />. It displays the proposed
		derivation rather than three successive utterances from a narrative.
	</p>
	<p>
		Instrumental incorporation follows a comparable pattern in a literary example from <i
			>Kutune Shirka / Itadorimaru</i
		>:
	</p>
	<Ex
		m="ratki apa a=sapa-e-puni"
		g="hang door 4.A=head-APPL-raise"
		tr="I lifted the suspended door with my head."
		cite="shibatani1990:68, example 121b"
		note="Shibatani's Itadori label identifies Kindaichi's 1931 version of the literary text. The incorporated head supplies the instrument; the door remains external."
	/>
	<p>
		A semantic location need not begin as an oblique. Satō's
		<i lang="ain-Latn">kane k-φ-upsor-omare</i>, “I put money into my bosom,” incorporates a
		location already selected by
		<i lang="ain-Latn">omare</i>. No additional applicative occurs
		<Ref k="sato2023b" p="47, §4.2, example 13" />. The relevant distinction is between an available
		argument and an otherwise peripheral participant.
	</p>
</S>

<S t="Affix order and multiple incorporated elements" id="adverb-stacking">
	<p>
		When an applicative and incorporation concern the same noun, many forms place the noun outside
		the applicative, as in
		<i lang="ain-Latn">sapa-e-puni</i>. When they concern different nouns, the applicative can occur
		outside an incorporated patient. Shibatani gives <i lang="ain-Latn">a-ko-tam-etaye</i>, with
		incorporated “sword” and a separate location related through
		<i lang="ain-Latn">ko-</i>
		<Ref k="shibatani1990" p="68–70, examples 121, 125–127" />.
	</p>
	<p>
		He uses these orders as evidence for successive derivations, but also reports Chiri's
		counterexamples, including
		<i lang="ain-Latn">ni o-pici</i> beside
		<i lang="ain-Latn">o-ni-pici</i> “fall from a tree.” He considers both an ordering irregularity
		and a different identity for the prefix. He found no corresponding examples in his
		<i>Itadorimaru</i> material
		<Ref k="shibatani1990" p="70–71, example 128" />. The order of noun and prefix therefore needs
		construction-specific evidence.
	</p>
	<p>
		Descriptions also differ over the number of nouns a verb may incorporate. Shibatani states a
		one-noun limit while allowing a noun and an adverbial element together. Nakagawa explicitly
		records rare two-object formations, including
		<i lang="ain-Latn">cep-ya-o-kuta</i>, “dump fish onto shore,” and
		<i lang="ain-Latn">itak-mak-kus-te</i>, “use hidden words,” literally sending words behind
		<Ref k="shibatani1990" p="72" />;
		<Ref k="nakagawa2024" p="488–489, §19.2.3" /> ‹contested›.
	</p>
	<p>
		Modifier incorporation has further lexical restrictions. Nakagawa compares <i lang="ain-Latn"
			>pirka-no a=ipere</i
		>
		with
		<i lang="ain-Latn">a=pirka-ipere</i> for feeding well or sufficiently <Ref
			k="nakagawa2024"
			p="484"
		/>. The status of the first element and the distribution of
		<i lang="ain-Latn">-no</i> are treated in
		<Xr ch="adverbial-incorporation" />.
	</p>
</S>

<S t="Tamura's 連他動詞 and Satō's quasi-incorporation" id="markedness-qi">
	<p>
		Tamura describes <span lang="ja">連他動詞</span> as adjacent words that function together as a
		verbal unit. Many combine a locative or body-part noun with a transitive verb. The noun carries
		O-series person marking and the verb carries A-series marking. Her dictionary independently
		classifies
		<i lang="ain-Latn">par(o) oyki</i> “feed/support” and
		<i lang="ain-Latn">aske uk</i> “invite” this way
		<Ref k="tamura1997" p="15, §C.4" />;
		<Ref k="tamura1996" p="entries par(o) oyki and aske uk" />.
	</p>
	<p>
		Satō calls the phrasal pattern <em>quasi-incorporation</em>. He also connects it with the older
		“third class of verbs” and Nakagawa's <span lang="ja">連動詞</span>. The crucial distinction is
		between morphological words and lexical units: a conventional noun–verb expression can be two
		morphological words while functioning as one lexical word <Ref k="sato2016" p="89–90" />;
		<Ref k="sato2021" p="89–94" />.
	</p>
	<Ex
		m="en=par a=oyki"
		g="1SG.O=mouth 4.A=care.for"
		tr="People support me."
		cite="sato2021:90, example 21"
		dial="CHI"
		note="The source's hyphens at person boundaries are normalized to equals signs. O marking belongs to the noun, while impersonal A marking belongs to the verb."
	/>
	<p>
		Compare ordinary <i lang="ain-Latn">ku-paro</i> “my mouth.” Satō explains the O-series marker
		and basic
		<i lang="ain-Latn">par</i> by treating the mouth's possessor as the object of the lexical unit
		“support.” The structure retains a noun–verb boundary, with restrictions on what can intervene
		<Ref k="sato2016" p="89–90" />;
		<Ref k="sato2021" p="90–94" />.
	</p>
	<p>
		His contrast concerns the kind of possessor marking. The rejected
		<i lang="ain-Latn">*a-i-par-oyki</i> has inflectional
		<i lang="ain-Latn">i-</i> referring to a literary first-person possessor; the accepted
		alternative is
		<i lang="ain-Latn">i-par a-oyki</i>. Derivational
		<i lang="ain-Latn">i-par-oyki</i> “support someone” and
		<i lang="ain-Latn">yay-par-oyki</i> “support oneself” can form one morphological word. The two
		uses of
		<i lang="ain-Latn">i-</i> must remain distinct
		<Ref k="sato2016" p="89, examples 8–9" />;
		<Ref k="satoni2022" p="§4, examples 25–29" />.
	</p>
	<p>
		Basic noun form is not an exceptionless requirement across all descriptions. Tamura gives both
		<i lang="ain-Latn">e-tom k-osma</i> “I bumped into you” and
		<i lang="ain-Latn">eci-tomó k-osma</i> “I bumped into you (plural),” with long
		<i lang="ain-Latn">tomó</i>
		in the second form <Ref k="tamura1997" p="15" />. Satō's own lexical analysis includes a phrase
		with an external uncle-possessor and affiliative
		<i lang="ain-Latn">paro</i>, meaning “I intend to support my uncle” <Ref
			k="sato2021"
			p="91, example 23; 94"
		/>.
	</p>
</S>

<S t="Nakagawa's one-word and two-word realizations" id="rendoosi">
	<p>
		Nakagawa's category <span lang="ja">連動詞</span> includes both one-word and two-word
		realizations. His person-marked examples make the difference visible. He analyzes Ishikari
		<i lang="ain-Latn">e=kaopas=an</i> and Shizunai
		<i lang="ain-Latn">an=e=kaopas</i>, both with first-person narrative reference to helping the
		addressee, as single verb words. The person markers cannot be assigned to a separate noun and an
		independently inflected verb in those forms
		<Ref k="nakagawa2024" p="495, examples 1133–1134" />.
	</p>
	<p>
		His Saru <i lang="ain-Latn">e=ka a=opas pe ne na</i>
		instead places person marking separately on the noun and verb. He also gives two-word forms with long
		<i lang="ain-Latn">kasi</i>
		<Ref k="nakagawa2024" p="496, examples 1136–1138" />. This account describes a wider
		morphological range than the core two-word quasi-incorporation pattern ‹contested›.
	</p>
	<p>
		Nakagawa emphasizes that one-word members can remain transitive. He relates their behavior to
		the special status of the nominal element and its O-series marking
		<Ref k="nakagawa2024" p="496–498" />. An expression's conventional meaning, its morphological
		boundaries, and its argument frame are separate parts of the comparison.
	</p>
</S>

<S t="The extension to or plus a case particle" id="locative-quasi-incorporation">
	<p>
		Satō's 2021 proposal extends quasi-incorporation beyond verbal phrases to <i lang="ain-Latn"
			>or ta</i
		>
		and related locative combinations. He compares <i lang="ain-Latn">en-or ta</i>
		“at my place” with <i lang="ain-Latn">en-par oyki</i>: both have O-series person marking on a
		basic noun form. He proposes that a two-word locative phrase can constitute one lexical unit
		<Ref k="sato2021" p="91–94" /> ‹speculative›.
	</p>
	<p>
		The analysis incorporates the usual contrast between
		<i lang="ain-Latn">cise or ta</i> “at the house” and
		<i lang="ain-Latn">unarpe oro ta</i> “at aunt's place,” while acknowledging animate uses of
		basic
		<i lang="ain-Latn">or</i> and an inanimate phrase with
		<i lang="ain-Latn">oro</i>. Satō also identifies an unresolved structural difference between the
		locative and verbal patterns
		<Ref k="sato2021" p="85–96" />. The distribution and explanatory limits are developed in
		<Xr ch="relational-and-spatial-nouns" s="quasi-incorporation" />.
	</p>
</S>

<S t="Diagnostics of word boundaries" id="word-boundary">
	<p>
		Person marking often distinguishes incorporation from an ordinary phrase: Nakagawa contrasts
		<i lang="ain-Latn">cep a=koyki</i> with
		<i lang="ain-Latn">cepkoyki=an</i>. Third-person forms without overt markers can leave the same
		distinction ambiguous
		<Ref k="nakagawa2024" p="482–483" />.
	</p>
	<p>
		Derivational morphology sometimes supplies further evidence, but it too requires analysis.
		Nakagawa contrasts a complex verb such as <i lang="ain-Latn">yay-kotan-esina</i> with a phrase
		in which <i lang="ain-Latn">yaykotan</i> is itself a noun
		<Ref k="nakagawa2024" p="483" />. A prefix's presence alone cannot distinguish those structures.
	</p>
	<p>
		Accent evidence also has to be tied to the formation described. Nakagawa leaves a general
		accentual diagnostic unresolved in this discussion, while Satō discusses accent changes in
		particular incorporating forms <Ref k="nakagawa2024" p="482" />;
		<Ref k="satoni2022" p="§2" />. Spacing in a transcription records an analysis; it cannot by
		itself decide every disputed boundary.
	</p>
</S>

<S t="Competing accounts of incorporation" id="debate">
	<p>
		Shibatani argues that both semantic role and grammatical relation are needed to describe Ainu
		incorporation. His criticism of Mithun's functional account is that Ainu's applicative-derived
		objects require grammatical-relation information. He explicitly acknowledges that Mithun
		discusses incorporated instruments and locations across languages
		<Ref k="shibatani1988" p="210–211" />;
		<Ref k="shibatani1990" p="60–62, discussing Mithun 1984" />;
		<Ref k="mithun1984" />.
	</p>
	<p>
		He also challenges predictions of Baker's syntactic incorporation account. In his presentation,
		the problem concerns abstract Case assignment to an applicative object with an unaccusative
		base. His Ainu examples show applicatives with predicates of existence or state <Ref
			k="shibatani1990"
			p="66–67, discussing Baker 1988"
		/>;
		<Ref k="baker1988" />. The criticism belongs to Shibatani's comparison of those theories; Ainu
		nouns do not overtly display the abstract Case at issue ‹contested›.
	</p>
	<p>
		Later descriptions expand the empirical domain. Satō's natural-force transitive-subject
		incorporation goes beyond the intransitive-subject and transitive-object domain of Shibatani's
		earlier formulation <Ref k="sato2016" p="83–88" />;
		<Ref k="satoni2022" p="§§1, 3" />. Satō's later argument-slot account allows nominal stems,
		nominal derivational prefixes, and person markers to satisfy a verb's argument requirements
		without deriving every incorporated noun by movement from an external phrase
		<Ref k="sato2023b" p="§§4.1–4.2" /> ‹contested›. His “slots” describe argument capacity, not successive
		positions in an affix template.
	</p>
</S>

<S t="An accessibility proposal and its limits" id="accessibility">
	<p>
		Satō proposes a hierarchy from ordinary object incorporation through natural-force and
		possessor-related subject incorporation to natural-force transitive-subject incorporation. He
		relates the restrictions to backgrounding, reflexive interpretation, and ambiguity, with
		quasi-incorporation supplying an alternative in the inflectionally marked possessor-object case
		<Ref k="sato2016" p="87–90" />;
		<Ref k="satoni2022" p="§§4–6" /> ‹speculative›.
	</p>
	<p>
		Satō reports the following distribution in his Chitose material, drawn from approximately 130
		hours of recordings with Shirasawa Nabe <Ref k="sato2016" p="83 n. 1; 88, table 2" />.
	</p>
	<table>
		<thead><tr><th>Incorporated argument</th><th>Reported share</th></tr></thead>
		<tbody>
			<tr><td>Object</td><td>85.9%</td></tr>
			<tr><td>Intransitive subject: natural force or phenomenon</td><td>6.8%</td></tr>
			<tr><td>Intransitive subject: noun requiring a possessor</td><td>5.6%</td></tr>
			<tr><td>Transitive subject: natural force or phenomenon</td><td>1.7%</td></tr>
		</tbody>
	</table>
	<p>
		His proposed penalty scores are an explanation of that distribution. The 2022 presentation
		repeats these percentages but changes some of the numerical weights
		<Ref k="sato2016" p="88, table 2" />; <Ref k="satoni2022" p="§6, table 1" />. The hierarchy
		classifies grammatical relations and noun types; Mithun's four functional types concern
		different properties of incorporation <Ref k="satoni2022" p="§1" />.
	</p>
	<p>
		Specificity and lexical restrictions require further qualifications. Yoshida's small comparison
		of Chitose and Sakhalin texts examines contextually specific incorporated nouns and questions
		whether low agentivity alone is sufficient
		<Ref k="yoshida2013" p="169–174" />. Nakagawa also records restricted complex nominal material
		in incorporating forms <Ref k="nakagawa2024" p="487–488, 497" />. These are distinct issues from
		the person-marking restriction that motivates Satō's core quasi-incorporation comparison.
	</p>
</S>

<S t="Polysynthesis as a broader description" id="polysynthesis">
	<p>
		Bugaeva describes Ainu as polysynthetic because a complex verb can express content that other
		languages distribute across a whole clause. Her literary example combines an incorporated noun,
		a verbal modifier, two reflexive elements, and two applicatives <Ref
			k="bugaeva2014polysynthesis"
			p="example 1, from Chiri 1974 [1936]: 169"
		/>. An inventory of such resources does not imply that their individual maxima all occur in one
		verb.
	</p>
	<p>
		Complex affixal words need not contain an incorporated noun. Nakagawa gives <i lang="ain-Latn"
			>a=e=si-ko-ek-te</i
		>, “I made you come to me,” as an example of verbal complexity
		<Ref k="nakagawa2024" p="481" />. Bugaeva's broad characterization also leaves open differences
		from Baker's formal polysynthesis framework, which her abstract explicitly notes <Ref
			k="bugaeva2014polysynthesis"
		/>;
		<Ref k="baker1996" /> ‹contested›.
	</p>
</S>
