<S t="The modifying clause precedes its head" id="basic-pattern">
	<p>
		An Ainu relative clause precedes the noun it identifies. The head noun corresponds to a
		participant or relation within the modifying clause. Bugaeva describes the construction as an
		NP-gap or zero-anaphora strategy: the head is not repeated as an ordinary noun phrase inside the
		relative clause, while material expressing its grammatical relation can remain
		<Ref k="bugaeva2015" p="46–48" />.
	</p>
	<Ex
		m="cise soy pak-no arki utar"
		g="house outside until-ADV come.PL people"
		tr="The people who came up to the doorway"
		cite="bugaeva2015:47"
		dial="CHI"
		place="Excerpt from example 9, citing Bugaeva 2004:95"
		note="Utar is the relative head and the subject of arki. The complete published sentence continues by discussing letting these people enter."
	/>
	<p>
		The verb keeps its ordinary morphology. A special relative pronoun is unnecessary. Heads include
		ordinary nouns and general forms such as <i lang="ain-Latn">kur</i>
		‘person’, <i lang="ain-Latn">utar</i> ‘people’, and <i lang="ain-Latn">p/pe</i>
		‘thing, person’ <Ref k="bugaeva2015" p="47" />.
	</p>
</S>

<S t="Arguments and remaining roles" id="arguments">
	<p>
		Subjects and objects can serve as relative heads. Nakagawa illustrates an object relation with <i
			lang="ain-Latn">aynu kar sake</i
		>
		‘sake that people make’: ‘people’ supplies the actor, and the head ‘sake’ supplies what is made.
		In his arity analysis, the modifying clause <i lang="ain-Latn">aynu kar</i> has one remaining
		argument role
		<Ref k="nakagawa2024" p="503–504" />. This calculation concerns the clause before the head.
	</p>
	<p>
		Applicatives allow an applied object to become the head. Bugaeva's
		<i lang="ain-Latn">a=e-hotke usi</i> refers to a place to lie down, while
		<i lang="ain-Latn">kampi a=e-pakasnu hekattar</i> refers to children taught to read and write.
		In the latter, <i lang="ain-Latn">e-</i> adds the content being taught to
		<i lang="ain-Latn">pakasnu</i> ‘teach someone’; the children are its recipients
		<Ref k="bugaeva2015" p="48, examples 12–13" />. Both recipient and theme relativization are
		represented in her three-place-verb examples. The number of person markers on the verb does not
		determine the number of accessible roles.
	</p>
</S>

<S t="Retained instrumental and comitative relations" id="retention">
	<p>
		An oblique relative can retain a postposition or postpositional adverb. Applicativization is
		another available construction, but it is not required for every oblique head <Ref
			k="bugaeva2015"
			p="48–49"
		/>.
	</p>
	<Ex
		m="tura-no ku=yupo kamuy cotca acapo"
		g="with-ADV 1SG.POSS=elder.brother bear shoot uncle"
		tr="The uncle with whom my elder brother shot the bear"
		cite="bugaeva2015:49"
		dial="CHI"
		place="Example 15, citing Bugaeva 2004:96"
		note="Tura-no expresses accompaniment inside the relative clause. Acapo is the lexical head ‘uncle’; its initial a is not segmented as a person marker."
	/>
	<p>
		Instrumental <i lang="ain-Latn">ani</i> is retained in the regular pattern described by
		Nakagawa, including the drinking-vessel example in <Xr ch="nominalization-p-pe" />
		<Ref k="nakagawa2024" p="504–506" />. Satō nevertheless records
		<i lang="ain-Latn">ku=yupo kamuy tukan teppo</i> ‘the gun with which my elder brother shot a
		bear’ without <i lang="ain-Latn">ani</i>. He regards this as an unusual pattern and tentatively
		suggests Japanese influence <Ref k="sato2008" p="170–171" />. His contact explanation remains a
		proposal.
	</p>
</S>

<S t="Places and possessors" id="places-possessors">
	<p>
		A locative relation commonly retains both a relational noun and a postposition. Satō's Chitose
		illustration uses the affiliative form <i lang="ain-Latn">oro</i>
		when the head follows the clause <Ref k="sato2008" p="171" />.
	</p>
	<Ex
		m="oro ta ku=yamuk cikuni"
		g="place.POSS LOC 1SG.S=gather.chestnuts tree"
		tr="The tree where I gathered chestnuts"
		cite="sato2008:171"
		dial="CHI"
		place="Author's relative-clause illustration"
	/>
	<p>
		Satō explicitly notes that Shizunai and some other varieties retain
		<i lang="ain-Latn">ot ta</i> in this pattern <Ref k="sato2008" p="172" />. Bugaeva calls
		retained <i lang="ain-Latn">or-o</i> resumptive relational material
		<Ref k="bugaeva2015" p="50" />. This is compatible with the absence of a separate resumptive
		personal pronoun.
	</p>
	<Ex
		m="cikir-ihi tanne kikir"
		g="leg-POSS be.long insect"
		tr="The insect whose legs are long"
		cite="bugaeva2015:49"
		dial="SAR"
		place="Example 17a, quoting Tamura 2000:189"
		note="The affiliative suffix on ‘leg’ preserves the relation to the head ‘insect’."
	/>
	<p>
		Bugaeva analyzes inalienable possessors as accessible through this retained possessive
		morphology. She treats alienable possessors differently because the relevant base possessive
		construction already contains a relative clause, invoking an island restriction
		<Ref k="bugaeva2015" p="49, note 10" />.
	</p>
</S>

<S t="Accessibility and the comparison equivalent" id="accessibility">
	<p>
		Bugaeva's hierarchy survey distinguishes an unattested relative on the standard of a comparison
		proper from an attested equivalent built with degree/allative
		<i lang="ain-Latn">pak(-no)</i> and an existential or negative existential. This construction
		can express a person with no equal in some quality <Ref k="bugaeva2015" p="52–56" />. Its heads
		include general <i lang="ain-Latn">kur</i> and <i lang="ain-Latn">p/pe</i>, as well as nouns
		such as <i lang="ain-Latn">nispa</i> ‘wealthy man’.
	</p>
	<p>
		The survey's reported gaps are evidence about that study's sample. For example, its absence of a
		three-place-verb actor relative is reported as “not attested”
		<Ref k="bugaeva2015" p="47" />. Such observations should remain separate from an explicit
		grammatical rejection of a construction.
	</p>
</S>
