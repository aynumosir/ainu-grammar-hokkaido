<S t="An unspecified object and a changed argument frame" id="overview">
	<p>
		Derivational <i lang="ain-Latn">i-</i> forms verbs whose object is left unspecified or
		understood as part of a conventional activity. A two-place verb commonly becomes one-place:
		<i lang="ain-Latn">huraye</i> “wash something” yields
		<i lang="ain-Latn">i-huraye</i> “do laundry.” Nakagawa describes the prefix through its
		generalized nominal meaning and its reduction of arity. Bugaeva and Kobayashi use the term
		<strong>antipassive</strong>, emphasizing object suppression, generic interpretation, and the
		discourse focus on the actor and activity <Ref k="nakagawa2024" p="190–191" />;
		<Ref k="bugaevakobayashi2022" p="§4.2.3" />. The nominal-prefix and antipassive accounts
		highlight different aspects of the construction ‹contested›.
	</p>
	<Ex
		m="menoko i-huraye kor an na"
		g="woman ANTIP-wash CONJ exist.SG FIN"
		tr="The woman was doing the laundry."
		cite="nakagawa2024:190"
		dial="CHI"
		place="Ending of example 170"
		note="The preceding relative clause describes the woman's incomparable beauty; this continuous excerpt begins at menoko."
	/>
	<p>
		The change of person series supplies a morphological diagnostic when the resulting verb is
		one-place. In the next example, <i lang="ain-Latn">i-ri</i> “skin the catch” takes the
		fourth-person S form <i lang="ain-Latn">=an</i>. The corresponding transitive use of
		<i lang="ain-Latn">ri</i> has an A form
		<Ref k="bugaevakobayashi2022" p="§4.2.3, example 24" />.
	</p>
	<Ex
		m="i-ri=an wa or-o wa sini=an na"
		g="ANTIP-skin=4.S CONJ place-POSS ABL rest=4.S FIN"
		tr="I will skin the catch and then rest."
		cite="bugaevakobayashi2022:§4.2.3"
		dial="SHI"
		place="Example 24b"
		note="The Handbook cites Shizunai Board of Education 1991–1995, O0130054_6. Person boundaries are written with = here. Its transitive comparison comes from a different, Saru source."
	/>
</S>

<S t="Conventional activities and lexical restrictions" id="lexicalization">
	<p>
		An unspecified object can have a fairly specific conventional interpretation:
		<i lang="ain-Latn">i-ku</i> denotes drinking alcohol,
		<i lang="ain-Latn">i-tese</i> weaving mats, and <i lang="ain-Latn">i-carpa</i> making offerings
		to ancestors. The object remains part of the event's meaning even though it has no separate
		expression in the clause <Ref k="nakagawa2024" p="190–191" />;
		<Ref k="bugaevakobayashi2022" p="§4.2.3" />.
	</p>
	<p>
		The Handbook describes limited productivity and substantial lexicalization. Its sample of 48
		verbal lexemes concentrates on perception, cognition, ingestion, interaction, communication,
		grooming, and traditional activities. This is a published sample, with semantic restrictions
		proposed for its distribution
		<Ref k="bugaevakobayashi2022" p="§4.2.3" />. Nakagawa also reports historical analyses of
		<i lang="ain-Latn">inkar</i>
		from <i lang="ain-Latn">i-nukar</i> and the verb
		<i lang="ain-Latn">ipe</i> “eat a meal” from <i lang="ain-Latn">i-e</i>
		<Ref k="nakagawa2024" p="191" />. These analyses involve lexical history and phonological
		change.
	</p>
</S>

<S t="Interaction with applicatives and higher valency" id="higher-valency">
	<p>
		Reducing a three-place verb by one argument leaves a transitive verb. Bugaeva's example of
		serving illustrates theme suppression while the recipient remains expressed
		<Ref k="bugaeva2012" p="487" />.
	</p>
	<Ex
		m="a=kor ekasi hoski-no nea okkaypo utar ko-i-puni"
		g="4.A=have grandfather first-ADV that young.man PL APPL-ANTIP-raise"
		tr="The young men served my grandfather first."
		cite="bugaeva2012:487"
		place="Example 53b; K7803231UP.072"
		note="The source's zero person indexes are omitted. The served item is backgrounded; the grandfather remains the recipient."
	/>
	<p>
		An applicative can also follow antipassivization in the derivation. In
		<i lang="ain-Latn">e-i-kasuy</i>, the people helped are left unspecified and
		<i lang="ain-Latn">e-</i> introduces the work. The final verb again has two arguments
		<Ref k="bugaeva2012" p="487" />;
		<Ref k="bugaevakobayashi2022" p="§4.2.3, example 25" />.
	</p>
	<Ex
		m="tokaci wa ek pewre kur monrayke e-i-kasuy"
		g="Tokachi ABL come.SG young man work APPL-ANTIP-help"
		tr="A young man who came from Tokachi helped people with work."
		cite="bugaeva2012:487"
		dial="ISH"
		place="Example 54b; SK160"
		note="Bugaeva cites Sunazawa 1983:160. Tokachi is the place mentioned in the story; the example is identified as Ishikari."
	/>
	<p>
		Lexicalized verbs may depart from simple arithmetic. Satō discusses
		<i lang="ain-Latn">iyomare</i> “pour alcohol,” classified as intransitive in the Nakagawa and
		Tamura dictionaries despite its analysis with the three-place base
		<i lang="ain-Latn">omare</i>. He proposes that the ritual context already supplies the location,
		a cup, before <i lang="ain-Latn">i-</i> suppresses the theme. He leaves the extent of this
		pragmatic reduction unresolved ‹speculative›
		<Ref k="sato2023b" p="57–59, example 20 and note 20" />.
	</p>
</S>

<S t="The historical relationship with person i=" id="history">
	<p>
		Derivational <i lang="ain-Latn">i-</i> and fourth-person object
		<i lang="ain-Latn">i=</i> have different grammatical functions; see
		<Xr ch="indefinite-fourth-person-paradigm" />. Their historical relationship remains disputed.
		Bugaeva's 2012 account derives the antipassive from indefinite person marking, while also
		considering a deeper relationship with the bound noun <i lang="ain-Latn">hi/i</i>
		<Ref k="bugaeva2012" p="486" />. Her later 2021 analysis, reported by Nam, instead derives the
		antipassive from incorporation of a generic noun and proposes that person marking developed from
		the antipassive ‹contested›
		<Ref k="nam2021" p="64–66" />.
	</p>
	<p>
		Nam supports the generic-noun account but reconstructs <i lang="ain-Latn">*hi</i> or
		<i lang="ain-Latn">*ihi</i>. He compares nominalizing and possessive morphology and suggests
		ways in which the initial consonant could have disappeared. These are historical hypotheses
		‹speculative› <Ref k="nam2021" p="65–66, 73–74" />. The distinction between an unspecified
		incorporated participant and an indexed participant also matters for the quasi-incorporation
		constructions in <Xr ch="noun-incorporation-oblique-polysynthesis-debate" />.
	</p>
</S>
