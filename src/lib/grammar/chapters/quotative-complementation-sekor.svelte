<S t="Quoted speech and person reference" id="quotation">
	<p>
		<i lang="ain-Latn">Sekor</i> marks quoted material in many southern Hokkaido examples. The
		quotation can contain ordinary first-person forms or forms from the fourth-person series
		referring to the quoted speaker. This latter use is called <em>logophoric</em>: it identifies
		the person whose words or perspective are represented
		<Ref k="nikitina2021" p="613, §2" />.
	</p>
	<Ex
		m="asinuma arpa=an kusu ne sekor hawean"
		g="4.SG go.SG=4.S intention COP QUOT say.SG"
		tr="They said, ‘I will go.’"
		cite="nikitina2021:613"
		dial="SAR"
		place="Example 1b, quoting Tamura 2000:74"
		note="English ‘they’ leaves the speaker's gender unspecified. Asinuma and =an refer to that quoted speaker. The source's LOG labels are normalized to the fourth-person form series used here."
	/>
	<p>
		The form <i lang="ain-Latn">=an</i> remains fourth-person morphology even when its referent is a
		third person from the current reporter's viewpoint. Identifying a referent and identifying a
		morphological form are separate tasks. Ordinary third-person marking on
		<i lang="ain-Latn">hawean</i> introduces the quoted person's speech.
	</p>
</S>

<S t="Direct, logophoric, and indirect analyses" id="analyses">
	<p>
		Bugaeva's earlier account organizes reported discourse into direct, semi-direct, and indirect
		types, taking the orientation of person reference as a central criterion. Her semi-direct
		category combines the quoted speaker's and reporter's perspectives
		<Ref k="bugaeva2008" p="31" />.
	</p>
	<p>
		Nikitina and Bugaeva later compare syntactic properties. They find that Ainu logophoric speech
		patterns with direct speech in its flexible relation to reporting material, while indirect
		speech behaves more like a selected object complement
		<Ref k="nikitina2021" p="§§3.1–3.2" />. A change in person reference therefore does not by
		itself diagnose an indirect complement.
	</p>
	<Ex
		m="onne=an pe ne kusu a=e-isoytak sekor sino nispa hawean"
		g="be.old=4.S NMLZ COP because 4.A=APPL-tell QUOT true elder say.SG"
		tr="‘I told it because I was old,’ said an esteemed elder."
		cite="nikitina2021:619"
		dial="SAR"
		place="Example 11a, citing Nakagawa et al., K7908051UP.377"
		note="The quoted speaker is expressed with fourth-person forms. Sino nispa stands between sekor and the reporting verb; the construction does not require adjacency between those two words."
	/>
	<p>
		The study also documents quotations placed within reporting material and cases without an overt
		speech verb <Ref k="nikitina2021" p="§§3.1–3.2" />. The usual sequence of quotation followed by
		<i lang="ain-Latn">sekor</i> is compatible with this broader syntactic flexibility.
	</p>
</S>

<S t="Indirect content and the reporting viewpoint" id="indirect">
	<p>
		Nakagawa describes indirect speech with markers such as <i lang="ain-Latn">kuni</i>,
		<i lang="ain-Latn">kunak</i>, <i lang="ain-Latn">yak</i>, and
		<i lang="ain-Latn">kusu</i>, followed by transitive predicates including
		<i lang="ain-Latn">ye</i> ‘say’ and <i lang="ain-Latn">ramu</i> ‘think’. The forms have
		different distributions; they do not constitute a freely interchangeable set <Ref
			k="nakagawa2024"
			p="475–479"
		/>.
	</p>
	<Ex
		m="e=rayke kunak a=wenonaha ye wa"
		g="2SG.O=kill COMP 4.POSS=bad.father say CONJ"
		tr="My wicked father said that he would kill you, and…"
		cite="nakagawa2024:475"
		dial="SAR"
		place="Example 1106"
		note="A young man reports his absent father's threat to his wife. ‘You’ identifies the wife from the young man's reporting viewpoint; the father is the zero-marked third-person actor of rayke."
	/>
	<p>
		This example has no mechanical conversion of every embedded first person to fourth person.
		Reference is assigned from the reporting viewpoint. Nakagawa also distinguishes the embedded
		verb phrase from a full quotation: his indirect construction excludes the final particle <i
			lang="ain-Latn">na</i
		>
		retained in the corresponding quoted utterance
		<Ref k="nakagawa2024" p="476, example 1107" />.
		<Xr ch="kuni-complementizer-purpose-complements" /> discusses the individual complement frames.
	</p>
</S>

<S t="Dialect and predicate selection" id="dialects">
	<p>
		Refsing's Shizunai description uses <i lang="ain-Latn">ari</i> with speech predicates and with
		<i lang="ain-Latn">yaynu</i>
		‘think, reflect’, while
		<i lang="ain-Latn">ramu</i> selects <i lang="ain-Latn">kuni</i> in her account
		<Ref k="refsing1986" p="265–267" />. Her comparison with frequent Saru
		<i lang="ain-Latn">sekor</i> is explicitly based on Hattori's dialect dictionary. These
		descriptions cannot be combined into one unrestricted alternation of
		<i lang="ain-Latn">ari</i> and <i lang="ain-Latn">sekor</i>.
	</p>
	<p>
		Narrative quotation can also mix person series. Nakagawa documents Horobetsu dialogue with both
		first-person plural and fourth-person forms referring to the speaker, and notes uncertainty in
		translating particular occurrences as ‘I’ or ‘we’
		<Ref k="nakagawa2024" p="475, example 1105" />. The original performance and its discourse
		context remain essential to interpreting a quoted participant.
	</p>
</S>
