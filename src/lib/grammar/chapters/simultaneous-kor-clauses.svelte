<S t="Actions and states that overlap" id="simultaneity">
	<p>
		One use of <i lang="ain-Latn">kor</i> relates situations that hold at the same time. The
		predicates can describe different participants: Tamura's example has a group dancing and another
		person watching the speaker
		<Ref k="tamura1997" p="49" />.
	</p>
	<Ex
		m="horippa=as kor en=nukar"
		g="dance.PL=1PL.S CONJ 1SG.O=see"
		tr="While we danced, he looked at me."
		cite="tamura1997:49"
		dial="SAR"
		place="J5, kor example"
		note="The source's hyphens at person boundaries are written as equals signs. The plural dancers and singular object follow its Japanese translation."
	/>
	<p>
		Satō makes the same point with a Chitose oral-literature passage in which the narrator's parents
		speak while smoke rises at their home
		<Ref k="sato2008" p="50" />. The English translations ‘while’ and ‘as’ can express this overlap
		without imposing a shared-subject requirement.
	</p>
</S>

<S t="Kor an and the comparison with wa and no" id="aspect">
	<p>
		<i lang="ain-Latn">Kor</i> followed by <i lang="ain-Latn">an</i> or
		<i lang="ain-Latn">oka</i> participates in continuative constructions. These include both events
		in progress and habits extending across a longer period. Tamura also allows the preceding
		predicate and the existential to have different subjects <Ref k="tamura1997" p="49" />. See <Xr
			ch="existential-aspect-an-oka"
		/> for their person marking and interpretation.
	</p>
	<p>
		Nakagawa's Saru comparison places <i lang="ain-Latn">kor</i> with an action in progress,
		<i lang="ain-Latn">wa</i>
		with its resulting state, and <i lang="ain-Latn">no</i> with a state without temporal change. He
		explicitly notes that manner constructions require more than this phase comparison <Ref
			k="nakagawa2024"
			p="341–342"
		/>.
	</p>
	<Ex
		m="a=onaha somo mokor no kamuyoritak kor an"
		g="4.A=father.POSS NEG sleep CONJ pray CONJ exist.SG"
		tr="My father was praying without sleeping."
		cite="nakagawa2024:340"
		dial="SAR"
		place="Example 614"
	/>
	<p>
		Here <i lang="ain-Latn">no</i> links the negative sleeping predicate to prayer, and
		<i lang="ain-Latn">kor an</i>
		describes the continuing prayer. This example illustrates the combination in Saru; the wider
		distribution of negative linkage is discussed in <Xr
			ch="sequential-wa-and-clause-chaining"
			s="distribution"
		/>.
	</p>
</S>

<S t="Habitual and conditional kor" id="conditional">
	<p>
		The same written form also connects a recurring circumstance with what happens in it. Satō
		illustrates this with birds returning to roost at night
		<Ref k="sato2008" p="49" />.
	</p>
	<Ex
		m="sironuman kor cikap utar iwak"
		g="become.dark CONJ bird PL return.home"
		tr="When it gets dark, the birds return to roost."
		cite="sato2008:49"
		dial="CHI"
		place="§6.4, regular-condition example"
	/>
	<p>
		Satō also describes hypothetical questions such as asking what one should say, and a rare
		factual use, <i lang="ain-Latn">taanta ek kor, as</i>, ‘He came here and stopped.’ His account
		therefore includes more than a single division between simultaneous actions and habitual
		conditions
		<Ref k="sato2008" p="49" />. Nakagawa notes that simultaneous and conditional interpretations
		can be difficult to distinguish in some contexts <Ref k="nakagawa2024" p="340" />.
	</p>
</S>

<S t="Regional constructions and historical proposals" id="regional">
	<p>
		Regional comparison must distinguish the functions of the connectors. Horobetsu has conditional <i
			lang="ain-Latn">ko</i
		>
		alongside continuative <i lang="ain-Latn">kor</i>. Shizunai
		<i lang="ain-Latn">konno</i> and <i lang="ain-Latn">koonno</i>
		have factual and habitual uses. Several varieties east of Shizunai use
		<i lang="ain-Latn">kane</i> or <i lang="ain-Latn">kan</i> for continuation and sustained states
		<Ref k="nakagawa2024" p="342, 348–349" /><Ref
			k="nakagawafukazawa2022"
			p="§4.3.2, examples 16–21"
		/>.
	</p>
	<p>
		Nakagawa and Fukazawa propose that conditional <i lang="ain-Latn">ko</i>
		is older and became <i lang="ain-Latn">kor</i> in some regions through attraction to the other
		connector. In their hypothesis, Shizunai subsequently added <i lang="ain-Latn">-no</i> to
		preserve a distinction
		<Ref k="nakagawafukazawa2022" p="§4.3.2" />. This is a historical proposal based on the
		distribution, rather than an automatic rule deleting final <i>r</i> in every
		<i lang="ain-Latn">ko</i> form.
	</p>
</S>
