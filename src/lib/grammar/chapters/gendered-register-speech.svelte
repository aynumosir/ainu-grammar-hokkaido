<S t="Interjections and changing greeting conventions" id="interjections">
	<p>
		Nakagawa lists <i lang="ain-Latn">hap</i> as a women's expression of gratitude and Chitose
		<i lang="ain-Latn">okko</i>
		as a call used by women to other women. These are particular lexical conventions within a larger
		inventory of <Xr ch="interjections-ideophones-sound-symbolism">interjections</Xr>
		<Ref k="nakagawa2024" p="290–291" />.
	</p>
	<p>
		Ōno describes traditional <i lang="ain-Latn">irankarapte</i> as a polite reunion greeting
		ordinarily delivered by a man with a gesture of respect. His account also documents a later,
		gender-neutral use as a general greeting, often without the traditional gesture. The older
		restriction therefore cannot be assumed for every recent use
		<Ref k="ono2022" p="§8.2" />.
	</p>
</S>

<S t="Performance roles and genre names" id="performance">
	<p>
		Traditional performance roles vary by genre and region. Endō reports adult male performance of
		prayers and ceremonial negotiation,
		<i lang="ain-Latn">caranke</i>. Incantations are used by people of either sex and any age.
		Heroic epics are traditionally associated with men in several regions, but women have also
		recorded them. Satō's Chitose account distinguishes verse performance from
		<i lang="ain-Latn">irupaye</i>, a prose telling of heroic material permitted to women <Ref
			k="endo2022"
			p="§§2.3, 2.4.3"
		/>
		<Ref k="sato2008" p="259" />.
	</p>
	<p>
		Performer gender, protagonist gender, and genre name need not coincide.
		<i lang="ain-Latn">Menoko yukar</i> names divine epics in the middle Saru area; it is also used
		regionally for heroic epics with a female protagonist. The name alone does not identify a single
		narrative form
		<Ref k="endo2022" p="§§2.4.2–2.4.3" />. See <Xr ch="oral-literature-genre-taxonomy" />.
	</p>
</S>

<S t="Limits of the conversational record" id="documentation">
	<p>
		Nakagawa stresses the scarcity of everyday conversations, particularly conversations between men
		and women. He finds it difficult to infer a literary character's gender from the wording of a
		speech alone. This observation leaves room for the specific address and lexical differences
		described above <Ref k="nakagawa2024" p="525–526" />.
	</p>
	<p>
		His discussion also quotes Kindaichi's historical impression that voiced pronunciations were
		more common among men and adults and in less careful speech. This is an attributed auditory
		observation, without measurements establishing a gender-conditioned sound rule
		<Ref k="nakagawa2024" p="525–526, citing Kindaichi 1928:83" />.
	</p>
</S>
