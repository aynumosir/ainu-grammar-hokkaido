	<p>
		Number can be established by discourse, independent pronouns, or other expressions in the
		clause. The marker itself leaves it open. With a three-place verb, an overt third-person noun
		may identify the theme while the second-person object index identifies a recipient. The presence
		of such a noun therefore does not automatically identify the subject as second plural <Ref
			k="sato2008"
			p="121, 147"
		/>. See <Xr ch="object-indexing-monotransitive" /> for the distinction between two objects and one
		object index.
	</p>
</S>

<S t="Second-to-first forms in Saru and Chitose" id="second-to-first">
	<p>
		The reverse interaction has its own pattern. Nakagawa's Saru table gives
		<i lang="ain-Latn">en=</i> and <i lang="ain-Latn">un=</i> for a second-singular subject acting
		on first singular and first plural respectively. With a second-plural subject, it gives
		<i lang="ain-Latn">eci=en=</i>
		and <i lang="ain-Latn">eci=un=</i>
		<Ref k="nakagawa2024" p="171, table 28" />.
	</p>
	<p>
		Satō's principal Chitose description uses the shorter forms for both second-person numbers. On
		the same page, however, he acknowledges the longer second-plural forms reported by Nakagawa
		1995. The alternatives must be read with their source descriptions
		<Ref k="sato2008" p="147" />. Bugaeva's combined Saru/Chitose table includes the overt
		second-plural sequences <Ref k="bugaeva2012" p="474, table 15.3" /> ‹contested›.
	</p>
</S>

<S t="Regional interaction patterns" id="regional">
	<p>
		Shizunai does not share the same first-to-second-person pattern. Refsing describes
		<i lang="ain-Latn">an=e=</i> with a second-singular object and either first-person number. With
		a second-plural object, first singular permits <i lang="ain-Latn">an=eci=</i> or
		<i lang="ain-Latn">eci=…=an</i>; her first-plural row has <i lang="ain-Latn">an=eci=</i>
		<Ref k="refsing1986" p="223–225, diagram 6 and examples 371–375" />.
	</p>
	<Ex
		m="eci=en=kik yak anak eci=pakasnu=an na"
		g="2PL.A=1SG.O=hit COND TOP 2PL.O=punish=1SG.A FIN"
		tr="If you hit me, I shall punish you."
		cite="refsing1986:225"
		dial="SHI"
		place="Example 372"
		note="Refsing prints eci en kik and eci pakasnu an separately. Her consultant also accepts an eci pakasnu with the same meaning. The gloss identifies the interaction's first-singular subject."
	/>
	<p>
		Nakagawa's comparative tables show further patterns. Horobetsu has
		<i lang="ain-Latn">e=…=as</i> and <i lang="ain-Latn">eci=…=as</i> for first-to-second reference.
		Ishikari distinguishes first-singular <i lang="ain-Latn">=an</i> from first-plural
		<i lang="ain-Latn">=as</i>
		in these combinations; Tokachi has
		<i lang="ain-Latn">eci=…=an</i> in all four first-to-second cells. Several cells elsewhere in
		the regional tables remain uncertain <Ref k="nakagawa2024" p="171–174, tables 30–34" />.
	</p>
</S>

<S t="Narrative reference and historical proposals" id="register">
	<p>
		A literary “I” may use fourth-person morphology. Satō records Chitose
		<i lang="ain-Latn">a=e=</i> and <i lang="ain-Latn">aci=</i> in literary first-to-second
		reference and notes that the full literary interaction paradigm is incompletely known
		<Ref k="sato2008" p="262" />. Nakagawa's examples likewise distinguish narrative person from the
		conversational first-person row <Ref k="nakagawa2024" p="174, examples 130–132" />.
	</p>
	<p>
		Refsing tentatively relates <i lang="ain-Latn">eci=</i> to second-singular
		<i lang="ain-Latn">e=</i> plus a plural element <i lang="ain-Latn">ci</i>
		<Ref k="refsing1986" p="217" /> ‹speculative›. That proposed decomposition does not by itself explain
		the distribution of the Saru/Chitose portmanteau or supply the missing regional cells. The person-series
		distinctions are developed in <Xr ch="indefinite-fourth-person-paradigm" />.
	</p>
</S>
