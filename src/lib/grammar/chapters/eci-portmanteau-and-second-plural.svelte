<S t="Second plural and first-to-second reference" id="two-functions">
	<p>
		The form <i lang="ain-Latn">eci=</i> has two functions in the Saru/Chitose conversational
		paradigm. It marks second-person plural in ordinary S, A and O forms. It also expresses the
		combination of a first-person subject with a second-person object, across all four singular and
		plural combinations <Ref k="nakagawa2024" p="167–171, tables 25–29" />;
		<Ref k="sato2008" p="146–147" />;
		<Ref k="bugaeva2012" p="472, 474" />.
	</p>
	<table>
		<thead><tr><th>Construction</th><th>Value of eci=</th></tr></thead>
		<tbody>
			<tr><td>Intransitive</td><td>Second-plural S</td></tr>
			<tr><td>Transitive, third-person O</td><td>Second-plural A</td></tr>
			<tr><td>Transitive, third-person A</td><td>Second-plural O</td></tr>
			<tr
				><td>First-person A, second-person O</td><td
					>Combined A–O marker; either number for each participant</td
				></tr
			>
		</tbody>
	</table>
	<p>
		The last use is commonly called a portmanteau: a single form realizes a combination of features.
		Bugaeva reports that the corresponding combinations of ordinary first-person subject and
		second-person object prefixes are excluded in this paradigm
		<Ref k="bugaeva2012" p="474" />. The portmanteau is consequently learned as part of the
		interaction paradigm.
	</p>
</S>

