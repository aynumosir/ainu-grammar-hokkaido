<S t="Source, location, and instrumental descriptions" id="roles">
	<p>
		Bugaeva's lexical classification assigns 57% of the sampled <i lang="ain-Latn">o-</i>
		applicatives to Goal, 29% to Location, and 14% to an Other category containing Source and Theme. The
		corresponding expressions in her table include
		<i lang="ain-Latn">ta/un</i>, <i lang="ain-Latn">ta</i>, and
		<i lang="ain-Latn">wa</i>, with no paraphrase supplied for Theme
		<Ref k="bugaeva2006" p="191, table 3" />. These proportions describe lexical entries in her
		sample.
	</p>
	<p>
		Nakagawa gives a more unified place-based explanation. He treats a causal or source translation
		of <i lang="ain-Latn">o-tumi-ne</i>, “war arose because of it,” as compatible with his
		directed-place meaning <Ref k="nakagawa2024" p="198" />. The semantic labels therefore depend
		partly on the analysis used.
	</p>
	<p>
		Satō explicitly recognizes an instrumental use in <i lang="ain-Latn">aoypep</i>
		“eating vessel.” He analyzes the word as <i lang="ain-Latn">a-o-ipe-p</i>, a thing people use
		for eating, while noting that he lacks another suitable instrumental example
		<Ref k="sato2008" p="245" />. His instrumental analysis extends beyond the predominantly spatial
		descriptions ‹contested›.
	</p>
</S>

<S t="Base valency and lexical limits" id="valency">
	<p>
		An applicative can attach to an already transitive base as well as to an intransitive one
		<Ref k="sato2008" p="243" />;
		<Ref k="bugaevakobayashi2022" p="§4.1.1" />. Consequently, an
		<i lang="ain-Latn">o-</i> form should not automatically be assigned two arguments merely because some
		common motion examples have that frame. The base and remaining participants must be identified first.
	</p>
	<p>
		Nakagawa describes <i lang="ain-Latn">o-</i> as less frequent than
		<i lang="ain-Latn">e-</i> and <i lang="ain-Latn">ko-</i>, with much of its use in verse
		<Ref k="nakagawa2024" p="198" />. Satō likewise considers its examples less usual
		<Ref k="sato2008" p="243" />. These source observations do not establish a measured
		token-frequency ratio across dialects or genres.
	</p>
</S>

<S t="Independent verbs and incorporation" id="related-forms">
	<p>
		Independent <i lang="ain-Latn">o/oma</i> and related placement verbs require their own lexical
		argument analysis. Nakagawa distinguishes several frames among these forms
		<Ref k="nakagawa2024" p="212–213" />. Initial <i lang="ain-Latn">o</i> in a word is therefore insufficient
		evidence for an applicative boundary.
	</p>
	<p>
		With incorporation, <i lang="ain-Latn">o-</i> can occur outside an already incorporated stem, as
		in Shibatani's <i lang="ain-Latn">o-tumi-osma</i>. Other derivations place the incorporated
		applied object outside an applicative
		<Ref k="shibatani1990" p="62–63, 68–71" />. These structural differences are developed in <Xr
			ch="applicative-stacking-relativization-feeding"
		/> and
		<Xr ch="noun-incorporation-oblique-polysynthesis-debate" />.
	</p>
</S>
