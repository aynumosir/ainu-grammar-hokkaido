	<p>
		Nakagawa uses these separate examples to contrast a place object with a personal object. The
		village and the sister are expressed in the clauses. His distinction concerns the place
		requirement of <i lang="ain-Latn">o-</i>; <i lang="ain-Latn">ko-</i> can itself occur with
