<S t="Adverbial modification" id="adverb-class">
	<p>
		Adverbs express time, manner, degree, and other circumstances of a predicate. Nakagawa
		distinguishes ordinary adverbs from postpositional adverbs that take an antecedent or person
		marker. In his account, a completed adverbial phrase has zero arity; the postpositional word has
		one place to be filled by its antecedent
		<Ref k="nakagawa2024" p="273, 280, §§6.1, 6.3" />.
	</p>
	<p>
		Basic forms include temporal <i lang="ain-Latn">esir</i> ‘a short time ago’, manner
		<i lang="ain-Latn">arorkisne</i>
		‘quietly, secretly’, and degree <i lang="ain-Latn">sonno</i> ‘truly’. Nakagawa also includes
		negative and interrogative adverbs, among them
		<i lang="ain-Latn">makanak</i> ‘how’ and
		<i lang="ain-Latn">hempara</i> ‘when’
		<Ref k="nakagawa2024" p="273–275" />.
	</p>
	<Ex
		m="kani anakne sonno sino ku=nepki"
		g="1SG TOP truly truly 1SG.S=work"
		tr="I really, really worked."
		cite="nakagawa2024:274"
		dial="CHI"
		place="Example 343"
	/>
</S>

<S t="Derived and converted adverbs" id="deverbal-adverbs">
	<p>
		Many property and state predicates form an adverb with
		<i lang="ain-Latn">-no</i>: <i lang="ain-Latn">pirka</i> ‘good’ has
		<i lang="ain-Latn">pirkano</i>
		‘well’, and
		<i lang="ain-Latn">pon</i> ‘small’ has
		<i lang="ain-Latn">ponno</i> ‘in a small way’. Nakagawa records both
		<i lang="ain-Latn">poronno</i>
		and
		<i lang="ain-Latn">porono</i> from <i lang="ain-Latn">poro</i>. He regards the boundary between
		this formation and connective
		<i lang="ain-Latn">no</i> as difficult to draw
		<Ref k="nakagawa2024" p="275–276" />.
	</p>
	<p>
		Some predicates also occur adverbially without
		<i lang="ain-Latn">-no</i>. The published Saru examples use both
		<i lang="ain-Latn">tunas</i> and <i lang="ain-Latn">tunasno</i>
		for getting up early <Ref k="nakagawa2024" p="276, examples 349–350" />. For clause-sized
		modifiers, see
		<Xr ch="manner-and-degree-adverbial-clauses" />.
	</p>
	<Ex
		m="kunneywa tunasno hopuni=an hine ipe=an"
		g="morning early get.up=4.S CONJ eat=4.S"
		tr="I got up early in the morning and ate."
		cite="nakagawa2024:276"
		dial="SAR"
		place="Example 350"
	/>
	<p>
		Directional formations have additional structure. Nakagawa analyzes
		<i lang="ain-Latn">e-/o-</i> with ‘head/butt’ meanings, a positional noun, and
		<i lang="ain-Latn">ne</i>
		or <i lang="ain-Latn">un</i>; a second series combines <i lang="ain-Latn">he-/ho-</i>, a
		positional noun, and <i lang="ain-Latn">asi</i>. Thus his tables include
		<i lang="ain-Latn">ekimne</i> ‘toward the mountains’ and
		<i lang="ain-Latn">okimne</i> ‘from the mountains’. Some of these forms also function as
		person-marked verbs: his Chitose
		<i lang="ain-Latn">k=ekimne</i> means ‘I go into the mountains’
		<Ref k="nakagawa2024" p="277–279, Tables 68–69 and example 357" />.
	</p>
</S>

<S t="Postpositional adverbs and their antecedents" id="postpositional-adverbs">
	<p>
		The antecedent of <i lang="ain-Latn">os</i> ‘after’ can be an overt noun phrase, a person
		marker, or a participant supplied by context. In the next example <i lang="ain-Latn">i=</i>
		identifies the person followed into the house <Ref
			k="nakagawa2024"
			p="280, examples 362–364"
		/>.
	</p>
	<Ex
		m="ahun=an akusu i=os ahun hine"
		g="enter=4.S CONJ 4.O=after enter CONJ"
		tr="When I entered, she came in after me, and…"
		cite="nakagawa2024:280"
		dial="CHI"
		place="Example 363"
		note="An excerpt ending in a connective. Fourth-person forms refer to the narrator; the following woman's subject has no overt person marker."
	/>
	<p>
		Transitive verbs supply many postpositional adverbs, including
		<i lang="ain-Latn">ani</i> ‘by means of’ and
		<i lang="ain-Latn">tura</i> ‘with’. Their patterns are partly lexical:
		<i lang="ain-Latn">tura</i> also has <i lang="ain-Latn">turano</i>, whereas Nakagawa rejects an
		analogous
		<i lang="ain-Latn">ani-no</i>. He also notes exceptional subject marking in
		<i lang="ain-Latn">a=opitta</i>
		‘all of us’
		<Ref k="nakagawa2024" p="276–277, 281" />.
	</p>
	<p>
		These expressions differ from <Xr ch="postpositions-local-case-and-motion-events"
			>place particles</Xr
		>. Nakagawa's <i lang="ain-Latn">kari</i> can follow ‘bridge’ or ‘window’ directly, while
		<i lang="ain-Latn">peka</i>
		requires an expression of grammatical place, sometimes supplied by a positional noun <Ref
			k="nakagawa2024"
			p="282"
		/>.
	</p>
</S>

<S t="Comparison, equality, and particular intensity" id="comparison">
	<p>
		Refsing describes Shizunai comparisons with
		<i lang="ain-Latn">akkari</i> ‘than’, leaving the property predicate unchanged. Her
		<i lang="ain-Latn">koraci</i>
		example expresses similarity of behavior: a human will speak like a human
		<Ref k="refsing1986" p="169–170, §14.5.6" />.
	</p>
	<p>
		Bugaeva describes an equivalent of an equative construction with
		<i lang="ain-Latn">pak(no)</i>. Its predicate is often
		<i lang="ain-Latn">an</i> ‘exist’ or <i lang="ain-Latn">isam</i>
		‘not exist’; the compared property can modify the noun or remain implicit. Size is implicit in this
		narrative example
		<Ref k="bugaeva2015" p="54–55, §5.1" />.
	</p>
	<Ex
		m="kotan noski ta mosir pak cise an hine"
		g="village middle LOC island extent house exist.SG CONJ"
		tr="In the middle of the village there was a house as big as an island, and…"
		cite="bugaeva2015:54"
		dial="SAR"
		place="Example 25a, Kimura text K8109171UP.200"
		note="The translation supplies the size comparison; there is no overt property word meaning ‘big’ in the Ainu line."
	/>
	<p>
		Tamura's dictionary gives <i lang="ain-Latn">iyotta</i> the range ‘particularly, most,
		extremely’. Its example
		<i lang="ain-Latn">tanike iyotta pirka</i> can mean ‘This one is best’, but the entry explicitly
		cautions against treating
		<i lang="ain-Latn">iyotta</i> simply as a grammatical superlative
		<Ref k="tamura1996" p="s.v. iyotta" />.
	</p>
</S>
