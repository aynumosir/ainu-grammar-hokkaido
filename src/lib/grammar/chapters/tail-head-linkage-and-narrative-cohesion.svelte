<S t="Continuing a narrative" id="continuation">
	<p>
		Ainu narratives connect situations through particles, formal-noun constructions, adverbial
		expressions, and repeated information.
		<i lang="ain-Latn">Hine</i> can link an introductory description to further events, while
		<i lang="ain-Latn">hike</i>
		presents a preceding situation as the background for what follows
		<Ref k="nakagawa2024" p="338, 516" />.
	</p>
	<Ex
		m="a=saha an hine oka=an hike a=saha cis a cis a kor"
		g="4.A=older.sister.POSS exist.SG CONJ exist.PL=4.S CONJ 4.A=older.sister.POSS cry ITR cry ITR CONJ"
		tr="I was living with my older sister, and she kept crying, …"
		cite="nakagawa2024:516"
		dial="SAR"
		place="Example 1185"
		note="The fourth-person construction refers to the narrator. The repeated cis a cis a depicts continued crying, and the source excerpt remains open after kor."
	/>
	<p>
		Nakagawa distinguishes this connective <i lang="ain-Latn">hike</i>
		from a nominal <i lang="ain-Latn">hike</i> that occupies an argument position in the following
		predicate. He makes the same distinction for linking uses of <i lang="ain-Latn">p/pe</i>
		<Ref k="nakagawa2024" p="515–516, examples 1182–1185" />. A recurring word shape can therefore
		have different structural roles.
	</p>
</S>

<S t="Orowa and related connective expressions" id="orowa">
	<p>
		<i lang="ain-Latn">Orowa</i>, <i lang="ain-Latn">orowano</i>,
		<i lang="ain-Latn">ora</i>, and related forms can follow an apparent sentence ending or another
		connector. Nakagawa illustrates
		<i lang="ain-Latn">ora</i> after <i lang="ain-Latn">kusu</i> and
		<i lang="ain-Latn">orowano</i> after <i lang="ain-Latn">hine</i>
		within one account of buying seeds and arranging a box for planting
		<Ref k="nakagawa2024" p="517, example 1187" />.
	</p>
	<p>
		Tamura describes these forms as often signalling that the speaker will continue, while allowing
		time to formulate the next words. They can also have a temporal sense such as ‘from that time’
		<Ref k="tamura1997" p="34–35" />. Nakagawa likewise records <i lang="ain-Latn">hi orano</i> and
		<i lang="ain-Latn">hi orowano</i> with ‘since’ meanings
		<Ref k="nakagawa2024" p="517, example 1188" />. Their presence alone does not identify the scale
		of a scene change.
	</p>
</S>

<S t="Repetition and reference" id="repetition">
	<p>
		Dal Corso examines a passage about a woman who raises her son, sees him marry, and then
		unexpectedly becomes blind. The narrative revisits the upbringing and marriage before describing
		the three people living together
		<Ref k="dalcorso2018" p="196–198, §6.3, example 170; TMA:2" />.
	</p>
	<Ex
		m="a=po-ho a=resu hine oka=an pe ne a p a=po-ho mat-kor hine orano u-heturaste=an wa oka=an a p"
		g="4.A=child-POSS 4.A=raise CONJ exist.PL=4.S NMLZ COP PFV CONJ 4.A=child-POSS wife-have CONJ then RECP-live.together=4.S CONJ exist.PL=4.S PFV CONJ"
		tr="I had raised my son, but … my son married and we all lived together, but …"
		cite="dalcorso2018:197"
		dial="HK"
		place="Example 170, recapitulation excerpt; source siglum TMA:2"
		note="TMA:2 is Tamura 1984:2, Audio Materials of Ainu 1, cited through Dal Corso. Person boundaries and glosses are adapted to this grammar. PFV follows the disclosed convention in chapter 111; Dal Corso uses PRF in this passage. The following clause says that the woman suddenly became completely blind."
	/>
	<p>
		Dal Corso interprets the repetition as clarification: the explicit mention of the son helps
		recover reference in the earlier account. He takes the final <i lang="ain-Latn">a p</i> before
		the blindness as a boundary introducing a turn in events
		<Ref k="dalcorso2018" p="197–198" />. This is an analysis of a particular passage. It does not
		establish an obligatory pattern in which every narrative segment repeats the end of the previous
		one.
	</p>
</S>

<S t="Changes of scene, topic, and actor" id="boundaries">
	<p>
		Yoshikawa describes a broader tendency for <i lang="ain-Latn">a</i>
		with <i lang="ain-Latn">p</i>, <i lang="ain-Latn">korka</i>, or
		<i lang="ain-Latn">wa</i> to occur where a story changes scene, topic, or actor. One example
		moves from the narrator's upbringing by a grandfather to growing older and noticing something;
		another includes a change of actor
		<Ref k="yoshikawa2022" p="§4.1.1, examples 34–36" />.
	</p>
	<p>
		Yoshikawa relates this tendency to her perfective analysis of
		<i lang="ain-Latn">a</i>, emphasizing the earlier situation's separation from the current one.
		That explanation belongs to the competing aspectual accounts in <Xr
			ch="perfective-anterior-a"
		/>. The narrative interpretation also depends on time expressions, lexical participants, and
		context; a connector by itself does not identify every shift in speaker, actor, or viewpoint.
	</p>
</S>
