<S t="Voice, wording, and reported information" id="meaning">
	<p>
		<i lang="ain-Latn">Hawe</i> relates a clause to speech or meaningful vocal expression. It can
		concern something another person has said, or the speaker's own explanation of their words.
		Nakagawa illustrates both uses
		<Ref k="nakagawa2024" p="398–399" />.
	</p>
	<Ex
		m="nep ne yakka k=eramuan pe k=ukopoye wa ku=ye hawe ne"
		g="what COP CONC 1SG.A=remember NMLZ 1SG.A=mix CONJ 1SG.A=say EVID COP"
		tr="I am saying it by mixing together whatever I remember."
		cite="nakagawa2024:399"
		dial="CHI"
		place="Example 807"
	/>
	<p>
		In another example, someone has just announced a visitor's arrival. The person inside responds
		with <i lang="ain-Latn">a=kor nispa ek hawe ne hike</i>, ‘if our gentleman has come, as you
		say’, and considers letting him in
		<Ref k="nakagawa2024" p="398, example 805" />. The report belongs to the immediate exchange; the
		construction has no inherent past-time restriction.
	</p>
	<p>
		Nakagawa also questions an older claim excluding self-wording uses from Horobetsu. He supplies a
		Horobetsu example in which a person explains what they are saying before death <Ref
			k="nakagawa2024"
			p="399, examples 808–809"
		/>. This is his counterevidence to that earlier regional claim.
	</p>
</S>

<S t="Responding to words and cries" id="questions">
	<p>
		<i lang="ain-Latn">Hawe an</i> can ask about information conveyed in an utterance. The following
		question responds to a riddle offering two choices
		<Ref k="nakagawa2024" p="399" />.
	</p>
	<Ex
		m="inan pe ku=kor kor pirka hawe an"
		g="which NMLZ 1SG.A=have CONJ be.good EVID exist.SG"
		tr="Which one are you saying I should take?"
		cite="nakagawa2024:399"
		dial="SAR"
		place="Example 810, citing Tamura 1984:62"
	/>
	<p>
		Nakagawa explains the choice through its relation to the other person's words. Independently
		considering which thing to take would allow a different framing. He also gives <i
			lang="ain-Latn">makanak ne hawe an</i
		>
		in response to an urgent cry announcing an accident. The cry carries a message even though it is
		not an articulated sentence <Ref k="nakagawa2024" p="399–400, examples 811–812" />. A simple
		distinction between speech sounds and every other sound would miss this use.
	</p>
</S>

<S t="The noun and its clause-ending forms" id="forms">
	<p>
		Tamura's Saru dictionary distinguishes ordinary ‘voice’ from formal
		<i lang="ain-Latn">hawe</i>. The ordinary possessed noun can have the fuller form
		<i lang="ain-Latn">hawehe</i>; the formal noun does not take that extra syllable. The formal
		entry includes <i lang="ain-Latn">hawe ne</i>, questions and exclamations, and replies with
		<i lang="ain-Latn">hawe un</i>
		<Ref k="tamura1996" p="s.v. hawe, formal-noun entry" />.
	</p>
	<p>
		The ordinary noun <i lang="ain-Latn">haw</i> includes human and animal voices and certain
		instrumental sounds, such as a violin. Its lexical range and the functions of an evidential
		ending are related questions, but require separate description <Ref
			k="tamura1996"
			p="s.v. haw, ordinary-noun entry"
		/>. For the shared ending patterns, see <Xr ch="evidential-schema-overview" />.
	</p>
</S>

<S t="Hawe as and the source of a report" id="as">
	<p>
		Dal Corso distinguishes inferential, reportative, and independent lexical uses of <i
			lang="ain-Latn">hawe as</i
		>. One inferential example concerns loud voices approaching while the narrator escapes; another
		passage directly quotes a voice granting permission to enter <Ref
			k="dalcorso2018"
			p="308, examples 248–249"
		/>.
	</p>
	<p>
		In his reportative analysis, a recoverable speaker supports a quotative reading, while an
		unspecified source gives a hearsay reading. The source can occur nearby in the discourse, rather
		than immediately beside <i lang="ain-Latn">hawe as</i>
		<Ref k="dalcorso2018" p="329–331, §8.4.2.2" />. He finds reportative uses predominant in his
		surveyed material while retaining the other functions.
	</p>
	<p>
		The broader grammar of quotation, person reference, and indirect reports is covered in <Xr
			ch="quotative-complementation-sekor"
		/>. For sounds, bodily experience, and other impressions, compare
		<Xr ch="humi-ne-sensory" />.
	</p>
</S>
