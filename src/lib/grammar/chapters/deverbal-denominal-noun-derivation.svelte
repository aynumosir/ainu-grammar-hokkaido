<S t="Ways of forming nouns" id="scope">
	<p>
		Ainu nouns can be formed through affixation, compounding, nominal uses of verbs, and the
		lexicalization of larger expressions. Satō distinguishes formations containing two words from
		those combining a word with a prefix or suffix
		<Ref k="sato2008" p="265–266" />. Nakagawa's compound account additionally uses nominal
		conversion of one-place verbs
		<Ref k="nakagawa2024" p="267–272" />.
	</p>
	<p>
		Several nominalizing forms participate in both word formation and clause-level constructions.
		Shibatani describes this dual use for
		<i lang="ain-Latn">p/pe</i>, <i lang="ain-Latn">i</i>, and related forms
		<Ref k="shibatani1990" p="32–34" />. A lexical meaning such as “food” or “clothing” can coexist
		with grammatical properties inherited from a phrase.
	</p>
</S>

<S t="Nouns with p and pe" id="p-pe">
	<p>
		Shibatani gives <i lang="ain-Latn">pirka-p</i> “good thing,”
		<i lang="ain-Latn">husko-p</i> “old thing,” <i lang="ain-Latn">wen-pe</i>
		“poor person,” and <i lang="ain-Latn">ray-pe</i> “the dead”
		<Ref k="shibatani1990" p="32, example 37" />. The nominal expression refers to a person or thing
		characterized by the verbal material.
	</p>
	<S t="The two forms" id="allomorphy">
		<p>
			Satō describes <i lang="ain-Latn">p</i> after vowels and
			<i lang="ain-Latn">pe</i> after consonants
			<Ref k="sato2008" p="177, 180" />. His word-formation examples include
			<i lang="ain-Latn">asin-pe</i> “compensation” and
			<i lang="ain-Latn">ami-p</i> “clothing”
			<Ref k="sato2008" p="266" />. The conventional meaning of each word can be more specific than
			a literal rendering of its parts.
		</p>
	</S>
	<S t="Food and clothing" id="lexicalized">
		<p>
			Tamura explicitly analyzes <i lang="ain-Latn">aep</i> “food” as
			<i lang="ain-Latn">a=e-p</i> and <i lang="ain-Latn">amip</i>
			“clothing” as <i lang="ain-Latn">a=mi-p</i>
			<Ref k="tamura1996" p="s.vv. aep, amip" />.
		</p>
		<Ex
			m="a=mi-p"
			ain="amip"
			g="4.A=wear-NMLZ"
			tr="clothing"
			lit="what one wears"
			cite="tamura1996:s.v. amip"
			dial="SAR"
			note="The dictionary's morphological analysis; fourth person identifies the form series, with generic reference here."
		/>
		<p>
			Satō treats <i lang="ain-Latn">amip</i> as a word established from a phrase
			<Ref k="sato2008" p="269" />. Nakagawa notes that its initial person marker can disappear or
			be replaced in possessed expressions, preserving properties of the original relative
			construction <Ref k="nakagawa2024" p="507" />. Tamura gives <i lang="ain-Latn">ku=mipi</i> “my
			clothing”
			<Ref k="tamura1996" p="s.v. amip" />.
		</p>
	</S>
</S>

<S t="The analysis of lexical ci-" id="arity-slot">
	<p>
		Satō distinguishes the <i lang="ain-Latn">ci-</i> in
		<i lang="ain-Latn">ci-kuy-pas</i> “chewed charcoal” from an ordinary person marker. He treats it
		as a derivational prefix with low productivity
		<Ref k="sato2008" p="269, 304" />. Nakagawa likewise distinguishes nominalizing
		<i lang="ain-Latn">ci-</i> from person <i lang="ain-Latn">ci=</i>, while proposing a historical
		connection <Ref k="nakagawa2024" p="592" /> ‹speculative›.
	</p>
	<p>
		Other descriptions retain a person analysis in lexical nominalizations. Bugaeva glosses <i
			lang="ain-Latn">ci=ronnu-p</i
		>
		“fox” with first-person plural exclusive A marking <Ref k="bugaeva2016" p="100, example 5a" />.
		Tamura's entry for <i lang="ain-Latn">cep</i> “fish” gives
		<i lang="ain-Latn">c(i)-e-p</i> and interprets its first element as “we”
		<Ref k="tamura1996" p="s.v. cep" />. The synchronic treatment of these person-shaped elements
		differs among the accounts ‹contested›.
	</p>
	<p>
		The lexical formation can also have a specialized meaning. Tamura's
		<i lang="ain-Latn">ci-karkar-pe</i> denotes an embroidered, lined ceremonial garment <Ref
			k="tamura1996"
			p="s.v. cikarkarpe"
		/>. The dictionary associates
		<i lang="ain-Latn">karkar</i> with decoration or embroidery.
	</p>
</S>

<S t="Instrument expressions" id="instrument">
	<p>Nakagawa contrasts a relative-based utensil name with an ordinary compound:</p>
	<Ex
		m="a=e-suke-p"
		ain="aesukep"
		g="4.A=APPL.INS-cook-NMLZ"
		tr="kitchen utensil"
		lit="something one cooks with"
		cite="nakagawa2024:507"
		dial="SAR"
		note="Nakagawa's analysis identifies e- as the element expressing the instrumental relation."
	/>
	<p>
		In <i lang="ain-Latn">aesukep</i>, person marking and the applicative identify the grammatical
		relation between the verb and the nominal head. In the compound
		<i lang="ain-Latn">suke-makiri</i> “kitchen knife,” the association between “cook” and “knife”
		is expressed through compound formation
		<Ref k="nakagawa2024" p="507" />. The compound patterns are described in
		<Xr ch="noun-noun-compounding" />.
	</p>
</S>

<S t="Lexicalization and clause structure" id="lexical-syntactic">
	<p>
		A relative head has a grammatical relation to its modifying clause. A content complement
		nominalizes a complete proposition without requiring its head to fill an argument position
		inside that proposition
		<Ref k="nakagawa2024" p="507–510" />. This distinction concerns clause structure. Lexicalization
		concerns whether a formation has become a conventional word, as in <i lang="ain-Latn">amip</i>
		and <i lang="ain-Latn">aep</i>. Both Satō and Nakagawa retain phrase-like properties in these
		lexical items
		<Ref k="sato2008" p="269" />; <Ref k="nakagawa2024" p="507" />.
	</p>
	<p>
		Satō leaves the classification of <i lang="ain-Latn">kamuy-e-p</i> “bear food” open between an
		ordinary phrase and a lexical item derived from one
		<Ref k="sato2008" p="269" />. The wider syntactic distinctions are treated in
		<Xr ch="lexical-head-formal-noun-nominalization" />.
	</p>
</S>

<S t="Other nominalizing forms and possessed nouns" id="affiliative-nmlz">
	<p>
		Shibatani also analyzes <i lang="ain-Latn">-i</i> and
		<i lang="ain-Latn">-ike</i> as noun-forming suffixes. His examples include
		<i lang="ain-Latn">esan-i</i> “peninsula,”
		<i lang="ain-Latn">sinean-i</i> “a certain place or time,” and
		<i lang="ain-Latn">pirka-ike</i> “goodness, a good thing or person”
		<Ref k="shibatani1990" p="32–33, example 38" />. He also recognizes phrasal and clausal uses of
		these forms.
	</p>
	<S t="Affiliative morphology" id="conditioning">
		<p>
			Affiliative suffixes form relational or possessed forms of nouns, with patterns such as <i
				lang="ain-Latn">tek → teke(he)</i
			>
			“hand → its hand”
			<Ref k="nakagawa2024" p="226–230" />. Their grammatical function and lexical distribution are
			described in
			<Xr ch="concept-form-affiliative-form" /> and
			<Xr ch="affiliative-suffix-morphophonology" />. Shared sounds among a nominalizer and a
			possessive ending do not establish that they have identical distributions.
		</p>
	</S>
</S>

<S t="Formal nouns as heads" id="class-noun-heads">
	<p>
		<i lang="ain-Latn">Kur</i> “person,” <i lang="ain-Latn">usi</i> “time, place,” and
		<i lang="ain-Latn">uske</i>
		“place” belong to Nakagawa's formal-noun inventory <Ref k="nakagawa2024" p="258" />. Shibatani
		uses a suffix analysis for <i lang="ain-Latn">kur</i> in both lexical names and larger nominal
		expressions <Ref k="shibatani1990" p="33, example 40" /> ‹contested›. Their dependence and permitted
		modifiers are described in
		<Xr ch="formal-defective-nouns" />.
	</p>
</S>

<S t="Nominal conversion and noun-based derivation" id="zero-conversion">
	<p>
		Nakagawa describes nominal uses of one-place verbs without an overt nominalizer.
		<i lang="ain-Latn">Ipe</i> can mean “eat a meal,” “meal,” or “food,” with the nominal
		interpretation extending beyond the event itself
		<Ref k="nakagawa2024" p="120–121" />. His grammatical evidence includes object use and nominal
		modification. Conversion also enters the compound analyses described in <Xr
			ch="noun-noun-compounding"
		/>.
	</p>
	<p>
		Noun-based formations include prefixes such as <i lang="ain-Latn">ar-</i> in Satō's
		<i lang="ain-Latn">ar-kamyasi</i>
		“real monster” and the diminutive
		<i lang="ain-Latn">-po</i> in <i lang="ain-Latn">cep-po</i> “small fish”
		<Ref k="sato2008" p="266" />. Diminutive and affective formations are treated in <Xr
			ch="nominal-derivation-diminutive-augmentative"
		/>.
	</p>
</S>

<S t="Historical analysis and the Sakhalin comparison" id="grammaticalization">
	<p>
		Bugaeva proposes that lexical nominalizing suffixes developed from nominalizing words and
		earlier nominal heads <Ref k="bugaeva2016" p="100" /> ‹speculative›. The proposal connects lexical
		formation with relative-clause structure while retaining the different functions found in the later
		constructions.
	</p>
	<p>
		<strong>Sakhalin comparison.</strong> Bugaeva contrasts Hokkaido formations with nominalizing
		words and West Coast Sakhalin verbal forms carrying possessive morphology. Her comparison
		includes clause nominalization and several sentence-level uses, but assigns no lexical
		noun-forming use to the Sakhalin verb-plus-possessive construction
		<Ref k="bugaeva2016" p="113–114, Table 1" />. The historical relation between these strategies
		is presented as a proposed development
		<Ref k="bugaeva2016" p="114" /> ‹speculative›.
	</p>
</S>
