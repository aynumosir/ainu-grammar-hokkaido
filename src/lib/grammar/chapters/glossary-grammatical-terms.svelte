<S t="How the terms are used" id="scope">
	<p>
		This glossary explains the descriptive terms used in the grammar. Some identify observable
		distributions; others belong to competing analyses. A label such as ‘fourth person’, ‘formal
		noun’, or ‘perfective’ does not imply that all authors analyze the relevant forms alike. The
		linked chapters compare those differences. Abbreviated gloss labels are listed in
		<Xr ch="abbreviations-glossing-symbols" />.
	</p>
</S>

<S t="Arguments and alignment" id="arguments">
	<dl>
		<dt>Oblique</dt>
		<dd>
			A participant expressed outside the core argument pattern, often through a postpositional
			phrase. Its semantic relation and grammatical status depend on the construction.
		</dd>
		<dt>Argument</dt>
		<dd>
			A participant licensed by a predicate, such as the person who sees or the thing seen.
			Arguments can be understood without an overt noun phrase.
		</dd>
		<dt>S, A, O</dt>
		<dd>
			Comparative role labels: S is the sole argument of an intransitive verb; A and O distinguish
			the more agent-like and more patient-like arguments of a transitive verb. Their actual
			meanings depend on the verb.
		</dd>
		<dt>Valency</dt>
		<dd>
			The number and grammatical arrangement of a predicate's arguments. It is distinct from how
			many noun phrases happen to be spoken.
		</dd>
		<dt>Transitive and intransitive</dt>
		<dd>
			Verb classes distinguished by argument structure and person-marking behavior. A transitive
			verb can appear without an overt object noun phrase.
		</dd>
		<dt>Alignment</dt>
		<dd>
			The grouping of S, A, and O in marking or syntax. Ainu person series and constructions show
			different groupings; a single label does not describe every part of the system.
		</dd>
		<dt>Head marking</dt>
		<dd>
			Marking a grammatical relationship on its head, as when a verb indexes participants or a
			possessed noun marks its possessor.
		</dd>
		<dt>Case and postposition</dt>
		<dd>
			Case concerns grammatical relations; a postposition follows a nominal expression and specifies
			a relation. These are different kinds of description, even when the same construction is
			discussed under both.
		</dd>
	</dl>
	<p>
		See <Xr ch="verbal-subclasses-taxonomy" /> and
		<Xr ch="person-marking-architecture" /> for the Ainu diagnostics and competing alignment descriptions
		<Ref k="bugaeva2012" p="472–475" />.
	</p>
</S>

<S t="Person and reference" id="person">
	<dl>
		<dt>Inclusive and exclusive</dt>
		<dd>
			First-person plural reference including or excluding the addressee. The morphological
			distinctions and their other uses vary regionally.
		</dd>
		<dt>Fourth person</dt>
		<dd>
			A conventional label for a person-form series. Depending on construction and dialect, it can
			express inclusive, indefinite, impersonal, honorific, or narrative reference.
		</dd>
		<dt>Indefinite and generic reference</dt>
		<dd>
			An indefinite expression leaves an individual unspecified; generic reference concerns a class
			or people in general. The two need not have identical grammar.
		</dd>
		<dt>Logophoric reference</dt>
		<dd>
			Reference associated with the person whose speech, thought, or perspective is represented.
			Accounts differ on how Ainu quotation and narrative forms should be analyzed.
		</dd>
		<dt>Honorific use</dt>
		<dd>
			A form selected to express respect toward a participant. Grammatical plurality can have
			singular respectful reference.
		</dd>
		<dt>Zero marking</dt>
		<dd>
			The absence of an overt marker in a paradigm cell. An unmarked verb is interpreted within its
			construction; imperatives, for example, need not refer to a third person.
		</dd>
	</dl>
	<p>
		The paradigms and interpretations are compared in
		<Xr ch="indefinite-fourth-person-paradigm" />,
		<Xr ch="fourth-person-honorific" />, and
		<Xr ch="logophoric-narration-and-reported-discourse" />.
	</p>
</S>

<S t="Words and nominal constructions" id="words">
	<dl>
		<dt>Portmanteau</dt>
		<dd>
			A form expressing a combination of grammatical values without a separate segment for each, as
			in some person-interaction analyses.
		</dd>
		<dt>Morpheme, stem, affix</dt>
		<dd>
			A morpheme is an analytical unit of form and grammatical or lexical function. A stem is a base
			for further morphology; an affix attaches to a base.
		</dd>
		<dt>Clitic</dt>
		<dd>
			An element dependent on a neighboring host, often with a distribution different from ordinary
			affixes. The term requires grammatical and prosodic evidence; this grammar's equals sign alone
			does not establish clitic status.
		</dd>
		<dt>Concept and affiliative forms</dt>
		<dd>
			Terms for noun forms distinguished in descriptions of possession and related dependence. An
			affiliative form commonly denotes something in relation to a possessor; suffix patterns and
			usage vary by noun and dialect.
		</dd>
		<dt>Alienable and inalienable possession</dt>
		<dd>
			Descriptive categories for contrasting possessive constructions, often associated with
			ordinary ownership versus inherent relationships. A noun's actual construction cannot always
			be predicted from that semantic contrast.
		</dd>
		<dt>Locative or spatial noun</dt>
		<dd>
			A noun expressing a position or region relative to another entity. Its nominal behavior
			matters in distinguishing it from a postposition.
		</dd>
		<dt>Formal noun</dt>
		<dd>
			A traditional descriptive term for a noun-like dependent expression with a grammatical role,
			often after a modifying clause. Different accounts give these forms different category
			boundaries.
		</dd>
		<dt>Relative clause</dt>
		<dd>
			A clause modifying a nominal head, with a semantic relationship between that head and the
			clause. Ainu also permits modifying clauses whose relationship is established more broadly by
			context.
		</dd>
		<dt>Copula and existential</dt>
		<dd>
			A copula relates a subject to a nominal predicate; an existential predicates existence or
			location. Ainu ne and an/oka(y) belong to different constructions.
		</dd>
		<dt>Nominal and verbal number</dt>
		<dd>
			Nominal number concerns individuals or groups denoted by a noun phrase. Verbal number can
			concern participants, actions, or situations, depending on the verb and analysis.
		</dd>
		<dt>Transnumerality</dt>
		<dd>
			Number neutrality: an unmarked nominal expression can refer to one or more entities where
			context permits.
		</dd>
		<dt>Nominalization</dt>
		<dd>
			The use or formation of an expression with nominal properties. Whether a particular Ainu
			construction involves a nominalizing affix, a separate nominal head, or another analysis is
			source-dependent.
		</dd>
		<dt>Property predicate</dt>
		<dd>
			A predicate describing a quality or state. Many corresponding Ainu words show verbal behavior;
			the status and extent of an adjective class are disputed.
		</dd>
	</dl>
	<p>
		See <Xr ch="alienable-inalienable-split" />,
		<Xr ch="relational-and-spatial-nouns" />,
		<Xr ch="nominalization-p-pe" />, and
		<Xr ch="no-adjective-class-property-verbs" />.
	</p>
</S>

<S t="Derived predicates" id="derivation">
	<dl>
		<dt>Causative</dt>
		<dd>
			A construction introducing causation, often adding a causer to the argument structure. Ainu
			productive causatives and lexical transitive pairs require separate treatment.
		</dd>
		<dt>Applicative</dt>
		<dd>
			A derivation giving an associated participant a core relation to the verb. Ainu e-, o-, and
			ko- have construction-specific meanings and restrictions.
		</dd>
		<dt>Reflexive and reciprocal</dt>
		<dd>
			Reflexive interpretation identifies participants within a predicate; reciprocal interpretation
			relates members of a group to one another. Ainu si-, yay-, and u- have uses beyond a single
			English reflexive or reciprocal paraphrase.
		</dd>
		<dt>Antipassive</dt>
		<dd>
			An analysis in which an object is demoted or left unspecified while the actor remains central.
			The range and historical interpretation of Ainu i- are disputed.
		</dd>
		<dt>Noun incorporation</dt>
		<dd>
			A construction combining nominal material with a verb in a complex predicate. Wordhood,
			argument structure, and possessor behavior help distinguish its subtypes.
		</dd>
		<dt>Quasi-incorporation</dt>
		<dd>
			Satō’s analysis of certain noun–verb combinations as one lexical unit even when they remain
			two morphological words. He tentatively extends this analysis to a locative noun with a case
			particle, including or ta.
		</dd>
	</dl>
	<p>
		Satō’s proposed extension to locative constructions remains hypothetical
		<Ref k="sato2021" p="89–94; 97, §6" />. Tamura discusses related noun–verb constructions under
		<span lang="ja">連他動詞</span>
		<Ref k="tamura1997" p="15" />. The distinctions and examples appear in
		<Xr ch="noun-incorporation-oblique-polysynthesis-debate" />.
	</p>
</S>

<S t="Time, evidence, and discourse" id="discourse">
	<dl>
		<dt>Switch-reference</dt>
		<dd>
			Marking that tracks whether participants in linked clauses are the same or different.
			Proposals applying this to Ainu connectives require qualification; hine and akusu do not form
			an exceptionless same-subject/different-subject pair.
		</dd>
		<dt>Tense</dt>
		<dd>
			Grammatical location of a situation relative to a reference time. Ainu can express time
			without obligatory tense inflection.
		</dd>
		<dt>Aspect</dt>
		<dd>
			The presentation of a situation's temporal course, including continuation, completion,
			repetition, and resulting state.
		</dd>
		<dt>Perfective and perfect</dt>
		<dd>
			Perfective presents a situation as bounded or complete; perfect commonly relates an earlier
			situation to a later reference point. These labels belong to competing accounts of Ainu a and
			related forms.
		</dd>
		<dt>Modality</dt>
		<dd>
			Meanings involving possibility, necessity, intention, or the speaker's assessment and stance.
		</dd>
		<dt>Evidentiality</dt>
		<dd>
			The expression of the basis or source of information. Ainu constructions with ruwe, siri,
			hawe, and humi also have discourse and modal uses whose analysis differs by author.
		</dd>
		<dt>Mirativity</dt>
		<dd>
			The presentation of information as newly discovered, unexpected, or surprising. Its
			relationship to Ainu evidential and aspectual forms remains an analytical question.
		</dd>
		<dt>Topic and focus</dt>
		<dd>
			Topic concerns what an utterance is about; focus concerns the information singled out within a
			relevant set of alternatives. Their expression depends on context as well as particles and
			syntax.
		</dd>
		<dt>Register and genre</dt>
		<dd>
			Register concerns language associated with a situation or social use; genre concerns a type of
			discourse or performance. A poetic feature need not occur in every verse genre or be absent
			from prose.
		</dd>
	</dl>
	<p>
		For the competing analyses, see <Xr ch="perfective-anterior-a" />,
		<Xr ch="evidential-schema-overview" />, and
		<Xr ch="oral-literature-genre-taxonomy" />.
	</p>
</S>

<S t="Sound structure and language change" id="sound-history">
	<dl>
		<dt>Phoneme</dt>
		<dd>A contrastive sound unit within the analysis of a particular variety.</dd>
		<dt>Allophone and allomorph</dt>
		<dd>
			An allophone is a phonetic realization of a phoneme; an allomorph is a variant form of a
			morpheme.
		</dd>
		<dt>Pitch accent</dt>
		<dd>
			A word-level contrast or pattern expressed through pitch. Varieties without distinctive word
			accent can still have sentence intonation and pitch variation.
		</dd>
		<dt>Polysynthesis</dt>
		<dd>
			A typological characterization of languages with complex word formation, often including
			incorporation or extensive participant marking. Its definition varies; it does not by itself
			decide the boundary of an Ainu word.
		</dd>
		<dt>Grammaticalization</dt>
		<dd>
			The development of grammatical functions from lexical expressions or constructions. Proposed
			historical stages require evidence beyond present-day similarity.
		</dd>
	</dl>
