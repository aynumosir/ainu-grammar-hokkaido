<S t="Affected participants and different constructions" id="overview">
	<p>
		Ainu has several constructions that present an affected participant without an ordinary personal
		actor as subject. They include middle <i lang="ain-Latn">ci-</i>, passive-like uses of
		fourth-person A marking, and verbs in <i lang="ain-Latn">si-</i> with spontaneous or
		anticausative meanings. Their morphology, participant structure and lexical distribution differ <Ref
			k="nakagawa2024"
			p="189–190, 428–430"
		/>;
		<Ref k="bugaevakobayashi2022" p="§§4.2.2, 4.2.4" />.
	</p>
</S>

<S t="Middle ci- and resultative descriptions" id="middle">
	<p>
		Nakagawa derives one-place <i lang="ain-Latn">ci-cari</i> “be scattered” from two-place
		<i lang="ain-Latn">cari</i>
		“scatter.” In his middle analysis, the affected participant becomes the subject <Ref
			k="nakagawa2024"
			p="189"
		/>. The Handbook uses the descriptive gloss RES, “object-resultative,” while noting that the
		construction has received limited study <Ref k="bugaevakobayashi2022" p="§4.2.4" />.
	</p>
	<Ex
		m="tane anakne aynu kam ka upas ka ta ci-cari kamuyasi kam ka ci-cari kor"
		g="now TOP human flesh ADD snow top LOC MID-scatter monster flesh ADD MID-scatter CONJ"
		tr="Now human flesh lay scattered on the snow, and the monster's flesh also lay scattered, and …"
		cite="nakagawa2024:189"
		dial="CHI"
		place="Example 167"
		note="The first and third ka are additive particles; the ka after upas is the spatial noun ‘top’. The snow is the location of the scattered flesh."
	/>
	<p>The resultative description is also illustrated by a phrase from Tamura's Saru dictionary.</p>
	<Ex
		m="kem-ihi ci-car-i uske-he"
		g="blood-POSS RES-scatter-TR.SG place-POSS"
		tr="A place where blood clots are scattered."
		cite="bugaevakobayashi2022:§4.2.4"
		dial="SAR"
		place="Example 28, quoting Tamura 1996:48"
		note="The final i in ci-car-i is the verbal TR.SG suffix in the source's segmentation. Possessive morphology occurs on kem-ihi and uske-he."
	/>
	<p>
		Nakagawa reports that these middle verbs occur mainly in the third person, with other persons
		uncommon. Shirasawa Nabe rejects <i lang="ain-Latn">*ku=cimontapire</i> for “I was caught off
		guard and flustered” and prefers
		<i lang="ain-Latn">a=en=montapire</i>. This is a particular Chitose judgment, alongside his more
		qualified statement about the class <Ref k="nakagawa2024" p="189" />.
	</p>
	<p>
		In Saru and Chitose, <i lang="ain-Latn">ci-</i> often loses its vowel before
		<i lang="ain-Latn">a, u, e, o</i>, giving <i lang="ain-Latn">ca, cu, ce, co</i>. Nakagawa
		relates it historically to personal <i lang="ain-Latn">ci=</i>, without equating their present
		functions ‹speculative› <Ref k="nakagawa2024" p="189–190" />. Refsing reports no middle
		<i lang="ain-Latn">a-/ci-</i>
		examples in her Shizunai material and describes spontaneous events with
		<i lang="ain-Latn">si-</i>
		<Ref k="refsing1986" p="31" />. These descriptions have different dialect and material coverage.
	</p>
</S>

<S t="Indefinite-person forms in passive constructions" id="passive">
	<p>
		Fourth-person A forms can background the actor. An agent can be expressed with
		<i lang="ain-Latn">or(o) wa</i>, a locative-noun and ablative expression. Nakagawa gives the
		following comparison to illustrate the construction
		<Ref k="nakagawa2024" p="428–429" />.
	</p>
	<Ex
		m="seta or wa aynu a=kupapa"
		g="dog place ABL human 4.A=bite"
		tr="The person was bitten by the dog."
		cite="nakagawa2024:429"
		place="Author's illustration 945″"
		note="The dog is expressed in the or wa phrase. The a= form does not index it as an ordinary third-person subject."
	/>
	<p>
		The affected participant has O-series person marking when overtly indexed. The agent phrase can
		still identify a particular actor, so the traditional term “indefinite” does not require an
		unknowable agent in every passive use
		<Ref k="sato2008" p="205–206" />;
		<Ref k="shibatani1990" p="58–60" />. Dialect forms and the other uses of the series are
		described in <Xr ch="indefinite-fourth-person-paradigm" />.
	</p>
	<p>
		Nakagawa distinguishes this construction from middle <i lang="ain-Latn">ci-</i>, which he
		describes as unable to take the same agent phrase. He also discusses different uses of
		<i lang="ain-Latn">ci-</i>
		in poetic expansions
		<Ref k="nakagawa2024" p="430" />. A similar English passive translation can therefore correspond
		to grammatically different Ainu expressions.
	</p>
</S>

<S t="The syntactic status of the passive patient" id="analysis">
	<p>
		Satō and Nakagawa retain object status for the affected participant in the
		<i lang="ain-Latn">a=</i> construction. Satō supports this analysis with the desire
		construction: a speaker who wants to be loved uses a nominalized desired event plus
		<i lang="ain-Latn">ku=ki rusuy</i>, as when the desirer differs from the subject of the desired
		event <Ref k="sato2008" p="205–206" />;
		<Ref k="nakagawa2024" p="428–429" />.
	</p>
	<Ex
		m="huci oro wa a=en=omap hi ku=ki rusuy pe ne korka"
		g="grandmother place ABL 4.A=1SG.O=love NMLZ 1SG.A=do DES NMLZ COP CONC"
		tr="I would like my grandmother to love me, but …"
		cite="sato2008:206"
		place="Opening of the grandmother example"
		note="The sentence continues by saying that grandmother does not love the speaker. En= indexes the speaker as object in the nominalized event; ku= marks the desirer on ki."
	/>
	<p>
		Shibatani argues for syntactic subjecthood despite the object morphology. His evidence includes
		the patient's position before an ablative agent phrase and honorific plural verbs referring to
		the patient in Classical Ainu. He interprets the mismatch as syntactic reanalysis of an
		indefinite-person construction, with older morphology surviving ‹contested› <Ref
			k="shibatani1990"
			p="58–60"
		/>. His account and Satō's differ in the syntactic diagnostics and material they emphasize.
		Their disagreement concerns grammatical relations as well as the choice of the term “passive.”
	</p>
</S>

<S t="Spontaneous change and anticausatives" id="anticausative">
	<p>
		Some verbs in <i lang="ain-Latn">si-</i> present a change without an expressed causer. Bugaeva
		distinguishes these anticausatives from self-induced motion, which she calls autocausative, and
		proposes a historical development through reflexive, autocausative and anticausative functions
		‹speculative› <Ref k="bugaeva2025" p="178–181" />. The lexical constructions and competing
		accounts of <i lang="ain-Latn">si-</i> are described in <Xr ch="reflexive-possessive-si" />.
		This family of meanings does not make every reflexive verb spontaneous or every passive
		construction intransitive under all analyses.
	</p>
</S>
