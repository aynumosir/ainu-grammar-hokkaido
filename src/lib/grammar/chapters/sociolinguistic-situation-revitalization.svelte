<S t="Historical setting and language shift" id="history">
	<p>
		The shift from Ainu to Japanese took place under unequal social and political conditions. Ōno
		describes restrictions on Ainu use in schools, the growing need for Japanese in daily life, and
		discrimination that discouraged families from transmitting Ainu to children. He reports no
		general legal prohibition of the language, while documenting restrictions in particular settings <Ref
			k="ono2022"
			p="§2"
		/>. Language shift consequently cannot be explained by a single ban or date.
	</p>
	<p>
		Transmission and documentation also varied by locality and family. People could retain knowledge
		of songs, stories, prayers, or familiar expressions after Japanese became their usual language.
		Ōno's account follows the changing roles of recording, teaching, and public language activity in
		this history <Ref k="ono2022" p="§§2–4" />. The broader history of settlement and displacement
		is outlined in <Xr ch="ainu-people-homeland-history" />.
	</p>
</S>

<S t="Speakers and language knowledge" id="speakers">
	<p>
		Speaker estimates depend on what is being counted. Childhood acquisition, the ability to sustain
		a conversation, knowledge of a particular genre, and later study describe different kinds of
		competence. In his 2022 account, Ōno reports very few fluent speakers and severe difficulties in
		finding childhood speakers able to assess newly composed examples across a wide range of topics <Ref
			k="ono2022"
			p="§8"
		/>. These observations concern the situation described in that publication; they do not supply a
		current census.
	</p>
	<p>
		Janhunen distinguishes remaining childhood speakers with partial competence from people who have
		learned Ainu later in life, including both Ainu and non-Ainu learners
		<Ref k="janhunen2022" p="§2(3)" />. A population estimate for people of Ainu ancestry cannot be
		substituted for a count of speakers. For linguistic work, the relevant information is a
		speaker's learning history, variety, repertoire, and the circumstances of the recorded speech.
	</p>
</S>

<S t="Recording and community teaching" id="revival">
	<p>
		Ainu speakers have taken an active part in creating the written record. Ōno discusses Chiri
		Yukie's collection of divine songs, Kannari Matsu's extensive narrative manuscripts, and the
		Ainu-language periodical <i>Aynu-mosir</i>, published by Yamamoto Tasuke and Yamaji Hiroaki
		between 1957 and 1965 <Ref k="ono2022" p="§3" />. These materials reflect choices made by
		writers and narrators about what to preserve and how to address their readers.
	</p>
	<p>
		Kayano Shigeru's work in Nibutani joined the collection of cultural materials with language
		teaching. After efforts to include Ainu teaching in a nursery met administrative obstacles, he
		opened a private language school in 1983. The Ainu Association began an organized programme of
		local language classes in 1987 <Ref k="ono2022" p="§4" />. Ōno also describes activities among
		Ainu living in the Tokyo region, showing that the movement extended beyond Hokkaido.
	</p>
	<p>
		Cooperation between community organizations and researchers has involved access to recordings,
		teaching materials, and linguistic analysis. Ōno places this cooperation within a longer history
		of unequal relations between researchers and the people whose language they studied
		<Ref k="ono2022" p="§5" />. Attribution to narrators and recognition of their decisions about
		recording remain relevant when such materials are reused.
	</p>
</S>

<S t="Institutions and public support" id="legislation">
	<p>
		The 1997 Ainu Culture Promotion Act was followed by the establishment of the Foundation for
		Research and Promotion of Ainu Culture. Its activities included support for language teaching
		and radio courses <Ref k="ono2022" p="§6, §8.3" />. Ōno subsequently describes the 2008 Diet
		resolution on indigenous recognition and the 2019 law that replaced the 1997 act
		<Ref k="ono2022" p="§7" />.
	</p>
	<p>
		Upopoy opened in Shiraoi in July 2020. It includes the National Ainu Museum, a park, and
		memorial facilities. Ōno discusses its opportunities for cultural and language activity,
		alongside the question of how support reaches Ainu communities in other places
		<Ref k="ono2022" p="§7.3" />. Institutional visibility and opportunities for sustained language
		use are separate matters in his assessment.
	</p>
	<p>
		Training programmes have also supported learners who later work in cultural institutions and
		teaching. Ōno describes the Foundation's programme beginning in Shiraoi in 2008 and its move to
		Biratori in 2020, as well as university initiatives
		<Ref k="ono2022" p="§§7.1–7.2" />. Those dates specify the programmes covered by his account.
	</p>
</S>

<S t="Writing and teaching materials" id="orthography">
	<p>
		Latin transcription and katakana are both used to write Hokkaido Ainu. Ōno discusses the
		practical demands each places on learners, including familiarity with the writing system and the
		representation of Ainu sounds <Ref k="ono2022" p="§8" />. The conventions are explained in <Xr
			ch="latin-phonemic-transcription"
		/> and
		<Xr ch="katakana-and-small-kana-codas" />. Differences between written forms may reflect
		dialect, transcription, or an author's spelling choices.
	</p>
	<p>
		Teaching materials include both recorded utterances and examples composed for instruction. Ōno
		identifies a practical difficulty: restricting a textbook to surviving recordings limits its
		topics, while new examples may be difficult to check with childhood speakers
		<Ref k="ono2022" p="§8" />. Their provenance therefore matters when they are used as evidence
		for grammar. A teaching example can illustrate an analysis without establishing its frequency in
		earlier speech.
	</p>
</S>

<S t="Vocabulary for contemporary use" id="neologisms">
	<p>
		Contemporary language use requires expressions for institutions, technologies, and activities
		that may be poorly represented in older recordings. Ōno describes both the incorporation of
		Japanese expressions and proposals for Ainu formations, including terms used at Upopoy
		<Ref k="ono2022" p="§8" />. His account also notes earlier coinages associated with changes in
		everyday life, showing that lexical innovation has a history within Ainu-speaking communities.
	</p>
	<p>
		A proposed form, its adoption in a particular setting, and its wider circulation are distinct
		observations. Grammatical discussion needs to identify the source and use of an example. Older
		Japanese borrowings are described in <Xr ch="japanese-loanwords-in-ainu" />; the history of
		lexical contact is considered separately from contemporary proposals.
	</p>
</S>

<S t="Learning and opportunities for use" id="new-speakers">
	<p>
		Ōno distinguishes learning about the language from developing the ability to converse in it. He
		describes classes organized around place names, rituals, recorded stories, or grammatical
		explanation, and argues for more opportunities to practise speaking and listening
		<Ref k="ono2022" p="§8" />. The range of activities helps explain why participants can develop
		different repertoires even after several years of involvement.
	</p>
	<p>
		Later learners work with teachers, recordings, dictionaries, and grammars, often while using
		Japanese for most daily communication. Ōno discusses the resulting influence of Japanese on new
		expressions and the limited availability of fluent childhood speakers for consultation
		<Ref k="ono2022" p="§8" />. Specific claims about a new-speaker variety require examples from
		identified speakers or communities. The historical corpus alone cannot establish how a
		contemporary group uses the language.
	</p>
</S>
