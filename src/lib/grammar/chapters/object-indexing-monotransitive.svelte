<S t="Two objects and one object index" id="three-place">
	<p>
		Three-place verbs such as <i lang="ain-Latn">kore</i> “give” and
		<i lang="ain-Latn">nukare</i> “show” involve a subject and two objects. Satō distinguishes these
		arguments from the person indexes: his account does not allow both objects to receive separate O
		indexes simultaneously. A meaning such as “he introduced me to you” may require a paraphrase
		that distributes the participants across clauses
		<Ref k="sato2008" p="147–148" />. The number of indexes consequently does not determine the
		verb's semantic valency; see <Xr ch="transitivity-and-valence-classes" />.
	</p>
	<p>
		Satō's 2008 account reports recipient indexing for these giving and showing constructions. His
		later discussion explicitly acknowledges theme-indexing examples reported by Bugaeva 2011:244,
		while retaining recipient indexing as the basic pattern for
		<i lang="ain-Latn">kore</i>
		<Ref k="sato2023b" p="40 n. 5" /> ‹contested›. The later qualification prevents a universal recipient-only
		rule. It does not establish how frequent either construction is.
	</p>
</S>

<S t="Fourth-person i= and derivational i-" id="i">
	<p>
		Fourth-person <i lang="ain-Latn">i=</i> belongs to the person paradigm. Its reference can be
		inclusive, honorific, or narrative, depending on the construction
		<Ref k="nakagawa2024" p="170, 174–180" />. The derivational prefix
		<i lang="ain-Latn">i-</i>, by contrast, can form a verb with an unspecified object. Bugaeva
		analyzes <i lang="ain-Latn">i-sitoma</i> “fear” as an antipassive formation even in a clause
		whose support verb has fourth-person A marking <Ref k="bugaeva2012" p="475, example 18b" />.
	</p>
	<p>
		The relationship between the two has received different analyses. Refsing treats the objective
		form in close connection with her intransitivizing prefix
		<Ref k="refsing1986" p="31, 218–219" /> ‹contested›. Satō also records honorific
		<i lang="ain-Latn">ku-i-kusa</i>, but rejects the corresponding formation with
		<i lang="ain-Latn">kore</i>; he treats this as restricted derivation rather than a complete
		person-paradigm row <Ref k="sato2008" p="147" />.
	</p>
</S>

<S t="Unexpressed third person" id="third-zero">
	<p>
		A third-person argument need not have an overt exponent on the verb. Satō represents this
		structurally with a zero affix and explains why ordinary examples can leave it unwritten
		<Ref k="sato2008" p="121, 147" />. Nakagawa's tables leave the third-person cells blank
		<Ref k="nakagawa2024" p="167, 170" />. Their notation agrees on the absence of an audible form;
		the analysis of zero morphology is discussed in <Xr ch="person-marking-architecture" />. An
		unexpressed object index therefore does not establish that a verb is intransitive.
	</p>
</S>
