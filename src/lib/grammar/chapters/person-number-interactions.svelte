<S t="Person number and verbal number" id="overview">
	<p>
		Person forms and verb stems can both express number. Their relationship depends on the verb, the
		construction, and the use of the person series. Some verbs distinguish singular and plural
		stems; others have no such pair, or use a plural formation for repeated or distributed events
		<Ref k="nakagawa2024" p="141–160" />. The inventory and meanings of these formations appear in <Xr
			ch="suppletive-verbal-number"
		/>.
	</p>
	<p>
		Third person has no overt singular–plural contrast in the basic person paradigm
		<Ref k="nakagawa2024" p="166–170" />. A change in verb stem can therefore express number even
		where person marking remains unchanged.
	</p>
</S>

<S t="Participants identified by nouns and phrases" id="plural-control">
	<Ex
		m="kunneywa tunas a=yupi hopuni hine suke"
		g="morning early 4.POSS=elder.brother rise.SG CONJ cook"
		tr="Early in the morning, my elder brother got up and cooked."
		cite="nakagawa2024:151"
		dial="SAR"
		place="Example 57"
	/>
	<Ex
		m="kunneywa an hine a=yuputari ka hopunpa"
		g="morning exist CONJ 4.POSS=elder.brothers ADD rise.PL"
		tr="When morning came, my elder brothers also got up."
		cite="nakagawa2024:151"
		dial="SAR"
		place="Example 58"
		note="These are separate source sentences. The a= forms mark nominal possession; the predicates have third-person subjects."
	/>
	<p>
		Here the number of the subject is expressed in both the noun and the verb stem. Comitative
		expressions can instead describe the participants through a combination of phrases. Shibatani's
		Ishikari example groups the speaker with the husband and uses a plural motion verb with
		first-plural S marking <Ref k="shibatani1990" p="36, example 48c" />.
	</p>
	<Ex
		m="ku=kor-kur ku=tura Aspet ta arki=as"
		g="1SG.A=have-person 1SG=with Aspet LOC come.PL=1PL.S"
		tr="My husband and I went to Ashibetsu."
		cite="shibatani1990:36"
		dial="ISH"
		place="Example 48c"
		note="The translation follows Shibatani. Arki is the plural come stem; the source also prints ku- on tura. Person boundaries are normalized."
	/>
	<p>
		This example supports participant grouping in that construction. It does not make the number of
		overt noun phrases a general rule for choosing a person suffix.
	</p>
</S>

<S t="Numerals and plural stems" id="numerals">
	<p>
		Refsing disputes earlier claims that a numeral expression excludes a plural verb. In her
		Shizunai material, plural person marking accompanies a plural stem, where one exists, even when
		a numeral is present. Examples without overt person marking show greater variation
		<Ref k="refsing1986" p="38" /> ‹contested›. Her observation concerns the data and construction she
		describes; neither an obligatory singular-stem rule nor an obligatory plural-stem rule follows for
		every numeral phrase in Ainu.
	</p>
	<p>
		The person marker <i lang="ain-Latn">eci=</i> also requires care. Its ordinary second-plural use
		contrasts with a Saru/Chitose portmanteau that can represent two singular participants, “I” and
		“you” <Ref k="nakagawa2024" p="170–173" />. Its spelling alone does not establish plural
		reference. See <Xr ch="eci-portmanteau-and-second-plural" />.
	</p>
</S>

