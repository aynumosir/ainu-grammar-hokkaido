		<i lang="ain-Latn">siri an</i> and <i lang="ain-Latn">siri ki</i>, discussing what visible
		evidence licenses an inference. The account also examines combinations with formal-noun endings,
		while expressly limiting its regional coverage <Ref k="dalcorso2018" p="326–327" />.
	</p>
