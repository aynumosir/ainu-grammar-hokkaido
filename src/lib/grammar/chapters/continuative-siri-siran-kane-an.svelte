<S t="Kane an and the situation that continues" id="kane">
	<p>
		<i lang="ain-Latn">Kane an</i> can describe an activity in progress or a state left by an
		earlier change. Its distribution differs across regional descriptions. Nakagawa's Samani
		examples include both carrying a bag and sucking a finger; these correspond to different
		<i lang="ain-Latn">wa an</i>
		and
		<i lang="ain-Latn">kor an</i> constructions in the Saru comparisons
		<Ref k="nakagawa2024" p="447, examples 1008–1011" />.
	</p>
	<Ex
		m="askepeci kemkem kane an na"
		g="finger suck CONJ exist.SG FIN"
		tr="The baby is sucking a finger."
		cite="nakagawa2024:447"
		dial="SAM"
		place="Example 1010"
		note="The source supplies the baby as the understood subject; no noun meaning ‘baby’ occurs in the Ainu sentence."
	/>
	<p>
		For Shizunai, Yoshikawa discusses examples involving growth and becoming white that allow either
		an ongoing-change or a resulting-state interpretation
		<Ref k="yoshikawa2021shizunai" p="8–9, §3.1" />. Nakagawa also cites a Shizunai description of
		vines wrapped around door and window openings as a resulting-state use <Ref
			k="nakagawa2024"
			p="447, example 1007"
		/>. In the Ishikari and Horobetsu examples he surveys, resulting states are particularly
		prominent <Ref k="nakagawa2024" p="447–448" />.
	</p>
</S>

<S t="Emphasis, degree, and ordinary continuation" id="interpretation">
	<p>
		Saru and Chitose accounts give additional weight to how a situation is presented. Nakagawa
		reports Tamura's unexpectedness analysis and Satō's proposal that
		<i lang="ain-Latn">kane</i> fundamentally relates to reaching a degree or standard. He favors
		the latter as a broad account while recognizing emphatic uses in actual examples <Ref
			k="nakagawa2024"
			p="308, 446–447, reporting Tamura 1960:75 and Satō 2002:84–85"
		/>.
	</p>
	<p>
		One Saru passage describes a bear deity appearing in a dream after the bear's head has been
		ritually prepared. It contains both
		<i lang="ain-Latn">sapa tuye kane an</i>, concerning the prepared head, and
		<i lang="ain-Latn">mina kane an</i>, concerning laughter. The ritual and dream context explains
		why a literal translation of the first expression alone would mislead <Ref
			k="nakagawa2024"
			p="446, example 1004"
		/>. Yoshikawa's analysis also stresses conventional combinations with particular predicates;
		interchangeability with <i lang="ain-Latn">kor an</i> is limited
		<Ref k="yoshikawa2022" p="§3.2" />.
	</p>
</S>

<S t="Kan an and tek an" id="regional">
	<p>
		Tokachi and Ishikari have <i lang="ain-Latn">kan an</i>, also pronounced as
		<i lang="ain-Latn">kanan</i>. Nakagawa finds ongoing activity especially prominent in the
		Tokachi examples and resulting states in the Ishikari examples. Both readings are represented in
		the comparative material <Ref k="nakagawa2024" p="448" />.
	</p>
