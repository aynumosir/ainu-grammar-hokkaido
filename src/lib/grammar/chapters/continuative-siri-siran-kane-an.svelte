		dial="TOK"
		place="Example 1018, citing Ainu no minwa 2 (1985):232"
		note="The excerpt does not identify the fourth-person subject. Okay is retained as printed."
	/>
	<p>
		Takahashi connects a Tokachi restriction on first-person progressive
		<i lang="ain-Latn">kor an</i> with the availability of <i lang="ain-Latn">kan an</i>, within an
		observational account of the constructions <Ref k="takahashi2022" p="§4" />. Tokachi
		<i lang="ain-Latn">tek an</i>
		also describes lasting states, such as vines covering a house. Its relationship to Saru/Chitose auxiliary
		<i lang="ain-Latn">tek</i>, used for brief actions, remains a question; the meanings cannot
		simply be transferred between the constructions
		<Ref k="nakagawa2024" p="448–449" />.
	</p>
</S>

<S t="Appearance and evidential constructions" id="appearance">
