<S t="Independent pronouns and person markers" id="pronouns-and-indexing">
	<p>
		An independent personal pronoun can identify or contrast a participant, while the predicate
		retains its person marking. In Chitose, for example,
		<i lang="ain-Latn">kani</i> “I” can emphasize the speaker's decision to undertake a task <Ref
			k="nakagawa2024"
			p="255"
		/>. The pronoun and the prefix have different grammatical roles:
	</p>
	<Ex
		m="kani k=uomare kusu ne na"
		g="1SG 1SG.A=tidy.up PURP COP FIN"
		tr="I'll tidy up."
		cite="nakagawa2024:255, example 321"
		dial="CHI"
		note="The speaker intervenes when another person is about to do the tidying."
	/>
	<p>
		Satō and Refsing likewise distinguish independent forms from the person markers carried by
		predicates <Ref k="sato2008" p="27–28" />;
		<Ref k="refsing1986" p="§12.3.1" />. Third person has zero indexing, so this distinction does
		not imply a pronounced affix in every clause. The marker paradigms are in <Xr
			ch="person-marking-architecture"
		/>.
	</p>
</S>

