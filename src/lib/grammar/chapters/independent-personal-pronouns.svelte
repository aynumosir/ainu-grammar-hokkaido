<S t="Emphasis, contrast, and particles" id="pronoun-functions">
	<p>
		Independent pronouns are often unnecessary in a neutral statement whose participants are
		identified by person marking and context. Nakagawa describes an overt pronoun as unusual in a
		neutral narrative self-introduction, while showing its use for emphasis and contrast
		<Ref k="nakagawa2024" p="255–256" />. His contrastive example assigns different amounts of food
		to a puppy and to
		<i lang="ain-Latn">eani</i> “you”; no topic particle is required there.
	</p>
	<p>
		An independent pronoun can also support a particle. Nakagawa contrasts
		<i lang="ain-Latn">kani anakne</i> with the rejected
		<i lang="ain-Latn">*ku= anakne</i>: the person prefix cannot stand alone as the host for topic
		<i lang="ain-Latn">anakne</i>
		<Ref k="nakagawa2024" p="256, example 323" />. This is a syntactic difference between a word and
		a bound marker, beyond their shared person reference.
	</p>
</S>

<S t="Third-person expressions" id="third-person">
	<p>
		Nakagawa includes third-person pronouns and cites their contrastive uses, including Chitose <i
			lang="ain-Latn">sinuma</i
		>
		alongside the narrator's
		<i lang="ain-Latn">asinuma</i>. His Horobetsu examples also contain
		<i lang="ain-Latn">anihi</i>, beyond table 63's
		<i lang="ain-Latn">ani</i>
		<Ref k="nakagawa2024" p="256–257" />.
	</p>
	<p>
		Satō acknowledges <i lang="ain-Latn">sinuma</i> and
		<i lang="ain-Latn">okay</i> in Nakagawa's dictionary, but omits third-person pronouns from his
		teaching paradigm because they are rare
		<Ref k="sato2008" p="26" />. Refsing describes Shizunai reference through demonstrative
		expressions, including <i lang="ain-Latn">ikiap</i>
		<Ref k="refsing1986" p="§§12.3.1–12.3.2" />. These treatments differ in classification and
		material; none establishes a universal absence of third-person pronouns.
	</p>
	<p>
		The plural forms are particularly difficult to count because they coincide with existential <i
			lang="ain-Latn">oka(y)</i
		>. Nakagawa identifies a Saru example whose syntax and antecedent support a pronominal reading
		<Ref k="nakagawa2024" p="257, example 327" />.
	</p>
</S>

<S t="The boundary between group nouns and pronouns" id="utari">
	<p>
		Forms in <i lang="ain-Latn">utari</i> can be pronominal, especially in Tokachi, but similar
		possessed group nouns occur elsewhere. Nakagawa's Chitose
		<i lang="ain-Latn">a=utari</i> in the following question means the addressee's family:
	</p>
	<Ex
		m="a=utar-i opitta totek wa oka ya"
		g="4.A=relative-POSS all be.well CONJ exist.PL Q"
		tr="Is all your family well?"
		cite="nakagawa2024:254, example 318"
		dial="CHI"
		note="The family excludes the addressee in Nakagawa's interpretation; the verbs have third-person zero indexing."
	/>
	<p>
		By contrast, he gives Tokachi <i lang="ain-Latn">anutari</i> with a fourth-person predicate, and
		another example where
		<i lang="ain-Latn">eciutari</i> means “you” but the verb has third-person indexing. He regards
		the latter as intermediate between a group noun and a pronoun <Ref
			k="nakagawa2024"
			p="253–254, examples 316–319"
		/>
		‹contested›. Related nominal forms are discussed in
		<Xr ch="nominal-number-utar-transnumerality" />.
	</p>
</S>

<S t="Formation accounts and historical limits" id="formation">
	<p>
		Nakagawa distinguishes three formation patterns: forms built around an existential verb, forms
		containing <i lang="ain-Latn">utari</i>, and
		<i lang="ain-Latn">sinuma</i>-based forms. His existential account, developed through Tamura
		(1971), includes a nominal element historically related to <i lang="ain-Latn">hi</i>
		<Ref k="nakagawa2024" p="253–255" /> ‹speculative›. Kindaichi and Chiri provide an earlier derivational
		analysis and register-based tables <Ref k="kindaichi1936" p="52–53, §§76–79" />.
	</p>
	<p>
		The older tables include <i lang="ain-Latn">esinuma</i>. Nakagawa reports that an actual example
		has not been confirmed despite its appearance in earlier works <Ref k="nakagawa2024" p="255" />.
		The status of that form differs from the attested pronouns above. Respectful choices likewise
		require contextual and dialect information; see <Xr ch="kinship-honorific-possession" />.
	</p>
</S>
