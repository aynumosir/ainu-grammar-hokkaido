<S t="Connecting predicates and events" id="linking">
	<p>
		Ainu connects predicates with forms such as <i lang="ain-Latn">wa</i>,
		<i lang="ain-Latn">hine</i>, and <i lang="ain-Latn">kor</i>. The verb does not acquire a special
		linking form distinct from its sentence-final form. Nakagawa emphasizes this morphological
		difference from Japanese when explaining why a Japanese translation is an unreliable guide to
		Ainu sentence structure <Ref k="nakagawa2024" p="514–515, §21.1" />.
	</p>
	<Ex
		m="micipa ku=kar hine ohaw or k=omare"
		g="honewort 1SG.A=make CONJ soup inside 1SG.A=put.into"
		tr="I gathered honewort and put it into the soup."
		cite="sato2008:44"
		dial="CHI"
		place="§6.2, hine example"
	/>
	<p>
		The connector relates the gathering and putting-in events. Other connectors can present a cause,
		condition, simultaneous action, concession, or manner. Their uses overlap, and a single form can
		serve more than one relation
		<Ref k="sato2008" p="44–47" />.
	</p>
</S>

<S t="Different accounts of the structure" id="analyses">
	<p>
		Nakagawa groups linking expressions into conjunctive particles, formal nouns, and adverbial
		phrases. He treats them as belonging to neither adjacent sentence, pointing to utterances with a
		pause before the connector and to the possibility of continuing after an apparent sentence
		ending
		<Ref k="nakagawa2024" p="514–515, §§21.1–21.2" />.
	</p>
	<p>
		Refsing distinguishes free conjunctions from bound “conjunctionalizers” in Shizunai. She
		analyzes the preceding sentence as an embedded adjunct and usually places the pause after its
		conjunctionalizer. She also records pauses before it, interpreting these as a delayed decision
		to continue
		<Ref k="refsing1986" p="238–239, §14.12" />.
	</p>
	<p>
		Bugaeva instead organizes Southern Hokkaido clause linkage under coordination and subordination.
		Her inventory includes <i lang="ain-Latn">kor</i> in both groups, with different uses, and she
		notes that Tamura's cited treatment does not make this structural distinction
		<Ref k="bugaeva2012" p="497–498, §15.4.6" />. These classifications reflect different analyses
		of attachment and dependence. The shared verb forms alone do not decide between them.
	</p>
</S>

<S t="Participants across a chain" id="subjects">
	<p>
		Successive predicates may share a subject or introduce another one. Satō's Chitose example names
		a child in the first clause and a barrel in the second <Ref k="sato2008" p="45" />.
	</p>
	<Ex
		m="hekaci suma osura wa ontaro hokus"
		g="boy stone throw CONJ barrel fall.over"
		tr="The child threw a stone and the barrel fell over."
		cite="sato2008:45"
		dial="CHI"
		place="§6.2, causal use of wa"
	/>
	<p>
		Neither third-person subject has an overt person index. The noun phrases, the meanings of the
		predicates, and the event sequence identify their roles. An overt first- or second-person affix
		can provide additional information, as the repeated first-person marking does in the honewort
		example above. The connector <i lang="ain-Latn">wa</i> itself does not require a shared subject <Ref
			k="bugaeva2012"
			p="497"
		/>.
	</p>
</S>

