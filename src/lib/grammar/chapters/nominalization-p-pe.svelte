<S t="Forms and phrase scope" id="forms">
	<p>
		The forms <i lang="ain-Latn">p</i> and <i lang="ain-Latn">pe</i> follow verbal material to form
		expressions referring to a thing, person, or situation. Satō gives
		<i lang="ain-Latn">p</i> after a vowel and <i lang="ain-Latn">pe</i> after a consonant
		<Ref k="sato2008" p="177" />. The relevant sound is the one immediately before the form, even
		when a longer phrase precedes it.
	</p>
	<p>
		Analyses differ over its grammatical category. Nakagawa argues for a clitic analysis of
		phrase-level nominalizers because their scope includes the entire preceding phrase
		<Ref k="nakagawa2022pos" p="§3.3" />. Satō distinguishes a relative-clause head with concrete
		reference from a nominalizer of a whole clause, allowing
		<i lang="ain-Latn">p/pe</i> in both functions <Ref k="sato2008" p="175, 177–180" />. A written
		hyphen or space alone does not resolve this difference.
	</p>
</S>

<S t="A participant identified by a clause" id="participant">
	<p>
		When <i lang="ain-Latn">p/pe</i> denotes a participant, the preceding clause specifies which
		participant is meant. The head can correspond to an object, a subject, or a relation expressed
		by another element in that clause <Ref k="nakagawa2024" p="503–504, 512" />.
	</p>
	<Ex
		m="ani usey a=ku p isam"
		g="with hot.water 4.A=drink thing not.exist"
		tr="There is nothing for me to drink hot water with."
		cite="nakagawa2024:504"
		dial="SAR"
		place="Example 1156"
		note="P identifies the instrument associated with ani, here a drinking vessel. Usey ‘hot water’ is the object of ku ‘drink’."
	/>
	<p>
		Nakagawa requires <i lang="ain-Latn">ani</i> in this instrumental example. The head's general
		meaning ‘thing’ does not remove the need to express its relation to the action. Applicative
		constructions provide another way to express such relations; see <Xr
			ch="applicative-stacking-relativization-feeding"
		/>.
	</p>
	<Ex
		m="a=se wa okay pe tuypa hine su or esikte"
		g="4.A=carry CONJ exist.PL thing cut.PL CONJ pot place fill"
		tr="They cut up what I had been carrying and filled the pot."
		cite="nakagawa2024:512"
		dial="SAR"
		place="Example 1179"
		note="Nakagawa identifies pe as the object of se and the subject of okay. The later cutting and filling predicates have zero third-person marking; a=se identifies the narrative ‘I’ only as the carrier."
	/>
	<p>
		Here carrying is expressed by <i lang="ain-Latn">se</i>; <i lang="ain-Latn">okay</i>
		is the plural existential. The same head participates in both linked clauses. Although its lexical
		meaning is light, it remains an overt head in this analysis. The separate questions of headless and
		internally headed relatives are discussed in
		<Xr ch="headless-internally-headed-noun-modifying-clauses" />.
	</p>
</S>

<S t="A situation or content" id="content">
	<p>
		In other uses, <i lang="ain-Latn">p/pe</i> presents the content of the preceding clause as a
		whole. Nakagawa contrasts the preceding participant examples with a statement about not
		understanding why people are speaking and crying
		<Ref k="nakagawa2024" p="512–513" />.
	</p>
	<Ex
		m="ne kusu haweoka wa cis pa p ka a=erampewtek"
		g="what for speak.PL CONJ cry PL NMLZ ADD 4.A=not.understand"
		tr="I did not understand why they were speaking that way and crying."
		cite="nakagawa2024:512–513"
		dial="SAR"
		place="Example 1180"
		note="The unknown content is the situation or reason for it. Nakagawa explicitly rejects an interpretation in which the speaker does not know which people are crying."
	/>
	<p>
		The distinction concerns the role of the whole expression. It cannot be reduced to
		<i lang="ain-Latn">p/pe</i> always denoting something concrete and
		<i lang="ain-Latn">hi</i> always denoting something abstract. The range of
		<i lang="ain-Latn">hi</i> and other formal nouns is described in
		<Xr ch="lexical-head-formal-noun-nominalization" />.
	</p>
</S>

<S t="People, expectations, and clause endings" id="extensions">
	<p>
		<i lang="ain-Latn">Pe</i> can refer to a person. Satō notes that this often has an unfavorable
		tone, as in <i lang="ain-Latn">wen pe</i> ‘bad person’, and contrasts politer
		<i lang="ain-Latn">kur</i>
		<Ref k="sato2008" p="180" />. The tendency does not make every human use of
		<i lang="ain-Latn">pe</i> derogatory.
	</p>
	<Ex
		m="ratcitara rok=an pe ne na"
		g="quietly sit.PL=4.S NMLZ COP FIN"
		tr="You should sit quietly."
		cite="sato2008:177"
		dial="CHI"
		place="Illustration of pe ne"
		note="The normative address is expressed with the fourth-person series. The plural root and person form need not mean that several addressees are being counted."
	/>
	<p>
		Satō also describes final <i lang="ain-Latn">p/pe</i> as frequently conveying regret, surprise,
		or other emotion <Ref k="sato2008" p="177–178" />. Nakagawa relates adversative linking
		<i lang="ain-Latn">p/pe</i>
		to content nominalization, while recognizing that the linked expression no longer functions as a subject
		or object of the following clause
		<Ref k="nakagawa2024" p="513" />. Participant reference, content nominalization, normative
		predication, and clause linkage are distinct uses that must be interpreted in their own
		constructions.
	</p>
</S>
