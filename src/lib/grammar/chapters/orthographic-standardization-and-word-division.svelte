<S t="Writing systems and their purposes" id="two-scripts">
	<p>
		Latin and katakana writing serve several overlapping purposes in Ainu: recording speech,
		publishing literature, teaching pronunciation, and making grammatical structure visible. These
		purposes can favor different conventions. Nakagawa's survey describes substantial variation
		within both scripts, including publications that cite the same pedagogical model
		<Ref k="nakagawa2024" p="54–69" />.
	</p>
	<p>
		A reference grammar needs readable examples and explicit analysis. Its segmented Latin forms
		show the components relevant to a construction. Source spellings remain important where a change
		of notation could obscure pronunciation, dialect, or an alternative reading; see <Xr
			ch="cyrillic-and-multiscript-rendering"
		/>.
	</p>
</S>

<S t="Shared conventions and continuing variation" id="history">
	<p>
		Modern phonemic Latin transcription developed through the work of Hattori and Tamura in the
		1950s. It coexists with older Hepburn-based conventions and with differences among phonemic
		analyses <Ref k="nakagawa2024" p="54–58" />. The history of those letter systems is described in <Xr
			ch="historical-orthographies-and-the-batchelor-tradition"
		/>.
	</p>
	<p>
		For katakana, <em>Akor Itak</em> supplied a widely cited model after its publication in 1994.
		Nakagawa observes that the model's brief instructions still leave room for different practices <Ref
			k="nakagawa2024"
			p="66–69"
		/>. Satō's account likewise specifies choices for his own grammar, including small final glides
		and a default fixed kana for final /r/
		<Ref k="sato2008" p="16" />. These are identifiable conventions within an ongoing writing
		tradition.
	</p>
</S>

<S t="The equals sign for person marking" id="equals-sign">
	<p>
		Nakagawa explains four ways of writing a person form: joined to its stem, separated by a space,
		linked by a hyphen, or linked by an equals sign. For “I sleep,” his comparison gives
		<i lang="ain-Latn">kumokor</i>, <i lang="ain-Latn">ku mokor</i>,
		<i lang="ain-Latn">ku-mokor</i>, and <i lang="ain-Latn">ku=mokor</i>
		<Ref k="nakagawa2024" p="59" />. The alternatives make the person boundary more or less visible.
	</p>
	<p>
		His equals-sign convention arose from using different marks for person forms and derivational
		affixes. It appeared in the transcription principles of <em>Katari no naka no seikatsushi</em>
		in 1986 and subsequently spread <Ref k="nakagawa2024" p="60" />. It also helps a reader identify
		a dictionary headword when the person prefix changes the beginning of the word.
	</p>
	<p>
		The same sign has a separate use for clitics in the Leipzig Glossing Rules
		<Ref k="comrie2015" />. Here it identifies person marking under the Ainu convention. The
		grammatical status of each form requires evidence about its behavior, as discussed in
		<Xr ch="personal-affix-template-and-ordering" s="status" />.
	</p>
</S>

<S t="Spacing and morphological analysis" id="word-spacing">
	<p>
		Spacing can reflect an analysis of wordhood, a practical reading convention, or both. Nakagawa
		contrasts Kirikae's separated person forms with continuous and hyphenated spelling, and
		discusses the consequences for representing syllables and accent
		<Ref k="nakagawa2024" p="59–61" />. The spaces in a printed text should therefore be interpreted
		alongside the author's grammatical account.
	</p>
	<p>
		In a segmented example, a hyphen identifies a proposed internal boundary. It does not show that
		the two elements can occur independently, nor that a speaker pauses between them. Compoundhood
		and incorporation require additional evidence about distribution and meaning; see <Xr
			ch="noun-noun-compounding"
		/> and <Xr ch="noun-incorporation-object" />.
	</p>
</S>

<S t="Where notations differ" id="contested-choices">
	<p>
		Three recurring differences in Latin spelling concern nasals before labial consonants, glides
		between vowels, and glottal stops. Nakagawa compares the alternatives explicitly
		<Ref k="nakagawa2024" p="57–59" />. Some differences arise from competing phonological analyses;
		others arise from different choices about how much structure to show in print.
	</p>
</S>

<S t="Nasals before p and m" id="nasal-labial">
	<p>
		Before /p/ and /m/, the nasal is pronounced [m]. The spelling can nevertheless preserve an
		underlying or morphologically related /n/. Nakagawa describes three main conventions: writing <em
			>n</em
		>
		throughout this environment; preserving root identity and defaulting to
		<em>n</em> when the root is unclear; or preserving root identity and defaulting to <em>m</em>
		<Ref k="nakagawa2024" p="58–59" />.
	</p>
	<p>
		He associates these respectively with Hattori's dialect dictionary, Tamura's Saru dictionary,
		and his own Chitose dictionary. Thus the loanword “horse” is written
		<i lang="ain-Latn">unma</i> under one convention and <i lang="ain-Latn">umma</i> under another. The
		spelling difference alone establishes no pronunciation contrast.
	</p>
</S>

<S t="Glides at vowel boundaries" id="glide-notation">
	<p>
		Nakagawa omits transitional glides in forms such as <i lang="ain-Latn">uepeker</i>, while other
		transcriptions write <i lang="ain-Latn">uwepeker</i>
		<Ref k="nakagawa2024" p="58" />. A related choice arises in person-marked forms:
		<i lang="ain-Latn">ku=itak</i> displays the stem, while
		<i lang="ain-Latn">kuytak</i> makes the surface syllable sequence apparent
		<Ref k="nakagawa2024" p="59–61" />.
	</p>
	<p>
		A spelling chosen for morphological clarity may consequently need a separate pronunciation line.
		The phonological conditions are treated in <Xr ch="glides-w-y" /> and
		<Xr ch="glide-epenthesis-hiatus-resolution" />.
	</p>
</S>

<S t="Glottal-stop notation" id="glottal-onset">
	<p>
		The omission of an apostrophe can have two different explanations. An author may analyze the
		glottal onset as predictable, or may recognize it as a phoneme but omit the symbol for
		readability. Nakagawa distinguishes his analysis from Tamura's later notational practice on
		precisely this point <Ref k="nakagawa2024" p="57" />. Identical spellings can thus accompany
		different phonemic analyses ‹contested›.
	</p>
	<p>
		The analysis should be cited explicitly when it matters. Ordinary vowel-initial spelling by
		itself cannot settle the question; see <Xr ch="glottal-stop" />.
	</p>
</S>

