		Sakhalin fricative outcomes, including Hokkaido <i lang="ain-Latn">tek</i> 'hand' and Sakhalin
		<i lang="ain-Latn">teh</i>. Alternations involving the possessed form can preserve evidence for
		the earlier consonant
		<Ref k="alonso2022" p="§1" />. These comparisons are developed in
		<Xr ch="final-h-history-and-sakhalin-length-reflex" />.
	</p>
	<p>
		Other reconstructions concern vowels, accent, morpheme boundaries, and the histories of
		grammatical forms. Their strength varies with the available alternations and dialect
		correspondences <Ref k="alonso2022" p="§§2–4" />. The detailed proposals appear in
		<Xr ch="internal-reconstruction-and-grammaticalization-pathways" />; broader affiliation and
		contact arguments are collected in
		<Xr ch="macro-comparison-and-deep-contact-controversies" />.
	</p>
</S>
