<S t="Isolate status and internal diversity" id="isolate">
	<p>
		Ainu has no established genealogical relationship with another language family. Janhunen
		describes it as an isolate while recognizing enough internal diversity to speak of an Ainuic
		family, with Hokkaido, Sakhalin, and Northern Kuril branches
		<Ref k="janhunen2022" p="§2(3)" />. These two descriptions concern different levels of
		classification: the external affiliation of Ainu and the relationships among its documented
		varieties.
	</p>
	<p>
		The internal evidence supports comparison of sounds, forms, and constructions across those
		varieties. Alonso de la Fuente uses it to reassess Proto-Ainu phonology and morphology
		<Ref k="alonso2022" p="§§1–4" />. The reconstructions are treated in
		<Xr ch="proto-ainu-segmental-reconstruction" /> and
		<Xr ch="internal-reconstruction-and-grammaticalization-pathways" />; Hokkaido's internal
		classification is described in <Xr ch="hokkaido-dialect-classification-and-dialectometry" />.
	</p>
</S>

<S t="Evidence and methods" id="method">
	<p>
		Alonso de la Fuente distinguishes internal reconstruction, investigation of language contact,
		and typological comparison. For Ainu, internal reconstruction draws on alternations and dialect
		differences to propose earlier forms. Contact studies examine material shared with languages
		such as Japanese and Nivkh. Typological comparison supplies possible models of change, whose
		application must then be tested against the Ainu evidence
		<Ref k="alonso2022" p="§1" />.
	</p>
	<p>
		A claim of common descent requires systematic correspondences that distinguish inheritance from
		borrowing or resemblance. Shared word order or a few similar words leave several explanations
		open. Conversely, structural differences alone cannot settle a genealogical question: the
		history of individual forms and the regularity of the proposed correspondences must be examined.
		Alonso de la Fuente accordingly cautions against treating typological parallels as proof of a
		reconstruction <Ref k="alonso2022" p="§1" />.
	</p>
	<p>
		The depth of a reconstruction depends on the evidence and on what the proposed stage represents.
		Alonso de la Fuente estimates approximately a millennium for the differentiation underlying the
		documented Ainu varieties and distinguishes Pre-Proto-Ainu, Proto-Ainu, and Common Ainu <Ref
			k="alonso2022"
			p="§1, §4"
		/>. Janhunen places Proto-Ainu in the Satsumon period, between roughly 500 and 1,000 years ago <Ref
			k="janhunen2022"
			p="§4"
		/>. These are authors' historical estimates, not directly dated attestations of the
		reconstructed language.
	</p>
</S>

<S t="External comparison" id="macro">
	<p>
		The literature contains proposals connecting Ainu with several surrounding or more distant
		language groups. Their evidence differs: some concern possible cognates, others loanwords, and
		others broad structural parallels. Janhunen finds no unambiguous external affiliation
		<Ref k="janhunen2022" p="§2(3)" />. Alonso de la Fuente sets affiliation proposals aside in his
		reassessment of internal reconstruction <Ref k="alonso2022" p="§1" />.
	</p>
	<S t="Altaic and areal comparisons" id="altaic">
		<p>
			Comparisons with the languages of Northeast Asia often draw on shared SOV order and
			agglutinating morphology. Bugaeva contrasts these similarities with differences in person
			indexing, possession, and the location of grammatical marking
			<Ref k="bugaeva2022" p="Ch.1 §1, §7" />. Her Pacific Rim comparison is discussed in
			<Xr ch="typological-profile" />. The descriptive similarities and differences can be stated
			without assigning Ainu to an Altaic or other external family.
		</p>
	</S>
	<S t="Vovin's Austroasiatic proposal" id="austroasiatic">
		<p>
			Vovin's reconstruction of Proto-Ainu was developed alongside a proposal of Austroasiatic
			affiliation <Ref k="vovin1993" />. Alonso de la Fuente reports that reviewers Sidwell,
			Abondolo, and Witczak criticized the influence of that assumption on the reconstructed
			consonant system. He also discusses De Boer's separate review of the suprasegmental analysis
			<Ref k="alonso2022" p="§1" />. These reviews are cited here through his account.
		</p>
		<p>
			Alonso de la Fuente re-examines vowels, consonants, and prosody using Ainu evidence and
			presents alternative reconstructions as proposals for further consideration
			<Ref k="alonso2022" p="§§1–2" />. Evaluation of a reconstructed segment therefore requires its
			dialect correspondences and morphological evidence, independently of the proposed external
			affiliation. See <Xr ch="proto-ainu-segmental-reconstruction" />.
		</p>
	</S>
	<S t="Nivkh and northern contact" id="nivkh">
		<p>
			Ainu and Nivkh communities were in contact on Sakhalin, together with speakers of Tungusic
			languages such as Uilta. Janhunen describes this regional contact zone and the wider
			connections of the Santan trade <Ref k="janhunen2022" p="§2(2)" />. Shiraishi and Tangiku
			examine linguistic contact involving Ainu in their Handbook chapter
			<Ref k="shiraishitangiku2022" />. Shared material must be assessed for borrowing direction,
			chronology, and distribution across Ainu varieties.
		</p>
		<p>
			The regional label <em>Paleosiberian</em>, also called <em>Paleo-Asiatic</em>, has been
			applied to several otherwise unaffiliated languages or small families. It provides no
			established common ancestor for Ainu and Nivkh
			<Ref k="janhunen2022" p="§2(3), §3(3c)" />. The recoverable contact evidence is treated in
			<Xr ch="northern-contact-nivkh-tungusic-manchu" />.
		</p>
	</S>
</S>

<S t="Ainu and Japonic" id="japonic">
	<p>
		Ainu and Japanese have a history of contact. Alonso de la Fuente points to Japanese loans whose
		form reflects features of northern Japanese dialects, including the merger of Japanese vowel
		distinctions and the retention of prenasalized consonants. He discusses these together with
		possible contact effects on inherited Ainu material
		<Ref k="alonso2022" p="§1" />. Loanword analysis therefore requires comparison with the relevant
		regional and historical Japanese varieties; modern standard Japanese alone may be an inadequate
		point of reference.
	</p>
	<p>
		Janhunen proposes an older contact history linking the Ainu lineage to the languages present in
		Japan before the expansion of Japonic. His account includes substrate influence on Japanese and
		early Japanese borrowing into Ainu
		<Ref k="janhunen2022" p="§3(3a–3c)" />. Vovin develops a different line of evidence, arguing for
		Ainu-derived words in Old Japanese and using them to infer a wide earlier distribution of Ainu <Ref
			k="vovin2022"
			p="§§1–2"
		/> ‹contested›. Each proposed loan needs its own phonological, semantic, and chronological assessment.
	</p>
	<p>
		Japanese loans in Ainu are discussed in <Xr ch="japanese-loanwords-in-ainu" />; proposed Ainu
		loans and place-name interpretations in Japanese are examined in
		<Xr ch="ainu-loanwords-and-toponymy-in-japanese" />. Evidence for contact contributes to these
		histories without establishing a genealogical relationship between Ainu and Japonic.
	</p>
</S>

<S t="Language history and the history of populations" id="ethnogenesis">
	<p>
		Janhunen places the ancestry of the Ainu linguistic lineage in Jōmon Japan and associates its
		later northward spread with the Satsumon culture. His account allows for successive populations
		to adopt the language, as well as for migration
		<Ref k="janhunen2022" p="§3(3a), §4" />. It also assumes that other languages were spoken in
		prehistoric Japan, although their identities cannot be recovered from the surviving Ainu record.
	</p>
	<p>
		The proposed history of the language must therefore be distinguished from biological ancestry
		and from the distribution of archaeological cultures. Janhunen discusses each separately before
		relating them in his model of Ainu ethnogenesis
		<Ref k="janhunen2022" p="§§3–4" />. Similarities between populations or material traditions do
		not supply the missing linguistic correspondences needed to establish an external family
		relationship. The historical setting is developed in
		<Xr ch="ainu-people-homeland-history" />.
	</p>
</S>

