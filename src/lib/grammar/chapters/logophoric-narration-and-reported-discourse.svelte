<S t="Logophoric speech and indirect complements" id="analyses">
	<p>
		Bugaeva calls speech with reported-speaker forms ‘semi-direct’ in her 2008 account and treats
		direct, semi-direct, and indirect reporting as stylistic options. Her later joint study with
		Nikitina argues that direct and logophoric speech share a syntactic structure: both permit
		flexible placement, peripheral expressions, and mixtures of person reference. Indirect
		complements have stronger restrictions on their licensing predicates and position ‹contested›
		<Ref k="bugaeva2008" p="45–48" />
		<Ref k="nikitina2021" p="616–624" />.
	</p>
	<p>
		In the latter analysis, a verb following a quotation can take the addressee as its object; the
		presence of transitive
		<i lang="ain-Latn">ye</i> does not automatically make the quoted words its object. The
		constructions are detailed in
		<Xr ch="quotative-complementation-sekor" />
		<Ref k="nikitina2021" p="616–618" />. Bugaeva separately documents Asahikawa
		<i lang="ain-Latn">sekor</i> reports with indirect interpretations, including first person
		referring to the reporter
		<Ref k="bugaeva2008" p="53, examples 36–37" />.
	</p>
</S>

<S t="Historical interpretations" id="historical-accounts">
	<p>
		The history of narrative person remains disputed. Satō criticizes an origin in indefinite-person
		reference and proposes literary circumlocution through plural forms, which leave reference less
		direct. Nakagawa proposes a fourth-person narrative basis with exclusive forms contributing the
		character of divine speech; he also suggests that written revision helped regularize Chiri
		Yukie's collection. These are competing interpretations of the historical evidence ‹contested› <Ref
