<S t="Narrative perspective and person forms" id="narrative-person">
	<p>
		A narrator can speak as a character whose experiences are presented through ‘I’. In much Saru
		and Chitose narrative, that participant is expressed with <i lang="ain-Latn">a=</i>,
		<i lang="ain-Latn">=an</i>, and <i lang="ain-Latn">i=</i>, the <Xr
			ch="indefinite-fourth-person-paradigm">fourth-person series</Xr
		>. Tamura relates this usage to the person forms found in quotations of another speaker's words <Ref
			k="tamura1972"
			p="26–27, §2.8"
		/>.
	</p>
	<p>
		Nakagawa distinguishes speaking as a character from the performer speaking in their own person.
		A prayer can have elevated wording and ordinary first-person <i lang="ain-Latn">ku=</i>, while a
		prose tale with relatively conversational wording uses fourth person. Narrative person therefore
		does not by itself identify an elevated style
		<Ref k="nakagawa2024" p="601–602" />.
	</p>
</S>

<S t="Self-quotation and another speaker's words" id="quotation-person">
	<p>
		In Tamura's Saru account, self-quotation retains ordinary first person. When reporting another
		person's speech, the quoted speaker is usually represented by the forms she calls the first
		person of quotation. Second- and third-person forms within the quotation generally retain their
		reference <Ref k="tamura1972" p="24–25, §2.7" />.
	</p>
	<p>
		The reported-speaker pattern has documented alternatives. Tamura records ordinary first-person
		singular and exclusive plural forms in quotations of other people. She describes them as rare in
		her third-party reports and notes a vivid or immediate effect in the plural comparison
		<Ref k="tamura1972" p="24–26, examples 42–47" />.
	</p>
	<Ex
		m="paye=as wa arki=as na sekor haweoka"
		g="go.PL=1PL.EXCL.S CONJ come.PL=1PL.EXCL.S FIN QUOT say.PL"
		tr="They said, ‘We are going and coming back!’"
		cite="tamura1972:26"
		dial="SAR"
		place="Example 46"
		note="Person boundaries are normalized to = and accent marks are omitted. Tamura contrasts this wording with quotation-person =an in example 47; the latter example also continues with ‘and they went’."
	/>
	<p>
		Tamura treats her few examples of quoting an addressee cautiously: they were elicited through
		situations set up for questioning, rather than observed in spontaneous use. They cannot
		establish the frequency of the alternatives in conversation
		<Ref k="tamura1972" p="25, note 8" />.
	</p>
</S>

