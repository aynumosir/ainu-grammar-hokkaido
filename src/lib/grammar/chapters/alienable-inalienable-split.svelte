<S t="Adjacent nouns and the limits of a semantic rule" id="analysis-limits">
	<p>
		Two adjacent concept-form nouns can express a classifying or attributive relation. Nakagawa
		separates this pattern from his two possession constructions: its first noun cannot simply be
		replaced by a possessive person marker
		<Ref k="nakagawa2024" p="218" />. The phrase–compound distinction is treated in <Xr
			ch="noun-noun-compounding"
		/> and <Xr ch="noun-phrase-structure" />.
	</p>
	<p>
		Nakagawa further proposes that any ordinary noun might potentially have an affiliative when the
		semantic relation is suitable, pointing especially to material–product expressions. This broader
		proposal differs from an account organized around lexical non-possessibility
		<Ref k="nakagawa2024" p="230" />;
		<Ref k="nakagawa2022pos" p="§4.2" />;
		<Ref k="bugaeva2021poss" p="55–56" /> ‹contested›. The documented constructions support a wider range
		than bodily ownership alone; they do not supply a complete affiliative paradigm for every noun.
	</p>
	<p>
		A specific possessor is also insufficient as the sole condition. Nakagawa quotes Satō (1997:
		150) on a Chitose sentence about all human beings having bellies, where the belly noun is
		affiliative despite the generic statement
		<Ref k="nakagawa2024" p="231, example 268" />. Further grammatical conditions appear in <Xr
			ch="concept-form-affiliative-form"
		/>.
	</p>
</S>
