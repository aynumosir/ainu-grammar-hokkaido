<S t="Two ways to express a possessive relation" id="two-constructions">
	<p>
		Hokkaido Ainu commonly expresses possession either with the verb
		<i lang="ain-Latn">kor</i> “have” before a noun or with person marking on an affiliative noun
		form. Compare <i lang="ain-Latn">ku=kor cip</i> “my boat” and <i lang="ain-Latn">ku=tekehe</i>
		“my hand.” In the first expression,
		<i lang="ain-Latn">ku=</i> marks the subject of “have”; in the second it identifies the
		possessor of the hand <Ref k="nakagawa2024" p="218–219" />;
		<Ref k="sato2008" p="151–152" />. The noun forms themselves are introduced in
		<Xr ch="concept-form-affiliative-form" />.
	</p>
	<Ex
		m="ku=tek-ehe"
		g="1SG.A=hand-POSS"
		tr="my hand"
		dial="CHI"
		cite="nakagawa2024:219, example 241"
	/>
	<p>
		The labels <em>alienable</em> and <em>inalienable</em> describe the familiar contrast between transferable
		possessions and relations such as body part to person. They offer a useful starting point, but the
		choice also depends on the noun, dialect, genre, and intended relation. A list dividing all objects
		into things that can or cannot change owners would miss several documented patterns.
	</p>
</S>

<S t="Possessibility as a grammatical property" id="possessibility">
	<p>
		Bugaeva, Nichols and Bickel distinguish semantic alienability from
		<em>grammatical possessibility</em>: whether a noun can or must take a possessor in its own
		argument structure. In their analysis, many Ainu alienable nouns are grammatically
		non-possessible. A dog can be owned, for example, while “my dog” is expressed through “the dog
		that I have,” with the person marker on
		<i lang="ain-Latn">kor</i>
		<Ref k="bugaeva2021poss" p="47–55, example 19a" />. Their term therefore describes the noun's
		grammar, rather than the practical possibility of ownership.
	</p>
	<p>
		Satō illustrates the lexical restriction with Chitose
		<i lang="ain-Latn">ku-kor káne</i> “my money,” rejecting
		<i lang="ain-Latn">*ku-kane</i> for that meaning
		<Ref k="sato2008" p="151" />. The asterisk reports his judgment. It does not establish an
		identical restriction for every noun referring to an artifact.
	</p>
</S>

<S t="The verbal construction with kor" id="kor-relative-clause">
	<p>
		In the relative-clause analysis, the possessor is the subject of
		<i lang="ain-Latn">kor</i>, and the following noun is the head corresponding to its unexpressed
		object. The construction retains verbal possibilities, including aspectual material and further
		modification
		<Ref k="bugaeva2021poss" p="55, 58–59" />. An overt possessor noun can also precede the verb;
		see <Xr ch="adnominal-possession-double-marking" />.
	</p>
	<p>
		Bugaeva, Nichols and Bickel also report an elicited prosodic pattern in which third-person
		possessive <i lang="ain-Latn">kor</i> attaches closely to the following noun. They interpret
		this as a tendency toward cliticization
		<Ref k="bugaeva2021poss" p="59, example 35" /> ‹contested›. This is an analysis of a developing pattern
		alongside the construction's verbal behavior.
	</p>
</S>

<S t="Body parts, clothing, tools, and material relations" id="semantic-range">
	<p>
		Body parts and many kinship terms take affiliative forms. The pattern extends to some clothing
		and tools carried on the body: Nakagawa cites Chitose
		<i lang="ain-Latn">ku=tesmaha</i> “my snowshoes” and Saru
		<i lang="ain-Latn">a=tasiroho</i> “my machete”
		<Ref k="nakagawa2024" p="219, examples 244–245" />. Satō likewise includes blood, the heart,
		clothing, and tutelary spirits in his discussion
		<Ref k="sato2008" p="151–152" />.
	</p>
	<p>
		Affiliatives also express relations between a whole and a part, or between a material and
		something made from it. Nakagawa's examples include
		<i lang="ain-Latn">op nici(hi)</i> “a spear's shaft,”
		<i lang="ain-Latn">sinta atu(hu)</i> “a cradle's cord,”
		<i lang="ain-Latn">sayo ruri(hi)</i> “the liquid of porridge,” and
		<i lang="ain-Latn">ikaray ohawe(he)</i> “nettle soup.” Parentheses show the long-form extension.
		His <i lang="ain-Latn">top cise(he)</i> describes a house made of bamboo, a different relation
		from a person's ownership of a house
		<Ref k="nakagawa2024" p="219–220" />.
	</p>
</S>

<S t="Lexical, dialect, and genre differences" id="variation">
	<p>
		For ordinary ownership of <i lang="ain-Latn">cise</i> “house,” Nakagawa reports the construction
		with <i lang="ain-Latn">kor</i> in Saru, Chitose, and Horobetsu prose. Affiliatives occur in
		verse in these varieties and in prose elsewhere <Ref k="nakagawa2024" p="220–221" />. In her
		Shizunai material, Refsing finds <i lang="ain-Latn">e cisehe</i> and
		<i lang="ain-Latn">e kor cise</i> similarly frequent, with no apparent meaning difference <Ref
			k="refsing1986"
			p="88"
		/>. Her observation applies to that material.
	</p>
	<p>
		The sources also differ on “bow.” Satō lists Chitose
