<S t="Presenting a topic or contrast" id="topic">
	<p>
		<i lang="ain-Latn">Anak</i> and <i lang="ain-Latn">anakne</i>
		present an expression as a topic, often in contrast with another possibility.
		The topic need not be the subject of the following predicate. Satō's
		Chitose example speaks about a child by identifying the child's father
		<Ref k="sato2008" p="62" />.
	</p>
	<Ex m="tan hekaci anak onaha kotan kor kur ne wa"
		g="this boy TOP father.POSS village have person COP FIN"
		tr="As for this child, his father is the village chief."
		cite="sato2008:62" dial="CHI" place="§7.2, first anak example" />
	<p>
		Satō also contrasts understanding what is heard with not knowing how to
		reply. Both expressions receive <i lang="ain-Latn">anak</i> in that
		example. Topic marking is not obligatory wherever an English ‘as for’ or
		Japanese <span lang="ja">は</span> might seem appropriate
		<Ref k="sato2008" p="62–63" />.
	</p>
</S>

<S t="What can carry the particle" id="hosts">
	<p>
		Nakagawa gives the particles after nouns, adverbial phrases, and verbal
		expressions. A village-directed phrase can receive
		<i lang="ain-Latn">anakne</i> to single out that destination, and a
		feeding predicate can receive <i lang="ain-Latn">anak</i> before it
		is repeated in the comment
		<Ref k="nakagawa2024" p="320–321, examples 515–518" />.
	</p>
	<Ex m="a=i=ipere anak pirkano a=i=ipere korka"
		g="4.A=4.O=feed TOP well 4.A=4.O=feed CONJ"
		tr="As for feeding me, they feed me well, but …"
		cite="nakagawa2024:321" dial="SAR" place="Example 518"
		note="The subsequent account concerns a plan to sell the narrator to a trading post. The favourable comment is limited to the feeding." />
	<p>
		In Nakagawa's analysis, adding an adverbial particle to a verb phrase
		requires a following verb to restore its verbal function.
		<i lang="ain-Latn">Ki</i> is common, but other predicates are possible,
		and the example above repeats the lexical verb
		<Ref k="nakagawa2024" p="319–321, §§9.4.1–9.4.2" />.
	</p>
</S>

<S t="Anak, anakne, and discourse familiarity" id="delivery">
	<p>
		Tamura's Saru dictionary finds no clear difference in meaning
		between the two forms. It associates <i lang="ain-Latn">anak</i> with
		a lighter, flowing delivery and <i lang="ain-Latn">anakne</i> with
		slower or more segmented speech, or a clearer boundary between topic and
		comment. The rhythm explanation is tentative
		<Ref k="tamura1996" p="s.vv. anak and anakne" />.
	</p>
	<p>
		Satō likewise leaves the exact difference open. He reports nearly twice
		as many <i lang="ain-Latn">anakne</i> tokens as
		<i lang="ain-Latn">anak</i> in his data
		<Ref k="sato2008" p="63" />.
		That is a finding about his material, not a frequency ratio for Hokkaido as
		a whole.
	</p>
	<p>
		Satō proposes that the topic is already familiar in the discourse. He
		reports difficulty adding the particle when first asking what a visible
		object is, while acknowledging that an object can be visible without
		having been discussed. His explanation is tentative and does not establish
		a general ban on topic marking in questions
		<Ref k="sato2008" p="62–63" />.
	</p>
</S>

<S t="Restriction with patek and takup" id="restriction">
	<p>
		<i lang="ain-Latn">Patek</i> restricts the alternatives to what precedes
		it, with readings such as ‘only’ or ‘nothing but’. Nakagawa treats it as
		a particle with independent uses; the Tamura analysis he quotes places it
		among adverbs with particle-like behaviour
		<Ref k="nakagawa2024" p="328, reporting Tamura 1988a:45" />.
	</p>
	<p>
		<i lang="ain-Latn">Takup</i> has related restrictive meanings and
		noun-like properties, including <i lang="ain-Latn">takupi</i>.
		Nakagawa commonly finds <i lang="ain-Latn">ne</i> after a verb plus
		<i lang="ain-Latn">takup</i>, but also gives
		<i lang="ain-Latn">heru a=i=kikkik takup ki hawe!</i>, a complaint
		that all that will happen is being beaten. The example contains
		<i lang="ain-Latn">ki</i>
		<Ref k="nakagawa2024" p="328–329, examples 553–554" />.
	</p>
</S>

<S t="Minimum alternatives and additive expressions" id="alternatives">
	<p>
		<i lang="ain-Latn">Poka</i> and regional
		<i lang="ain-Latn">pokay</i> can single out a minimum acceptable
		alternative, as in asking for at least a little. Nakagawa restricts his
		description to something sought or unrealized
		<Ref k="nakagawa2024" p="329" />.
		Satō's Chitose examples also include a completed sequence, doing everything
		possible and finally moving something elsewhere
		<Ref k="sato2008" p="67–68" />.
		The published descriptions thus differ in the range they assign to this form.
	</p>
	<p>
		Additive <i lang="ain-Latn">ka</i> has further uses with indefinites and
		negation. Its presence need not always add strong emphasis, as explained in
		<Xr ch="negation-polarity-items-scope" />.
		Sentence-final particles and their combinations are treated in
		<Xr ch="sentence-final-particles-illocutionary-force" />.
	</p>
</S>
