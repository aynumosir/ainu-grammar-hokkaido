<S t="Ability and possibility" id="ability">
	<p>
		<i lang="ain-Latn">Easkay</i> ‘can’ and <i lang="ain-Latn">eaykap</i> ‘cannot’ can follow a
		person-marked predicate as auxiliaries. The circumstances that make an action possible or
		impossible are often explicit in the sentence
		<Ref k="sato2008" p="80–81" /><Ref k="nakagawa2024" p="315" />.
	</p>
	<Ex
		m="ku=kuwakor kor easir k=apkas easkay"
		g="1SG.S=use.walking.stick CONJ only.then 1SG.S=walk be.able"
		tr="I can walk only with a walking stick."
		cite="sato2008:80"
		dial="CHI"
		place="§9.2, easkay examples"
	/>
	<Ex
		m="na sesek wa ku=ku ka eaykap"
		g="still be.hot CONJ 1SG.A=drink ADD be.unable"
		tr="It was still hot, so I could not drink it."
		cite="sato2008:80"
		dial="CHI"
		place="§9.2, eaykap example"
	/>
	<p>
		Nakagawa gives <i lang="ain-Latn">eaykap</i> a broad range covering both lack of ability and
		circumstances that prevent an action. The heat in Satō's example is an external circumstance; a
		definition restricted to an inherent incapacity would be too narrow <Ref
			k="nakagawa2024"
			p="315"
		/>.
	</p>
</S>

<S t="Auxiliary and lexical uses" id="structure">
	<p>
		In an auxiliary construction, person marking is on the preceding verb. A lexical use instead
		puts the person index on the ability verb. Satō's literary <i lang="ain-Latn"
			>inawke anak a=easkay</i
		>
		concerns being skilled at making prayer sticks; <i lang="ain-Latn">wakkata ka a=eaykap</i>
		concerns inability to fetch water <Ref k="sato2008" p="80–81" />.
	</p>
	<p>
		The distribution is sensitive to source and register. Satō reports no independent colloquial <i
			lang="ain-Latn">k=eaykap</i
		>
		in his Chitose material, while finding literary <i lang="ain-Latn">a=eaykap</i> ordinary
		<Ref k="sato2008" p="90" />. Tamura's Saru description gives person-marked
		<i lang="ain-Latn">k=eaykap</i>
		in a statement about being very poor at sewing
		<Ref k="tamura1960" p="§20.1, 77 (continuous pagination 353)" />.
	</p>
	<p>
		Compounds add another structural possibility. Nakagawa's Chitose
		<i lang="ain-Latn">hemesu-easkay=an</i> ‘I can climb’ is one word by the placement of its person
		suffix. He leaves open whether this is auxiliary incorporation or incorporation of nominally
		used <i lang="ain-Latn">hemesu</i>
		as the object of transitive <i lang="ain-Latn">easkay</i>
		<Ref k="nakagawa2024" p="491, examples 1123–1123′" />. Compare <Xr ch="desiderative-rusuy" />.
	</p>
</S>

<S t="The intervening particle ka" id="ka">
	<p>
		<i lang="ain-Latn">Ka</i> can stand between a verb and an auxiliary of verbal origin, as in the
		drinking example. Nakagawa says its presence need not create a particular difference in meaning <Ref
			k="nakagawa2024"
			p="314"
		/>. Refsing describes emphatic Shizunai uses and translates one mist-covered-mountain example
		with ‘could not even see it’ <Ref k="refsing1986" p="208, example 323" />. An English ‘even’
		reading should follow the particular context.
	</p>
</S>

<S t="More specific obstacles" id="obstacles">
	<p>
		Other predicates distinguish kinds of difficulty. Nakagawa's
		<i lang="ain-Latn">niwkes</i> concerns being unable to complete something: a narrator cannot
		finish a cup alone. His <i lang="ain-Latn">koyaykus</i>
		concerns an obstructing situation, while <i lang="ain-Latn">etoranne</i>
		can concern lacking the inclination or composure to act
		<Ref k="nakagawa2024" p="316, examples 493–497" />.
	</p>
	<p>
		Satō's Chitose <i lang="ain-Latn">koyayekus</i> has painful or unendurable difficulty among its
		meanings: a person cannot get up under a carried load. He stresses that examples are few <Ref
			k="sato2008"
			p="83–84"
		/>. These lexical distinctions are useful without turning the forms into an exhaustive paradigm
		of internal and external inability.
	</p>
</S>
