<S t="Two conversational meanings of we" id="clusivity">
	<p>
		In the Saru/Chitose reference paradigm, conversational “we” distinguishes a group that excludes
		the addressee from one that includes the addressee. The exclusive series has three different
		forms for S, A and O. Inclusive reference uses the series also called fourth person
		<Ref k="tamura1972" p="18–19, §§2.2–2.3" />;
		<Ref k="nakagawa2024" p="164–165, 175" />;
		<Ref k="bugaeva2012" p="472, 474–475" />.
	</p>
	<table>
		<thead><tr><th>Conversational reference</th><th>S</th><th>A</th><th>O</th></tr></thead>
		<tbody>
			<tr
				><td>We, excluding you</td><td><i lang="ain-Latn">=as</i></td><td
					><i lang="ain-Latn">ci=</i></td
				><td><i lang="ain-Latn">un=</i></td></tr
			>
			<tr
				><td>We, including you</td><td><i lang="ain-Latn">=an</i></td><td
					><i lang="ain-Latn">a=</i></td
				><td><i lang="ain-Latn">i=</i></td></tr
			>
		</tbody>
	</table>
	<p>
		The transitive cells assume a third-person counterpart. Inclusive reference can comprise just
		speaker and addressee or a larger group. The forms themselves do not specify that group's size <Ref
			k="tamura1972"
			p="19"
		/>. The independent pronouns have their own regional forms; see <Xr
			ch="independent-personal-pronouns"
		/>.
	</p>
</S>

<S t="Subject forms in clause chains" id="ci-as">
	<p>
		The exclusive prefix <i lang="ain-Latn">ci=</i> marks a transitive subject; the suffix
		<i lang="ain-Latn">=as</i> marks an intransitive subject. Takahashi's Tokachi example contains
		both, with the same participants riding and coming <Ref k="takahashi2015" p="207, example 2" />.
	</p>
	<Ex
		m="kuruma an wa ci=o tek arki=as"
		g="car exist CONJ 1PL.A=ride CONJ come.PL=1PL.S"
		tr="There was a car, and we rode in it and came."
		cite="takahashi2015:207"
		dial="TOK"
		place="Example 2; Sawai Tomeno of Honbetsu"
		note="Accent marks omitted; person boundaries normalized to equals signs."
	/>
	<p>
		Western Hidaka and Chitose contract <i lang="ain-Latn">ci=</i> to
		<i lang="ain-Latn">c=</i> before stem-initial <i lang="ain-Latn">a, u, e, o</i>
		<Ref k="nakagawa2024" p="167" />. This regional alternation parallels first-singular
		<i lang="ain-Latn">ku=</i>; see <Xr ch="personal-affix-sandhi-connected-speech-reduction" />.
	</p>
</S>

<S t="Inclusive invitations and exclusive reports" id="inclusive">
	<Ex
		m="eani hem paye=an ro"
		g="2SG also go.PL=4.S HORT"
		tr="Let's go together, you and I."
		cite="nakagawa2024:175"
		dial="CHI"
		place="Example 138"
	/>
	<Ex
		m="tanto anakne hopasi arki=as ruwe ne wa"
		g="today TOP from.downstream come.PL=1PL.S NMLZ COP FIN"
		tr="Today we came from downstream."
		cite="nakagawa2024:175"
		dial="CHI"
		place="Example 139"
	/>
	<p>
		The invitation includes the addressee in the proposed journey. In the second example, the
		speakers tell the addressee about their arrival; that group excludes the listener. Both verbs
		have plural stems, while the person suffixes express the difference in membership
		<Ref k="nakagawa2024" p="175" />.
	</p>
</S>

<S t="Object forms and their references" id="un">
	<p>
		Exclusive <i lang="ain-Latn">un=</i> and fourth-person <i lang="ain-Latn">i=</i> occupy
		different rows of the paradigm <Ref k="nakagawa2024" p="170, table 27" />. The following request
		uses <i lang="ain-Latn">un=</i> for the people seeking protection. The water deity addressed in the
		request is outside that group.
	</p>
	<Ex
		m="wakka us kamuy un=epunkine wa un=kore yan"
		g="water inhabit deity 1PL.O=protect CONJ 1PL.O=give IMP"
		tr="Water deity, please protect us."
		cite="nakagawa2024:170"
		dial="CHI"
		place="Example 123"
		note="The second verb belongs to the request construction; the translation renders the whole expression."
	/>
	<p>
		First-to-second-person combinations follow the interaction paradigm in
		<Xr ch="eci-portmanteau-and-second-plural" />. The two object forms above cannot be exchanged
		merely because both can refer to several people.
	</p>
</S>

<S t="Register and competing accounts" id="register">
	<p>
		Literary uses of the CI series can refer to a single narrator. Satō reports that Chitose divine
		songs and prose narratives sometimes begin with <i lang="ain-Latn">ci=/=as</i> before shifting
		to <i lang="ain-Latn">a=/=an</i>. He contrasts this with the sustained CI-series usage in Chiri
		Yukie's collection <Ref k="sato2008" p="261" />. A conversational translation such as “we
		excluding you” therefore does not describe every literary occurrence.
	</p>
	<p>
		Refsing's Shizunai account emphasizes a concrete, cohesive group whose members the speaker can
		represent; she associates indefinite forms with reference outside those conditions
		<Ref k="refsing1986" p="215–216" />. This semantic account differs from a description stated
		solely in terms of addressee inclusion. Takahashi instead develops an inclusive-person analysis
		for Tokachi, connecting several functions through extensions of inclusive reference
		<Ref k="takahashi2015" p="205–206, 211–212" /> ‹contested›.
	</p>
	<p>
		Sakhalin comparisons also depend on the variety and analysis. Sakaguchi's East Sakhalin account
		allows grammatical CI-series plural forms with singular reference and does not posit the same
		semantic clusivity division as in Hokkaido. Dal Corso describes an eastern exclusive set and
		contrasts western descriptions that lack it
		<Ref k="sakaguchi2024" p="25–29" />;
		<Ref k="dalcorso2025align" p="195–196" /> ‹contested›. The wider range of fourth-person functions
		is treated in
		<Xr ch="indefinite-fourth-person-paradigm" />.
	</p>
</S>
