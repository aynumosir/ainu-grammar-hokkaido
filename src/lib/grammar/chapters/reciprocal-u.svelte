<S t="Mutual action" id="overview">
	<p>
		In a canonical reciprocal, participants act on one another. Prefixing
		<i lang="ain-Latn">u-</i> to a two-place verb identifies each participant as both actor and
		affected participant, producing an intransitive verb with a semantically plural subject <Ref
			k="bugaevakobayashi2022"
			p="§4.2.1"
		/>. Nakagawa illustrates the pattern with <i lang="ain-Latn">koyki → u-koyki</i> “attack → fight
		each other” and
		<i lang="ain-Latn">siru → u-siru</i> “rub → rub against each other”
		<Ref k="nakagawa2024" p="186" />.
	</p>
	<Ex
		m="u-tumam=an hine hotke=an"
		g="RECP-sleep.embracing=4.S CONJ lie.down=4.S"
		tr="We held each other and slept."
		cite="bugaevakobayashi2022:§4.2.1"
		dial="SAR"
		place="Example 9c; K8109171UP.069"
		note="Kimura Kimi's example as quoted in the Handbook. Person boundaries are written with =. The fourth-person forms have inclusive reference in the source translation."
	/>
	<p>
		This intransitivizing pattern concerns a two-place base. Other reciprocal constructions retain
		an object or have reciprocating participants who are objects of a larger causative predicate.
		Their argument frames belong to the same broader system described in
		<Xr ch="valency-voice-overview" />.
	</p>
</S>

<S t="Retained objects and object-oriented reciprocals" id="objects">
	<p>
		With a three-place base, an indirect reciprocal can identify the actor and addressee while
		leaving the theme as an object. The Handbook gives
		<i lang="ain-Latn">u-w-e-pakasnu</i> “teach it to each other,” after Tamura's dictionary. Here
		<i lang="ain-Latn">w</i>
		is a linking consonant and
		<i lang="ain-Latn">e-</i> introduces the subject matter
		<Ref k="bugaevakobayashi2022" p="§4.2.1, example 10c" />.
	</p>
	<p>
		Causativizing a reciprocal adds a causer. In the following example, the younger brother causes
		the villagers to fight one another.
	</p>
	<Ex
		m="a=ak-ihi a=utar-i utar u-koyki-re"
		g="4.POSS=younger.brother-POSS 4.POSS=people-POSS PL RECP-attack-CAUS"
		tr="My younger brother made the villagers fight against each other."
		cite="bugaevakobayashi2022:§4.2.1"
		dial="SAR"
		place="Example 11b; K8010281UP.071"
		note="The Handbook quotes Kimura Kimi's narrative. The two written a= forms belong to possessed nouns; the verb's causer is the younger-brother phrase."
	/>
	<p>
		Joining constructions provide another object-oriented pattern. The joined things can be
		expressed as two nouns. The Handbook analyzes the base of
		<i lang="ain-Latn">u-ko-sina</i> as a three-place applicative
		<Ref k="bugaevakobayashi2022" p="§4.2.1, example 12" />.
	</p>
	<Ex
		m="ku ay a=u-ko-sina wa a=nu p ne"
		g="bow arrow 4.A=RECP-APPL-tie CONJ 4.A=hear NMLZ COP"
		tr="I tried to bundle the bow and an arrow together."
		cite="bugaevakobayashi2022:§4.2.1"
		dial="CHI"
		place="Example 12c; OI990302UP.029"
		note="Oda Ito's example. Initial ku means ‘bow’. The full construction with nu is translated as trying to bundle them."
	/>
</S>

<S t="Reciprocal possession" id="possession">
	<p>
		The reciprocal can supply the possessor of an incorporated noun. The Handbook calls
		<i lang="ain-Latn">u-oruspe-nu</i> “listen to each other's stories” and
		<i lang="ain-Latn">u-tek-kisma</i> “seize each other's hands” quasi-possessive reciprocals. It
		cautiously observes that corresponding non-incorporated expressions seem absent <Ref
			k="bugaevakobayashi2022"
			p="§4.2.1, example 13 and following discussion"
		/>. Reflexive possessors have related constructions; see <Xr ch="reflexive-yay" />.
	</p>
	<p>
		The prefix also occurs with locative nouns, postpositions and adverbs, including
		<i lang="ain-Latn">u-sam</i> “near each other,” <i lang="ain-Latn">u-tura</i> “together,” and
		<i lang="ain-Latn">u-neno</i>
		“similar to each other”
		<Ref k="bugaevakobayashi2022" p="§4.2.1" />. These uses need their own word-class analysis; a
		nominal or adverbial form does not itself undergo verbal detransitivization.
	</p>
</S>

<S t="Joint participation and sociatives" id="sociative">
	<p>
		Some <i lang="ain-Latn">u-</i> formations express joint participation without two parallel acts
		directed at one another. Nakagawa's <i lang="ain-Latn">u-tures-kor</i>
		refers to a brother and younger sister, with the brother presented as the grammatical subject. His
		<i lang="ain-Latn">u-mina-re</i>
		describes people laughing together. The latter combines a one-place base, a causative and a reciprocal:
		1 + 1 − 1 = 1
		<Ref k="nakagawa2024" p="186–187" />. The conventional meaning is established by usage, beyond
		this argument count.
	</p>
	<p>
		Sociative <i lang="ain-Latn">uko-</i> and <i lang="ain-Latn">uwe-</i> express doing something
		together while retaining the base's valency. The Handbook relates them to
		reciprocal-plus-applicative combinations
		<Ref k="bugaevakobayashi2022" p="§4.3.2" />. Nakagawa contrasts intransitive
		<i lang="ain-Latn">u-kor</i> “marry” with transitive
		<i lang="ain-Latn">u-ko-kor</i> “have together” <Ref k="nakagawa2024" p="211" />.
	</p>
	<Ex
		m="matkaci a=maci turano a=u-ko-kor hine oka=an wa"
		g="girl 4.POSS=wife with 4.A=RECP-APPL-have CONJ exist.PL=4.S CONJ"
		tr="My wife and I had a daughter together, and we were living there, and …"
		cite="nakagawa2024:211"
		dial="SAR"
		place="Example 218"
		note="The source gives a collective first-person interpretation. The daughter remains an object of u-ko-kor; the prefix combination contributes joint participation."
	/>
</S>
