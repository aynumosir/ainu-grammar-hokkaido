		Nakagawa distinguishes ambient <i lang="ain-Latn">mean</i> “be cold” from experienced
		<i lang="ain-Latn">merayke</i> “feel cold.” He treats the former as zero-place and the latter as
		one-place <Ref k="nakagawa2024" p="129–130" />. The contrast concerns whether an experiencer is
		a grammatical argument. Other authors' classifications of ambient expressions are compared in <Xr
			ch="verbal-subclasses-taxonomy"
		/>.
	</p>
	<p>
		An absence of overt person marking can have several causes, including zero third person and a
		predicate analyzed as lacking a person-indexed argument. Meaning alone is insufficient to choose
		between those structures. The broader alignment debate is treated in
