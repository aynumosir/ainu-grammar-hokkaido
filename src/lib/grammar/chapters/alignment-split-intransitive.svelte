<S t="Argument role and event meaning" id="scope">
	<p>
		An intransitive subject can act, undergo a change, or experience a condition. These semantic
		differences do not by themselves assign different person markers in the Hokkaido reference
		paradigm. Its intransitive arguments use the S forms appropriate to their person series
		<Ref k="nakagawa2024" p="129–130, 166–170" />;
		<Ref k="bugaeva2012" p="472–474" />.
	</p>
	<p>
		A split-intransitive analysis of person marking would require a grammatical contrast between
		classes of S arguments. The familiar contrast between <i lang="ain-Latn">ku=</i> and
		<i lang="ain-Latn">en=</i> instead distinguishes first-singular S/A from O. Likewise,
		first-plural <i lang="ain-Latn">ci=</i> and <i lang="ain-Latn">=as</i> distinguish A and S
		<Ref k="bugaeva2012" p="472" />. The documented split is conditioned by person, as set out in <Xr
			ch="person-marking-architecture"
		/>.
	</p>
</S>

<S t="A patient with subject marking" id="uniform-s">
	<Ex
		m="atuy so kurka a=koyayosura hine orowano rittursere=an kor mom=an"
		g="sea surface top 4.A=throw.oneself CONJ then be.rolled.by.waves=4.S CONJ drift=4.S"
		tr="I threw myself into the sea, and then drifted, being rolled by the waves."
		cite="nakagawa2024:129–130"
		dial="CHI"
		place="Example 14"
	/>
	<p>
		Nakagawa analyzes <i lang="ain-Latn">rittursere</i> as a one-place verb formed by incorporating
		“waves” into a transitive verb meaning “knock over.” The remaining participant undergoes the
		event, yet receives S <i lang="ain-Latn">=an</i>
		<Ref k="nakagawa2024" p="130" />. Grammatical subject and semantic agent are consequently
		different notions in this example.
	</p>
	<p>
		The same distinction applies to an experiencer. Nakagawa gives
		<i lang="ain-Latn">ku=merayke</i> “I feel cold,” with first-singular S marking. He analyzes the
		verb's internal components as “coldness” and “kill,” while treating the resulting verb as
		one-place <Ref k="nakagawa2024" p="130" />. Its lexical history does not make the experiencer an
		object of the present-day predicate.
	</p>
</S>

<S t="Lexical classes in incorporation and applicatives" id="lexical-classes">
	<p>
		Shibatani discusses active and inactive intransitives in connection with incorporation and
		applicative formation. He describes patient-like intransitive subjects among the targets of
		incorporation and also warns that a bare noun–verb sequence may be ambiguous between a phrase
		and an incorporated word <Ref k="shibatani1990" p="62–63" />. These are claims about lexical
		classes and particular constructions.
	</p>
	<p>
		His inactive-verb examples also challenge a restriction on applicatives attributed to Baker's
		theoretical account <Ref k="shibatani1990" p="66–67, discussing Baker 1988" />;
		<Ref k="baker1988" /> ‹contested›. The argument concerns whether these verbs permit an applicative
		and what grammatical relation the added participant has. It does not establish an ordinary active/stative
		choice between S and O person indexes.
	</p>
	<p>
		Later incorporation evidence further qualifies broad restrictions on the types of subjects that
		can be incorporated; see <Xr ch="noun-incorporation-oblique-polysynthesis-debate" />. An
		analysis of incorporation needs those constructional facts as well as the basic paradigm.
	</p>
</S>

<S t="Derived valency and person forms" id="valency-morphology">
	<p>
		Derivation can change which person forms a verb requires. Shibatani compares an intransitive
		“arrive” construction with its applicative counterpart: fourth-person S
		<i lang="ain-Latn">=an</i> becomes A <i lang="ain-Latn">a=</i> when the verb becomes transitive <Ref
			k="shibatani1990"
			p="65, example 115a–a′; 67"
		/>. That change follows the derived argument structure.
	</p>
	<p>
		Causatives, reflexives and reciprocals require their own valency descriptions. Productive
		causatives introduce a causer; a reflexive or reciprocal of a three-place base can remain
		two-place <Ref k="nakagawa2024" p="137–140, 207–210" />. A rule that assigns one fixed person
		template to every semantically causative or reflexive event would obscure these differences. See <Xr
			ch="transitivity-and-valence-classes"
		/>.
	</p>
</S>

<S t="Predicates without an indexed participant" id="zero-place">
