<S t="Reading a kana source" id="katakana">
	<p>
		A kana source can be shown above its Latin analysis when its spelling matters. Small kana
		usually identify final consonants, but the treatment of final /t/, /r/, /y/, and /w/ varies
		among authors <Ref k="sato2008" p="16" />; <Ref k="nakagawa2024" p="61–69" />. The source's
		conventions determine whether a letter represents a vowel-bearing syllable or a final consonant.
	</p>
	<p>
		For example, Nakagawa shows that <span lang="ain-Kana">ミッポ</span> can represent either
		<i lang="ain-Latn">mitpo</i> or <i lang="ain-Latn">mippo</i> “grandchild” under the
		<em>Akor Itak</em> conventions <Ref k="nakagawa2024" p="68" />. A Latin transcription that
		selects one form has made an interpretive choice. The recording, a parallel Latin text, or the
		editor's explanation may resolve it. The correspondence rules are described in <Xr
			ch="katakana-and-small-kana-codas"
		/>.
	</p>
</S>

<S t="Sakhalin comparisons" id="cyrillic">
	<p>
		The language variety must be established independently of the script. Latin and kana sources
		also document Sakhalin Ainu, whose sound system differs from Hokkaido Ainu. In particular,
		Sakhalin vowel length can distinguish words; Nakagawa illustrates the comparison with Hokkaido
		accent distinctions <Ref k="nakagawa2024" p="26–27" />.
	</p>
	<p>
		Normalizing the script should preserve these distinctions. A doubled vowel in a Sakhalin form
		cannot be discarded on the grounds that ordinary Hokkaido spelling lacks phonemic vowel length.
		Sakhalin and Kuril examples carry their own dialect labels and are discussed as comparisons in <Xr
			ch="sakhalin-and-kuril-ainu-contrast"
		/>.
	</p>
</S>

