<S t="Reading across writing systems" id="traditions">
	<p>
		Ainu sources use several Latin and katakana conventions. The same spoken form can consequently
		look different in two editions, while one spelling can conceal a distinction made explicit
		elsewhere. Nakagawa's survey documents differences in consonant letters, glottal-stop notation,
		glides, person boundaries, and the kana treatment of closed syllables
		<Ref k="nakagawa2024" p="54–69" />.
	</p>
	<p>
		Three kinds of information need to be distinguished when comparing such sources: what the
		edition prints, how the expression is pronounced, and how its grammatical parts are analyzed. A
		transliteration transfers a spelling into another script. A phonemic transcription or
		morphological analysis can require further decisions about the language.
	</p>
</S>

