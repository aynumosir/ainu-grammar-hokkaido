<S t="When a possessor becomes the verbal subject" id="possessor-subject">
	<p>
		In some Ainu noun-incorporating predicates, a body-part noun forms a single stem with a verb,
		while the person whose body part is involved becomes the subject of the resulting predicate.
		Satō calls this <em>possessor-requiring subject incorporation</em>
		<Ref k="sato2016" p="84–86" />;
		<Ref k="satoni2022" p="§3.3" />. It provides a concrete instance of the grammatical relation
		often discussed as possessor raising or stranding.
	</p>
	<p>Satō's Chitose comparison makes the change visible:</p>
	<Ex
		m="ku=tek-e pase"
		orig="ku-ték-e páse"
		origLang="ain-Latn"
		g="1SG.A=hand-POSS heavy"
		tr="My hands are heavy."
		dial="CHI"
		cite="satoni2022:§3.3, example 23a"
	/>
	<Ex
		m="ku=tek-e-pase"
		orig="ku-ték-e-pase"
		origLang="ain-Latn"
		g="1SG.S=hand-POSS-heavy"
		tr="I feel as if I have aged."
		dial="CHI"
		cite="satoni2022:§3.3, example 23b"
		note="Literally, ‘I am my-hands-heavy.’ The source's person-prefix boundary is normalized to = in both examples."
	/>
	<p>
		In the first clause, the possessed hand is the subject of “be heavy.” In the second, the
		possessor is the subject of the whole incorporated predicate. The affiliative <i lang="ain-Latn"
			>-e</i
		>
		remains in the noun stem. The two occurrences of <i lang="ain-Latn">ku=</i> have the same shape, but
		the first indexes nominal possession and the second the intransitive verbal subject.
	</p>
</S>

<S t="Person marking, valency, and incorporation type" id="person-valency">
	<p>
		The change in grammatical relation does not require a prefix to become a suffix. First-singular <i
			lang="ain-Latn">ku=</i
		>
		remains prefixed in the published example. The fourth-person intransitive form uses a different
		position in the person paradigm; this follows the person system described in
		<Xr ch="person-marking-architecture" />
		<Ref k="satoni2022" p="§2, examples 1–2" />.
	</p>
	<p>
		Satō describes this construction as retaining verbal valency: the body-part subject is
		incorporated, while its possessor supplies the resulting subject. He assigns it to Mithun's Type
		II, which changes the grammatical relation of an element outside the incorporating verb
		<Ref k="satoni2022" p="§3.3" />;
		<Ref k="mithun1984" />. The broader incorporation classification appears in
		<Xr ch="noun-incorporation-subject-possessor-stranding" />.
	</p>
</S>

<S t="Backgrounding and reflexive interpretation" id="interpretation">
	<p>
		Satō explains the construction through a combination of body-part backgrounding and a reflexive
		interpretation: the incorporated noun's possessor is understood as the subject of the whole
		predicate. In his account, this limits how independently the incorporated noun is specified
		<Ref k="sato2016" p="85–87" />;
		<Ref k="satoni2022" p="§§4–5" /> ‹contested›. This is a theoretical explanation of the pattern. The
		published comparison establishes the grammatical contrast more directly than it establishes a general
		discourse condition for choosing it.
	</p>
</S>

<S t="A comparison without possession" id="natural-force-comparison">
	<p>
		Ainu also has incorporation in which an external subject corresponds to a patient. Satō compares
		a clause where waves wash someone with an incorporated predicate meaning that the person is
		washed by waves
		<Ref k="sato2016" p="85, example 4" />;
		<Ref k="satoni2022" p="§3.4, example 24" />.
	</p>
	<Ex
		m="koy en=yanke"
		g="wave 1SG.O=raise"
		tr="The waves wash me up."
		cite="satoni2022:§3.4, example 24a"
		dial="CHI"
		note="Person boundary normalized from the source's hyphen."
	/>
	<Ex
		m="ku=koy-yanke"
		g="1SG.S=wave-raise"
		tr="I am washed up by the waves."
		cite="satoni2022:§3.4, example 24b"
		dial="CHI"
	/>
	<p>
		The person here is the affected patient. There is no possessive relation between that person and
		the waves. The example illustrates another change in grammatical relation caused by
		incorporation, with a different semantic basis.
	</p>
</S>

<S t="Object incorporation has different restrictions" id="object-incorporation">
	<p>
		The subject pattern cannot simply be extended to objects. Satō rejects
		<i lang="ain-Latn">*a-i-par-oyki</i> for “People support me,” with
		<i lang="ain-Latn">i-</i> interpreted as a person index for the possessor of the incorporated
		mouth. He gives the phrasal alternative
		<i lang="ain-Latn">i-par a-oyki</i>, and treats this close noun–verb combination as
		quasi-incorporation
		<Ref k="sato2016" p="89–90" />;
		<Ref k="satoni2022" p="§4, examples 28–29; §6" />.
	</p>
	<p>
		A different, derivational <i lang="ain-Latn">i-</i> appears in formations with an unspecified
		possessor. Bugaeva, Nichols and Bickel analyze it as antipassive morphology functioning as
		unspecified-possessor marking when the possessor is non-coreferential with the subject. Their
		examples include
		<i lang="ain-Latn">i-rekut-tuye</i> “cut someone's throat,” reported from Okuda (1999) <Ref
			k="bugaeva2021poss"
			p="54, example 16b and note 11"
		/>. Satō likewise distinguishes derivational and inflectional uses of the homophonous prefix <Ref
			k="satoni2022"
			p="§4"
		/>.
	</p>
	<p>
		These object-incorporation conditions concern different constructions from
		<i lang="ain-Latn">tek-e-pase</i>. They do not require the affiliative vowel to disappear from
		the subject-incorporating example.
	</p>
</S>

<S t="Related derivations and the scope of the comparison" id="related-derivations">
	<p>
		Kobayashi uses “affiliative-like” for some valency-neutral
		<i lang="ain-Latn">e-</i> and <i lang="ain-Latn">o-</i> derivatives referring to a head/tip or a
		lower/end part. His analysis retains the participant whose part is involved and distinguishes
		these patterns from valency-increasing applicatives <Ref k="kobayashi2025" p="171, 176" />. His
		proposed relation to verb classes is a tendency with an acknowledged counterexample ‹contested›.
	</p>
	<p>
		Applicative prefixes have a wider range of argument-structural functions
		<Ref k="bugaeva2006" p="185–187, 192" />. Those functions are described in
		<Xr ch="applicative-system-overview" />. The possessor-to-subject contrast developed here rests
		on the specific incorporation examples and their person-marking diagnostics.
	</p>
</S>
