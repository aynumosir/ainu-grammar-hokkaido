<S t="Plural reference does not always require a plural stem" id="singular-defaults">
	<p>
		Nakagawa gives transitive singular stems with explicitly plural objects. In a Saru narrative, <i
			lang="ain-Latn">a=eci=rayke</i
		>
		combines second-person plural object marking with singular “kill.” Other examples describe repeated
		hunting with either singular
		<i lang="ain-Latn">rayke</i> or plural
		<i lang="ain-Latn">ronnu</i>
		<Ref k="nakagawa2024" p="144–145, examples 48–52" />. He consequently treats singular as a
		default in such transitive pairs, with plural making the multiplicity salient.
	</p>
	<p>
		The intransitive pattern is different in his analysis. A single husband going back and forth
		repeatedly retains singular “go” and “come”; repetition alone does not require the plural stems
		<Ref k="nakagawa2024" p="145, example 53, from Tamura 1984: 30" />. Shibatani discusses lexical
		selectional restrictions as an alternative to ordinary agreement for much of the number system
		<Ref k="shibatani1990" p="52–54" /> ‹contested›.
	</p>
	<p>
		Numerals and quantifiers often occur with singular forms, but plural forms are also documented.
		Their distribution supplies no fixed numerical threshold for switching stems
		<Ref k="nakagawa2024" p="160–162" />;
		<Ref k="refsing1986" p="117–118" />. See <Xr
			ch="numeral-classifiers-ordinals-and-quantifier-syntax"
		/>.
	</p>
</S>

<S t="Additional pa and ci" id="additional-plural-marking">
	<p>
		Additional <i lang="ain-Latn">pa</i> must be distinguished from the stem-forming pattern above.
		It can follow an already plural stem or causative morphology and can occur after a person
		suffix. Nakagawa analyzes it as an auxiliary; the Handbook discussion also considers clitic
		terminology <Ref k="nakagawa2024" p="156–160" />;
		<Ref k="nakagawa2022" p="§5.1" />. Satō's Chitose description retains suffixal terminology and
		reports limited evidence for its exceptional position
		<Ref k="sato2008" p="103–104" /> ‹contested›.
	</p>
	<p>
		Additional <i lang="ain-Latn">pa</i> can express participant plurality or repeated action.
		Nakagawa explains its occurrence after an already plural stem by assigning the two forms
		different contributions: the stem may count participants and the following
		<i lang="ain-Latn">pa</i>
		repeated events, or the stem may express object/action plurality while
		<i lang="ain-Latn">pa</i> identifies several actors
		<Ref k="nakagawa2024" p="157–158" />.
	</p>

	<p>
		Satō gives accepted <i lang="ain-Latn">yaynu-an-pa</i> and rejected
		<i lang="ain-Latn">*yaynu-pa-an</i>
		in 2008. His later discussion reports a different elicitation in which proposed
		<i lang="ain-Latn">yaynu-as pa</i> was returned without
		<i lang="ain-Latn">pa</i>; the further form he considers is a possibility, not an established
		correction to the earlier example
		<Ref k="sato2008" p="104" />;
		<Ref k="sato2025b" p="26" />.
	</p>
	<p>
		The distribution of <i lang="ain-Latn">ci</i> also differs by dialect. Nakagawa contrasts
		Horobetsu
		<i lang="ain-Latn">iki-ci=as</i>, with the number element inside the person suffix, and Shizunai
		<i lang="ain-Latn">hotke=an ci</i>, with it after the inflected verb. Additional
		<i lang="ain-Latn">pa</i>
		occurs in Saru and Chitose, but also Tokachi and Ishikari in his account
		<Ref k="nakagawa2024" p="155–159" />. These distributions are more specific than a
		western–eastern division.
	</p>
	<p>
		Nakagawa compares Sakhalin <i lang="ain-Latn">(a)hci</i> with these forms, drawing on Murasaki's
		descriptions. Its person and number distribution, and its status as an affix or a following
		element, receive different analyses <Ref k="nakagawa2024" p="153–156" />;
		<Ref k="nakagawa2022" p="§5.3" /> ‹contested›.
	</p>
</S>

