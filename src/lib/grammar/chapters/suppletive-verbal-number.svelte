<S t="Number is a property of particular verb stems" id="verbal-number">
	<p>
		Some Ainu verbs have distinct singular and plural stems. The distinction is especially visible
		in existence, posture, movement, and certain transitive actions; most verbs have no such pair
		<Ref k="nakagawa2024" p="141–148" />;
		<Ref k="sato2008" p="101–104" />. Stem number is therefore a lexical property to learn alongside
		a verb's argument frame.
	</p>
	<p>
		Intransitive alternations generally follow the subject's number. Transitive alternations often
		concern the object or repeated action, but there are exceptions. The transitive pair
		<i lang="ain-Latn">eramuan / eramuoka</i> “understand,” for example, follows the subject in
		Nakagawa's Saru examples
		<Ref k="nakagawa2024" p="142–143" />. A causative may retain the base verb's number contrast:
		the participant that was its subject becomes an object of the causative
		<Ref k="nakagawa2024" p="146" />.
	</p>
</S>

