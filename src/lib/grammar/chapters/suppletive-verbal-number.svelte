<S t="Consonant alternation and stem-forming pa" id="formal-patterns">
	<p>
		A group of directional intransitives alternates final
		<i lang="ain-Latn">-n</i> and <i lang="ain-Latn">-p</i>:
		<i lang="ain-Latn">rikin / rikip</i> “ascend,”
		<i lang="ain-Latn">ran / rap</i> “descend,”
		<i lang="ain-Latn">san / sap</i> “come down from the mountains,” and
		<i lang="ain-Latn">ahun / ahup</i>
		“enter”
		<Ref k="nakagawa2024" p="148, table 18" />. Other apparent pairs have narrower documentation:
		the plural
		<i lang="ain-Latn">repup</i> is reported only from Shiranuka in that survey, and
		<i lang="ain-Latn">makap</i>
		from Samani, Kushiro, and Sakhalin <Ref k="nakagawa2024" p="148, notes 10–11" />.
	</p>
	<p>
		A further pattern replaces a final vowel with
		<i lang="ain-Latn">-pa</i>, as in
		<i lang="ain-Latn">tuye / tuypa</i> “cut,”
		<i lang="ain-Latn">kaye / kaypa</i> “break,” and
		<i lang="ain-Latn">komo / kompa</i> “bend something.” Many such transitive pairs concern a
		change in the object, but
		<i lang="ain-Latn">ani / anpa</i> “hold” illustrates a different meaning <Ref
			k="nakagawa2024"
			p="149–150, table 20"
		/>.
	</p>
	<p>
		Derived intransitives can retain the alternation. Nakagawa relates
		<i lang="ain-Latn">hopuni / hopunpa</i> “get up” to
		<i lang="ain-Latn">puni / punpa</i> “raise something.” In the intransitive pair, the contrast
		follows the subject
		<Ref k="nakagawa2024" p="150–151, table 21" />.
	</p>
	<Ex
		m="kunneywa tunas, a=yupi hopuni hine suke"
