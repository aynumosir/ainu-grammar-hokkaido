<S t="Word accent within an utterance" id="rising-nucleus">
	<p>
		Intonation is the pitch pattern of a phrase or utterance. In Ainu varieties with lexical accent,
		it coexists with the accent of individual words. Saru
		<i lang="ain-Latn">nísap</i> “suddenly” and <i lang="ain-Latn">nisáp</i> “shin” differ in accent
		position, but their complete pitch contours also depend on how they are spoken in context <Ref
			k="nakagawa2024"
			p="48–49"
		/>.
	</p>
	<p>
		Nakagawa's rising-kernel account allows the pitch after the accented syllable to remain high or
		to fall. The accent mark identifies the lexical rise without specifying every later pitch
		movement <Ref k="nakagawa2024" p="49" />. This leaves room for utterance intonation to express a
		question, an exclamation, or an expectation that the listener will respond. Word-level rules are
		described in <Xr ch="pitch-accent-placement-rule" />.
	</p>
</S>

<S t="Dialect and source coverage" id="dialect-split">
	<p>
		The best-known accounts of Ainu intonation concern particular varieties and samples. Shiraishi
		reviews instrumental work on Saru and a study of Tokachi questions
		<Ref k="shiraishi2022" p="§7" />. Refsing gives a shorter description for Shizunai, with
		slightly falling declaratives and gradually rising questions
		<Ref k="refsing1986" p="§10.6, 74" />.
	</p>
	<p>
		These descriptions should be kept separate from the classification of dialects by lexical
		accent. A variety can lack an accent contrast between words while retaining meaningful utterance
		contours. Nakagawa and Fukazawa's regional accent classification concerns the former distinction <Ref
			k="nakagawafukazawa2022"
			p="§3.1"
		/>.
	</p>
</S>

<S t="Statements and continuation" id="declarative">
	<p>
		Tamura describes ordinary Saru speech as having a gradual decline in pitch, without an
		additional marked rise or fall at the sentence end. Shiraishi reports this description alongside
		acoustic studies that support it <Ref k="tamura1996" p="4, via Shiraishi 2022 §7" />;
		<Ref k="shiraishi2022" p="§7" />. The general decline can coexist with the local prominence of
		accented words.
	</p>
	<p>
		A level or falling ending can also occur where more speech is expected. Shiraishi reports
		Simeon's observation that such contours indicate continuation, while a terminal rise can mark an
		utterance as complete <Ref k="shiraishi2022" p="§7" />. This observation and Tamura's
		description concern different contrasts. They do not imply that every falling declarative is
		grammatically incomplete, or that a rise has a single function throughout Ainu.
	</p>
</S>

<S t="Questions and expectations of a response" id="interrogative">
	<p>
		In Tamura's Saru account, a rising contour can accompany an expectation of a response to a
		report, question, answer, request, or invitation. Questionhood is therefore one use of the rise
		within a wider interactional pattern
		<Ref k="tamura1996" p="4, via Shiraishi 2022 §7" />.
	</p>
	<p>
		Makarova examined 35 Saru interrogatives and found pronounced pitch movement and an intensity
		peak mainly on the final word, often an interrogative particle. Shiraishi's review also records
		three questions in that sample without a final rise
		<Ref k="shiraishi2022" p="§7, reporting Makarova 2002:76" />. The sample supports a frequent
		pattern with exceptions; it does not establish an obligatory rising contour.
	</p>
	<Ex
		m="Kusur ta e-arpa amkir_a"
		g="Kushiro LOC 2SG.S-go.SG know_Q"
		tr="Have you ever been to Kushiro?"
		cite="shiraishi2022:§7, example 30"
		dial="SAR"
		note="Tamura and Motohashi's example as reproduced by Shiraishi, who reports a falling ending. The source's underscore represents the contracted final sequence amkir + ya; segmentation is retained."
	/>
	<p>
		The final question particle in this example is represented in a contracted form. Tamura and
		Motohashi consider both a possible association with
		<i lang="ain-Latn">ya</i> and influence from Japanese; they leave the explanation open
		<Ref k="shiraishi2022" p="§7" /> ‹speculative›. The morphology and interpretation of question particles
		are discussed in <Xr ch="interrogative-strategies-question-particles" />.
	</p>
	<p>
		For Tokachi, Takahashi describes non-rising questions ending in a noun or nominalizer, or in a
		connective followed by an interrogative particle. He associates the absence of the expected
		final predicate with incompleteness and a request for confirmation
		<Ref k="shiraishi2022" p="§7, reporting Takahashi 2015:24" />. The proposed relation between
		confirmation and an absent predicate concerns these Tokachi constructions. The Saru question
		above has a predicate and presents a different structural case.
	</p>
</S>

<S t="Exclamations and wishes" id="exclamatory">
	<p>
		Tamura describes Saru exclamations and wishes with an elevated pitch level across the utterance
		and a lengthened rising–falling contour at the end
		<Ref k="tamura1996" p="4, via Shiraishi 2022 §7" />. Both the overall register and the final
		movement matter in this description.
	</p>
	<p>
		Sentence-final particles also contribute to the interpretation of an utterance. Their forms and
		speech-act functions are described in
		<Xr ch="sentence-final-particles-illocutionary-force" />.
	</p>
</S>

<S t="Grouping words into larger units" id="phrasal-domains">
	<p>
		Pitch also reflects how words combine. Shiraishi reports that close combinations, including
		compounds and some modifier–noun or verb–auxiliary sequences, can give primary accent to the
		first member and weaken the second member's accent
		<Ref k="shiraishi2022" p="§5.2" />. Such a combination need not correspond to one
		space-delimited word. See <Xr ch="accent-in-compounds-and-affixation" />.
	</p>
	<p>
		Consonant changes at boundaries provide another kind of evidence for grouping. In the Saru
		recordings reviewed by Shiraishi, /n/-sandhi was blocked at sentence boundaries, whereas
		/r/-sandhi could extend across them. Both processes were sensitive to an intervening pause <Ref
			k="shiraishi2022"
			p="§6.2"
		/>. Their domains consequently cannot simply be identified with the domain of compound accent.
		These boundary effects are described in <Xr ch="coda-r-assimilation-sonorant-sandhi" />.
	</p>
</S>

<S t="Japanese contact as a proposed explanation" id="hachijo">
	<p>
		The falling Saru questions discussed above have prompted comparison with Japanese, including
		falling polar questions in Hokkaido Japanese. Shiraishi reports contact as one explanation
		considered by Tamura and Motohashi, alongside a possible effect of the Ainu question particle <Ref
			k="shiraishi2022"
			p="§7"
		/> ‹speculative›.
	</p>
	<p>
		The observed Ainu contour and the proposed reason for it have different evidential status. A
		falling question is documented; the historical or interactional source of that contour remains
		unresolved in the cited study. Similarity between two languages' pitch patterns is insufficient
		by itself to establish borrowing.
	</p>
</S>
