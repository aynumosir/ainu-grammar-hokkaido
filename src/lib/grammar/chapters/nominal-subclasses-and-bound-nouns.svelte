<S t="Common nouns and the affiliative form" id="common-nouns">
	<p>
		The conceptual form presents an entity without explicitly relating it to another. The <Xr
			ch="concept-form-affiliative-form">affiliative form</Xr
		> presents it in such a relation, often possession. For example, <i lang="ain-Latn">tek</i>
		“hand” has <i lang="ain-Latn">teke(he)</i>, with an optional longer ending
		<Ref k="nakagawa2024" p="217, 227" />. The first-person form is
		<i lang="ain-Latn">ku=tekehe</i> “my hand”
		<Ref k="nakagawa2024" p="216" />.
	</p>
	<S t="The extent of the paradigm" id="affiliative-conditions">
		<p>
			Bugaeva states that some Southern Hokkaido common nouns lack possessive forms
			<Ref k="bugaeva2012" p="470" />. Nakagawa argues that an affiliative can potentially be formed
			when a suitable semantic relation is available
			<Ref k="nakagawa2024" p="230" /> ‹contested›. The latter account also retains unresolved conditions
			involving particular modifiers and constructions
			<Ref k="nakagawa2024" p="230–233" />.
		</p>
		<p>
			Suffix selection is partly lexical and varies by dialect. The final vowel alone does not
			determine every ending <Ref k="nakagawa2024" p="226–230" />. The forms are described in <Xr
				ch="affiliative-suffix-morphophonology"
			/>.
		</p>
	</S>
</S>

<S t="Two senses of nominal dependence" id="bound-nouns">
	<p>
		The label <em>bound noun</em> has different uses in descriptions of Ainu. Bugaeva's 2012
		subclass contains forms that require a modifier: for example,
		<i lang="ain-Latn">tan kur</i> “this person,” with bare
		<i lang="ain-Latn">*kur</i> excluded in the cited contrast
		<Ref k="bugaeva2012" p="470" />. In her account of possession, <em>bound inalienables</em>
		instead describes dependence associated with possessive morphology
		<Ref k="bugaeva2022" p="§5.1.1" />. Requiring a modifier and requiring a possessive relation are
		distinct grammatical properties.
	</p>
	<S t="Kinship nouns" id="kinship-subclasses">
		<p>
			Kinship terms differ in whether they can be used in address and in the forms used for
			reference. A reference-only term can still describe the speaker's own relative
			<Ref k="nakagawa2024" p="222–224" />. Some terms also depend on the sex of the person through
			whom the relation is defined: <i lang="ain-Latn">tures</i>
			is a man's younger sister, while <i lang="ain-Latn">matak</i> is a woman's younger sister <Ref
				k="nakagawa2024"
				p="223–224"
			/>. Their possessive and address patterns are treated in <Xr
				ch="kinship-honorific-possession"
			/>.
		</p>
	</S>
	<S t="Independence and contextual reference" id="boundness-gradience">
		<p>
			Nakagawa ranks common-noun conceptual forms, Type-2 locative nouns, and pronouns as relatively
			independent. Affiliatives and long locative forms can constitute a noun phrase while
			presupposing a possessor or reference point. Basic Type-1 locatives have stronger syntactic
			dependence, and formal nouns require modification
			<Ref k="nakagawa2022pos" p="§3.3" />. This account distinguishes several degrees of dependence
			within the nominal domain.
		</p>
	</S>
</S>

<S t="Locative nouns and grammatical locations" id="locative-nouns">
	<p>
		Locative nouns such as <i lang="ain-Latn">ka</i> “top” and
		<i lang="ain-Latn">sam</i> “side” identify a spatial relation to a reference point. They take
		O-series markers, as in <i lang="ain-Latn">en=ka</i> “above me”
		<Ref k="nakagawa2024" p="216" />. They also supply the grammatical location required by locative
		particles and certain verbs.
	</p>
	<p>
		Common-noun conceptual forms generally require a locative noun in such constructions. Nakagawa's
		Saru contrast has <i lang="ain-Latn">nupuri or ta</i> “at the mountain,” with
		<i lang="ain-Latn">or</i>
		before <i lang="ain-Latn">ta</i>; he rejects bare <i lang="ain-Latn">nupuri ta</i> in that
		example
		<Ref k="nakagawa2024" p="216, example 233" />. Lexical and regional exceptions include uses of
		<i lang="ain-Latn">kotan</i>
		“village,”
		<i lang="ain-Latn">mosir</i> “land,” and place names
		<Ref k="nakagawa2022pos" p="§4.5" />.
	</p>
	<p>
		Common-noun affiliatives generally function as locations too. Nakagawa's Chitose example places
		the affiliative of “mouth” directly before the source particle:
	</p>
	<Ex
		m="par-oho wa konkane tuy wa"
		ain="paroho wa konkane tuy wa"
		g="mouth-POSS ABL gold fall CONJ"
		tr="Gold fell from its mouth, and…"
		cite="nakagawa2024:216, example 235"
		dial="CHI"
	/>
	<p>
		There are exceptions, including kinship terms in the 2022 account and a Shizunai example with <i
			lang="ain-Latn">cisehe or ta</i
		>, where an affiliative is still followed by a locative noun <Ref
			k="nakagawa2022pos"
			p="§4.5"
		/>;
		<Ref k="nakagawa2024" p="220–221" />. The constructional details are described in <Xr
			ch="postpositions-local-case-and-motion-events"
		/>.
	</p>
	<S t="Basic and long forms" id="locative-types">
		<p>
			Type-1 locatives such as <i lang="ain-Latn">sam</i> require a preceding reference expression
			when the basic form is unprefixed. A person prefix can supply that relation: Nakagawa's
			Chitose example begins
			<i lang="ain-Latn">en=sam un</i> “to my side” without a preceding noun phrase
			<Ref k="nakagawa2024" p="239–241, example 281" />. Long forms can occur with their reference
			point understood from context.
		</p>
		<p>
			Type-2 locatives, including <i lang="ain-Latn">soy</i> “outside” and
			<i lang="ain-Latn">kim</i> “mountains, inland,” allow independent basic forms. They also have
			long forms, such as <i lang="ain-Latn">soykehe</i>
			and <i lang="ain-Latn">kimkehe</i>. Nakagawa reports that person marking remains unconfirmed
			for many members of this type
			<Ref k="nakagawa2024" p="245–246" />. See
			<Xr ch="relational-and-spatial-nouns" /> for the wider inventory.
		</p>
	</S>
	<S t="Differences between the locative analyses" id="type2-controversy">
		<p>
			Nakagawa's 2022 account permits locative nouns to be modified by a verb phrase
			<Ref k="nakagawa2022pos" p="§3.4, Table 3" />. His 2024 grammar explicitly excludes this
			possibility, alongside the corresponding restriction on pronouns
			<Ref k="nakagawa2024" p="215, Table 47" /> ‹contested›. Clause modification therefore receives different
			treatments even within these two closely related classification schemes.
		</p>
	</S>
</S>

<S t="Proper names" id="proper-nouns">
	<p>
		Refsing distinguishes proper names from general nouns, noting restrictions on affixes and the
		rarity of preceding modifiers in her Shizunai account
		<Ref k="refsing1986" p="75, 89" />. Nakagawa discusses their distinctive behavior without
		establishing a separate major noun subclass
		<Ref k="nakagawa2024" p="233" /> ‹contested›. Both accounts recognize that names differ in typical
		distribution from ordinary descriptive nouns.
	</p>
</S>

<S t="Pronouns and formal nouns" id="pronouns-formals-overview">
	<p>
		Pronouns can stand as noun phrases but do not take the ordinary possessive morphology. Formal
		nouns depend on modifiers, with item-specific restrictions
		<Ref k="nakagawa2022pos" p="§§3.1–3.4" />. Their respective systems are described in <Xr
			ch="independent-personal-pronouns"
		/> and
		<Xr ch="formal-defective-nouns" />.
	</p>
	<p>
		The evidential forms <i lang="ain-Latn">ruwe</i>, <i lang="ain-Latn">hawe</i>,
		<i lang="ain-Latn">siri</i>, and <i lang="ain-Latn">humi</i> preserve affiliative morphology.
		Nakagawa relates their formal-noun-like uses to ordinary nouns, while Bugaeva assigns evidential
		uses to particles
		<Ref k="nakagawa2024" p="258–259" />;
		<Ref k="bugaeva2012" p="470" /> ‹contested›. Nominal origin and current constructional function receive
		separate treatment in
		<Xr ch="evidential-schema-overview" />.
	</p>
</S>
