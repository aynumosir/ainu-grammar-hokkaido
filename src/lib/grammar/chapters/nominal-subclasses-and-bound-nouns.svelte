		person marking, independence, and permitted modifiers
		<Ref k="nakagawa2022pos" p="§3" />;
		<Ref k="nakagawa2024" p="214–217" />. Bugaeva uses three noun subclasses, common, relational,
		and bound nouns, with pronouns separate
		<Ref k="bugaeva2012" p="469–470" />. Her relational nouns correspond broadly to Nakagawa's
		locative nouns, and her small bound-noun class to formal nouns.
	</p>
