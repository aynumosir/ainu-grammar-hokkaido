<S t="The causee's grammatical role" id="causee">
	<p>
		In a productive causative, the causer becomes the subject and the base's subject becomes a
		causee object. Nakagawa demonstrates the change with first-person marking:
		<i lang="ain-Latn">ku=sinot</i> “I played” corresponds to
		<i lang="ain-Latn">hapo en=sinot-te</i> “Mother made me play”
		<Ref k="nakagawa2024" p="431, examples 955–955′" />. The S form changes to O even though the
		person playing is the same.
	</p>
	<p>
		A transitive base already has an object. Causativization can retain that object while adding the
		causee, producing a three-place verb
		<Ref k="bugaeva2014" p="138, 141–142" />;
		<Ref k="bugaevakobayashi2022" p="§4.1.2" />. The resulting semantic roles need to be
		distinguished from the smaller number of person indexes visible on the verb.
	</p>
</S>

<S t="An indexed causee and an expressed theme" id="three-place">
	<Ex
		m="ki kusu hat punkar a=e=tuy-e-re wa"
		g="do because grape vine 4.A=2SG.O=be.cut-TRVZ-CAUS CONJ"
		tr="So I made you cut grapevines, and …"
		cite="bugaeva2014:142"
		dial="SAR"
		place="Example 23c; Kimura Kimi, K7803233UP.144"
		note="Bugaeva glosses both suffixes CAUS. The TRVZ–CAUS gloss here distinguishes the forming vowel from productive causative -re, following Nakagawa's terminology."
	/>
	<p>
		The narrative causer is indexed by <i lang="ain-Latn">a=</i>, the causee by
		<i lang="ain-Latn">e=</i>, and the vines are the theme being cut. This example shows a free
		theme phrase alongside an indexed causee. It does not establish an unrestricted preference rule
		for every three-place causative
		<Ref k="bugaeva2014" p="142, example 23c" />;
		<Ref k="bugaevakobayashi2022" p="§4.1.2, example 6c" />.
	</p>
	<p>
		The handbook describes simultaneous overt expression of both objects as infrequent and notes
		ordinary omission when context supplies the reference
		<Ref k="bugaevakobayashi2022" p="§4.1.2" />. Bugaeva's earlier wording is more categorical
		<Ref k="bugaeva2014" p="142–143" /> ‹contested›. An absent noun phrase should therefore be distinguished
		from an absent argument position.
	</p>
</S>

<S t="What double causative counts" id="double-causative">
	<p>
		The description of <i lang="ain-Latn">tuy-e-re</i> as a double causative depends on the analysis
		of <i lang="ain-Latn">tuy-e</i>. Bugaeva counts its vowel ending as direct causation and the
		following productive suffix as an additional causal layer. Nakagawa treats that vowel as a
		transitive forming suffix on a root
		<Ref k="bugaeva2014" p="130–131, 142" />;
		<Ref k="nakagawa2024" p="199–200" /> ‹contested›.
	</p>
	<p>
		The recorded <i lang="ain-Latn">kor-e-re</i> “cause someone to give” contains two ordinary
		causative layers: <i lang="ain-Latn">kor</i> “have,”
		<i lang="ain-Latn">kor-e</i> “give,” and a further causative. Bugaeva cites this form from
		Batchelor's dictionary; Nakagawa also records the dictionary attestations
		<Ref k="bugaeva2014" p="143, citing Batchelor 1938:269" />;
		<Ref k="nakagawa2024" p="135" />. A dictionary headword establishes the recorded formation
		without supplying its frequency or a complete clause with all participants expressed.
	</p>
</S>

<S t="Four participants in a textual example" id="four-place">
	<p>
		Nakagawa's Saru example describes a narrator asking a woman to empty food into a cat's dish. It
		contains a further causative of three-place <i lang="ain-Latn">omare</i> “put something in
		something” <Ref k="nakagawa2024" p="135, example 34" />.
	</p>
	<Ex
		m="a=omare-re akusu"
		g="4.A=put-CAUS CONJ"
		tr="When I had her put it there, …"
		cite="nakagawa2024:135"
		dial="SAR"
		place="Final predicate of example 34, from Chiba University ed. 2015:420, as reproduced by Nakagawa"
		note="The preceding instruction and narrative identify the woman, the food, and the cat's dish. The source writes the derived stem omarere without internal hyphens."
	/>
	<table>
		<thead><tr><th>Role</th><th>Participant supplied by the passage</th></tr></thead>
		<tbody>
			<tr><td>Causer</td><td>The narrator</td></tr>
			<tr><td>Causee</td><td>The woman asked to perform the placement</td></tr>
			<tr><td>Theme</td><td>The contents being transferred</td></tr>
			<tr><td>Location</td><td>The cat's dish</td></tr>
		</tbody>
	</table>
	<p>
		The four roles are recoverable from discourse. They do not appear as four separate bare noun
		phrases accompanying this predicate. Nakagawa uses the passage as textual evidence that
		causativization of a three-place base is possible <Ref k="nakagawa2024" p="135" />.
	</p>
</S>

<S t="Backgrounding and causal interpretation" id="backgrounding">
	<p>
		Bugaeva compares causee incorporation and antipassive formation across causative classes. Her
		account permits backgrounding of nonreferential causees in documented direct
		<i lang="ain-Latn">-ka</i> and productive-causative constructions, while excluding it in
		indirect causatives and in the direct vowel and <i lang="ain-Latn">-ke</i> formations she
		compares <Ref k="bugaeva2014" p="131–132, 137–138, 141–144" />. She relates the distribution to
		affectedness and referentiality; the restrictions belong to that analysis and its lexical
		comparisons.
	</p>
	<p>
		Indefinite <i lang="ain-Latn">-yar/-ar</i> offers a different construction, retaining valency
		without adding a causee object. Its structure and the older plural-causee accounts are treated
		in <Xr ch="permissive-sociative-causative-yar" />. For the productive forms, see <Xr
			ch="causative-morphological-re-e-te"
		/>.
	</p>
</S>
