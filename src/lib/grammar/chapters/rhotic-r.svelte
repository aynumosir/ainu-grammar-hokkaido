<S t="The rhotic consonant" id="overview">
	<p>
		The consonant /r/ occurs both at the beginning and at the end of a Hokkaido Ainu syllable. A tap
		[ɾ] is its common realization, but speakers also produce trilled and other variants
		<Ref k="nakagawa2024" p="28, 30" />; <Ref k="sato2008" p="12" />. Its final realization deserves
		particular attention because a vowel-like release can make a closed syllable sound as though it
		ends in a vowel.
	</p>
	<p>
		The phonological distinction between /r/ and /rV/ is supported by pronunciation, suffix
		selection, and behavior at boundaries. The release of final /r/ cannot be read as an additional
		vowel solely because it is audible <Ref k="shiraishi2022" p="§3.2" />.
	</p>
</S>

<S t="Realizations of r" id="onset">
	<p>
		Nakagawa describes syllable-initial /r/ as usually a tap, with a trill or a voiced stop-like
		realization in some speakers. Shiraishi's review also reports lateral and [d]-like variants <Ref
			k="nakagawa2024"
			p="28"
		/>;
		<Ref k="shiraishi2022" p="§3.2" />. These are phonetic descriptions of one rhotic category in
		the cited varieties.
	</p>
	<p>
		The precise realization therefore needs a speaker and context. Latin <em>r</em> identifies the phoneme
		without committing every occurrence to a single articulatory shape. A narrow transcription may add
		the detail required for a phonetic comparison.
	</p>
</S>

<S t="Final r and its vowel-like release" id="coda-echo">
	<p>
		The release of final /r/ often resembles the preceding vowel, giving the familiar term
		<em>echo vowel</em>. It can also be influenced by a following vowel or have a more central
		quality. Nakagawa discusses the pronunciations of <i lang="ain-Latn">pirka</i> “good” and
		<i lang="ain-Latn">arki</i>
		“come, plural,” while Shiraishi reviews instrumental and descriptive work on the variation <Ref
			k="nakagawa2024"
			p="30–31"
		/>;
		<Ref k="shiraishi2022" p="§3.2" />; <Ref k="bugaeva2012" p="466" />.
	</p>
	<p>
		A full vowel after /r/ can distinguish words. The pair
		<i lang="ain-Latn">etor</i> “nasal mucus” and <i lang="ain-Latn">etoro</i> “snore” is a standard
		example <Ref k="nakagawa2024" p="30" />. In connected speech the difference can be difficult to
		hear, so grammatical behavior provides additional evidence.
	</p>
	<p>
		Shiraishi recounts Chiri Yukie's observations, reported by Kindaichi, that /r/-final forms
		select consonant-following suffixes and participate in consonant sandhi. The nominalizer
		alternation illustrates the point:
	</p>
	<Ex
