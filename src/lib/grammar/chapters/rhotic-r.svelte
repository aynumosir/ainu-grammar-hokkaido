<S t="Devoicing and frication in clusters" id="devoicing">
	<p>
		Shibatani describes devoicing of the rhotic after [k] and [p], devoicing with some frication
		after [t], and a fully fricated voiceless realization after [ʃ]
		<Ref k="shibatani1990" p="§2.2" />. These statements concern adjacent consonants. They should be
		distinguished from the vowel-like release of a rhotic following a vowel.
	</p>
	<p>
		The phonetic variants leave /r/ in the consonant inventory. Their distribution can be
		investigated in recordings without treating each realization as a separate phoneme.
	</p>
</S>

<S t="Changes at morpheme and word boundaries" id="sandhi-activity">
	<p>
		Final /r/ participates in assimilation. Among the diagnostics reviewed by Shiraishi is the
		contrast between a final /r/ that changes before /n/ and a full /rV/ sequence that does not. The
		cited form <i lang="ain-Latn">a-kor-nispa</i> “my husband” has a pronunciation with [nn] at the
		/r+n/ boundary, while
		<i lang="ain-Latn">poro nay</i> “big river” retains the vowel before /n/
		<Ref k="shiraishi2022" p="§3.2" />.
	</p>
	<p>
		The environments, dialect differences, and degrees of regularity are treated in
		<Xr ch="coda-r-assimilation-sonorant-sandhi" />. This morphological evidence is also useful when
		an isolated recording leaves the presence of a full vowel uncertain.
	</p>
</S>

<S t="Dialectal comparisons" id="dialect">
	<p>
		Some northern Hokkaido records have alternatives with and without a vowel after /r/. Shiraishi
		discusses <i lang="ain-Latn">kikir</i> ~ <i lang="ain-Latn">kikiri</i>
		“insect,” citing Asai's observations <Ref k="shiraishi2022" p="§3.2" />. These forms show why
		the lexical shape must be established for the particular variety.
	</p>
	<p>
		In Sakhalin, Tangiku describes a vowel following historical final /r/ and illustrates
		<i lang="ain-Latn">nukara</i> “see” beside Hokkaido
		<i lang="ain-Latn">nukar</i>
		<Ref k="tangiku2022" p="§2.4" />. A Sakhalin full vowel and a Hokkaido phonetic release have
		different structural status, even when their pronunciations seem similar. The comparative
		patterns are developed in
		<Xr ch="sakhalin-and-kuril-ainu-contrast" />.
	</p>
