	<p>
		The ending of <i lang="ain-Latn">mokor</i> behaves as a consonant despite its audible release.
		This distinction was obscured by older spellings such as
		<i lang="ain-Latn">mokoro</i>, as discussed in
		<Xr ch="historical-orthographies-and-the-batchelor-tradition" />.
	</p>
	<p>
		Performance can make the release more prominent. Shiraishi describes lengthening in song and
		emphatic speech, as well as Satō's observation of a repeated final vowel used to fill a pause
		after /r/-final words <Ref k="shiraishi2022" p="§3.2" />. Such realizations need their prosodic
		context preserved in transcription.
	</p>
