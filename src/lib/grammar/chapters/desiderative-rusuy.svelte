<S t="Desire after a predicate" id="form">
	<p>
		The auxiliary <i lang="ain-Latn">rusuy</i> commonly expresses wanting to perform an action. In
		the separate-auxiliary construction, the preceding verb carries person marking.
		<i lang="ain-Latn">Rusuy</i>
		itself does not inflect
		<Ref k="sato2008" p="77" /><Ref k="nakagawa2024" p="305, 311" />.
	</p>
	<Ex
		m="nisatta k=ekimne rusuy"
		g="tomorrow 1SG.S=go.hunting DES"
		tr="I want to go hunting tomorrow."
		cite="sato2008:77"
		dial="CHI"
		place="Lesson 9, example 2"
	/>
	<p>
		Desire can concern another person. Refsing gives Shizunai questions about the addressee's wish
		to eat, conditional clauses of the same kind, and a narrative about a horse deity wanting a wife <Ref
			k="refsing1986"
			p="205–206, examples 312–314"
		/>. The grammatical construction is therefore not restricted to first-person assertions.
	</p>
</S>

<S t="A phrase or a compound" id="fusion">
	<p>
		<i lang="ain-Latn">Rusuy</i> can also combine with the preceding verb as one word. Nakagawa
		contrasts <i lang="ain-Latn">ahun=an rusuy</i> with
		<i lang="ain-Latn">arpa-rusuy=an</i>. In the first, the person suffix follows ‘enter’; in the
		second, it follows the whole ‘want to go’ combination
		<Ref k="nakagawa2024" p="294, examples 406–407" />.
	</p>
	<Ex
		m="TOKIYO un a=suci utar eun arpa-rusuy=an kusu"
		g="Tokyo LOC.ATTR 4.POSS=grandmother ASS ALLAT go.SG-want=4.S CONJ"
		tr="Because I wanted to go to my grandmother and her people in Tokyo, …"
		cite="nakagawa2024:294"
		dial="SAR"
		place="Example 407"
		note="The suffix marks the whole compound. The fourth-person forms have narrative first-person reference here."
	/>
	<p>
		<i lang="ain-Latn">Iperusuy</i> ‘be hungry’ and
		<i lang="ain-Latn">konrusuy</i> ‘want something’ are commonly single words in Nakagawa's
		account, related respectively to <i lang="ain-Latn">ipe</i> ‘eat’ and <i lang="ain-Latn">kor</i>
		‘have’ <Ref k="nakagawa2024" p="311–312" />. A person suffix after such a compound supplies no
		evidence for a freely independent verb <i lang="ain-Latn">rusuy</i>. Nakagawa explicitly rejects
		a separate
		<i lang="ain-Latn">apkas a=rusuy</i> as the counterpart of ‘want to walk’
		<Ref k="nakagawa2024" p="491, examples 1124–1124′" />.
	</p>
</S>

<S t="Whose wish?" id="desirer">
	<p>
		Tamura describes ordinary Saru <i lang="ain-Latn">V rusuy</i> as expressing the action
		participant's desire. For wishing that someone else act, she gives a clause with
		<i lang="ain-Latn">hi</i>
		followed by person-marked
		<i lang="ain-Latn">ki rusuy</i>. One example concerns wanting a young woman to become acquainted
		with the speaker's younger sister
		<Ref k="tamura1960" p="§12, 74 (continuous pagination 350)" />.
	</p>
	<p>
		Refsing reports a different Shizunai construction:
		<i lang="ain-Latn">toonpe en=koitak rusuy</i>, translated as a wish that the addressee tell the
		speaker something <Ref k="refsing1986" p="206, example 315" />. This source difference prevents
		a universal rule identifying the desirer from the position of a person marker alone.
	</p>
	<p>
		<i lang="ain-Latn">Rusuy</i> can also describe an impending feeling without an active wish for
		it. Tamura's <i lang="ain-Latn">tane k=etoranne rusuy humi as</i>
		expresses feeling about to become fed up
		<Ref k="tamura1960" p="§12, 74 (continuous pagination 350)" />.
	</p>
</S>

<S t="Competing incorporation analyses" id="analysis">
	<p>
		Nakagawa treats the one-word <i lang="ain-Latn">V-rusuy</i> pattern as a strong candidate for
		auxiliary incorporation, since <i lang="ain-Latn">rusuy</i> lacks the independent verbal use
		available to some other auxiliaries
		<Ref k="nakagawa2024" p="491" />. Satō instead analyzes <i lang="ain-Latn">ipe-rusuy-an</i>
		through incorporation of a nominalized intransitive into <i lang="ain-Latn">rusuy</i>. He
		proposes pseudo-incorporation for the morphologically separate
		<i lang="ain-Latn">a=e rusuy</i> construction, using it to explain how the auxiliary
		construction relates to head marking
		<Ref k="sato2025a" p="374–375, examples 26–27" />.
	</p>
	<p>
		These proposals assign the structural relations differently. Satō's argument about the
		illustrated transitive construction should also be read alongside Nakagawa's lexical <i
			lang="ain-Latn">konrusuy</i
		>. For the broader distinctions among incorporation, quasi-incorporation, and morphological
		wordhood, see
		<Xr ch="noun-incorporation-oblique-polysynthesis-debate" />.
	</p>
</S>
