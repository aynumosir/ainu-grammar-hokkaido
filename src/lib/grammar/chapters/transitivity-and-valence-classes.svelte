<S t="Argument frames and their expression" id="argument-frames">
	<p>
		A verb's argument frame specifies the participants it takes grammatically. An intransitive has a
		subject; a transitive has a subject and an object; a ditransitive has two objects. Ainu also has
		predicates without a subject, and some descriptions recognize rare derived four-place verbs
		<Ref k="nakagawa2024" p="124–135" />;
		<Ref k="sato2008" p="97" />.
	</p>
	<p>
		The number of words spoken in a clause need not equal its argument count. Arguments may be
		understood from context, and third person has no audible person marker. Conversely, a phrase
		describing a place can be an object selected by the verb. English translations with “in” or “to”
		do not determine the Ainu construction <Ref k="nakagawa2024" p="125–129" />.
	</p>
</S>

<S t="Zero-place predicates and experienced states" id="zero-place">
	<p>
		Ambient predicates describe weather or surrounding conditions without a grammatical subject.
		Nakagawa's Saru comparison distinguishes them from one-place predicates describing a
		participant's experience
		<Ref k="nakagawa2024" p="129–130, table 12" />.
	</p>
	<table>
		<thead
			><tr><th>Condition</th><th>Ambient, zero-place</th><th>Experienced, one-place</th></tr></thead
		>
		<tbody>
			<tr><td>Cold</td><td lang="ain-Latn">mean</td><td lang="ain-Latn">merayke</td></tr>
			<tr><td>Cool</td><td lang="ain-Latn">sirmeman</td><td lang="ain-Latn">meman</td></tr>
			<tr><td>Warm</td><td lang="ain-Latn">sirpopke</td><td lang="ain-Latn">popke</td></tr>
			<tr><td>Hot</td><td lang="ain-Latn">sirsesek</td><td lang="ain-Latn">sesek</td></tr>
		</tbody>
	</table>
	<p>
		The forms do not follow a single recipe. Some contain
		<i lang="ain-Latn">an</i>, while others combine a different base with an ambient element.
		Nakagawa also notes a word-boundary question in
		<i lang="ain-Latn">apto as</i> “rain falls,” because
		<i lang="ain-Latn">apto</i> can be an independent noun
		<Ref k="nakagawa2024" p="129" />.
	</p>
	<p>
		In his cited narrative, <i lang="ain-Latn">mean</i> modifies
		<i lang="ain-Latn">cuk</i> “autumn,” while the narrator uses person-marked
		<i lang="ain-Latn">merayke</i>
		for feeling cold. The passage contrasts the season's weather with personal sensation
		<Ref k="nakagawa2024" p="130, example 15, from Kayano 1974a: 65" />.
	</p>
</S>

<S t="Subjects and objects have varied meanings" id="semantic-roles">
	<p>
		A one-place subject can act, undergo a change, or experience a state. In incorporating forms,
		the source of an event may be inside the stem while the affected participant receives subject
		marking
		<Ref k="nakagawa2024" p="129–130" />. The possessive and natural-force constructions are
		discussed in <Xr ch="external-possession-possessor-raising" />.
	</p>
	<p>
		Semantic roles can also vary without a change in argument count. Bugaeva and Kobayashi discuss <i
			lang="ain-Latn">as</i
		>
		with an intentional stander or a standing tree. They caution that the agency of nonhuman participants
		depends partly on narrative context
		<Ref k="bugaevakobayashi2022" p="§5.1.1" />. Such variation differs from a verb alternating
		between one and two arguments.
	</p>
</S>

<S t="A selected location can be an object" id="locative-objects">
	<p>
		Nakagawa contrasts an intransitive verb of entering with a transitive verb that selects a
		location. The place particle occurs in the first construction, while the second takes the place
		expression directly
		<Ref k="nakagawa2024" p="128, examples 12–13" />.
	</p>
	<Ex
		m="cise or ta ahun"
		g="house place LOC enter.SG"
		tr="Someone entered the house."
		cite="nakagawa2024:128, example 12"
		note="Published grammatical illustration; the source does not label an individual dialect here."
	/>
	<Ex
		m="cise or osma"
		g="house place enter"
		tr="Someone rushed into the house."
		cite="nakagawa2024:128, example 13"
		note="Osma selects the bare location cise or. Nakagawa rejects adding ta in this construction."
	/>
	<p>
		Locative selection also occurs in three-place frames. The verb
		<i lang="ain-Latn">o</i> “put” takes someone putting, a thing put, and a location. Nakagawa
		separates it from two-place locative
		<i lang="ain-Latn">o</i>, the plural counterpart of
		<i lang="ain-Latn">oma</i>, and from a two-place use meaning “ride” <Ref
			k="nakagawa2024"
			p="134–135, table 14"
		/>. The same short form thus occurs in distinct frames.
	</p>
</S>

<S t="The copula's special person pattern" id="copula">
	<p>
		Nakagawa includes <i lang="ain-Latn">ne</i> among two-place predicates because it relates a
		subject to a nominal complement. Its person pattern is special: the subject uses the A series,
		but the nominal complement is not indexed with an object-series marker
		<Ref k="nakagawa2024" p="132" />.
	</p>
	<Ex
		m="okkayo ku=ne"
		g="man 1SG.A=COP"
		tr="I am a man."
		cite="nakagawa2024:132, example 23"
		note="The source's illustration of subject marking on the copula."
	/>
	<p>
		This is one reason to keep semantic participants, grammatical arguments, and person-index
		positions distinct. Satō explicitly separates those notions in his discussion of valency
		<Ref k="sato2023b" p="39–40, 45–50" />.
	</p>
</S>

<S t="Higher valency and derivation" id="higher-valency">
	<p>
		Three-place verbs include <i lang="ain-Latn">kore</i> “give” and
		<i lang="ain-Latn">epakasnu</i> “teach.” Applicative and causative morphology can also produce
		three-place frames from two-place bases
		<Ref k="nakagawa2024" p="133–134" />. The added participant's role depends on the construction.
	</p>
	<p>
		The causative <i lang="ain-Latn">-yar/-ar</i> behaves differently: it replaces the base subject
		with a causer while suppressing the causee as a separately expressible or indexed argument. Its
		causative meaning therefore coexists with unchanged valency
		<Ref k="bugaevakobayashi2022" p="§4.3.1" />.
	</p>
	<p>
		Nakagawa reports a rare four-place interpretation of
		<i lang="ain-Latn">omarere</i>, a causative of three-place
		<i lang="ain-Latn">omare</i>, from a Saru narrative
		<Ref k="nakagawa2024" p="135, example 34, from Chiba University 2015: 420" />. Satō questions
		making such marginal forms a general grammatical class and stresses the distinction between
		their semantic participants and the language's person-index positions
		<Ref k="sato2025b" p="22–24" /> ‹contested›.
	</p>
</S>

<S t="Transitivity pairs and rare unchanged forms" id="transitivity-pairs">
	<p>
		A change between intransitive and transitive use generally involves a different form. Satō
		contrasts visibly related pairs with lexically distinct pairs such as <i lang="ain-Latn">ipe</i>
		“eat a meal” and
		<i lang="ain-Latn">e</i> “eat something.” He reports identical plural
		<i lang="ain-Latn">roski</i>
		“stand” and “stand something up” as a rare exception in his Chitose account
		<Ref k="sato2008" p="97" />. Correspondences and stem formation are developed in <Xr
			ch="denominal-deverbal-verb-derivation"
		/>.
	</p>
</S>

<S t="Lexical frames and theoretical arity" id="arity-analysis">
	<p>
		Nakagawa's arity analysis assigns numerical values to stems, affixes, and phrases. A person
		marker reduces the number of independently available nominal arguments in that analysis. This
		leads him to reject zero third-person affixes within his system
		<Ref k="nakagawa2024" p="136–139" />. Satō instead distinguishes argument slots, semantic
		valency, and morphological valency, and retains zero third-person indices
		<Ref k="sato2023b" p="39, 45–50" />;
		<Ref k="sato2025b" p="21–25" /> ‹contested›.
	</p>
	<p>
		The disagreement affects the analysis of overt and unexpressed arguments. It does not remove the
		observed contrasts between person paradigms or between verbs selecting different complements.
		See
		<Xr ch="person-marking-architecture" /> and
		<Xr ch="verb-word-template" />.
	</p>
</S>
