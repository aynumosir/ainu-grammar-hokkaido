<S t="Two possessive constructions" id="possession">
	<p>
		The reply calls the bowl <i lang="ain-Latn">ku=koro pe</i>, ‘the thing I have’. The next
		question and answer use affiliative
		<i lang="ain-Latn">'itanki-hi</i> with person marking for ‘your bowl’ and ‘my bowl’. These
		constructions express possession through a verb and through the noun's morphology, respectively.
		The last answer combines the possessed noun with negative existential
		<i lang="ain-Latn">'isam</i>
		<Ref k="murasaki2025" p="16–17" />.
	</p>
	<p>
		Hokkaido also has possessive predicates with
		<i lang="ain-Latn">kor</i> and affiliative nouns, but the forms and their usage must be compared
		within each description. Tangiku discusses Sakhalin suffix classes and contextual differences
		between possessive constructions
		<Ref k="tangiku2022" p="§§4.1–4.2" />. See <Xr ch="alienable-inalienable-split" /> and
		<Xr ch="sakhalin-and-kuril-ainu-contrast" />.
	</p>
</S>

<S t="Questions and final particles" id="endings">
	<p>
		Murasaki lists <i lang="ain-Latn">hii/hee</i> among final particles used in affirmative,
		negative, and interrogative sentences. Her explanation associates questions with falling
		intonation and other uses with rising intonation. A consonant-final word gains
		<i>i</i> before the particle, as in
		<i lang="ain-Latn">'an-i hii</i>
		<Ref k="murasaki2025" p="19, §④" />.
	</p>
	<p>
		The same <i lang="ain-Latn">hee</i> therefore appears in the question about ownership and in the
		assertion ‘This bowl is mine’. The gloss FIN records its sentence-final role without assigning
		every occurrence an interrogative meaning. Murasaki lists
		<i lang="ain-Latn">nakorope</i> as ‘whose thing’ and
		<i lang="ain-Latn">nahta</i> as ‘where’
		<Ref k="murasaki2025" p="19, §⑤" />.
	</p>
</S>
