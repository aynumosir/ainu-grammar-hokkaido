<S t="Vowels at morphological boundaries" id="overview">
	<p>
		Combining Ainu forms often brings two vowels together. The resulting pronunciation may include a
		glide, a glottal closure, or the loss of a vowel. Some sequences remain as two adjacent vowels.
		The outcome depends on the forms being combined and on the variety being described <Ref
			k="shiraishi2022"
			p="§4.3"
		/>;
		<Ref k="okuda2025" p="40–44" />.
	</p>
	<p>
		Two glide processes are especially important. In <em>insertion</em>, a glide appears between
		vowels that remain in the form. In <em>glide formation</em>, also called vowel weakening, an
		existing /i/ or /u/ becomes /y/ or /w/. These processes change the syllable structure
		differently <Ref k="bugaeva2012" p="468–469" />;
		<Ref k="nakagawa2024" p="34, 40" />.
	</p>
</S>

<S t="Phonetic transitions and phonological glides" id="glide-watari">
	<p>
		Nakagawa treats the [j] heard in [ijomante] as a transition between vowels in the phonological
		form /iomante/. His spelling consequently omits it. Similarly, the first [w] of [uwenewsar] is
		transitional in his account, while the /w/ inside
		<i lang="ain-Latn">newsar</i> belongs to the word's phonological form
		<Ref k="nakagawa2024" p="34–35" />.
	</p>
	<p>
		Satō's Chitose analysis assigns some inserted glides phonological status, because their presence
		depends on morphological structure in addition to the adjacent vowels
		<Ref k="sato2006glides" p="47–49" />. Okuda compares the two approaches explicitly
		<Ref k="okuda2025" p="42–43" /> ‹contested›. A glide can be introduced by a phonological rule without
		being part of the deepest underlying form; “inserted” and “phonemic” therefore refer to different
		questions in this comparison.
	</p>
</S>

<S t="Insertion after particular prefixes" id="glide-insertion">
	<p>
		Satō's Chitose descriptions include /y/ after prefixal <i lang="ain-Latn">i-</i> and /w/ after
		reciprocal <i lang="ain-Latn">u-</i> before a vowel. His examples are
		<i lang="ain-Latn">iyomare</i> “pour liquor” and
		<i lang="ain-Latn">uwomare</i> “gather”
		<Ref k="sato2008" p="13" />. In both, the prefix vowel remains before the inserted glide.
	</p>
	<p>
		The Chitose trigger set also includes <i lang="ain-Latn">si-</i>. Satō illustrates
		<i lang="ain-Latn">si-y-osmak</i> “behind oneself” in his later discussion
		<Ref k="sato2008" p="248–249" />. His published comparison distinguishes Chitose insertion after
		this prefix from its absence after the corresponding prefix in Horobetsu <Ref
			k="sato2006glides"
			p="49"
		/>.
	</p>
	<S t="Morphological restrictions" id="boundary-block">
		<p>
			Other elements with the same final vowel need not behave like these prefixes. Satō gives
			Chitose <i lang="ain-Latn">turi-ecipo</i>, containing the incorporated noun “pole,” without an
			inserted /y/. His <i lang="ain-Latn">ru-emina</i> “smile” likewise lacks /w/ after the nominal
			prefix
			<Ref k="sato2006glides" p="48" />.
		</p>
		<Ex
			m="turi-ecipo"
			ain="turiecipo"
			g="pole-propel.boat.with"
			tr="Propel a boat with a pole."
			cite="sato2006glides:48"
			dial="CHI"
			note="Satō reports the absence of [j] between the noun's final /i/ and the verb's initial /e/."
		/>
		<p>
			Bugaeva also gives <i lang="ain-Latn">eci=opitta</i> “all of you” without /y/ following the
			second-person plural marker. She reports Satō's distinction between prefixes that trigger
			insertion and other prefixes or incorporated nouns that do not
			<Ref k="bugaeva2012" p="469, example 11" />. The shared vowel sequence alone is insufficient
			to predict the Chitose pattern.
		</p>
	</S>
</S>

<S t="When vowel weakening is blocked" id="cvvc-block">
	<p>
		In Saru and Chitose, a stem-initial /i/ can become /y/ after certain prefixes. Nakagawa gives <i
			lang="ain-Latn">ku=ipe</i
		>
		pronounced
		<i lang="ain-Latn">kúype</i> “I eat,” and <i lang="ain-Latn">e=itak</i> pronounced
		<i lang="ain-Latn">éytak</i> “you speak” <Ref k="nakagawa2024" p="52" />. The former vowel
		becomes the coda of the preceding syllable.
	</p>
	<p>
		A closed initial stem syllable has a different outcome. In
		<i lang="ain-Latn">inkar</i> “look,” converting /i/ to /y/ would create an impermissible consonant
		sequence. Nakagawa therefore gives a retained vowel:
	</p>
	<Ex
		m="ku=inkar"
		ain="kuínkar"
		g="1SG.S=look"
		tr="I look."
		cite="nakagawa2024:53"
		place="Saru and Chitose"
		note="The source retains initial /i/. Weakening would produce /ynk/ in the predicted form /kuynkar/."
	/>
	<p>
		Nakagawa gives the same blocking pattern with <i lang="ain-Latn">ikka</i> “steal”
		<Ref k="nakagawa2024" p="53" />. This condition concerns a process that removes a vowel nucleus
		by turning it into a consonant. Insertion preserves that vowel and has its own morphological
		conditions.
	</p>
</S>

<S t="Vowel weakening and accent" id="vowel-weakening">
	<p>
		Nakagawa also gives <i lang="ain-Latn">ko-itak</i> becoming
		<i lang="ain-Latn">koytak</i> “speak to,” and
		<i lang="ain-Latn">e-ukoytak</i> becoming <i lang="ain-Latn">ewkoytak</i>
		“discuss something.” He identifies these as common patterns in Saru and Chitose, leaving their wider
		dialect distribution open <Ref k="nakagawa2024" p="40" />.
	</p>
	<p>
		Satō relates weakening to the accentual effect of the preceding prefix. Alongside
		<i lang="ain-Latn">iyomare</i> and <i lang="ain-Latn">uwomare</i>, he gives
		<i lang="ain-Latn">ku-yomare</i> “I pour liquor” and
		<i lang="ain-Latn">ku-womare</i> “I gather”
		<Ref k="sato2008" p="13–14" />. His introductory account also preserves the vowel in
		<i lang="ain-Latn">o'ika</i>
		“go over,” whose stem-initial /i/ already bears accent, and notes that /u/ weakening is less regular
		than /i/ weakening
		<Ref k="sato2008" p="13–14" />.
	</p>
	<p>
		The contraction of <i lang="ain-Latn">ku=</i> to <i lang="ain-Latn">k=</i> and
		<i lang="ain-Latn">ci=</i> to <i lang="ain-Latn">c=</i> before certain vowels is a further
		process: the prefix loses its vowel. Nakagawa distinguishes this from stem-vowel weakening and
		identifies its dialect limits
		<Ref k="nakagawa2024" p="52–53" />. See
		<Xr ch="personal-affix-sandhi-connected-speech-reduction" />.
	</p>
</S>

<S t="Glottal realization between vowels" id="glottal-insertion">
	<p>
		A vowel sequence can also involve glottal closure or tension. Shiraishi's survey reports clearer
		glottal realization in some accented or closed following syllables, alongside individual
		variation <Ref k="shiraishi2022" p="§4.3" />. Audible closure is therefore not a necessary
		feature of every token lacking a glide.
	</p>
	<p>
		Okuda discusses alternative representations in terms of a glottal consonant or a syllable
		boundary <Ref k="okuda2025" p="43–44" /> ‹contested›. The dispute concerns the analysis of the observed
		contrasts, treated in <Xr ch="glottal-stop" />.
	</p>
</S>

<S t="Contraction and vowel deletion" id="vowel-deletion">
	<p>
		Published descriptions also record shorter forms resulting from vowel contact. Shibatani gives <i
			lang="ain-Latn">kera</i
		>
		plus <i lang="ain-Latn">an</i>
		as <i lang="ain-Latn">keran</i> “be tasty,” and
		<i lang="ain-Latn">ine-an-kur</i> as <i lang="ain-Latn">inankur</i>
		“which person” <Ref k="shibatani1990" p="§2.4, 13" />. Kindaichi and Chiri present corresponding
		contraction patterns in their older account
		<Ref k="kindaichi1936" p="§V.10, 6–7" />.
	</p>
	<p>
		The first comparison brings identical vowels together; the second loses the first vowel of an
		unlike pair. These are documented outcomes in particular forms. The prefix restrictions
		described above show why a single deletion rule cannot replace the separate morphological
		patterns.
	</p>
</S>

<S t="Comparing dialects and analyses" id="phonemic-status-debate">
	<p>
		Okuda's Shizunai observations add a lexical dimension. He reports a distinction in Orita
		Suteno's speech between [suʔat] “pot bail” and [suwat] “pothook,” crediting the discovery to <span
			lang="ja">志賀雪湖</span
		>. Some realizations become less distinct through weakening <Ref k="okuda2025" p="41" />.
	</p>
	<p>
		The same speaker's forms also distinguish lexicalized expressions from transparent combinations.
		Okuda reports a glide in the narrative term
		<i lang="ain-Latn">uwepeker</i>, but its absence in the transparent expression for “talk
		together,” and no inserted [j] in <i lang="ain-Latn">iomante</i>
		<Ref k="okuda2025" p="41–43" />. He relates these differences to lexical integration.
	</p>
