<S t="Person and the force of the advice" id="person">
	<p>
		The intransitive <i lang="ain-Latn">ikoysampa</i> takes fourth-person
		<i lang="ain-Latn">=an</i>; transitive
		<i lang="ain-Latn">nu</i> and <i lang="ain-Latn">nukar</i>
		take <i lang="ain-Latn">a=</i>. Nakagawa identifies this ending as advice with generic
		reference. English ‘you’ conveys that general application; it does not represent second-person
		morphology
		<Ref k="nakagawa2025" p="150" />.
	</p>
	<p>
		The preceding tale is predominantly in the third person. Its concluding fourth-person forms
		therefore do not make the whole performance a protagonist's first-person account. The broader
		distinctions are explained in
