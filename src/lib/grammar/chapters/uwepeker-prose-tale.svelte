<S t="The linked predicates" id="structure">
	<p>
		The repeated <i lang="ain-Latn">ka ki</i> joins listening and watching in parallel.
		<i lang="ain-Latn">Wa</i>
		connects this pair with the following action, and
		<i lang="ain-Latn">orowa</i> orders imitation after it. The literal concessive
		<i lang="ain-Latn">yakka</i>
		introduces the situation to which the advice applies. The final
		<i lang="ain-Latn">pe ne</i> gives the statement its normative reading in context. Compare the
		constructions in
