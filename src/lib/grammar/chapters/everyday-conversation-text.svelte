<S t="Person changes with the participant's role" id="person">
	<p>
		The wellbeing question and answer exchange
		<i lang="ain-Latn">e=an</i> ‘you are’ and
		<i lang="ain-Latn">ku=an</i> ‘I am’. In the request,
		<i lang="ain-Latn">ku=ku</i> contains two different elements with the same spelling:
		first-person marking and the verb ‘drink’.
		<i lang="ain-Latn">En=</i> marks the speaker as the recipient in <i lang="ain-Latn">en=kore</i> ‘give
		to me’.
	</p>
	<p>
		The bare <i lang="ain-Latn">ku</i> in the reply is an invitation to drink. Its interpretation
		follows the conversational turn, rather than a rule that every unprefixed predicate describes a
		third person. Compare the argument and person distinctions in
		<Xr ch="verbal-subclasses-taxonomy" />.
	</p>
</S>

<S t="Requests and sentence endings" id="request">
	<p>
		<i lang="ain-Latn">Rusuy</i> expresses the wish to drink, and
		<i lang="ain-Latn">kusu</i> connects it to the request as a reason. The response-final
		<i lang="ain-Latn">wa</i>
		and invitation-final <i lang="ain-Latn">ya</i> have functions tied to their positions in the
