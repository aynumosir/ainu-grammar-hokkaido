<S t="Contact on Sakhalin" id="contact">
	<p>
		Sakhalin Ainu, Nivkh, and Uilta participated in networks of trade, travel, and social contact.
		Uilta is Tungusic; Ainu and Nivkh have no established genetic relationship to that family.
		Shiraishi and Tangiku examine historical accounts and cultural vocabulary to investigate the
		extent and direction of borrowing
		<Ref k="shiraishitangiku2022" p="§§1–3" />.
	</p>
	<p>
		The conditions changed over time, including Qing-linked trade, Japanese supply routes, and later
		Russian influence. Accounts of multilingual speakers belong to those historical settings. Shared
		words need not all have entered through one language or during one period <Ref
			k="shiraishitangiku2022"
			p="§§2, 3.1"
		/>.
	</p>
</S>

<S t="Different routes for related goods" id="routes">
	<p>
		The words for scissors illustrate separate routes. Shiraishi and Tangiku connect Nivkh <i
			>haza/hazaŋ</i
		>
		and Uilta <i>xaǰa</i>
		with Manchu <i>hasaha</i>, while identifying Ainu
		<i lang="ain-Latn">hasami</i>, in both Sakhalin and Hokkaido, as Japanese. They also give
		Sakhalin
		<i lang="ain-Latn">konkaani</i> ‘gold’ as a Japanese loan
		<Ref k="shiraishitangiku2022" p="§3.1" />.
	</p>
	<p>
		Northern contact therefore coexists with Japanese borrowing in Sakhalin. Conversely, a shared
		cultural item need not have a shared name: the account compares Hokkaido Japanese-derived
		<i lang="ain-Latn">sato</i> ‘sugar’ with Sakhalin
		<i lang="ain-Latn">otoopenpe</i>, meaning more broadly ‘something sweet’ <Ref
			k="shiraishitangiku2022"
			p="§3.1"
		/>.
	</p>
</S>

