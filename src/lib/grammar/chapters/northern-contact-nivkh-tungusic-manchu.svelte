<S t="Vocabulary counts and grammatical convergence" id="grammar">
	<p>
		Shiraishi and Tangiku's selected cultural-vocabulary list has 31 items shared by all three
		languages, 61 by Nivkh and Uilta, 29 by Nivkh and Ainu, and 13 by Ainu and Uilta. These counts
		describe that list; they neither measure the whole lexicon nor demonstrate genetic relationship <Ref
			k="shiraishitangiku2022"
			p="§3.10, Appendix 1"
		/>.
	</p>
	<p>
		Grammatical parallels require their own comparison. Baek examines optional third-person number
		opposition and noun and verb plural functions in Sakhalin Ainu, Nivkh, and Uilta, comparing
		Uilta with Nanai and Ulcha. This supports discussion of possible convergence without
		establishing a shared affix-order rule
		<Ref k="baek2021" p="71–77, §§2–3, Table 4" />. Shiraishi and Tangiku leave the scale of a
		possible Sakhalin linguistic area as a research question
		<Ref k="shiraishitangiku2022" p="§1" />.
	</p>
