<S t="Property meanings expressed by verbs" id="overview">
	<p>
		Words such as <i lang="ain-Latn">pirka</i> “good,”
		<i lang="ain-Latn">poro</i> “large,” and <i lang="ain-Latn">hure</i> “red” function as
		predicates and take verbal person marking. Modern descriptions generally classify them as
		intransitive verbs
		<Ref k="nakagawa2024" p="118–120" />;
		<Ref k="sato2008" p="2–3" />; <Ref k="bugaeva2012" p="470" />. Their English translations belong
		to a different grammatical system, in which many of the corresponding words are adjectives.
	</p>
	<p>
		The Ainu classification rests on morphology and syntax. Property words can describe both states
		and changes into those states; this semantic flexibility also matters for their interpretation <Ref
			k="nakagawa2022pos"
			p="§§2.1–2.3"
		/>;
		<Ref k="shibatani1990" p="19" />.
	</p>
</S>

<S t="The evidence for the verbal analysis" id="standard-analysis">
	<S t="Predication and person marking" id="person-marking-frame">
		<p>
			Property predicates occur without a copula. Shibatani's examples include a mountain's height
			and the strength of the wind:
		</p>
		<Ex
			m="toan nupuri ri"
			g="DEM mountain be.high"
			tr="That mountain is high."
			cite="shibatani1990:19, example 13b"
			place="Hokkaido, dialect not specified"
		/>
		<Ex
			m="rera ruy"
			g="wind be.strong"
			tr="The wind is strong."
			cite="shibatani1990:19, example 13c"
			place="Hokkaido, dialect not specified"
		/>
		<p>
			Third person is unmarked in these examples. Other persons take the same S series as other
			intransitives. Nakagawa compares Saru <i lang="ain-Latn">ku=pewre</i>
			“I was young” and <i lang="ain-Latn">ku=mina</i> “I laugh” in their sentence contexts <Ref
				k="nakagawa2024"
				p="119, examples 1–2"
			/>. The first-person singular marker alone is shared with A marking, but the comparison
			extends to the intransitive paradigm <Ref k="nakagawa2022pos" p="§2.2, Table 2" />.
		</p>
	</S>
	<S t="Derivational morphology" id="morphological-identity">
		<p>
			Property verbs participate in verbal derivation. Refsing gives
			<i lang="ain-Latn">pirka → pirkare</i> “good → cure, heal” and
			<i lang="ain-Latn">wen → wente</i> “bad → damage”
			<Ref k="refsing1986" p="142" />. Nakagawa illustrates the combination of
			<i lang="ain-Latn">pirka</i> with applicative, reflexive, and causative morphology <Ref
				k="nakagawa2022pos"
				p="§2.2, example 6"
			/>.
		</p>
		<p>
			Compatibility depends on meaning and the particular formation. Productive causatives and
			lexical transitivizing pairs have different distributions; see
			<Xr ch="valency-voice-overview" />. These examples establish verbal derivation without
			requiring every affix to combine freely with every property predicate.
		</p>
	</S>
	<S t="States and changes of state" id="stative-inchoative">
		<p>
			<i lang="ain-Latn">Poro</i> can mean “large” or “become large,” and
			<i lang="ain-Latn">hure</i> “red” or “become red.” Context determines the appropriate reading <Ref
				k="nakagawa2024"
				p="119"
			/>. A separate copula is unnecessary for this change-of-state meaning. Nakagawa rejects
			<i lang="ain-Latn">hure ne</i> with the intended simple meaning “become red”
			<Ref k="nakagawa2024" p="119" />.
		</p>
		<p>An imperative can select a change-of-state reading:</p>
		<Ex
			m="tunasno pirka"
			g="quickly be.good"
			tr="Get well quickly!"
			cite="shibatani1990:19"
			place="Hokkaido, dialect not specified"
		/>
		<p>
			The range of readings need not be equally natural for every word. Nakagawa uses
			<i lang="ain-Latn">kiyanne-re</i> “treat someone as an elder” to illustrate the semantic
			potential of <i lang="ain-Latn">kiyanne</i> “be older”
			<Ref k="nakagawa2024" p="120" />. The causative describes a way of treating the person, rather
			than a literal alteration of chronological age.
		</p>
	</S>
</S>

<S t="Attributive uses and semantic subclasses" id="diagnostics">
	<p>
		Verbs precede nouns that they modify. Refsing compares
		<i lang="ain-Latn">mokor cep</i> “a sleeping fish” with
		<i lang="ain-Latn">pirka cep</i> “a fine fish,” and the corresponding predicates
		<i lang="ain-Latn">cep mokor</i> and <i lang="ain-Latn">cep pirka</i>
		<Ref k="refsing1986" p="141–142" />. Both verb types participate in the same attributive and
		predicative patterns.
	</p>
	<p>
		Shared patterns still allow semantic subclasses within verbs. Refsing leaves possible
		differences in the availability of affixes and auxiliaries open for further study
		<Ref k="refsing1986" p="142" />. Nakagawa likewise discusses residual differences between
		property and action predicates, especially in adverbial constructions
		<Ref k="nakagawa2022pos" p="§2.4" />.
	</p>
</S>

<S t="Prenominals and the historical adjective category" id="candidate-counter-class">
	<S t="The separate prenominal class" id="adnoun-class">
		<p>
			Demonstrative and numeral prenominals have a more restricted distribution than property verbs.
			A form such as <i lang="ain-Latn">tan</i> modifies a noun in <i lang="ain-Latn">tan cise</i>
			“this house,” and a formal noun supplies the head in <i lang="ain-Latn">tan pe</i> “this”
			<Ref k="bugaeva2012" p="471" />. The existence of this prenominal class does not determine the
			classification of predicates such as
			<i lang="ain-Latn">pirka</i> and <i lang="ain-Latn">poro</i>.
		</p>
	</S>
	<S t="Pon, poro, and differences among property meanings" id="poro-pon">
		<p>
			<i lang="ain-Latn">Pon</i> “small” and <i lang="ain-Latn">poro</i>
			“large” occur in noun-modifying expressions, but also take S marking as predicates. Nakagawa's Saru
			examples include <i lang="ain-Latn">ku-pon</i> in a clause meaning “when I was small” and
			<i lang="ain-Latn">ku-poro</i>
			in one meaning “since I became older”
			<Ref k="nakagawa2022pos" p="§§2.2–2.3, examples 3, 8" />.
		</p>
		<p>
			Property meanings also occur among zero-argument predicates. Weather
			<i lang="ain-Latn">mean</i> “be cold” contrasts with one-place
			<i lang="ain-Latn">merayke</i> “feel cold.” The latter takes an experiencer's person marker <Ref
				k="nakagawa2024"
				p="129–130, Table 12"
			/>. Their classification is described in <Xr ch="verbal-subclasses-taxonomy" />.
		</p>
	</S>
	<S t="The historical adjective analysis" id="historical-adjective">
		<p>
			Kindaichi and Chiri's 1936 grammar recognizes adjectives while stating that their person
			inflection coincides with that of its Class II verbs
			<Ref k="kindaichi1936" p="92, §129; 123–124, §§189–190" />. Its account also excludes an
			imperative use for adjectives, whereas Shibatani gives the imperative
			<i lang="ain-Latn">Tunasno pirka!</i> cited above
			<Ref k="shibatani1990" p="19" /> ‹contested›.
		</p>
		<p>
			Nakagawa relates the later verbal classification to Chiri's rejection of the verb–adjective
			distinction for these forms
			<Ref k="nakagawa2024" p="118" />. The historical label and the modern one therefore reflect
			different accounts of shared morphology and its grammatical consequences.
		</p>
	</S>
</S>

<S t="Adverbial uses and degree" id="comparison-degree">
	<p>
		Nakagawa compares <i lang="ain-Latn">ipe wa mokor</i> “ate and slept” with
		<i lang="ain-Latn">pirka no mokor</i> “slept well.” He discusses whether the second pattern
		supports an adjective category, then relates the distribution to the meaning of the whole
		expression <Ref k="nakagawa2022pos" p="§2.4" />.
	</p>
	<p>
		He separately gives derived <i lang="ain-Latn">ipe-no</i> “eat well” and
		<i lang="ain-Latn">mokon-no</i> “sleep soundly,” which retain verbal behavior
		<Ref k="nakagawa2022pos" p="§2.4, example 13" />. The derivational and conjunctive uses of
		<i lang="ain-Latn">no</i>
		are treated in
		<Xr ch="adverbializer-no" />. Degree and comparison constructions are described in <Xr
			ch="adverbs-degree-comparison"
		/>.
	</p>
</S>

<S t="The cross-linguistic comparison" id="typological">
	<p>
		Nakagawa compares Ainu with languages in which property words also serve directly as predicates.
		His Japanese comparison illustrates why this syntactic fact alone does not settle word class:
		Japanese adjectives and verbs have distinct inflectional patterns, while the Ainu forms under
		discussion share verbal morphology
		<Ref k="nakagawa2022pos" p="§§2.1–2.2" />. The Ainu analysis draws on the combination of
		predication, modification, and morphology.
	</p>
</S>
