<S t="Interaction forms and proposed hierarchies" id="hierarchy">
	<p>
		Saru/Chitose <i lang="ain-Latn">eci=</i> covers first-person A acting on second-person O across
		four number combinations. Other dialects have prefix combinations and combinations on both sides
		of the stem <Ref k="nakagawa2024" p="171–174" />;
		<Ref k="refsing1986" p="223–225" />. These patterns show that person interaction affects the
		forms. Establishing a hierarchy-based analysis additionally requires an account of the ranking
		and of how each contrasting construction marks its direction.
	</p>
	<p>
		Dal Corso proposes such an account for Sakhalin. His referentiality hierarchy places speech-act
		participants above specific third persons, and specific third persons above nonspecific third
		persons. He explicitly leaves the ranking of first against second person irrelevant to that part
		of the argument <Ref k="dalcorso2025align" p="199, table 2 and n. 4" />
		‹speculative›. It therefore cannot be reduced to a claim that Ainu universally ranks “I” above “you.”
	</p>
</S>

<S t="The Sakhalin comparison" id="sakhalin">
	<p>
		Sakaguchi's East Sakhalin description uses a mixed alignment table, including tripartite
		first-plural and fourth-person rows. He adds that fourth person could be described as
		nominative–accusative if prefixed and suffixed AN are identified as the same form
		<Ref k="sakaguchi2024" p="31, table 3-3 and n. 25" />. The classification thus depends partly on
		what counts as formal identity.
	</p>
	<p>
		Dal Corso instead argues for a historical account of mixed nominative–neutral alignment with a
		later inverse component, rejecting tripartite classification in his analysis. His proposed
		development relates indefinite-agent marking to lower-referentiality subjects and extends the
		account to certain speech-act-participant interactions
		<Ref k="dalcorso2025align" p="210–214; §7" /> ‹contested›. He discusses departures from prototypical
		inverse systems and leaves related voice or focus analyses open for further investigation <Ref
			k="dalcorso2025align"
			p="213–214"
		/>.
	</p>
	<p>
		This is a Sakhalin proposal. The author explicitly cautions that the account may not apply to
		Hokkaido <Ref k="dalcorso2025align" p="201 n. 5" />. It offers a comparison with the Hokkaido
		patterns without replacing their dialect-specific descriptions.
	</p>
</S>

<S t="Alignment, lexical classes, and voice" id="active">
	<p>
		Active or inactive meanings raise a different question from the person-conditioned table. An
		affected participant can still take ordinary S marking in a one-place verb
		<Ref k="nakagawa2024" p="129–130" />. Shibatani's discussion of inactive verbs concerns
		incorporation and applicative formation <Ref k="shibatani1990" p="62–67" />; see <Xr
			ch="alignment-split-intransitive"
		/>.
	</p>
	<p>
		Voice analyses also use evidence beyond the shape of a person marker. Shibatani argues for a
		syntactic passive despite the retained object-looking person forms, while Satō emphasizes the
		affected participant's object status in an indefinite-subject construction
		<Ref k="shibatani1990" p="58–60" />;
		<Ref k="sato2008" p="203–206" /> ‹contested›. Their diagnostics are considered in
		<Xr ch="middle-anticausative-passive" />. A translation with an English passive or an isolated
		affix does not settle that disagreement.
	</p>
