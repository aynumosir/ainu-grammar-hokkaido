<S t="What an alignment description compares" id="question">
	<p>
		Morphological alignment compares the forms used for an intransitive subject S, a transitive
		subject A, and an object O. In Ainu, the answer changes with the person row under examination.
		Bugaeva describes Southern Hokkaido as having mixed alignment
		<Ref k="bugaeva2012" p="472" />. The first- and second-person interaction forms introduce
		further combinations that a basic three-column table cannot predict.
	</p>
</S>

