<S t="Kuni before a predicate of speech or thought" id="kuni">
	<p>
		<i lang="ain-Latn">Kuni</i> can introduce content that is intended, expected, inferred, or
		desired. It often occurs before <i lang="ain-Latn">ramu</i> ‘think’ or
		<i lang="ain-Latn">ye</i> ‘say’ <Ref k="sato2008" p="119" /><Ref
			k="nakagawa2024"
			p="476–477"
		/>. These meanings include future-oriented statements, but the construction also supports
		inference about an existing situation.
	</p>
	<Ex
		m="kamuy ne kuni a=ramu awa"
		g="deity COP COMP 4.A=think CONJ"
		tr="Then I thought it must be a deity."
		cite="shibatani1990:84"
		place="Example 166"
		note="Shibatani calls this expectative. His first-person narrative label is normalized to the fourth-person form series. Ne belongs to kamuy ne, before kuni."
	/>
	<Ex
		m="ku=ype kaspa humi ne kuni ku=ramu pakno ku=ype"
		g="1SG.S=eat excessively EVID COP COMP 1SG.A=think as.much.as 1SG.S=eat"
		tr="I ate so much that I thought I must have overeaten."
		cite="sato2008:177"
		dial="CHI"
		place="Illustration of kuni"
		note="The spelling ype follows Satō. Kuni introduces an inference about the eating, so a future-only interpretation would miss the point of the example."
	/>
	<p>
		The label COMP identifies the linking function in these examples. Their modal readings come from
		the source's account of the construction; it would be misleading to assign one tense value to
		every occurrence of <i lang="ain-Latn">kuni</i>.
	</p>
</S>

<S t="Kunak and yak in indirect reports" id="alternatives">
	<p>
		Nakagawa describes <i lang="ain-Latn">kunak</i> with prospective or inferred content. One
		example concerns men who conclude that a woman is the sole survivor, unaware that she has hidden
		her younger brother <Ref k="nakagawa2024" p="477, example 1111" />. This inference concerns the
		current situation.
	</p>
	<p>
		His <i lang="ain-Latn">yak</i> examples report a dream already experienced or an inference about
		an event being observed <Ref k="nakagawa2024" p="477–478" />. Bugaeva, while reporting Tamura's
		association of <i lang="ain-Latn">kuni</i> with future events and <i lang="ain-Latn">yak</i>
		with past ones, also records
		<i lang="ain-Latn">yak</i> with present and future content
		<Ref k="bugaeva2008" p="67–68" />. The temporal tendencies therefore need source and
		constructional qualification.
	</p>
	<p>
		Nakagawa further distinguishes indirect-complement <i lang="ain-Latn">yak</i> from conditional
		<i lang="ain-Latn">yakne</i>: the latter cannot simply replace it as the indirect-speech marker
		in his description <Ref k="nakagawa2024" p="478" />. The forms' other clause-linking uses do not
		make their complement uses interchangeable.
	</p>
</S>

<S t="Reporting an instruction" id="instructions">
	<p>
		An instruction can be reported through a causative predicate followed by
		<i lang="ain-Latn">kusu ye</i>. Nakagawa contrasts this with a directly quoted imperative
		<Ref k="nakagawa2024" p="478–479" />.
	</p>
	<Ex
		m="so anu munnupa hine ora i=ahun-te kusu ye"
		g="mat place sweep CONJ then 4.O=enter.SG-CAUS COMP say"
		tr="She laid out a mat, swept, and told me to come in."
		cite="nakagawa2024:478"
		dial="SAR"
		place="Example 1116"
		note="The actor is the woman from the narrative context. I= indexes the narrator as the person invited to enter. Ahunte is the causative counterpart of ahun."
	/>
	<p>
		The published direct counterpart has <i lang="ain-Latn">ahun</i> ‘come in’ or polite
		<i lang="ain-Latn">ahup yan</i>. The indirect frame changes the predicate to a causative and
		assigns person reference from the reporting context. It is a distinct construction from a bare
		verb followed by <i lang="ain-Latn">kuni</i>.
	</p>
</S>

<S t="Purpose linkage with kunine" id="purpose">
	<p>
		<i lang="ain-Latn">Kunine</i> also links an action to its intended result or purpose. Refsing
		describes this in Shizunai, where her material contains it less often than purpose
		<i lang="ain-Latn">kusu</i>
		<Ref k="refsing1986" p="252–253" />.
	</p>
	<Ex
		m="huci e kunine ku=kar"
		g="grandmother eat PURP 1SG.A=make"
		tr="I will make it so that grandmother can eat it."
		cite="refsing1986:253"
		dial="SHI"
		place="Example 444"
		note="Refsing's person-marker spacing is normalized with =. The embedded eater and the person preparing the food are different participants."
	/>
	<p>
		Satō also gives Chitose <i lang="ain-Latn">na a=nuno kunine itak</i>, an instruction to speak so
		that people can hear better <Ref k="sato2008" p="54" />. Refsing tentatively connects
		<i lang="ain-Latn">kunine</i>
		with
		<i lang="ain-Latn">kuni</i> and the copula. Her historical suggestion concerns this linker; the examples
		establish purpose linkage between predicates.
	</p>
</S>

<S t="Prospective nominal expressions" id="nominals">
	<p>
		<i lang="ain-Latn">Kuni</i> can occur before <i lang="ain-Latn">p/pe</i> in a nominal
		expression. Nakagawa's <i lang="ain-Latn">e=e kuni p</i> identifies food intended for the
		addressee to eat, within a statement that it has been stored in the house
		<Ref k="nakagawa2024" p="443, example 996" />. Such a phrase can refer to a concrete prospective
		object rather than an abstract duty.
	</p>
	<p>
		Bugaeva offers a morphological analysis of <i lang="ain-Latn">kun-i-p</i> under modal nominal
		expressions, marking the proposed obligation meaning of its first component as uncertain <Ref
			k="bugaeva2016"
			p="102"
		/>. That analysis and the attested meanings of complete constructions should remain distinct.
		Prospective, inferential, and directive readings depend on the surrounding predicates and
		discourse.
	</p>
</S>
