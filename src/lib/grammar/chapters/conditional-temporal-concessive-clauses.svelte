<S t="Concession and contrary expectations" id="concession">
	<p>
		<i lang="ain-Latn">Yakka</i> covers both hypothetical ‘even if’ and factual ‘although’
		relations. With an already realized situation, it can overlap with adversative expressions.
		Nakagawa lists
		<i lang="ain-Latn">yakkay</i> for Tokachi and Shiranuka and
		<i lang="ain-Latn">yakkayki</i> in verse and in Kushiro prose
		<Ref k="nakagawa2024" p="352, examples 667–669" />.
	</p>
	<p>
		<i lang="ain-Latn">Korka</i> and regional
		<i lang="ain-Latn">korkay</i> connect a situation with something contrary to an expectation.
		<i lang="ain-Latn">Hikeka</i>
		and its regional variants have closely overlapping uses
		<Ref k="nakagawa2024" p="351–352, examples 662–666" />. For permission with
		<i lang="ain-Latn">yakka pirka</i>, see
		<Xr ch="deontic-necessity" />.
	</p>
</S>
