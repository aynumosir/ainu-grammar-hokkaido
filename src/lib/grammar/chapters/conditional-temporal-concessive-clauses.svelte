<S t="Conditions and the following clause" id="conditions">
	<p>
		Conditional connectors differ in the situations they introduce and in the kinds of statement,
		question, or directive that follow. Satō's comparison uses Chitose material from Shirasawa Nabe
		and explicitly presents an exploratory account. The distinctions involve habituality, factual
		sequence, evaluation, and sentence type, with no simple one-to-one match to Japanese conditional
		forms <Ref k="sato2009" p="50–55, §3 and notes 2–11" />.
	</p>
	<p>
		Regional descriptions add further uses. The following sections retain the dialect and
		construction relevant to each comparison.
	</p>
</S>

<S t="Yakun: taking a situation as a premise" id="yakun">
	<p>
		Tamura describes <i lang="ain-Latn">yakun</i> as setting up the circumstances in which an event
		happens or has happened. It can also begin a new utterance with the sense ‘in that case’
		<Ref k="tamura1997" p="51" />. Satō's Chitose examples have following clauses expressing
		conjecture, a command, intention, or a question <Ref k="sato2009" p="52, examples 27–30" />.
	</p>
	<Ex
		m="e=ype rusuy hawe ne yakun tan kaboca e"
		g="2SG.S=eat DES EVID COP COND this pumpkin eat"
		tr="If you say you are hungry, eat this pumpkin."
		cite="sato2009:52"
		dial="CHI"
		place="Example 28; Shirasawa Nabe"
		note="The source's ype spelling is retained. Hawe ne presents the addressee's expressed desire to eat."
	/>
	<p>
		Refsing's Shizunai rain example means ‘If/when the rain stops, we go home.’ The temporal reading
		does not assert that the rain has already stopped
		<Ref k="refsing1986" p="257, example 453" />. The event's time and realization are interpreted
		from its context.
	</p>
</S>

<S t="Yak and evaluation" id="yak">
	<p>
		Southern descriptions frequently connect <i lang="ain-Latn">yak</i>
		and <i lang="ain-Latn">yakne</i> with a desirable or undesirable result.
		<i lang="ain-Latn">Yak pirka</i> can give advice or a directive, and
		<i lang="ain-Latn">yak wen</i> warns against the preceding action
		<Ref k="tamura1997" p="51–52" /><Ref k="nakagawa2024" p="349" />. The following predicate need
		not literally be ‘good’ or ‘bad’: the examples also include fear, pain, and survival
		<Ref k="sato2009" p="51–52, examples 25–26 and note 6" /><Ref
			k="nakagawa2024"
			p="349, examples 649–651"
		/>.
	</p>
	<p>
		Refsing's Shizunai account emphasizes a necessary consequence, often a habitual relation, with
		warnings among its uses
		<Ref k="refsing1986" p="257–258, example 454" />. These emphases differ from the southern
		descriptions and should not be collapsed into one universal semantic rule.
	</p>
	<p>
		Tamura describes <i lang="ain-Latn">yak easir</i> as identifying a necessary condition. She also
		gives <i lang="ain-Latn">yak pirka p</i>
		for wishes, allowing both realizable hopes and wishes contrary to past fact
		<Ref k="tamura1997" p="52" />. Satō separately notes that his examples involving past or
		counterfactual premises are too few for a full account
		<Ref k="sato2009" p="54–55, notes 8 and 11" />.
	</p>
</S>

<S t="Ciki and cik: directives, questions, and factual uses" id="ciki">
	<p>
		Satō finds <i lang="ain-Latn">ciki</i> especially with questions and commands in his Chitose
		material. An example tells the addressees to put clothes away if the clothes belong to them
		<Ref k="sato2009" p="51, examples 19–20" />. Nakagawa also gives a Saru polar question with
		<i lang="ain-Latn">ya</i>:
	</p>
	<Ex
		m="paye=an ciki e=siramkir ya"
		g="go.PL=4.S COND 2SG.S=know.the.place Q"
		tr="If we go, will you know the place?"
		cite="nakagawa2024:350"
		dial="SAR"
		place="Example 656"
		note="The plural first-person interpretation is supplied by the person construction and context; the source's Japanese leaves the going participant unexpressed."
	/>
	<p>
		Satō's 2009 study reports no reliable polar-question example in its material. Nakagawa's later
		Saru example supplies a different dialect-and-source context <Ref
			k="sato2009"
			p="55, note 11"
		/>.
	</p>
	<p>
		Nakagawa further records factual <i lang="ain-Latn">ciki</i> in Horobetsu and Chitose. He lists
		<i lang="ain-Latn">cik</i>
		for Shizunai, Samani, and Tokachi, including Tokachi
		<i lang="ain-Latn">cik pirka</i> for advice
		<Ref k="nakagawa2024" p="350–351, examples 658–661" />. Tamura's Tokachi examples include
		ordinary declarative conditions such as ‘If you go, you will understand’ <Ref
			k="tamura1997"
			p="53"
		/>.
	</p>
</S>

