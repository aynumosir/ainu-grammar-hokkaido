<S t="Time reference without obligatory tense inflection" id="time">
	<p>
		Ainu verbs do not obligatorily distinguish past, present, and future through inflection. A
		clause's time reference can come from context, a temporal expression, or a construction with
		aspectual or modal meaning <Ref k="nakagawa2024" p="434" />.
	</p>
	<Ex
		m="cimakina ku=ta kusu numan ka k=ekimne"
		g="udo 1SG.A=gather PURP yesterday ADD 1SG.S=go.to.mountains"
		tr="I went into the mountains yesterday too, to gather udo."
		cite="nakagawa2024:434"
		dial="CHI"
		place="Example 964"
		note="Numan supplies the past time reference. The main verb has person marking without a past-tense ending."
	/>
	<p>
		Tense concerns location in time; aspect concerns the temporal course of a situation; modality
		concerns possibilities, intentions, judgments, and related meanings. Evidential constructions
		present information in relation to perception, report, or inference. These distinctions help
		organize the descriptions, although a single Ainu form can have more than one function <Ref
			k="takahashi2022"
			p="§§1–3"
		/><Ref k="yoshikawa2022" p="§5" />.
	</p>
</S>

