<S t="A and aan: forms before analysis" id="a-aan">
	<p>
		Descriptions of <i lang="ain-Latn">a</i> differ. Satō calls it a past/perfect auxiliary, often
		connecting an earlier event with its present relevance while acknowledging examples where that
		connection is less clear <Ref k="sato2008" p="187–188" />.
	</p>
	<Ex
		m="kuneywa cep k=e a wa"
		g="this.morning fish 1SG.A=eat PST FIN"
		tr="I ate fish this morning."
		cite="sato2008:188"
		dial="CHI"
		place="Illustration of a"
		note="Satō explains the example as implying that the speaker has already eaten. PST follows his past/perfect description; other analyses assign different aspectual values to a."
	/>
	<p>
		Yoshikawa proposes a contrast between perfective <i lang="ain-Latn">a</i> and perfect
		<i lang="ain-Latn">aan</i>, further associating the former with direct evidence and the latter
		with indirect evidence. The account treats recollection, certainty, and mirative readings as
		related extensions. Its conclusions concern usage trends in chiefly fourth-person Saru and
		Chitose narratives, with explicit limits on their application to other varieties <Ref
			k="yoshikawa2022"
			p="§§4–5"
		/>. The following chapters examine the examples and competing accounts in more detail.
	</p>
</S>

<S t="Existential combinations and participant identity" id="existential-aspect">
	<p>
		Combinations with <i lang="ain-Latn">an</i> or its plural counterpart often express
		continuation. Their interpretation depends on whether the first predicate describes an activity,
		a state, or a change. Yoshikawa therefore calls them forms capable of aspectual interpretation
		and keeps the boundary with accompanying circumstances open
		<Ref k="yoshikawa2022" p="§§2–3, 5" />.
	</p>
	<p>
		Person marking helps identify the participants in each predicate. Nakagawa analyzes
		<i lang="ain-Latn">ku=tere wa k=an</i> ‘I am waiting’ as linked predicates, each carrying its
		own person form <Ref k="nakagawa2024" p="442" />. With a transitive first verb, the subject of
		the existential can instead be the affected object.
	</p>
	<Ex
		m="e=e kuni p cise or a=o wa an ruwe ne na"
		g="2SG.A=eat COMP thing house place 4.A=put CONJ exist.SG EVID COP FIN"
		tr="I have put the food for you to eat in the house."
		cite="nakagawa2024:443"
		dial="SAR"
		place="Example 996"
		note="The narrator is the actor of o ‘put’. The zero-marked subject of an is the food that remains in the house, not the narrator."
	/>
	<p>
		Dialect restrictions also matter. Takahashi describes Tokachi progressive
		<i lang="ain-Latn">kor an</i> as excluding first-person subjects, with
		<i lang="ain-Latn">kan an</i> available for first-person ongoing activity
		<Ref k="takahashi2022" p="§4" />. This restriction belongs to the reported Tokachi system.
	</p>
</S>

<S t="Modality, evidentiality, and sentence type" id="modality">
	<p>
		Prospective <i lang="ain-Latn">kusu ne</i>, desiderative
		<i lang="ain-Latn">rusuy</i>, and inferential or reported-content constructions must be read in
		their own frames. <Xr ch="kuni-complementizer-purpose-complements" /> shows why
		<i lang="ain-Latn">kuni</i> is not uniformly future or obligatory. Likewise, the meanings of formal-noun
		endings depend on the construction and the source's analysis.
	</p>
	<p>
		Their order has specific restrictions. Nakagawa permits <i lang="ain-Latn">a</i> and
		<i lang="ain-Latn">nankor</i> after <i lang="ain-Latn">ruwe ne</i>, while allowing
		<i lang="ain-Latn">kusu ne ruwe ne</i> and rejecting the reverse sequence
		<Ref k="nakagawa2024" p="378, 393–394" />. These facts constrain particular combinations without
		supplying a universal order for every tense, aspect, modal, and evidential form.
	</p>
	<p>
		Commands add another distinction: an ordinary singular imperative lacks subject person marking,
		but a transitive command can retain an object marker. Negative commands use preverbal <i
			lang="ain-Latn">iteki</i
		>, and plural or polite commands can have final
		<i lang="ain-Latn">yan</i>
		<Ref k="bugaeva2012" p="496–497" />. Sentence type therefore interacts with person marking as
		well as with clause endings.
	</p>
</S>
