<S t="Property words as predicates" id="predicates">
	<p>
		Words such as <i lang="ain-Latn">pon</i> ‘be small’, <i lang="ain-Latn">pewre</i>
		‘be young’ and <i lang="ain-Latn">pirka</i> ‘be good, be well’ can head predicates directly.
		They take the subject markers of intransitive verbs. Nakagawa compares
		<i lang="ain-Latn">ku=pewre</i> ‘I am young’ with <i lang="ain-Latn">ku=mina</i>
		‘I laugh’: their person morphology belongs to the same paradigm
		<Ref k="nakagawa2024" p="119" />.
	</p>
	<Ex
		m="cape pon"
		g="cat be.small"
		tr="The cat is small."
		cite="nakagawa2022pos:§2.1"
		place="Author's illustration"
	/>
	<Ex
		m="wen menoko ku=ne"
		g="be.poor woman 1SG.A=COP"
		tr="I am a poor woman."
		cite="nakagawa2022pos:§2.1"
		place="Author's illustration"
		note="Wen modifies menoko. The noun phrase ‘poor woman’ is the complement of ne, whose person form indexes the speaker."
	/>
	<p>
		The second example contains a noun phrase as the copular complement. A property predicate can
		also modify a noun directly, with the same form that it has as a predicate. These two uses are
		central to the prevailing classification of such words as verbs
		<Ref k="nakagawa2022pos" p="§§2.1–2.2" />.
	</p>
</S>

<S t="Being in a state and entering it" id="change">
	<p>
		A single property verb can describe a state or a change into that state.
		<i lang="ain-Latn">Poro</i> can mean ‘be big, be older’ or ‘grow big, grow older’;
		<i lang="ain-Latn">pirka</i> can express good health or recovery. Context supplies the
		appropriate reading <Ref k="nakagawa2022pos" p="§2.3" />.
	</p>
	<Ex
		m="paykar wa-no ku=pirka ku=monrayke"
		g="spring from-ADV 1SG.S=be.well 1SG.S=work"
		tr="When spring came, I got well and began working."
		cite="nakagawa2022pos:§2.3"
		dial="ISH"
		place="Example 10, citing Sunazawa 1983:158"
		note="The recovery reading of pirka follows the published translation. No separate change-of-state suffix appears."
	/>
	<p>
		Adding <i lang="ain-Latn">ne</i> is not the way to obtain this reading. Nakagawa explicitly
		rejects <i lang="ain-Latn">*poro ne</i> for ‘become big’ in the Handbook discussion
		<Ref k="nakagawa2022pos" p="§2.3" /> and <i lang="ain-Latn">*hure ne</i> for ‘become red’ in the
		later grammar <Ref k="nakagawa2024" p="119" />. The property verb itself supplies the predicate.
		Copular <i lang="ain-Latn">ne</i> has its own state and change readings with nominal
		complements; see <Xr ch="copula-ne-predicate-nominals" />.
	</p>
</S>

<S t="Manner expressions and auxiliary uses" id="manner">
	<p>
		The ending <i lang="ain-Latn">-no</i> forms many manner expressions from property verbs,
		including <i lang="ain-Latn">pirka-no</i> ‘well’. Some verbs also have a bare adverbial use:
		Nakagawa records <i lang="ain-Latn">tunas</i> ‘quick’ directly before a verb, alongside
		<i lang="ain-Latn">tunasno</i> ‘quickly’. He describes this bare use as lexically limited
		<Ref k="nakagawa2024" p="121" />.
	</p>
	<p>
		A few property verbs can follow another verb as auxiliaries. In the Chitose example
		<i lang="ain-Latn">ek moyre ruwe an na</i>, <i lang="ain-Latn">moyre</i> ‘slow’ describes delay
		in coming <Ref k="nakagawa2024" p="121–122, example 5" />. These patterns concern particular
		lexical items and constructions. Compound uses, where a property stem precedes another stem
		without <i lang="ain-Latn">no</i>, are discussed in
		<Xr ch="adverbial-incorporation" />.
	</p>
</S>

<S t="Ambient conditions and personal sensations" id="experience">
	<p>
		A similar English adjective can translate predicates with different argument structures.
		Nakagawa distinguishes Saru zero-place <i lang="ain-Latn">mean</i> ‘be cold’ of the weather from
		one-place <i lang="ain-Latn">merayke</i> ‘feel cold’. In his example, a cold autumn coexists
		with the narrator's feeling no cold <Ref k="nakagawa2024" p="130, table 12 and example 15" />.
		The experiencer is the grammatical subject of <i lang="ain-Latn">merayke</i> and receives intransitive
		subject marking. An ambient predicate has no corresponding personal subject.
	</p>
</S>

<S t="The adjective analysis" id="classification">
	<p>
		Nakagawa argues that the shared syntax and person morphology justify treating property
		predicates as intransitive verbs. He also considers differences in the manner-linking uses of <i
			lang="ain-Latn">no</i
		>, and attributes them chiefly to the meaning of the predicate phrase. His discussion explicitly
		disagrees with Dixon's proposal that a separate adjective class should be recognized in every
		language <Ref k="nakagawa2022pos" p="§2.4" />. The observed property meanings remain useful
		semantic distinctions within the verbal analysis. The broader classification debate is covered
		in <Xr ch="no-adjective-class-property-verbs" />.
	</p>
</S>
