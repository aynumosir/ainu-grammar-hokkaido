		tr="One fine day, in my marsh, I had only my eyes and mouth sticking out and was looking around, when…"
		cite="nakagawa2024:603"
		dial="HOR"
		place="Example 1308, through Chiri Yukie 1923:76, fifth tale"
		note="The source tier follows Nakagawa's quotation of Chiri. This opening excerpt ends in a connective; the story continues."
	/>
	<p>
		Here <i lang="ain-Latn">ci=</i> and
		<i lang="ain-Latn">=as</i> belong to the exclusive first-person plural series, although the
		story's speaker is singular. Nakagawa contrasts the collection's consistent narrative use of
		these forms with mixtures found in other Horobetsu and Bihoro materials <Ref
			k="nakagawa2024"
			p="603–604"
		/>. The two excerpts therefore illustrate conventions of particular performances and
		collections, rather than one person pattern imposed by verse.
	</p>
</S>

