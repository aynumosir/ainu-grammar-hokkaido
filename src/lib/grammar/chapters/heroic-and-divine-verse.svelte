	<p>
		The narrator uses <i lang="ain-Latn">a=</i> on transitive
		<i lang="ain-Latn">kar</i> and
		<i lang="ain-Latn">uwanpare</i>, and
		<i lang="ain-Latn">=an</i> on intransitive predicates. The plural stems
		<i lang="ain-Latn">rap</i>
		and
		<i lang="ain-Latn">okay</i> have singular narrative reference; Satō explicitly leaves the
		singular-reference use of
		<i lang="ain-Latn">okay</i> as a problem for further study
