<S t="Formal nouns and their modifiers" id="overview">
	<p>
		A <em>formal noun</em> (<span lang="ja">形式名詞</span>) has a general meaning whose reference
		is supplied by a preceding modifier. These nouns normally cannot stand alone as complete noun
		phrases. They can head relative constructions, as in Satō's <i lang="ain-Latn">poro hike</i>
		“the larger one”
		<Ref k="sato2008" p="180" />. Nakagawa also uses the term <em>noun particle</em>, reflecting
		their limited independence <Ref k="nakagawa2024" p="257–258" />.
	</p>
	<p>
		The class boundary differs among descriptions. Bugaeva calls a corresponding small class <em
			>bound nouns</em
		>
		<Ref k="bugaeva2012" p="470" />. Satō provisionally distinguishes formal nouns heading relative
		constructions from nominalizers that turn a content clause into a nominal expression <Ref
			k="sato2008"
			p="175, 180"
		/>. Nakagawa instead distinguishes a noun's subclass from its complementizer function
		<Ref k="nakagawa2024" p="258–259, 507–510" /> ‹contested›.
	</p>
</S>

<S t="Representative forms" id="inventory">
	<p>
		Nakagawa's general inventory includes <i lang="ain-Latn">p/pe</i> “thing,”
		<i lang="ain-Latn">hi</i> “fact, thing, time, place,”
		<i lang="ain-Latn">hike</i> “the one, the side,”
		<i lang="ain-Latn">katu</i> “manner,” <i lang="ain-Latn">uske</i> “place,”
		<i lang="ain-Latn">usi(ke)</i> “time, place,” <i lang="ain-Latn">kur</i>
		“person,” and <i lang="ain-Latn">utar</i> “people, plural”
		<Ref k="nakagawa2024" p="258" />. Their permitted modifiers and their further grammatical uses
		differ by item.
	</p>
	<p>
		Satō gives both <i lang="ain-Latn">tan usi</i> and
		<i lang="ain-Latn">tan usike</i> with the demonstrative “this”
		<Ref k="sato2008" p="181" />. A modifying clause is therefore only one of the available
		environments for these forms.
	</p>
	<Ex
		m="tan usike pusu"
		g="DEM place cultivate"
		tr="Cultivate this place."
		cite="sato2008:181"
		dial="CHI"
	/>
</S>

<S t="Dependence and clause modification" id="diagnostics">
	<p>
		A modifying clause can identify the person, thing, time, or place denoted by its head. Satō's
		fragment illustrates a property predicate modifying
		<i lang="ain-Latn">hike</i>:
	</p>
	<Ex
		m="ku=poho poro hike"
		orig="ku-poho, poro hike"
		origLang="ain-Latn"
		g="1SG.A=son.POSS be.large one"
		tr="the larger one of my sons"
		cite="sato2008:180"
		dial="CHI"
		note="Source fragment; the person-marker boundary is normalized to an equals sign in the morphemic line."
	/>
	<p>
		Formal nouns differ from common nouns in their dependence and possessive morphology, and from
		pronouns in their ability to take clause modifiers
		<Ref k="nakagawa2024" p="214–217" />. For the wider comparisons, see
		<Xr ch="nominal-subclasses-and-bound-nouns" />.
	</p>
	<p>
		Nakagawa observes that <i lang="ain-Latn">p/pe</i> and
		<i lang="ain-Latn">hi</i> are closely joined in pronunciation to what precedes. Their syntactic
		scope can nevertheless encompass a whole verb phrase, which leads him to analyze these uses as
		clitics <Ref k="nakagawa2022pos" p="§3.3" />. Bugaeva also recognizes suffixal uses in
		particular word formations
		<Ref k="bugaeva2012" p="470–471" />. The construction determines which properties are involved.
	</p>
</S>

<S t="P and pe" id="p-pe">
	<p>
		Satō describes <i lang="ain-Latn">p</i> after vowels and
		<i lang="ain-Latn">pe</i> after consonants
		<Ref k="sato2008" p="177, 180" />. These forms can head expressions referring to things or
		people. In his account, human reference with
		<i lang="ain-Latn">p/pe</i> often has an unfavorable nuance, while
		<i lang="ain-Latn">kur</i> is more polite
		<Ref k="sato2008" p="180" />. The choice thus has pragmatic as well as grammatical consequences.
	</p>
	<p>
		The forms also occur in content and sentence-final constructions. Their relative, complement,
		and final uses are distinguished in <Xr ch="nominalization-p-pe" />. Lexical formations such as
		<i lang="ain-Latn">amip</i>
		“clothing” are treated in
		<Xr ch="deverbal-denominal-noun-derivation" />
		<Ref k="sato2008" p="266, 268–269" />.
	</p>
</S>

<S t="Hi, places, and content clauses" id="hi">
	<p>
		<i lang="ain-Latn">Hi</i> occurs with temporal, spatial, and content readings. In the following
		Saru example, the expression headed by
		<i lang="ain-Latn">hi</i> is the object of “object to.” Nakagawa analyzes the preceding clause
		as complete: <i lang="ain-Latn">hi</i> nominalizes its content without itself filling an
		argument position inside that clause
		<Ref k="nakagawa2024" p="507–508" />.
	</p>
	<Ex
		m="hekattar tura sinot=an hi ka a=onaha kopan"
		g="children with play=4.S NMLZ also 4.A=father.POSS object.to"
		tr="My father also objected to my playing with the children."
		cite="nakagawa2024:507, example 1161"
		dial="SAR"
	/>
	<p>
		In Nakagawa's arity analysis, this completed clause has no remaining argument position; a
		relative modifier retains a positive arity. He discusses
		<i lang="ain-Latn">uske</i> and <i lang="ain-Latn">usi</i> in both kinds of construction <Ref
			k="nakagawa2024"
			p="508–510"
		/>. Satō's distinction between nominalizers and formal nouns organizes these uses differently
		<Ref k="sato2008" p="175, 180" /> ‹contested›.
	</p>
	<p>
		Nakagawa's 2022 account restricts <i lang="ain-Latn">hi</i> to verb-phrase modifiers, while his
		2024 grammar records the restricted combination
		<i lang="ain-Latn">nea hi</i> and analyzes contracted
		<i lang="ain-Latn">tani</i> as <i lang="ain-Latn">tan + hi</i>
		<Ref k="nakagawa2022pos" p="§3.4" />;
		<Ref k="nakagawa2024" p="288" />. He also records Tokachi and Ishikari
		<i lang="ain-Latn">ihi</i>, used almost exclusively in
		<i lang="ain-Latn">ene an ihi</i> “the following is how it happened”
		<Ref k="nakagawa2024" p="258" />.
	</p>
</S>

<S t="People, plurality, and prospective complements" id="kur-kuni">
	<p>
		<i lang="ain-Latn">Kur</i> can follow a clause or a prenominal:
		<i lang="ain-Latn">tan kur</i> means “this person”
		<Ref k="bugaeva2012" p="470" />. <i lang="ain-Latn">Utar</i> also follows ordinary nouns.
		Nakagawa contrasts a clause meaning “the people whom I was helping” with
		<i lang="ain-Latn">cikappo utar</i>
		“small birds”
		<Ref k="nakagawa2024" p="258, examples 332–333" />. Its number meanings are described in <Xr
			ch="nominal-number-utar-transnumerality"
		/>.
	</p>
	<p>
		Satō includes <i lang="ain-Latn">kuni</i> and
		<i lang="ain-Latn">kunak</i> among nominalizers, with prospective or intended content in their
		cited constructions <Ref k="sato2008" p="177" />. Nakagawa discusses them among forms
		functioning as complementizers
		<Ref k="nakagawa2024" p="510" />. Their selection and interpretation belong to
		<Xr ch="nominalized-complements-control-raising" />.
	</p>
</S>

<S t="Noun forms in evidential constructions" id="evidential-quartet">
	<p>
		Four ordinary nouns have affiliative forms used in evidential constructions:
		<i lang="ain-Latn">ru → ruwe</i>, <i lang="ain-Latn">haw → hawe</i>,
		<i lang="ain-Latn">sir → siri</i>, and <i lang="ain-Latn">hum → humi</i>. Nakagawa associates
		their lexical bases with a path or trace, voice, appearance, and sound or feeling, respectively <Ref
			k="nakagawa2024"
			p="259, Table 66"
		/>. The possessive morphology differs among the words; see
		<Xr ch="affiliative-suffix-morphophonology" />.
	</p>
	<p>
		Nakagawa describes their formal-noun-like uses alongside their ordinary noun status. Bugaeva
		classifies their evidential uses as particles
		<Ref k="nakagawa2024" p="258–259" />;
		<Ref k="bugaeva2012" p="470" /> ‹contested›. Lexical noun uses, complements, and final evidential
		constructions have different distributions, detailed in
		<Xr ch="evidential-schema-overview" />.
	</p>
</S>

<S t="Nominal origins and grammatical functions" id="diachrony">
	<p>
		Several items combine lexical and grammatical uses. Satō distinguishes
		<i lang="ain-Latn">utar</i> “relatives,” with affiliative
		<i lang="ain-Latn">utari</i>, from its use after a noun or modifying clause
		<Ref k="sato2008" p="181" />. Nakagawa treats the plural use as a development from the noun <Ref
			k="nakagawa2022pos"
			p="§3.3"
		/> ‹speculative›.
	</p>
	<p>
		The analytical label <em>nominalizer</em> can cover a wider set than the formal-noun inventory:
		Refsing groups several types under that heading
		<Ref k="refsing1986" p="259–264" />. The differences among lexical heads, clause nominalization,
		and connective uses are developed in
		<Xr ch="lexical-head-formal-noun-nominalization" />.
	</p>
</S>
