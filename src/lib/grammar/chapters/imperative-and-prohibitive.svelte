<S t="Direct commands" id="direct">
	<p>
		A direct imperative uses the verb without its ordinary subject index. Object indexing remains
		possible: <i lang="ain-Latn">en=tere</i> means ‘wait for me’, with first-person object
		<i lang="ain-Latn">en=</i>. Since third-person predicates also lack an overt subject index,
		context and intonation help identify a command
		<Ref k="sato2008" p="128" /><Ref k="nakagawa2024" p="422" />.
	</p>
	<Ex
		m="hetak pusu wa inkar"
		g="come.on dig CONJ look"
		tr="Come on, try digging!"
		cite="nakagawa2024:422"
		dial="CHI"
		place="Example 911"
		note="Wa inkar has the supplementary meaning ‘try’ here. The initial interjection helps establish the directive reading."
	/>
	<p>
		A plural or polite command can end in <i lang="ain-Latn">yan</i>. For intransitives with
		separate singular and plural stems, Nakagawa describes the plural stem with
		<i lang="ain-Latn">yan</i>, as in
		<i lang="ain-Latn">hosippa yan</i> ‘go home’. His teaching contrast excludes the bare plural
		stem as a command in that construction
		<Ref k="nakagawa2024" p="422, example 914" />. Satō likewise gives <i lang="ain-Latn">hopuni</i>
		beside polite/plural
		<i lang="ain-Latn">hopunpa yan</i>
		<Ref k="sato2008" p="128–129" />.
	</p>
</S>

<S t="Requests and final particles" id="requests">
	<p>
		Adding <i lang="ain-Latn">wa en=kore</i> can make a request to do something for the speaker.
		Nakagawa's haircut request is
		<i lang="ain-Latn">ku=sapa kar wa en=kore</i>; the object index on
		<i lang="ain-Latn">kore</i> identifies the beneficiary
		<Ref k="nakagawa2024" p="423, example 917" />. Satō restricts this supplementary use of
		<i lang="ain-Latn">wa kore</i>
		to requests, while Nakagawa says it is especially common in requests
		<Ref k="sato2008" p="88" /><Ref k="nakagawa2024" p="455" />.
	</p>
	<p>
		<i lang="ain-Latn">Hani</i> can soften an instruction while impressing it on the addressee. It
		also occurs with declarative expressions, so its contribution is broader than imperative
		marking. A reduced <i lang="ain-Latn">ani</i> occurs, often after a consonant <Ref
			k="sato2008"
			p="72"
		/><Ref k="nakagawa2024" p="422–423" />.
	</p>
	<Ex
		m="iteki omkekar yan hani"
		g="PROH catch.cold IMP.PL FIN"
		tr="Please don't catch cold."
		cite="sato2008:72"
		dial="CHI"
		place="§8.2, hani examples"
	/>
</S>

<S t="Indirect directives" id="indirect">
	<p>
		Ordinary finite constructions can perform a directive function. Nakagawa lists
		<i lang="ain-Latn">yak pirka</i> ‘it would be good if’,
		<i lang="ain-Latn">kusu ne na</i>, <i lang="ain-Latn">p ne na</i>, and
		<i lang="ain-Latn">nankor na</i>. In second-person formulations, the predicate retains its
		person index
		<Ref k="nakagawa2024" p="423–424" />.
	</p>
	<p>
		Third-person phrasing is also possible. Nakagawa's instruction to daughters to wash their hands
		and cook properly literally says that it would be good if ‘my daughters’ did so. The verbs have
		ordinary zero third-person marking
		<Ref k="nakagawa2024" p="424, example 923" />. The directive force of a sentence therefore does
		not by itself identify its grammatical subject or require a bare imperative verb.
	</p>
</S>

<S t="Prohibitions" id="prohibition">
	<p>
		<i lang="ain-Latn">Iteki</i> introduces a prohibition and can occur before a direct imperative
		or within an indirect directive. Nakagawa lists regional
		<i lang="ain-Latn">itekke</i> for Shizunai, Samani, and Tokachi;
		<i lang="ain-Latn">etekke</i> for Shiranuka, Bihoro, and Tokachi; and Ishikari
		<i lang="ain-Latn">ecik(k)i</i>. The overlapping lists do not define exclusive regional
		boundaries <Ref k="nakagawa2024" p="424–425" />.
	</p>
	<Ex
		m="iteki e=esina no e=ye p ne na"
		g="PROH 2SG.A=hide CONJ 2SG.A=say NMLZ COP FIN"
		tr="Tell it without hiding anything."
		cite="nakagawa2024:425"
		dial="SAR"
		place="Example 935"
		note="Both verbs retain second-person indexing in this indirect directive."
	/>
	<p>
		Other prohibitive expressions include <i lang="ain-Latn">ika</i>,
		<i lang="ain-Latn">ikiyan</i>, and <i lang="ain-Latn">inkian</i>, with ordinary finite
		predicates. Satō's description particularly associates such indexed forms with admonition, while
		acknowledging that their finer differences remain unclear
		<Ref k="sato2008" p="129" /><Ref k="nakagawa2024" p="425–426" />. For the wider modal
		constructions, see <Xr ch="tam-overview" />.
	</p>
</S>
