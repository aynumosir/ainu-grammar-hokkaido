<S t="Indefinite expressions in positive and negative sentences" id="indefinites">
	<p>
		<i lang="ain-Latn">Nep ka</i> and <i lang="ain-Latn">nen ka</i> can refer to something or
		someone in affirmative sentences. Nakagawa gives an explanation involving
		<i lang="ain-Latn">nep ka moto</i>
		‘some cause’ and a sentence about giving someone to <i lang="ain-Latn">nen ka</i> ‘someone’.
		Their occurrence is therefore not confined to negative contexts
		<Ref k="nakagawa2024" p="323, examples 526–528" />.
	</p>
	<p>
		With a negative predicate, these expressions can receive ‘nothing’ or ‘nobody’ readings. The
		interpretation involves the surrounding construction as well as the indefinite expression.
	</p>
	<Ex
		m="seta ka nep ka isam pe ne a p"
		g="dog ADD what ADD not.exist NMLZ COP PFV CONJ"
		tr="There were no dogs or anything, but …"
		cite="nakagawa2024:323"
		dial="SAR"
		place="Example 529"
		note="The source presents an unfinished adversative clause. PFV is the conventional gloss used in chapter 111; Nakagawa describes earlier background contrasted with what follows (pp. 305–306). The two occurrences of ka associate the named category ‘dog’ with the broader indefinite expression."
	/>
	<p>
		An indefinite need not have the same form as the corresponding interrogative. Several dialects
		use forms beginning in <i>h</i> for questions alongside
		<i>n</i>-initial indefinite bases. Nakagawa also records crossovers between the two sets <Ref
			k="nakagawa2024"
			p="420, table 79 and example 903"
		/>. See <Xr ch="interrogative-pro-forms" /> for the regional paradigms.
	</p>
</S>

<S t="Ka with lexical and grammatical negation" id="ka">
	<p>
		<i lang="ain-Latn">Ka</i> occurs with ordinary <i lang="ain-Latn">somo</i>
		negation and with lexical negatives such as <i lang="ain-Latn">isam</i>,
		<i lang="ain-Latn">sak</i>, and <i lang="ain-Latn">eaykap</i>. It can follow a noun or a
		predicate. Nakagawa's examples include a person without a necklace and a narrator unable even to
		lift a hand
		<Ref k="nakagawa2024" p="323, examples 530–533" />.
	</p>
	<p>
		Its contribution varies. Nakagawa describes a possible connection between additive meaning and
		emphatic absence, while expressly allowing negative sentences without <i lang="ain-Latn">ka</i>.
		In his account of
		<i lang="ain-Latn">(ka) somo ki</i>, its presence need not add the usual unexpectedness or
		additive meaning <Ref k="nakagawa2024" p="323, 407" />. Satō tentatively calls these uses a
		negative particle, but says that they cannot be strictly separated from additive
		<i lang="ain-Latn">ka</i>
		<Ref k="sato2008" p="124, §15.2" />.
	</p>
	<p>
		Sentence type also matters. A Shizunai example with
		<i lang="ain-Latn">nep ka</i> and <i lang="ain-Latn">henne</i> asks whether the hearer saw any
		sign of a woman passing. Its negative-question form does not assert that no such sign existed
		<Ref k="nakagawa2024" p="408, example 837, after Okuda ed. 1999:2030997" />.
	</p>
</S>

<S t="Free choice" id="free-choice">
	<p>
		Indefinite bases also combine with <i lang="ain-Latn">ne yakka</i>. Nakagawa illustrates
		<i lang="ain-Latn">nen ne yakka</i>
		‘whoever they are’ in a suggestion to let visitors enter, and Satō gives
		<i lang="ain-Latn">ney ta ne yakka</i> ‘wherever’ in a description of mushrooms growing
		throughout the mountains
		<Ref k="nakagawa2024" p="420, example 902" /><Ref k="sato2008" p="119" />. These readings belong
		to a different construction from negative
		<i lang="ain-Latn">nep ka</i>.
	</p>
</S>

<S t="Where the negation falls" id="scope">
	<Ex
		m="sinep ka a=isamka ka somo ki ruwe ne kusu"
		g="one.thing ADD 4.A=lose ADD NEG do EVID COP because"
		tr="Because I have not lost even one, …"
		cite="nakagawa2024:393"
		dial="SAR"
		place="Example 779"
	/>
	<p>
		Here <i lang="ain-Latn">somo ki</i> negates losing something, and
		<i lang="ain-Latn">ruwe ne</i> follows that negative predicate. Nakagawa contrasts this with
		<i lang="ain-Latn">ruwe somo ne</i>, which his next example uses for rhetorical confirmation
		<Ref k="nakagawa2024" p="393, examples 779–780" />. These examples show distinct placements and
		interpretations of negation. They do not by themselves establish a complete rule for which
		indefinites can occur under every kind of higher or embedded negation. Further uses of copular
		negation appear in <Xr ch="negation-somo-standard-clausal" s="scope" />.
	</p>
</S>
