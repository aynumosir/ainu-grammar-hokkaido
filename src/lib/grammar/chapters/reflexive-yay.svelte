<S t="Reflexive participants" id="overview">
	<p>
		The prefix <i lang="ain-Latn">yay-</i> commonly identifies an object's referent with the
		subject: <i lang="ain-Latn">yay-ipe-re</i> means “feed oneself,” and
		<i lang="ain-Latn">yay-kar</i> “transform oneself.” A two-place base thereby becomes one-place.
		With a higher-valency base, another object can remain
		<Ref k="bugaevakobayashi2022" p="§4.2.2" />;
		<Ref k="nakagawa2024" p="187–188" />. The reflexive identifies participants; its effect on the
		final argument count depends on the base and other derivations.
	</p>
	<Ex
		m="aynu ne yay-kar wa kamuy ko-sunke wa an ruwe ne"
		g="human as REFL-make CONJ deity APPL-lie CONJ exist.SG INFR.EVID COP"
		tr="He transformed himself into a human and was lying to the god."
		cite="bugaevakobayashi2022:§4.1.1"
		place="Example 4b"
		note="The Handbook's transformation example uses aynu ne as the resulting form. The grammatical gloss INFR.EVID follows its functional analysis of ruwe."
	/>
	<p>
		Person marking applies to the derived verb's argument frame. The prefix is derivational and its
		availability is partly lexical <Ref k="sato2008" p="251" />. See
		<Xr ch="valency-voice-overview" /> for the comparison with other valency operations and
		<Xr ch="personal-affix-template-and-ordering" /> for the position of person forms.
	</p>
</S>

<S t="Intentionality and direct participation" id="yay-si">
	<p>
		A traditional account contrasts intentional <i lang="ain-Latn">yay-</i> with unintentional
		<i lang="ain-Latn">si-</i>. The familiar pair is
		<i lang="ain-Latn">yay-pusu</i>, coming to the surface through one's own action, and
		<i lang="ain-Latn">si-pusu</i>, floating up spontaneously. Nakagawa quotes Tamura's formulation
		but observes that clear lexical pairs of this kind are limited
		<Ref k="nakagawa2024" p="187" />.
	</p>
	<Ex
		m="hekaci pet or un rawkuske ayne yay-pusu"
		g="boy river place ALLAT dive CONJ REFL-draw.out"
		tr="A boy dives into the river and finally comes to the surface."
		cite="bugaevakobayashi2022:§4.2.2"
		place="Example 14"
		note="The Handbook reproduces Kindaichi 1931:149. This is a source illustration; no dialect is assigned here beyond its reported Ainu provenance."
	/>
	<p>
		Satō proposes <em>direct reflexive</em> for <i lang="ain-Latn">yay-</i> and
		<em>indirect reflexive</em> for <i lang="ain-Latn">si-</i>. On his account,
		<i lang="ain-Latn">yay-</i> presents the subject as directly carrying out the action on itself,
		while <i lang="ain-Latn">si-</i> can involve the action or perception of others. Deliberate
		<i lang="ain-Latn">si-</i>
		constructions, including having someone help oneself and pretending ignorance, motivate this
		alternative to an intentionality contrast ‹contested› <Ref k="sato2007" p="§3.3" />;
		<Ref k="sato2008" p="249–251" />. The constructions and other analyses are discussed in
		<Xr ch="reflexive-possessive-si" />.
	</p>
</S>

<S t="Reflexive possession inside a verb" id="possession">
	<p>
		A reflexive may identify the possessor of an incorporated noun with the subject. In
		<i lang="ain-Latn">yay-par-oyki</i> “feed oneself,” the relevant possession is one's own mouth.
		The Handbook calls this a <em>quasi-possessive reflexive</em>
		<Ref k="bugaevakobayashi2022" p="§4.2.2, example 16" />.
	</p>
	<Ex
		m="yay-par-oyki"
		g="REFL-mouth-do.about"
		tr="Feed oneself (literally, do about one's own mouth)."
		cite="bugaevakobayashi2022:§4.2.2"
		place="Lexical illustration, example 16"
		note="The Handbook attributes the example to Satō 2018. The reflexive is the incorporated noun's possessor."
	/>
	<p>
		This derivational possessor differs from the person indexes in the two-word constructions that
		Satō calls quasi-incorporation. Their lexical and morphological structure is compared in <Xr
			ch="noun-incorporation-oblique-polysynthesis-debate"
		/>. Neither construction supports a blanket ban on possession in complex verbs.
	</p>
</S>

<S t="Lexical extensions and combinations" id="lexical">
	<p>
		Nakagawa records uses of <i lang="ain-Latn">yay-</i> with no arity reduction:
		<i lang="ain-Latn">yay-an</i> “be ordinary” remains one-place, and
		<i lang="ain-Latn">yay-kotan</i> means “one's own village.” He analyzes the prefix as
		arity-neutral in these uses <Ref k="nakagawa2024" p="187" />. The English word “self” thus
		covers several grammatical constructions.
	</p>
	<p>
		The documented <i lang="ain-Latn">yay-si-turi-re</i> means to stretch oneself out and lie down.
		Nakagawa notes that he has not found the reversed ordering with
		<i lang="ain-Latn">si-</i> outside <i lang="ain-Latn">yay-</i>, suggesting a closer association
		of <i lang="ain-Latn">si-</i> with the root ‹speculative›
		<Ref k="nakagawa2024" p="188" />. The attested combination is compatible with lexically
		restricted derivation; it does not supply a general recipe for stacking the two prefixes.
	</p>
</S>
