<S t="Narration and speech within a story" id="narrative-perspective">
	<p>
		Narrative tense, aspect, and evidentiality depend partly on whose utterance is being
		represented. A storyteller introduces events to an audience; a character speaks to another
		character within those events. The same construction can occur at both levels. Hirosawa
		illustrates this with a Saru tale about Pananpe and Penanpe, examining
		<i lang="ain-Latn">ruwe ne</i> as a way of presenting information that the addressee does not
		yet recognize
		<Ref k="hirosawa2026" p="75–78, §6.2" />.
	</p>
	<Ex
		m="pananpe an penanpe an hine siran pe ne ruwe ne hike"
		g="Pananpe exist.SG Penanpe exist.SG CONJ be.so NMLZ COP EVID COP CONJ"
		tr="There were Pananpe and Penanpe."
		cite="hirosawa2026:76"
		dial="SAR"
		place="Example 13; Tamura 1988, Ainu Audio Materials 5, text 05-02, p. 4"
		note="The opening introduces the two protagonists in the third person. The final connective continues the narrative beyond this excerpt."
	/>
	<p>
		Later, the sea deity identifies himself to the two men. Here the fourth-person forms refer to
		the speaking character. This is direct speech inside the tale, whose opening has already
		established a third-person narrative <Ref k="hirosawa2026" p="76–77, example 16" />.
	</p>
	<Ex
		m="atuy kor kamuy a=ne hine an=an ruwe ne"
		g="sea have deity 4.A=COP CONJ exist.SG=4.S EVID COP"
		tr="I am the sea god."
		cite="hirosawa2026:77"
		dial="SAR"
		place="Example 16; Tamura 1988, Ainu Audio Materials 5, text 05-02, p. 6"
		note="The sea deity reveals his identity to Pananpe and Penanpe. Person boundaries are normalized; Hirosawa labels these forms indefinite."
	/>
	<p>
		First-person storytelling is widespread, with regional person-marking conventions described in <Xr
			ch="logophoric-narration-and-reported-discourse"
		/>. Neither fourth-person marking nor <i lang="ain-Latn">ruwe ne</i>
		alone identifies a text as prose, heroic epic, or divine epic.
	</p>
</S>

<S t="Aspect at narrative transitions" id="aspect-transitions">
	<p>
		Yoshikawa observes that <i lang="ain-Latn">a</i> followed by
		<i lang="ain-Latn">p</i>, <i lang="ain-Latn">korka</i>, or
		<i lang="ain-Latn">wa</i> often occurs where the scene, topic, or actor changes. Her examples
		include a childhood episode followed by ‘now’ and the protagonist's growing up, and an
		established situation followed by ‘one day’ and a new event. She relates this discourse use to
		her analysis of <i lang="ain-Latn">a</i> as perfective, separating a completed situation from
		the current one
		<Ref k="yoshikawa2022" p="§4.1.1, examples 34–36" />.
	</p>
	<p>
		That explanation belongs to a wider disagreement over the form's temporal, aspectual, and modal
		meaning. The competing accounts are compared in <Xr ch="perfective-anterior-a" />. A transition
		in a particular passage therefore supports a discourse observation without requiring all
		occurrences of the form to have one narrative function.
	</p>
</S>

<S t="Two evidentials and two perspectives" id="double-evidentiality">
	<p>
		Dal Corso's example 273 contains
		<i lang="ain-Latn">sekor hawean kor ran hawe as ruwe ne</i>, translated as a crow seeming to
		come down while speaking. He assigns
		<i lang="ain-Latn">hawe as</i> to the character's indirect evidence and
		<i lang="ain-Latn">ruwe ne</i>
		to the narrator's knowledge of the traditional account. On this reading, the two constructions present
		complementary sources from different perspectives
		<Ref k="dalcorso2018" p="331–332, §8.5, example 273; KAY 24-2,7" />.
	</p>
	<p>
		Other combinations receive a different explanation. In example 276,
		<i lang="ain-Latn">hawe ne nankor ruwe ne</i> accompanies a character's suggestion that a
		protective deity has secretly informed them. Dal Corso analyzes <i lang="ain-Latn">hawe ne</i>
		as direct auditory evidence and the final construction as epistemic reinforcement. The passage does
		not simply report hearsay. He also records reversed orders of direct and indirect forms, so his examples
		do not establish a single obligatory order for every pair
		<Ref k="dalcorso2018" p="332–333, examples 274–276" />. See <Xr
			ch="evidential-schema-overview"
		/> for the underlying constructions and their competing analyses.
	</p>
</S>

<S t="What genre comparisons establish" id="genre-comparison">
	<p>
		Dal Corso reports fewer evidential tokens in rhythmic texts than in non-rhythmic texts of equal
		length in an exploratory comparison. His main study concentrates on prose; its source list also
		includes epic recited as prose. In the Hokkaido evidential sample, 1,508 of 2,232 tokens are
		<i lang="ain-Latn">ruwe ne</i> (67.56%). The denominator is evidential tokens, so this figure
		does not give the percentage of clauses containing the construction or its frequency within each
		genre
		<Ref k="dalcorso2018" p="39–42; 70–72, Table 4" />.
	</p>
	<p>
		Hirosawa likewise selects prose partly to avoid the effects of metre
		<Ref k="hirosawa2026" p="63" />. These studies establish uses within identified narratives. A
		comparison with sung epic or prayer must also consider performance, speaker, dialect, and the
		proportion of quoted speech. Refrains and metrical material are discussed in
		<Xr ch="sakehe-refrain-and-sung-verse-structure" />; prayer endings and person choices in <Xr
			ch="honorific-ritual-and-taboo-registers"
		/>. The Tokachi bare forms studied by Takahashi concern dialect and construction, with no
		demonstrated restriction to a narrative genre
		<Ref k="takahashi2013" p="129–134" />.
	</p>
