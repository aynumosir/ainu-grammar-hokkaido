<S t="A relative-headed expression as a copular subject" id="identification">
	<p>
		A description ending in a general noun such as <i lang="ain-Latn">p</i>
		can stand as the subject of a copular statement. Nakagawa's example
		identifies what is placed on a shelf as food
		<Ref k="nakagawa2024" p="512, example 1178" />.
	</p>
	<Ex m="parka a=omare wa a=anu p haru ne na"
		g="shelf 4.A=put.into CONJ 4.A=put NMLZ food COP FIN"
		tr="What one puts on the shelf is food."
		cite="nakagawa2024:512" dial="SAR" place="Example 1178"
		note="NMLZ is the conventional gloss for p; Nakagawa analyzes it here as the head of a relative construction, corresponding to the object of omare and anu." />
	<p>
		The construction identifies a referent through a description. The source
		also translates it as a statement about putting food on the shelf.
		Neither paraphrase by itself demonstrates the exhaustive meaning ‘food
		and nothing else’, or a special construction devoted to contrastive focus.
	</p>
</S>

<S t="A participant or the content of a situation" id="head-content">
	<p>
		Nakagawa distinguishes relative-headed <i lang="ain-Latn">p/pe</i>
		from a complement marker introducing the content of a situation. His next
		comparison has a speaker unable to understand why people speak and cry;
		the incomprehensible content is their conduct and its reason
		<Ref k="nakagawa2024" p="512–513, example 1180" />.
	</p>
	<p>
		Satō makes a related distinction between a relative construction, whose
		head can be understood as a participant in a corresponding sentence, and
		a content clause. He cautions that the finer uses of the nominalizing
		forms need further investigation
		<Ref k="sato2008" p="175–177, §22.1" />.
		The full comparison appears in <Xr ch="nominalization-p-pe" /> and
		<Xr ch="lexical-head-formal-noun-nominalization" />.
	</p>
	<p>
		Concreteness is only part of the distinction. <i lang="ain-Latn">Hi</i>
		occurs with places, times, and propositional content; Nakagawa explicitly
		records variation in the locative constructions he compares
		<Ref k="nakagawa2024" p="511–512, examples 1175–1177" />.
	</p>
</S>

<S t="Nominal function without a separate nominalizer" id="zero">
	<p>
		Bugaeva allows “zero-nominalization” when a morphologically unmarked
		clause has a nominal function. She distinguishes this from constructions
		with an overt nominalizing word and notes that the verb retains its person
		marking in both types <Ref k="bugaeva2016" p="99–100, examples 4a–4b" />.
		Her proposal concerns complement structure; it does not make every bare
		verb sequence an identificational or focus construction.
	</p>
	<p>
		Different authors consequently use “nominalization” for partly different
		sets of structures. The presence or absence of an overt
		<i lang="ain-Latn">p</i> or <i lang="ain-Latn">hi</i> is one
		piece of evidence alongside the function of the whole expression.
	</p>
</S>

<S t="Formal nouns and clause endings" id="endings">
	<p>
		Formal nouns also enter clause endings. Nakagawa gives a statement about
		the name Piratur among his examples with a formal noun and
		<i lang="ain-Latn">ne</i>
		<Ref k="nakagawa2024" p="393, example 778, after Tamura 1985:30" />.
	</p>
	<Ex m="tap a=ye katu Piratur sekor a=ye hawe ne"
		g="now 4.A=say manner Piratur QUOT 4.A=say EVID COP"
		tr="In the way we say it now, it is called Piratur."
		cite="nakagawa2024:393" dial="SAR" place="Example 778, after Tamura 1985:30" />
	<p>
		The words for manner and voice, the quoted name, and the clause ending each
		contribute to this expression. Its occurrence does not establish a separate
		“naming cleft” construction. The source's analysis belongs with the
		formal-noun endings described in <Xr ch="evidential-schema-overview" />.
	</p>
</S>

<S t="Context and focus interpretations" id="focus">
	<p>
		A copular identification can answer a question about what something is;
		a topic-marked phrase can contrast one matter with another. These
		interpretations depend on the expression and context. The mere sequence
		of a nominalizing form and <i lang="ain-Latn">ne</i> does not establish
		one common focus meaning for relative descriptions, content clauses, and
		evidential endings.
		The directly described topic contrasts are treated in
		<Xr ch="topic-marking-anakne" />.
	</p>
</S>
