<S t="Regional names and overlapping labels" id="regional-names">
	<p>
		Endō gives <i lang="ain-Latn">uepeker</i> for southwestern prose tales and
		<i lang="ain-Latn">tuytak</i>
		across much of central and northeastern Hokkaido. Southwestern divine epics are commonly called
		<i lang="ain-Latn">kamuy yukar</i>, eastern ones
		<i lang="ain-Latn">oyna</i>, and middle-Saru ones
		<i lang="ain-Latn">menoko yukar</i>
		<Ref k="endo2022" p="§§2.4.1–2.4.2" />.
	</p>
	<p>
		The same labels can identify different forms elsewhere. Southwestern
		<i lang="ain-Latn">oyna</i> names a sacred biography in which a culture hero narrates, without a
		divine epic's refrain.
		<i lang="ain-Latn">Menoko yukar</i> also occurs for heroic epics whose protagonist is a woman.
		Those uses require the locality and performance form to be specified
		<Ref k="endo2022" p="§§2.4.3–2.4.4" />.
	</p>
	<p>
		Regional heroic-epic names include eastern <i lang="ain-Latn">sakorpe</i>
		and Samani <i lang="ain-Latn">yayerap</i>. Endō also distinguishes legends or experiential lore,
		called <i lang="ain-Latn">upaskuma</i>,
		<i lang="ain-Latn">ucaskuma</i>, or <i lang="ain-Latn">ikopepeka</i>. These prose accounts lack
		the fixed opening and closing patterns of prose tales <Ref k="endo2022" p="§§2.4.3–2.4.4" />.
	</p>
</S>

