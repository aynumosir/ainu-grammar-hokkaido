<S t="Ways of classifying oral literature" id="classification">
	<p>
		Ainu oral literature includes songs, wordplay, prayers, negotiation, and several kinds of
		narrative. Classification depends on whether form, performance, or purpose takes precedence.
		Endō notes the absence of a single accepted scheme and adopts Nakagawa's functional grouping
		into songs, word games, chants, and narratives
		<Ref k="endo2022" p="§2" />.
	</p>
	<p>
		The frequently cited division into prose tales, divine epics, and heroic epics concerns the
		narrative repertoire. It does not include all verbal arts, and it requires regional
		qualifications even within narrative
		<Ref k="endo2022" p="§§2.1–2.4" />.
	</p>
</S>

