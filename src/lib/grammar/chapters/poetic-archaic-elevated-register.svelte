<S t="Elevated wording and performance" id="register">
	<p>
		<i lang="ain-Latn">A=tomte itak</i> ‘ornamented language’ differs from ordinary
		<i lang="ain-Latn">yayan itak</i>
		through vocabulary, complex word formation, expanded expressions, and recurrent formulas.
		Nakagawa distinguishes this register contrast from the division into verse and prose. Elevated
		expressions can occur in prose, and the grammar of a poetic prayer need not match narrative
		person marking
		<Ref k="nakagawa2024" p="586, 592, 600–602" />.
	</p>
	<p>
		The register also includes metaphor, exaggeration, understatement, and paired phrases. Satō
		treats these as literary techniques; he suggests that metrical requirements and the demands of
		remembering long performances contribute to formulaic wording
		<Ref k="sato2008" p="264, §34.4" />
		<Ref k="endo2022" p="§4" />.
	</p>
</S>

<S t="Vocabulary and incorporated expressions" id="word-formation">
	<p>
		Nakagawa's lexical comparisons include ordinary
		<i lang="ain-Latn">cise</i> ‘house’ beside elevated
		<i lang="ain-Latn">kenru</i>, <i lang="ain-Latn">cip</i> ‘boat’ beside
		<i lang="ain-Latn">nimam</i>, and <i lang="ain-Latn">ru</i>
		‘path’ beside <i lang="ain-Latn">kiroru</i>. Choice can depend on the passage: a dog called
		<i lang="ain-Latn">seta</i>
		in a prose tale is addressed as <i lang="ain-Latn">reyep</i> ‘creeping one’ in a prayer within
		that tale
		<Ref k="nakagawa2024" p="586–587, example 1252 and Table 87" />.
	</p>
	<p>
		<Xr ch="noun-incorporation-oblique-polysynthesis-debate">Complex incorporated words</Xr> can combine
		grammatical derivation with material serving the metre. Nakagawa analyzes the following Saru formation
		with incorporated <i lang="ain-Latn">pusa</i> ‘tassel’ and metrical <i lang="ain-Latn">kur</i>.
	</p>
	<Ex
		m="u-ko-pusa-kur-suypa"
		g="RECP-APPL-tassel-METR-shake.PL"
