<S t="Expanded verbs and person placement" id="expanded-verbs">
	<p>
		One expansion surrounds an intransitive base with middle
		<i lang="ain-Latn">ci-</i> and causative-shaped morphology. In Nakagawa's analysis, the
		resulting expression retains the original intransitive event while increasing its length
		<Ref k="nakagawa2024" p="590–591, §25.3.1" />.
	</p>
	<Ex
		m="atuy ruyanpe yupke hike ci-hopuni-re"
		g="sea storm be.strong one MID-rise-CAUS"
		tr="A fierce storm arose at sea."
		cite="nakagawa2024:590"
		dial="SAR"
		place="Example 1256, citing Kubodera 1977a:316"
		note="The source divides this into three lines. Its paraphrase describes the storm arising; the causative-shaped suffix does not introduce a separate external causer here."
	/>
	<p>
		Other expansions distribute person marking and lexical meaning over separate words. Nakagawa
		describes nominalized verbal material followed by person-marked <i lang="ain-Latn">ki</i>. In
		the next example, he analyzes the second <i lang="ain-Latn">ki</i> as metrical material <Ref
			k="nakagawa2024"
			p="599–600, §25.4.3"
		/>.
	</p>
	<Ex
		m="yaykomismu a=ki ki kusu"
		g="feel.lonely 4.A=do METR because"
		tr="Because I felt lonely…"
		cite="nakagawa2024:599"
		dial="CHI"
		place="Example 1302"
		note="The source has a line break after yaykomismu. The first ki is the person-marked verb; the following ki supplies metrical length in Nakagawa's account."
	/>
	<p>
		With transitive bases, he describes a related expansion using
		<i lang="ain-Latn">ci-</i> and person-marked
		<i lang="ain-Latn">ekarkar</i>. Its Chitose prose example shows that the construction extends
		beyond sung verse
		<Ref k="nakagawa2024" p="591–592, examples 1260–1261" />.
	</p>
</S>

<S t="Metrical additions and formula variation" id="metrical-material">
	<p>
		Nakagawa identifies metrical uses of
		<i lang="ain-Latn">ko</i>, <i lang="ain-Latn">konna</i>,
		<i lang="ain-Latn">kur</i>, and <i lang="ain-Latn">or</i>, including places where their usual
		lexical or grammatical relations are absent. The classification concerns those constructions; it
		does not make every occurrence of these forms semantically empty
		<Ref k="nakagawa2024" p="592–595" />.
	</p>
	<p>
		Formulaic wording also permits variation. Nakagawa compares two performances of the same Chitose
		tale, two years apart, with different ordering and elaboration of its sewing formulas. He treats
		these as alternative realizations of shared material
		<Ref k="nakagawa2024" p="614–615, examples 1333–1334" />. See <Xr
			ch="parallelism-couplets-and-word-pairs"
		/> and
		<Xr ch="sakehe-refrain-and-sung-verse-structure" />.
	</p>
</S>

