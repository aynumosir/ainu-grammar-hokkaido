<S t="What remains unspecified on the verb" id="tenselessness">
	<p>
		A clause can describe an earlier, current, or later situation without changing the verb into a
		past, present, or future inflection. Nakagawa calls this an absence of grammatical tense and
		explains how speakers nevertheless locate events through context and other expressions <Ref
			k="nakagawa2024"
			p="434–437"
		/>.
	</p>
	<Ex
		m="horkew kamuy utar anakne nisatta iwor or ta a=hopunpa-re"
		g="wolf deity PL TOP tomorrow hunting.ground place LOC 4.A=depart.PL-CAUS"
		tr="The wolf deities will be sent off tomorrow at the hunting ground."
		cite="nakagawa2024:434"
		dial="SAR"
		place="Example 965"
		note="The translation leaves the actor unexpressed, following the source. Nisatta ‘tomorrow’ locates the sending-off in the future."
	/>
	<p>
		Nakagawa explicitly considers the same sentence without
		<i lang="ain-Latn">nisatta</i>: it could then describe a sending-off already completed.
		Conversely, removing ‘yesterday’ from his gathering example allows a future reading
		<Ref k="nakagawa2024" p="435" />. These are his illustrative comparisons, showing how much
		interpretation the temporal expressions supply.
	</p>
</S>

<S t="The reference point of a time expression" id="reference-points">
	<p>
		Ma distinguishes expressions anchored to the time of speaking, expressions anchored to another
		reference time, and expressions identifying a calendar or seasonal time. His study uses
		published Saru and Chitose material and includes nouns and phrases under the broad heading
		“temporal adverbs” <Ref k="ma2024" p="177–178, §3" />.
	</p>
	<table>
		<thead><tr><th>Reference</th><th>Examples in Ma's description</th></tr></thead>
		<tbody>
			<tr
				><td>Time of speaking</td><td
					><i lang="ain-Latn">tane</i> ‘now’, <i lang="ain-Latn">tanto</i> ‘today’</td
				></tr
			>
			<tr
				><td>A time identified in the account</td><td
					><i lang="ain-Latn">ne etoho</i> ‘that day’, <i lang="ain-Latn">ne onuman</i> ‘that night’</td
				></tr
			>
			<tr
				><td>A named date or seasonal period</td><td
					>Calendar dates expressed with Japanese loans; seasonal expressions such as <i
						lang="ain-Latn">arhucuk</i
					> ‘early autumn’</td
				></tr
			>
		</tbody>
	</table>
	<p>
		The examples belong to Ma's respective classes <Ref k="ma2024" p="§§3.1–3.3" />. A reference
		time supplied inside a story need not be the moment at which the storyteller is speaking.
		Likewise, a date identifies a position on a calendar without inherently meaning ‘past’ or
		‘future’.
	</p>
	<p>
		Even ‘now’ covers an interval. Ma contrasts <i lang="ain-Latn">tane k=okere</i>
		‘I have just finished’ with <i lang="ain-Latn">tane ku=ye na</i> ‘I will say it now’, both
		quoted from Tamura. The first event precedes the utterance slightly; the second follows it <Ref
			k="ma2024"
			p="§3.1.1, examples 1–2"
		/>.
	</p>
</S>

<S t="Prospective and current situations" id="prospective">
	<p>
		Several constructions describe a situation as still ahead. Nakagawa lists
		<i lang="ain-Latn">kusu ne</i> for intention, <i lang="ain-Latn">oasi</i> for an expected
		occurrence, <i lang="ain-Latn">etokus</i> for intention or likelihood, and
		<i lang="ain-Latn">etokoyki</i> for preparation <Ref k="nakagawa2024" p="435" />. They preserve
		their particular meanings while contributing future reference.
	</p>
	<Ex
		m="niskur uekarpa kusu suy sirwen oasi"
		g="cloud gather because again weather.be.bad expected"
		tr="The clouds are gathering, so the weather will probably turn bad again."
		cite="nakagawa2024:435"
		dial="SAR"
		place="Example 967, citing Honda 2001:16"
	/>
	<p>
		Current situations can also be presented through a formal-noun ending. Nakagawa's Chitose canoe
		prayer uses <i lang="ain-Latn">sap=as siri ne</i> while the speaker and family are actually
		traveling downstream
		<Ref k="nakagawa2024" p="435, example 970" />. This use includes the speaker's own ongoing
		activity; the construction's full sensory and aspectual range is considered in <Xr
			ch="continuative-siri-siran-kane-an"
		/>.
	</p>
</S>

<S t="Completion relative to a time" id="completion">
	<p>
		Completed situations can be presented with <i lang="ain-Latn">a</i>,
		<i lang="ain-Latn">nisa</i>, or combinations such as <i lang="ain-Latn">wa okere</i>. In a
		context centered on the current utterance, completion naturally points to an earlier event <Ref
			k="nakagawa2024"
			p="436"
		/>.
	</p>
	<Ex
		m="k=oyra wa okere wa"
		g="1SG.A=forget CONJ finish FIN"
		tr="I have forgotten it."
		cite="nakagawa2024:436"
		dial="SAR"
		place="Example 974, citing Tamura 1984:56"
	/>
	<p>
		The reference time can shift. Nakagawa's next example uses
		<i lang="ain-Latn">ipe wa okere kor</i> for what a son habitually does whenever he finishes
		eating. Completion is repeated within that sequence of events
		<Ref k="nakagawa2024" p="436–437, example 975" />. It does not locate the whole account at one
		fixed distance before the moment of speaking.
	</p>
</S>

<S t="Tense labels in grammatical analysis" id="analyses">
	<p>
		The absence of obligatory tense inflection is compatible with different analyses of particular
		constructions. Satō describes <i lang="ain-Latn">a</i> through past and perfect meanings <Ref
			k="sato2008"
			p="187–188"
		/>. Yoshikawa assigns
		<i lang="ain-Latn">a</i> and <i lang="ain-Latn">aan</i> past-time properties alongside aspectual
		and evidential differences in the Saru/Chitose account
		<Ref k="yoshikawa2022" p="§5" />.
		<Xr ch="perfective-anterior-a" /> compares those interpretations with narrative-sequencing analyses.
		None requires a mandatory three-way tense paradigm on every verb.
	</p>
</S>
