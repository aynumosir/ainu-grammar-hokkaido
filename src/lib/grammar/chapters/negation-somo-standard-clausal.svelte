<S t="Two common negative constructions" id="patterns">
	<p>
		Many Hokkaido descriptions give two ordinary ways to negate a verbal predicate:
		<i lang="ain-Latn">somo</i> before the person-marked verb, or
		<i lang="ain-Latn">(ka) somo ki</i> after it. The person index remains on the lexical predicate <Ref
			k="sato2008"
			p="124"
		/><Ref k="nakagawa2024" p="407" />.
	</p>
	<Ex
		m="somo k=arpa"
		g="NEG 1SG.S=go.SG"
		tr="I do not go."
		cite="sato2008:124"
		dial="CHI"
		place="§15.2, teaching comparison"
	/>
	<Ex
		m="k=arpa ka somo ki"
		g="1SG.S=go.SG ADD NEG do"
		tr="I do not go."
		cite="sato2008:124"
		dial="CHI"
		place="§15.2, teaching comparison"
		note="The ADD gloss identifies ka; the source does not require an emphatic ‘even’ interpretation here."
	/>
	<p>
		Satō places preverbal <i lang="ain-Latn">somo</i> immediately before the verb in the ordinary
		pattern. This differs from the freer placement of prohibitive
		<i lang="ain-Latn">iteki</i>
		<Ref k="sato2008" p="124" />. The negative construction itself does not select an English
		present or past tense.
	</p>
</S>

<S t="Ka and the analysis of somo ki" id="analysis">
	<p>
		Nakagawa allows the postverbal construction with or without
		<i lang="ain-Latn">ka</i>, and says that the negative examples need not carry its usual additive
		or unexpectedness meaning <Ref k="nakagawa2024" p="407" />. Satō similarly questions whether
		strong emphasis belongs to every negative use
		<Ref k="sato2008" p="124" />.
	</p>
	<Ex
		m="nep a=nukar ka somo ki korka"
		g="what 4.A=see ADD NEG do CONJ"
		tr="Although I saw nothing, …"
		cite="nakagawa2024:407"
		dial="SAR"
		place="Example 833"
		note="Ka follows the verb. It is not adjacent to nep in this sentence."
	/>
	<p>
		The structural accounts also differ. Satō proposes treating
		<i lang="ain-Latn">somo ki</i> as a single auxiliary, comparing its position and lack of person
		inflection with other auxiliaries
		<Ref k="sato2008" p="86" />. Bugaeva describes an emphatic construction in which the preceding
		predicate functions as an object noun phrase of <i lang="ain-Latn">ki</i>
		<Ref k="bugaeva2012" p="496" />. The surface pattern is well documented; constituency and
		obligatory emphasis are not described identically by these authors.
	</p>
</S>

<S t="Nominal predicates and evidential scope" id="scope">
	<p>
		A nominal predicate normally places <i lang="ain-Latn">(ka) somo</i> before copular
		<i lang="ain-Latn">ne</i>. Satō contrasts this with postverbal
		<i lang="ain-Latn">ka somo ki</i> and notes that
		<i lang="ain-Latn">ne ka somo ki</i> is very uncommon in his description
		<Ref k="sato2008" p="22" />.
	</p>
	<p>
		An evidential ending can follow a negated predicate. Nakagawa's
		<i lang="ain-Latn">a=isamka ka somo ki ruwe ne</i> presents not losing something as the content
		of the assertion. His contrasting
		<i lang="ain-Latn">ruwe somo ne</i> example is rhetorical confirmation; Tamura also records
		ordinary denial with that copular-negative shape
		<Ref k="nakagawa2024" p="393, examples 779–780" /><Ref k="tamura1997" p="71" />. See <Xr
			ch="ruwe-ne-inferential"
		/> for the contextual distinction.
	</p>
</S>

<S t="Regional forms and limits of the general pattern" id="regional">
	<p>
		Nakagawa records <i lang="ain-Latn">omo</i> in eastern varieties,
		<i lang="ain-Latn">henne</i> in Shizunai and Samani examples,
		<i lang="ain-Latn">senne</i> in Horobetsu, and Tokachi
		<i lang="ain-Latn">sien</i> alongside the wider <i lang="ain-Latn">somo</i>
		pattern <Ref k="nakagawa2024" p="407–408" />. He questions an exclusively rhetorical
		interpretation of
		<i lang="ain-Latn">sien</i> and distinguishes idiomatic
		<i lang="ain-Latn">sem</i>, whose status as prefix or adverb is disputed.
	</p>
	<p>
		Takahashi calls ordinary Tokachi preverbal negation symmetric: the positive
		<i lang="ain-Latn">ruyanpe ruy</i> ‘it rained’ becomes
		<i lang="ain-Latn">ruyanpe somo ruy</i> ‘it did not rain’, without another structural change <Ref
			k="takahashi2016"
			p="75, §3, examples 11a–b"
		/>. His separate restrictions on negative temporal clauses have a narrower domain than that
		main-clause description.
	</p>
	<p>
		Negative linkage varies too. Nakagawa prints Shiranuka
		<i lang="ain-Latn">omo an=ki wa okay=an</i>, with
		<i lang="ain-Latn">wa</i> after a negative predicate
		<Ref k="nakagawa2024" p="408, example 835" />. See <Xr ch="sequential-wa-and-clause-chaining" /> for
		the construction-specific comparisons. Lexical absence and inability receive separate treatment in
		<Xr ch="negation-existential-possessive-isam" /> and
		<Xr ch="negation-ability-cognition-predicates" />.
	</p>
</S>
