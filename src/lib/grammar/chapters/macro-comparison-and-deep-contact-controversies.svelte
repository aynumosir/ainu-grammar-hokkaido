<S t="Relationship, contact, and resemblance" id="evidence">
	<p>
		Ainu has no established external genetic affiliation. This describes the present evidential
		position; it does not make a relationship impossible in principle. Proposed ancestry, borrowing,
		and chance resemblance require different tests. Repeated sound correspondences, comparable
		meanings, morphology, and a plausible history matter more than isolated similar words <Ref
			k="shibatani1990"
			p="3–7"
		/>;
		<Ref k="alonso2022" p="§1" />.
	</p>
	<p>
		The documented Ainu varieties provide a firmer comparative starting point than a proposed
		distant relative. Reconstructions must still account for Hokkaido, Sakhalin, and Kuril evidence
		on their own terms; see <Xr ch="proto-ainu-segmental-reconstruction" />.
	</p>
</S>

<S t="External-affiliation proposals" id="affiliation">
	<p>
		Shibatani reviews proposals connecting Ainu with Japanese, Altaic, and other languages. His
		account says Chamberlain rejected a Japanese or Altaic affinity. It also reports differing
		assessments of Patrie's 1982 reconstruction, with Miller more encouraging and Street
		unfavorable. <Ref k="shibatani1990" p="5–7" />.
	</p>
	<p>
		Bugaeva regards southern connections as plausible while withholding endorsement of the
		particular Austroasiatic hypothesis. Alonso criticizes the influence of that hypothesis on
		Vovin's 1993 Proto-Ainu reconstruction and treats the internal reconstruction separately <Ref
			k="bugaeva2012"
			p="462"
		/>;
		<Ref k="alonso2022" p="§1" />. Alonso's roughly thousand-year working depth belongs to his
		reconstruction discussion; it is not a universally established limit on how far Ainu history can
		be investigated.
	</p>
</S>

<S t="Early Japanese contact: a disputed extent" id="japanese-contact">
	<p>
		Vovin argues for Ainu influence on Old Japanese, including proposed lexical and grammatical
		borrowing. His grammatical comparisons include the focus particle <i>ka</i> and the negator
		<i lang="ain-Latn">somo</i>. These are contact proposals, not claims that the two languages
		descend from an immediately shared ancestor <Ref k="vovin2022" p="§2" />.
	</p>
	<p>
		The extent of the proposed influence is disputed. Bugaeva states that Ainu has not affected
		Japanese grammar, while proposing Japanese influence on several Ainu constructions
		<Ref k="bugaeva2012" p="498–499, §§15.5–15.6" />. That position differs from Vovin's later
		account. Similar constructional meanings alone cannot decide between borrowing, independent
		development, and inherited structure.
	</p>
	<p>
		Vovin's individual etymologies also involve philological choices. His discussion of <i>kuta</i>
		and Ainu
		<i lang="ain-Latn">kotan</i> supplies semantic parallels; his place-name discussion considers
		alternative analyses of
		<i>Nipu</i> and difficulties with <i>Unapî</i>. The latter includes the problem that the
		relevant Rokkō setting is not volcanic <Ref k="vovin2022" p="§§4–5" />. The more recent loans
		and place-name evidence are introduced in <Xr ch="ainu-loanwords-and-toponymy-in-japanese" />.
	</p>
</S>

<S t="Archaeology and language history" id="archaeology">
	<p>
		Janhunen proposes an ethnolinguistic history linking Ainu development with changes associated
		with Jōmon, Satsumon, and neighboring populations. He allows multiple unknown linguistic
		lineages in the Jōmon setting and does not identify Ainu as the only substrate
		<Ref k="janhunen2022" p="§3(3a–c), §4" />.
	</p>
	<p>
		Archaeological continuity and material exchange help constrain such histories, but neither
		directly records a spoken language. Population history, cultural transmission, and language
		transmission can follow different paths. Proposed dates in these reconstructions should
		therefore remain attached to the author's argument, rather than becoming dates of independently
		attested Ainu speech.
	</p>
</S>

<S t="What comparison can establish" id="limits">
	<p>
		A well-supported loan can establish contact without establishing common ancestry. A regional
		sound correspondence can support Proto-Ainu reconstruction without resolving an external
		affiliation. A place name can preserve an older linguistic layer while leaving its exact date
		and donor variety uncertain. These distinctions let the evidence be compared without forcing all
		of it into one history. For item-specific northern borrowing arguments, see
		<Xr ch="northern-contact-nivkh-tungusic-manchu" />.
	</p>
</S>
