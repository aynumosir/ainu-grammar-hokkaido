<S t="Respectful address and the fourth-person series" id="honorific">
	<p>
		Fourth-person forms can address a person respectfully. In this use, the Saru forms are
		<i lang="ain-Latn">a=</i> for a transitive subject, <i lang="ain-Latn">=an</i> for an
		intransitive subject, and <i lang="ain-Latn">i=</i> for an object. Tamura treats this as
		second-person honorific, a semantic category sharing forms with other person categories
		<Ref k="tamura1972" p="28–30, §2.11" />. Nakagawa groups it among the uses of fourth person
		<Ref k="nakagawa2024" p="174–176" />. The broader series is described in
		<Xr ch="indefinite-fourth-person-paradigm" />.
	</p>
	<p>
		A single addressee can take a plural verb. The following Tokachi example addresses the speaker's
		husband with two plural motion stems <Ref k="takahashi2015" p="208, example 5" />.
	</p>
	<Ex
		m="anokay enon paye=an tek tap osippa=an ru an a"
		g="4 where.to go.PL=4.S CONJ EMPH return.PL=4.S NMLZ exist FIN"
		tr="Where have you been and come back from?"
		cite="takahashi2015:208"
		dial="TOK"
		place="Example 5; address to a husband"
		note="Accent marks omitted and person boundaries normalized. Takahashi calls this the inclusive-person series."
	/>
</S>

<S t="Relationships and speaker differences" id="social-context">
	<p>
		Tamura's Saru account associates the honorific especially with women's address to adult men. It
		also records family exceptions: mothers addressing sons and older sisters addressing younger
		brothers can retain ordinary second-singular forms after the men reach adulthood
		<Ref k="tamura1972" p="28–29" />. Her consultants also differ over respectful address to women.
		Hattozawa Fujino allows honorific address in some such circumstances; Hiraga Sada describes
		ordinary second person even toward a woman of high status
		<Ref k="tamura1972" p="30" />.
	</p>
	<p>
		The age at which address changes is consequently part of a speaker's reported practice. Tamura
		explicitly cautions against treating one consultant's approximate age threshold as a precise
		general rule <Ref k="tamura1972" p="29" />. Nakagawa similarly presents the gender and status
		associations as tendencies and records uses outside the most frequent pattern <Ref
			k="nakagawa2024"
			p="176, 530"
		/>.
	</p>
</S>

<S t="Prayer and regional alternatives" id="dialects">
	<p>
		Fourth-person address occurs in prayers, but the addressee's being a deity does not determine
		the person form. Nakagawa juxtaposes Saru prayers from the same speaker that use fourth person
		for a protective deity and ordinary second person for the tsunami deities
		<Ref k="nakagawa2024" p="176, examples 142–143" />. The choice has to be understood within the
		particular address tradition.
	</p>
	<p>
		Ishikari differs from the Saru pattern. Tamura describes ordinary respectful singular address
		with the second-plural series, including the pronoun <i lang="ain-Latn">esokay</i>, and
		fourth-person <i lang="ain-Latn">anokay</i> for a higher level of respect. Her Ishikari
		consultant allows both toward a husband. Saru second-plural
		<i lang="ain-Latn">ecioka</i> lacks that corresponding honorific use in her account
		<Ref k="tamura1972" p="30" />. Nakagawa summarizes the regional contrast through Tamura's later
		description <Ref k="nakagawa2024" p="530, citing Tamura 1988a:22–23" />.
	</p>
	<p>
		For Tokachi, Takahashi records honorific singular <i lang="ain-Latn">anokay</i> and reports
		<i lang="ain-Latn">anutari</i> for several addressees. He notes that the latter honorific use
		was not recorded in a sentence example in his material
		<Ref k="takahashi2015" p="208" />. Refsing's Shizunai description also emphasizes address
		through status nouns <Ref k="refsing1986" p="218" />.
	</p>
</S>

<S t="Honorific objects and different referents" id="object">
	<Ex
		m="taampe a=i=kore ruwe"
		g="this 4.A=4.O=give NMLZ"
		tr="Was this given to you?"
		cite="tamura1972:28"
		dial="SAR"
		place="Example 57"
		note="Accent and glottal-onset notation normalized. The source gloss identifies an indefinite giver and an honorifically addressed recipient."
	/>
	<p>
		Both indexes in this example belong to the series called fourth person here, yet they refer to
		different participants and have different functions. Tamura uses such combinations in her
		argument for distinguishing the semantic categories. When subject and object are the same
		participant, reflexive derivation is relevant instead
		<Ref k="tamura1972" p="35" />. A common numerical label for two forms does not make their
		referents identical.
	</p>
</S>

<S t="Honorific, narrative, and quoted-speaker reference" id="other-functions">
	<p>
		Honorific address refers to the listener. Narrative fourth person follows a character's
		perspective, while quoted-speaker uses represent someone else's words or thoughts. These
		functions can differ in verbal number: Saru/Chitose honorific singular takes plural stems,
		whereas a singular narrator or quoted speaker can take singular stems
		<Ref k="nakagawa2024" p="176, 178–180" />;
		<Ref k="bugaeva2012" p="475–476" />.
	</p>
	<p>
		Quoted-speaker marking also depends on dialect and whose speech is repeated. Nakagawa notes
		ordinary first person in self-quotation by the current speaker
		<Ref k="nakagawa2024" p="471, example 1087" />. Takahashi's everyday Tokachi data retain
		ordinary first person in reported speech, although literary passages may switch person series
		<Ref k="takahashi2015" p="207, 210–211" />. These distributions keep the honorific analysis
		distinct from an unrestricted rule about all represented speech.
	</p>
</S>
