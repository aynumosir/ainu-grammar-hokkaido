<S t="The spoken record" id="overview">
	<p>
		Recordings and editions of oral literature supply connected speech: a construction can be read
		in the story, exchange, or performance in which it occurred. They preserve information that an
		isolated dictionary example may leave open, including who is speaking, what a pronoun refers to,
		and how a speaker introduces another person's words. Ainu has an extensive recorded and written
		documentary record, though its coverage varies considerably by region and genre
		<Ref k="nakagawa2024" p="14, 101" />; <Ref k="endo2022" p="§5" />.
	</p>
	<p>
		A performance, its recording, its transcription, and a later annotated edition are related
		sources. Each preserves different evidence. Audio is needed to investigate delivery and
		intonation; an editor's word division or translation records an interpretation of the
		performance. The source note attached to an example identifies the edition used and, where
		available, the speaker and recording.
	</p>
</S>

<S t="The documentary tradition" id="tradition">
	<S t="Chiri Yukie's collection" id="chiri-yukie">
		<p>
			Chiri Yukie's <em>Ainu Shin'yōshū</em>, published in 1923, contains thirteen divine songs in
			Ainu with her Japanese translations <Ref k="chiri1923" />. Her work belongs to the history of
			Ainu speakers writing and publishing their own language, alongside the extensive recording of
			oral literature by Kannari Matsu <Ref k="ono2022" p="§3" />. Chiri's Latin transcription also
			matters for the history of writing: it distinguishes syllable-final
			<em>r</em> from <em>r</em> followed by a vowel, a distinction obscured in Batchelor's spelling <Ref
				k="nakagawa2024"
				p="55"
			/>.
		</p>
		<p>
			A printed song preserves its wording and the author's arrangement of the text. Its
			punctuation, line breaks, and refrain spelling require interpretation when used as evidence
			for syntax or pronunciation. The conventions of a modern transcription should therefore be
			checked against the edition being cited; see
			<Xr ch="historical-orthographies-and-the-batchelor-tradition" />.
		</p>
	</S>
	<S t="Recordings and local text series" id="postwar">
		<p>
			From the 1980s, institutions in Hokkaido regularly published text collections prepared by
			transcribing recordings and adding Japanese translations. Nakagawa surveys these series as a
			substantial source of material from different dialects
			<Ref k="nakagawa2024" p="101" />. Ōno places recording and publication within the wider
			history of community language work, including Kayano Shigeru's activities and exchanges
			between speakers and researchers <Ref k="ono2022" p="§§4–5" />.
		</p>
		<p>
			Publication date and recording date answer different questions. A recently edited text may
			preserve a performance recorded decades earlier. For dialect comparison, the speaker's
			language history and the circumstances of the recording are usually more informative than the
			publisher's location.
		</p>
	</S>
	<S t="Audio with transcription and glosses" id="recent">
		<p>
			Other collections frequently cited in this grammar include the Ainu materials published
			by the Research Institute for Languages and Cultures of Asia and Africa at Tokyo
			University of Foreign Studies (ILCAA), and the Ainu-language and oral-literature
			materials of the Nibutani Ainu Culture Museum in Biratori. Endō lists both among the
			online resources accompanying the documentary record <Ref k="endo2022" p="§1 and references" />.
			Their individual texts need their own speaker, dialect, and recording attributions.
		</p>
		<p>
			NINJAL hosts <em>A Glossed Audio Corpus of Ainu Folklore</em>, edited by Nakagawa, Bugaeva,
			Kobayashi, and Yoshikawa <Ref k="glossedcorpus2016" />. Its Japanese and English titles refer
			to the same resource. The introduction dated 22 February 2021 describes Saru materials
			narrated by Kimura Kimi and Chitose materials narrated by Oda Ito. Kimura's recordings were
			made by Nakagawa in 1977–1983; Oda's were made by Bugaeva in 1999–2000. The audio,
			transcription, glosses, and translations can be consulted together on the
			<a href="https://ainu.ninjal.ac.jp/folklore/">corpus website</a>.
		</p>
		<p>
			These materials allow a reader to examine the context of a cited passage and compare the
			printed analysis with the recording. Their dialect coverage remains the coverage of the named
			speakers. Combining them in one searchable collection does not make every form common to Saru
			and Chitose.
		</p>
	</S>
</S>

