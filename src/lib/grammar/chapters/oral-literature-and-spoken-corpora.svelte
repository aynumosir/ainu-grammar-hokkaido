<S t="Genre and grammatical interpretation" id="grammar-and-genre">
	<p>
		Oral literature includes heroic epics, divine songs, prose narratives, and other forms whose
		names and conventions vary regionally <Ref k="endo2022" />. A genre label gives useful context,
		but grammatical interpretation still depends on the passage. The speaker introducing a story,
		the character whose experiences it recounts, and a character quoted within it can occupy
		different speech roles.
	</p>
	<p>
		Person marking is particularly sensitive to these distinctions. Bugaeva describes the use of the
		indefinite or fourth-person forms for a narrator's first-person reference in oral literature,
		alongside their other uses <Ref k="bugaeva2022" p="Ch. 1, §4.1" />. Consequently, a gloss
		identifying a person form cannot by itself determine the English pronoun in a literary
		translation. The dialect, narrator, and surrounding discourse belong in the analysis; see <Xr
			ch="logophoric-narration-and-reported-discourse"
		/> and
		<Xr ch="oral-literature-genre-taxonomy" />.
	</p>
</S>

<S t="Uneven coverage" id="coverage">
	<p>
		Endō describes a pronounced regional imbalance in the surviving oral-literature materials:
		Hidaka and Iburi are richly represented, while northern and eastern Hokkaido have much less
		material <Ref k="endo2022" p="§5" />. The distribution of examples in a collection can therefore
		reflect the history of documentation as much as the distribution of a construction.
	</p>
	<p>
		A long narrative from one speaker offers many occurrences within one linguistic setting. It
		offers fewer grounds for a claim about variation across speakers or dialects. Frequency
		comparisons need a defined sample, with genre and speaker composition stated; the relevant
		counting choices are described in <Xr ch="dialect-sample-and-corpus-method" />.
	</p>
</S>

<S t="Reading an edited performance" id="philological">
	<p>
		The transcription and translation should be read together. An editor may divide a sequence into
		words, restore a contextually understood participant in translation, or normalize an older
		spelling. Such decisions can be reasonable while still affecting an argument about word
		boundaries, omitted arguments, or sound structure. A grammatical claim needs the Ainu passage as
		well as the translation.
	</p>
	<p>
		Audio can help resolve a reading, though recording quality and the performance itself may leave
		uncertainty. Where editions disagree, the variants should remain attributable to their sources.
		Questions about refrain structure, parallel phrasing, and ritual language receive separate
		treatment in <Xr ch="sakehe-refrain-and-sung-verse-structure" />,
		<Xr ch="parallelism-couplets-and-word-pairs" />, and
		<Xr ch="honorific-ritual-and-taboo-registers" />.
	</p>
</S>
