<S t="Connective words and clause endings" id="connective-words">
	<p>
		A connection between clauses can be expressed at the end of the first clause or by an expression
		introducing the next. Nakagawa groups
		<i lang="ain-Latn">orowa</i> and related words among adverbs. Unlike connective particles, these
		words need not follow a verb phrase directly; they can follow an existing connective
		<Ref k="nakagawa2024" p="516–517, §21.2.3" />.
	</p>
	<p>
		Refsing calls the corresponding Shizunai expressions conjunctions. Her statement that Ainu has
		no “genuine” conjunctions concerns the absence of morphemes exclusively serving that function in
		her classification. She nevertheless describes their connective use, including temporal,
		simultaneous, and conditional relations
		<Ref k="refsing1986" p="128–131, §12.6.1" />. The principal clause endings appear in
		<Xr ch="clause-linkage-overview" />.
	</p>
	<Ex
		m="ipe orwa hosipi"
		g="eat then return"
		tr="Eat, and then go home!"
		cite="refsing1986:129"
		dial="SHI"
		place="Example 138"
		note="Refsing's spelling orwa is retained. Both verbs have the bare imperative form."
	/>
</S>

<S t="The orowa family" id="orowa">
	<p>
		Nakagawa lists <i lang="ain-Latn">orowa</i>,
		<i lang="ain-Latn">orowano</i>, <i lang="ain-Latn">orowaun</i>,
		<i lang="ain-Latn">ora</i>, and <i lang="ain-Latn">oraun</i>, with contextual meanings such as
		‘and’, ‘then’, and ‘so’. He traces the family to positional <i lang="ain-Latn">or</i>
		and ablative <i lang="ain-Latn">wa</i>. Expressions combining
		<i lang="ain-Latn">hi</i> with <i lang="ain-Latn">orano</i> or
		<i lang="ain-Latn">orowano</i> can retain a ‘from’ or ‘since’ meaning
		<Ref k="nakagawa2024" p="517, examples 1187–1188" />.
	</p>
	<Ex
		m="hi kusu ora nonno piye a=hok hine orowano nea HAKO asama a=opusi kuni a=ye"
		g="NMLZ because then flower seed.POSS 4.A=buy CONJ then that box bottom.POSS 4.A=make.holes NMLZ 4.A=say"
		tr="So I bought flower seeds, then told someone to make holes in the bottom of the box."
		cite="nakagawa2024:517"
		dial="SAR"
		place="Example 1187"
		note="Ora follows kusu and orowano follows hine. The source capitalizes the Japanese loan HAKO. The prospective complement reports an instruction."
	/>
	<p>
		Connective expressions do not prescribe a fixed pause pattern. Refsing describes junctures that
		vary with cohesion, phrase length, and speech rate. She also records connectors after
		conjunctionalizers, and conjunctionalizers separated from the preceding predicate by a pause
		<Ref k="refsing1986" p="128–131" />. Repetition around narrative transitions is treated in
		<Xr ch="tail-head-linkage-and-narrative-cohesion" />.
	</p>
</S>

<S t="Rapok and overlapping situations" id="rapok">
	<p>
		Expressions built on <i lang="ain-Latn">rapok</i> relate situations as ‘during’, ‘while’, or
		‘meanwhile’. Nakagawa distinguishes a positional-noun construction with
		<i lang="ain-Latn">ta</i>
		from adverbial <i lang="ain-Latn">rapokke</i>. His first example places a contemplated action
		during the in-laws' sleep; the second introduces a pregnancy noticed while a woman is caring for
		her grandmother
		<Ref k="nakagawa2024" p="517–518, examples 1189–1190" />.
	</p>
	<p>
		Refsing's Shizunai <i lang="ain-Latn">rapoketa</i> likewise links simultaneous situations. Her
		example has one person's speech occurring while other things are being said nearby
		<Ref k="refsing1986" p="130, example 142" />.
	</p>
</S>

<S t="Coordination within a phrase" id="nominal-coordination">
	<p>
		Coordination of nouns has its own constructions, described in
		<Xr ch="noun-phrase-structure" />. Kindaichi and Chiri analyze
		<i lang="ain-Latn">newa</i> historically as
		<i lang="ain-Latn">ne</i> plus <i lang="ain-Latn">wa</i>
		<Ref k="kindaichi1936" p="140" />. Nakagawa records nominal coordination with
		<i lang="ain-Latn">usa</i> in Tokachi and Kushiro. In his Tokachi
		<i lang="ain-Latn">iku usa ipe usa ki</i> ‘drink and eat’, he analyzes ‘drinking’ and ‘eating’
		as coordinated nominal objects of
		<i lang="ain-Latn">ki</i> ‘do’
		<Ref k="nakagawa2024" p="324, example 537, citing Ainu Museum 1994:14" />.
	</p>
</S>
