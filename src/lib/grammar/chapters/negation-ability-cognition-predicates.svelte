<S t="Lexical meanings of inability and ignorance" id="meanings">
	<p>
		Several verbs include a negative meaning in their lexical sense. Tamura's Saru dictionary
		distinguishes inability, lack of familiarity or experience, and lack of knowledge or
		understanding <Ref k="tamura1996" p="s.vv. eaykap, eramiskari, erampewtek" />.
	</p>
	<table>
		<thead><tr><th>Predicate</th><th>Principal contrast in the dictionary</th></tr></thead>
		<tbody>
			<tr
				><td><i lang="ain-Latn">eaykap</i></td><td
					>Be unable or unskilled; counterpart <i lang="ain-Latn">easkay</i>.</td
				></tr
			>
			<tr
				><td><i lang="ain-Latn">eramiskari</i></td><td
					>Not know or recognize someone; have no experience of something; counterpart <i
						lang="ain-Latn">amkir</i
					>.</td
				></tr
			>
			<tr
				><td><i lang="ain-Latn">erampewtek</i></td><td
					>Not understand or possess the relevant knowledge; counterparts <i lang="ain-Latn"
						>eraman</i
					>, <i lang="ain-Latn">eramuan</i>.</td
				></tr
			>
		</tbody>
	</table>
	<p>
		The English word ‘know’ overlaps several of these distinctions. Tamura explicitly contrasts not
		recognizing a person with not understanding something <Ref
			k="tamura1996"
			p="s.vv. eramiskari and erampewtek"
		/>.
	</p>
</S>

<S t="Independent predicates and auxiliary uses" id="structure">
	<p>
		A person index on the negative verb identifies an independent-predicate use. When the same form
		follows a person-marked verb as an auxiliary, it adds a meaning to that preceding event.
		Nakagawa's table distinguishes the two uses
		<Ref k="nakagawa2024" p="314–315, table 75" />.
	</p>
	<Ex
		m="nikar kari ku=hemesu ka eramuskari"
		g="ladder via 1SG.S=climb ADD never.have.done"
		tr="I have never climbed a ladder."
		cite="sato2008:90"
		dial="CHI"
		place="§9.4, auxiliary-use examples"
	/>
	<p>
		Compare Nakagawa's Saru <i lang="ain-Latn">a=kar erampewtek</i>, used by a narrator who had not
		known about making a pole for displaying the bear's skull
		<Ref k="nakagawa2024" p="315, example 489" />. The relevant ignorance concerns the action or
		practice described by the preceding predicate. Chitose <i lang="ain-Latn">eramuskari</i> and
		Ishikari
		<i lang="ain-Latn">eramuskare</i> are among the variants in the source examples
		<Ref k="nakagawa2024" p="314–315, examples 487–488" />.
	</p>
</S>

<S t="Capacity and circumstances" id="ability">
	<p>
		<i lang="ain-Latn">Eaykap</i> has a broad range covering ability and other obstacles. Tamura
		particularly associates <i lang="ain-Latn">koyaykus</i>
		with circumstances or current conditions. Her example comments on a child who has grown too heavy
		to lift <Ref k="tamura1996" p="s.vv. eaykap and koyaykus" />.
	</p>
	<Ex
		m="ku=puni koyaykus"
		g="1SG.A=lift be.unable"
		tr="I can't lift [the child]."
		cite="tamura1996"
		dial="SAR"
		place="s.v. koyaykus, excerpt from an S example"
		note="The preceding words express surprise at the child's weight. The dictionary identifies the utterance as praise of the child's growth."
	/>
	<p>
		These descriptions do not make circumstances the exclusive domain of
		<i lang="ain-Latn">koyaykus</i>. For further distinctions involving completion, inclination, and
		endurance, see <Xr ch="abilitative-easkay-eaykap" />.
	</p>
</S>

<S t="Dialect and register limits" id="variation">
	<p>
		Satō finds independent <i lang="ain-Latn">a=eaykap</i> in literary Chitose, while reporting no
		ordinary colloquial <i lang="ain-Latn">k=eaykap</i> in his material. He proposes a stylistic
		factor in the difference
		<Ref k="sato2008" p="90" />.
	</p>
	<p>
		Refsing finds Shizunai <i lang="ain-Latn">koyaykus</i>,
		<i lang="ain-Latn">maka</i>, and <i lang="ain-Latn">nukuri</i> only as auxiliaries, without
		intervening <i lang="ain-Latn">ka</i>, in her sample
		<Ref k="refsing1986" p="211, §14.9.4.9" />. Tamura and Nakagawa describe transitive uses in Saru
		for some of these forms. The lexical entries and constructional distributions need to be kept
		with their respective dialect and register evidence.
	</p>
</S>
