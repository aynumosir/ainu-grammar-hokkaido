	<p>
		In <i lang="ain-Latn">repni</i>, <i lang="ain-Latn">rep</i> means “beat time” and
		<i lang="ain-Latn">ni</i>
		“wood.” The wood is neither its subject nor an object of this intransitive verb. Nakagawa
		follows the pseudo-modification account: verbal material is used nominally, allowing a broader
		semantic relation between the parts <Ref k="nakagawa2024" p="268" />. Satō develops the same
		issue with
		<i lang="ain-Latn">pe-ta-ru</i> “path for fetching water”
		<Ref k="sato2008" p="267–268" />.
	</p>
	<S t="A possessed part as subject" id="type-five">
		<p>
			In Type V, the affiliative noun is the subject of the property verb. The resulting name refers
			to its possessor: <i lang="ain-Latn">ami-tanne</i> “crab” combines “its claws” and “long”;
			<i lang="ain-Latn">teke-tanne</i>
			“thief” combines “its hands” and “long” <Ref k="nakagawa2024" p="271–272" />. Kindaichi and
			Chiri also describe the possessed first element in this pattern
			<Ref k="kindaichi1936" p="171, §222" />.
		</p>
	</S>
	<S t="An incorporated object" id="type-six">
		<p>
			In Type VI, the noun fills the object role of a two-place transitive verb. Nakagawa analyzes
			<i lang="ain-Latn">cikap-koyki</i> “hawk” from “bird” and “attack, bully.” Object
			incorporation produces a one-place verb, and nominal conversion produces the lexical name <Ref
				k="nakagawa2024"
				p="272"
			/>. The underlying operation is described in <Xr ch="noun-incorporation-object" />.
		</p>
	</S>
</S>

<S t="Interpretation and internal structure" id="semantics">
	<S t="Attributive relations" id="sem-attributive">
		<p>
			A compound's meaning can identify a kind, a use, or a characteristic. In
			<i lang="ain-Latn">tokapipe</i> “lunch,” “daytime” qualifies the nominal use of “eat.”
			Nakagawa also records verbal <i lang="ain-Latn">ku=tokapipe</i>
			“I eat lunch” <Ref k="nakagawa2024" p="270–271" />. The lexical formation can thus participate
			in both nominal and verbal constructions.
		</p>
	</S>
	<S t="Names containing kor and kur" id="sem-possessive">
		<p>
			Tamura records <i lang="ain-Latn">cisekorkur</i> “householder” and
			<i lang="ain-Latn">kotankorkur</i> “village head,” with corresponding separated forms <Ref
				k="tamura1996"
				p="s.vv. cisekorkur, kotankorkur"
			/>. Shibatani presents <i lang="ain-Latn">kotan kor-kur</i> in his treatment of nominalization <Ref
				k="shibatani1990"
				p="33, example 40b"
			/>. These analyses connect lexical names with the relative-head use of
			<i lang="ain-Latn">kur</i> “person.”
		</p>
	</S>
	<S t="Compounds and explicit clause relations" id="sem-attribution-scope">
		<p>
			Nakagawa contrasts the plant name <i lang="ain-Latn">wakkakukuttar</i> with
			<i lang="ain-Latn">ani wakka ku kuttar</i> “the hollow-stemmed plant with which someone drank
			water.” The modifying clause retains the instrumental expression <i lang="ain-Latn">ani</i>;
			the compound expresses the associated use through lexical composition <Ref
				k="nakagawa2024"
				p="269"
			/>.
		</p>
	</S>
	<S t="Possessor and actor names" id="sem-other">
		<p>
			The names in Types V–VI can refer to the possessor of a body part or the actor of an
			incorporated-verb formation. Their referent need not be denoted by an independent nominal head
			inside the word
			<Ref k="nakagawa2024" p="271–272" />. The modifier–head description of ordinary noun–noun
			compounds therefore has a narrower domain than the full six-type classification.
		</p>
	</S>
</S>

<S t="Lexicalization at the phrase boundary" id="compound-phrase">
	<p>
		Satō treats <i lang="ain-Latn">amip</i> “clothing” as a lexical item derived from
		<i lang="ain-Latn">a-mi p</i>
		“what one wears,” retaining person-marked material characteristic of a phrase. He leaves forms
		such as
		<i lang="ain-Latn">kamuy-e-p</i> “bear food” difficult to classify decisively
		<Ref k="sato2008" p="269" />. Nakagawa likewise notes continuing relative-clause properties in
		<i lang="ain-Latn">amip</i>
		and <i lang="ain-Latn">aep</i>
		<Ref k="nakagawa2024" p="507" />. These formations are discussed further in
		<Xr ch="deverbal-denominal-noun-derivation" />.
	</p>
</S>
