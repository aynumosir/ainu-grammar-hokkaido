<S t="Compounds and phrases" id="overview">
	<p>
		A nominal compound combines lexical material into a noun. Its internal structure can differ from
		that of a syntactic noun phrase. Nakagawa distinguishes noun–noun patterns from formations that
		first produce a one-place verb and then use it nominally
		<Ref k="nakagawa2024" p="264–272" />. His account follows Kirikae's analysis of modification and
		pseudo-modification, recast through his own arity framework.
	</p>
	<p>
		Satō likewise distinguishes ordinary clause modification from compound formation, while
		recognizing words derived historically from phrases
		<Ref k="sato2008" p="267–269" />. Lexicalization and grammatical structure interact, so a
		conventional lexical meaning need not erase every property of the original construction.
	</p>
</S>

<S t="Evidence for a word boundary" id="diagnostics">
	<p>
		Nakagawa uses person-marker position, affiliative endings, lexicalized meaning, and the
		combination of conceptual noun forms as diagnostics. Their usefulness varies with the
		construction. Sound alternations alone are inconclusive because they also occur across word
		boundaries <Ref k="nakagawa2024" p="264–266" />.
	</p>
	<S t="Person-marker position" id="diag-person-affix">
		<p>
			In <i lang="ain-Latn">poro a=yupi</i> “my big elder brother,” the person marker follows
			<i lang="ain-Latn">poro</i>. In the corresponding compound
			<i lang="ain-Latn">a=poroyupi</i>, it precedes the whole formation
			<Ref k="nakagawa2024" p="265" />. Since intransitive
			<i lang="ain-Latn">poro</i> takes S marking, Nakagawa interprets the initial A-series marker in
			the latter as belonging to the nominal compound.
		</p>
	</S>
	<S t="Affiliative endings" id="diag-affiliative">
		<p>The position of a possessive ending can identify a different grouping:</p>
		<Ex
			m="a=mac-i utar"
			g="4.A=wife-POSS PL"
			tr="my wives"
			cite="nakagawa2024:265"
			place="Hokkaido, dialect not specified"
			note="Nakagawa's phrase example and contextual first-person translation; mat appears as mac before i."
		/>
		<Ex
			m="a=mat-utar-i"
			g="4.A=wife-PL-POSS"
			tr="my wives"
			cite="nakagawa2024:265"
			place="Hokkaido, dialect not specified"
			note="Nakagawa's compound example, with internal boundaries shown for glossing."
		/>
		<p>
			In the first expression, the affiliative ending follows “wife”; in the second, it follows the
			whole compound. Nakagawa also records forms such as
			<i lang="ain-Latn">a=yup-i utar-i</i>, with endings on both words, often with much the same
			meaning as the corresponding single plural expression
			<Ref k="nakagawa2024" p="265" />. The formal grouping does not by itself fix every semantic
			distinction.
		</p>
	</S>
	<S t="Lexicalized meaning" id="diag-lexicalization">
		<p>
			Nakagawa contrasts <i lang="ain-Latn">retar cikap</i> “white bird” with
			<i lang="ain-Latn">retatcir</i> “swan.” The latter has a conventional species meaning and
			contains <i lang="ain-Latn">cir</i>, which is not independently used in this comparison <Ref
				k="nakagawa2024"
				p="266"
			/>. Semantic specialization helps here, but becomes less decisive for transparent formations
			such as <i lang="ain-Latn">ni-kap</i> “tree bark.”
		</p>
	</S>
	<S t="Conceptual noun forms" id="diag-concept">
		<p>
			Nakagawa proposes treating conceptual-form plus conceptual-form combinations as compounds,
			including <i lang="ain-Latn">sik-kap</i> “eyelid,”
			<i lang="ain-Latn">ni-kap</i> “tree bark,” and
			<i lang="ain-Latn">cep-kap</i> “fish skin”
			<Ref k="nakagawa2024" p="266–267" />. This supplies a structural criterion where the degree of
			lexicalized meaning is hard to judge. It is part of his analysis of the relationship between
			compounding and possession.
		</p>
	</S>
</S>

<S t="Heads, modifiers, and accent" id="headedness">
	<p>
		In the ordinary noun–noun pattern, the first noun qualifies the second. Kindaichi and Chiri give
		this ordering for noun–noun compounds
		<Ref k="kindaichi1936" p="170, §221" />. Nakagawa's examples include
		<i lang="ain-Latn">seta-rus</i> “dog fur” and
		<i lang="ain-Latn">menoko-ru</i> “women's toilet”
		<Ref k="nakagawa2024" p="267" />. The semantic relation between the parts can be broad,
		including source, use, or an associated class of people.
	</p>
	<p>
		Compound accent has its own patterns and exceptions, described in
		<Xr ch="accent-in-compounds-and-affixation" />. Nakagawa's word-boundary discussion does not
		treat an accent change or consonant alternation as an automatic compound test <Ref
			k="nakagawa2024"
			p="264"
		/>.
	</p>
</S>

<S t="Six formation patterns" id="formation-types">
	<p>
		Nakagawa distinguishes six structural types. Types II–IV involve nominal conversion of one-place
		verbal material and can be analyzed on the noun–noun pattern of Type I. Types V–VI first form a
		one-place verb from grammatically related parts, then convert that whole formation to a noun <Ref
			k="nakagawa2024"
			p="267–272"
		/>.
	</p>
