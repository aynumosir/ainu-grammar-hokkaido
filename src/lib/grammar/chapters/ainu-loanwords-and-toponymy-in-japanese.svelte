<S t="Borrowed words and proposed etymologies" id="loans">
	<p>
		Japanese vocabulary includes words identified as Ainu loans. Bugaeva lists Japanese <i>rakko</i>
		‘sea otter’ and
		<i>shishamo</i> ‘smelt’, the latter compared with Ainu
		<i lang="ain-Latn">susam</i>. Her proposed connection of Japanese <i>sake/shake</i> ‘salmon’
		with Ainu
		<i lang="ain-Latn">sak-ipe</i> is explicitly uncertain
		<Ref k="bugaeva2012" p="498, §15.5" />. These examples have different evidential status even
		when they appear together in a loanword list.
	</p>
	<p>
		A borrowing analysis must identify the compared forms and meanings, account for their sound
		relationship, and establish a plausible direction of transmission. Later changes within Japanese
		need to be distinguished from the form originally borrowed. Deep historical proposals are
		discussed separately in
		<Xr ch="macro-comparison-and-deep-contact-controversies" />.
	</p>
</S>

<S t="Place names as linguistic records" id="toponymy">
	<p>
		Ainu-derived place names preserve evidence beyond the localities with recorded Ainu speech.
		Nakagawa reviews earlier research on northern Honshu, including Yamada's distributional
		arguments, while distinguishing place-name evidence from actual language records
		<Ref k="nakagawa2024" p="77; 87, §2.2" />. The density of plausible names can support a
		historical hypothesis; it does not supply a complete grammar of an otherwise unrecorded regional
		variety.
	</p>
	<p>
		The recurrent elements <i lang="ain-Latn">pet</i> and
		<i lang="ain-Latn">nay</i> concern waterways, but their meaning cannot be reduced to a universal
		large-river/small-stream contrast. Tamura's Saru dictionary notes that, in the Saru, Mukawa, and
		Monbetsu region, even a small principal river can be
		<i lang="ain-Latn">pet</i>, while a large tributary can be
		<i lang="ain-Latn">nay</i>. The latter can also refer to a linear depression or streambed
		<Ref k="tamura1996" p="s.vv. pet, nay" />.
	</p>
	<p>
		Knowing an element's meaning is only part of a particular name's analysis. Its recorded
		spellings, local geography, and historical explanations must also be examined. A modern Japanese
		spelling cannot by itself establish all the sound changes that produced it.
	</p>
</S>

<S t="Two documented local explanations" id="local-explanations">
	<p>
		Sapporo's account of Nopporo reports an earlier name
		<span lang="ja">ヌポロペツ</span>, analyzed as
		<span lang="ja">ヌプ・オル・オ・ペッ</span>, ‘river in the field’. The city presents this as an
		explanation of the name, using qualified wording <Ref k="sapporo2021" p="厚別3" />. It is a
		documented local interpretation rather than an analysis derived afresh from the modern spelling.
	</p>
	<p>
		Niikappu's local-history account separates a naming legend from commentary on the word. The
		legend concerns an official's misunderstood question; the commentary identifies
		<span lang="ja">ニカプ</span> with elm bark, especially that of Manchurian elm. The naming event
		belongs to the legend; the lexical explanation is the author’s commentary
		<Ref k="niikappu2024" p="7, 第73話「新冠の地名について（伝説と歴史）」" />.
	</p>
</S>

