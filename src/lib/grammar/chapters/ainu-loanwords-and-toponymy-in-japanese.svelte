		proposed sequence runs through
		<i>*siw kor pe</i>, <i>*si kor pe</i>, and
		<i>*si ker pe</i>, with Japanese <i>*sikorope</i> borrowed at an earlier stage. The asterisks
		identify reconstructed forms
		<Ref k="ochiai2026" p="191–196, §§4–5" />.
	</p>
	<p>
		Ochiai explicitly qualifies the taste-based derivation and treats modern <i lang="ain-Latn"
			>sikerpe</i
		>
		as an opaque lexical unit. Ochiai also discusses an objection to the proposed assimilation
		across a morpheme boundary. The account therefore offers a historical explanation for
		evaluation, without making the modern word a transparent compound that independently proves
		borrowing direction
		<Ref k="ochiai2026" p="194–195, §§4.4–4.5, note 54" />. The further Japanese forms belong to
		subsequent proposed reanalysis within Japanese <Ref k="ochiai2026" p="196, §5" />.
	</p>
