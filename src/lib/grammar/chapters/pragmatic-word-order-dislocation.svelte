<S t="Preverbal order and interpretation" id="order">
	<p>
		Ainu normally places the verb after its lexical arguments, with flexibility
		in their relative order. Nakagawa illustrates this with three Chitose
		passages in which a wife teaches her daughter women's work. They were told
		by the same speaker in separate stories
		<Ref k="nakagawa2024" p="364, examples 700–702" />.
	</p>
	<Ex m="menoko ne hike a=macihi menoko monrayke epakasnu"
		g="woman COP one.of 4.A=wife.POSS woman work teach"
		tr="My wife taught our daughter women's work."
		cite="nakagawa2024:364" dial="CHI" place="Example 700"
		note="Menoko ne hike identifies the female child in the source context. The phrase order is recipient, teacher, then subject matter." />
	<p>
		The second passage puts the teaching material before the wife; the third
		starts with <i lang="ain-Latn">a=macihi anakne</i> and uses
		<i lang="ain-Latn">menoko po</i> ‘girl’ for the daughter.
		These are attested alternatives with their own wording and contexts.
		Nakagawa stresses that the participants' roles are understood from the
		situation and ordinary expectations about the participants
		<Ref k="nakagawa2024" p="364–365" />.
	</p>
	<p>
		This flexibility does not make every permutation equally interpretable.
		The basic order and the relation between word order and semantic roles
		are described in <Xr ch="constituent-order-head-final" />.
	</p>
</S>

<S t="Topics and initial emphasis" id="topics">
	<p>
		Nakagawa suggests that an expression marked with
		<i lang="ain-Latn">anakne</i> or additive <i lang="ain-Latn">ka</i>
		tends to come first, independently of its grammatical role
		<Ref k="nakagawa2024" p="365" />.
		This is a positional tendency. The range of phrases carrying topic
		particles is described in <Xr ch="topic-marking-anakne" />.
	</p>
	<p>
		Refsing records a more specific Shizunai possibility: an indirect object
		that would ordinarily be unmarked may be placed initially for emphasis
		and take an allative postposition
		<Ref k="refsing1986" p="164, §14.5" />.
		Her description permits that construction without requiring allative
		marking on every fronted noun phrase.
	</p>
</S>

<S t="Nouns after a lexical predicate" id="postverbal">
	<p>
		Bugaeva discusses examples in which the speaker first gives a lexical
		predicate and then names a participant before <i lang="ain-Latn">ki</i>
		‘do’. In the following passage, the baby follows the repeated washing
		predicate <Ref k="bugaeva2022" p="Chapter 1, §4.3, example 18" />.
	</p>
	<Ex m="orano nani usey kar hine huraye a huraye a nea iwatarap ki hine"
		g="then immediately hot.water make CONJ wash ITR wash ITR that baby do CONJ"
		tr="Right away, [my wife] made hot water and washed the baby's body carefully, …"
		cite="bugaeva2022" dial="HK" place="Chapter 1, §4.3, example 18; Nakagawa et al. 2016–2021, K8109171UP.159"
		note="The wife is supplied in Bugaeva's translation. The continuing hine is retained; a marks the repeated washing in the source gloss." />
	<p>
		Bugaeva calls this right dislocation and interprets the later noun phrase
		as clarification of a subject or object. Her next example names the
		daughters and sons after the growth predicate
		<Ref k="bugaeva2022" p="Chapter 1, §4.3, example 19; K8109171UP.296" />.
		These examples establish the order and support her proposed interpretation;
		they do not supply a complete taxonomy of afterthoughts or a restriction
		covering every person category.
	</p>
</S>

<S t="Ordering constraints and constituent analyses" id="analysis">
	<p>
		Flexible noun-phrase order coexists with more constrained constructions.
		Satō places ordinary preverbal <i lang="ain-Latn">somo</i> immediately
		before the relevant verb, while prohibitive <i lang="ain-Latn">iteki</i>
		can occur earlier <Ref k="sato2008" p="124" />.
		Postpositions follow their nominal expressions, auxiliaries follow verbs,
		and nominal modifiers precede their heads in Nakagawa's description
		<Ref k="nakagawa2024" p="365" />.
	</p>
	<p>
		The structural status of an overt noun phrase remains an analytical
		question. Bugaeva favours argumenthood shared by an index and its
		coreferential noun phrase; Satō develops a different head-marking account,
		with a special position for the unindexed theme of a three-place verb
		<Ref k="bugaeva2022" p="Chapter 1, §4.3" /><Ref k="sato2025a" p="363–370" />.
		Those proposals are compared in <Xr ch="nonconfigurationality-pronominal-argument" />.
	</p>
</S>
