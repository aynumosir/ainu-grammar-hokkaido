<S t="What counts as a sentence-final particle" id="inventory">
	<p>
		Final particles contribute to how an utterance addresses its hearer:
		as a question, request, suggestion, explanation, or reminder.
		Their inventories depend partly on the grammatical classification.
		Refsing recognizes four “genuine” sentence-final forms in Shizunai,
		<i lang="ain-Latn">yan</i>, <i lang="ain-Latn">na</i>,
		<i lang="ain-Latn">ya</i>, and <i lang="ain-Latn">wa</i>,
		while treating many formal-noun endings separately
		<Ref k="refsing1986" p="228–229, §14.11" />.
	</p>
	<p>
		Satō's Chitose description and Nakagawa's comparative account include
		additional forms. Satō cautions that the nuances remain difficult to
		translate and are incompletely understood
		<Ref k="sato2008" p="72–76" /><Ref k="nakagawa2024" p="332–337" />.
		The descriptions below follow their stated contexts.
	</p>
</S>

<S t="Requests, suggestions, and wishes" id="directives">
	<table>
		<thead><tr><th>Form</th><th>Source description</th></tr></thead>
		<tbody>
			<tr><td><i lang="ain-Latn">yan</i></td><td>Plural or polite imperative; subject-number-sensitive verbs normally take their plural stem.</td></tr>
			<tr><td><i lang="ain-Latn">ro</i>, regional <i lang="ain-Latn">rok/no</i></td><td>Invitation or proposal seeking agreement; person forms extend beyond inclusive joint action.</td></tr>
			<tr><td><i lang="ain-Latn">so</i></td><td>Self-directed deliberation about a possible action, in the Chitose examples.</td></tr>
			<tr><td><i lang="ain-Latn">oka</i></td><td>A wish construction associated with earlier <i lang="ain-Latn">ta</i>.</td></tr>
		</tbody>
	</table>
	<p>
		Nakagawa distinguishes Ishikari imperative <i lang="ain-Latn">ya</i>
		from <i lang="ain-Latn">yan</i>. His Chitose
		<i lang="ain-Latn">eci=kay ro</i> means ‘I will carry you’, showing
		that a proposal need not have an inclusive subject
		<Ref k="nakagawa2024" p="332–334, examples 568 and 579–580; p.336, example 593" />.
		The full constructions appear in <Xr ch="imperative-and-prohibitive" />
		and <Xr ch="hortative-and-optative" />.
	</p>
</S>

<S t="Na, wa, and un in interaction" id="interaction">
	<p>
		<i lang="ain-Latn">Na</i> can invite a response or action without an
		explicit command. Nakagawa gives this remark while cushions are being
		offered to a visitor <Ref k="nakagawa2024" p="335, example 583" />.
	</p>
	<Ex m="pirka HUTON poronno an na"
		g="be.good cushion many exist.SG FIN"
		tr="There are plenty of good cushions."
		cite="nakagawa2024:335" dial="CHI" place="Example 583"
		note="In context, the hearer is being invited to sit on one. The source capitalizes the Japanese loan HUTON." />
	<p>
		Satō similarly proposes an appeal to the hearer for
		<i lang="ain-Latn">na</i>, but notes that this does not straightforwardly
		explain its occurrence in the narration of deity songs. He leaves that
		extension open <Ref k="sato2008" p="73" />.
	</p>
	<p>
		Nakagawa describes final <i lang="ain-Latn">wa</i> as softening a
		conversational statement. His paired examples have an old woman calling
		herself poor and a reply reassuring her; both speakers use
		<i lang="ain-Latn">wa</i>
		<Ref k="nakagawa2024" p="334, examples 581–582" />.
		This final particle is distinguished by its construction from connective
		<i lang="ain-Latn">wa</i>.
	</p>
	<p>
		<i lang="ain-Latn">Un</i> can occur in answers, including a short
		nominal or locative reply, and also in questions. Nakagawa quotes
		<i lang="ain-Latn">eani un?</i> ‘And you?’ and a question ending
		<i lang="ain-Latn">an un?</i> through Tamura
		<Ref k="nakagawa2024" p="335, examples 585–588" />.
		Satō adds an imperative response granting permission to go out and play
		<Ref k="sato2008" p="74" />.
	</p>
</S>

<S t="Combinations and emphatic endings" id="combinations">
	<p>
		<i lang="ain-Latn">Hani</i> can follow <i lang="ain-Latn">yan</i>
		or <i lang="ain-Latn">na</i>, adding an instructive or insistent
		nuance. Satō also gives it with a statement of intention
		<Ref k="sato2008" p="72" />.
	</p>
	<Ex m="k=onaha oro ta ku=teskar kus ne na hani"
		g="1SG.A=father.POSS place.POSS LOC 1SG.S=tell.tales intention COP FIN FIN"
		tr="I will tell my father."
		cite="sato2008:72" dial="CHI" place="§8.2, hani with a non-imperative"
		note="The English translation leaves the advisory nuance to the context. Kus follows Satō's spelling; Nakagawa quotes the sentence with kusu." />
	<p>
		Stacking extends beyond <i lang="ain-Latn">hani</i>. Satō's permission
		response combines a reduced imperative <i lang="ain-Latn">yan</i>
		with <i lang="ain-Latn">un</i>.
	</p>
	<Ex m="sōyenpa wa sinot an un"
		g="go.out.PL CONJ play IMP.POL FIN"
		tr="Go outside and play."
		cite="sato2008:74" dial="CHI" place="§8.2, reply granting permission"
		note="Satō explicitly prints an as a reduced form of yan here. It is not the existential verb; his long-vowel notation is retained." />
	<p>
		Nakagawa associates emphatic <i lang="ain-Latn">ne(k)</i> with
		<i lang="ain-Latn">tas(i)</i>, and describes Shizunai
		<i lang="ain-Latn">esta</i> and Tokachi
		<i lang="ain-Latn">esta(p)</i> with final <i lang="ain-Latn">ne</i>.
		He distinguishes this ending from the identically written copula
		<Ref k="nakagawa2024" p="337, examples 594–598" />.
	</p>
</S>

<S t="Questions and the boundary of an utterance" id="boundary">
	<p>
		The analysis of interrogative <i lang="ain-Latn">a</i> varies.
		Refsing describes it as a pronunciation of <i lang="ain-Latn">ya</i>
		after consonants in Shizunai. Nakagawa argues for a separate particle
		where Chitose and Ishikari examples place <i lang="ain-Latn">a</i>
		after vowels <Ref k="refsing1986" p="229" /><Ref k="nakagawa2024" p="332–333, examples 570–572" />.
		See <Xr ch="interrogative-strategies-question-particles" />.
	</p>
	<p>
		Nakagawa treats final particles as normally closing an utterance against
		further connective attachment. He nevertheless records rare imperative
		clauses with <i lang="ain-Latn">yan</i> joined by connective
		<i lang="ain-Latn">wa</i>
		<Ref k="nakagawa2024" p="404–405, example 828" />.
		The source's closure account includes this qualification.
	</p>
</S>
