<S t="Indefinite causation without an added object" id="overview">
	<p>
		The causative suffix <i lang="ain-Latn">-yar/-ar</i> introduces a causer without adding a causee
		object. The new causer replaces the base's subject. A one-place base consequently remains
		one-place, while a two-place base retains its original object
		<Ref k="nakagawa2024" p="200–201, 432–433" />;
		<Ref k="sato2008" p="250–251" />;
		<Ref k="bugaevakobayashi2022" p="§4.3.1" />. This construction is commonly called
		<em>indefinite causation</em>.
	</p>
	<Ex
		m="ipe-yar=an ro"
		g="eat.meal-INDEF.CAUS=4.S HORT"
		tr="Let's offer the guest some food."
		cite="bugaevakobayashi2022:§4.3.1, example 30b"
		place="From Tamura 2000 [1988]:214, as reproduced in the handbook"
		note="The source's literal meaning is ‘let's make somebody eat.’ Its stated context is a proposal to provide food for a guest, without mentioning the guest directly."
	/>
	<p>
		The person marked by <i lang="ain-Latn">=an</i> is the causer. The understood guest is the
		eater, but receives no object index. The handbook explicitly notes that a known causee can be
		left unmentioned for politeness <Ref k="bugaevakobayashi2022" p="§4.3.1" />. “Indefinite”
		therefore does not require that the speakers be unable to identify the person.
	</p>
</S>

<S t="A retained object" id="transitive-base">
	<Ex
		m="a=en=kopisi p anakne opitta ku=ye wa ku=nu-yar"
		g="4.A=1SG.O=ask NMLZ TOP all 1SG.A=say CONJ 1SG.A=hear-INDEF.CAUS"
		tr="As for what I was asked, I will tell it all."
		cite="nakagawa2024:432"
		dial="SAR"
		place="Example 959, from Tamura 1984:12, as reproduced by Nakagawa"
		note="The internal boundary in nu-yar follows Nakagawa's analysis. The relative clause has its own A–O indexing, separate from the first-person subject of the main clause."
	/>
	<p>
		The base <i lang="ain-Latn">nu</i> “hear” takes a content object. In
		<i lang="ain-Latn">nu-yar</i>, that content remains the object; the person caused to hear is not
		added as another object. Nakagawa contrasts it with three-place
		<i lang="ain-Latn">nu-re</i>, which can express both the listener and the content as objects
		<Ref k="nakagawa2024" p="432, examples 958–959" />.
	</p>
</S>

<S t="Identifying a causee in an oblique phrase" id="oblique">
	<p>
		Nakagawa allows the understood causee to be identified with oblique expressions such as
		<i lang="ain-Latn">or peka, or un</i>, or <i lang="ain-Latn">eun</i>, depending on the verb. One
		example names a specific thunder deity as the recipient of a proposed marriage
		<Ref k="nakagawa2024" p="433, examples 961–963" />.
	</p>
	<Ex
		m="kanna kamuy eun a=kor-ar kunak a=ye"
		g="thunder deity ALLAT 4.A=have-INDEF.CAUS COMP 4.A=say"
		tr="I said that I would give her to the thunder deity."
		cite="nakagawa2024:433"
		dial="SAR"
		place="Example 963"
		note="The source identifies her as the narrator's younger sister. The recipient is the understood causee of have; the person given remains the object."
	/>
	<p>
		This makes the restriction on a causee object distinct from a ban on mentioning a causee
		anywhere in the clause. The handbook's general formulation says that the causee cannot be
		expressed by an NP or indexed on the verb; Nakagawa's oblique examples qualify the broader NP
		restriction <Ref k="bugaevakobayashi2022" p="§4.3.1" />;
		<Ref k="nakagawa2024" p="433" /> ‹contested›. Nakagawa also leaves open the precise difference between
		his example and a counterpart with ordinary <i lang="ain-Latn">kore</i>.
	</p>
</S>

<S t="The reported allomorph distributions" id="allomorphs">
	<p>
		The descriptions do not give one identical rule for the two suffix shapes. Nakagawa has
		<i lang="ain-Latn">-ar</i> after <i lang="ain-Latn">r</i> and
		<i lang="ain-Latn">-yar</i> elsewhere, illustrated by
		<i lang="ain-Latn">nukar-ar</i> and <i lang="ain-Latn">ipe-yar</i>
		<Ref k="nakagawa2024" p="201" />. The handbook's note instead gives
		<i lang="ain-Latn">-yar</i> after vowels and <i lang="ain-Latn">-ar</i> after consonants
		<Ref k="bugaevakobayashi2022" p="note 229" /> ‹contested›.
	</p>
	<p>
		Satō writes <i lang="ain-Latn">sikasuy-yar</i> and specifies the pronunciation
		<i lang="ain-Latn">sikasuy-ar</i>
		<Ref k="sato2008" p="250" />. The earlier Kindaichi–Chiri description prints consonant-final
		<i lang="ain-Latn">chish-yar</i> and derives <i lang="ain-Latn">-ar</i> after
		<i lang="ain-Latn">r</i>
		<Ref k="kindaichi1936" p="122, §188" />. Morphological segmentation, pronunciation at the
		boundary, and the scope of each account all matter when comparing these forms.
	</p>
</S>

<S t="Older plural accounts and the Ishikari comparison" id="comparison">
	<p>
		Kindaichi and Chiri characterize <i lang="ain-Latn">-yar</i> as marking plural causees
		<Ref k="kindaichi1936" p="122, §188" />. Shibatani presents that plural account, then reports
		Fukuda's description of indefinite and honorific uses in which valency does not increase <Ref
			k="shibatani1990"
			p="49–50"
		/> ‹contested›.
	</p>
	<p>
		Shibatani also reports Asai's Ishikari <i lang="ain-Latn">ku-us-te-yar</i> as a double causative
		involving an intermediary: the causer has someone make another participant wear the shoes <Ref
			k="shibatani1990"
			p="50, example 84, citing Asai 1970"
		/>. That dialect-specific report has to be distinguished from the valency-retaining construction
		described above.
	</p>
	<p>
		Sociative constructions expressing joint activity are treated separately in the handbook, with
		forms such as <i lang="ain-Latn">uko-</i> and <i lang="ain-Latn">uwe-</i>
		<Ref k="bugaevakobayashi2022" p="§4.3.2" />. Polite use of an indefinite causative likewise does
		not make it a permissive-only suffix: ordinary causatives can express permission too
		<Ref k="sato2008" p="237" />. See <Xr ch="causative-morphological-re-e-te" />.
	</p>
</S>
