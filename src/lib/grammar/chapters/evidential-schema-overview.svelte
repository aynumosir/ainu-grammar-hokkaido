<S t="Clause endings and regional differences" id="frames">
	<p>
		For the southern constructions, Nakagawa describes declarative
		<i lang="ain-Latn">N + ne</i>, content questions with
		<i lang="ain-Latn">N + an</i>, bare nouns in polar questions and exclamations, and affirmative
		replies with <i lang="ain-Latn">N + un</i>. Each frame has its own qualifications and possible
		continuations
		<Ref k="nakagawa2024" p="392–396" />.
	</p>
	<p>
		Tokachi frequently uses shorter <i lang="ain-Latn">ru</i>,
		<i lang="ain-Latn">sir</i>, <i lang="ain-Latn">haw</i>, and
		<i lang="ain-Latn">hum</i>. Takahashi's Tokachi material includes declarative
		<i lang="ain-Latn">N + an</i> and a relative construction containing it. An
		<i lang="ain-Latn">an</i>
		ending consequently cannot be identified as a question solely from its surface form <Ref
			k="takahashi2013"
			p="129–131, §3"
		/>.
	</p>
	<Ex
		m="atuy otakpa sir an"
