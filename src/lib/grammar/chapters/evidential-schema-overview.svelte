<S t="Formal nouns and judgments about a situation" id="nouns">
	<p>
		<i lang="ain-Latn">Ruwe</i>, <i lang="ain-Latn">siri</i>,
		<i lang="ain-Latn">hawe</i>, and <i lang="ain-Latn">humi</i> can take a preceding clause as
		their content. They also enter clause endings that relate the situation to a speaker's knowledge
		or perception. Their ordinary noun counterparts concern traces, appearance, voice, and sound or
		feeling
		<Ref k="nakagawa2024" p="391–392" />.
	</p>
	<p>
		Nakagawa distinguishes an internal noun phrase from an ending that comments on the assertion.
		Hearing ‘the voice of my brother crying out’, for example, makes the voice part of what the
		sentence describes. An ending in
		<i lang="ain-Latn">hawe ne</i> has a different grammatical role
		<Ref k="nakagawa2024" p="391, example 774; 392–393" />.
	</p>
	<table>
		<thead><tr><th>Form with ne</th><th>Nakagawa's descriptive starting point</th></tr></thead>
