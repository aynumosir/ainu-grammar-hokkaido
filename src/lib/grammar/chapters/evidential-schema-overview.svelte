<S t="Comparing the analyses" id="analysis">
	<p>
		The term <em>evidentiality</em> concerns how an utterance relates information to its source. The Ainu
		constructions also raise questions about interpretation, speaker knowledge, and discourse. Their noun
		morphology does not itself settle these semantic questions.
	</p>
	<p>
		Dal Corso distinguishes direct forms
		<i lang="ain-Latn">ruwe ne, siri ne, humi ne, hawe ne</i> from indirect forms
		<i lang="ain-Latn">siri an, siri ki, humi as, hawe as</i> in the Hokkaido material he surveys.
		His model uses both event accessibility and source reliability; the two inventories do not
		constitute four simple identical-noun pairs
		<Ref k="dalcorso2018" p="337–338, table 18" />.
	</p>
	<p>
		Hirosawa proposes that <i lang="ain-Latn">ruwe</i> refers to knowledge formed through the
		speaker's internal processing of information. The account connects this with the presentation of
		new information and with whose informational domain a proposition belongs to <Ref
			k="hirosawa2026"
			p="63, 81–82, §§6.4–6.5"
		/>.
	</p>
</S>

<S t="Negation, ordering, and further reading" id="scope">
	<p>
		Negating the preceding predicate differs from placing
		<i lang="ain-Latn">somo</i> before the copula. Nakagawa gives rhetorical confirmation for
		<i lang="ain-Latn">ruwe somo ne</i>, while Tamura also describes
		<i lang="ain-Latn">N somo ne</i>
		as ordinary denial
		<Ref k="nakagawa2024" p="393, examples 779–780" /><Ref k="tamura1997" p="71" />. The
		interpretation must retain the source's construction and context.
	</p>
	<p>
		Ordering restrictions are similarly specific. Nakagawa permits
		<i lang="ain-Latn">kusu ne ruwe ne</i> and rejects the reverse order in that construction, while
		allowing auxiliaries such as <i lang="ain-Latn">nankor</i>
		after <i lang="ain-Latn">N + ne</i>
		<Ref k="nakagawa2024" p="393–394" />. For the four noun families, see <Xr
			ch="ruwe-ne-inferential"
		/>,
		<Xr ch="siri-ne-situational" />, <Xr ch="hawe-ne-reportative" />, and
		<Xr ch="humi-ne-sensory" />. Their combinations are considered in
		<Xr ch="mirativity-scope-grammaticalization" />.
	</p>
</S>
