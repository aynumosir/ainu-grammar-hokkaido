<S t="Kinship terms have several grammatical patterns" id="kinship-patterns">
	<p>
		Many kinship nouns have affiliative forms, including
		<i lang="ain-Latn">yup</i> → <i lang="ain-Latn">yupi(hi)</i>
		“elder brother” and <i lang="ain-Latn">sa</i> →
		<i lang="ain-Latn">sa(ha)</i> “elder sister.” Other kin expressions use
		<i lang="ain-Latn">kor</i>, and some permit more than one construction. Nakagawa's upper-Saru
		tables therefore distinguish forms individually
		<Ref k="nakagawa2024" p="221–223, tables 49–50" />. Person, dialect, and the difference between
		reference and address all matter.
	</p>
	<p>
		The noun <i lang="ain-Latn">mici</i> “father” is a useful example. Nakagawa allows both
		<i lang="ain-Latn">ku=mici</i>
		and
		<i lang="ain-Latn">ku=kor mici</i> for first-singular possession in Saru, with other persons
		using <i lang="ain-Latn">kor</i>
		<Ref k="nakagawa2024" p="223" />. His table lists
		<i lang="ain-Latn">mici(hi)</i>, while Tamura's Saru entry explicitly excludes final
		<i lang="ain-Latn">hi</i>
		<Ref k="tamura1996" p="s.v. míci" />. Refsing reports no possessed
		<i lang="ain-Latn">mici</i> in her Shizunai material
		<Ref k="refsing1986" p="86" /> ‹contested›.
	</p>
</S>

<S t="Dialect differences in parent and sibling terms" id="dialect-differences">
	<p>
		Parent terms require a dialect label. Chitose
		<i lang="ain-Latn">hāpo</i> means “father,” with
		<i lang="ain-Latn">totto</i> for “mother”; in much of Hokkaido,
		<i lang="ain-Latn">hapo</i> instead means “mother”
		<Ref k="sato2008" p="152, 168, 214" />. Nakagawa gives
		<i lang="ain-Latn">mici</i> for “father” in Horobetsu, Shizunai, middle and upper Saru, and
		several eastern varieties; lower Saru has
		<i lang="ain-Latn">iyapo</i>, while Ishikari has
		<i lang="ain-Latn">hampe</i>
		<Ref k="nakagawa2024" p="222–223" />.
	</p>
	<p>
		“Mother” <i lang="ain-Latn">totto</i> is also recorded in Tamura's Saru dictionary <Ref
			k="tamura1996"
			p="s.v. totto"
		/>. Its occurrence alone does not identify a passage as Chitose. In a quotation attributed to
		Nakamoto Mutsuko, an Ainu Times article contrasts <i lang="ain-Latn">ku=tekehe</i>
		“my hand” with <i lang="ain-Latn">ku=kor totto</i> “my mother”
		<Ref k="yokoyama2002" p="ainu-times/024/1#19–20" />. The article's transcription is labelled
		Saru–Chitose.
	</p>
	<p>
		Sibling vocabulary also encodes the relationship between the people involved. Nakagawa
		distinguishes a woman's younger sister,
		<i lang="ain-Latn">matak</i>, from a man's younger sister: upper-Saru
		<i lang="ain-Latn">matapa</i>, Chitose <i lang="ain-Latn">macirpe</i>, and
		<i lang="ain-Latn">tures</i>
		in other varieties and in Saru oral literature <Ref k="nakagawa2024" p="224" />.
	</p>
</S>

<S t="Reference and address" id="reference-address">
	<p>
		A word used to describe a relative need not be the ordinary word used to call that person.
		Nakagawa distinguishes reference terms such as
		<i lang="ain-Latn">ona</i> “father,” <i lang="ain-Latn">unu</i>
		“mother,” <i lang="ain-Latn">yup</i> “elder brother,” and
		<i lang="ain-Latn">sa</i> “elder sister” from their address counterparts. Many address terms can
		appear alone; some occur with first-singular
		<i lang="ain-Latn">ku=</i>
		<Ref k="nakagawa2024" p="224–226" />.
	</p>
	<p>
		The distinction has historical and genre limits. Kindaichi and Chiri record epic vocatives <i
			lang="ain-Latn">a-ona</i
		>
		and
		<i lang="ain-Latn">a-unu</i>
		<Ref k="kindaichi1936" p="25" />
		‹contested›. These differ from a general reference-only characterization of those parent terms in
		the modern descriptions.
	</p>
	<p>
		For sibling address, both Satō and Nakagawa give
		<i lang="ain-Latn">ku=yupo</i> and <i lang="ain-Latn">ku=sapo</i>. Satō reports a speaker's
		rejection of younger-sibling address, whereas Nakagawa quotes Saru
		<i lang="ain-Latn">ku=mataki</i>
		“younger sister” and a Chitose address to a niece, <i lang="ain-Latn">ku=matkarku</i>
		<Ref k="sato2008" p="152" />;
		<Ref k="nakagawa2024" p="225–226, examples 263–265" /> ‹contested›. These forms need to be learned
		as documented address expressions; the contrast does not establish a general vocative suffix.
	</p>
</S>

<S t="Social address and grammatical person" id="social-address">
	<p>
		Kinship terms can address people outside biological kinship. Satō's Chitose examples use <i
			lang="ain-Latn">acapo</i
		>
		“uncle” or
		<i lang="ain-Latn">ku=sapo</i> “elder sister” respectfully for suitable non-relatives. When such
		an ordinary noun identifies the addressee, the verb has third-person, zero indexing in his
		examples
		<Ref k="sato2008" p="213–214" />.
	</p>
	<p>
		His <i lang="ain-Latn">ku-sapo ipe a ruwe?</i> addresses the listener: “Elder sister, have you
		eaten?” The first-singular prefix belongs to the kinship noun, while <i lang="ain-Latn">ipe</i>
		has no second-person prefix
		<Ref k="sato2008" p="214" />. The same surface person pattern can describe a third party in a
		different context; the conversational setting supplies the address reading.
	</p>
	<p>
		Satō also describes senior kin terms such as <i lang="ain-Latn">totto</i>
		used for self-reference when speaking to a younger relative. He excludes
		<i lang="ain-Latn">yupo</i> and <i lang="ain-Latn">sapo</i> from that self-reference pattern <Ref
			k="sato2008"
			p="215"
		/>. Address and self-reference thus have different restrictions even within his Chitose account.
	</p>
</S>

<S t="Honorific fourth person" id="honorific-fourth-person">
	<p>
		Honorific use of the fourth-person series refers to the <em>addressee</em>. Nakagawa describes
		it in respectful speech and prayers, alongside inclusive, indefinite, narrative, and quotation
		uses of the same formal series
		<Ref k="nakagawa2024" p="175–176" />;
		<Ref k="bugaeva2021poss" p="53" />. These functions must be distinguished by context; an
		isolated fourth-person possessive form does not determine which one is intended.
	</p>
	<p>Nakagawa's Chitose honorific question illustrates the listener reading:</p>
	<Ex
		m="hunak wa arki=an ruwe an"
		g="where ABL come.PL=4.S EVID exist.SG"
		tr="Where have you come from?"
		cite="nakagawa2024:176, example 140"
		dial="CHI"
		note="Respectful address by a woman to an adult man; the plural verb occurs despite a singular addressee."
	/>
	<p>
		Fourth person is not obligatory in every prayer. Nakagawa contrasts an owl-god prayer using
		fourth person with a tsunami-god prayer using second person by the same speaker. He tentatively
		suggests that the addressed being may affect the choice <Ref
			k="nakagawa2024"
			p="176, examples 142–143"
		/>
		‹speculative›. See <Xr ch="person-marking-architecture" /> for the full range of person functions.
	</p>
</S>

<S t="Narrative possession and existential clauses" id="narrative-possession">
	<p>
		In first-person narratives, fourth-person kinship forms can refer to the narrator's relatives.
		Kimura Kimi's Saru narrative begins with two existential clauses:
	</p>
	<Ex
		m="iwan a=yup-i an iwan a=sa-ha an"
		g="six 4.A=elder.brother-POSS exist.SG six 4.A=elder.sister-POSS exist.SG"
		tr="I had six elder brothers and six elder sisters."
		cite="glossedcorpus2016:Kimura Kimi, K7908032UP.001; huber2025:252, example 16"
		dial="SAR"
		note="Excerpt from the opening sentence, recorded on 3 August 1979; aligned transcription ninjal-folklore/035#0. Person glosses are normalized to the A series."
	/>
	<p>
		The possessive relation is expressed on the kinship nouns, while
		<i lang="ain-Latn">an</i> predicates their existence. Chudá discusses this pattern among
		existential possession constructions in the oral material examined in her study <Ref
			k="huber2025"
			p="252–254"
		/>. Its narrative first-person interpretation supplies no evidence for honorific reference to an
		esteemed third party. See <Xr ch="predicative-possession-clauses" /> for the comparison with possession
		expressed by a verb.
	</p>
</S>
