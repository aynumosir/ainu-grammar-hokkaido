<S t="Finishing an action" id="completion">
	<p>
		Several constructions describe an event's beginning, continuation, repetition, or completion.
		Their grammar varies: some are auxiliaries following a predicate, while others contain a
		connective and a second verb. Nakagawa treats
		<i lang="ain-Latn">wa okere</i> as carrying an action through to its end
		<Ref k="nakagawa2024" p="450–453" />.
	</p>
	<Ex
		m="yaykata ipe wa okere kor"
		g="oneself eat CONJ finish CONJ"
		tr="When they too had finished eating, …"
		cite="nakagawa2024:452–453"
		dial="SAR"
		place="Example 1033, opening clause"
		note="Nakagawa explains that this means finishing the meal; it need not mean consuming all the food."
	/>
	<p>
		Satō notes that <i lang="ain-Latn">wa okere</i> often concerns a resulting change that is
		regrettable <Ref k="sato2008" p="89" />. The emotional interpretation is a tendency in that
		description. Nakagawa also gives degree readings with state predicates:
		<i lang="ain-Latn">onne wa okere</i>
		describes a very old grandfather, and <i lang="ain-Latn">pirka wa okere</i> very fine young men
		<Ref k="nakagawa2024" p="453, examples 1035–1036" />.
	</p>
	<p>
		The second verb can carry person marking, as in
		<i lang="ain-Latn">e=e wa e=okere</i> ‘you finish eating it’. Nakagawa also preserves a
		speaker's <i lang="ain-Latn">a=tuypa wa okere</i>, without the expected second
		<i lang="ain-Latn">a=</i>, and relates this habit to
		<i lang="ain-Latn">okere</i> losing some independence as a main verb
		<Ref k="nakagawa2024" p="452–453, examples 1030, 1034" />.
	</p>
</S>

<S t="Disappearance and a completed change" id="isam">
	<p>
		<i lang="ain-Latn">Wa isam</i> often describes a completed event involving breakage, loss, or
		disappearance. Satō's example has an overturned bowl breaking
		<Ref k="sato2008" p="88" />. Yoshikawa places disappearance at the center of the analysis and
		rejects an inherent meaning of misfortune
		<Ref k="yoshikawa2022" p="§2" />.
	</p>
	<p>
		Nakagawa discusses a less literal case: an elder brother
		<i lang="ain-Latn">hotke wa isam</i>, ‘has gone to bed’, while still visible in the same
		one-room house. He understands the expression as entering fully into the sleeping posture.
		Another example concerns sewing that leaves the cloth badly bunched up <Ref
			k="nakagawa2024"
			p="451–452, examples 1027, 1032"
		/>. These examples motivate a broader account in his description. The authors' analyses should
		remain distinguishable when interpreting a new passage.
	</p>
</S>

<S t="Recent change, brief action, and repetition" id="auxiliaries">
	<p>
		The auxiliary <i lang="ain-Latn">nisa</i> presents something as having already come about.
		Nakagawa gives the following narrative example
		<Ref k="nakagawa2024" p="311" />.
	</p>
	<Ex
		m="arwenkamuy ne an=an nisa ruwe ne na"
		g="extremely.evil.deity COP exist.SG=4.S PFV EVID COP FIN"
		tr="I have become an extremely evil kamuy."
		cite="nakagawa2024:311"
		dial="SAR"
		place="Example 470, citing Chiba University 2015:299"
		note="The fourth-person narrative form refers to the speaker. PFV is the broad aspect gloss used here for nisa."
	/>
	<p>
		Saru/Chitose <i lang="ain-Latn">tek</i> can make an action brief or sudden: Nakagawa's examples
		include jumping into and out of bed and momentarily showing a grin <Ref
			k="nakagawa2024"
			p="312, examples 477–478"
		/>. Tokachi <i lang="ain-Latn">tek an</i> has a different distribution, discussed in
		<Xr ch="continuative-siri-siran-kane-an" />.
	</p>
	<p>
		<i lang="ain-Latn">Ranke</i> marks repeated action in Nakagawa's Saru and Horobetsu examples. In
		the Saru puppy narrative, the puppy repeatedly goes away, returns, and jumps at the narrator;
		the final <i lang="ain-Latn">oka=an</i> belongs to the narrator's continuing situation <Ref
			k="nakagawa2024"
			p="311, example 471"
		/>. Refsing treats <i lang="ain-Latn">ranke</i> within her Shizunai account of linked events <Ref
			k="refsing1986"
			p="198–199"
		/>. Repeated
		<i lang="ain-Latn">V a</i> sequences provide another resource for sustained or repeated
		activity; see <Xr ch="perfective-anterior-a" />.
	</p>
</S>

<S t="Other event contours" id="other">
	<p>
		A beginning can emerge from a predicate and its context. Satō's
		<i lang="ain-Latn">epuykehe tane sipuske kor oka</i> describes flower buds beginning to open <Ref
			k="sato2008"
			p="86"
		/>. Habitual activity likewise occurs with
		<i lang="ain-Latn">kor an</i>, as described in <Xr ch="existential-aspect-an-oka" />.
	</p>
	<p>
		<i lang="ain-Latn">Wa anu</i> concerns doing something and leaving its tangible result in place,
		such as gathering and drying greens. Nakagawa distinguishes this from abstract uses of Japanese
		‘do beforehand’ <Ref k="nakagawa2024" p="453–454" />. His <i lang="ain-Latn">wa inkar</i> and
		<i lang="ain-Latn">wa inu</i>
		descriptions concern trying an action with visually and otherwise perceptible results
		respectively
		<Ref k="nakagawa2024" p="454–455" />. These constructions add their own meanings to the lexical
		event; their shared two-verb shape does not make them one aspect category.
	</p>
</S>
