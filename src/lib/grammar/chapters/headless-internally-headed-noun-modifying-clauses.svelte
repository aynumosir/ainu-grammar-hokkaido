<S t="Different questions about a noun-modifying clause" id="distinctions">
	<p>
		A general head, an internally complete clause, and an internally headed relative describe
		different properties. The first concerns the head's lexical meaning, the second the roles within
		the clause, and the third the proposed position of the head. Keeping them separate makes the
		Ainu analyses easier to compare
