<S t="General heads remain heads" id="general-heads">
	<p>
		Bugaeva lists <i lang="ain-Latn">kur</i> ‘person’, <i lang="ain-Latn">utar</i> ‘people’,
		<i lang="ain-Latn">p/pe</i> ‘thing, person’ and place-related forms among the common heads of
		Ainu relatives <Ref k="bugaeva2015" p="47" />. An English translation such as ‘what I carried’
		can conceal the overt Ainu head. It does not establish syntactic headlessness. See <Xr
			ch="nominalization-p-pe"
		/> for examples with
		<i lang="ain-Latn">p/pe</i>.
	</p>
	<p>
		General heads also occur in the comparison-equivalent construction. Bugaeva's <i lang="ain-Latn"
			>pak sermaka yupke p isam pe e=ne</i
		>
		describes someone whose guardian deity has no equal in strength, with both
		<i lang="ain-Latn">p</i>
		and
		<i lang="ain-Latn">pe</i> in the construction <Ref k="bugaeva2015" p="55, example 30" />. This
		belongs to her degree-relative analysis, distinct from relativization of a comparative standard
		proper.
	</p>
</S>

<S t="Clauses with no head-related gap" id="gapless">
	<Ex
		m="e=munin hura"
		g="2SG.S=rot smell.POSS"
		tr="The smell of you rotting"
		cite="bugaeva2012:480"
		dial="CHI"
		place="Example 41, citing Bugaeva 2004:96"
		note="Bugaeva treats this as a noun-modifying construction whose head cannot be restored as an argument or adjunct of the preceding predicate."
	/>
	<p>
		The smell is related to the event of rotting, but it does not fill a missing role in
		<i lang="ain-Latn">e=munin</i>. Bugaeva compares this construction with Japanese
		<em>soto no kankei</em>, an external semantic relation between clause and noun
		<Ref k="bugaeva2012" p="480" />. “External relation” here describes that relationship; it is not
		a claim that the construction is an ordinary externally headed gap relative.
	</p>
	<p>
		Nakagawa makes a related distinction through argument structure. His
		<i lang="ain-Latn">hekattar tura sinot=an</i> ‘I play with the children’ is internally complete.
		Adding <i lang="ain-Latn">hi</i> can make it a complement, whereas adding
		<i lang="ain-Latn">cise</i> ‘house’ alone cannot make a relative meaning ‘the house where I play
		with the children’ <Ref k="nakagawa2024" p="507–508" />. The latter requires the locative
		relation to be expressed. These are distinct grammatical uses of material before a noun.
	</p>
</S>

<S t="Dal Corso's incorporation analysis" id="incorporation">
	<p>
		Dal Corso studies a narrower set of southern Hokkaido sensory-evidential constructions. He
		distinguishes pseudo-incorporation, morphological incorporation, and classificatory
		incorporation. His pseudo-incorporation analysis allows some syntactic independence: in one
		example, <i lang="ain-Latn">i-os</i> ‘behind us’ intervenes between
		<i lang="ain-Latn">aynu ek hum</i> and <i lang="ain-Latn">as</i>
		<Ref k="dalcorso2020" p="58–60, example 19" />.
	</p>
	<p>
		Possessive morphology alone does not distinguish all these patterns. The paper allows possessive
		marking in some incorporated or pseudo-incorporated sensory forms and relies on their syntax as
		well. This proposal addresses sensory predicates; Satō's lexical quasi-incorporation and
		Tamura's <span lang="ja">連他動詞</span> concern the constructional problems discussed in <Xr
			ch="noun-incorporation-oblique-polysynthesis-debate"
		/>.
	</p>
	<p>
		In classificatory incorporation, an incorporated sensory noun has an additional, syntactically
		unbound copy. Dal Corso illustrates <i lang="ain-Latn">haw-e</i> before
		<i lang="ain-Latn">haw-as</i>, and reports only three examples of this pattern in his reference
		corpora <Ref k="dalcorso2020" p="62, example 21" />.
	</p>
</S>

<S t="The internally headed proposal and its limits" id="internal-head">
	<Ex
		m="cisinaot onnay-un sesserke haw-e-as haw-e ene an hi"
		g="grave interior-ALLAT cry voice-POSS-stand voice-POSS like.this exist.SG NMLZ"
		tr="From inside the grave someone seemed to be crying, and that voice was like this…"
		cite="dalcorso2020:63"
		place="Example 22, citing Kayano 6-3,3"
		note="The segmentation follows Dal Corso's analysis. A copy of hawe follows the sensory predicate hawe-as, and ene an hi introduces the continuation."
	/>
	<p>
		Dal Corso proposes that the later <i lang="ain-Latn">hawe</i> in this pattern is an internally
		positioned relative head. He derives the construction from one containing an unbound copy of the
		incorporated noun, then analyzes the head as displaced to the right edge while remaining inside
		the relative clause
		<Ref k="dalcorso2020" p="63–65" />.
	</p>
	<p>
		He explicitly leaves its position relative to a verb phrase unresolved, because the required
		analysis of Ainu VP structure is not established. He also says that the available constructions
		do not provide consistent evidence for a secure historical sequence
		<Ref k="dalcorso2020" p="64–66" />. The proposal supplies an account of these copied-noun
		patterns; its scope does not extend automatically to every sensory complement or every clause
		with a general nominal head.
	</p>
</S>
