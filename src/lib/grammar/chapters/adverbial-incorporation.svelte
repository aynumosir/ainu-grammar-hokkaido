<S t="Manner expressed inside a verbal stem" id="overview">
	<p>
		A complex verb can include an element describing how its event proceeds. Nakagawa calls this
		adverbial incorporation while observing that much of it is structurally verb incorporation: a
		property verb supplies an adverbial meaning inside another verbal stem
		<Ref k="nakagawa2024" p="492–493" />. His introductory comparison is:
	</p>
	<Ex
		m="pirka-no a=ipere"
		g="good-ADV 4.A=feed"
		tr="I fed someone sufficiently."
		cite="nakagawa2024:484"
		place="Author's illustration with a separate adverb"
	/>
	<Ex
		m="a=pirka-ipere"
		g="4.A=good-feed"
		tr="I fed someone sufficiently."
		cite="nakagawa2024:484"
		place="Author's incorporated comparison"
	/>
	<p>
		The incorporated form has <i lang="ain-Latn">pirka</i> where the separate adverb has
		<i lang="ain-Latn">pirka-no</i>. The added manner component leaves the recipient of feeding
		available as an object. This differs from incorporation of an object noun, which fills a
		participant position; see <Xr ch="noun-incorporation-object" />.
	</p>
</S>

<S t="Property verbs and lexical combinations" id="property-verbs">
	<p>
		Shibatani likewise observes that adverbs derived with <i lang="ain-Latn">-no</i> occur inside
		these compounds in their basic verbal form. He gives an Itadori example containing
		<i lang="ain-Latn">a-moyre-caka</i> “I opened it slowly” and another with
		<i lang="ain-Latn">tunas</i> “fast” within a causative-applicative predicate
		<Ref k="shibatani1990" p="71–72, example 129" />. These descriptions concern particular compound
		patterns; Ainu also has an independent adverb class.
	</p>
	<p>
		A separate adverbial paraphrase is not always attested. Nakagawa's Saru
		<i lang="ain-Latn">a=pirkaonnere</i> describes enabling one's fathers or forefathers to live out
		their natural lives. He presents a hypothetical separate-adverb version to explain the
		construction, while stating that he has not found that alternative in use
		<Ref k="nakagawa2024" p="492, example 1126" />. Lexical meaning and constructional possibility
		therefore need to be distinguished from a recorded alternation.
	</p>
</S>

<S t="An apparent exception with no" id="mono">
	<p>
		Nakagawa discusses <i lang="ain-Latn">monoa</i>, in which
		<i lang="ain-Latn">mono</i> accompanies “sit.” Its interpretation involves sitting with the
		knees bent. A segmentation into <i lang="ain-Latn">mo-no</i> would make it an example retaining
		the adverbial suffix inside the compound
		<Ref k="nakagawa2024" p="492–493" />.
	</p>
	<Ex
		m="oraun hopuni=an hine monoa=an akusu"
		g="then rise.SG=4.S CONJ sit=4.S CONJ"
		tr="Then I got up and sat down, when …"
		cite="nakagawa2024:492"
		dial="SAR"
		place="Example 1128, citing Chiba University 2015:2155"
		note="Monoa is left unsegmented because the source discusses competing analyses of mono. The excerpt preserves the continuing akusu clause."
	/>
	<p>
		He also considers <i lang="ain-Latn">mono</i> a possible lexical unit, since independent
		<i lang="ain-Latn">mo</i> has restricted use. Tokachi <i lang="ain-Latn">mona</i>, contracted
		from the longer form and meaning simply “sit,” supplies a further comparison ‹contested› <Ref
			k="nakagawa2024"
			p="492–493"
		/>. The analysis does not support a universal rule deleting every <i lang="ain-Latn">-no</i> in a
		complex verb.
	</p>
</S>

<S t="Temporal nouns and the productivity question" id="productivity">
	<p>
		A temporal noun can also appear within a verbal stem. Satō gives a daytime-sleep example and
		describes this type as uncommon <Ref k="sato2008" p="220–221" />.
	</p>
	<Ex
		m="tanto anak ku=tokap-mokor a wa"
		g="today TOP 1SG.S=daytime-sleep PST FIN"
		tr="Today I had a daytime sleep."
		cite="sato2008:220"
		place="Example 5"
		note="The source's past gloss for a is retained. Tokap is the temporal noun ‘daytime’; wa is sentence-final in this example."
	/>
	<p>
		The broader productivity of adverbial incorporation is disputed. Shibatani describes relatively
		free incorporation of adverbs, subject to the basic-form restriction. Satō instead emphasizes
		its lexical character and rejects productive adverbial incorporation as a general Ainu process
		‹contested› <Ref k="shibatani1990" p="71" />;
		<Ref k="sato2023b" p="46–47, note 12" />. The attested constructions establish possible
		combinations without settling how freely speakers could create new ones.
	</p>
	<p>
		Refsing reports no comparable verb–adverb compounds in her Shizunai material
		<Ref k="refsing1986" p="40" />. This limits the evidence supplied by that study without
		invalidating the examples from other descriptions.
	</p>
</S>
