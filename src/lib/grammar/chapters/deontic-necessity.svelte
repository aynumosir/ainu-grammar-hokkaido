<S t="What has to be done" id="necessity">
	<p>
		Obligation, advice, permission, and expectation are expressed through several constructions. The
		auxiliary <i lang="ain-Latn">easirki</i> directly expresses necessity. Nakagawa finds it chiefly
		in Saru examples, with Horobetsu evidence as well <Ref k="nakagawa2024" p="308" />.
	</p>
	<Ex
		m="e=ona eun paye=an easirki p mak e=iki hawe an"
		g="2SG.POSS=father ALLAT go.PL=4.S must CONJ how 2SG.S=do EVID exist.SG"
		tr="We must go to your father; what are you doing?"
		cite="nakagawa2024:308"
		dial="SAR"
		place="Example 457, citing Chiba University 2015:390"
		note="The first clause concerns a plural group including the speaker. P links the necessity with the reproach expressed by the question."
	/>
</S>

<S t="Kuni: obligation and expectation" id="kuni">
	<p>
		<i lang="ain-Latn">Kuni</i> spans what is supposed to happen, what is expected, and what ought
		to be done. Nakagawa gives it before a noun, before final
		<i lang="ain-Latn">un</i>, and before <i lang="ain-Latn">pekor</i> ‘as if’
		<Ref k="nakagawa2024" p="309, examples 461–463" />. A translation with ‘should’ must therefore
		be read in context: it can express an expectation as well as a requirement.
	</p>
	<Ex
		m="ku=rura kuni p ne korka toonta k=anu ruwe ne wa"
		g="1SG.A=carry should NMLZ COP CONJ over.there 1SG.A=put EVID COP FIN"
		tr="I should carry it, but I left it over there."
		cite="sato2008:84"
		dial="CHI"
		place="§9.2, kuni example"
	/>
	<p>
		Satō states that <i lang="ain-Latn">kuni</i> does not occur alone at the end of a sentence in
		this use; the example continues through
		<i lang="ain-Latn">p ne</i>. Nakagawa's
		<i lang="ain-Latn">ene ne kuni un</i> instead means ‘that must be so’, with a final particle <Ref
			k="sato2008"
			p="84"
		/><Ref k="nakagawa2024" p="309, example 462" />. For complement and purpose constructions, see
		<Xr ch="kuni-complementizer-purpose-complements" />.
	</p>
</S>

<S t="Advice and permission" id="advice">
	<p>
		A conditional clause followed by a property predicate can advise someone how to act. Satō
		describes <i lang="ain-Latn">yak pirka</i>, literally ‘if …, good’, and
		<i lang="ain-Latn">yak wen</i>, literally ‘if …, bad’, as conventional ways to give positive and
		negative advice
		<Ref k="sato2009" p="51, examples 23–24" />.
	</p>
	<Ex
		m="pirkano e=tese yak pirka na"
		g="well 2SG.A=weave COND be.good FIN"
		tr="You should weave it neatly."
		cite="sato2009:51"
		dial="CHI"
		place="Example 23, citing Satō 2008:50"
	/>
	<p>
		Permission can be expressed with <i lang="ain-Latn">yakka pirka</i>. In Nakagawa's Saru
		exchange, <i lang="ain-Latn">e=arpa yakka pirka</i>
		answers a speaker considering departure: ‘you may go’
		<Ref k="nakagawa2024" p="334, example 578, citing Tamura 1988a:55" />. These particular
		constructions do not establish a complete paradigm in which every connective and property
		predicate has one fixed modal value.
	</p>
</S>

<S t="Directive force and grammatical person" id="directives">
	<p>
		<i lang="ain-Latn">Yak pirka</i>, <i lang="ain-Latn">kusu ne na</i>,
		<i lang="ain-Latn">p ne na</i>, and
		<i lang="ain-Latn">nankor na</i> can also serve as indirect directives. They retain ordinary
		person marking, including third-person formulations that name the people addressed <Ref
			k="nakagawa2024"
			p="423–424"
		/>. Their interpretation depends on the speaker's relation to the addressee and the context of
		the instruction; they do not all contain a morpheme meaning ‘must’.
	</p>
	<p>
		Compare <Xr ch="imperative-and-prohibitive" /> for direct commands and prohibitions, and <Xr
			ch="epistemic-irrealis-modality"
		/> for conjecture and prospective events.
	</p>
</S>
