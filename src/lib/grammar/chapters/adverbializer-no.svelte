<S t="Manner adverbs from property predicates" id="manner-adverbs">
	<p>
		Adding <i lang="ain-Latn">-no</i> to many property-denoting intransitives produces an adverbial
		expression. Nakagawa gives
		<i lang="ain-Latn">pirka-no</i> “well,”
		<i lang="ain-Latn">pon-no</i> “small, in a small way,” and
		<i lang="ain-Latn">ukattuyma-no</i> “far apart, at long intervals.” He describes the pattern as
		productive, especially with predicates of state or quality <Ref k="nakagawa2024" p="275–276" />.
		Refsing gives a corresponding Shizunai account
		<Ref k="refsing1986" p="134–135" />.
	</p>
	<Ex
		m="cise ne yakka pirkano a=kar wa, oro ta an=an"
		g="house COP CONC well 4.A=make CONJ place LOC exist.SG=4.S"
		tr="I built a fine house too, and lived there."
		cite="nakagawa2024:276, example 347"
		dial="SAR"
	/>
	<p>
		The adverb describes the manner or quality of the action. Its meaning can become specialized: <i
			lang="ain-Latn">poronno</i
		>
		expresses quantity, “a lot/many,” rather than simply reproducing the meaning “big” of
		<i lang="ain-Latn">poro</i>
		<Ref k="nakagawa2024" p="276, 341" />.
	</p>
</S>

<S t="Forms and lexical restrictions" id="forms-and-restrictions">
	<p>
		In <i lang="ain-Latn">pon-no</i>, the predicate
		<i lang="ain-Latn">pon</i> ends in <i lang="ain-Latn">n</i>
		and the suffix begins with the same consonant. The resulting
		<i lang="ain-Latn">ponno</i> follows directly from that boundary.
		<i lang="ain-Latn">Poronno</i> has an additional consonant relative to
		<i lang="ain-Latn">poro</i>; Nakagawa also explicitly records
		<i lang="ain-Latn">porono</i>
		<Ref k="nakagawa2024" p="275–276" />.
	</p>
	<p>
		Adverbial use need not always carry <i lang="ain-Latn">-no</i>. Nakagawa lists
		<i lang="ain-Latn">tunas</i>
		“early/quickly,”
		<i lang="ain-Latn">moyre</i> “slowly,”
		<i lang="ain-Latn">hanke</i> “near,” and
		<i lang="ain-Latn">tuyma</i> “far” with unsuffixed adverbial uses alongside suffixed forms <Ref
			k="nakagawa2024"
			p="276"
		/>. Refsing additionally describes bare <i lang="ain-Latn">pirka</i>
		and <i lang="ain-Latn">wen</i> in her Shizunai account
		<Ref k="refsing1986" p="135" />.
	</p>
	<Ex
		m="kunneywa tunasno hopuni=an hine ipe=an"
		g="morning early get.up.SG=4.S CONJ eat=4.S"
		tr="I got up early in the morning and ate."
		cite="nakagawa2024:276, example 350"
		dial="SAR"
		note="The preceding example in Nakagawa uses unsuffixed tunas in a different sentence."
	/>
</S>

<S t="Transitive-derived adverbs" id="transitive-adverbs">
	<p>
		Some adverbial expressions derive from transitive verbs and retain a relation to an object.
		Nakagawa compares
		<i lang="ain-Latn">tura</i> and
		<i lang="ain-Latn">turano</i> “together with,” which can alternate in his examples. The same
		pattern is unavailable with instrumental
		<i lang="ain-Latn">ani</i>: he rejects
		<i lang="ain-Latn">*anino</i>
		<Ref k="nakagawa2024" p="276–277, examples 352–355" />.
	</p>
	<p>
		These restrictions prevent extending the suffix mechanically to every transitive verb. The
		postposed-adverb constructions are described in
		<Xr ch="postpositions-local-case-and-motion-events" />.
	</p>
</S>

<S t="Adverbial no and clause-linking no" id="adverb-and-connective">
	<p>
		The boundary between an adverbial suffix and connective
		<i lang="ain-Latn">no</i> receives different treatments. Refsing identifies the adverb-forming
		element with her conjunctionalizer. Nakagawa recognizes continuity between the uses but finds a
		uniform analysis difficult
		<Ref k="refsing1986" p="134" />;
		<Ref k="nakagawa2024" p="276, 340–341" /> ‹contested›.
	</p>
	<p>
		Nakagawa considers person-marked <i lang="ain-Latn">k=eyam no</i>, “taking care,” particularly
		revealing. Treating the whole form as an adverb requires an adverb with A-series person marking;
		treating it as a verbal phrase followed by a connective preserves ordinary verbal indexing.
		Conversely, specialized quantity
		<i lang="ain-Latn">poronno</i> is awkward to analyze as an ordinary unchanged predicate plus
		connective
		<Ref k="nakagawa2024" p="340–341" />.
	</p>
	<p>
		With a negative predicate, <i lang="ain-Latn">no</i> commonly links a state of not doing something
		to a following event.
	</p>
	<Ex
		m="a=ona-ha somo mokor no kamuyoritak kor an"
		g="4.A=father-POSS NEG sleep CONJ pray.to.gods CONJ exist.SG"
		tr="My father was praying to the gods without sleeping…"
		cite="nakagawa2024:340, example 614"
		dial="SAR"
		note="The source translates the passage as continuing. The affiliative suffix is segmented here."
	/>
	<p>
		Nakagawa's explicitly Saru comparison accepts
		<i lang="ain-Latn">somo ipe no soyne</i>, “go out without eating,” while rejecting
		<i lang="ain-Latn">*ipe no soyne</i>
		for an ordinary sequence of eating and going out. He contrasts this with
		<i lang="ain-Latn">wa</i> for a resulting state and
		<i lang="ain-Latn">kor</i> for ongoing activity
		<Ref k="nakagawa2024" p="341" />. The comparison concerns these constructions and their temporal
		interpretation; negative clauses have further linking possibilities discussed in
		<Xr ch="negation-somo-standard-clausal" />.
	</p>
</S>

<S t="Intensive no remains verbal" id="intensive-no">
	<p>
		A same-shaped verbal suffix intensifies a predicate. Nakagawa gives
		<i lang="ain-Latn">retar-no</i>, realized as
		<i lang="ain-Latn">retanno</i> “be pure white,”
		<i lang="ain-Latn">hure-no</i> “be bright red,” and
		<i lang="ain-Latn">ipe-no</i> “eat well.” These are verbs in his analysis and retain verbal
		person marking
		<Ref k="nakagawa2024" p="209" />.
	</p>
	<Ex
		m="ipeno=an pe ne kusu poro=an"
		g="eat.well=4.S NMLZ COP because be.big=4.S"
		tr="Because I ate well, I grew big."
		cite="nakagawa2024:209, example 215′"
		dial="CHI"
		note="Nakagawa's analysis respells the previously spaced ipe no an as intensive verb ipeno plus person suffix. This is his published resegmentation."
	/>
	<p>
		Satō also lists intensive formations with transitive bases, including
		<i lang="ain-Latn">nu-no</i> and
		<i lang="ain-Latn">rayke-no</i>
		<Ref k="sato2008" p="274" />. The two inventories have different scopes, while both distinguish
		intensified verbal meaning from ordinary manner modification.
	</p>
</S>
