<S t="Text collections as samples" id="attested-corpus">
	<p>
		A corpus assembled from published texts reflects the histories of those collections. Endō
		describes a strong regional bias in the oral-literature record: Hidaka and Iburi are well
		represented, while northern and eastern Hokkaido have far fewer surviving materials
		<Ref k="endo2022" p="§5" />. A large number of sentences therefore need not imply broad coverage
		of dialects or speakers.
	</p>
	<p>
		Narrative performance, conversation, elicited examples, and written compositions also provide
		different opportunities for a construction to occur. Repeated passages or repeated publication
		of the same recording can further affect counts. The collections and their provenance are
		described in <Xr ch="oral-literature-and-spoken-corpora" />. A frequency statement needs to
		identify the particular material searched, including any exclusions.
	</p>
</S>

<S t="Interpreting corpus figures" id="corpus-method">
	<p>
		A count of a written form is a count of matches under particular search conditions. It may
		include several meanings or grammatical functions. Spelling variants, word division, and the
		treatment of person markers affect which occurrences are found. Counts of individual tokens,
		multiword sequences, and sentences containing a form have different denominators and cannot be
		compared as if they measured the same thing.
	</p>
	<p>
		A grammatical frequency claim requires the retrieved examples to be classified for the use under
		discussion. For comparison between dialects or genres, the relevant subcorpora and their sizes
		must also be specified. An occurrence rate per thousand sentences expresses the number of
		occurrences divided by the number of sentences, multiplied by one thousand. It measures that
		sample; it does not by itself show the proportion of speakers who use the construction.
	</p>
	<p>
		Figures quoted from a publication belong to that author's dataset and counting method. Counts
		obtained from an online corpus depend on the version and date searched. A reproducible result
		therefore needs a source or snapshot, the query and normalization used, the counting unit, and
		the criteria used to classify matches. A missing search result leaves open whether the form is
		absent, spelled differently, or outside the indexed material.
	</p>
</S>

<S t="Example provenance" id="attribution">
	<p>
		An example's citation identifies the published source in which it can be found. Narrator,
		locality, and recording information distinguish the speech event from the edition that presents
		it. Where an example is encountered through a later study, the note identifies that
		intermediary. These details allow a reader to trace both the expression and its interpretation.
	</p>
	<p>
		The label <em>constructed</em> identifies an illustration composed for the grammar. Such an
		example is separate from attested speech and does not supply evidence for a frequency claim.
		Transcription, segmentation, glossing, and translation can each involve editorial decisions; the
		conventions are explained in <Xr ch="glossing-abbreviations-and-citation" />.
	</p>
</S>

