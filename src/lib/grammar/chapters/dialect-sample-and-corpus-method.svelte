<S t="Observations outside published descriptions" id="community-leads">
	<p>
		A speaker's explanation, a learner's observation, or a discussion of a particular passage can
		identify a grammatical question that published descriptions leave open. Its value depends on the
		expression and context it identifies. A claim based on such an observation needs an attribution
		and supporting examples; a tentative suggestion remains tentative until its evidence has been
		examined.
	</p>
