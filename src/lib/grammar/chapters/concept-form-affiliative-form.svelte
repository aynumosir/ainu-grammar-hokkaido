<S t="Concept, affiliative, and personal forms" id="three-forms">
	<p>
		The <em>concept form</em> is the base noun: for example,
		<i lang="ain-Latn">tek</i> “hand.” Its <em>affiliative forms</em>,
		<i lang="ain-Latn">teke</i> and <i lang="ain-Latn">tekehe</i>, express a hand in relation to its
		possessor. A person marker identifies that possessor, as in <i lang="ain-Latn">ku=tekehe</i> “my
		hand”
		<Ref k="nakagawa2022pos" p="§4.2" />;
		<Ref k="nakagawa2024" p="219" />. Satō distinguishes the affiliative from the resulting
		<em>personal form</em>, illustrated with
		<i lang="ain-Latn">par</i> → <i lang="ain-Latn">paro</i> →
		<i lang="ain-Latn">e-paro</i> “your mouth”
		<Ref k="sato2008" p="152–153" />.
	</p>
	<p>
		Kindaichi and Chiri's older terms “abstract” and “concrete” describe the corresponding
		distinction <Ref k="kindaichi1936" p="16–17, §16" />. The terminology should not imply that
		affiliative forms refer only to things already identified in the conversation. Generic and
		unspecified possessors also occur, as the examples below show.
	</p>
</S>

<S t="Short and long affiliatives" id="short-long">
	<p>
		Many nouns have a short and a long affiliative. Compare
		<i lang="ain-Latn">siki</i> / <i lang="ain-Latn">sikihi</i> “someone's eye” and
		<i lang="ain-Latn">sapa</i>
		/ <i lang="ain-Latn">sapaha</i>
		“someone's head.” With vowel-final <i lang="ain-Latn">sapa</i>, the short affiliative has the
		same segmental form as the concept form
		<Ref k="sato2008" p="153–154" />. Third-person possession adds no pronounced person marker, so
		an affiliative can appear without a visible prefix.
	</p>
	<p>
		Satō reports no apparent meaning difference between short and long forms but leaves their
		distribution unresolved. Nakagawa associates the alternation with prosody and rhythm <Ref
			k="sato2008"
			p="153–154"
		/>;
		<Ref k="nakagawa2024" p="219, 226" />. Refsing finds short forms more often in her Shizunai
		material, with long forms relatively frequent for monosyllabic words <Ref
			k="refsing1986"
			p="85"
		/>. These observations do not establish free interchangeability in every environment.
	</p>
	<p>
		Suffix selection depends partly on the stem's final segment and partly on the individual noun.
		The full set of patterns, including exceptional forms, is in
		<Xr ch="affiliative-suffix-morphophonology" />.
	</p>
</S>

