<S t="An expressed or contextually supplied possessor" id="possessor-context">
	<p>
		A separate possessor noun phrase need not accompany every personal form. Satō's Chitose <i
			lang="ain-Latn">siki</i
		>
		can itself mean “his/her eye(s),” with the possessor supplied by the context. First- and
		second-person independent pronouns likewise commonly remain unexpressed
		<Ref k="sato2008" p="156" />;
		<Ref k="bugaeva2021poss" p="52" />.
	</p>
	<p>
		The possessor may also be separated from the affiliative noun. Satō discusses examples with
		intervening topic <i lang="ain-Latn">anakne</i> and argues that the person-marked noun has
		substantial grammatical independence. He therefore questions a uniform analysis of every
		possessor–affiliative sequence as a single tightly integrated noun phrase
		<Ref k="sato2008" p="156–157" /> ‹contested›. Further constructional differences appear in <Xr
			ch="adnominal-possession-double-marking"
		/> and
		<Xr ch="external-possession-possessor-raising" />.
	</p>
</S>

<S t="Generic and unspecified possessors" id="unspecified-possession">
	<p>
		An affiliative can have a generic possessor. Nakagawa quotes Satō (1997: 150) on a Chitose
		sentence meaning that all humans have bellies; the belly noun is
		<i lang="ain-Latn">honihi</i>. He also gives a Saru warning about pointing at a rainbow with
		fourth-person <i lang="ain-Latn">a=teke</i>, referring generally to a person's hand <Ref
			k="nakagawa2024"
			p="231"
		/>.
	</p>
	<p>
		Bugaeva, Nichols and Bickel quote an eyes riddle from Tamura (1993: 16, 18), whose answer
		contains <i lang="ain-Latn">a-sik-ihi</i>. The fourth-person marker supplies an unspecified
		human possessor
		<Ref k="bugaeva2021poss" p="53, example 15" />. In object-incorporating formations, the same
		authors discuss antipassive <i lang="ain-Latn">i-</i> as marking a possessor non-coreferential
		with the subject, using Tamura's and Okuda's examples
		<Ref k="bugaeva2021poss" p="53–54, examples 16–18" />. That analysis concerns incorporation; it
		does not make <i lang="ain-Latn">i-</i> an alternative possessive prefix for every independent noun.
	</p>
</S>

<S t="Grammatical conditions and unresolved uses" id="affiliative-conditions">
	<p>
		Nakagawa contrasts <i lang="ain-Latn">saraha tanne seta</i> “a dog with a long tail” with a
		rejected version containing concept-form
		<i lang="ain-Latn">sar</i>. The dog need not be a specific individual; the tail noun
		nevertheless takes its affiliative form. He argues that grammar must supplement a purely
		semantic condition on specificity
		<Ref k="nakagawa2024" p="231–232" />. His earlier treatment illustrates the parallel
		construction with a fox <Ref k="nakagawa2022pos" p="§4.2" />.
	</p>
	<p>
		Some uses remain less clear. Nouns following <i lang="ain-Latn">usa</i>
		“various” or <i lang="ain-Latn">nep</i> “what” sometimes have affiliative forms. Nakagawa
		tentatively connects some verse uses after
		<i lang="ain-Latn">usa</i> with syllable count, while noting that adjacent expressions can
		differ: his Chitose example has affiliative
		<i lang="ain-Latn">cikapi</i> but concept-form
		<i lang="ain-Latn">cironnup</i>. He proposes a possessive interpretation for the wider range
		after <i lang="ain-Latn">nep</i>
		<Ref k="nakagawa2024" p="232–233" /> ‹speculative›. Neither expression licenses an automatic rule
		for all following nouns.
	</p>
</S>
