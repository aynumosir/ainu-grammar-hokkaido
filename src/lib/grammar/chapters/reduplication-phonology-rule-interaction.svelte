<S t="Copying roots and stems" id="overview">
	<p>
		Reduplication repeats all or part of a word. In Hokkaido Ainu verbs, the repeated material may
		be a root, a whole stem, or a smaller portion of the stem. The resulting verbs express repeated
		action, continuation, degree, or a maintained result, with differences among formations and
		individual words
		<Ref k="nakagawa2024" p="151–153" />; <Ref k="sato2008" p="247–248, 277–278" />.
	</p>
	<p>
		The distinction between a root and a stem matters here. In Satō's analysis,
		<i lang="ain-Latn">moymoye</i> repeats the root <i lang="ain-Latn">moy-</i>
		before the transitive suffix <i lang="ain-Latn">-e</i>; it does not repeat the whole verb
		<i lang="ain-Latn">moye</i>
		“move something”
		<Ref k="sato2008" p="247" />. Full-stem reduplication instead repeats all of
		<i lang="ain-Latn">apkas</i> “walk” in <i lang="ain-Latn">apkasapkas</i>
		<Ref k="nakagawa2024" p="153" />.
	</p>
</S>

