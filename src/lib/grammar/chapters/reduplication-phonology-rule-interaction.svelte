<S t="Interpreting a repeated form" id="sandhi-summary">
	<p>
		A reduplicated word may preserve the copied consonants, as in
		<i lang="ain-Latn">kikkik</i>, or show assimilation, as in
		<i lang="ain-Latn">tutturi</i> and <i lang="ain-Latn">nukannukar</i>. The copy pattern and the
		pronunciation boundary are distinct properties: Shiraishi's glottal example supplies a
		particular boundary-sensitive pronunciation, while the root and stem comparisons establish how
		the words are formed
		<Ref k="tamura1996" p="s.vv. kikkik, nukannukar" />;
		<Ref k="nakagawa2024" p="152" />; <Ref k="shiraishi2022" p="§4.4" />.
	</p>
</S>
