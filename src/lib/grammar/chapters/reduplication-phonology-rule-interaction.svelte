	<p>
		Repetition occurs in both the root and whole-stem examples. The partial form describes the
		continuation of the resulting position. Nakagawa's broader classification also includes high
		degree among the meanings of root and whole-stem reduplication
		<Ref k="nakagawa2024" p="152" />. These categories therefore overlap in meaning.
	</p>
</S>

<S t="Extent of an action and lexical restrictions" id="coda-alternation">
	<p>
		Satō compares root reduplication in <i lang="ain-Latn">yasyaske</i> with whole-word
		reduplication in <i lang="ain-Latn">yaskeyaske</i>. In his Chitose examples, the former
		describes clothes torn in several places; the latter describes wood broken into fine pieces. He
		provisionally relates the difference to repetition over a limited portion versus repetition of a
		complete action
		<Ref k="sato2008" p="247–248" /> ‹speculative›.
	</p>
	<Ex
		m="ku=mipi yasyaske"
		orig="ku-mipi yasyaske"
		origLang="ain-Latn"
		g="1SG.A=clothes be.torn.in.places"
		tr="My clothes are torn in several places."
		cite="sato2008:247"
		dial="CHI"
		note="Satō's original hyphenation is shown separately; the possessive person marker is glossed by its A-series form."
	/>
	<p>
		The available formation also depends on the lexical item. Satō describes
		<i lang="ain-Latn">moymoye</i> as usual and marks
		<i lang="ain-Latn">*moyemoye</i> as a form not normally used
		<Ref k="sato2008" p="248" />. Nakagawa restricts root and partial-stem reduplication, in
		principle, to the V/<i lang="ain-Latn">-pa</i> class, whose final vowel is replaced by
		<i lang="ain-Latn">-pa</i> in the plural; whole-stem copying extends to other classes
		<Ref k="nakagawa2024" p="153" />.
	</p>
	<p>
		Satō also identifies a partial-root pattern in
		<i lang="ain-Latn">sik-mak-ak-a</i> “keep the eyes open.” Here the repeated material is
		<i lang="ain-Latn">ak</i>, within a larger formation
		<Ref k="sato2008" p="277–278" />. Kindaichi and Chiri's earlier classification likewise
		distinguishes full-stem, root, root-minus-initial-consonant, and final-syllable patterns <Ref
			k="kindaichi1936"
			p="171–174, §§223–225"
		/>.
	</p>
</S>

<S t="Consonants at the copy boundary" id="sandhi">
	<p>
		Copying can place two consonants together without any sound change:
		<i lang="ain-Latn">kik-kik</i>, from <i lang="ain-Latn">kik</i>
		“hit,” already contains /kk/. Nakagawa's Saru sentence describes the narrator clapping to summon the
		master of a house
		<Ref k="nakagawa2024" p="153, example 66" />.
	</p>
	<Ex
		m="a=teke a=kik-kik"
		ain="a=teke a=kikkik"
		g="4.A=hand 4.A=hit-RED"
		tr="I clapped my hands."
		cite="nakagawa2024:153, example 66"
		dial="SAR"
		note="Clause excerpt. The narrative first-person interpretation follows the source; the reduplication boundary follows Tamura's kikkik entry."
	/>
	<p>
		Tamura explicitly segments <i lang="ain-Latn">kikkik</i> as
		<i lang="ain-Latn">kik-kik</i>
		<Ref k="tamura1996" p="s.v. kikkik" />. The longer <i lang="ain-Latn">apkas-apkas</i> also shows
		that the repeated unit can contain several syllables <Ref k="nakagawa2024" p="153" />.
	</p>
	<S t="Assimilation of final /r/" id="r-sandhi">
		<p>
			Other formations show a consonant alternation at the copy boundary. In
			<i lang="ain-Latn">tur-turi → tutturi</i>, /r/ assimilates to the following /t/ <Ref
				k="nakagawa2024"
				p="152"
			/>. Tamura gives
			<i lang="ain-Latn">catcari</i> “scatter repeatedly” with the analysis
			<i lang="ain-Latn">car-car-i</i>, and <i lang="ain-Latn">nukannukar</i>
			“look after” with <i lang="ain-Latn">nukar-nukar</i>
			<Ref k="tamura1996" p="s.vv. catcari, nukannukar" />. The latter displays /r+n/ as /nn/. The
			wider conditions on final /r/ are described in
			<Xr ch="coda-r-assimilation-sonorant-sandhi" />.
		</p>
	</S>
	<S t="A lexical formation with /t+s/" id="t-s-sandhi">
		<p>
			Tamura analyzes <i lang="ain-Latn">ketketcep</i> “tree frog” as
			<i lang="ain-Latn">ketket-se-p</i>
			<Ref k="tamura1996" p="s.v. ketketcep" />. The /tc/ sequence occurs where the analysis places
			/t+s/. Nakagawa describes the wider /t+s/ to /tc/ correspondence as limited in occurrence and
			historical
			<Ref k="nakagawa2024" p="37" />. In this word, the relevant boundary follows the repeated
			<i lang="ain-Latn">ketket</i> material.
		</p>
	</S>
</S>

<S t="Boundaries, resyllabification, and accent" id="boundary">
	<p>
		A final consonant often becomes the onset of a following vowel-initial syllable across a
		morpheme boundary. Shiraishi illustrates this with
		<i lang="ain-Latn">sik-o → si.ko</i> “open the eyes” and
		<i lang="ain-Latn">mat-ak → ma.tak</i> “younger sister.” He also reports occasional blocking
		associated with accent or morphological structure
		<Ref k="shiraishi2022" p="§4.4, examples 7–8" />.
	</p>
	<p>
		His reduplication example, reported from Tamura, is
		<span lang="ain-Latn">ˈay-[ʔ]ay</span> “baby.” The glottal stop preserves a boundary before the
		second vowel despite preceding consonantal /y/. In
		<span lang="ain-Latn">paˈraparak-ˌ[ʔ]an</span> “cry,” the illustrated boundary instead precedes
		the person suffix <i lang="ain-Latn">-an</i>, which bears secondary accent <Ref
			k="shiraishi2022"
			p="§4.4, example 8"
		/>.
	</p>
	<S t="The /t+i/ alternation" id="palatalization">
		<p>
			Shiraishi discusses <i lang="ain-Latn">mat-ikor → macikor</i> and
			<i lang="ain-Latn">rekut-i → rekuci</i> under resyllabification
			<Ref k="shiraishi2022" p="§4.4, example 9" />. These formations contain no reduplication.
			Their /t+i/ alternation is described in
			<Xr ch="citation-vs-combining-stem-shapes" s="t-i-junction" />.
		</p>
	</S>
</S>

<S t="Person marking on reduplicated verbs" id="person-prefix">
	<p>
		The resulting verb takes person marking. Nakagawa's Saru examples include
		<i lang="ain-Latn">a=kikkik</i> “I clapped,”
		<i lang="ain-Latn">a=koturiri</i> “I kept holding it out toward someone,” and
		<i lang="ain-Latn">apkasapkas=an</i> “I kept walking”
		<Ref k="nakagawa2024" p="152–153, examples 63, 65–66" />. The person marker stands outside the
		repeated material. Its phonological behavior depends on the marker and the adjacent sounds; see
		<Xr ch="personal-affix-sandhi-connected-speech-reduction" />.
	</p>
</S>

<S t="Lexical meanings and aspect" id="corpus">
	<p>
		Some reduplicated formations have specialized lexical meanings.
		<i lang="ain-Latn">Tuytuye</i>, related to <i lang="ain-Latn">tuye</i>
		“cut,” means “winnow”; <i lang="ain-Latn">nukannukar</i>, related to
		<i lang="ain-Latn">nukar</i> “see,” means “look after”
		<Ref k="nakagawa2024" p="153" />. The meaning of a particular reduplicated verb therefore
		requires lexical information as well as its copy pattern.
	</p>
	<p>
		Refsing discusses reduplication among mechanisms of plural formation, while describing its usual
		contribution as repetition or duration
		<Ref k="refsing1986" p="149, §13.7" />. Nakagawa treats it as lexical aspect and excludes it
		from his Handbook account of grammatical number
		<Ref k="nakagawa2022" p="§1" />. These are different ways of organizing the morphology
		‹contested›. Related aspectual constructions are treated in
		<Xr ch="phasal-iterative-habitual-aspect" />.
	</p>
</S>

