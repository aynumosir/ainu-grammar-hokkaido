		note="The source compares the general possessive predicate kor with more specific verbs."
	/>
	<p>
		The authors also show that modern possessive
		<i lang="ain-Latn">kor</i> retains relative-clause properties: it can carry number and aspect
		marking and take adverbial modifiers. Its conventional possessive function therefore coexists
		with verbal syntax <Ref k="bugaeva2021poss" p="59, examples 30–33" />.
	</p>
</S>

<S t="Person and nominalization: proposed histories" id="person-nominalization">
	<p>
		Refsing suggests an etymological connection between existential
		<i lang="ain-Latn">an</i> and person forms. Bugaeva proposes a development from inclusive
		reference to logophoric use. These concern different steps: a possible source of morphology and
		a possible expansion of its discourse functions
		<Ref k="refsing1986" p="218–219, §14.10.4" />;
		<Ref k="bugaeva2008" p="§4.2.2" />. Neither makes every modern use of the fourth-person series
		interchangeable; see <Xr ch="indefinite-fourth-person-paradigm" />.
	</p>
	<p>
		Bugaeva separately proposes a tentative history of nominalization: zero nominalization,
		constructions with nominalizing words, Sakhalin verbal forms with possessive-style agreement,
		and independent clause uses of those forms. She considers adverbial constructions containing a
		copula a possible starting point for the Sakhalin development <Ref
			k="bugaeva2016"
			p="114, §6"
		/>. The proposed sequence organizes cross-dialectal evidence; its stages are not dated
		documentary observations. Present constructional differences are treated in <Xr
			ch="nominalization-p-pe"
		/> and
		<Xr ch="nominalized-complements-control-raising" />.
	</p>
</S>

<S t="The limits of segmentation" id="segmentation">
	<p>
		Alonso explores whether recurring final segments in nouns might preserve older class terms or
		classifiers. He distinguishes compound heads from grammatical classifiers and notes the
		difficulty of testing some proposed analyses <Ref k="alonso2022" p="§3.2, Table 17" />. A shared
		final consonant among words with related meanings does not by itself establish a productive
		ancestral suffix.
	</p>
	<p>
		Even familiar lexical forms admit competing historical analyses. For <i lang="ain-Latn">cep</i>
		‘fish’, Alonso's reconstructed stages and Bugaeva and colleagues' exclusive-person analysis of
		its components use different labels and arguments
		<Ref k="alonso2022" p="§4, Table 18" />;
		<Ref k="bugaeva2021poss" p="58, example 28" />. Such proposals should be evaluated against their
		correspondences and constructional evidence; a newly segmented spelling is not an additional
		attested utterance.
	</p>
</S>
