<S t="Possession and the expansion of kor" id="possession">
	<p>
		Bugaeva and colleagues propose an earlier set of possessive verbs distinguishing such
		relationships as hunting, food preparation, and use of objects, followed by wider use of general
		<i lang="ain-Latn">kor</i> ‘have’. Their argument combines surviving specific constructions with
		lexicalized nouns
		<Ref k="bugaeva2021poss" p="57–59" />.
	</p>
