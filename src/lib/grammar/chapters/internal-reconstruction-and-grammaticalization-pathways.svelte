<S t="Recovering earlier grammatical structure" id="method">
	<p>
		Grammaticalization describes the development of grammatical functions from lexical words or
		larger constructions. Ainu provides transparent relationships between some verbs and grammatical
		forms, but resemblance alone does not determine the order or date of changes. Alonso de la
		Fuente emphasizes the uneven documentation, especially for the history of person marking <Ref
			k="alonso2022"
			p="§3.1"
		/>.
	</p>
	<p>
		His proposed pathways include <i lang="ain-Latn">ani</i> ‘hold’ to an instrumental expression,
		<i lang="ain-Latn">kusu</i>
		‘reason’ to a causal connective, and an anaphoric
		<i lang="ain-Latn">ne</i> to the copula. He relates aspectual
		<i lang="ain-Latn">a/rok</i> to ‘sit down’; this proposal must be kept distinct from
		derivational <i lang="ain-Latn">-an</i> and existential
		<i lang="ain-Latn">an</i>
		<Ref k="alonso2022" p="§3.1" />. For present-day aspect analyses, see <Xr
			ch="perfective-anterior-a"
		/>.
	</p>
</S>

